from .strands import _noise

_UNDER_TUFT = 0.01     # З-1: тоньше этой доли плёнки мазка сырая краска под кончиком вытертой (Долг-ф: и почти пустой) кисти — не краска: цвет берётся по пучку (`_цвет_под_пучком`)
_PATH_MAX = 100.0    # К5: во сколько раз путь волоска может быть длиннее шага оси (кисть поперёк хода на дуге радиуса меньше её полуширины)


class Soft:
    """Край пучка на один мазок: `кас` (N, nr) — насколько волосок гребня достаёт до холста; `кладёт` (N, nr) — доля
    полной плёнки, которую он оставляет при своём нажиме; `вбок` (N, nr) — на сколько px крайний волосок ушёл вбок."""
    __slots__ = ('кас', 'кладёт', 'вбок', 'глубина', 'между', 'случай', 'вглубь', 'отдача')

    @staticmethod
    def for_(brush, with_, rng, p, ds, N, W, wet=None, release=None):
        """Край мягкой кисти или None — у щетины. Ношу краёв убавляет тут же (`с.нагр`). Свой поток случая заводится
        только у мягкой кисти: мазки прежних кистей не сдвигаются."""
        if getattr(brush, 'кайма', 0.0) <= 0.0 or brush.shape == 'мастихин':
            return None
        rng = np.random.default_rng(rng.bit_generator.seed_seq.spawn(1)[0])
        dome, shorter, power, irregularity, tremor, transition, full, gamma, carry_st, carry_floor, spread, edge, clamped = _MYaGBrushAYa
        m = Soft()
        m.release = None if release is None else np.interp(np.arange(N) / max(N - 1, 1), release[:, 0], release[:, 1])[:, None]   # К5: (N, 1)
        nr = with_.nr
        from_edges = np.maximum(W / 2 - np.abs(with_.center), 0.0)
        t = clamp(1.0 - from_edges / max(brush.edge_band * W, 1e-6), 0.0, 1.0)        # 0 — тело пучка, 1 — самый край
        m.depth = t
        # волос к краю короче (купол по всей ширине, у края — круче) и стоит вразнобой: чем ближе к краю, тем реже достаёт
        lacks = dome * with_.distance ** 2 + shorter * t ** power + edge[0] * t ** edge[1] + (irregularity[0] + irregularity[1] * t) * _together(rng.standard_normal(nr))
        # волосок вдоль хода то прижат, то отходит (у края — сильнее): кромка живёт, а не идёт по линейке
        # (край пучка качается целиком — рука держит кисть не ровно: у каждого бока свой ход; волосок — ещё чуть сам по себе.
        # Один шум на волосок рвал кайму на острова в ширину гребня)
        side = _noise(rng, N, 2, max(0.7 * W, 16.0) / ds)[:, (with_.center > 0).astype(np.intp)]
        wanders = (tremor[1] * t)[None, :] * side + (tremor[0] + tremor[2] * t)[None, :] * _together(_noise(rng, N, nr, max(0.5 * W, 12.0) / ds))
        q = q_bottom = p[:, None] - lacks[None, :] - wanders                  # нажим кончика волоска на холст
        if wet is not None:
            # 4б: сырая плёнка под волоском (кайма соседнего мазка того же слоя) — не голый холст: кончик, который до холста
            # чуть не достаёт, её касается, и краска с него сходит в плёнку — кайма на кайму складывается, ложбины нет.
            # Волосок, поднятый выше (вход, сход, дальний край пучка), не касается и её
            q = q + _ShResponseIn[0] * clamp(wet / _ShResponseIn[1], 0.0, 1.0)
        # 4а-2: пучок — купол, волос наружу короче и опирается на соседа изнутри: крайний волосок не прижат сильнее него —
        # отдельной ниткой через голую щель он не идёт, а тает вместе с краем (в теле пучка, где каймы нет, — как было)
        # 5а-2: `q_дно` — тот же нажим без прибавки `_ШОВ`: до сырой плёнки волосок достаёт, а в слой идёт на свой нажим на холст
        for side_g in (np.nonzero((with_.center > 0) & (t > 0))[0], np.nonzero((with_.center < 0) & (t > 0))[0][::-1]):
            if len(side_g):
                inner = side_g[0] - 1 if with_.center[side_g[0]] > 0 else side_g[0] + 1
                for a in ((q,) if q_bottom is q else (q, q_bottom)):
                    row = a[:, side_g] if not 0 <= inner < nr else np.concatenate([a[:, inner:inner + 1], a[:, side_g]], axis=1)
                    a[:, side_g] = np.minimum.accumulate(row, axis=1)[:, -len(side_g):]
        z = clamp(q / transition, 0.0, 1.0)
        m.touch = z * z * (3.0 - 2.0 * z)
        m.lays = clamp(q / full, 0.0, 1.0) ** gamma                     # слабо прижатый мягкий волос оставляет плёнку тоньше
        m.deep = m.lays if q_bottom is q else clamp(q_bottom / full, 0.0, 1.0) ** gamma   # 5а-2: насколько волосок идёт в лежащий сырой слой (`Обмен` вытертой кисти)
        # к краю пучка волос реже — и краски несёт меньше (до нуля не доходит: пустой гребень считать нечем)
        # 4а-2: и набран мягкий волос ровнее щетины: краска — между волосками, ноша и запас соседей близки
        with_.load, with_.reserve = _by_neighbors(with_.load, _TELResponse[4]), np.exp(_by_neighbors(np.log(with_.reserve), _TELResponse[0]))
        with_.load = with_.load * (carry_floor + (1.0 - carry_floor) * (1.0 - t ** carry_st))
        # редкий крайний волос соседями не зажат: вбок его водит на пиксель (у широкой кисти — больше) — всем краем пучка и чуть врозь
        # 4б-3: врозь ходит только слабо прижатый волосок. Под плотной рукой пучок придавлен, волос прижат сильнее, чем нужно
        # для полной плёнки, и зажат соседями — сам по себе вбок не идёт: следы соседних волосков не сходятся в гребень
        # и не расходятся ложбиной (был гребень 1,1–2 тела в 6–9 px от кромки), край водит только весь бок пучка
        m.sideways = spread * float(clamp(W / 48.0, 0.5, 1.0)) ** 0.5 * float(clamp(W / 48.0, 1.0, 2.5)) ** _TELResponse[5] * t[None, :] * (0.7 * _noise(rng, N, 2, max(0.8 * W, 20.0) / ds)[:, (with_.center > 0).astype(np.intp)] + 0.5 * (1.0 - clamp((q - full) / clamped, 0.0, 1.0)) * _noise(rng, N, nr, max(1.2 * W, 30.0) / ds))
        # 4а-2: вбок волос уходит не по одному, а плавно по месту на кисти — между соседними волосками след тянется, щель
        # под крайним не открывается: у выборок профиля уход — между уходами двух ближних гребней
        k = clamp(np.searchsorted(with_.center, with_.u) - 1, 0, max(nr - 2, 0))
        m.between = (k, clamp((with_.u - with_.center[k]) / np.maximum(with_.center[np.minimum(k + 1, nr - 1)] - with_.center[k], 1e-6), 0.0, 1.0))
        m.chance = rng                         # 4в-4: тот же свой поток — дальше из него берёт только `Обмен` (мазки без обмена не сдвигаются)
        return m

    def touch(self, touch, reserve):
        """Касание гребней (N, nr) с краем пучка. запас — нажим гребня сверх его порога касания, как его считает укладка
        (посадка, подъём на кончик, срыв): волосок, который отходит от холста на сходе нажима, тоже кладёт плёнку тоньше —
        конец мазка тает, а не кончается клином с твёрдым краем."""
        leaves = clamp(reserve / _MYaGBrushAYa[6], 0.0, 1.0) ** _MYaGBrushAYa[7]
        self.lays, self.deep = self.lays * leaves, self.deep * leaves
        return touch * self.touch


def wet_under(brush, layer, x, y, angle, center, ox, oy, tau):
    """Сырая краска слоя под волосками мягкой кисти до мазка (часть 4б): (N, nr), в толщинах плёнки `тау` (покрытие 63 %);
    None — у щетины и на слое без сырого. Берётся по месту волоска на оси кисти, без ухода вбок и отставания."""
    if getattr(brush, 'кайма', 0.0) <= 0.0 or brush.shape == 'мастихин':
        return None
    wet = getattr(layer, '_сыро', None)      # 2б: у среза слоя в процессе ответ про весь слой дан заранее (`ядра.py`)
    if not (layer.moisture.any() if wet is None else wet):
        return None
    ix = np.floor(x[:, None] - np.sin(angle)[:, None] * center[None, :]).astype(np.intp) - ox
    iy = np.floor(y[:, None] + np.cos(angle)[:, None] * center[None, :]).astype(np.intp) - oy
    In, Sh = layer.thickness.shape
    inside = (ix >= 0) & (ix < Sh) & (iy >= 0) & (iy < In)
    ix, iy = np.where(inside, ix, 0), np.where(inside, iy, 0)
    return np.where(inside, layer.thickness[iy, ix] * layer.moisture[iy, ix], 0.0) / tau


def with_axis(brush, frame, x, y):
    """2б: рамка мазка (x0, y0, x1, y1) — прямоугольник, вне которого мазок холста не читает и не пишет. У щетины это след
    прядей с полями; мягкая кисть ещё до следа читает сырое слоя под своими волосками на оси хода (`сырое_под`), а след
    с отставанием прядей может лежать в стороне от оси — её рамка накрывает и ось."""
    if getattr(brush, 'кайма', 0.0) <= 0.0 or brush.shape == 'мастихин':
        return frame
    r = 0.5 * float(brush.width)
    return (min(frame[0], int(np.floor(x.min() - r))), min(frame[1], int(np.floor(y.min() - r))),
            max(frame[2], int(np.floor(x.max() + r)) + 1), max(frame[3], int(np.floor(y.max() + r)) + 1))


def rubs_in(m, threshold, pad, wet):
    """Часть 4в, мягкая кисть по сырому: порог нажима, с которого кончик достаёт до лежащей сырой краски. `порог` — щетины,
    `подушка` (nr,) — на сколько его поднимает подушка своей краски под кончиком, `сыр` (nr,) — сырая краска под гребнями
    в толщинах мазка. Щетина упругая и едет по своей подушке: лёгкой рукой полная кисть кладёт плашку своего цвета поверх
    сырого. Мягкий волос подушку не держит: краска у него — между волосками, она и ложится в лежащий сырой слой, краска
    в краску. Поэтому над сырым слоем своя краска порог у мягкой кисти не поднимает, а опускает (`_СЫРОЕ[0]`): полная кисть
    берёт лежащее и мешает его со своим прядями и под лёгкой рукой; чем плотнее рука, тем больше. Почти пустая (ореол,
    полутень: подушки нет) своё положенное не снимает. По тонкой сырой плёнке (кайма соседнего мазка: шов, 4б) ложиться
    не во что — там порог прежний (`_СЫРОЕ[2:]`: с какой толщины лежащего и на сколько толщины идёт переход).
    У щетины (м — None) — как было."""
    if m is None:
        return threshold
    return threshold - _WithYRResponseE[0] * pad * clamp((wet - _WithYRResponseE[2]) / _WithYRResponseE[3], 0.0, 1.0)


class Exchange:
    """Часть 4в-2: почти пустая мягкая кисть в толстом сыром слое (стык двух сырых заливок). Своей краски у неё — тонкая
    плёнка, подушки нет: пучок идёт в лежащем слое, и краска между волосками — та, что лежит. За шаг кончик меняется со
    слоем: столько-то лежащей краски уходит в каплю, столько же краски капли ложится на её место — объём слоя и капли те
    же, меняется цвет. Так кисть несёт краску одной заливки в другую, а не кладёт поверх плёнку своей.
    Сколько меняется — доля `_СТЫК[2]` лежащего под гребнем, с нажимом больше; пучок в слое или нет — по слою под соседними
    волосками (`_СТЫК[3]` раз выровнено: у самого стыка заливки тоньше, а пучок держится соседями), с толщины `_СТЫК[0]`
    мазка, переход `_СТЫК[1]`: по тонкой плёнке (ореол, шов 4б) обмена нет. Ничего не размывается: краску несёт капля
    гребня, поперёк пучка её разносит обмен соседних кончиков (`делят`)."""
    __slots__ = ('сел', 'пуста', 'толщина', 'мт', 'тонет', 'кладёт', 'набрано', 'на_месте', 'сыр', 'кс_холста', 'несёт', 'ёмкость', 'своё', 'своей', 'ушло', 'врозь')

    @staticmethod
    def for_(m, lean, Nc, nr, mt, ic, wet_g, ks_canvas, spacing_brush, W, clean=False):
        """Обмен или None — у щетины и у набранной кисти. `тощая` — во сколько раз плёнка своей краски тоньше той,
        с которой кисть чужой краски на кончик уже не берёт (`срастание.Вал`); `ic` — шаги пути под шагами переноса; `сыр_г`, `кс_холста` — лежащая сырая краска под гребнями, толщина и цвет.
        Часть 4в-4: у волоска своя длина и свой нажим вдоль хода (`_ПРЯДЬ`), соседи их не выравнивают: от них — какую долю
        разворошённой краски волосок несёт с собой (`несёт`, остальное мешает на месте) и сколько краски держит между собой
        и соседями (`ёмкость`, в каплях кончика): длинный волосок несёт набранное дальше короткого."""
        if m is None or lean <= 1.0:
            return None
        response = Exchange()
        response.empty, response.thickness, response.sinks, response.on_place, response.mt = float(clamp(lean - 1.0, 0.0, 1.0)), np.zeros((Nc, nr)), np.zeros((Nc, nr)), np.zeros((Nc, nr)), mt
        response.charged, response.wet, response.ks_canvas = np.zeros(nr), wet_g, ks_canvas
        response.settled = None
        if clean: response.charged, response.settled = np.ones(nr), np.zeros(nr, bool)   # 5а: у вытертой кисти своей плёнки на кончике нет — между волосками сразу лежащая краска
        _color_under_tuft(ks_canvas, wet_g, mt)   # З-1; Долг-ф: и у почти пустой кисти с краской — пустое место слоя и плёнка в тысячные мазка цвета в каплю не дают
        response.lays = (m.deep * (_HAndWithTAYa[6] * (1.0 - _HAndWithTAYa[4] * m.depth ** _HAndWithTAYa[5]))[None, :] if clean else m.lays)[ic]   # 4в-3: едва касающийся волосок меняется слабее — тем же законом, каким кладёт свою плёнку; 5а-2: у вытертой кисти — по нажиму волоска на холст, без прибавки `_ШОВ`
        share, r_lengths, r_sweep, wave, yo0, r_capacity = _PRYaD[:6]
        length = m.chance.standard_normal(nr)
        response.carries = clamp(share + r_lengths * length[None, :] + r_sweep * _noise(m.chance, Nc, nr, wave * W / spacing_brush), 0.0, 1.0)
        response.capacity = yo0 * np.exp(r_capacity * length)
        response.apart = 1.0
        if clean and len(_HAndWithTAYa) > 1:        # 5а-2: вытертый пучок держит краску не поровну — прядями, и краска пряди к соседней почти не идёт
            response.capacity, response.apart = yo0 * np.exp(_HAndWithTAYa[1] * _by_neighbors(length, _HAndWithTAYa[2]) / 0.61 ** min(_HAndWithTAYa[2], 1)), _HAndWithTAYa[3]
        response.own, response.own, response.went = np.ones(nr), np.ones(nr), np.zeros(nr)
        return response

    @staticmethod
    def feed(response, c, ks_with, ks_drops, path, own):
        """Краска, которая на шаге c приходит на кончик из ворса; заодно — насколько пучок идёт в лежащем слое
        (`тонет`, (nr,)). Часть 4в-3: между волосками залитого пучка стоит лежащая краска, своя из запаса расходится в ней —
        почти пустая кисть не подаёт на кончик свою краску весь ход (была плашка во всю ширину кисти).
        Часть 4в-4: пигмент кисти не пропадает. Своя краска доходит до кончика долей `своей`: вся, пока пучок не залит, и всё
        меньшая по мере хода в слое (на длине `_ПРЯДЬ[6]` px, у волоска с большей ёмкостью — дольше); остальной объём подачи —
        лежащая краска, как в 4в-3. Запас расходуется только на свою долю (`расход`):
        что ушло из запаса, то легло в след, остальное осталось в кисти. Без обмена — `кс_с`."""
        if response is None:
            return ks_with
        under = _by_neighbors(response.wet[c], _WithTYBrush[3])
        t = response.sinks[c] = response.empty * clamp((under / response.mt - _WithTYBrush[0]) / _WithTYBrush[1], 0.0, 1.0)
        if response.settled is not None:                  # 5а: вытертый пучок, впервые сев в сырое, заливается той краской, что тут лежит (объём слоя тот же)
            # З-1: сел — значит пучок идёт в слое (`тонет`), а не волосок задел плёнку тоньше той, с которой начинается обмен;
            # и где под самим кончиком плёнка тоньше этой, заливает его краска, что лежит под пучком у этого волоска, —
            # по объёму (тем же весом соседей, каким пучок тонет), а не цвет одного пикселя под кончиком. Было: волосок,
            # входящий в слой с пустого места, «садился» на первом пикселе с краской любой толщины и брал его цвет на всю
            # каплю; у кромки слоя плёнка в тысячные доли мазка несёт цвет случайный (до чёрного — цвета пустого места
            # слоя), и капля серого шла дальше в толстое светлое — серые хвосты по ходу. В толстом сыром — бит в бит как было
            new = ~response.settled & (path * response.wet[c] > 0.0) & (t > 0.0)
            if new.any():
                ks_drops[new] = response.ks_canvas[c][new]
                thin = new & (response.wet[c] < _WithTYBrush[0] * response.mt)      # под самим кончиком плёнка тоньше той, с которой идёт обмен
                if thin.any():
                    ks_drops[thin] = (_by_neighbors((response.ks_canvas[c] * response.wet[c][:, None]).T, _WithTYBrush[3]).T / np.maximum(under, 1e-12)[:, None])[thin]
                response.settled |= new
            if not response.settled.all():                # У-1: на несевшем волоске краски нет — его «цвет» тот, что под ним, чтобы ни при каком
                ks_drops[~response.settled] = response.ks_canvas[c][~response.settled]   # счёте (отсчёты между шагами, соседи) в след не шла краска набора
        response.own = 1.0 - t * (1.0 - response.own)
        response.own = response.own * np.exp(-t * path / (_PRYaD[6] * response.capacity))
        response.went += own * response.own
        return ks_with * response.own[:, None] + response.ks_canvas[c] * (1.0 - response.own)[:, None]

    @staticmethod
    def consumption(response):
        """Доля подачи, которая идёт из запаса своей краски (nr,) или 1 — без обмена."""
        return 1.0 if response is None else response.own

    @staticmethod
    def remember(response, brush, places, ks_drops):
        """Что осталось на кончиках — в память кисти (`Кисть._запомнить`). У-1: у вытертой кисти — только волоски, севшие
        в сырое: на прочих краски нет (цвет набора до `нагрузка=0` или заглушка мазка без цвета); не сел ни один — память
        кисти та же. Иначе — как было."""
        if response is None or response.settled is None or response.settled.all():
            brush._remember(places, ks_drops)
        elif response.settled.any():
            brush._remember(places[response.settled], ks_drops[response.settled])

    @staticmethod
    def balance(response, brush, reserve, charge0, charge, drop0, sh_g):
        """Баланс краски кисти после мазка с обменом — в `к._баланс`, объёмы в единицах слоя (h · px²): набрано (запас и
        первая капля), осталось в запасе, подано своей на кончик."""
        if response is not None:
            brush._balance = dict(charged=float(((reserve * charge0 + drop0) * sh_g).sum()), in_reserve=float((reserve * charge * sh_g).sum()), fed=float((response.went * sh_g).sum()), drop0=float((drop0 * sh_g).sum()))

    def spacing(self, c, wet, pressure, path, drop, ks_drops, ks_canvas, full, fed):
        """Шаг переноса c; `подано` — объём, пришедший на кончик на этом шаге. Ответ — для `делят`: краска капли после
        обмена, полная капля, пучок в слое (nr,) 0–1.
        Часть 4в-3: меняется со слоем та краска капли, что набрана по пути (`набрано`, доля капли): в начале хода на кончике
        только своя плёнка, лежащей между волосками ещё нет — кисть кладёт свою тонкую плёнку, как по сухому, а нести
        лежащую начинает по мере того, как ею заливается. Доля растёт с подачей из слоя и с самим обменом.
        Часть 4в-4: через кончик идёт доля `несёт` волоска, остальное он мешает на месте; набранное держит не одна капля
        кончика, а краска между волосками — `ёмкость` капель: волосок заливается и забывает набранное на своей длине хода."""
        sinks = self.sinks[c]
        kneads = _WithTYBrush[2] * sinks * (0.4 + 0.6 * pressure) * wet * self.lays[c]      # столько лежащей кончик ворошит под собой
        n = self.charged * self.carries[c]
        self.thickness[c], self.on_place[c] = kneads * n, kneads * (1.0 - n)
        q, holds = self.thickness[c] * path, drop * self.capacity
        self.charged = clamp((self.charged * holds + fed * sinks + q) / np.maximum(holds + fed + q, 1e-12), 0.0, 1.0)
        q = q[:, None]
        return (ks_drops * holds[:, None] + ks_canvas * q) / np.maximum(holds[:, None] + q, 1e-12), full, sinks * self.lays[c] * self.apart, None if self.settled is None else ~self.settled

    @staticmethod
    def not_from_nothing(response, wiped, not_removed, laid, V, V_r):
        """V4, 2а: краска не возникает. Обмен кладёт краски капли столько, сколько лежащей кончик заменил, и кончик уносит
        подобранное в каплю, а лежащая под ходом считана до хода: ход, который идёт по своему следу (спираль ореола — шаг
        витка 8 px у кисти 48), просит её с одного места на каждом витке, снять же можно только то, что лежит. Чего снять не
        вышло (`не_снято`, по пикселям, после своего слоя и слоёв ниже), то в след и не легло: плёнка `V` и её рельеф `V_р`
        убавлены на эту долю того, что легло (`легло`). У вытертой кисти то же делает `сведено`. Было: один кусок спирали
        ореола по сырому слою 0,2 прибавлял 16 тыс. единиц краски при кисти, набранной на 900, — бугор толщиной 300–760
        в центре ореола R 440, под светом серый диск («мишень»). Где просьба снята целиком, множитель — ровно 1: бит в бит.
        Без обмена (щетина, набранная кисть) — как было."""
        if response is None or wiped or not (not_removed > 0.0).any():
            return V, V_r
        k = clamp(1.0 - not_removed / np.maximum(laid, 1e-12), 0.0, 1.0)
        return V * k, V_r * k

    @staticmethod
    def in_trace(response, ts_drops, ts_canvas, film, i0, i1, f0, f1, g, ii, jj, weight):
        """Отсчёты плёнки `плёнка` (d, цвет, …) с обменом: на месте гребня легло краски капли столько, сколько лежащей
        он там заменил, и лежащая, которую он разворошил на месте (`ц_холста()` — её цвет по отсчётам): своя плёнка не
        ложится поверх, а расходится в ней. Ответ — плёнка и объём, снятый с лежащего слоя, по отсчётам; без обмена — 0."""
        if response is None:
            return (*film, 0.0)
        d, ts = film[:2]
        by_samples = lambda a: between_steps(a, i0, i1, f0, f1, g, ii, jj)
        exchange, place = by_samples(response.thickness) * weight, by_samples(response.on_place) * weight
        everything = d + exchange + place
        return (everything, (ts * d[:, None] + ts_drops * exchange[:, None] + ts_canvas() * place[:, None]) / np.maximum(everything, 1e-12)[:, None], *film[2:], exchange + place)


def _color_under_tuft(ks_canvas, wet, mt):
    """З-1: цвет лежащей краски под волоском вытертой кисти (Долг-ф: и почти пустой кисти с краской — обмен тот же)
    там, где под самим кончиком её нет или почти нет (тоньше `_ПОД_ПУЧКОМ` плёнки мазка), — цвет сырой краски под
    пучком у этого волоска, по объёму (соседи — тем же весом, каким пучок тонет, `_СТЫК[3]`); под всем пучком пусто —
    средний цвет сырой краски под ходом. Пишется на место, в `кс_холста` (Nc, nr, полос). У пустого места слоя цвета нет (в массиве — чёрный), у плёнки в тысячные мазка он
    случайный; объёма такой волосок не кладёт, но его «цвет» шёл в след счётом между соседними волосками и шагами —
    тёмная кайма у края краски слоя. Где краска под кончиком есть — не трогается: в сыром слое бит в бит как было."""
    thin = wet < _UNDER_TUFT * mt
    if not thin.any() or thin.all():
        return
    sh = np.nonzero(thin.any(axis=1))[0]
    ob = ks_canvas[sh] * wet[sh][:, :, None]
    weight = _by_neighbors(wet[sh], _WithTYBrush[3])
    beside = np.swapaxes(_by_neighbors(np.swapaxes(ob, 1, 2), _WithTYBrush[3]), 1, 2)
    shared = (ks_canvas * wet[:, :, None]).sum(axis=(0, 1)) / max(float(wet.sum()), 1e-30)
    has = weight > 1e-9 * mt
    color = np.where(has[:, :, None], beside / np.where(has, weight, 1.0)[:, :, None], shared)
    ks_canvas[sh] = np.where(thin[sh][:, :, None], color, ks_canvas[sh])


def clean(brush, load):
    """Часть 5а (растушёвка): (толщина плёнки полного мазка, вытерта ли кисть). Нагрузка 0 — кисть вытерта: своей краски нет
    ни в запасе, ни на кончике, а между волосками она держит столько, сколько плёнка почти пустой кисти `_ЧИСТАЯ[0]` — это
    только ёмкость пучка. Вытертая мягкая кисть плёнки не кладёт и с холста не уносит: сев в сырой слой, пучок заливается
    лежащей краской и дальше меняется ею со слоем (`Обмен`) — краски на холсте столько же. По сухому и по голому грунту
    не делает ничего."""
    H = brush.thickness_film(load)
    return (H, False) if H > 0.0 else (brush.thickness_film(_HAndWithTAYa[0]), True)


def sweep_hair(m, wiped, profile, ii, jj):
    """Г-3 (ворс растушёвки): вытертый мягкий волос в сырой краске тащит лежащую за собой по своей бороздке — что он
    разворошил (`Обмен.в_след`), ложится по поперечному профилю борозд (`борозда.профиль_борозд`): под кончиком
    ведущего волоска тоньше, между волосками — гребень. Объём сечения тот же (профиль поделён на своё среднее по
    ширине кисти). Без этого лежащая ложилась ровно под всей шириной пучка — середина растушёвки гладкая, как
    размытая. Кисть с краской и щетина — 1: как было."""
    if m is None or not wiped:
        return 1.0
    return (profile / np.maximum(profile.mean(axis=1, keepdims=True), 1e-9))[ii, jj]


def plough(m, wiped, weight_hair):
    """Г-3: отсчёты для поля «профиль борозд под волоском» вытертой мягкой кисти — к весам растра дописывается одно поле
    (касание × профиль, `ход_волоса`); у прочих кистей — ничего, поля прежние."""
    return [weight_hair] if m is not None and wiped else []


def by_hair(m, wiped, fields, touch):
    """Г-3: во что вытертая мягкая кисть ровняет лежащее под собой (множитель к сглаженному рельефу, вокруг 1).
    Мягкий волос гладит крупный рельеф щетины, но сам идёт в сырой краске бороздками: под кончиком ведущего волоска
    тоньше, между волосками — гребень (`борозда.профиль_борозд`; поле — последнее в `поля`, `плуг`). Где кисть не
    касалась — 1. Объём ровняния держит `ровно`. Прочие кисти — 1: ровняют к гладкому, как было."""
    if m is None or not wiped:
        return 1.0
    return np.where(touch > 1e-6, fields[-1] / np.maximum(touch, 1e-6), 1.0)


def place_lift(brush, wiped, center, ferrule):
    """Часть 5а-2: место гребня на кисти, от которого идёт порог его касания на входе и подъёме. У щетины порог идёт больше
    от места пряди (`обоймой`): прядь обоймы отрывается разом. Вытертый мягкий пучок прядей обоймы не держит (`пучок`): он
    отходит от холста куполом, волосок за волоском по своему месту — у следа нет прямого бока по границе пряди. Мягкая кисть
    с краской (нагрузка > 0) — как было."""
    return center if wiped and getattr(brush, 'кайма', 0.0) > 0.0 and brush.shape != 'мастихин' else ferrule


def even(wiped, evener, touches, wet=None, window=None):
    """Часть 5а: на сколько кисть разровняла рельеф лежащего под собой. Вытертая краски не прибавляет: что снято с бугров,
    то легло во впадины. Иначе — как было.
    З-1: двигает кисть только сырую краску, которой касается (`сырое` — её толщина под ходом до него, поле; `окно` —
    среднее по окну ровняния). (1) Остаток объёма сводится по местам, где сырая краска лежит, а не по всему следу
    кисти. Было: ход, начатый в краске и ушедший за её край, расстилал остаток ровной плёнкой по всему следу — и по
    пустому месту слоя в сотнях px от краски: плёнка без цвета (цвет пустого места слоя — чёрный) с покрытием до 2–3 %
    за ход, серое пятно на светлом нижнем слое. (2) На голое место рядом с краской кисть сгоняет краску в меру того,
    какой долей краски в окне она касается: краску, мимо которой прошла не задев, на голое не доливает (было: плёнка
    из ничего и без цвета вдоль кромки пятна). Где сырая краска лежит под всем следом — бит в бит как было."""
    if not wiped:
        return evener
    if wet is not None:
        has = wet > 0.0
        bare = ~has & (evener > 0.0)
        if bare.any():
            evener = np.where(bare, evener * clamp(window(wet * (touches > 0.0)) / np.maximum(window(wet), 1e-12), 0.0, 1.0), evener)
        touches = touches * has
    return evener - touches * (evener.sum() / max(float(touches.sum()), 1e-9))


def reduced(wiped, h_was, h_became, remove, asked, V, V_r, weight):
    """Часть 5а: лежащий слой после съёма и плёнка мазка. Вытертая кисть возвращает ровно столько, сколько разворошила: где
    лежащего под ней меньше, чем просил обмен, меньше и ложится; и разглаживание струй (`срастание.Струи.ровнять`) объёма
    не меняет. Иначе — как было."""
    if not wiped:
        return h_became, V, V_r
    V = V * (remove / np.maximum(asked, 1e-12))
    return h_became - weight * ((float(h_became.sum()) - float(h_was.sum()) + float(remove.sum())) / max(float(weight.sum()), 1e-9)), V, V


def release_along(profile, brush=None):
    """К5, поле журнала "load_along": профиль отдачи краски по ходу [[доля пути 0–1, множитель 0–1], …] -> массив (n, 2)
    или None. Доли строго по возрастанию. Только у мягкой кисти (`Кисть.кайма` > 0): щетина плёнку тоньше не кладёт —
    у неё бедный гребень сужается в нитку. Кривой профиль и щетина — ValueError."""
    if profile is None:
        return None
    try:
        p = np.asarray(profile, dtype=np.float64)
    except (TypeError, ValueError):
        p = None
    if p is None or p.ndim != 2 or p.shape[1] != 2 or len(p) < 1 or not np.isfinite(p).all():
        raise ValueError('load_along: должен быть списком пар [доля пути, множитель]')
    if (p[:, 0] < 0).any() or (p[:, 0] > 1).any() or (np.diff(p[:, 0]) <= 0).any():
        raise ValueError('load_along: доли пути — в 0–1, строго по возрастанию')
    if (p[:, 1] < 0).any() or (p[:, 1] > 1).any():
        raise ValueError('load_along: множитель вне 0–1')
    if brush is not None and (getattr(brush, 'кайма', 0.0) <= 0.0 or brush.shape == 'мастихин'):
        raise ValueError('load_along: только у мягкой кисти (кайма больше нуля)')
    return p


def _by_neighbors(a, times):
    """Ряд по гребням (…, nr), выровненный между соседними волосками `раз` раз (края — сами с собой)."""
    for _ in range(times):
        q = np.concatenate([a[..., :1], a, a[..., -1:]], axis=-1)
        a = 0.25 * q[..., :-2] + 0.5 * q[..., 1:-1] + 0.25 * q[..., 2:]
    return a


def _together(a):
    """Случай по волоскам (…, nr) — общий с соседями (4а-2): частый мягкий волос короче, длиннее и отходит от холста не
    по одному, а с соседом. Разброс — прежний (один проход оставляет 0,61 разброса белого шума)."""
    return _by_neighbors(a, _TELResponse[2]) / 0.61 ** min(_TELResponse[2], 1) if _TELResponse[2] else a


# ---- тело мягкой кисти (часть 4а-2). Всё зовёт `укладка.положить_мазок`; м None (щетина) — ответ тот, что дали.
def tuft(m, tack, leaving):
    """Пряди мягкой кисти (N, ns): тонкий частый волос с краской держится одним пучком — к осям прядей при слабом нажиме
    не собирается и вбок ходит весь разом, а не прядь от пряди: щели между прядями не открываются."""
    if m is None:
        return tack, leaving
    return np.ones_like(tack), np.broadcast_to(leaving.mean(axis=1, keepdims=True), leaving.shape)


def without_slit(m, gap):
    """Просвет между прядями (`срастание.Просвет`): у мягкой кисти щелей между прядями нет — нечему открываться и затекать."""
    if m is not None:
        gap.has = False
    return gap


def reserve(m, uneven, thickness):
    """Неровный запас гребней и густота краски на них (Nc, nr, вокруг 1) у мягкого волоса: волос частый и тонкий, краску
    держит не каждый волосок своей нитью, а пучок между волосками — комок запаса лежит на нескольких соседних, и пустеют
    они вместе; густота у соседей близка."""
    if m is None:
        return uneven, thickness
    return 1.0 + _by_neighbors(uneven - 1.0, _TELResponse[0]), 1.0 + _by_neighbors(thickness - 1.0, _TELResponse[4])


def furrows(m, furrow):
    """Жизнь борозд (`борозда.борозды`) под мягким волосом: тонкий гибкий волосок плёнку до дна не скребёт и комка,
    сорвавшись, не оставляет — борозда и капля мельче щетинных во столько раз (`_ТЕЛО[3]`). Место и ход борозд — те же."""
    if m is None or furrow is None:
        return furrow
    deeper, wider, drop, sticking = furrow
    return deeper * _TELResponse[3], wider, drop * _TELResponse[3], sticking


def share(m, drop, ks_drops, full, in_layer=None, empty=None):
    """Соседние волоски мягкой кисти делят каплю на кончиках: краска между ними — одно тело, и полнота кончиков
    (капля к полной) за шаг переноса выравнивается на долю `_ТЕЛО[1]`. Объём и цвет не теряются: что ушло от
    полного волоска, пришло к соседу с его краской. Ответ — капля (nr,) и её краска (nr, полос).
    У-1: `пусты` (nr,) — волоски вытертой кисти, ещё не севшие в сырое (`Обмен.сел`): краски между ними нет, и с соседом
    они не меняются ничем — цвет, с которым кисть набирали до `нагрузка=0`, в след не идёт. None — как было."""
    if m is None or len(drop) < 2:
        return drop, ks_drops
    bridge = 1.0 if empty is None or not empty.any() else (~(empty[1:] | empty[:-1])).astype(np.float64)
    r = drop / np.maximum(full, 1e-12)
    flow = 0.5 * _TELResponse[1] * (r[1:] - r[:-1]) * np.minimum(full[1:], full[:-1]) * bridge     # > 0 — от правого к левому
    from_pr, from_left = np.maximum(flow, 0.0), np.maximum(-flow, 0.0)
    asked = np.zeros_like(drop)
    asked[1:] += from_pr
    asked[:-1] += from_left
    gives = np.minimum(1.0, drop / np.maximum(asked, 1e-12))                           # больше своей капли волосок не отдаст
    from_pr, from_left = from_pr * gives[1:], from_left * gives[:-1]
    new = drop.copy()
    new[1:] -= from_pr
    new[:-1] -= from_left
    ks = ks_drops * new[:, None]
    new[:-1] += from_pr
    ks[:-1] += ks_drops[1:] * from_pr[:, None]
    new[1:] += from_left
    ks[1:] += ks_drops[:-1] * from_left[:, None]
    ks = np.where((new > 1e-12)[:, None], ks / np.maximum(new, 1e-12)[:, None], ks_drops)
    # часть 4в: краска между мягкими волосками — одно тело и при равной полноте: соседние кончики за шаг переноса меняются
    # долей `_СЫРОЕ[1]` меньшей из двух капель. Объём у каждого тот же, краска — мешается поперёк пучка (одна краска — без перемен)
    exchange = _WithYRResponseE[1] * np.minimum(new[1:], new[:-1]) * bridge
    diff = (ks[1:] - ks[:-1]) * exchange[:, None]
    ks2 = ks.copy()
    ks2[:-1] += diff / np.maximum(new[:-1], 1e-12)[:, None]
    ks2[1:] -= diff / np.maximum(new[1:], 1e-12)[:, None]
    if in_layer is not None and in_layer.any():
        # часть 4в-2: в толстом сыром слое пучок полон лежащей краски, и поперёк она расходится быстрее — ещё `_СТЫК[4]` раз
        # по доле `_СТЫК[5]` за шаг (между волосками, которые оба в слое)
        exchange = _WithTYBrush[5] * np.minimum(in_layer[1:], in_layer[:-1]) * np.minimum(new[1:], new[:-1]) * bridge
        for _ in range(_WithTYBrush[4]):
            diff = (ks2[1:] - ks2[:-1]) * exchange[:, None]
            ks2[:-1] += diff / np.maximum(new[:-1], 1e-12)[:, None]
            ks2[1:] -= diff / np.maximum(new[1:], 1e-12)[:, None]
    return new, ks2


def mask(m, touch_m, filled, x, bristle):
    """Что кладёт отсчёт гребня (N, nm). У щетины (`щетина()` — её счёт) бедный краской гребень сужается в нитку под своим
    волоском, и между нитками — голая щель в волосок. Мягкие волоски стоят вплотную и смыкаются: ширину следа гребня держит
    касание (`кас_м`), а бедный гребень кладёт на ту же ширину плёнку тоньше — тот же объём, что сужаясь (`заполнен`)."""
    if m is None:
        return bristle()
    width = clamp((touch_m * 1.2 - x[None, :]) * 10.0, 0.0, 1.0)
    if m.release is not None:
        # К5, поле журнала "load_along": рука по ходу отпускает кисть — волосок касается холста на ту же ширину, а плёнку
        # отдаёт тоньше во столько раз. Ширина следа и кайма те же; тоньшает плёнка, а не редеет след
        width = width * m.release
    return width * clamp((filled * 1.2 - 0.05) / np.maximum(np.minimum(touch_m * 1.2 - 0.05, 0.95), 1e-6), 0.0, 1.0)


def by_path(m, X, Y, u, ds):
    """К5, с полем журнала "load_along": плёнка ложится на путь волоска, а не на шаг оси кисти. Отсчёт профиля за шаг
    заметает на холсте свою площадь: на дуге внутренний бок кисти идёт короче наружного, у центра поворота кончик почти
    стоит, отставший косой ворс идёт уже; где волосок идёт вдоль ряда соседей, своей полосы он не заметает.
    Ответ (N, nm) — эта площадь к площади на прямом ходе (`шир * ds`): толщина плёнки по ширине следа выходит той же, что
    на прямой, а не толще к центру дуги (были витки). Площадь — шаг кончика по пути на расстояние до пути соседа; кончики
    стоят в своих следах (`за_кистью`), и разное место кончиков у соседних прядей в неё не входит. Без поля — 1: прежние
    журналы бит в бит."""
    if m is None or m.release is None or X.shape[0] < 2 or X.shape[1] < 2:
        return 1.0
    xi, yi, du = np.gradient(X, axis=0), np.gradient(Y, axis=0), np.gradient(u)[None, :]
    return clamp(np.abs(xi * np.gradient(Y, axis=1) - yi * np.gradient(X, axis=1)) / (du * ds), 0.0, _PATH_MAX)


def behind_brush(m, bx, by, vd, qx, qy):
    """Места кончиков на холсте (N, n): корни волосков (bx, by) и место кончика вдоль ворса `вд` (N, n), px (позади корня —
    меньше нуля, впереди — больше), qx, qy (N,) — куда смотрит ворс. Без поля "load_along" — как было: кончик стоит от
    корня по направлению хода оси кисти. На прямой это верно; на дуге уже полуширины кисти корни по разные стороны от
    центра поворота идут в разные стороны, а кончики «по ходу оси» все выходят наружу от центра — в центре витков яма
    радиусом в `вд` (4–8 px): до неё не достаёт ни один волосок. К5, с полем: ворс лежит в следе своего волоска — кончик
    стоит на пути своего корня, на |вд| px этого пути позади него или впереди. На прямой — то же место, что было; на дуге
    кончик идёт тем же кругом, что корень, а у волоска в центре поворота стоит на месте: центр закрыт. За началом и концом
    пути корня — по прямой, как было."""
    X, Y = bx + vd * qx[:, None], by + vd * qy[:, None]
    if m is None or m.release is None or len(bx) < 2:
        return X, Y
    σ = np.concatenate([np.zeros((1, bx.shape[1])), np.cumsum(np.hypot(np.diff(bx, axis=0), np.diff(by, axis=0)), axis=0)])
    for j in range(bx.shape[1]):
        target = σ[:, j] + vd[:, j]
        behind = target - clamp(target, 0.0, σ[-1, j])                       # вышло за концы пути корня — этот остаток идёт по прямой
        edge = np.where(behind < 0.0, 0, len(bx) - 1)
        X[:, j] = np.interp(target, σ[:, j], bx[:, j]) + behind * qx[edge]
        Y[:, j] = np.interp(target, σ[:, j], by[:, j]) + behind * qy[edge]
    return X, Y


def released(m, clot):
    """К5, "load_along": сгусток и наплыв остановки (N, nm) сходят с кисти той же отдачей, что плёнка: отпущенная кисть
    (множитель 0) не оставляет ничего. Тем же множится касание (N, nm): отпущенная кисть лежащую сырую краску не снимает,
    не втирает и не ровняет. Без поля — как было."""
    return clot if m is None or m.release is None else clot * m.release


def released(m, ic):
    """К5, "load_along": отдача на шагах переноса (Nc,) — ею множатся подача из запаса на кончик, расход запаса, сход
    капли и съём лежащей сырой краски: отпущенная кисть (множитель 0) краску не тратит, не подбирает и дальше по ходу
    кладёт как свежая. Без поля — единицы."""
    return np.ones(len(ic)) if m is None or m.release is None else m.release[ic, 0]


def separate(m, X, Y, ax, ay, ridge=None):
    """Места на холсте (N, …) — с уходом крайних волосков мягкой кисти вбок, по широкой оси; м None (щетина) — как были."""
    if m is None:
        return X, Y
    if ridge is None:
        in_ = m.sideways
    else:
        k, w = m.between
        in_ = m.sideways[:, k] * (1.0 - w)[None, :] + m.sideways[:, np.minimum(k + 1, m.sideways.shape[1] - 1)] * w[None, :]
    return X + in_ * ax[:, None], Y + in_ * ay[:, None]
