"""Мастихин: пять проб ножа на чистом холсте. Лист проб инструмента, не кусок картины.

    python3 примеры/нож.py [папка]        # из папки «движок»; пишет нож.png и печатает мерки

Холст 8 px/мм, нож 5,5 мм (44 px). Пробы слева направо:
1. `плоскость` — нож с краской по голому грунту: гладкая лента, валики по бокам, ком там, где нож оторван;
2. `размазать` — нож без краски (`нагрузка=0`, цвет `None`) поперёк двух сырых пастозных ходов, нажим 0,8: сырое срезано
   до тонкой плёнки и протянуто по ходу, краски в слое столько же;
3. `по_сухому` — те же ходы высушены, нож с краской поперёк: нажим 0,3 садит краску на вершины, 0,95 оставляет в низинах;
4. `срезать` — нож без краски с нажимом 1 по толстому сырому: слой снят до следа, краска ушла на нож (`о.на_ноже`);
5. `ребро` — `касание=0`: с краской — линия-валик, без краски по сырому — борозда с валиками.
Импорт ничего не кладёт: `from примеры.нож import плоскость, размазать, по_сухому, срезать, ребро` (из «движок»)."""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))   # папка «движок»

import numpy as np

from кисть import Холст, Кисть, жест

ПРЕСЕТЫ = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'пресеты')
ГРУНТ = (150, 141, 126)
КРАСНАЯ, СИНЯЯ, СВЕТЛАЯ, ОХРА = (200, 60, 40), (40, 70, 160), (240, 235, 220), (210, 190, 150)


def _нож(**поля):
    return Кисть.из_файла(os.path.join(ПРЕСЕТЫ, 'мастихин.json'), **поля)


def _холст(ш=400, в=200, px=8.0):
    х = Холст(ш, в, грунт=ГРУНТ, px_на_мм=px)
    х.замер = False
    return х


def _два_хода(х, сушить=False):
    """Два пастозных хода щетиной — что нож размазывает или по чему идёт."""
    к = Кисть.из_файла(os.path.join(ПРЕСЕТЫ, 'плоская.json'), ширина=40)
    for j, (y, ц) in enumerate(((60, КРАСНАЯ), (140, СИНЯЯ))):
        х.мазок(жест([[30, y], [370, y + 3]], 40, 'остановка', сид=30 + j, нажим=0.7), ц, к, нагрузка=0.9)
        к.вытереть()
    if сушить:
        х.подсушить(1.0)


def плоскость(нагрузка=0.6, нажим=0.7, px=8.0):
    """Нож с краской по голому грунту. Ответ — холст."""
    k = px / 8.0
    х = _холст(int(400 * k), int(120 * k), px)
    х.мазок(жест([[40 * k, 60 * k], [360 * k, 60 * k]], 44 * k, 'подъём', сид=10, нажим=нажим), ОХРА, _нож(ширина=44 * k), нагрузка=нагрузка)
    return х


def размазать(нажим=0.8):
    """Нож без краски поперёк двух сырых пастозных ходов. Ответ — холст и толщина слоя до хода ножа."""
    х = _холст()
    _два_хода(х)
    до = np.array(х.слои['основа'].толщина[0:200, 0:400], np.float64)
    х.мазок(жест([[200, 20], [205, 185]], 44, 'подъём', сид=40, нажим=нажим), None, _нож(), нагрузка=0)
    return х, до


def по_сухому(нажим=0.5, нагрузка=0.3):
    """Нож с краской поперёк двух высохших пастозных ходов. Ответ — холст и толщина слоя до хода ножа."""
    х = _холст()
    _два_хода(х, сушить=True)
    до = np.array(х.слои['основа'].толщина[0:200, 0:400], np.float64)
    х.мазок(жест([[200, 20], [205, 185]], 44, 'остановка', сид=40, нажим=нажим), СВЕТЛАЯ, _нож(), нагрузка=нагрузка)
    return х, до


def срезать(нажим=1.0):
    """Нож без краски с полным нажимом по толстому сырому слою. Ответ — холст, толщина до и ответ мазка ножа."""
    х = _холст()
    х.мазок(жест([[30, 100], [370, 103]], 120, 'остановка', сид=50, нажим=0.8), КРАСНАЯ,
            Кисть.из_файла(os.path.join(ПРЕСЕТЫ, 'плоская.json'), ширина=60), нагрузка=1.0)
    до = np.array(х.слои['основа'].толщина[0:200, 0:400], np.float64)
    х.замер = True
    о = х.мазок(жест([[120, 30], [280, 170]], 44, 'остановка', сид=60, нажим=нажим), None, _нож(), нагрузка=0)
    return х, до, о


def ребро():
    """Ребро ножа (`касание=0`): с краской по грунту и сырому, без краски по сырому. Ответ — холст и толщина до ножа."""
    х = _холст()
    х.мазок(жест([[30, 100], [370, 103]], 120, 'остановка', сид=50, нажим=0.8), КРАСНАЯ,
            Кисть.из_файла(os.path.join(ПРЕСЕТЫ, 'плоская.json'), ширина=60), нагрузка=1.0)
    до = np.array(х.слои['основа'].толщина[0:200, 0:400], np.float64)
    х.мазок(жест([[120, 20], [120, 180]], 44, 'остановка', сид=41, нажим=0.6), СВЕТЛАЯ, _нож(), нагрузка=0.6, касание=0)
    х.мазок(жест([[280, 40], [280, 160]], 44, 'остановка', сид=42, нажим=0.8), None, _нож(), нагрузка=0, касание=0)
    return х, до


def _кадр(х):
    к = х.картинка(поверхность='полуматовое')
    return (np.clip(np.where(к <= 0.0031308, к * 12.92, 1.055 * np.power(np.maximum(к, 1e-9), 1 / 2.4) - 0.055), 0, 1) * 255 + 0.5).astype(np.uint8)


if __name__ == '__main__':
    from PIL import Image
    куда = sys.argv[1] if len(sys.argv) > 1 else '.'
    кадры = []
    х = плоскость()
    h = np.asarray(х.слои['основа'].толщина)
    print(f'плоскость: плёнка {np.median(h[40:80, 100:300]):.2f}, валик у бока {h[30:50, 150].max():.2f}, ком на отрыве {h[60, 300:390].max():.2f}')
    кадры.append(np.pad(_кадр(х), ((40, 40), (0, 0), (0, 0)), constant_values=255))
    х, до = размазать()
    h = np.asarray(х.слои['основа'].толщина)
    print(f'размазать: объём {до.sum():.0f} → {h.sum():.0f}; под ножом на ходе {до[60, 190:215].mean():.2f} → {h[60, 190:215].mean():.2f}; в щели между ходами {h[100, 190:215].mean():.2f}')
    кадры.append(_кадр(х))
    for нажим in (0.3, 0.95):
        х, до = по_сухому(нажим)
        h = np.asarray(х.слои['основа'].толщина)
        print(f'по сухому, нажим {нажим}: покрыто новым на ходе {float(((h - до)[45:75, 185:220] > 0.05).mean()):.2f}; наименьший прирост {float((h - до).min()):.3f}')
        кадры.append(_кадр(х))
    х, до, о = срезать()
    print(f'срезать: объём {до.sum():.0f} → {np.asarray(х.слои["основа"].толщина).sum():.0f}; {о}')
    кадры.append(_кадр(х))
    х, до = ребро()
    кадры.append(_кадр(х))
    Image.fromarray(np.concatenate([np.pad(k, ((0, 0), (0, 6), (0, 0)), constant_values=255) for k in кадры], 1)).save(os.path.join(куда, 'нож.png'))
