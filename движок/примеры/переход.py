"""Гладкий переход тона по сырому (У-1): два сырых пятна одного слоя и растушёвка стыка вытертой мягкой кистью.
Лист проб кисти, не кусок картины. Замер — `х.переход(…)`: ширина спада 10–90 % и наибольшая ступень L на 8 px.

    python3 примеры/переход.py [папка] [--до]   # из папки «движок»; --до — прежний рецепт (короткие ходы в одну сторону)

Холст 1200×400. Пятна — `плоская` 90, нагрузка 0,6, ряды через 55 px: слева L 75, справа L 90 (C 0,03, h 250), стык
у x = 600 внахлёст на 30 px; правое кладётся справа налево — к стыку, кончая ход на сыром левом. Растушёвка —
`мягкая` 90, `нагрузка=0`, без цвета (кисть вытерта: своей краски нет, пучок заливается лежащей и носит её), нажим 0,35,
`'подъём'`, ряды через 24 px, шесть проходов со сдвигом 5 px; ход 200–500 px, середина хода у стыка ± 80 px, каждый
следующий — в другую сторону, `к.вытереть()` перед каждым. Мерка 18.11, сид примера: переход ~240 px, ступень ~1,6 L;
прежний рецепт (ход 120 px в одну сторону, `'остановка'`, 4 прохода через 12 px) — ~10 px, ступень ~12 L.
Импорт ничего не кладёт: `from примеры.переход import пятна, растушевать` (из «движок»)."""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))   # папка «движок»

import numpy as np

from кисть import Холст, Кисть, жест, цвет

ПРЕСЕТЫ = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'пресеты')
ГРУНТ = (150, 141, 126)
ТЁМНАЯ, СВЕТЛАЯ = цвет(75, 0.03, 250), цвет(90, 0.03, 250)
Ш, В, СТЫК = 1200, 400, 600


def пятна(х, слой='небо'):
    """Два сырых пятна плоской 90 в одном слое, стык у x = СТЫК внахлёст."""
    к = Кисть.из_файла(os.path.join(ПРЕСЕТЫ, 'плоская.json'), ширина=90)
    for i, y in enumerate(range(-10, В + 60, 55)):
        for j, (a, b, ц) in enumerate(((-80, СТЫК + 30, ТЁМНАЯ), (Ш + 80, СТЫК - 30, СВЕТЛАЯ))):
            х.мазок(жест([[a, y], [(a + b) / 2, y + 2], [b, y]], 90, 'остановка', сид=100 + 10 * i + j, нажим=0.65),
                    ц, к, слой=слой, сид=100 + 10 * i + j, нагрузка=0.6)
            к.вытереть()


def растушевать(х, слой='небо', ширина=90, нажим=0.35, длины=(200, 500), разброс=80, проходы=6, шаг=24,
                конец='подъём', туда_сюда=True, сид=7000):
    """Растушёвка стыка у x = СТЫК вытертой мягкой кистью: ходы поперёк стыка, разной длины и места, туда и обратно.
    Ответ — сколько ходов."""
    к = Кисть.из_файла(os.path.join(ПРЕСЕТЫ, 'мягкая.json'), ширина=ширина)
    r = np.random.default_rng(сид)                       # места ходов — от сида примера; мазки — своими сидами
    n = 0
    for p in range(проходы):
        for y in np.arange(-20 + (p * 5) % шаг, В + 20, шаг):
            к.вытереть()
            д, c = r.uniform(*длины), СТЫК + r.uniform(-разброс, разброс)
            a, b = c - д / 2, c + д / 2
            if туда_сюда and n % 2:
                a, b = b, a
            yy = y + r.uniform(-3, 3)
            х.мазок(жест([[a, yy], [b, yy + r.uniform(-4, 4)]], ширина, конец, сид=сид + n, нажим=нажим),
                    None, к, слой=слой, сид=сид + n, нагрузка=0)          # без цвета: кисть вытерта
            n += 1
    return n


ПРЕЖНИЙ = dict(ширина=48, нажим=0.45, длины=(120, 120), разброс=0, проходы=4, шаг=12, конец='остановка', туда_сюда=False)


def лист(прежний=False, ядра=None, журнал=None):
    """Холст с пятнами и растушёвкой. Ответ — (холст, мерка стыка до растушёвки, мерка после)."""
    х = Холст(Ш, В, грунт=ГРУНТ, px_на_мм=8.0, ядра=ядра, журнал=журнал)
    пятна(х)
    область = (СТЫК - 400, 100, СТЫК + 400, 300)          # 200 px по высоте — среднее поперёк
    до = х.переход(область)
    растушевать(х, **(ПРЕЖНИЙ if прежний else {}))
    return х, до, х.переход(область)


if __name__ == '__main__':
    куда = next((a for a in sys.argv[1:] if not a.startswith('--')), '.')
    os.makedirs(куда, exist_ok=True)
    х, до, после = лист('--до' in sys.argv, журнал=os.path.join(куда, 'переход.jsonl'))
    for имя, м in (('пятна', до), ('растушёвка', после)):
        print(f"{имя}: L {м['L_от']} → {м['L_до']}, переход 10–90 % {м['ширина']} px ({м['от_10']}–{м['до_90']}), "
              f"ступень {м['ступень']} L у x {м['где']}")
    х.взгляд((СТЫК - 300, 0, СТЫК + 300, В), путь=os.path.join(куда, 'переход.png'))
