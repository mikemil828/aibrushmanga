"""Растушёвка за край краски слоя (З-1): вытертая мягкая кисть идёт из сырого пятна своего слоя на пустое место слоя
и обратно. Лист проб кисти, не кусок картины.

    python3 примеры/за_край.py [папка]   # из папки «движок»: кропы ×4 до и после, числа в окно

Холст 460×220. Слой «низ» — светлые ходы `плоская` 100, высушен. Слой «пятно» — одна светлая краска `мягкая` 48,
стоячими ходами: плотно у x 40–110 (нагрузка 0,4), дальше плёнка сходит на нет (0,2 → 0,08 → 0,02, до x ≈ 215) — край
без шва, как у второго сеанса по сухому. Растушёвка — `мягкая` 48, `нагрузка=0`, цвет `None`, нажим 0,45, `'подъём'`:
ходы через 14 px, чётные — из пятна за край (x 70 → 430), нечётные — с пустого места в пятно (430 → 70).

Что должно быть (и что мерит `мерка`): вне краски слоя ход не делает ничего — нижний слой тот же, в слое «пятно» там
пусто; в самой краске слоя нет цвета темнее её самой — у слоя одна краска, тёмному взяться неоткуда. До З-1 было
иначе: за краем краски ложилась плёнка без цвета (серое на светлом), а ход, входящий в пятно с пустого места, вёл
в светлое серые хвосты.
Импорт ничего не кладёт: `from примеры.за_край import лист, мерка` (из «движок»)."""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))   # папка «движок»

import numpy as np

from кисть import Холст, Кисть, жест

ПРЕСЕТЫ = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'пресеты')
ГРУНТ = (166, 146, 129)
НИЗ, КРАСКА = (243, 240, 235), (255, 255, 251)
Ш, В = 460, 220
ВНЕ = (320, 20, 440, 200)        # область, где краски слоя «пятно» нет: дальше двух ширин кисти от края пятна
В_КРАСКЕ = (40, 30, 200, 190)    # область пятна с его сходящим краем


def пятно(х, сид=0):
    """Высохший светлый «низ» и сырое пятно слоя «пятно», сходящее на нет к x ≈ 215."""
    пл = Кисть.из_файла(os.path.join(ПРЕСЕТЫ, 'плоская.json'), ширина=100)
    for i, y in enumerate(range(20, В + 40, 60)):
        х.мазок(жест([[-40, y], [Ш + 40, y]], 100, 'остановка', сид=сид + i, нажим=0.7), НИЗ, пл.с(), слой='низ', нагрузка=0.6)
    х.подсушить(1.0)
    мг = Кисть.из_файла(os.path.join(ПРЕСЕТЫ, 'мягкая.json'), ширина=48)
    n = 0
    for x, наг in ((40, 0.4), (75, 0.4), (110, 0.4), (140, 0.2), (165, 0.08), (190, 0.02)):
        for y0 in (15, 110):
            х.мазок(жест([[x, y0], [x, y0 + 95]], 48, 'остановка', сид=сид + 100 + n, нажим=0.5), КРАСКА, мг.с(), слой='пятно', нагрузка=наг)
            n += 1
    return мг


def растушевать(х, мг, сид=0):
    """Вытертая мягкая 48 поперёк края пятна: из краски на пустое место слоя и обратно."""
    for j, y in enumerate(range(30, В - 20, 14)):
        a, b = (70, 430) if j % 2 == 0 else (430, 70)
        х.мазок(жест([[a, y], [b, y]], 48, 'подъём', сид=сид + 300 + j, нажим=0.45), None, мг.с(), слой='пятно', нагрузка=0)


def _состояние(х):
    """Картинка (серое sRGB, без света) и поля слоя «пятно» — для мерки."""
    x0, y0, x1, y1 = В_КРАСКЕ
    сл = х.слои['пятно']
    return dict(вид=np.asarray(х.взгляд(свет=False), dtype=np.float64).mean(axis=2),
                цвет=np.array(сл.цвет)[y0:y1, x0:x1].mean(axis=2), покрытие=np.array(сл.покрытие),
                толщина=np.array(сл.толщина))


def мерка(до, после):
    """Что сделала растушёвка: вне краски слоя — среднее |ΔL| картинки (серое sRGB 0–255), наибольшее потемнение
    пикселя, пиксели слоя с плёнкой; в краске слоя — самый тёмный цвет плёнки, что кроет (покрытие ≥ 0,3; линейный
    свет 0–1), до и после, и пиксели с тёмной плёнкой (цвет ниже 0,6 при покрытии ≥ 0,01)."""
    x0, y0, x1, y1 = ВНЕ
    d = (после['вид'] - до['вид'])[y0:y1, x0:x1]
    a0, b0, a1, b1 = В_КРАСКЕ
    def тёмное(с):
        A = с['покрытие'][b0:b1, a0:a1]
        return float(с['цвет'][A >= 0.3].min()), int(((с['цвет'] < 0.6) & (A >= 0.01)).sum())
    return dict(вне_dL=float(np.abs(d).mean()), вне_темнее=float(-d.min()),
                вне_плёнки=int((после['толщина'][y0:y1, x0:x1] > 0).sum()),
                цвет_до=тёмное(до)[0], цвет_после=тёмное(после)[0], тёмных_до=тёмное(до)[1], тёмных_после=тёмное(после)[1])


def лист(сид=0, ядра=1, журнал=None):
    """Холст с пятном и растушёвкой за край. Ответ — (холст, мерка)."""
    х = Холст(Ш, В, грунт=ГРУНТ, px_на_мм=8.0, ядра=ядра, журнал=журнал)
    мг = пятно(х, сид)
    до = _состояние(х)
    растушевать(х, мг, сид)
    return х, мерка(до, _состояние(х)), до


if __name__ == '__main__':
    куда = next((a for a in sys.argv[1:] if not a.startswith('--')), '.')
    os.makedirs(куда, exist_ok=True)
    for сид in (0, 1000, 2000):
        х, м, _ = лист(сид)
        print(f"сид {сид}: вне краски слоя |ΔL| {м['вне_dL']:.2f}, темнее всего на {м['вне_темнее']:.1f}, пикселей с плёнкой {м['вне_плёнки']}; "
              f"в краске: самый тёмный цвет {м['цвет_до']:.3f} → {м['цвет_после']:.3f}, тёмной плёнки {м['тёмных_до']} → {м['тёмных_после']} px")
        if сид == 0:
            х.взгляд((120, 30, 270, 180), 4, свет=False, путь=os.path.join(куда, 'за_край_x4.png'))
            х.взгляд((0, 0, Ш, В), 2, свет=False, путь=os.path.join(куда, 'за_край.png'))
