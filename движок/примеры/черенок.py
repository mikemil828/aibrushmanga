"""Процарапывание черенком по сырому (К-14а): светлая линия одним движением. Лист проб инструмента, не кусок картины.

    python3 примеры/черенок.py [папка]   # из папки «движок»: лист 1:1 и кропы ×4, числа в окно

Холст 75×75 мм (600×600 px при 8 px/мм). Светлый слой высушен, поверх — тёмный сырой (нагрузка 0,6, ряды
внахлёст на полкисти). Шесть пар линий
`х.снять(точки, 'черенок', ширина=…)`: конец 1 и 3 мм, нажим 0,3 / 0,6 / 0,9, прямая и дуга.

- нажим 0,9 — конец идёт по сухому: по оси линии открыт нижний слой, по бокам — валики из раздвинутой краски;
- нажим 0,6 — под концом плёнка: линия темнее; 0,3 — борозда в краске, нижнего не видно;
- конец 3 мм при том же нажиме оставляет плёнку втрое толще, чем 1 мм; линия у него шире, а чистая полоса по оси —
  узкая: конец круглый;
- объём краски на листе тот же, сухой слой не тронут.

`мерка(х, места)` — L по оси каждой прямой и L нижнего слоя там же, объём слоёв до и после, валики.
Импорт ничего не кладёт: `from примеры.черенок import лист, мерка` (из «движок»)."""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))   # папка «движок»

import numpy as np

from кисть import Холст, Кисть, жест

ПРЕСЕТЫ = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'пресеты')
ГРУНТ = (200, 190, 170)
СВЕТЛАЯ, ТЁМНАЯ = (214, 170, 92), (38, 30, 24)
ЛИНИИ = ((1, 0.3), (1, 0.6), (1, 0.9), (3, 0.3), (3, 0.6), (3, 0.9))      # конец, мм; нажим


def _L(картинка):
    """Светлота L* линейной картинки."""
    к = np.asarray(картинка, np.float64)[..., :3]
    Y = 0.2126 * к[..., 0] + 0.7152 * к[..., 1] + 0.0722 * к[..., 2]
    return 116.0 * np.cbrt(np.maximum(Y, 1e-9)) - 16.0


def _объём(х):
    return sum(float(np.asarray(с.толщина, np.float64).sum()) for с in х.слои.values())


def лист(px_на_мм=8.0, нагрузка_низа=0.25):
    """Лист проб. Ответ: (холст, места) — в `места` линии, ответы черенка и снятое до процарапывания (для `мерка`)."""
    k = px_на_мм
    х = Холст(int(75 * k), int(75 * k), грунт=ГРУНТ, px_на_мм=px_на_мм)
    пл = Кисть.из_файла(os.path.join(ПРЕСЕТЫ, 'плоская.json'), ширина_мм=7.5)
    ряды = [(2.5 + 6.9 * i) * k for i in range(12)]
    for i, y in enumerate(ряды):
        х.мазок(жест([[-5 * k, y], [80 * k, y]], 7.5 * k, 'остановка', сид=i, нажим=0.7), СВЕТЛАЯ, пл.с(), слой='низ', нагрузка=нагрузка_низа)
    х.подсушить(1.0)
    места = {'k': k, 'L_низа': _L(х.картинка(свет=False)),
             'низ': {п: np.array(getattr(х.слои['низ'], п)) for п in ('толщина', 'цвет', 'покрытие', 'влажность', 'схват')}}
    for i in range(24):                                        # тёмный — рядами внахлёст на полкисти: кроет сплошь
        y = (1.0 + 3.45 * i) * k
        х.мазок(жест([[-5 * k, y + 0.9 * k], [80 * k, y - 0.6 * k]], 7.5 * k, 'остановка', сид=100 + i, нажим=0.7), ТЁМНАЯ, пл.с(), слой='верх', нагрузка=0.6)
    места['объём_до'] = _объём(х)
    места['верх_до'] = np.array(х.слои['верх'].толщина)
    места['L_до'] = _L(х.картинка(свет=False))
    места['прямые'], места['дуги'] = [], []
    u = np.linspace(0.0, np.pi, 40)
    for i, (мм, н) in enumerate(ЛИНИИ):
        y = (8 + 10.5 * i) * k
        точки = [[7 * k, y, н], [37 * k, y + 1.5 * k, н]]
        места['прямые'].append((мм, н, точки, х.снять(точки, 'черенок', ширина=мм * k)))
        дуга = np.column_stack([(55 + 11 * np.cos(u) * (1 if i % 2 else -1)) * k, (y / k - 2 + 4 * np.sin(u)) * k, np.full(len(u), н)])
        места['дуги'].append((мм, н, дуга, х.снять(дуга, 'черенок', ширина=мм * k)))
    return х, места


def мерка(х, места):
    """Числа листа: 'объём_%' — на сколько процентов изменился объём краски листа; 'низ_цел' — сухой слой бит в бит;
    'прямые' — по каждой: (мм, нажим, L по оси — медиана, L нижнего слоя там же, L тёмного до процарапывания,
    валик — во сколько раз слой у боков борозды толще, чем лежал, ответ черенка)."""
    k = места['k']
    L = _L(х.картинка(свет=False))
    верх = np.asarray(х.слои['верх'].толщина, np.float64)
    ответ = {'объём_%': 100.0 * (_объём(х) - места['объём_до']) / места['объём_до'],
             'низ_цел': all(np.array_equal(было, np.asarray(getattr(х.слои['низ'], п))) for п, было in места['низ'].items()),
             'прямые': []}
    for мм, н, ((xa, ya, _), (xb, yb, _)), о in места['прямые']:
        xs = np.arange(int(xa + 5 * k), int(xb - 5 * k))
        ys = np.round(ya + (yb - ya) * (xs - xa) / (xb - xa)).astype(int)
        бок = int(round(о.ширина / 2.0)) + 1 if о else int(мм * k / 2)
        полоса = [ys + s * (бок + j) for s in (-1, 1) for j in range(max(2, int(0.4 * k)))]
        валик = float(np.mean([верх[r, xs].mean() for r in полоса]) / max(np.mean([места['верх_до'][r, xs].mean() for r in полоса]), 1e-9))
        ответ['прямые'].append((мм, н, float(np.median(L[ys, xs])), float(np.median(места['L_низа'][ys, xs])),
                                float(np.median(места['L_до'][ys, xs])), валик, о))
    return ответ


if __name__ == '__main__':
    куда = sys.argv[1] if len(sys.argv) > 1 else None
    х, места = лист()
    м = мерка(х, места)
    print(f"объём краски листа: {м['объём_%']:+.4f} %; сухой нижний слой бит в бит: {'да' if м['низ_цел'] else 'НЕТ'}")
    for мм, н, Lо, Lн, Lд, валик, о in м['прямые']:
        print(f'конец {мм} мм, нажим {н}: L по оси {Lо:.1f} (нижний слой {Lн:.1f}, тёмный до {Lд:.1f}); валики — слой у боков ×{валик:.2f}')
        print('   ', о)
    if куда:
        os.makedirs(куда, exist_ok=True)
        k = int(места['k'])
        х.взгляд((0, 0, 75 * k, 75 * k), 1, путь=os.path.join(куда, 'черенок_1к1.png'))
        х.взгляд((12 * k, 14 * k, 30 * k, 32 * k), 4, путь=os.path.join(куда, 'черенок_1мм_x4.png'))
        х.взгляд((12 * k, 45 * k, 30 * k, 63 * k), 4, путь=os.path.join(куда, 'черенок_3мм_x4.png'))
        х.взгляд((46 * k, 13 * k, 64 * k, 31 * k), 4, путь=os.path.join(куда, 'черенок_дуги_x4.png'))
        х.взгляд((46 * k, 45 * k, 64 * k, 63 * k), 4, путь=os.path.join(куда, 'черенок_дуги3_x4.png'))
