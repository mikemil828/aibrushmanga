"""Пример пользования движком «Кисть» из Python: python3 примеры/пользование.py [папка для листа].
То же журналом: python -m кисть.повтор примеры/пользование.jsonl --out лист.png (из папки «движок»). Описание — README_ПОЛЬЗОВАНИЕ.md."""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))   # папка «движок», где лежит пакет «кисть»

import numpy as np
from кисть import Холст, Кисть, Краска, жест, путь_с_нажимом, нажим_вдоль

х = Холст(400, 240, грунт=(150, 141, 126), px_на_мм=8.0)
rng = np.random.default_rng(1)

# 1. подмалёвок: широкая плоская щетина, три хода внахлёст, слой «низ»
плоская = Кисть.из_файла('пресеты/плоская.json', ширина=48)
for k in range(6):
    y = 24 + 40 * k
    точки = жест([[10, y], [200, y + 4], [390, y]], 48, 'остановка', rng, нажим=0.7)
    х.мазок(точки, (70, 92, 84), плоская, слой='низ', сид=10 + k, нагрузка='обычная')
    плоская.вытереть()

# 2. удар в две краски по сырому, пастозно
удар = Кисть.из_файла('пресеты/плоская.json', ширина=32)
точки = жест([[60, 70], [150, 60], [230, 80]], 32, 'отрыв', rng, нажим=0.6)
прям = х.мазок(точки, [((232, 226, 205), 0.3), ((188, 132, 52), 0.7)], удар, слой='низ', сид=21,
               раскладка='полосы', нагрузка='пастозная')

# 3. высушить и положить лессировку в свой слой
х.подсушить(1.0)
мягкая = Кисть.из_файла('пресеты/мягкая.json', ширина_мм=6)
точки = путь_с_нажимом([[40, 170], [200, 180], [360, 165]], 48, rng, нажим=0.5)
х.мазок(точки, Краска((70, 34, 22), 'лессировочная'), мягкая, слой='лессировка', сид=31, нагрузка='протирка')

# 4. тонкая линия острой кистью, нажим падает к концу
узкая = Кисть.из_файла('пресеты/плоская_узкая.json', ширина=6)
точки = нажим_вдоль(жест([[250, 40], [300, 90], [370, 110]], 6, 'подъём', rng, нажим=0.8), [[0, 1], [1, 0.4]])
х.мазок(точки, (30, 28, 26), узкая, слой='верх', сид=41)

куда = sys.argv[1] if len(sys.argv) > 1 else '.'
х.png(os.path.join(куда, 'лист.png'), свет=True)          # PNG 16 бит, sRGB
х.сохранить(os.path.join(куда, 'лист.npz'))               # состояние холста: слои, сырость, толщина
картинка = х.картинка(свет=False)     # numpy (В, Ш, 3), линейный свет 0..1
print('записанный прямоугольник удара:', прям, '· слои снизу вверх:', list(х.слои))
