"""Правка задним числом (К-3, А-7) на чистом холсте: низ 30 ходов, верх 60 поверх, низ одного места теплее на 0,02 —
`х.править` пересобирает только то, что лежит над этим местом и рядом. Лист проб инструмента, не кусок картины.

    python3 примеры/задним.py [папка]      # из папки «движок»; пишет задним_до_после.png и печатает ответ правки

Импорт ничего не кладёт: `from примеры.задним import низ_и_верх, теплее_место` (из «движок»)."""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))   # папка «движок»

from кисть import Холст, Кисть, жест

ПРЕСЕТЫ = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'пресеты')
МЕСТО = (0, 0, 100, 80)           # px: клетка левого верха — её низ станет теплее


def низ_и_верх(журнал, ядра=None):
    """Холст 600×400, 8 px/мм, с журналом: низ — 30 ходов плоской 40 px, по ходу в клетке 100×80 (6 × 5), сушка, верх —
    60 ходов плоской 24 px по сырому верхнему слою, по два в клетке. Ответ — (холст, кисть низа, кисть верха)."""
    х = Холст(600, 400, грунт=(166, 146, 129), px_на_мм=8.0, журнал=журнал, ядра=ядра)
    низ = Кисть.из_файла(os.path.join(ПРЕСЕТЫ, 'плоская.json'), ширина=40)
    верх = Кисть.из_файла(os.path.join(ПРЕСЕТЫ, 'плоская.json'), ширина=24)
    клетки = [(100 * i, 80 * j) for j in range(5) for i in range(6)]
    for k, (x, y) in enumerate(клетки):
        низ.вытереть()
        х.мазок(жест([[x + 22, y + 40], [x + 78, y + 42]], 40, 'остановка', сид=k, нажим=0.7), (120 + 2 * k, 140, 170),
                низ, слой='низ')
    х.подсушить(0.3)
    for k, (x, y) in enumerate(клетки * 2):
        верх.вытереть()
        dy = 30 if k < 30 else 50
        х.мазок(жест([[x + 35, y + dy], [x + 65, y + dy + 2]], 24, 'остановка', сид=100 + k, нажим=0.7),
                (200, 180 - k, 150), верх, слой='верх')
    return х, низ, верх


def теплее_место(х, путь=None):
    """Низ места `МЕСТО` теплее на 0,02 (b OKLab): одна команда, холст после неё — уже пересобранный."""
    return х.править(слой='низ', область=МЕСТО, теплее=0.02, путь=путь)


if __name__ == '__main__':
    куда = sys.argv[1] if len(sys.argv) > 1 else '.'
    os.makedirs(куда, exist_ok=True)
    х, *_ = низ_и_верх(os.path.join(куда, 'задним.jsonl'))
    о = теплее_место(х, путь=os.path.join(куда, 'задним_до_после.png'))
    print(о)
    х.закрыть()
