"""Пятно со спадом по кругу (5а): белый диск по сырому небу и растушёвка вытертой мягкой кистью крест-накрест —
ходы по радиусу и дуги по кругу. Лист проб кисти, не кусок картины. Замер — `замер_круга(х, центр)`: профиль L(r)
(медиана по секторам 5°), спад 10–90 %, наибольшая ступень на 8 px, σ L по углу на окружности середины спада.

    python3 примеры/пятно_по_кругу.py [папка] [--приём радиус|круг|крест] [--масштаб 0.5]   # из папки «движок»

Холст 1200×1200, 8 px/мм. Небо — `плоская` 90, `разброс_тона=0.3`, нагрузка 0,6, ряды через 45 px (через 55 —
щели грунта, σ по углу самого неба ~4 L). Диск — `мягкая` 48, белила (250, 250, 248) нагрузкой 0,5, хорды через
24 px, r 150, по сырому небу. Растушёвка — `мягкая` 90, `нагрузка=0`, без цвета, нажим 0,35, `'подъём'`,
`к.вытереть()` перед каждым ходом:
  (1) 240 ходов по радиусу от r ~40 до ~560 (разброс концов ±30 и ±40 px), углы через 1,5°, каждый следующий — обратно;
  (2) дуги в четверть круга по окружностям r 80…520 через 24 px, внахлёст на четверть дуги, через одну — обратно;
  (3) то же (1) и (2) вторым проходом своими сидами (углы и окружности сдвинуты);
  (4) дуги в полкруга по окружностям r 100…500 и 115…515 через 30 px.
Без (4) спад тот же, а σ по углу ~2,3 L: короткие дуги не разносят тон по кругу. Только по радиусу — лучи
(σ по углу ~6 L, мелкими по углу — 5,9), только по кругу — спада нет (~30 px), углы и дуги вразброс — пятно
лепестками (σ ~12 L). Мерка 18.11 (Движок 169), сид примера: спад 218 px, σ по углу 1,6 L, ~1400 ходов, ~4 мин на
одном ядре.
Импорт ничего не кладёт: `from примеры.пятно_по_кругу import небо, диск, растушевать, замер_круга` (из «движок»)."""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))   # папка «движок»

import numpy as np

from кисть import Холст, Кисть, жест, цвет
from кисть.глаз import светлота
from кисть.краска import из_линейного

ПРЕСЕТЫ = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'пресеты')
ГРУНТ = (150, 141, 126)
НЕБО, БЕЛИЛА = цвет(72, 0.03, 250), (250, 250, 248)


def _к(имя, w, **поля):
    return Кисть.из_файла(os.path.join(ПРЕСЕТЫ, имя + '.json'), ширина=w, **поля)


def небо(х, м=1.0, слой='небо'):
    """Сырое небо плоской 90 рядами через 45 px (м — масштаб: px и ширины множатся)."""
    к, w = _к('плоская', 90 * м, разброс_тона=0.3), 90 * м
    for i, y in enumerate(np.arange(-10 * м, х.высота + 60 * м, 45 * м)):
        х.мазок(жест([[-80 * м, y], [х.ширина / 2, y + 2 * м], [х.ширина + 80 * м, y]], w, 'остановка', сид=100 + i,
                     нажим=0.65), НЕБО, к, слой=слой, сид=100 + i, нагрузка=0.6)
        к.вытереть()


def диск(х, центр, r=150, м=1.0, слой='небо'):
    """Белый диск мягкой 48 хордами через 24 px по сырому."""
    cx, cy = центр
    w = 48 * м
    к = _к('мягкая', w)
    for n, y in enumerate(np.arange(cy - r + 0.3 * w, cy + r, 24 * м)):
        hx = np.sqrt(max(r * r - (y - cy) ** 2, 0.0))
        a, b = (cx - hx, cx + hx) if n % 2 == 0 else (cx + hx, cx - hx)
        х.мазок(жест([[a, y], [(a + b) / 2, y + м], [b, y]], w, 'остановка', сид=300 + n, нажим=0.6),
                БЕЛИЛА, к, слой=слой, сид=300 + n, нагрузка=0.5)
        к.вытереть()


def _радиус(х, к, w, центр, r0, r1, n, сид, слой):
    rng = np.random.default_rng(сид)
    for i in range(n):
        φ = 2 * np.pi * i / n + rng.uniform(-0.01, 0.01)
        a, b = max(0.0, r0 + rng.uniform(-30, 30) * w / 90), r1 + rng.uniform(-40, 40) * w / 90
        if i % 2:
            a, b = b, a
        p = [[центр[0] + t * np.cos(φ), центр[1] + t * np.sin(φ)] for t in np.linspace(a, b, 4)]
        к.вытереть()
        х.мазок(жест(p, w, 'подъём', сид=сид + i, нажим=0.35), None, к, слой=слой, сид=сид + i, нагрузка=0)
    return n


def _круг(х, к, w, центр, r0, r1, шаг, дуга, сид, слой):
    rng = np.random.default_rng(сид)
    i = 0
    for r in np.arange(r0, r1, шаг):
        φ0 = rng.uniform(0, 2 * np.pi)
        for φa in np.arange(φ0, φ0 + 2 * np.pi - 1e-6, дуга * 0.75):
            φ = np.linspace(φa, φa + дуга, 12)
            if i % 2:
                φ = φ[::-1]
            rr = r + rng.uniform(-5, 5) * w / 90
            p = [[центр[0] + rr * np.cos(t), центр[1] + rr * np.sin(t)] for t in φ]
            к.вытереть()
            х.мазок(жест(p, w, 'подъём', сид=сид + i, нажим=0.35), None, к, слой=слой, сид=сид + i, нагрузка=0)
            i += 1
    return i


def растушевать(х, центр, м=1.0, приём='крест', слой='небо'):
    """Растушёвка пятна по кругу вытертой мягкой 90: 'крест' — рецепт (ходы по радиусу, дуги в четверть и в полкруга);
    'радиус', 'круг' — одна часть, для сравнения. Ответ — сколько ходов."""
    w = 90 * м
    к = _к('мягкая', w)
    R = lambda *a: _радиус(х, к, w, центр, 40 * м, 560 * м, 240, *a, слой)
    K = lambda r0, r1, шаг, дуга, сид: _круг(х, к, w, центр, r0 * м, r1 * м, шаг * м, дуга, сид, слой)
    if приём == 'радиус':
        return R(5000)
    if приём == 'круг':
        return K(80, 520, 24, np.pi / 2, 6000)
    return (R(5000) + K(80, 520, 24, np.pi / 2, 6000) + R(5500) + K(90, 530, 24, np.pi / 2, 6500)
            + K(100, 500, 30, np.pi, 6700) + K(115, 515, 30, np.pi, 6900))


def замер_круга(х, центр, r_max=None, свет=False):
    """Профиль L(r) от центра — медиана по секторам 5° средних L в кольцах по 1 px; ядро — медиана r 5–40, фон —
    последние 10 % профиля. Спад 10–90 % — от последнего места до середины, где тон ещё выше 90 % пути от фона к ядру,
    до первого после середины ниже 10 %. Ступень — наибольшая разность профиля на 8 px в спаде (±16 px). σ по углу —
    σ средних L 72 секторов на кольце середины ±4 px; 'σ мелкая' — её часть с периодом короче 60° (лучи, ворс),
    'σ крупная' — длиннее (форма пятна). Ответ — словарь с 'профиль' (numpy)."""
    cx, cy = центр
    r_max = int(r_max or min(cx, cy, х.ширина - cx, х.высота - cy))
    x0, y0 = int(cx - r_max), int(cy - r_max)
    рамка = (x0, y0, x0 + 2 * r_max, y0 + 2 * r_max)
    L = светлота(np.clip(из_линейного(х.картинка(свет=свет, область=рамка)) * 255.0, 0.0, 255.0)).astype(np.float64)
    yy, xx = np.mgrid[0:L.shape[0], 0:L.shape[1]]
    dx, dy = xx + x0 + 0.5 - cx, yy + y0 + 0.5 - cy
    R = np.hypot(dx, dy)
    A = np.degrees(np.arctan2(dy, dx)) % 360
    ri, ai = R.astype(int), (A // 5).astype(int)
    m = ri < r_max
    сум, кол = np.zeros((r_max, 72)), np.zeros((r_max, 72))
    np.add.at(сум, (ri[m], ai[m]), L[m])
    np.add.at(кол, (ri[m], ai[m]), 1)
    сек = np.where(кол > 0, сум / np.maximum(кол, 1), np.nan)
    проф = np.nanmedian(сек, axis=1)
    а, б = float(np.nanmedian(проф[5:40])), float(np.nanmedian(проф[-max(8, r_max // 10):]))
    t = (проф - б) / (а - б)
    с = int(np.nanargmin(np.abs(t[20:] - 0.5))) + 20
    выше, ниже = np.nonzero(t[:с + 1] > 0.9)[0], np.nonzero(t[с:] < 0.1)[0]
    i90 = int(выше[-1]) + 1 if len(выше) else 0
    i10 = с + int(ниже[0]) if len(ниже) else r_max
    d = np.abs(проф[8:] - проф[:-8])
    lo, hi = max(0, i90 - 16), min(len(d), i10 + 16)
    ст = int(np.nanargmax(d[lo:hi])) + lo
    кольцо = (R > с - 4) & (R < с + 4)
    a2 = (A // 2.5).astype(int)
    сек2 = np.array([L[кольцо & (a2 == k)].mean() for k in range(144)])
    F = np.abs(np.fft.rfft(сек2 - сек2.mean())) / len(сек2) * np.sqrt(2)
    сек5 = np.array([L[кольцо & (ai == k)].mean() for k in range(72)])
    return {'ядро': round(а, 1), 'фон': round(б, 1), 'r_90': i90, 'r_10': i10, 'спад': i10 - i90, 'середина': с,
            'ступень': round(float(d[ст]), 2), 'где': ст + 4, 'σ по углу': round(float(сек5.std()), 2),
            'σ крупная': round(float(np.sqrt((F[1:7] ** 2).sum())), 2),
            'σ мелкая': round(float(np.sqrt((F[7:] ** 2).sum())), 2), 'профиль': проф}


def лист(приём='крест', м=1.0, ядра=None, журнал=None):
    """Холст: небо, диск r 150, растушёвка. Ответ — (холст, замер диска до растушёвки, замер после)."""
    х = Холст(int(1200 * м), int(1200 * м), грунт=ГРУНТ, px_на_мм=8.0 * м, ядра=ядра, журнал=журнал)
    ц = (600 * м, 600 * м)
    небо(х, м)
    диск(х, ц, 150 * м, м)
    до = замер_круга(х, ц)
    растушевать(х, ц, м, приём)
    return х, до, замер_круга(х, ц)


if __name__ == '__main__':
    арг = sys.argv[1:]
    def _ключ(имя, умолч):
        return арг[арг.index(имя) + 1] if имя in арг else умолч
    приём, м = _ключ('--приём', 'крест'), float(_ключ('--масштаб', 1.0))
    куда = next((a for i, a in enumerate(арг) if not a.startswith('--') and (i == 0 or not арг[i - 1].startswith('--'))), '.')
    os.makedirs(куда, exist_ok=True)
    х, до, после = лист(приём, м, журнал=os.path.join(куда, 'пятно_по_кругу.jsonl'))
    for имя, з in (('диск', до), (приём, после)):
        print(f"{имя}: L {з['ядро']} → {з['фон']}, спад 10–90 % {з['спад']} px (r {з['r_90']}–{з['r_10']}), "
              f"ступень {з['ступень']} L у r {з['где']}, σ по углу {з['σ по углу']} L (мелкая {з['σ мелкая']}, "
              f"крупная {з['σ крупная']})")
    х.взгляд(путь=os.path.join(куда, 'пятно_по_кругу.png'))
