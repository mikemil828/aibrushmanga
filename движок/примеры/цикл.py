"""Рабочий цикл на чистом холсте: пробник → кладка → кроп → замер → правка. Лист проб кисти, не кусок картины.
Замер — ответом самого мазка (`о = х.мазок(…)`: `о.цвет`, `о.закрыто`, `о.просветы`, `о.ширина`, `о.сырое`, `о.край`)
и вызовами холста (`х.борозды`); своего счёта по пикселям в примере нет.

    python3 примеры/цикл.py [папка] [--мал] [--попытка N]   # из папки «движок»; --мал — лист вдвое меньше (для теста)

Лист 640×400 px на сером грунте, четыре пробы, каждая — своим слоем:
1. заливка — плоская 100 px, ряды внахлёст, нагрузка от пробника; замер — просветы хода (грунт в бороздах) и борозды σ L;
2. шкала нажима — круглая 32 px, четыре хода нажимом 0,2…0,8; замер — ширина следа и L хода;
3. сырое в сырое — светлые ходы поперёк тёмной полосы: по сырому своего слоя и по высохшему в новом слое; замер — L хода
   и сколько сырого он подобрал;
4. край — мягкая 48 px нажимом 0,35 и 0,85; замер — кайма (от 10 до 50 % уровня тела следа поперёк хода).
Один прогон — одна попытка (без номера — последняя в ПОПЫТКИ). После прогона открыть кроп `цикл_N.png` глазами,
решить, что не так, и дописать в ПОПЫТКИ строку: что увидел → что меняю. Число подтверждает глаз, а не решает.
В живой сессии (`python3 -i примеры/цикл.py …`) — `х.откатить(снимок)` и `писать_лист(…)` с новым.
Импорт ничего не кладёт: `from примеры.цикл import пробник, писать_лист, кроп, замер` (из «движок»).
Журнал пишет холст сам: `цикл.jsonl` рядом; `python -m кисть.повтор цикл.jsonl --out повтор.png` — те же пиксели.
Нужны numpy и Pillow (кроп)."""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))   # папка «движок»

from кисть import Холст, Кисть, жест

ГРУНТ = (150, 141, 126)
ТЁМНАЯ, СВЕТЛАЯ = (52, 60, 78), (226, 220, 200)


# ---------- 1. пробник: какая нагрузка кроет грунт ----------
def пробник(грунт, нагрузки=(0.24, 0.45, 0.6), ширина=100):
    """Ход плоской на пробу (`х.проба`: положить, взять ответ мазка, откатить) — какая нагрузка кроет грунт.
    Ответ — наименьшая, при которой просветов (места под кистью, где краска не легла) меньше 0,5 %."""
    проба, к = Холст(500, 200, грунт=грунт, px_на_мм=8.0), Кисть.из_файла('пресеты/плоская.json', ширина=ширина)
    просветы = {}
    for наг in нагрузки:
        о, _ = проба.проба(жест([[40, 100], [250, 102], [460, 100]], ширина, 'остановка', сид=1, нажим=0.65),
                           ТЁМНАЯ, к, сид=1, нагрузка=наг, свет=False)    # о — ответ мазка: что вышло
        просветы[наг] = 100 * о.просветы
        print(f'пробник: нагрузка {наг}: просветы {просветы[наг]:.2f} %, закрыто {о.закрыто:.2f}, L {о.цвет["L"]:.0f}')
    return min((н for н, г in просветы.items() if г < 0.5), default=max(нагрузки))


# ---------- 2. кладка: четыре пробы ----------
def писать_лист(х, м, нагрузка, разброс, ровно=None):
    """Лист проб на холсте `х`; `м` — масштаб листа (1 или 0,5). Ответ — ответы мазков по пробам: {проба: [о, …]}."""
    Ш, о = х.ширина, {'заливка': [], 'шкала': [], 'сырое': [], 'край': []}
    х.пометка('заливка', этап=1, объект='заливка')
    к = Кисть.из_файла('пресеты/плоская.json', ширина=100 * м, разброс_тона=разброс)
    for i, y in enumerate((50, 110)):                       # ряды внахлёст на 40 %, ход за края холста
        о['заливка'].append(х.мазок(жест([[-80 * м, y * м], [Ш / 2, (y + 3) * м], [Ш + 80 * м, y * м]], 100 * м, 'остановка', сид=10 + i, нажим=0.65),
                                    ТЁМНАЯ, к, слой='заливка', сид=10 + i, нагрузка=нагрузка, ровно=ровно))

    х.пометка('шкала нажима', этап=2, объект='шкала')
    к = Кисть.из_файла('пресеты/круглая.json', ширина=32 * м)
    for i, наж in enumerate(НАЖИМЫ):
        x = (20 + 156 * i) * м
        о['шкала'].append(х.мазок(жест([[x, 210 * м], [x + 130 * м, 210 * м]], 32 * м, 'остановка', сид=20 + i, нажим=наж),
                                  СВЕТЛАЯ, к, слой='шкала', сид=20 + i, нагрузка=0.6))
        к.вытереть()

    х.пометка('сырое в сырое', этап=3, объект='сырое')
    к = Кисть.из_файла('пресеты/плоская.json', ширина=64 * м)
    for i, x0 in enumerate((20, 340)):                      # две тёмные полосы в одном слое; правая — досуха
        х.мазок(жест([[x0 * м, 290 * м], [(x0 + 280) * м, 290 * м]], 64 * м, 'остановка', сид=30 + i, нажим=0.65),
                ТЁМНАЯ, к, слой='сырое', сид=30 + i, нагрузка=0.8)
        к.вытереть()
    х.подсушить(1.0, область=(int(330 * м), int(240 * м), Ш, int(340 * м)))
    к = Кисть.из_файла('пресеты/плоская.json', ширина=24 * м)
    for i, (x, слой) in enumerate(((160, 'сырое'), (480, 'по_сухому'))):   # светлый ход поперёк: по сырому — тем же слоем
        о['сырое'].append(х.мазок(жест([[x * м, 250 * м], [x * м, 330 * м]], 24 * м, 'остановка', сид=40 + i, нажим=0.75),
                                  СВЕТЛАЯ, к, слой=слой, сид=40 + i, нагрузка=0.3))
        к.вытереть()

    х.пометка('край мягкой', этап=4, объект='край')
    к = Кисть.из_файла('пресеты/мягкая.json', ширина=48 * м)
    for i, (x0, наж) in enumerate(((20, 0.35), (340, 0.85))):
        о['край'].append(х.мазок(жест([[x0 * м, 365 * м], [(x0 + 280) * м, 365 * м]], 48 * м, 'остановка', сид=50 + i, нажим=наж),
                                 СВЕТЛАЯ, к, слой='край', сид=50 + i, нагрузка=0.05))
        к.вытереть()
    return о


НАЖИМЫ = (0.2, 0.4, 0.6, 0.8)


# ---------- 3–4. глаз: кроп и замер ----------
def кроп(х, куда, имя):
    """Кроп листа со светом, ×2 у малого листа, PNG 8 бит в `куда` — `х.взгляд`."""
    путь = os.path.join(куда, имя)
    х.взгляд(масштаб=2 if х.ширина < 400 else 1, путь=путь)
    return путь


def замер(х, о, м):
    """Числа проб — из ответов мазков `о` (`писать_лист`) и мерки холста: заливка (просветы хода %, борозды σ L), шкала
    (ширина следа и L по нажиму), сырое (L хода, доля подобранного сырого), край (кайма, px)."""
    з = {'заливка грунт %': round(100 * max(а.просветы for а in о['заливка']), 2),
         'заливка фактура σ L': round(х.борозды((int(20 * м), int(20 * м), х.ширина - int(20 * м), int(140 * м)), ширина=12 * м)['σ'], 1)}
    for наж, а in zip(НАЖИМЫ, о['шкала']):
        з[f'шкала {наж}: ширина px, L'] = (round(а.ширина / м), round(а.цвет['L']))
    for имя, а in zip(('по сырому', 'по сухому'), о['сырое']):
        з[f'сырое: L хода {имя}'] = а.цвет['L']
        з[f'сырое: подобрано {имя}'] = а.сырое['подобрано']
    for наж, а in zip((0.35, 0.85), о['край']):
        з[f'край {наж}: кайма px'] = round(а.край['кайма'] / м, 1)
    return з


# Попытки листа: каждая следующая дописана после взгляда на кроп прошлой — что увидел и что меняю.
ПОПЫТКИ = [
    {'разброс': 1.0, 'ровно': None, 'увидел': '', 'меняю': 'кисть как есть'},
    {'разброс': 1.0, 'ровно': 0.4, 'увидел': 'цикл_1.png: в заливке борозды, по ним нитями светит грунт',
     'меняю': 'заливка ровнее: ровно 0.4'},
]   # цикл_2.png: борозды ушли, грунта нет; шкала, сырое и край — как в первой: правка тронула только заливку

# ---------- попытка: кладка, кроп, замер; правка — следующей строкой ПОПЫТКИ после взгляда на кроп ----------
if __name__ == '__main__':
    мал = '--мал' in sys.argv
    куда = next((a for a, до in zip(sys.argv[1:], sys.argv) if not a.startswith('--') and до != '--попытка'), '.')
    os.makedirs(куда, exist_ok=True)
    м = 0.5 if мал else 1.0
    попытка = int(sys.argv[sys.argv.index('--попытка') + 1]) if '--попытка' in sys.argv else len(ПОПЫТКИ)
    НАГРУЗКА = пробник(ГРУНТ)

    х = Холст(int(640 * м), int(400 * м), грунт=ГРУНТ, px_на_мм=8.0, журнал=os.path.join(куда, 'цикл.jsonl'))   # журнал пишется сам
    п = ПОПЫТКИ[попытка - 1]
    снимок = х.снимок()                                  # до куска: откат вернёт холст и журнал
    о = писать_лист(х, м, НАГРУЗКА, п['разброс'], п['ровно'])     # ответы мазков: что вышло у каждого хода
    print(о['сырое'][0])                                 # ответ мазка словами: цвет, закрыто, ширина, сырое, край
    print(f'попытка {попытка} — кроп:', кроп(х, куда, f'цикл_{попытка}.png'), '· замер:', замер(х, о, м))
    х.заметка({'попытка': попытка, 'увидел': п['увидел'], 'меняю': п['меняю'], 'замер': замер(х, о, м)}, этап=4, объект='край')
    х.сохранить(os.path.join(куда, 'цикл.npz'))
    print('журнал:', х.журнал.путь)
