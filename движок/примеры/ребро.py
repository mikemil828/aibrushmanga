"""Ребро плоской кисти (Д-7): у пучка есть толщина — на ребре след сплошной полосой в 1–2 мм. Лист проб кисти, не
кусок картины.

    python3 примеры/ребро.py [папка]   # из папки «движок»: лист 1:1 и кропы ×4, числа в окно

Холст 75×50 мм (600×400 px при 8 px/мм; при других px/мм — те же мм). `плоская` 5 мм:

1. три хода на ребре (`касание=0`) с нажимом 0,3 / 0,6 / 0,9 — полоса 1,1–1,6 мм без щелей, шире с нажимом;
2. та же кисть плашмя, тот же ход — 5 мм: одна кисть кладёт и плоскость, и линию;
3. ход с поворотом кисти в пальцах (`углы_вдоль(точки, поворот=…)`, 0 → 90°): плашмя — и сходит в ребро;
4. вход нажимом: свои точки, нажим 0,15 → 0,6 на первых 40 % хода, без `нажим_вдоль` — след начинается узко и
   раскрывается за нажимом;
5. тычки плоской 0,5–1,5 мм (4–12 px) — отпечаток в размер кисти, плашмя и на ребре один и тот же;
6. прежнее ребро — кисть без толщины (`пучок_мм=0`): след идёт за нажимом от нити до всей ширины, с `нажим_вдоль`
   и `нажим_руки=True` — клин.

`мерка(х)` — ширины полос в мм и щели, отпечатки тычков в долях кисти, вход в долях ширины тела.
Импорт ничего не кладёт: `from примеры.ребро import лист, мерка` (из «движок»)."""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))   # папка «движок»

import numpy as np

from кисть import Холст, Кисть, жест, нажим_вдоль, тычок
from кисть.повтор import углы_вдоль

ПРЕСЕТЫ = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'пресеты')
ГРУНТ = (200, 190, 170)
КРАСКА = (60, 50, 70)
НАЖИМЫ = (0.3, 0.6, 0.9)
ТЫЧКИ_ММ = (0.5, 0.75, 1.0, 1.5)      # 4, 6, 8, 12 px при 8 px/мм


def _плоская(ширина_мм, **замены):
    return Кисть.из_файла(os.path.join(ПРЕСЕТЫ, 'плоская.json'), ширина_мм=ширина_мм, **замены)


def лист(сид=0, px_на_мм=8.0):
    """Лист проб. Ответ: (холст, места) — места проб в px холста, для `мерка`."""
    k = px_на_мм                                               # px в мм
    х = Холст(int(75 * k), int(50 * k), грунт=ГРУНТ, px_на_мм=px_на_мм)
    W = 5.0 * k
    места = {'k': k, 'ребро': [], 'тычки': []}
    # 1. ребро: касание 0, три нажима
    for i, н in enumerate(НАЖИМЫ):
        y = (4 + 4 * i) * k
        х.мазок(жест([[5 * k, y], [45 * k, y]], W, 'подъём', сид=сид + i, нажим=н), КРАСКА, _плоская(5.0, касание=0), нагрузка=0.5)
        места['ребро'].append((y, 14 * k, 32 * k))             # ось, тело хода от x до x
    # 2. та же кисть плашмя
    y = 19 * k
    х.мазок(жест([[5 * k, y], [45 * k, y]], W, 'подъём', сид=сид + 5, нажим=0.6), КРАСКА, _плоская(5.0), нагрузка=0.5)
    места['плашмя'] = (y, 14 * k, 32 * k)
    # 3. поворот кисти в пальцах: плашмя -> ребром
    y = 27 * k
    х.мазок(углы_вдоль(жест([[5 * k, y], [45 * k, y]], W, 'подъём', сид=сид + 6, нажим=0.6), поворот=[[0, 0], [0.25, 0], [0.7, 90]]),
            КРАСКА, _плоская(5.0), нагрузка=0.5)
    места['поворот'] = (y, 5 * k, 45 * k)
    # 4. вход нажимом: свои точки, без нажим_вдоль
    y = 35 * k
    s = np.linspace(0.0, 1.0, max(int(40 * k / 3), 40))
    p = np.where(s < 0.4, 0.15 + 0.45 * s / 0.4, 0.6) * np.clip((1.0 - s) / 0.15, 0.0, 1.0)
    х.мазок(np.column_stack([(5 + 40 * s) * k, np.full(len(s), y), p]), КРАСКА, _плоская(5.0), нагрузка=0.5, сид=сид + 7)
    места['вход'] = (y, 5 * k, 45 * k)
    # 5. тычки 0,5–1,5 мм: плашмя (верхний ряд) и на ребре (нижний)
    for r, кас in enumerate((1, 0)):
        for j, мм in enumerate(ТЫЧКИ_ММ):
            x, y = (52 + 6 * j) * k, (5 + 5 * r) * k
            х.мазок(тычок(x, y, нажим=0.85, угол=0), КРАСКА, _плоская(мм, касание=кас), нагрузка=0.5, сид=сид + 20 + j)
            места['тычки'].append((x, y, мм, кас))
    # 6. прежнее ребро: кисть без толщины пучка — клин по нажиму руки
    y = 44 * k
    х.мазок(нажим_вдоль(жест([[5 * k, y], [45 * k, y]], W, 'подъём', сид=сид + 8, нажим=0.9), [[0, 1], [0.45, 0.9], [1, 0.3]]),
            КРАСКА, _плоская(5.0, касание=0, пучок_мм=0), нагрузка=0.5, нажим_руки=True)
    места['клин'] = (y, 5 * k, 45 * k)
    return х, места


def _покрытие(х):
    return np.asarray(next(iter(х.слои.values())).покрытие) > 0.5


def _полоса(A, y, x0, x1, полуширина):
    """Ширина следа по столбцам (px) и наибольшая щель внутри следа (px) на участке хода."""
    тело = A[int(y - полуширина):int(y + полуширина) + 1, int(x0):int(x1)]
    шир, щель = тело.sum(axis=0), 0
    for c in range(тело.shape[1]):
        есть = np.nonzero(тело[:, c])[0]
        if len(есть):
            щель = max(щель, int(есть[-1] - есть[0] + 1 - len(есть)))
    return шир, щель


def мерка(х, места):
    """Числа листа: 'ребро_мм' — медиана ширины полосы на ребре по трём нажимам, 'щель' — наибольшая щель в них, px,
    'пусто' — доля столбцов тела без следа; 'плашмя_мм'; 'поворот_мм' — ширина в начале и в конце хода с поворотом;
    'вход' — ширина через 1 мм от начала следа в долях ширины тела; 'тычки' — [(мм кисти, касание, поперёк, вдоль
    в долях кисти)]; 'клин_мм' — ширина клина прежнего ребра в четверти хода и у конца."""
    k, A = места['k'], _покрытие(х)
    ответ = {'ребро_мм': [], 'щель': 0, 'пусто': 0.0}
    for y, x0, x1 in места['ребро']:
        шир, щель = _полоса(A, y, x0, x1, 1.9 * k)
        ответ['ребро_мм'].append(float(np.median(шир)) / k)
        ответ['щель'] = max(ответ['щель'], щель)
        ответ['пусто'] = max(ответ['пусто'], float((шир == 0).mean()))
    y, x0, x1 = места['плашмя']
    ответ['плашмя_мм'] = float(np.median(_полоса(A, y, x0, x1, 3.9 * k)[0])) / k
    y, x0, x1 = места['поворот']
    шир = _полоса(A, y, x0, x1, 3.9 * k)[0]
    ответ['поворот_мм'] = (float(np.median(шир[int(4 * k):int(8 * k)])) / k, float(np.median(шир[int(30 * k):int(34 * k)])) / k)
    y, x0, x1 = места['вход']
    шир = _полоса(A, y, x0, x1, 3.9 * k)[0]
    начало = int(np.nonzero(шир > 0)[0][0])
    ответ['вход'] = float(шир[начало + int(k)]) / max(float(np.median(шир[int(22 * k):int(30 * k)])), 1.0)
    ответ['тычки'] = []
    for x, y, мм, кас in места['тычки']:
        пятно = A[int(y - 2.4 * k):int(y + 2.4 * k), int(x - 2.4 * k):int(x + 2.4 * k)]
        ys, xs = np.nonzero(пятно)
        W = мм * k
        ответ['тычки'].append((мм, кас, (ys.max() - ys.min() + 1) / W if len(ys) else 0.0, (xs.max() - xs.min() + 1) / W if len(xs) else 0.0))
    y, x0, x1 = места['клин']
    шир = _полоса(A, y, x0, x1, 3.9 * k)[0]
    ответ['клин_мм'] = (float(np.median(шир[int(8 * k):int(12 * k)])) / k, float(np.median(шир[int(30 * k):int(33 * k)])) / k)
    return ответ


if __name__ == '__main__':
    куда = sys.argv[1] if len(sys.argv) > 1 else None
    х, места = лист()
    м = мерка(х, места)
    print('ребро, нажим 0,3 / 0,6 / 0,9: ' + ' / '.join(f'{v:.2f}' for v in м['ребро_мм']) + f" мм; щель {м['щель']} px; плашмя {м['плашмя_мм']:.2f} мм")
    print(f"поворот 0 → 90°: {м['поворот_мм'][0]:.2f} → {м['поворот_мм'][1]:.2f} мм; вход нажимом: {м['вход']:.2f} ширины тела")
    print('тычки (мм кисти, касание: поперёк × вдоль, в ширинах кисти): ' + '; '.join(f'{мм} мм, {кас}: {a:.2f} × {b:.2f}' for мм, кас, a, b in м['тычки']))
    print(f"прежнее ребро (пучок_мм=0), клин: {м['клин_мм'][0]:.2f} → {м['клин_мм'][1]:.2f} мм")
    if куда:
        os.makedirs(куда, exist_ok=True)
