"""Правка высохшей краски: «прижать» и «размочить» на чистом холсте (М-3). Лист проб инструмента, не кусок картины.

    python3 примеры/правка.py [папка]      # из папки «движок»; пишет правка.png и печатает мерки

Холст 8 px/мм. Две пробы:
1. `срезать_вал` — пастозный ход высушен; мастихин плашмя поперёк него, нажим 1, два хода (`х.прижать`): гребни под
   ножом срезаны до тела мазка — ровная площадка с кромкой от ножа, цвет тот же, срезанное ушло на нож;
2. `смягчить_границу` — два цвета встык высушены: растушёвка их не берёт; `х.размочить(1.0, область=…)` — и та же
   растушёвка вытертой мягкой кистью вяжет границу, как сырую.
Импорт ничего не кладёт: `from примеры.правка import срезать_вал, смягчить_границу` (из «движок»)."""
import os
import sys
import warnings
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))   # папка «движок»

import numpy as np

from кисть import Холст, Кисть, жест

ПРЕСЕТЫ = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'пресеты')
ГРУНТ = (150, 141, 126)


def _кисть(имя, **поля):
    return Кисть.из_файла(os.path.join(ПРЕСЕТЫ, имя + '.json'), **поля)


def _холст():
    х = Холст(400, 200, грунт=ГРУНТ, px_на_мм=8.0)
    х.замер = False
    return х


def срезать_вал(ходов=2, глубина=None):
    """Ответ: (холст, гребни до, гребни после, [ответы `Прижато`]); гребни — p99 − медиана рельефа под ножом, h."""
    х = _холст()
    х.мазок(жест([[30, 100], [370, 103]], 120, 'остановка', сид=50, нажим=0.8), (200, 60, 40), _кисть('плоская', ширина=60), нагрузка=1.0)
    х.подсушить(1.0)
    гребни = lambda: float(np.percentile(х.рельеф(70, 130, 180, 220), 99) - np.median(х.рельеф(70, 130, 180, 220)))   # noqa: E731
    до = гребни()
    нож = _кисть('мастихин')
    ответы = [х.прижать(жест([[200, 30], [205, 170]], 44, 'подъём', сид=60 + k, нажим=1.0), нож, глубина=глубина) for k in range(ходов)]
    return х, до, гребни(), ответы


def смягчить_границу(размочить=True):
    """Ответ: (холст, наибольший шаг тона на px поперёк границы в долях перепада): сухая ~0,8, размоченная ~0,2."""
    х = _холст()
    к = _кисть('плоская', ширина=60)
    х.мазок(жест([[30, 70], [370, 70]], 60, 'остановка', сид=5, нажим=0.8), (40, 70, 160), к, нагрузка='обычная')
    к.вытереть()
    х.мазок(жест([[30, 128], [370, 128]], 60, 'остановка', сид=6, нажим=0.8), (220, 190, 60), к, нагрузка='обычная')
    х.подсушить(1.0)
    if размочить:
        х.размочить(1.0, область=(100, 60, 300, 140))
    м = _кисть('мягкая', ширина=40)
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')                      # по сухому растушёвка пуста — `ПустойМазок`
        for i, x in enumerate(range(120, 290, 14)):
            х.мазок(жест([[x, 75 if i % 2 else 125], [x + 6, 125 if i % 2 else 75]], 40, 'подъём', сид=20 + i, нажим=0.6), None, м, нагрузка=0)
    L = np.asarray(х.картинка(свет=False), float)[80:120, 150:250].mean(axis=(1, 2))
    return х, float(np.abs(np.diff(L)).max() / abs(L[-1] - L[0]))


if __name__ == '__main__':
    папка = sys.argv[1] if len(sys.argv) > 1 else '.'
    х, до, после, ответы = срезать_вал()
    print(f'прижать: гребни под ножом {до:.2f} → {после:.2f} h')
    for о in ответы:
        print('  ', о)
    х.png(os.path.join(папка, 'правка.png'))
    for слово, мочить in (('сухая', False), ('размоченная', True)):
        print(f'граница {слово}: шаг тона {смягчить_границу(мочить)[1]:.2f} перепада на px')
