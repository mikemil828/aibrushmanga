"""Веерная и растрёпанная кисть (К-14б): ход кладёт не полосу, а пучок линий. Лист проб кистей, не кусок картины.

    python3 примеры/пучки.py [папка]   # из папки «движок»: лист 1:1 и кропы ×4, числа в окно

Холст 100×50 мм (800×400 px при 8 px/мм). Левая половина — сухой грунт, правая — сырой слой охры. Верхний ряд —
`веерная`, нижний — `растрёпанная`. В каждой четверти: пять тычков (нажим 0,4–0,9) и десять одинаково заданных
протяжек (та же длина, наклон, нажим и кисть — разные только место и сид).

- у веерной ворс стоит редкими пучками в один ряд, кончики — дугой (`просветы`, `в_пучке`, `веер`): протяжка — линии
  разной длины и толщины, лёгкая рука — только середина веера; тычок — дуга чёрточек;
- у растрёпанной ворс торчит клоками разной длины и жёсткости: протяжка — полосы с просветами, тычок — пятна клоков с голым между ними;
- по сырому линии берут лежащую краску: цвет каждой — свой;
- соседние ходы с тем же вызовом и разными сидами — разные раскладки пучков, а не сдвиг одной картинки.

`серия(имя)` — 30 одинаково заданных ходов кистью пресета на чистом холсте и зеркало однообразия этой серии
(`х.однообразие`): у кисти из пучков длина, ширина и нажим считаются по линиям пучков (в журнале — "lines").
Импорт ничего не кладёт: `from примеры.пучки import лист, серия` (из «движок»)."""
import os
import sys
import tempfile
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))   # папка «движок»

from кисть import Холст, Кисть, жест, тычок

ПРЕСЕТЫ = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'пресеты')
ГРУНТ = (214, 204, 184)
ОХРА, ЗЕЛЁНАЯ = (196, 150, 70), (40, 62, 30)
КИСТИ = ('веерная', 'растрёпанная')
НАЖИМЫ = (0.4, 0.55, 0.7, 0.8, 0.9)


def _кисть(имя, **поля):
    return Кисть.из_файла(os.path.join(ПРЕСЕТЫ, имя + '.json'), **поля)


def лист(журнал=None):
    """Лист проб. Ответ: (холст, места) — в `места` по кисти и половине ('сухое', 'сырое') ответы тычков и протяжек."""
    х = Холст(800, 400, грунт=ГРУНТ, px_на_мм=8.0, журнал=журнал)
    пл = _кисть('плоская', ширина_мм=7.5)
    for i in range(8):                                          # сырой слой справа: ряды внахлёст
        y = 28.0 + 50.0 * i
        х.мазок(жест([[395, y + 4], [810, y - 3]], 60, 'остановка', сид=500 + i, нажим=0.7), ОХРА, пл.с(), слой='низ', сид=500 + i, нагрузка=0.45)
    места = {}
    for r, имя in enumerate(КИСТИ):
        к = _кисть(имя)
        for h, половина in enumerate(('сухое', 'сырое')):
            x0, y0 = 400 * h, 200 * r
            тычки, протяжки = [], []
            for j in range(5):
                x = x0 + 40 + 80 * j
                сид = 1000 * r + 100 * h + j
                тычки.append(х.мазок(тычок(x, y0 + 28, НАЖИМЫ[j], угол=-90), ЗЕЛЁНАЯ, к.с(), слой='верх', сид=сид))
                for q in range(2):
                    y = y0 + 122 + 72 * q
                    сид = 1000 * r + 100 * h + 10 + 5 * q + j
                    протяжки.append(х.мазок(жест([[x - 4, y], [x + 4, y - 56]], к.ширина, 'подъём', сид=сид, нажим=0.7), ЗЕЛЁНАЯ, к.с(), слой='верх', сид=сид))
            места[имя, половина] = {'тычки': тычки, 'протяжки': протяжки}
    return х, места


def серия(имя, n=30, нажим=0.7, папка=None):
    """n одинаково заданных протяжек кистью пресета по чистому холсту (разные только место и сид) и зеркало этой серии.
    Ответ: (холст, `Однообразие`)."""
    папка = папка or tempfile.mkdtemp(prefix='пучки_')
    os.makedirs(папка, exist_ok=True)
    х = Холст(800, 400, грунт=ГРУНТ, px_на_мм=8.0, журнал=os.path.join(папка, f'серия_{имя}.jsonl'))
    к = _кисть(имя)
    for i in range(n):
        x, y = 44 + 79 * (i % 10), 110 + 125 * (i // 10)
        х.мазок(жест([[x - 5, y], [x + 5, y - 70]], к.ширина, 'подъём', сид=i, нажим=нажим), ЗЕЛЁНАЯ, к.с(), слой='верх', сид=i)
    return х, х.однообразие()


if __name__ == '__main__':
    куда = sys.argv[1] if len(sys.argv) > 1 else None
    х, места = лист()
    for (имя, половина), м in места.items():
        print(f'{имя}, {половина}: тычков со следом {sum(о is not None for о in м["тычки"])} из 5, протяжек {sum(о is not None for о in м["протяжки"])} из 10')
    серии = {}
    for имя in ('плоская_узкая',) + КИСТИ:
        серии[имя] = серия(имя, папка=куда)
        о = серии[имя][1]
        print(f'серия 30 одинаковых ходов, {имя}: зеркало {о.оценка:.3f}; узость {о.сводка["узость"]}; линии {о.сводка["линии"]}')
    if куда:
        os.makedirs(куда, exist_ok=True)
        х.взгляд((0, 0, 800, 400), 1, путь=os.path.join(куда, 'пучки_1к1.png'))
        for имя, (x0, y0) in (('веерная_сухое', (0, 0)), ('веерная_сырое', (400, 0)), ('растрёпанная_сухое', (0, 200)), ('растрёпанная_сырое', (400, 200))):
            х.взгляд((x0, y0, x0 + 200, y0 + 200), 4, путь=os.path.join(куда, f'пучки_{имя}_x4.png'))
            х.взгляд((x0 + 200, y0, x0 + 400, y0 + 200), 4, путь=os.path.join(куда, f'пучки_{имя}_x4б.png'))
        for имя, (хс, _) in серии.items():
            хс.взгляд((0, 0, 800, 400), 1, путь=os.path.join(куда, f'серия_{имя}_1к1.png'))
            хс.взгляд((0, 20, 240, 200), 4, путь=os.path.join(куда, f'серия_{имя}_x4.png'))
