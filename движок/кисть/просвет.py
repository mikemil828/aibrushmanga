"""v4, 3д (Б-3): карта просвета — какая доля грунта или нижнего слоя видна сквозь краску, по пикселю; дыры списком.

Только читает: холст, кисти, сиды и журнал не меняются. Счёт — тот же, что у `Холст.картинка`: слой кладётся на то,
что под ним, как `к = к · пропуск; к = к + (цвет − к) · покрытие`, — значит, свет того, что лежит под слоем, доходит
до глаза долей `(1 − покрытие) · пропуск`, а сквозь несколько слоёв — произведением этих долей. Это и есть карта:
1 — видно только нижнее (краски нет), 0 — нижнее закрыто целиком. `пропуск` (не кроющая краска: лессировка, вуаль)
трёхцветный — берётся его яркость (вес каналов линейного света 0,2126, 0,7152, 0,0722).

`слой=None` — сквозь все слои, видно грунт; `слой='луг'` — сквозь этот слой и все выше: видно то, что лежит под
ним. Дыра — связное (8 соседей) место, где карта не ниже `порог`, площадью от `площадь` px.
"""
import numpy as np

ЯРКОСТЬ = np.array([0.2126, 0.7152, 0.0722], np.float32)


class Просвет:
    """Ответ `х.просвет`: `.карта` — float32 (В, Ш) области, 0–1; `.дыры` — список словарей по убыванию площади:
    'рамка' (x0, y0, x1, y1 холста), 'центр' (x, y), 'площадь' px, 'просвет' (среднее карты в дыре), 'у края' (дыра
    касается края области — может быть просто краем зоны); `.сводка` — 'просвет' (среднее карты), 'доля' (доля
    пикселей от порога), 'дыр', 'в дырах' px, 'сквозь' (слои), 'видно' ('грунт' или имя слоя под ними), 'порог',
    'площадь', 'область'; `.лист` — uint8 «холст | карта» с рамками дыр (`путь` — PNG)."""
    __slots__ = ('карта', 'дыры', 'сводка', 'область', '_лист')

    def __getitem__(self, ключ):
        return self.сводка[ключ]

    @property
    def лист(self):
        return self._лист() if callable(self._лист) else self._лист

    def __repr__(self):
        с = self.сводка
        return (f'Просвет({с["область"]}: видно {с["видно"]} {с["просвет"]:.3f} в среднем, от {с["порог"]} — '
                f'{с["доля"]:.3f} места, дыр {с["дыр"]}' +
                (f', крупная {self.дыры[0]["площадь"]} px у {self.дыры[0]["центр"]})' if self.дыры else ')'))


def карта(х, область=None, слой=None):
    """Карта просвета области (float32 (В, Ш)) и слои, сквозь которые она взята, и что под ними видно."""
    from .глаз import _рамка
    х.досчитать()
    x0, y0, x1, y1 = _рамка(х, область)
    имена = list(х.слои)
    if слой is not None and слой not in имена:
        raise KeyError(f'просвет: слоя {слой!r} нет (слои снизу вверх: {имена})')
    сквозь = имена[имена.index(слой):] if слой is not None else имена
    видно = 'грунт' if слой is None or имена.index(слой) == 0 else f'под «{слой}»'
    ly, lx = slice(y0 - х.y0, y1 - х.y0), slice(x0 - х.x0, x1 - х.x0)
    к = np.ones((y1 - y0, x1 - x0), np.float32)
    for и in сквозь:
        с = х.слои[и]
        к *= 1.0 - np.asarray(с.покрытие[ly, lx], np.float32)
        if с.пропуск is not None:
            к *= np.asarray(с.пропуск[ly, lx], np.float32) @ ЯРКОСТЬ
    np.clip(к, 0.0, 1.0, out=к)
    return к, (x0, y0, x1, y1), сквозь, видно


def просвет(х, область=None, слой=None, порог=0.5, площадь=4, дыр=50, путь=None, масштаб=1, без=None, до=None):
    """Б-3: карта просвета области и дыры. Подробно — модуль и `Просвет`."""
    from scipy import ndimage
    from .глаз import без_слоёв
    if not 0.0 < порог <= 1.0:
        raise ValueError('просвет: порог — от 0 (не включая) до 1')
    х = без_слоёв(х, без, до)
    к, рамка, сквозь, видно = карта(х, область, слой)
    x0, y0 = рамка[:2]
    метки, n = ndimage.label(к >= порог, structure=np.ones((3, 3), bool))
    дыры = []
    if n:
        площади = np.bincount(метки.ravel(), minlength=n + 1)
        суммы = np.bincount(метки.ravel(), weights=к.ravel().astype(np.float64), minlength=n + 1)
        места = ndimage.find_objects(метки)
        for j in np.argsort(-площади[1:], kind='stable') + 1:
            s = int(площади[j])
            if s < площадь:
                break
            sy, sx = места[j - 1]
            yy, xx = np.nonzero(метки[sy, sx] == j)
            дыры.append({'рамка': (x0 + sx.start, y0 + sy.start, x0 + sx.stop, y0 + sy.stop),
                         'центр': (round(x0 + sx.start + float(xx.mean()), 1), round(y0 + sy.start + float(yy.mean()), 1)),
                         'площадь': s, 'просвет': round(float(суммы[j] / s), 3),
                         'у края': bool(sy.start == 0 or sx.start == 0 or sy.stop == к.shape[0] or sx.stop == к.shape[1])})
    п = Просвет()
    п.карта, п.дыры, п.область = к, дыры[:дыр] if дыр is not None else дыры, рамка
    п.сводка = {'просвет': round(float(к.mean()), 4), 'доля': round(float((к >= порог).mean()), 4), 'дыр': len(дыры),
                'в дырах': int(sum(д['площадь'] for д in дыры)), 'сквозь': сквозь, 'видно': видно, 'порог': порог,
                'площадь': площадь, 'область': рамка}
    п._лист = lambda: _лист(х, п, масштаб, None)
    if путь is not None:
        п._лист = _лист(х, п, масштаб, путь)
    return п


def _лист(х, п, масштаб, путь):
    """«холст | карта»: карта серым (белое — видно нижнее), рамки дыр красным — на обеих половинах."""
    from PIL import Image, ImageDraw
    from .глаз import взгляд, _масштаб, _лист as лист_панелей
    левая = взгляд(х, п.область, масштаб=масштаб)
    правая = _масштаб((np.repeat(п.карта[..., None], 3, -1) * 255.0 + 0.5).astype(np.uint8), масштаб)
    правая = правая[:левая.shape[0], :левая.shape[1]]
    x0, y0 = п.область[:2]
    m = левая.shape[1] / max(1, п.карта.shape[1])
    панели = []
    for a in (левая, правая):
        im = Image.fromarray(np.ascontiguousarray(a))
        д = ImageDraw.Draw(im)
        for дд in п.дыры[:20]:
            a0, b0, a1, b1 = дд['рамка']
            д.rectangle([(a0 - x0) * m - 2, (b0 - y0) * m - 2, (a1 - x0) * m + 1, (b1 - y0) * m + 1], outline=(230, 30, 30))
        панели.append(np.asarray(im))
    с = п.сводка
    подписи = [f'холст {п.область}, ×{масштаб}',
               f'просвет: видно {с["видно"]} (белое) · среднее {с["просвет"]:.3f} · дыр {с["дыр"]}'.replace('.', ',')]
    return лист_панелей(панели, подписи, путь)
