"""К-5 (К-17 баланса): мягкость края числом — `край_для`: какой край (`о.край`: кайма в мм и px, рваность, слово)
даст один ход до кладки, и что взять под заказ каймы — нагрузку, нажим и, если нужно, поле `кайма` кисти.

Почему стенд, а не таблица (замер Движка 191, 960 точек × 3 сида). Кайма идёт не за одним числом: у `мягкая` 32 по
сухому она растёт от тяжёлой руки к лёгкой (0,12 → 0,35 мм), по сырому — наоборот и не монотонно: нагрузка 0,05–0,1
кладёт 0,06 мм, 0,2–0,3 — 0,42 мм; сырое толщиной 0,1 гасит кайму совсем, 0,3–0,4 даёт самую широкую, 0,7 — снова
уже. Поле `кайма` у щетины расширяет край (плоская 40: 0,25 → 0,62 мм), круглая 22 по сырому больше 0,23 мм не даёт.
Кисть модели — любая, с любыми полями; таблица на каждую не снимется. Поэтому счёт — сам ход на своём стенде в памяти:
ход 0,06–0,15 с; прогноз — 24 сида (48, где один ход гуляет на 0,08 мм и больше), 2–7 с; заказ — перебор сетки по
6 сидов и сверка лучших всеми, по сухому 20–110 с, по сырому 70–150 с.

Стенд (в мм — тот же при любом `px_на_мм`; при 8 px/мм — 600×200 px): чистый грунт (166, 146, 129), гладкий; ход
`путь_с_нажимом` прямо, 50 мм (`длина=` 10–200), от 12,5 мм с края, посередине высоты, краской (40, 40, 60), в слой
'основа', кистью модели (её копией), сиды `СИДЫ` 101–124. По сырому — под ходом в том же слое заливка: `плоская`
5 мм рядами вдоль хода, шаг 3,25 мм, `ровно=1`, нажим 0,6, светлой (220, 200, 160), сиды 50 + номер ряда; нагрузка
заливки — 0,6 (`по_сырому=True`) или по кривой сырой толщины (`по_сырому=` числом, или место холста).

Мерка — `о.край` хода (`ответ.py`: кайма — px от 10 до 50 % уровня тела поперёк хода, медиана двух сторон). Слово —
большинство по сидам. Только счёт: холст, кисть и журнал модели не трогаются.
"""
import math
import warnings

import numpy as np

ГРУНТ = (166, 146, 129)
ПХ = 8.0
ДЛИНА = 50.0                                # ход стенда, мм
ДЛИНЫ = (10.0, 200.0)
ПОЛЕ_ММ = 12.5                              # от края стенда до хода, мм
ВЫСОТА_ММ = 25.0
КРАСКА = (40, 40, 60)
ЗАЛИВКА = (220, 200, 160)
РЯДЫ_ММ = (5.0, 3.25, 5.0, 21.25)           # ширина `плоская` заливки, шаг рядов, от края стенда по x, по высоте —
                                            # до последнего ряда (ряды от 5 мм до 21,25 мм)
НАГРУЗКА_ЗАЛИВКИ = 0.6                      # `по_сырому=True`
НАГРУЗКИ_ЗАЛИВКИ = (0.15, 0.3, 0.45, 0.6, 0.8, 1.0)   # кривая сырой толщины (под `по_сырому=` числом)
СИДЫ = tuple(range(101, 125))               # прогноз
СИДЫ_ПОИСКА = СИДЫ[:6]                      # перебор под заказ
СИДЫ_ШИРЕ = tuple(range(101, 149))          # прогноз, где один ход гуляет на ШУМ и больше: 48 сидов
ШУМ = 0.08                                  # мм σ по сиду — с него в ответе 'шум' (по сырому — 0,1–0,2 мм)
СЕТКА_НАГРУЗКИ = (0.05, 0.1, 0.15, 0.2, 0.3, 0.45, 0.65, 0.85)
СЕТКА_НАЖИМА = (0.35, 0.5, 0.65, 0.85)
ПОЛЯ_КАЙМЫ = (0.15, 0.3, 0.5, 0.7)          # поле `кайма` кисти, если её как есть не хватает (по возрастанию)
ДОПУСК = (0.04, 0.12)                       # своя цель перебора: в max(0,04 мм, 12 %) от заказа (приёмка — 0,08 / 25 %)
ВЕС_РАЗБРОСА = 1.0                          # точка перебора судится |μ − заказ| + σ: ровная лучше точной (по сырому
                                            # один ход гуляет на 0,1–0,2 мм)
СВЕРОК = 4                                  # лучших точек перебора, что сверяются всеми `СИДЫ`
СЫРО = 1e-3                                 # сырая толщина, ниже которой ход идёт по сухому
_ЗАЛИВКИ = {}                               # (нагрузка, px, длина) -> Холст стенда (память процесса)
_КРИВЫЕ = {}                                # (px, длина) -> [(нагрузка заливки, толщина)]


def _px(v, px):
    return float(v) * px


def _холст(px, дл):
    from .холст import Холст
    return Холст(int(round((float(дл) + 2 * ПОЛЕ_ММ) * px)), int(round(ВЫСОТА_ММ * px)), грунт=ГРУНТ, px_на_мм=px,
                 ядра=1, подсказки=False)


def _окно(px, дл):
    """Окно хода стенда (x0, y0, x1, y1), px: средняя половина длины, ±1 мм поперёк — там меряется сырая толщина."""
    a, b = _px(ПОЛЕ_ММ, px), _px(ПОЛЕ_ММ + дл, px)
    yc = _px(ВЫСОТА_ММ / 2, px)
    return (int(a + (b - a) / 4), int(yc - px), int(b - (b - a) / 4), int(yc + px) + 1)


def заливка(нагрузка, px=ПХ, дл=ДЛИНА):
    """Холст стенда: None — сухой грунт; число — сырая заливка этой нагрузкой (ряды вдоль хода). Копией из памяти."""
    import copy
    if нагрузка is None:
        return _холст(px, дл)
    ключ = (round(float(нагрузка), 4), float(px), round(float(дл), 2))
    if ключ not in _ЗАЛИВКИ:
        from .кисть import Кисть
        from .путь import путь_с_нажимом
        from . import калибровка as кал
        import os
        х = _холст(px, дл)
        ш, шаг, от, до = (_px(v, px) for v in РЯДЫ_ММ)
        к = Кисть.из_файла(os.path.join(кал._ПРЕСЕТЫ, 'плоская.json'), ширина=ш)
        x1 = х.ширина - от
        with warnings.catch_warnings():
            warnings.simplefilter('ignore')
            y, i = от, 0
            while y <= до + 1e-6:
                т = путь_с_нажимом([(от, y), (x1, y)], ш, нажим=0.6, сид=50 + i)
                х.мазок(т, ЗАЛИВКА, к, сид=50 + i, нагрузка=float(нагрузка), ровно=1, слой='основа')
                y, i = y + шаг, i + 1
        if len(_ЗАЛИВКИ) >= 16:
            _ЗАЛИВКИ.pop(next(iter(_ЗАЛИВКИ)))
        _ЗАЛИВКИ[ключ] = х
    return copy.deepcopy(_ЗАЛИВКИ[ключ])


def толщина_стенда(нагрузка, px=ПХ, дл=ДЛИНА):
    """Сырая толщина заливки стенда под ходом (единицы `Слой.толщина`, как `смешение.сырая_толщина`)."""
    from .смешение import сырая_толщина
    return сырая_толщина(заливка(нагрузка, px, дл), _окно(px, дл))


def _кривая(px, дл):
    ключ = (float(px), round(float(дл), 2))
    if ключ not in _КРИВЫЕ:
        _КРИВЫЕ[ключ] = [(н, толщина_стенда(н, px, дл)) for н in НАГРУЗКИ_ЗАЛИВКИ]
    return _КРИВЫЕ[ключ]


def _нагрузка_заливки(толщина, px, дл):
    к = _кривая(px, дл)
    т = [v for _, v in к]
    if not (т[0] - 1e-9 <= толщина <= т[-1] + 1e-9):
        ближ = min(max(толщина, т[0]), т[-1])
        raise ValueError(f'край_для: сырое под ходом {толщина:.3f} — стенд кладёт заливку {т[0]:.3f}…{т[-1]:.3f}; '
                         f'ближайшее — {ближ:.3f}' + ('; тоньше — ход почти по сухому: по_сырому=None'
                                                      if толщина < т[0] else ''))
    return float(np.interp(толщина, т, [н for н, _ in к]))


def _сырое(по_сырому, холст, место, слой, px, дл):
    """(нагрузка заливки стенда или None, сырая толщина под ходом, откуда)."""
    if место is not None:
        if холст is None:
            raise ValueError('край_для: место= читается с холст=х')
        from .смешение import _сырое_слоёв
        сл = _сырое_слоёв(холст, tuple(int(round(v)) for v in место))
        и = слой or 'основа'
        т = сл.get(и, (0.0, 0.0))[0]
        if по_сырому is not None and по_сырому is not True:
            raise ValueError('край_для: место= или по_сырому= числом — одно из двух')
        if т < СЫРО:
            return None, round(т, 4), f'место, слой {и!r}: сухо'
        return _нагрузка_заливки(т, px, дл), round(т, 4), f'место, слой {и!r}'
    if по_сырому is None or по_сырому is False:
        return None, 0.0, 'сухо'
    if по_сырому is True:
        return НАГРУЗКА_ЗАЛИВКИ, round(толщина_стенда(НАГРУЗКА_ЗАЛИВКИ, px, дл), 4), 'стенд: заливка 0,6'
    т = float(по_сырому)
    if т < СЫРО:
        return None, 0.0, 'сухо'
    return _нагрузка_заливки(т, px, дл), round(т, 4), 'толщина'


def замер_хода(х, кисть, нагрузка, нажим, сид, px=ПХ, дл=ДЛИНА, разбавитель=None, краска=КРАСКА):
    """Один ход стенда по холсту `х` (кладёт на `х`!) — ответ мазка. Им же меряется живое в тесте пункта."""
    from .путь import путь_с_нажимом
    ш = float(кисть.ширина)
    yc = _px(ВЫСОТА_ММ / 2, px)
    т = путь_с_нажимом([(_px(ПОЛЕ_ММ, px), yc), (_px(ПОЛЕ_ММ + дл, px), yc)], ш, нажим=float(нажим), сид=сид)
    д = {'разбавитель': float(разбавитель)} if разбавитель else {}
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        return х.мазок(т, краска, кисть.копия(), сид=сид, нагрузка=нагрузка, слой='основа', **д)


def _прогноз(кисть, нз, нагрузка, нажим, px, дл, разбавитель, краска, сиды=СИДЫ):
    база = заливка(нз, px, дл)
    с = база.снимок()
    к, р, слова = [], [], []
    for сид in сиды:
        о = замер_хода(база, кисть, нагрузка, нажим, сид, px, дл, разбавитель, краска)
        база.откатить(с)
        if о is None or о.край is None:
            к.append(0.0), р.append(0.0), слова.append('нет следа')
            continue
        к.append(float(о.край['кайма'])), р.append(float(о.край['рваность'])), слова.append(о.край['слово'])
    к = np.asarray(к) / px
    if сиды == СИДЫ and float(к.std()) >= ШУМ:                # гуляет — точнее среднее: 48 сидов
        return _прогноз(кисть, нз, нагрузка, нажим, px, дл, разбавитель, краска, СИДЫ_ШИРЕ)
    слово = max(set(слова), key=lambda w: (слова.count(w), w))
    шум = ({'шум': f'один ход гуляет на ±{float(к.std()):.2f} мм: в кайму {float(к.mean()):.2f} попадает среднее ходов, '
                   f'а один ход — в ±{2 * float(к.std()):.2f}; ровнее — по сухому или другой нагрузкой'}
           if float(к.std()) >= ШУМ else {})
    return {**шум, 'кайма_мм': round(float(к.mean()), 3), 'кайма_px': round(float(к.mean() * px), 2),
            'разброс_мм': round(float(к.std()), 3), 'рваность_px': round(float(np.mean(р)), 2), 'слово': слово,
            'слова': {w: слова.count(w) for w in sorted(set(слова))}, 'сидов': len(сиды)}


def _нагрузка(нагрузка):
    from .инструмент import НАГРУЗКИ as ИМЕНА
    if isinstance(нагрузка, str):
        if нагрузка not in ИМЕНА or нагрузка == 'сухая':
            raise ValueError(f'край_для: нагрузка {нагрузка!r} — числом или {", ".join(к for к in ИМЕНА if к != "сухая")}')
        return float(ИМЕНА[нагрузка])
    н = float(нагрузка)
    if not (0.03 <= н <= 1.0):
        raise ValueError(f'край_для: нагрузка {н:g} — от 0,03 до 1; ближайшее — {min(max(н, 0.03), 1.0):g}')
    return н


def _допуск(цель):
    return max(ДОПУСК[0], ДОПУСК[1] * цель)


def край_для(кисть, кайма_мм=None, нагрузка=None, нажим=None, по_сырому=None, холст=None, место=None, слой=None,
             поле=True, длина=None, px_на_мм=None, разбавитель=None, цвет=None):
    """К-5: край одного хода числом — до кладки; ничего не кладёт.

    С `нагрузка=` (и `нажим=`, умолчание 0,6) — прогноз `о.край`: {'кайма_мм', 'кайма_px', 'разброс_мм' (σ по сиду),
    'рваность_px', 'слово' ('мягкий' / 'жёсткий' / 'рваный' — большинство сидов), 'слова', 'сидов' (24; где один ход
    гуляет на 0,08 мм и больше — 48), 'шум' (только тогда: словом, на сколько гуляет один ход), 'нагрузка', 'нажим',
    'кайма_кисти' (поле кисти), 'сырое': {'толщина', 'откуда'}}.

    С заказом `кайма_мм=` — то же в точке, где 24 сида дают кайму ближе всего к заказу, и что взять: 'нагрузка',
    'нажим', 'поле' — {} или {'кайма': v} (поле кисти, если её как есть не хватило; `поле=False` — не трогать), 'кисть' —
    копия кисти с этим полем (её и класть). Нажим дан — только при нём. Шире или уже достижимого — `ValueError` с
    ближайшим и тем, чем делать иначе (шире 0,7 мм — растушёвкой: `х.переход`, рецепт «Пятно со спадом»).

    Сырое под ходом: `по_сырому=None` — сухой грунт; `True` — заливка стенда нагрузкой 0,6 (сырая толщина ~0,39);
    число — сырая толщина слоя хода (единицы `Слой.толщина`, как `смешение_для(толщина=)`, стенд 0,10…0,72); или
    `холст=х, место=(x0, y0, x1, y1)` — толщина сырого слоя хода `слой=` (умолчание 'основа') в месте; холст только
    читается. Ход берёт сырое только своего слоя: сырое в других слоях кайму не меняет.

    Стенд — `кисть/край.py`: прямой ход 50 мм (`длина=`), гладкий грунт, сырое — ровные ряды одной краской вдоль хода.
    Свой путь, зерно, борозды места — ближе к `х.проба`."""
    px = float(холст.px_на_мм) if (холст is not None and холст.px_на_мм) else float(px_на_мм or ПХ)
    дл = ДЛИНА if длина is None else float(длина)
    if not (ДЛИНЫ[0] <= дл <= ДЛИНЫ[1]):
        raise ValueError(f'край_для: длина хода {дл:g} мм — стенд {ДЛИНЫ[0]:g}…{ДЛИНЫ[1]:g} мм; ближайшее — '
                         f'{min(max(дл, ДЛИНЫ[0]), ДЛИНЫ[1]):g}')
    if нажим is not None and not (0.05 <= float(нажим) <= 1.0):
        raise ValueError(f'край_для: нажим {float(нажим):g} — от 0,05 до 1; ближайшее — {min(max(float(нажим), 0.05), 1.0):g}')
    if разбавитель is not None and not (0.0 <= float(разбавитель) <= 1.0):
        raise ValueError(f'край_для: разбавитель {float(разбавитель):g} — от 0 до 1')
    краска = КРАСКА if цвет is None else tuple(int(round(float(v))) for v in tuple(цвет)[:3])
    нз, толщина, откуда = _сырое(по_сырому, холст, место, слой, px, дл)
    сырое = {'толщина': толщина, 'откуда': откуда}
    своя = float(getattr(кисть, 'кайма', 0.0) or 0.0)

    def итог(п, к, н, нж, поле_):
        п.update(нагрузка=round(float(н), 4), нажим=float(нж), кайма_кисти=round(float(getattr(к, 'кайма', 0.0) or 0.0), 3),
                 сырое=dict(сырое), поле=dict(поле_))
        return п

    if кайма_мм is None:
        if нагрузка is None:
            raise ValueError('край_для: дай нагрузка= (прогноз) или кайма_мм= (заказ)')
        н = _нагрузка(нагрузка)
        нж = 0.6 if нажим is None else float(нажим)
        return итог(_прогноз(кисть, нз, н, нж, px, дл, разбавитель, краска), кисть, н, нж, {})
    if нагрузка is not None:
        raise ValueError('край_для: с кайма_мм= нагрузку не давай — она и подбирается (нажим — можно)')
    цель = float(кайма_мм)
    if not (0.0 < цель <= 5.0):
        raise ValueError(f'край_для: кайма {цель:g} мм — больше 0 (мм, от 10 до 50 % тела поперёк хода)')
    нажимы = (float(нажим),) if нажим is not None else СЕТКА_НАЖИМА
    кисти = [(кисть, {})]
    if поле and getattr(кисть, 'форма', '') != 'мастихин':
        кисти += [(кисть.с(кайма=v), {'кайма': v}) for v in ПОЛЯ_КАЙМЫ if v > своя + 1e-6]
    точки, сверено, проверены = [], [], set()       # точки: (оценка, μ, σ, i кисти, нагрузка, нажим)
    for i, (к, _) in enumerate(кисти):
        for н in СЕТКА_НАГРУЗКИ:
            for нж in нажимы:
                п = _прогноз(к, нз, н, нж, px, дл, разбавитель, краска, СИДЫ_ПОИСКА)
                if п['слово'] != 'нет следа':
                    μ, σ = п['кайма_мм'], п['разброс_мм']
                    точки.append((abs(μ - цель) + ВЕС_РАЗБРОСА * σ, μ, σ, i, н, нж))
        if not точки:
            continue
        if not any(т[3] == i and abs(т[1] - цель) <= _допуск(цель) for т in точки) and i + 1 < len(кисти):
            continue                                 # эта кисть не достаёт — шире полем
        for оц, μ, σ, j, н, нж in sorted(точки)[:СВЕРОК]:     # лучшие — всеми сидами; кисть, что достала, — без шире
            if (j, н, нж) in проверены:
                continue
            проверены.add((j, н, нж))
            п = _прогноз(кисти[j][0], нз, н, нж, px, дл, разбавитель, краска)
            сверено.append((abs(п['кайма_мм'] - цель) + ВЕС_РАЗБРОСА * п['разброс_мм'], п, j, н, нж))
            if abs(п['кайма_мм'] - цель) <= _допуск(цель) and п['разброс_мм'] <= max(0.05, 0.2 * цель):
                break
        _, п, j, н, нж = min(сверено, key=lambda т: т[0])
        if abs(п['кайма_мм'] - цель) <= max(0.08, 0.25 * цель):
            к, поле_ = кисти[j]
            п = итог(п, к, н, нж, поле_)
            п['кисть'] = к.копия()
            return п
    if not точки:
        raise ValueError('край_для: ход не оставляет следа ни при какой нагрузке и нажиме сетки — кисть или краска?')
    _, μ, σ, i, н, нж = min(точки, key=lambda т: abs(т[1] - цель))     # ближайшее без веса разброса — тоже 24 сидами
    if (i, н, нж) not in проверены:
        сверено.append((0.0, _прогноз(кисти[i][0], нз, н, нж, px, дл, разбавитель, краска), i, н, нж))
    _, п, i, н, нж = min(сверено, key=lambda т: abs(т[1]['кайма_мм'] - цель))   # ближайшее — проверенное 24 сидами
    if abs(п['кайма_мм'] - цель) <= max(0.08, 0.25 * цель):   # проверенное в допуске заказа — заказ, не ошибка
        к, поле_ = кисти[i]
        п = итог(п, к, н, нж, поле_)
        п['кисть'] = к.копия()
        return п
    поле_ = кисти[i][1]
    чем = (f'нажим {нажимы[0]:g}' if len(нажимы) == 1 else 'нажим 0,35…0,85') + ', нагрузка 0,05…0,85' + (
        f', поле кайма до {max(своя, ПОЛЯ_КАЙМЫ[-1]):g}' if поле and len(кисти) > 1 else ', поле кисти как есть')
    if цель > п['кайма_мм']:
        совет = ('; шире одним ходом нельзя — растушёвкой поверх: `х.переход` (рецепт «Пятно со спадом»)'
                 + ('' if поле or своя >= ПОЛЯ_КАЙМЫ[-1] else ', или поле=True — шире полем кисти'))
    else:
        совет = '; уже — тяжелее рука (нагрузка больше), щетиной без каймы, по сухому или подсушенному'
    пк = поле_
    ближ = f'{п["кайма_мм"]:.2f} ± {п["разброс_мм"]:.2f} мм (нагрузка {н:g}, нажим {нж:g}' + (f', поле кайма {пк["кайма"]:g}' if пк else '') + ')'
    сыр = '' if нз is None else f', по сырому {толщина:.2f}'
    raise ValueError(f'край_для: кайма {цель:g} мм недостижима ({чем}{сыр}): ближайшее — {ближ}' + совет)
