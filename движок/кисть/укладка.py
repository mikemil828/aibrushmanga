    # волоска — едва коснувшаяся полная кисть кладёт гребень почти во всю ширину, а не серую дымку
    заполнен = ((кас_у ** (1.0 - 0.75 * густо) * np.sqrt(сыт))[:, г] if рвёт is None else рвёт.заполнен(кас_у ** (1.0 - 0.75 * густо), Сыт, i0, i1, f0, f1, г)) * (1.0 if сход_г is None else сход_г[:, г])   # п. 5б: по выборкам профиля
    маска = М.маска(мяг, (кас_у ** (1.0 - 0.75 * густо))[:, г], заполнен, с.x, lambda: зажать((заполнен * 1.2 - с.x[None, :]) * 10.0, 0.0, 1.0) if рвёт is None else рвёт.гребнем(заполнен, с.x) if not рвёт.сухая else рвёт.волосок(заполнен, (кас_у ** (1.0 - 0.75 * густо))[:, г], с.x, X, Y, ds, p, тащит, W))   # пятно касания у концов множится ниже, после `вых`; п. 18: пятно касания у концов — на укладке, перенос краски в теле прежний; п. 10, инструмент 2: у полупустой кисти кладёт волосок, а не гребень; 4а-2: бедный мягкий гребень кладёт тоньше, а не уже
    вых = (Вых[i0] * f0 + Вых[i1] * f1)[:, г]
    маска = _пятном(маска, вых, пятно_м, пятно_м0, путь['s'], W)
    шир = W / nm; путь_м = М.по_пути(мяг, X, Y, с.u, ds)      # К5, "load_along": площадь следа отсчёта — по пути волоска; без поля — 1
    # лёгкая кисть борозду не продавливает до дна: глубина борозд идёт с нажимом
    мелко = зажать(0.45 + 0.65 * p / 0.85, 0.0, 1.0)[:, None]
    профиль = профиль_борозд(с, бор, мелко)
    # след кладётся ядром в пиксель с лишним: чтобы он вышел в ширину кисти, самый край кисти краски не кладёт
    # (у густой: тонкая плёнка у края сходит на нет сама)
    край_м = np.ones(nm) if мастихин else 1.0 - густо * (1.0 - зажать((W / 2 - _ЯДРО / 2 - np.abs(с.u)) / 0.5 + 0.5, 0.0, 1.0))
    if густо > 0 and not мастихин and nr > 2:
        # крайний гребень уже двух пикселей густой краски не несёт: за бороздой крайнего волоска нитки-обводки нет
        for кр in (0, nr - 1):
            if 2.0 * с.полуш[кр] < 2.0:
                край_м = край_м * (1.0 - густо * (г == кр))
    if угол_м is not None:
        маска = маска * угол_м
    if посадка_м is not None:
        маска = маска * (1.0 + ((посадка_м if рвёт is None or not рвёт.сухая else рвёт.вразнобой(посадка_м, p, ds, W)) - 1.0) * плашмя)   # v3.21: у полупустой кисти посадка и подъём — по волоску
    if край_места is not None:
        рвёт_м = 1.0 - (1.0 - (край_места[0][i0] * f0 + край_места[0][i1] * f1)[:, г]) * край_места[1][None, :]
        маска = маска * рвёт_м
    D = вых * маска * профиль * (валик_м * (шир * ds)) * край_м[None, :] * (1.0 if тонко_г is None else тонко_г.тоньше(с, неровн, густота, i0, i1, f0, f1, шаг_к, None if перепад is None or рвёт is not None else lambda ж: перепад[зажать(np.floor(Y[ж] - by0).astype(np.intp), 0, перепад.shape[0] - 1), зажать(np.floor(X[ж] - bx0).astype(np.intp), 0, перепад.shape[1] - 1)])) * (сход_о[:, None] if живая > 0 else 1.0) * (1.0 if мяг is None else мяг.кладёт[:, г] * путь_м) * (1.0 if рвёт is None else рвёт.с_гребня())   # п. 13: гребень лежащей краски снимает с волоска полупустой кисти больше; мягкая кисть: слабо прижатый волос оставляет плёнку тоньше; п. 10: собранный к оси ворс кладёт краски по своей ширине, а не гуще
    # борозда цветом (п. 5, 5в): тон идёт за живой глубиной борозды — у тонкой краски. Пастозная кроет телом, её гребень и дно одного тона
    тон_бор = (тон_борозды(с, бор, профиль, D / (H * шир * ds), 1.0 - np.exp(-D / (тау * шир * ds)), к.разброс_тона * (1.0 - густо), ds)
               if бор is not None and густо < 1.0 else None)
    if по_месту is not None:
        D = D * (1.0 - _ШТРИХ[2] * (по_месту[2][i0] * f0 + по_месту[2][i1] * f1))
    if стыки is not None:
        for kс, щ, пол in zip(*стыки):
            if щ > 0:
                t = зажать(np.abs(с.u - (с.центр[kс] + с.полуш[kс])) / пол, 0.0, 1.0)
                D = D * (1.0 - min(1.7 * щ, 1.0) * (1.0 - t ** 4))[None, :]
    if бока is not None:
        # поджатая прядь краску не копит: что не легло, осталось на кисти — обводки с двух сторон нет
        D = D * (1.0 - (бока[:, :1] / (якорь_л + с.полуширина)) * (с.u < якорь_л)[None, :]
                 - (бока[:, 1:] / (с.полуширина - якорь_п)) * (с.u > якорь_п)[None, :])
    D = _валик_бока(просвет.открыть(D, с, шир, тау * ds, None if рвёт is None else рвёт.задет), с, к, p, расп, Вых, Hг, неровн, i0, i1, f0, f1, ds, W, густо, мяг is not None or чистая or скупо is not None or _сухая(к, нагрузка) or мутность < 1.0)   # п. 19: валик по бокам (текучая краска его ровняет сама, `_текучая`)
    сгус = Сгус[i0][:, г] * (шир / _ШК) * (1.0 if пятно_м is None else пятно_м)                       # сгусток — на шаги своего отрезка поровну
    if Напл is not None and Напл.any(): сгус = сгус + _вал_конца(_по_овалу(Напл[i0][:, г] * (шир / _ШК) * пятно_м, None if пятно_м0 is None else Напл0[i0][:, г] * (шир / _ШК) * пятно_м0), концы, с, путь['s'], _вдоль(отст_г, вдоль_к * тащит, обойма, предел), шир, ds, W)   # п. 19: наплыв — валом у кромки остановки
    if сгус.any():
        D += М.отпущено(мяг, сгус) * (0.6 + 0.4 * с.профиль)[None, :]   # К5: сгусток и наплыв сходят с кисти той же отдачей
    Xл, Yл = X - bx0, Y - by0
    кома_нет = not Ч._КОМ_ВКЛ or чистая or скупо is not None or _сухая(к, нагрузка) or рвёт is not None or к.сухость > 0 or мастихин or (мяг is not None and (мяг.отдача is not None or (густо <= 0.0 and есть_сырое)))             # п. 21, Д1: ком оседает и у не кроющей краски (пропуск считается ниже по осевшей плёнке — идёт с краской), и у мягкой кисти; полупустая кисть кома не несёт — её рельеф и есть след по зерну; мастихин — как был. Мягкая кисть с тонкой краской по сырому (Дв105): густо она кладёт не свою краску, а снятую сырую — жилами по прядям, в десятки толщин своей плёнки, посреди короткого хода; столба над сырым слоем это не ставит, а оседание уводило бы лежащую краску из пятна (ореол: тон ядра 0,925 → 0,891); К5, "load_along": рука отпускает кисть по ходу — кома на конце нет, а самое толстое место хода, который ложится сам на себя (спираль), — не конец
    ii, jj = np.nonzero((D > 0.0) | (кас_у[:, г] > 0.0))
    if len(ii) == 0 or (чистая and берёт is None):           # 5а: вытертая кисть по сухому и по голому грунту не меняет ничего
        return _пусто(почему, 'чистая' if чистая else 'пусто')
    xs, ys = Xл[ii, jj], Yл[ii, jj]
    d = D[ii, jj]
    цвета = из_кс(Цв)                                         # (Nc, nr, 3)
    if тонко is not None and набор:
        # краска набора не размешана и вдоль волоска: тон гребня плавно гуляет по ходу (без точек: тонкое место — в `_набор`)
        цвета = зажать(цвета * np.exp(_ТОН_ХОД * _шум(rng_в, Nc, nr, max(0.4 * W, 8.0) / шаг_к))[:, :, None], 0.0, 1.0)
    ц = цвета[i0[ii], г[jj]] * f0[ii] + цвета[i1[ii], г[jj]] * f1[ii]
    if тон_бор is not None:
        ц = зажать(ц * тон_бор[ii, jj], 0.0, 1.0)
    if по_месту is not None:
        # прожилка в часть гребня: поверх своей краски гребень несёт нитку соседней
        g = (по_месту[0][i0[ii], jj] * f0[ii, 0] + по_месту[0][i1[ii], jj] * f1[ii, 0])[:, None]
        ц_жил = np.stack([зажать(c[None, :] * тон_гр, 0.0, 1.0) for c, _ in краски])[по_месту[1][jj], г[jj]]
        ц = ц * (1.0 - g) + ц_жил * g
    if цепляет is not None:
        зона = зажать((_КРОМКА[3] - от_кр) / 0.8, 0.0, 1.0)[jj][:, None]      # крайние 3 px следа
        цвета_кр = из_кс(Цв_кр)
        ц = ц * (1.0 - зона) + (цвета_кр[i0[ii], г[jj]] * f0[ii] + цвета_кр[i1[ii], г[jj]] * f1[ii]) * зона
    касание_м = зажать((кас_у[:, г] * 1.2 - с.x[None, :]) * 4.0, 0.0, 1.0) * край_м[None, :] * (1.0 if пятно_м is None else пятно_м * сход_г[:, г])
    if угол_м is not None:
        касание_м = касание_м * угол_м
    if посадка_м is not None:
        касание_м = касание_м * (1.0 + (посадка_м - 1.0) * плашмя)
    if край_места is not None:
        касание_м = касание_м * рвёт_м
    касание_м = М.отпущено(мяг, касание_м)[ii, jj]; пл_м = шир * ds if np.ndim(путь_м) == 0 else (шир * ds) * путь_м[ii, jj]   # К5: и касание, и съём сырого — на ту же площадь
    d, ц, край, край_в, обм_м = М.Обмен.в_след(обмен, ц, lambda: (lambda цх: цх[i0[ii], г[jj]] * f0[ii] + цх[i1[ii], г[jj]] * f1[ii])(из_кс(кс_холста)), (d, ц, None, []) if струи is None else струи.в_плёнку(d, ц, i0, i1, f0, f1, г, ii, jj, None if край is None else край.к_плёнке(касание_м, Втир, _острая(W, к.остриё))), i0, i1, f0, f1, г, ii, jj, касание_м * пл_м * М.ход_волоса(мяг, чистая, профиль, ii, jj))   # Г-3: разворошённое вытертым мягким волосом ложится по его бороздкам; 6а-1: в струе своей краски нет; 6а-2: у входа, бока и отрыва по сырому своя плёнка меняется местами с лежащей (`Край`)
    веса = [d, d * ц[:, 0], d * ц[:, 1], d * ц[:, 2], касание_м * пл_м]
    if берёт is not None:
        снято = (берёт[i0] * f0 + берёт[i1] * f1)[:, г][ii, jj] * касание_м * с.съём[jj] * пл_м
        веса.append((снято if струи is None else струи.снято(снято, i0, i1, f0, f1, г, ii, jj, край)) + обм_м)   # в струе лежащая не снята, ноша ложится взамен неё; у бока съём — по ноше волоска
        веса += [(Втир[i0] * f0 + Втир[i1] * f1)[:, г][ii, jj] * касание_м * пл_м] + край_в + М.плуг(мяг, чистая, касание_м * пл_м * М.ход_волоса(мяг, чистая, профиль, ii, jj))   # Г-3: поле бороздок вытертого мягкого волоса — последним
    if вал is not None:
        xs, ys, веса = вал.в_растр(xs, ys, веса, с, W, на_холст, отст_г, i0, bx0, by0)
    xs, ys, веса = просвет.в_растр(xs, ys, веса, с, D, на_холст, отст_г, кончик, цвета, i0, ax, ay, расп, bx0, by0, None if держит is None else расп0, вдоль_х, qx * ax + qy * ay); xs, ys, веса = _сплошь(xs, ys, веса, X, Y, D, ii, jj)   # Д1б, строка 7: след кончика сплошной
    поля = _брызги2(xs, ys, bw, bh, веса)
    V, eps = (поля[0] if рвёт is None else рвёт.достал(поля[0])), 1e-9   # К6: в ложбину под лёгкой рукой краска не ложится
    ц_нов = np.stack(поля[1:4], axis=-1) / np.maximum(поля[0], eps)[..., None]
    касание = зажать(поля[4], 0.0, 1.0)
    # втирание по пикселям: где кисть лежащего не достала, оно не тронуто
    втирание = зажать(поля[6] / np.maximum(поля[4], 1e-6), 0.0, 1.0) if берёт is not None else None
    трогает = касание if втирание is None else касание * втирание

    # --- сырая краска под мазком: часть снята кистью (она уже в каплях), часть вмешана на месте
    def покрытие_от(h):
        return 1.0 - np.exp(-np.maximum(h, 0.0) / тау)

    # на голом месте краска, не собравшаяся в плёнку (едва заметные пиксели дальше 2 px от закрашенного),
    # не остаётся: за кромкой покрытие падает до нуля не дальше 2 px
    if мяг is None: V = np.where(_рядом_с_плёнкой(покрытие_от(V) >= 0.25) | (Aо > 0.02), V, 0.0)   # у мягкой кисти тонкая плёнка края и есть след
    V, ц_нов = (V, ц_нов) if кома_нет else _осел(V, ц_нов, W, _зона_кома(сгус, D, Xл, Yл, с.u, bh, bw, W, V), одна)                  # п. 21: ком у конца хода оседает по плёнке своего следа
    V_р = _рельеф_плёнки(V, густо, бор)                       # рельеф плёнки; V — её пигмент: он красит и кроет

    if мутность < 1.0 and густо < 1.0 and not _сухая(к, нагрузка):
        V = V_р = _оплыть(V, ц_нов, hо + sum(взять(нс.толщина) for нс in под), 1.0 - густо)     # п. 10, инструмент 3: густая и полупустая кисть не текут
    hо_исх = hо                                                       # v4, 5д-2: поверхность сырой под ходом до него
    if ровно: V, V_р, ушло_ч = _текучая(V, ц_нов, W, ровно, тау, sum(взять(нс.толщина) for нс in ровно_низ[0]) * ровно_низ[1], hо * wо_подв * (Aо > 0.5) if есть_краска else None, Cо, касание, None if слой.текучая is None else взять(слой.текучая), [c for c, _ in краски] if набор else None); hо = hо if ушло_ч is None else hо - ушло_ч   # К4: лежащая текучая плёнка отдала краску в шов; рядом — сырая краска своего слоя, что кроет (толщина без покрытия — оплывший рельеф, не плёнка)
    if есть_краска:
        # кисть разравнивает рельеф под собой
        ровный = _коробка(_коробка(hо, 8), 8)
        hо = hо + М.ровно(чистая, (ровный * М.по_волосу(мяг, чистая, поля, поля[4]) - hо) * (трогает * (0.95 if мастихин else 0.55 + 0.4 * wо)), трогает)   # 5а: вытертая кисть ровняет рельеф, краски не прибавляя
    вмешано = None
    if берёт is not None:
        просят = поля[5]
        доступно = сыр_h if not низ else hо * wо_подв
        снять = np.minimum(просят, доступно * 0.9)
        остаток_просьбы = просят - снять
        было = покрытие_от(hо)
        hо, V, V_р = М.сведено(чистая, hо, hо - снять if струи is None else струи.ровнять(hо - снять, струи.под_кистью(трогает) * wо_подв, _размыть), снять, просят, V, V_р, трогает * wо_подв)   # 6а-1: струя — не гребень
        # где сырую плёнку сняли до дна — в борозде открывается то, что под ней
        Aо = Aо * зажать(покрытие_от(hо) / np.maximum(было, 1e-6), 0.0, 1.0) ** 0.7
        for нс, hн, сн, cн in низ:
            ещё = np.minimum(остаток_просьбы, сн * 0.9)
            остаток_просьбы = остаток_просьбы - ещё
            нс.толщина[хол] = (hн - ещё)[лок]
    V, V_р = (V, V_р) if берёт is None else М.Обмен.не_из_ничего(обмен, чистая, остаток_просьбы, поля[0], V, V_р); ц_нов, hо = (ц_нов, hо) if край is None or чистая else край.на_месте(поля[7], V, hо, wо_подв, ц_нов, Cо)   # 6а-2: края по сырому — лежащая краска на месте; v4, 2а: чего с лежащего снять не вышло, то в след не легло
    if ровно and есть_краска: hо = hо - np.minimum(hо * wо, V_р) * (ровно * зажать(V_р / np.maximum(V_р.max(), eps) * 4.0, 0.0, 1.0))   # п. 15: лежащую сырую краску своего слоя текучий ход вытесняет — второй ход внахлёст ложится в уровень с первым; v4, 5д: по плёнке `V_р`, не по пигменту
    V_р = _кромка(V_р, разбавитель, np.maximum(hо_исх - hо, 0.0) * wо if есть_краска else None)              # v4, 5в: край плёнки спадает на длине в мм; 5д-2: убыль сырой под ходом плёнка доливает в уровень
    if есть_сырое and есть_краска:
        вмешано = np.minimum(hо, 0.3 * мт) * wо_подв * (0.10 + 0.4 * к.подбор) * трогает
    if слой.пропуск is not None: _просвет_за_толщиной(слой.пропуск, хол, лок, взять(слой.толщина), hо)      # п. 10, инструмент 3 (3а-2)
    M, ц_верх = _вмешать(V, вмешано, ц_нов, Cо, eps)
    # --- толщина красит: тонкая плёнка просвечивает, густая кроет
    альфа = покрытие_от(M if мутность >= 1.0 else _кроет(M, тау, мутность)) * непрозрачность
    Cо_сыр = Cо   # Ф-1: цвет лежащей краски до просвета — им красится плёнка без покрытия
    if мутность < 1.0: Cо = _на_просвет(пропуск(), хол, лок, ц_верх, M * непрозрачность, мутность, Cо)     # п. 10, инструмент 3

    # --- запись в слой
    A_нов = альфа + Aо * (1.0 - альфа)
    if ровно and not _сухая(к, нагрузка):      # Ф-2: текучая плёнка затекает в низины сухой лежащей краски — своего слоя и слоёв ниже
        ниже_h, сух_р = None, np.zeros((bh, bw))
        for нс in ровно_низ[0]:                # как их сложит `Холст.рельеф`: под краской слоя выше нижнее ослаблено
            т_н = взять(нс.толщина)
            ниже_h = т_н if ниже_h is None else ниже_h * (1.0 - (1.0 - ровно_низ[1]) * взять(нс.покрытие)) + т_н
            сух_р = np.where(т_н > eps, 1.0 - взять(нс.влажность), сух_р)
        if есть_краска: сух_р = np.where(hо_исх > eps, 1.0 - wо, сух_р)      # по толщине до хода: кисть ровняла её и за край лежащего
        if (сух_р > 1e-3).any():               # сухого под ходом нет (голый грунт, сырое) — как было
            V_р = _сомкнуть(V_р, hо if ниже_h is None else hо + ниже_h * (1.0 - (1.0 - ровно_низ[1]) * A_нов), сух_р, ровно, разбавитель)
    if есть_краска:
        C_нов = (Cо * (Aо * (1.0 - альфа))[..., None] + ц_верх * альфа[..., None]) / np.maximum(A_нов, eps)[..., None]
        h_нов = hо + V_р
        w_нов = np.where(h_нов > eps, (wо * hо + V_р) / np.maximum(h_нов, eps), 0.0)
        if ровно: h_нов = _срослась(h_нов, w_нов, V, ровно)       # п. 15
        # свежая краска не схвачена: схват слоя разбавляется её толщиной
        слой.схват[хол] = np.where(h_нов > eps, схо * hо / np.maximum(h_нов, eps), 0.0)[лок]
    else:
        C_нов = np.where((альфа > 0)[..., None], ц_верх, 0.0)
        h_нов = V_р
        w_нов = (V_р > eps) * 1.0
    слой.цвет[хол] = _цвет_без_покрытия(C_нов, A_нов, h_нов, Cо_сыр, hо, ц_верх, V_р, eps)[лок]
    слой.покрытие[хол] = A_нов[лок]
    слой.толщина[хол] = np.maximum(h_нов[лок], 0.0); слой.влажность[хол] = зажать(w_нов[лок], 0.0, 1.0)
    if ровно or слой.текучая is not None: _след_текучей(слой, хол, ровно, np.maximum(касание, V > 0.0)[лок], альфа[лок])   # К4
    if замер is not None: замер(dict(альфа=альфа[лок], касание=касание[лок], положено=float(V[лок].sum()), сырое=сыр_h[лок] if есть_сырое else None, снято=float((просят - остаток_просьбы)[лок].sum()) if берёт is not None else 0.0, x=x, y=y, W=W, угол=(cx0, cy0)))   # 3г (К-1): поля следа — ответу мазка (`ответ.Ответ`); слой и кисть уже записаны, здесь только чтение; снято — со своего слоя и нижних
    return (cx0, cy0, cx1, cy1)
