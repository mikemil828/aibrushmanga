    стыки, перетёк = _стыки(номера[0], с, rng_б, густо, len(краски), набор, p[ic], шаг_к, W) if not одна and густо > 0 and not мастихин and nr > 1 else (None, None)
    кс_своя = кс_красок[0] if одна else (np.einsum('cnq,qnk->cnk', доли_гр, кс_красок) if узкий_набор else None)   # узкий набор: (Nc, nr, 24) — что гребень несёт из запаса
    жилка = тонко = по_месту = None                                           # прожилка и тонкое место в часть гребня (п. 2д)
    if набор and nr > 2:
        жилка, кс_жилки, обрыв, тонко, по_месту = _набор(номера[0], с, путь, ic, p, rng_в, W, len(краски),
                                                          [д for _, д in краски], rng_д, *((полосы[1], np.cumsum(расход * кас_к.max(axis=1)) * шаг_к) if полосы else ()))
        кс_жилки = кс_красок[кс_жилки, гр]                     # (nr, 24)
    sc_к = путь['s'][ic] - путь['s'][int(np.argmax(p > 0.02))]   # px пути от касания, на шаге переноса
    # бок живой (п. 2г): крайний гребень реже и беднее краской — его след рвётся, кромка отступает и возвращается
    край_рвёт = 1.0 - живёт * (1.0 - _край(с, sc_к, rng_г, W, *((1.0, 1.0) if набор else _КРАЙ_ОДНА[2:]), узкая=набор and W < 20.0)) if толстая else None
    край_места = None
    if толстая and not набор:
        # тонкое место штрихом — и у одной краски (п. 2д): реже, чем у набора, — одна краска набрана ровнее
        тонко = 1.0 - _ШТРИХ[2] * живёт * _штрих(с, sc_к, rng_г, W, _ШТРИХ_ОДНА)
