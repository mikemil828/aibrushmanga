def _узко(W):
    """П. 10: во сколько раз кисть уже 16 px (`_ОСТРАЯ[0]`) (1 — не уже): на столько мельче её кромка по сырому — иначе
    кисть 3–6 px вся «кромка» и своей краски по сырому не даёт."""
    return min(W / Ч._ОСТРАЯ[0], 1.0)


def _острая(W, остр=1.0):
    """П. 10: насколько кисть — узкая с острым кончиком: 1 до 12 px, к 16 px сходит на нет (шире — как было).
    П. 12: `остр` — свойство кисти `Кисть.остриё`: 0 — щетина в обойме, и узкая лежит плашмя всей шириной."""
    return float(зажать((Ч._ОСТРАЯ[0] - W) / Ч._ОСТРАЯ[1], 0.0, 1.0)) * остр


def _брюшко(W, круглая, p_р=None):
    """П. 10: нажим, с которого след узкой кисти в одну краску идёт во всю ширину. Плоская и круглая до 6 px —
    `_ДРОЖЬ[4]`; пучок круглой кисти толще раскрывается до брюшка раньше (к 9 px — при `_КРУГЛАЯ[0]`), дальше его
    держит обойма: след круглой 9–12 px при нажиме листа выходит названной ширины, а не в две трети.
    С `p_р` — ответ другой: нажим (N,), по которому расходится ворс (у круглой — в счёте раннего брюшка, не выше 0,85)."""
    полн = Ч._ДРОЖЬ[4] - (Ч._ДРОЖЬ[4] - Ч._КРУГЛАЯ[0]) * float(зажать((W - Ч._КРУГЛАЯ[1]) / Ч._КРУГЛАЯ[2], 0.0, 1.0)) * bool(круглая)
    if p_р is None:
        return полн
    return np.maximum(p_р, np.minimum(p_р * Ч._ДРОЖЬ[4] / полн, 0.85)) if круглая else p_р


def _ноша_брюшка(с, W, живая):
    """П. 10: круглая узкая кисть в одну краску, раскрытая до брюшка (`_брюшко`: с 6 px, к 9 px — целиком), кладёт
    краем следа бок брюшка, а краска у круглой кисти — в брюшке: крайние гребни несут не `0,55` от середины, как у
    пучка на кончике, а `_КРУГЛАЯ[3]`. Иначе у следа 9–12 px плёнка у краёв, едва запас тронут, тоньше видимой, и тело
    выходит уже названного (круглая 12 — как круглая 9). Ответ — нагрузка гребней (nr,), в среднем 1."""
    доля = живая * float(зажать((W - Ч._КРУГЛАЯ[1]) / Ч._КРУГЛАЯ[2], 0.0, 1.0))
    if доля <= 0:
        return с.нагр
    купол = np.sqrt(зажать(1.0 - с.расст * с.расст, 0.0, 1.0))
    a = 0.55 + (Ч._КРУГЛАЯ[3] - 0.55) * доля
    нагр = с.нагр * (a + (1.0 - a) * купол) / (0.55 + 0.45 * купол)
    return нагр / np.average(нагр, weights=с.полуш)


def _сел(просвет, с, живая, p, ds, W, rng):
    """П. 10: щель между прядями узкой кисти в одну краску (`Просвет`, правится здесь: модель узкой кисти).
    Где кисть села каплей, краска держит пряди вместе, щель закрыта; каплю стягивает ходом за `_КАПЛЯ_УЗК[9]` ширины:
    корень следа плоской 9–12 px не расходится двумя зубцами. Дальше ворс собран в остриё и пряди то расходятся, то
    сходятся сами — щель открыта кусками в `_ЩЕЛЬ_УЗК[0..1]` ширины хода и закрыта между ними (свой поток случая);
    плёнкой поперёк открытой щели краска у узкой кисти не встаёт: перемычки `Просвет.затекла` через каждые 5–14 px
    читались «лесенкой» между двумя прядями (круглая 9 px по сухому)."""
    у_посадки = живая * np.exp(-np.cumsum(ds * (p > 0.03)) / (Ч._КАПЛЯ_УЗК[9] * W))
    Щ = Ч._ЩЕЛЬ_УЗК
    n = просвет.открыта.shape[1]
    z = зажать((_шум(rng, len(p), n, 0.5 * (Щ[0] + Щ[1]) * max(W, Щ[2]) / ds) - Щ[3]) / Щ[4] + 0.5, 0.0, 1.0)
    разошлись = 1.0 - живая * (1.0 - z * z * (3.0 - 2.0 * z))                       # (N, щелей и боков)
    просвет.затекла = просвет.затекла * (1.0 - живая)
    открыта = просвет.открыта * разошлись * (1.0 - у_посадки)[:, None]
    # края у открытой щели кладут тоньше — тот же счёт, что в `Просвет`, с новой `открыта`
    пр_м, ns, раскрытие = с.прядь[с.гребень], с.ns, max(Ч._СРАСТ_ПРОСВЕТ[2], 1e-6)
    у_п = зажать(1.0 - (просвет.прав[пр_м] - с.u) / раскрытие, 0.0, 1.0)
    у_л = зажать(1.0 - (с.u - просвет.лев[пр_м]) / раскрытие, 0.0, 1.0)
    щ_п, щ_л = np.where(пр_м < ns - 1, пр_м, ns), np.where(пр_м > 0, пр_м - 1, ns - 1)
    просвет.открыта = открыта
    просвет.тоньше = зажать(1.0 - открыта[:, щ_п] * у_п[None, :] - открыта[:, щ_л] * у_л[None, :], 0.0, 1.0)


def _остриё(с, W, p_р, расст, мастихин, живая=False, круглая=False, остр=1.0, слита=0.0):
    """Порог касания гребней (N, nr) и множитель ширины следа (N,) — с острым кончиком узкой кисти (п. 10).
    Ворс узкой кисти собран в остриё: пряди одной длины и отходят от холста по гребню от краёв к середине, а не прядью
    разом (кончик травинки 9–12 px выходил уступом); на слабом нажиме след сходится к оси, а не идёт двумя-тремя
    иглами на половине ширины; сужает его сбор ворса, а не уход гребней по одному. Широкая кисть — как было."""
    о = 0.0 if мастихин else _острая(W, остр)
    if о <= 0 and слита <= 0:
        return _А_НАЖИМ * расст ** 1.15 + с.порог[None, :], 1.0
    ср = np.bincount(с.прядь, weights=с.порог, minlength=с.ns) / np.maximum(np.bincount(с.прядь, minlength=с.ns), 1)
    if о <= 0:      # п. 16: текучая краска слепила пряди кисти на ребре (`_ось_подъёма`) — короткая прядь не отходит раньше соседей
        return _А_НАЖИМ * расст ** 1.15 + (с.порог - слита * (ср - ср.min())[с.прядь])[None, :], 1.0
    z = зажать(p_р / Ч._ОСТРАЯ[3], 0.0, 1.0)
    сход = (1.0 - z) ** 2
    if живая:
        # кисть в одну краску: остриё мягкое, след ширится с нажимом на всём ходе, а не только у самого схода —
        # ширина травинки идёт за рукой (иначе тело следа — лента по линейке, «проволока»)
        сход = (1.0 - зажать(p_р / _брюшко(W, круглая), 0.0, 1.0)) ** Ч._ДРОЖЬ[3]
    return (_А_НАЖИМ * (1.0 - о * Ч._ОСТРАЯ[5]) * расст ** 1.15 + (с.порог - о * Ч._ОСТРАЯ[2] * ср[с.прядь])[None, :],
            1.0 - о * (1.0 - Ч._ОСТРАЯ[4]) * сход)


def _дрожь(rng, p, W, ds, густо, нет, остр=1.0):
    """П. 10: узкую кисть с тонкой краской рука держит на весу, кончик мягкий — нажим вдоль хода то и дело слабеет
    (выше заданного не идёт); с ним идут ширина следа (`_остриё`) и отдача краски. Только кисть в одну краску; густая
    краска держит ворс обоймой, широкая кисть и набор — как было (свой поток случая, прежние не сдвигаются).
    Ответ: насколько кисть живая (0 — нет), нажим и нажим руки, каким он пришёл (по нему меряется вход, `_посадка`)."""
    живая = 0.0 if (нет or len(p) < 3) else _острая(W, остр) * (1.0 - густо)
    if живая <= 0:
        return 0.0, p, p
    шум = _шум(np.random.default_rng(rng.bit_generator.seed_seq.spawn(1)[0]), len(p), 1, max(Ч._ДРОЖЬ[1] * W, Ч._ДРОЖЬ[2]) / ds)[:, 0]
    # капля посадки: полная кисть садится каплей и касается холста через неё — там, где она села, след ложится как под
    # нажимом, какой бы лёгкой ни была рука, и сходит к нажиму руки за ширину-две хода (обратный ход начинается пятном)
    К = Ч._КАПЛЯ_УЗК
    капля = min(К[0], К[7] * float(p.max())) * np.exp(-np.cumsum(ds * (p > 0.03)) / max(К[1] * W, К[2])) * зажать(p / 0.03, 0.0, 1.0)
    # севшая каплей кисть обратно в остриё не собирается, пока рука ещё набирает нажим: след от пятна посадки идёт
    # в тело без перехвата (у кисти 6–9 px капля сходила раньше, чем рука набирала нажим, — «спичка»)
    держит = К[8] * np.maximum.accumulate(капля) * (np.arange(len(p)) <= int(np.argmax(p)))
    return живая, np.maximum(p * (1.0 - живая * Ч._ДРОЖЬ[0] * зажать(шум + 0.5, 0.0, 2.0)), живая * np.maximum(капля, держит)), p


def _шире_острия(W):
    """П. 10: насколько узкая кисть шире острия `_КАПЛЯ_УЗК[10]` px (0 — остриё, 1 — вдвое шире и больше): остриё 3 px
    кладёт как было (по сырому не тонет), у кисти шире краска к концу хода идёт из запаса скупее и плёнка тоньшает."""
    return float(зажать(W / Ч._КАПЛЯ_УЗК[10] - 1.0, 0.0, 1.0))


def _сыт(W, заряд, полный, брюшком=0.0):
    """П. 10 (v3.17): насколько кончик узкой кисти сыт (nr,): 1, пока в брюшке больше `_КАПЛЯ_УЗК[13]` набранного — краску
    к кончику тянет из брюшка, и короткое касание полной кисти (ход в 2–5 ширин) кладёт её до конца; дальше — по остатку
    в степени `_КАПЛЯ_УЗК[5]`: беднеет длинный ход. (Степень остатка шла с первого пикселя: касание в ширину кисти теряло
    седьмую часть краски, в три ширины — больше трети.) Остриё 3 px (`_шире_острия` = 0) — по остатку, как было.
    3б (v3.31): `брюшком` — насколько круглая кисть раскрыта до брюшка (`_раскрыта`). Она кладёт самим брюшком: часть
    запаса, из которого кормится кончик, уже на холсте, и сытая фаза короче — порог идёт к 1 на долю `_КАПЛЯ_УЗК[14]`:
    след 9–12 px по сухому беднеет к концу длинного хода, а не держит плёнку до кончика (покрытие конца к началу было
    0,73–0,78 при пороге 0,75)."""
    ш = _шире_острия(W)
    порог = Ч._КАПЛЯ_УЗК[13] + (1.0 - Ч._КАПЛЯ_УЗК[13]) * Ч._КАПЛЯ_УЗК[14] * брюшком
    return зажать(заряд / (полный * (1.0 - (1.0 - порог) * ш)), 0.0, 1.0) ** (1.0 + (Ч._КАПЛЯ_УЗК[5] - 1.0) * ш)


def _раскрыта(к, W, живая):
    """3б: доля, на которую круглая узкая кисть раскрыта до брюшка (0 — плоская и пучок до `_КРУГЛАЯ[1]` px, 1 — с 9 px;
    та же, что в `_ноша_брюшка`)."""
    return живая * float(зажать((W - Ч._КРУГЛАЯ[1]) / Ч._КРУГЛАЯ[2], 0.0, 1.0)) * (к.форма == 'круглая')


def _сытая_отдаёт(живая, W, p):
    """П. 10 (v3.17): сытый кончик отдаёт краску сам — капля смачивает холст, какой бы лёгкой ни была рука, как у щетины
    (корень из нажима); круче за нажимом (`_КАПЛЯ_УЗК[4]`) краска идёт, когда брюшко пустеет и её надо выжимать.
    Ответ — показатель (Nc,): отдача гребня делится на exp(показатель · сытость) (`_сыт`). Иначе лёгкое касание полной
    кисти (нажим 0,45) клало плёнку в 0,56 полной вместо 0,75 — светлые касания копии тускнели."""
    return Ч._КАПЛЯ_УЗК[4] * живая * _шире_острия(W) * np.log(зажать(p, 0.03, None) / 0.8)


def _узкая_краска(живая, W, p=None, заряд=None, полный=None, брюшком=0.0):
    """П. 10, краска узкой кисти в одну краску (живая > 0; иначе — как было, бит в бит). По тому, что дано:
    p — отдача от нажима: мягкий кончик отдаёт краску с нажимом круче, чем щетина широкой (тон идёт за рукой);
    заряд — сколько своей краски идёт из запаса в каплю: у узкой кисти — по мере запаса (плёнка тоньшает вдоль
    хода постепенно, а не держится до последней четверти запаса);
    ни то ни другое — во сколько раз короче запас: плёнка узкой кисти толще закона ширины (`_ПОЛ_ПЛЁНКИ`), а запас
    острия шире `_КАПЛЯ_УЗК[10]` px в px хода не растёт."""
    if p is not None:
        return np.sqrt(p / 0.8) if живая <= 0 else (p / 0.8) ** (0.5 + Ч._КАПЛЯ_УЗК[4] * живая)
    if заряд is not None:
        было = np.minimum(заряд * 2.5, 1.0)
        # остаток запаса — против того, с чем гребень начал (`полный`), а не против среднего набора: набор гуляет на ±20 %,
        # и в кубе бедно набранная кисть клала с первого пикселя треть плёнки — след 9–12 px выходил уже названного
        # п. 10 (v3.17): краску к кончику тянет из брюшка, и пока в брюшке больше `_КАПЛЯ_УЗК[13]` набранного, кончик сыт —
        # короткое касание полной кисти (ход в 2–5 ширин) кладёт краску до конца; беднеет длинный ход (куб остатка шёл
        # с первого пикселя: касание в ширину кисти теряло седьмую часть краски, в три ширины — больше трети)
        return было if живая <= 0 else было + живая * (_сыт(W, заряд, полный, брюшком) - было)
    if живая <= 0:
        return 1.0
    # запас острия в px хода не растёт с шириной (`_КАПЛЯ_УЗК[10]`): след 9–12 px тоньшает к концу хода, как след 3 px,
    # а не держит плёнку до кончика (по сухому читался наклейкой)
    Wо = min(W, Ч._КАПЛЯ_УЗК[10])
    return 1.0 - живая * (1.0 - min(Wо / Ч._ПОЛ_ПЛЁНКИ, 1.0) ** Ч._КАПЛЯ_УЗК[6] * (Wо / W) ** 0.5)


def _пряди_красок(краски, раскладка, с, Nc, шаг_к, rng, W):
    """П. 10: несколько красок на узкой кисти с острым концом (след до 12 px). Ворс собран в остриё, и краски лежат на
    нём не полосами по линейке, а прядями: граница двух красок идёт по ворсу и гуляет вдоль хода на `_ТРИ_УЗК[0]` ширины
    (σ; длина волны `_ТРИ_УЗК[1]` ширин, не короче `_ТРИ_УЗК[2]` px) — полоса то шире, то уже, местами сходит на нет, и
    соседние краски встречаются. Гребень, через который идёт граница, несёт обе краски по доле своей ширины.
    Ответ: доли красок на гребнях (Nc, nr, n), в сумме 1; порядок красок поперёк кисти — как у `_раскладка`."""
    n = len(краски)
    доли = np.array([д for _, д in краски])
    порядок = rng.permutation(n) if раскладка == 'полосы' else np.arange(n)[::-1]
    Т = Ч._ТРИ_УЗК
    границы = np.cumsum(доли[порядок])[:-1][None, :] + Т[0] * _шум(rng, Nc, n - 1, max(Т[1] * W, Т[2]) / шаг_к) \
        + Т[3] * rng.standard_normal(n - 1)[None, :]
    границы = np.sort(зажать(границы, 0.0, 1.0), axis=1)
    края = np.concatenate([np.zeros((Nc, 1)), границы, np.ones((Nc, 1))], axis=1)            # (Nc, n + 1)
    лев, прав = (с.центр - с.полуш) / W + 0.5, (с.центр + с.полуш) / W + 0.5
    общее = зажать(np.minimum(прав[None, :, None], края[:, None, 1:]) - np.maximum(лев[None, :, None], края[:, None, :-1]), 0.0, None)
    вес = np.zeros((Nc, с.nr, n))
    вес[:, :, порядок] = общее / np.maximum(общее.sum(axis=2, keepdims=True), 1e-9)
    return вес


def _узкий_набор(rng, краски, мастихин, W, раскладка, густо, остр=1.0):
    """П. 10: свой поток случая узкой кисти (пряди, щель, краски; прежние потоки не сдвигаются) и узкий ли это набор —
    несколько красок на кисти с острым концом (до 12 px): та же узкая кисть, что в одну краску (форма следа, капля,
    запас, щель), краски лежат прядями ворса (`_пряди_красок`). Только тонкая краска (густо = 0): густой набор, и у узкой
    кисти, — как был (п. 2в–2д: его держит `test_узкая_кисть_и_боковые_полосы`), как и набор широкой кисти."""
    return (np.random.default_rng(np.random.SeedSequence(rng.bit_generator.seed_seq.entropy, spawn_key=(41,))),
            len(краски) > 1 and not мастихин and густо <= 0.0 and _острая(W, остр) >= 1.0 and раскладка in ('полосы', 'ряд'))


def _пряди_узкой(с, уход, живая, rng, N, W, ds, круглая):
    """П. 10: ворс узкой кисти собран в остриё — прядь от пряди на весь ход не отходит (шум в 260 px на ходе в сотню —
    постоянный сдвиг до 1,5 px: у следа 9 px выходила щель-рельса на весь ход и нахлёст с другой стороны); пряди
    расходятся и сходятся на длине в 2–4 ширины, на доли пикселя. У круглой — и ноша брюшка (`_ноша_брюшка`, в `с.нагр`).
    Ответ — уход прядей вбок (N, ns)."""
    if живая <= 0:
        return уход
    if круглая:
        с.нагр = _ноша_брюшка(с, W, живая)
    Щ = Ч._ЩЕЛЬ_УЗК
    return уход * (1.0 - живая) + живая * Щ[5] * _шум(rng, N, с.ns, 0.5 * (Щ[0] + Щ[1]) * max(W, Щ[2]) / ds)


def _делят_каплю(кс_капли, k, шаг_к, W, пройдено):
    """П. 10, узкий набор: соседние гребни делятся каплей на кончике — краски местами смешиваются (на месте).
    Мешает их ход: севшая кисть несёт краски, как набрала, пряди трутся друг о друга, когда их потащило, — в полную
    силу к `_ТРИ_УЗК[5]` ширинам пути от касания (v3.17: короткое светлое касание в 2–3 краски тускнело с первой
    ширины хода — светлая прядь делилась с тёмной соседкой, ещё не сдвинувшись)."""
    d = (кс_капли[1:] - кс_капли[:-1]) * ((Ч._ТРИ_УЗК[4] * шаг_к / W) * float(зажать(пройдено / (Ч._ТРИ_УЗК[5] * W), 0.0, 1.0))
                                          * np.minimum(k[:-1], k[1:])[:, None])
    кс_капли[:-1] += d
    кс_капли[1:] -= d


def _обойма(рвёт, заряд, ёмкость, шаг):
    """v3.23: заряд гребней после шага переноса — у полупустой кисти краска запаса расходится по соседям (`зерно.Рвёт.делят`)."""
    return заряд if рвёт is None else рвёт.делят(заряд, ёмкость, шаг)


def _сухая(к, нагрузка):
    """П. 10, инструмент 2: кисть набрана полупустой — нагрузка 'сухая' (не мастихин)."""
    return (к.нагрузка if нагрузка is None else нагрузка) == 'сухая' and к.форма != 'мастихин'


class _Срыв:
    """П. 17, поле мазка `запас` (в журнале "reserve"): сухой срыв. Кисть набрана скупо — краски в ворсе на `запас` ширин
    кисти хода, и кончик кормится из ворса в меру того, что в нём осталось (у полной кисти кончик сыт, пока в запасе
    есть четверть набранного, а запаса хватает на десяток ширин: на ходе в 3–5 ширин он не кончается). Капля на кончике
    тоньшает вдоль всего хода; гребень кладёт, пока капля выше порога, — порог у каждого волоска свой: бугорок лежащей
    краски и зерна холста ближе, ложбина дальше, на богатой прядке краски больше (`зерно.по_зерну`). Начало хода
    плотное, дальше след рвётся на острова вдоль хода, к концу они реже и уже. Что легло, то из запаса убыло: рваный
    след тратит краску медленнее сплошного, хвост хода длинный."""
    __slots__ = ('ширин',)

    def __init__(self, ширин):
        self.ширин = float(ширин)

    def заряд(self, rng, nr):
        """Заряд гребней (nr,): набрано, сколько сказано, — от мазка к мазку кисть целиком не гуляет."""
        z = np.exp(0.10 * rng.standard_normal(nr))
        return Ч._СРЫВ[0] * z / z.mean()

    def запас(self, с, W):
        """На сколько px хода хватает единицы заряда гребня (nr,): от пряди к пряди запас ходит, в сумме по кисти — один."""
        з = np.sqrt(с.запас)
        return self.ширин * Ч._СРЫВ[2] * W * з / np.average(з, weights=с.полуш)

    @staticmethod
    def ровнее(неровн, полуш):
        """Запас гребней вдоль хода (Nc, nr): краски в кисти набрано, сколько сказано, — гребни богаче и беднее вокруг
        среднего по кисти, вся кисть разом от места к месту не богатеет и не беднеет."""
        return неровн + 1.0 - (неровн * полуш).sum(axis=1, keepdims=True) / полуш.sum()

    @staticmethod
    def делят(заряд, ёмкость, шаг):
        """Ворс в одной обойме: краска запаса расходится по соседним гребням (доля `_СРЫВ[9]` разницы на px пути) — кисть
        пустеет вся, а не гребень за гребнем рельсами; сумма заряд·ёмкость не меняется."""
        if len(заряд) < 2:
            return заряд
        поток = min(Ч._СРЫВ[9] * шаг, 0.33) * (заряд[:-1] - заряд[1:]) * np.minimum(ёмкость[:-1], ёмкость[1:])
        краска = заряд * ёмкость
        краска[:-1] -= поток
        краска[1:] += поток
        return краска / ёмкость

    @staticmethod
    def капли(капля, кс_капли, полная, шаг):
        """Краска на кончиках тоже общая: с бедной прядки, которая до холста не достаёт, она переходит на соседние
        кончики, что кладут (доля `_СРЫВ[12]` разницы на px пути), и несёт свой цвет. Иначе краска бедных прядок
        остаётся на кисти, а богатые пустеют — след гаснет разом. Ответ: капля и её краска (nr,), (nr, 24)."""
        if len(капля) < 2:
            return капля, кс_капли
        поток = min(Ч._СРЫВ[12] * шаг, 0.33) * (капля[:-1] / полная[:-1] - капля[1:] / полная[1:]) * np.minimum(полная[:-1], полная[1:])
        вправо, влево = np.maximum(поток, 0.0), np.maximum(-поток, 0.0)
        новая = капля.copy()
        новая[:-1] += влево - вправо
        новая[1:] += вправо - влево
        кс = кс_капли * (капля - np.append(вправо, 0.0) - np.insert(влево, 0, 0.0))[:, None]
        кс[1:] += кс_капли[:-1] * вправо[:, None]
        кс[:-1] += кс_капли[1:] * влево[:, None]
        return новая, np.where((новая > 1e-12)[:, None], кс / np.maximum(новая, 1e-12)[:, None], кс_капли)

    @staticmethod
    def подаёт(остаток, доля_капли):
        """Сколько своей краски идёт из ворса на кончик (nr,): в меру остатка запаса; полный кончик не переливается."""
        return зажать(остаток, 0.0, 1.0) ** Ч._СРЫВ[1] * зажать(2.2 - 1.2 * доля_капли, 0.0, 1.0)


def _срыв(запас, нет):
    """П. 17: `_Срыв` или None (поля нет; мастихин, вытертая и полупустая кисть — как были)."""
    if запас is None or нет:
        return None
    if not float(запас) > 0.0:
        raise ValueError('запас: больше нуля — на сколько ширин кисти хватает краски')
    return _Срыв(запас)


def _ось_подъёма(с, слита):
    """П. 16: место, от которого идёт порог касания гребня у кисти на ребре. У щетины это ось пряди: прядь отходит от
    холста разом, и бок сходящего следа идёт уступами в ширину пряди (6–10 px). Текучая краска (поле `ровно`) заливает
    ворс и слепляет пряди в одну обойму: гребни отходят по одному, по своему месту, — бок клина плавный. `слита` — 0–1:
    доля текучести у хода на ребре; 0 — как было (тот же массив)."""
    return с.ось_пряди[с.прядь] + (с.центр - с.ось_пряди[с.прядь]) * слита if слита > 0 else с.ось_пряди[с.прядь]


def _встал(к, мастихин, плашмя, скор):
    """П. 16: плоская кисть на ребре, которую остановили. Пряди отстают вдоль хода, пока их тащат (трение у каждой
    своё); рука тормозит и встаёт — ворс выпрямляется, кончики сходятся к линии кисти, и кисть отрывается разом:
    конец следа — торец той ширины, что касалась, а не хвост прядей на 20–30 px. Остановлена ли кисть — по скорости
    руки в конце хода (`_ТОРЕЦ[0]`: так кончается только «остановка»; подъём, отрыв, смахивание идут быстрее);
    выпрямляется ворс на всём тормозном пути, а не в последних пикселях: кончик, догоняющий кисть рывком, рвал бы след.
    Плашмя пряди держит обойма (`_ОБОЙМА`) — там как было. Ответ — множитель отставания прядей (N,) или 1.0."""
    if мастихин or к.форма != 'плоская' or плашмя >= 1.0 or скор[-1] >= Ч._ТОРЕЦ[0]:
        return 1.0
    z = зажать((Ч._ТОРЕЦ[1] - скор) / (Ч._ТОРЕЦ[1] - Ч._ТОРЕЦ[2]), 0.0, 1.0) * (np.arange(len(скор)) >= int(np.argmax(скор)))
    return 1.0 - Ч._ТОРЕЦ[3] * (1.0 - плашмя) * z * z * (3.0 - 2.0 * z)


def _уходит(p, доля, быстро):
    """Насколько руку поднимают (N,), 0…1: после наибольшего нажима, когда нажим упал ниже `_КОНЦЫ[5]` набранного
    (тело хода дышит нажимом на десятую — это не подъём); сорванная кисть (`быстро`) не поднята."""
    return (np.arange(len(p)) > int(np.argmax(p))) * зажать((Ч._КОНЦЫ[5] - доля) / Ч._КОНЦЫ[6], 0.0, 1.0) * (1.0 - быстро)


def _тает(с, сходит, поднята, сходит_рука, зап, p_р, кас, густо):
    """П. 18б: хвост хода, с которого рука сходит. Гребень — пучок волосков разной длины. Пока рука снимает нажим
    (`сходит_рука`), они отходят от холста не разом, а по одному, на `_ХВОСТ[0]` нажима от первого до последнего:
    гребень кладёт краску всё уже (касается доля волосков) и всё тоньше (слабо прижатый волосок отдаёт меньше,
    `_ХВОСТ[2]`) — прядь кончается нитью, а не торцом. Самые длинные волоски распрямляются вслед за рукой: их порог
    касания (и добавка крайних волосков пряди, `_сходит`) идёт к нулю вместе с нажимом (`поднята`, степень
    `_ХВОСТ[1]`), и последний держится, пока рука не сняла нажим совсем, — след доходит до конца нажима, а не
    обрывается на пороге. Дальние гребни отходят как раньше: кисть собирается к кончику. Плёнка сходит на нет у
    каждого гребня в своём месте, по его порогу; случайных чисел нет. Вне схода руки — всё как было, бит в бит.
    Ответ: касание гребней (N, nr); сход (N, nr) — доля волосков гребня на холсте, ею сужается его след; сколько
    краски отдаёт волосок против тела (N, nr); где хвост (N, 1)."""
    u, v = поднята[:, None], сходит_рука[:, None]
    к_нулю = (1.0 - u) ** Ч._ХВОСТ[1]
    выше = p_р[:, None] - зап - 0.04                                      # порог гребня сверх самого длинного (у него 0,04): кисть собирается к кончику как раньше
    доля_в = зажать((p_р[:, None] - выше - (0.04 + сходит[0]) * к_нулю) / ((_МЯГКОСТЬ + Ч._ХВОСТ[0] * v) * к_нулю + 1e-9), 0.0, 1.0)
    u = v                                                                 # хвост — весь сход руки
    стало = доля_в * доля_в * (3.0 - 2.0 * доля_в)
    кас_х = np.where(u > 0, np.maximum(кас, стало), кас)
    полон = np.maximum(кас_х ** (1.0 - 0.75 * густо), 1e-6)              # так гребень заполнен в теле (`заполнен`)
    # след гребня уже одной выборки профиля не бывает: нить тоньше неё кладёт краски во столько же раз меньше, а не пропадает
    нить = np.full(с.nr, np.inf); np.minimum.at(нить, с.гребень, с.x); нить = зажать((нить + 0.1) / 1.2, 0.0, 1.0)[None, :]
    return кас_х, np.minimum(np.where(стало > 0, np.maximum(стало, нить), 0.0) / полон, 1.0), np.where(u > 0, (1.0 - u * (1.0 - доля_в ** Ч._ХВОСТ[2])) * np.minimum(стало / нить, 1.0), 1.0), u > 0


def _сходит(к, с, мастихин, чистая, W, p, доля, быстро, слита, остр):
    """П. 18: как прядь уходит с холста, когда руку поднимают. Прядь — пучок: его крайние волоски отходят первыми, и
    след пряди сужается к её оси и сходит на нет, а не обрублен поперёк во всю прядь (лесенка сходящего хода). Последние,
    самые длинные волоски касаются холста, пока рука не сняла нажим совсем: порог и ширина перехода касания идут к нулю
    вместе с нажимом. Кисть ставят так же: прядь касается сначала осью и раскрывается, пока рука набирает нажим.
    Сорванная кисть (`быстро`) и текучая краска, слепившая пряди (`слита`), — как было. Ответ: (добавка к порогу
    (N, nr), пол порога (N,), мягкость (N,)) или None — не щетина плоской кисти, кисть уже `_ОСТРАЯ[0]` px, вытертая; не зовётся
    для мягкой кисти и не кроющей краски (она оплывает сама) — их концы как были."""
    if мастихин or чистая or к.форма != 'плоская' or W < Ч._ОСТРАЯ[0]:
        return None
    сила = 1.0 - слита
    if сила <= 0:
        return None
    N = len(p)
    уходит = _уходит(p, доля, быстро) * сила
    лев = np.full(с.ns, np.inf); прав = np.full(с.ns, -np.inf)
    np.minimum.at(лев, с.прядь, с.центр - с.полуш); np.maximum.at(прав, с.прядь, с.центр + с.полуш)
    от_оси = зажать(np.abs(с.центр - с.ось_пряди[с.прядь]) / np.maximum(0.5 * (прав - лев)[с.прядь], 0.5), 0.0, 1.0)
    z = 1.0 - уходит * (1.0 - зажать(доля / Ч._КОНЦЫ[1], 0.0, 1.0))
    набрал = int(np.argmax(p >= Ч._КОНЦЫ[4] * float(p.max())))
    входит = зажать(1.0 - p / (Ч._КОНЦЫ[4] * float(p.max())), 0.0, 1.0) * (np.arange(N) <= набрал) * сила
    return Ч._КОНЦЫ[0] * от_оси[None, :] * np.maximum(уходит, входит)[:, None], Ч._КОНЦЫ[2] + (1.0 - Ч._КОНЦЫ[2]) * z, Ч._КОНЦЫ[3] + (1.0 - Ч._КОНЦЫ[3]) * z


def _концы(к, с, s, p, зап, запас_г, лежит, W, густо, плашмя, скор, доля, быстро, слита, мастихин, чистая, сид, ровно=0.0):
    """П. 18: концы следа множителем укладки. Сколько краски кисть отдала и что у неё осталось, считается как раньше
    (тело хода не меняется); здесь — только где у концов хода волосок лежит на холсте: сход прядей (`_сходит`: по
    запасу нажима `зап` гребня на ребре; плашмя пряди держит обойма, и ход сходит как раньше — углами) и пятно
    касания (`_пятно`).
    Ответ: сход прядей по гребням (N, nr) — он сужает след гребня к его оси (гребень сходит остриём, а не гаснет во
    всю ширину); концы пятна (их кладёт `_лёг`); насколько кисть остановлена под нажимом. (None, None, 0.0) — как были."""
    сходит = _сходит(к, с, мастихин, чистая, W, p, доля, быстро, слита, None)
    if сходит is None:
        if слита >= 1.0 and _сходит(к, с, мастихин, чистая, W, p, доля, быстро, 0.0, None) is not None:
            # Д1, строка 6 (долг 16): текучая краска слепила пряди на ребре — врозь они не сходят, но прижатый ворс
            # лежит пятном касания, как и при `слита` чуть меньше 1: конец — пятно (овал по нажиму гребней), а не обрез пути
            return (np.ones((len(p), с.nr)),) + _пятно(с, s, p, запас_г, W, густо, плашмя, скор, слита / max(1.0 - плашмя, 1e-6) if плашмя < 1.0 else 0.0, ровно)
        return None, None, 0.0
    было, стало = зажать(зап / _МЯГКОСТЬ, 0.0, 1.0), зажать((зап + 0.04 * (1.0 - сходит[1][:, None]) - сходит[0]) / (_МЯГКОСТЬ * сходит[2][:, None]), 0.0, 1.0)
    было, стало = было * было * (3.0 - 2.0 * было), стало * стало * (3.0 - 2.0 * стало)
    доля_к = np.where(было > 1e-6, np.minimum(стало / np.maximum(было, 1e-6), 1.0), 1.0)
    return (1.0 + (доля_к - 1.0) * (1.0 - плашмя) * (1.0 - лежит[:, None]),) + _пятно(с, s, p, запас_г, W, густо, плашмя, скор, слита / max(1.0 - плашмя, 1e-6) if плашмя < 1.0 else 0.0, ровно)


def _хвост(к, с, p, p_р, зап, лежит, W, густо, плашмя, скор, доля, быстро, слита, мастихин, чистая, сухая, сход_г, кас, держит=None):
    """П. 18б: хвост сходящего хода поверх концов п. 18 (`_тает`). Хвост тянется, пока кисть идёт: вставшую кисть
    (`_ТОРЕЦ`) поднимают на месте, её конец — пятно и торец, как были; сорванная, текучая, узкая с острым кончиком
    (п. 10) и сухая (п. 17: у неё хвост кладёт волосок) — как были. Хвост на ребре идёт долей `1 − плашмя`; у кисти плашмя (п. 18в,
    `держит` — `_держит`) хвост — утоньшением плёнки (`_Плёнка`): гребни лежат до конца нажима. Ответ: сход прядей (N, nr), касание на укладке
    (N, nr), `_Плёнка` — сколько краски отдаёт волосок — или None."""
    сходит = None if сход_г is None or сухая else _сходит(к, с, мастихин, чистая, W, p, доля, быстро, слита, None)
    сила = 1.0 - _острая(W, к.остриё)
    if сходит is None or сила <= 0:
        return сход_г, кас, None
    if держит is not None:
        кас = _Плёнка.касание(с, p, кас, держит)
    идёт = (np.arange(len(p)) > int(np.argmax(p))) * зажать((скор - Ч._ТОРЕЦ[2]) / (2.0 * Ч._ТОРЕЦ[0] - Ч._ТОРЕЦ[2]), 0.0, 1.0) * (1.0 - быстро) * (1.0 - слита) * (1.0 - лежит) * сила * (1.0 - плашмя)
    кас_х, тает, тонко, хвост = _тает(с, сходит, идёт * (1.0 - зажать(доля / Ч._КОНЦЫ[5], 0.0, 1.0)), идёт * зажать((Ч._ХВОСТ[3] - доля) / Ч._ХВОСТ[4], 0.0, 1.0), зап, p_р, кас, густо)
    return np.where(хвост, тает, сход_г), кас_х, _Плёнка(тонко, держит, доля, густо)


def _расп(к, p, сорвана, лежит, брюшко, сход_о, держит=None):
    """Ширина следа в долях ширины кисти (N,): при обычном нажиме 0,85 след — в ширину кисти; придавленная кисть
    расходится веером шире; на слабом нажиме ворс собирается к оси (сорванная кисть отходит плашмя). П. 18в, `держит`
    (`_держит`): пока рука сходит с кисти плашмя на ходу, обойма держит ворс в ширину — к оси он не собирается и на
    кончик кисть не встаёт."""
    сбор = np.maximum(зажать(p / 0.15, 0.0, 1.0), сорвана)
    if держит is not None:
        сбор, лежит = np.maximum(сбор, держит * Ч._ПЛЁНКА[9]), np.maximum(лежит, держит * Ч._ПЛЁНКА[9])
    распл = к.распластывание + max(_ПЛАШМЯ - к.распластывание, 0.0) * лежит
    return (распл + (1.0 - распл) * (брюшко / 0.85) ** 0.6 * (1.0 + 0.9 * зажать(p - 0.85, 0.0, 0.15))) * (0.3 + 0.7 * сбор * сбор * (3.0 - 2.0 * сбор)) * сход_о


def _держит(к, p, W, плашмя, скор, доля, сорвана, ровно, нет):
    """П. 18в: насколько рука сходит с кисти, лежащей плашмя (N,), 0…1, или None — хвоста плашмя нет. Рука снимает
    нажим на ходу (ниже `_ПЛЁНКА[0]` набранного, в полную силу — ещё на `_ПЛЁНКА[1]` ниже): обойма идёт над холстом
    как шла, ворс распрямляется вслед за рукой, и гребни остаются на холсте всей шириной, пока нажим не снят совсем, —
    кисть не встаёт на кончик и не сужает след углами (`пряди._посадка`), она кладёт всё более тонкую плёнку
    (`_Плёнка`). Вставшая (`_ТОРЕЦ`), сорванная, текучая (`ровно`), узкая с острым кончиком, а с `нет` — мастихин,
    вытертая, сухая, скупо набранная, мягкая и не кроющая — как были."""
    if нет or плашмя <= 0 or ровно > 0 or к.форма != 'плоская' or W < Ч._ОСТРАЯ[0] or _острая(W, к.остриё) >= 1.0:
        return None
    сход = np.arange(len(p)) > int(np.argmax(p))
    # п. 18г: сорванная и смахнутая кисть хвоста плашмя не кладёт вовсе — ворс за рукой распрямиться не успевает. Жест
    # один на весь сход: нажим сорван хоть где-то (`сорвана` — срыв до доли густоты) или рука на сходе ускоряется
    # против хода тела (`_ПЛЁНКА[13]`, целиком — ещё на `[14]`), — кисть отходит, как отходила без хвоста
    тело = скор[доля >= 0.97]
    разгон = зажать((float(скор[сход].max(initial=0.0)) / max(float(np.median(тело)) if len(тело) else 1.0, 1e-6) - Ч._ПЛЁНКА[13]) / Ч._ПЛЁНКА[14], 0.0, 1.0)
    сила = (1.0 - float(сорвана[сход].max(initial=0.0))) * (1.0 - разгон * разгон * (3.0 - 2.0 * разгон))
    идёт = сход * зажать((скор - Ч._ТОРЕЦ[2]) / (2.0 * Ч._ТОРЕЦ[0] - Ч._ТОРЕЦ[2]), 0.0, 1.0) * сила * (1.0 - _острая(W, к.остриё)) * плашмя
    z = зажать((Ч._ПЛЁНКА[0] - доля) / Ч._ПЛЁНКА[1], 0.0, 1.0)
    return идёт * z * z * (3.0 - 2.0 * z) if идёт.any() else None


class _Плёнка:
    """П. 18в: хвост кисти плашмя — утоньшением плёнки, а не сужением пряди. Пока рука сходит (`_держит`), гребень лежит
    на холсте, но прижат всё слабее и краски отдаёт всё меньше. П. 18д: плёнка сначала тоньшает и светлеет, до грунта
    сходит только у конца и там, где на волоске краски нет (`тоньше`): толщина идёт к нулю плавно, без порога. Неровность —
    от запаса гребня (`борозда.неровный_запас`) и рельефа под кистью; по зерну холста её рвёт ещё и `зерно.по_зерну`.
    Гребень к оси не стягивается. Случайных чисел здесь нет. `ребро` — что отдаёт волосок в хвосте на ребре (`_тает`) или None."""
    __slots__ = ('ребро', 'держит', 'нажим', 'степень', 'мягко')

    def __init__(self, ребро, держит, доля, густо):
        self.ребро, self.держит = ребро, держит
        self.нажим = None if держит is None else зажать(доля / Ч._ПЛЁНКА[0], 0.0, 1.0)       # нажим в долях того, с которого рука сходит
        self.степень = Ч._ПЛЁНКА[2] + (Ч._ПЛЁНКА[17] - Ч._ПЛЁНКА[2]) * _Плёнка.густая(густо)   # слабо прижатый волосок оставляет мазню одной толщины, сколько бы краски ни нёс: густая плёнка тоньшает против своего тела круче
        self.мягко = Ч._ПЛЁНКА[5] + (Ч._ПЛЁНКА[18] - Ч._ПЛЁНКА[5]) * _Плёнка.густая(густо)       # густая плёнка до грунта почти не рвётся: в бедном месте она тоньше и светлее

    @staticmethod
    def густая(густо):
        """Насколько краска держит ворс обоймой и в хвосте (0…1): в полную меру — пастозная, до густоты `_ПЛЁНКА[12]`
        (нагрузка около 0,6) — нет: её пряди собираются к своим осям, а плёнка тоньшает только у конца нажима."""
        return float(зажать((густо - Ч._ПЛЁНКА[12]) / (1.0 - Ч._ПЛЁНКА[12]), 0.0, 1.0))

    @staticmethod
    def касание(с, p, кас, держит):
        """Касание гребней на укладке (N, nr): пока рука сходит, гребень лежит, как лежал плашмя, — отходит по своей
        длине (`_ДЛИНЫ_ПЛАШМЯ`), когда нажим снят почти совсем."""
        порог = с.порог * _ДЛИНЫ_ПЛАШМЯ
        z = зажать((p[:, None] - (порог - порог.min())[None, :] * Ч._ПЛЁНКА[6] - Ч._ПЛЁНКА[7]) / Ч._ПЛЁНКА[8], 0.0, 1.0)
        return кас + (np.maximum(z * z * (3.0 - 2.0 * z), кас) - кас) * держит[:, None]

    @staticmethod
    def пряди(липн, держит):
        """Сбор прядей к своим осям (N, ns): густая краска держит пряди вместе — пока рука сходит, прядь в язык не
        стягивается (`держит` — с долей густоты: тонкая краска пряди не держит, они собираются, как раньше)."""
        return 1.0 - (1.0 - липн) * (1.0 - Ч._ПЛЁНКА[10] * держит)[:, None]

    def тоньше(self, с, неровн, густота, i0, i1, f0, f1, шаг_к, под):
        """Множитель толщины плёнки по выборкам профиля (N, nm) или 1.0. П. 18д: толщина = нажим^`степень` · z^`_ПЛЁНКА[11]`,
        z = (запас волоска − уровень) / `мягко` + 1 в пределах 0…1. Уровень растёт со снятым нажимом — `_ПЛЁНКА[4]`·снято^`[3]` — и с
        путём, пройденным на сходящем нажиме (в полную силу — за `[19]` ширин кисти: кончик ворса отдаёт свою краску не разом;
        быстро снятая кисть плёнку порвать не успевает). Пока уровень ниже запаса на `мягко`, плёнка цела; дальше она
        тоньшает (степень `[11]`: широкая полоса тонкой светлой плёнки) и только при z = 0 сходит до грунта — кромка мягкая.
        Запас — по месту волоска между осями соседних гребней, мелкая неровность (против среднего на ширину кисти вдоль
        хода) весит в `[15]` раз больше: пятна идут и поперёк хода, и вдоль. `под(ж)` — рельеф лежащей краски под выборкой (в
        толщинах плёнки) или None (зерно холста и рельеф по волоску у сухой кисти и с полем "ridges" считает
        `зерно.по_зерну`), вес `[16]` растёт со снятым нажимом."""
        г, W = с.гребень, с.W
        m = 1.0 if self.ребро is None else self.ребро[:, г]
        if self.держит is None:
            return m
        ж = np.nonzero(self.держит > 0)[0]
        if not len(ж):
            return m
        v, t = self.держит[ж, None], self.нажим[ж, None]
        снято = 1.0 - t
        q = неровн * густота
        n = max(int(round(W / шаг_к)), 2)
        сум = np.cumsum(обложить(q, ((n // 2 + 1, n - n // 2 - 1), (0, 0)), край=True), axis=0)
        q = q + Ч._ПЛЁНКА[15] * (q - (сум[n:] - сум[:-n]) / n)                        # запас гребня в этом месте хода (Nc, nr)
        q = q[i0[ж]] * f0[ж] + q[i1[ж]] * f1[ж]
        # комок краски лежит на волосках гребня и его соседа: между осями гребней запас — по месту волоска
        j = зажать(np.searchsorted(с.центр, с.u) - 1, 0, с.nr - 2)
        w = зажать((с.u - с.центр[j]) / np.maximum(с.центр[j + 1] - с.центр[j], 1e-6), 0.0, 1.0)
        q = q[:, j] * (1.0 - w) + q[:, j + 1] * w
        if под is not None:
            q = q + Ч._ПЛЁНКА[16] * снято * под(ж)
        путь = (i0[ж] + f1[ж].reshape(-1)) * шаг_к
        z = зажать((q - Ч._ПЛЁНКА[4] * снято ** Ч._ПЛЁНКА[3] * зажать((путь - путь[0]) / (W * Ч._ПЛЁНКА[19]), 0.0, 1.0)[:, None]) / self.мягко + 1.0, 0.0, 1.0)
        тонко = np.ones((len(self.держит), len(г)))
        тонко[ж] = 1.0 - v * (1.0 - t ** self.степень * (z * z * z if Ч._ПЛЁНКА[11] == 3.0 else z ** Ч._ПЛЁНКА[11]))   # куб — умножением: степень с дробным показателем втрое дольше
        return m * тонко


def _дошла(встала, плашмя, скор):
    """П. 18: кисть плашмя, которую остановили под нажимом, доходит до последней точки пути. Пока кисть тащат, ворс
    согнут назад и кончики отстают от обоймы; рука тормозит и давит — согнутый ворс ложится на холст всей длиной от
    кончика до обоймы, и след кончается там, где встала кисть, а не там, куда дотянулись отставшие кончики.
    Поднятая и сорванная кисть ворса не кладёт (`встала` = 0) — её конец как был; на ребре то же делает `_встал`.
    Ответ — множитель отставания прядей (N,) или 1.0."""
    if встала <= 0 or плашмя <= 0:
        return 1.0
    z = зажать((Ч._ТОРЕЦ[1] - скор) / (Ч._ТОРЕЦ[1] - Ч._ТОРЕЦ[2]), 0.0, 1.0) * (np.arange(len(скор)) >= int(np.argmax(скор)))
    return 1.0 - Ч._ТОРЕЦ[3] * встала * плашмя * z * z * (3.0 - 2.0 * z)


def _ранг(a):
    """Место числа в своём ряду от −1 (наибольшее) до 1 (наименьшее); ряд из равных чисел — нули."""
    if len(a) < 2 or float(np.ptp(a)) <= 0:
        return np.zeros(len(a))
    return 1.0 - 2.0 * np.argsort(np.argsort(a, kind='stable'), kind='stable') / (len(a) - 1.0)


def _пряди_пятна(с, густо, плашмя, слита, ровно=0.0):
    """П. 18а: чем пряди в пятне касания разнятся. Случайных чисел здесь нет — всё из того, чем кисть уже набрана:
    прядь с меньшим порогом касания длиннее и ложится дальше, гребень внутри пряди — по своему порогу; у полупустой
    кисти гребень ещё и лежит по своему отставанию в пряди (на посадке и на остановке — в разные стороны). Гружёную
    кисть плашмя краска заливает, и кромка ровная; на ребре кончики прядей краску держат врозь, и в кромке посадки
    пряди читаются (`_ПЯТНО[15]`); текучая краска (`слита`) пряди слепляет. Ответ: множители избытка нажима гребня — посадка (nr,), остановка (nr,); у остановки гружёной кисти — сила, с которой пряди лежат врозь (`_ПЯТНО[16]`), и ранг пряди (nr,)."""
    ср = np.bincount(с.прядь, weights=с.порог, minlength=с.ns) / np.maximum(np.bincount(с.прядь, minlength=с.ns), 1)
    прядь, гребень = _ранг(ср)[с.прядь], 0.5 * _ранг(с.порог - ср[с.прядь])
    свой = _ранг(с.отст_гр)
    сух = 1.0 - Ч._ПЯТНО[6] * густо
    сел = 1.0 - Ч._ПЯТНО[6] * густо * (1.0 - Ч._ПЯТНО[15] * (1.0 - плашмя * плашмя) * (1.0 - слита) ** 2)
    # Д1, строка 5: и остановленная гружёная кисть держит пряди врозь — кромка остановки идёт по прядям, а не ровным
    # овалом, который растр режет равными ступенями: прядь длиннее ложится дальше овала, короче — ближе (на сколько —
    # `врозь` на ранг пряди; середину отсчёта ставит `_пятно`: площадь пятна та же); текучая краска (`ровно`) пряди слепляет и плашмя
    врозь = Ч._ПЯТНО[4] * Ч._ПЯТНО[6] * густо * Ч._ПЯТНО[16] * (1.0 - ровно) ** 2
    return (1.0 + Ч._ПЯТНО[4] * (сел * прядь + сух * гребень)) * (1.0 + Ч._ПЯТНО[5] * сух * свой), (1.0 + Ч._ПЯТНО[4] * сух * (прядь + гребень)) * (1.0 - Ч._ПЯТНО[5] * сух * свой), (врозь, прядь)


def _села(s, ia, окно, запас_г, где, отстаёт):
    """П. 18а: откуда меряется пятно посадки, когда рука набирает нажим по ходу. Гребни касаются холста по одному,
    каждый по своему порогу, и позже, чем легла бы кромка пятна от первого коснувшегося волоска: начало следа выходило
    веером прядей, а текучая краска затягивала веер в прямой срез. Кисть села там, где её ворс уже лежит пятном:
    кромка пятна проходит по касанию того гребня, что коснулся позже всех. При быстром входе все касаются сразу, и
    место прежнее. Ответ — место на пути, px."""
    кос = запас_г[окно][:, где] > 0
    позже = (s[окно][np.argmax(кос, axis=0)] - s[ia] - отстаёт[где])[кос.any(axis=0)]
    return float(s[ia]) + (max(float(позже.max()), 0.0) if len(позже) else 0.0)


def _веер(с, s, p, запас_г, ia, окно, pm, сила, прядь):
    """Д1б, строка 3: посадка гружёной кисти ребром — веером по нажиму руки. Кисть, которую ставят, касается
    холста сперва серединой: ком краски на кончиках держит её горкой, и в ширину ворс расходится по мере того, как рука
    дожимает: от первого касания до 85 % набранного нажима — на долю полуширины `(доля пути нажима)^_ПЯТНО[17]`;
    легший ворс лежит.
    Гребень ложится, когда раскрытие дошло до его места на кисти; длинная прядь (меньший порог) — раньше, короткая —
    позже (`_ПЯТНО[18]` на ранг пряди): кромка посадки — веер прядей. Длина посадки — путь, на котором рука набирает
    нажим: удар кладёт кисть разом, медленный набор — длинным языком. Ответ: на сколько px отстаёт гребень (nr,)
    от первой точки касания."""
    r = p[окно] / max(pm, 1e-6)
    ш = np.maximum.accumulate(зажать((r - r[ia]) / max(0.85 - r[ia], 1e-6), 0.0, 1.0) ** Ч._ПЯТНО[17])
    нужно = зажать(np.abs(с.центр / с.полуширина) * сила * (1.0 - Ч._ПЯТНО[18] * прядь), 0.0, 1.0)
    i = np.minimum(np.searchsorted(ш, нужно, side='left'), len(ш) - 1)
    кос = запас_г[окно] > 0                                       # и не раньше, чем гребень коснулся по своему порогу
    сам = np.where(кос.any(axis=0), s[окно][np.argmax(кос, axis=0)], s[окно][-1])
    return np.maximum(np.maximum(s[окно][i], сам) - s[ia], 0.0)


def _пятно(с, s, p, запас_г, W, густо, плашмя, скор, слита, ровно=0.0):
    """П. 18: концы следа — пятно касания согнутого ворса, а не обрез пути. Прижатый волосок лежит на холсте не точкой:
    чем больше у гребня нажима сверх порога касания, тем длиннее он лёг вдоль хода (длина — по избытку нажима).
    У середины касания избыток наибольший, к краям сходит на нет (на ребре — купол порогов, плашмя — купол длин ворса
    у углов обоймы): пятно кисти, которую поставили и которую остановили под нажимом, — овал, и концы следа круглые.
    Середина пятна доходит до первой и последней точки пути, края отстают. Гружёную кисть краска заливает, и пятно
    сплошное; у полупустой жёсткой каждая прядь лежит по-своему — край посадки рваный, пальцами прядей
    (`_пряди_пятна`). Поднятая кисть (нажим у конца снят) пятна не оставляет: её конец — сход прядей. Ответ: концы —
    у каждого (0 — посадка, 1 — остановка; место на пути; на сколько px отстаёт кромка у гребня (nr,) и у места на
    кисти (nm,)) — на холст их кладёт `_лёг`; насколько кисть остановлена под нажимом (0…1)."""
    N, nr = запас_г.shape
    есть = np.nonzero((p > 0.02) & (запас_г > 0).any(axis=1))[0]   # концы следа — где ворс коснулся и где отошёл: рука набирает нажим не с первой точки пути
    if not len(есть):
        return [], 0.0
    ia, ib = int(есть[0]), int(есть[-1])
    ход = float(s[ib] - s[ia])
    концы, встала = [], 0.0
    if ход < 2.0:
        return концы, встала
    t = с.центр / с.полуширина
    пряди = _пряди_пятна(с, густо, плашмя, слита, ровно)
    набран = max(float(s[int(np.argmax(p >= 0.85 * float(p.max())))] - s[ia]), 0.0)   # п. 18а: рука набирает нажим по ходу — кисть садится на всей этой длине
    for конец, окно in ((0, s <= s[ia] + min(max(0.5 * W, набран), ход / 3.0)), (1, s >= s[ib] - min(Ч._ПЯТНО[3] * W, ход / 4.0))):
        pm = float(p[окно].max())
        e = запас_г[окно].max(axis=0) - (Ч._ПЯТНО[2] * плашмя + Ч._ПЯТНО[12] * густо * (1.0 - плашмя)) * pm * t * t   # на ребре: ком краски на кончиках гружёной кисти — горкой к середине, углы касаются позже
        где = np.nonzero(e > 0)[0]
        if not len(где):
            continue
        полуш = 0.5 * float((с.центр + с.полуш)[где].max() - (с.центр - с.полуш)[где].min())
        # под нажимом ли кисть у этого конца: поднятая рукой пятна не оставляет, сорванная — оставляет
        if конец == 0:
            # удар: рука набрала нажим на первых трёх пикселях — кисть легла разом, торец плоский (плашка, п. 2д);
            # кисть, которую ставят (вход от `_ПЯТНО[9]` px), садится пятном
            вход = float(s[int(np.argmax(p >= 0.85 * pm))] - s[ia])
            сила = float(зажать((вход - Ч._ПЯТНО[8]) / (Ч._ПЯТНО[9] - Ч._ПЯТНО[8]), 0.0, 1.0))
        else:
            # пятно оставляет кисть, которую остановили под нажимом («остановка»: скорость руки в конце ниже `_ТОРЕЦ[0]`);
            # сорванная кончает обрывом, поднятая и остановленная на излёте нажима (клин, п. 16) — сходом прядей и торцом
            z = float(зажать((pm / max(float(p.max()), 1e-6) - Ч._ПЯТНО[10]) / Ч._ПЯТНО[11], 0.0, 1.0))
            сила = z * z * (3.0 - 2.0 * z) * (скор[-1] < Ч._ТОРЕЦ[0])
        z = float(зажать((pm - Ч._ПЯТНО[13]) / Ч._ПЯТНО[14], 0.0, 1.0))   # лёгкая рука ворса не гнёт: кисть касается кончиками, торец как был (п. 2а)
        if конец == 1: встала = сила * z * z * (3.0 - 2.0 * z)
        дл = min((Ч._ПЯТНО[0] - (Ч._ПЯТНО[0] - Ч._ПЯТНО[1]) * плашмя) * полуш, 0.3 * ход) * сила * z * z * (3.0 - 2.0 * z)
        if дл < 0.5:
            continue
        e = зажать(e * пряди[конец], 0.0, None)
        овал = lambda c=None: дл * (1.0 - зажать(e * (1.0 if c is None else 1.0 + пряди[2][0] * (пряди[2][1] - c)) / max(float(e[где].max()), 1e-6), 0.0, 1.0) ** Ч._ПЯТНО[7])
        отстаёт = ровный = овал()
        if конец == 0 and густо * (1.0 - плашмя) > 0.0:
            отстаёт = ровный = np.maximum(отстаёт, _веер(с, s, p, запас_г, ia, окно, pm, густо * (1.0 - плашмя), пряди[2][1]))
        if конец == 1 and пряди[2][0] > 0.0:
            # Д1, строка 5: пряди врозь вокруг такой середины ранга, при которой площадь пятна та же, что у ровного овала
            # (кромка в среднем там же: краски в конце хода столько же) — делением пополам, без случайных чисел
            lo, hi = 0.0, 1.0
            for _ in range(24):
                c = 0.5 * (lo + hi)
                lo, hi = (c, hi) if float(((овал(c) - ровный) * с.полуш).sum()) < 0.0 else (lo, c)
            отстаёт = овал(0.5 * (lo + hi))
        # гружёную кисть краска заливает между гребнями: кромка пятна идёт по месту на кисти, а не ступенями гребней
        по_месту = lambda о: о[с.гребень] + густо * (np.interp(с.u, с.центр, о) - о[с.гребень])
        концы.append((конец, _села(s, ia, окно, запас_г, где, отстаёт) if конец == 0 else float(s[ib]), отстаёт, по_месту(отстаёт)))
        if отстаёт is not ровный:                                                        # Д1, строка 5: ровный овал той же остановки — по нему меряется краска наплыва (`_вал_конца`): пряди врозь двигают кромку, а краски у пряди столько же
            концы[-1] += (ровный, по_месту(ровный))
    return концы, встала


def _пятном(маска, вых, пятно_м, пятно_м0, s, W):
    """П. 18: пятно касания у концов (`_лёг`) — множителем укладки (N, nm). Д1, строка 5: если кромка остановки идёт
    по прядям (`пятно_м0` — то же пятно ровным овалом), краски у пряди столько же, сколько при овале: прядь, вставшая
    раньше, кладёт своё на более коротком конце гуще, ушедшая дальше — тоньше (в окне конца хода)."""
    if пятно_м is None:
        return маска
    разн = np.nonzero((пятно_м != пятно_м0).any(axis=1))[0] if пятно_м0 is not None else []
    if len(разн):
        ок = s >= s[разн[0]] - Ч._ПЯТНО[3] * W
        было_бы, стало = (вых[ок] * маска[ок] * пятно_м0[ок]).sum(axis=0), (вых[ок] * маска[ок] * пятно_м[ок]).sum(axis=0)
        маска[ок] *= np.where(стало > 0.0, было_бы / np.maximum(стало, 1e-300), 1.0)[None, :]
    return маска * пятно_м


def _по_овалу(наплыв, овалом):
    """Д1, строка 5: краска наплыва по местам на кисти (N, nm) — столько, сколько её при ровном овале остановки
    (`овалом`, (N, nm) или None): пряди врозь двигают кромку, а не убавляют наплыв."""
    return наплыв if овалом is None else наплыв * (овалом.sum(axis=0) / np.maximum(наплыв.sum(axis=0), 1e-300))[None, :] * (наплыв.sum(axis=0) > 0)


def _вдоль(отст_г, тащит, обойма, предел):
    """Насколько кончик гребня лежит впереди кисти вдоль хода (N, nr), px (у отставшей пряди — меньше нуля); густая
    краска у кисти плашмя держит пряди обоймой — не дальше `предел`."""
    вд = отст_г[None, :] * тащит[:, None]
    return вд + (предел * np.tanh(вд / предел) - вд) * обойма if обойма > 0 else вд


def _вдоль_ворса(отст, конч, тащит, обойма, предел):
    """Насколько кончики лежат впереди кисти вдоль ворса (N, len(отст)), px: отставание пряди (`тащит` — (N,), с
    наклоном кисти) и место кончика; густая краска у кисти плашмя держит пряди обоймой — не дальше `предел`."""
    вд = отст[None, :] * тащит[:, None] + конч[None, :]
    if обойма > 0:
        вд = вд + (предел * np.tanh(вд / предел) - вд) * обойма
    return вд


def _впереди(к, с, путь, p, W, плашмя, густо, мастихин, скор):
    """К8б: насколько кончик гребня лежит впереди кисти вдоль хода (N, nr), px, — тем же счётом, что `на_холст` в
    `уложить` (отставание пряди набирается на первой ширине пути от касания), без остановки в конце: посадке нужен
    только вход. Ответ: это и сколько кисть уже тащат (N,), 0…1."""
    коснулась = путь['s'][int(np.argmax(p > 0.02))]
    тащит = (1.0 - np.exp(-np.maximum(путь['s'] - коснулась, 0.0) / W)) * _встал(к, мастихин, плашмя, скор)
    обойма = 0.0 if (мастихин or к.форма == 'круглая') else плашмя * густо
    вдоль_к = 1.0 + 2.0 * np.sin(np.radians(зажать(путь['наклон'], 0, 85)))
    return _вдоль(с.отст + (_ОТСТ_ГР[0] + _ОТСТ_ГР[1] * W) * обойма * с.отст_гр, вдоль_к * тащит, обойма, _ОБОЙМА * W), тащит


def _лёг(концы, с, s, отст_г, тащит, обойма, предел):
    """П. 18: пятно касания (`_пятно`) на холсте. Кончики прядей отстают от кисти вдоль хода (`отст_г`, `тащит`), и
    место гребня на холсте — не место кисти на пути: кромка пятна меряется от первой и последней точки пути по
    холсту, туда, где лёг кончик. Ответ: лежит ли гребень (N, nr) и место на кисти (N, nm); (None, None) — концы как были."""
    if концы is None:
        return None, None
    вд = _вдоль(отст_г, тащит, обойма, предел)
    лежит, лежит_м = np.ones(вд.shape), np.ones((len(s), len(с.u)))
    for конец, s0, отстаёт, по_месту in (q[:4] for q in концы):
        for кому, отст, назад in ((лежит, отстаёт, -вд), (лежит_м, по_месту, -вд[:, с.гребень])):   # вд — вперёд по ходу, у отставшей пряди меньше нуля
            z = зажать((((s - s0)[:, None] - назад) if конец == 0 else ((s0 - s)[:, None] + назад)) / 1.5 - отст[None, :] / 1.5 + 0.5, 0.0, 1.0)
            кому *= z * z * (3.0 - 2.0 * z)
    return лежит, лежит_м


def _наплыв(s, p, скор, W, густо):
    """П. 18: наплыв на остановке. Гружёная кисть гонит перед собой валик краски, выжатой из ворса; когда её
    останавливают (скорость руки в конце хода ниже `_ТОРЕЦ[0]` — так кончается «остановка»), валик остаётся там, где
    кисть встала: на длине `_НАПЛЫВ[1]` ширины у конца краски больше, чем в теле, и лежит она по пятну касания
    (`_пятно`). Валик набран всем ходом, а не кончиком: он не беднеет вместе с каплей. Тонкая краска валика не держит.
    Ответ: сколько толщин полной плёнки ложится сверх следа (N,)."""
    if густо <= 0 or скор[-1] >= Ч._ТОРЕЦ[0]:
        return np.zeros(len(p))
    есть = np.nonzero(p > 0.02)[0]
    z = зажать(1.0 - (s[есть[-1]] - s) / max(min(Ч._НАПЛЫВ[1] * W, 0.35 * float(s[есть[-1]] - s[есть[0]])), 1e-6), 0.0, 1.0)
    return Ч._НАПЛЫВ[0] * густо * z * z * (3.0 - 2.0 * z) * (p > 0.02)


def _замкнуть(кромка, окно, бок):
    """Д1, строка 4: жгут валика — сплошной по наружному краю следа: щель в крайней пряди короче окна (2·`окно` + 1
    шагов пути, `_ВАЛИК[10]` ширины кисти) он перекрывает по её штрихам, а не ныряет в каждую. Кромка «замкнута» вдоль
    хода: самое наружное в окне, потом самое внутреннее в окне; где след сужается надолго (поднятая прядь, скруглённая
    остановка, сход), замкнутая кромка — сама кромка, жгут за след не выходит. `кромка` — номер крайней выборки по
    рядам пути (у ряда без следа — середина кисти), `бок` — 0 или 1."""
    е = кромка * (1 if бок == 0 else -1)                                                  # меньше — наружу
    for f in (np.min, np.max):
        е = f(np.lib.stride_tricks.sliding_window_view(обложить(е, окно, край=True), 2 * окно + 1), axis=1)
    return е * (1.0 if бок == 0 else -1.0)


def _валик_бока(D, с, к, p, расп, Вых, Hг, неровн, i0, i1, f0, f1, ds, W, густо, нет):
    """П. 19: валик по бокам. Прижатая гружёная кисть выдавливает краску из-под ворса к краям; она ложится гребнем у
    кромки следа с обеих сторон: крутой склон наружу, пологий — к телу (п. 19а: вал шириной ~0,12 ширины кисти, вершина у самой кромки). Краска берётся из тела: сколько легло в гребни,
    столько не легло под ворсом (`D` — краска по выборкам профиля, (N, nm); сумма та же). Доля — с густотой и нажимом (`_ВАЛИК[1..2]`: выше 0,6 — там же, где густая кисть кладёт слой тоньше, `слой_от_нажима`; лёгкая рука и сход не выдавливают), у
    пустеющей кисти сходит на нет; тонкая краска (густо = 0) гребня не держит. У каждого бока своя доля — по запасу его
    крайней пряди (`борозда.неровный_запас`); выдавленное ложится не там же, а на длине `_ВАЛИК[3]` ширины хода: гребень
    идёт то выше, то ниже и не по линейке — по кромке следа, какой она легла (поджатая прядь, рваный край, сход).
    Случайных чисел нет. Узкая с острым кончиком, круглая, мастихин, а с `нет` — мягкая, вытертая, сухая, скупо
    набранная, не кроющая и текучая — как были (тот же массив)."""
    В = Ч._ВАЛИК
    сила = 0.0 if нет or к.форма != 'плоская' else густо * (1.0 - _острая(W, к.остриё)) * В[0] * float(зажать((100.0 / W) ** 0.5, 1.0, 1.12))   # выдавливает кромка ворса: у узкой кисти её доля больше (п. 19а: ненамного — тело не тоньше 0,7 прежнего)
    if сила <= 0 or с.nm < 8 or с.nr < 3:
        return D
    полна = зажать(((Вых / Hг[None, :]).mean(axis=1) - В[8]) / В[9], 0.0, 1.0)
    жмёт = зажать((p - В[1]) / В[2], 0.0, 1.2) * (полна[i0] * f0[:, 0] + полна[i1] * f1[:, 0])
    ряд = D.sum(axis=1)
    жив = (ряд > 0) & (жмёт > 0)
    if not жив.any():
        return D
    порог, m = (0.25 * ряд / np.maximum(np.count_nonzero(D, axis=1), 1))[:, None], с.nm // 2                                   # кромка следа — крайняя выборка, где краски не меньше четверти средней по ряду; ищется от своего бока до середины
    кромка = np.argmax(D[:, :m] > порог, axis=1), с.nm - 1 - np.argmax(D[:, :с.nm - m - 1:-1] > порог, axis=1)
    шаг = (W / с.nm) * расп                                                              # px между выборками (N,)
    n = max(int(round(В[3] * W / ds)), 1)
    ядро = np.hanning(n + 2)[1:-1]; ядро = ядро / ядро.sum()
    тело = 0.25 * float(np.median((ряд / np.maximum(np.count_nonzero(D, axis=1), 1))[жив]))               # Д1, строка 4: кромка для замыкания — где краски не меньше четверти средней по телу хода: тающий ряд (скруглённая остановка, сход) наружу её не выносит
    кромка_т, полный = (np.argmax(D[:, :m] > тело, axis=1), с.nm - 1 - np.argmax(D[:, :с.nm - m - 1:-1] > тело, axis=1)), ((D[:, :m] > тело).any(axis=1), (D[:, с.nm - m:] > тело).any(axis=1))
    окно_кр = max(int(round(0.5 * В[10] * W / ds)), 1) if В[10] > 0 else None                                   # Д1, строка 4: полуокно замыкания кромки, в шагах пути
    место, круто, ширь = max(В[5] * W, 1.0), max(В[6] * W, 0.6), max(В[7] * W, 1.0)
    ж = np.nonzero(жив)[0]                                                               # гребень считается только в полосе у кромки: дальше 3 его ширин краски нет
    k = np.arange(-1, min(int(np.ceil((место + 3.0 * ширь) / (0.5 * W / с.nm))) + 2, с.nm))[None, :]   # с запасом на собранный ворс; от хода не зависит
    доля, гребни = np.zeros(len(p)), []
    for бок, гр in ((0, 0), (1, с.nr - 1)):
        запас = неровн[:, гр] / max(float(неровн[:, гр].mean()), 1e-6)
        запас = зажать(запас[i0] * f0[:, 0] + запас[i1] * f1[:, 0], 0.0, 2.0) ** В[4]
        часть = 0.5 * сила * жмёт * запас * жив                                         # доля краски ряда — в этот бок: сколько легло в гребень, столько не легло под ворсом
        доля += часть
        лёг = np.convolve(часть * ряд, ядро)                                            # выдавленное ложится позади, на длине памяти гребня
        лёг, за_концом = лёг[:len(p)][ж], float(лёг[len(p):].sum())
        лёг[-min(len(ж), n):] += за_концом / min(len(ж), n)                             # что кисть не успела оставить, остаётся у конца следа
        # гребень — валик краски вдоль бока: за каждым зубцом рваной кромки он не прыгает, идёт по ней плавно
        е = кромка[бок] if окно_кр is None else _замкнуть(np.where(жив & полный[бок], кромка_т[бок], m if бок == 0 else с.nm - 1 - m), окно_кр, бок)
        кр = (np.convolve(е * жив, ядро, 'same') / np.maximum(np.convolve(жив * 1.0, ядро, 'same'), 1e-9))[ж]
        jj = (np.floor(кр).astype(np.intp)[:, None] + k) if бок == 0 else (np.ceil(кр).astype(np.intp)[:, None] - k)   # выборки от кромки внутрь (ж, K)
        d = ((jj - кр[:, None]) if бок == 0 else (кр[:, None] - jj)) * шаг[ж, None] - место
        годные = (jj >= 0) & (jj < с.nm)
        jj = np.where(годные, jj, 0)
        # за каждым зубцом рваной кромки гребень не прыгает; с `_ВАЛИК[10]` (Д1, строка 4) он ложится и в щель крайней
        # пряди, а крайняя выборка берёт его той долей, какой её полоса лежит внутри кромки
        край = (d > -место - 0.5 * шаг[ж, None]) * (D[ж[:, None], jj] > 0) if окно_кр is None else зажать((d + место) / шаг[ж, None] + 1.0, 0.0, 1.0)
        вес = np.where(d < 0, np.exp(-(d / круто) ** 2), np.exp(-(d / ширь) ** 2)) * край * годные
        гребни.append((jj, вес * (лёг / np.maximum(вес.sum(axis=1), 1e-9))[:, None]))
    D *= (1.0 - np.minimum(доля, 0.5))[:, None]
    for jj, гребень in гребни:
        np.add.at(D, (ж[:, None], jj), гребень)                                          # вне следа вес — ноль, а место у них общее: складывать, не присваивать
    return D


def _окно(a, ri, rj):
    """Среднее по прямоугольнику (2ri+1)×(2rj+1) через накопленные суммы. За краем — ноль."""
    if ri > 0:
        k = 2 * ri + 1
        c = np.cumsum(обложить(a, ((ri + 1, ri), (0, 0))), axis=0)
        a = (c[k:] - c[:-k]) / k
    if rj > 0:
        k = 2 * rj + 1
        c = np.cumsum(обложить(a, ((0, 0), (rj + 1, rj))), axis=1)
        a = (c[:, k:] - c[:, :-k]) / k
    return a


def _столб(V, x, y, W):
    """П. 21: во сколько толщин тела (`_тело`, в квадрате конца хода с полем; x, y — где кончилось тело следа) стоит
    самое высокое место свежей плёнки мазка. Порог «есть ли ком» — `_КОМ[9]`."""
    r = int(np.ceil(1.5 * Ч._КОМ[5] * W))
    п = V[max(int(y) - r, 0):int(y) + r + 2:2, max(int(x) - r, 0):int(x) + r + 2:2]                      # через пиксель: это только порог
    п = п[п > 0.0]
    return float(V.max() / _тело(п)) if len(п) else 0.0


def _зона_кома(ком, D, Xл, Yл, u, bh, bw, W, V):
    """П. 21: где кисть, уходя с холста, оставила ком — пиксели прямоугольника мазка (маска): последняя `_КОМ[5]` ширины
    следа (по холсту, от места, где кончилось его тело, и всё, что дальше) и ряды пути, где лёг сгусток срыва (`ком`,
    (N, nm)). Тело хода в зону не входит. Пряди — следы самих волосков (`Xл`, `Yл` — где шёл волосок на каждом шаге,
    `u` — его место поперёк кисти, px): на кривом конце прядь гнётся вместе с бороздой. Ответ: None или (y0, x0, маска,
    прядь, путь) — окно конца хода в прямоугольнике мазка, зона в нём и для каждого пикселя окна — номер пряди (-1 — волосок
    здесь не шёл) и путь вдоль неё, px (ноль — где кончилось тело следа)."""
    краски = D.sum(axis=1) + ком.sum(axis=1)
    if not краски.any():
        return None
    посл = int(np.nonzero(краски >= 0.25 * np.median(краски[краски > 0.0]))[0][-1])           # где кончается тело следа: дальше — только усы прядей
    сгустки = ком.any(axis=1)
    if _столб(V, Xл[посл].mean(), Yл[посл].mean(), W) <= Ч._КОМ[9]:
        return None                                                                          # столба у конца нет (кисть поднялась): оседать нечему, счёта нет
    xm, ym = Xл.mean(axis=1), Yл.mean(axis=1)
    до = np.hypot(xm - xm[посл], ym - ym[посл])                                              # по холсту, не по пути: на смахивании пряди отстают и ложатся короче пути
    ряды = (сгустки | (np.arange(len(краски)) > посл) | (до <= Ч._КОМ[5] * W)) & (краски > 0.0)
    iy, ix, r = np.rint(Yл[ряды]).astype(np.intp), np.rint(Xл[ряды]).astype(np.intp), int(np.ceil(Ч._КОМ[5] * W))
    y0, y1 = max(min(int(iy.min()) - 2, int(ym[посл]) - r), 0), min(max(int(iy.max()) + 3, int(ym[посл]) + r + 2), bh)   # окно конца хода: счёт идёт только в нём
    x0, x1 = max(min(int(ix.min()) - 2, int(xm[посл]) - r), 0), min(max(int(ix.max()) + 3, int(xm[посл]) + r + 2), bw)
    if y1 <= y0 or x1 <= x0:
        return None
    h, w = y1 - y0, x1 - x0
    зона = np.zeros((h, w), dtype=bool)
    зона[зажать(iy - y0, 0, h - 1), зажать(ix - x0, 0, w - 1)] = True
    зона = (_соседи(_соседи(зона * 1.0)) > 0.0) | ((np.arange(x0, x1)[None, :] - xm[посл]) ** 2 + (np.arange(y0, y1)[:, None] - ym[посл]) ** 2 <= (Ч._КОМ[5] * W) ** 2)   # отсчёт ложится ядром в пиксель с лишним
    # пряди окна: волосок красит пиксели своим номером и своим путём
    свои = np.nonzero(ряды | (до <= 1.25 * Ч._КОМ[5] * W))[0]                                # ряды пути у зоны: по ним меряется и толщина пряди рядом с комом
    с = int(свои[0])                                                                         # путь волоска копится подряд — от первого такого ряда
    через = max(int(max(len(u) - 1, 1) / max(u.max() - u.min(), 1e-6) + 1e-6), 1)   # волоски гуще пикселя — берётся каждый такой: шаг поперёк не шире 1 px, пропуски закрывают соседи
    Xо, Yо, u = Xл[с:, ::через], Yл[с:, ::через], u[::через]
    путь = np.concatenate([np.zeros((1, Xо.shape[1])), np.cumsum(np.hypot(np.diff(Xо, axis=0), np.diff(Yо, axis=0)), axis=0)])
    назад = np.nonzero(до[:посл + 1] <= 0.5 * Ч._КОМ[5] * W)[0][0]
    длина = float(до[назад])
    вперёд = 0.0 if длина <= 1.0 else ((Xл[посл, ::через] - xm[посл]) * (xm[посл] - xm[назад]) + (Yл[посл, ::через] - ym[посл]) * (ym[посл] - ym[назад])) / длина
    путь = путь - путь[max(посл - с, 0)][None, :] + вперёд                                    # ноль пути — поперёк хода у конца тела: на прямом ходу путь — это x
    if len(свои) < len(Xо):
        Xо, Yо, путь = Xо[свои - с], Yо[свои - с], путь[свои - с]
    jy, jx = np.rint(Yо).astype(np.intp) - y0, np.rint(Xо).astype(np.intp) - x0
    тут = (jy >= 0) & (jy < h) & (jx >= 0) & (jx < w)
    где = jy[тут] * w + jx[тут]
    S = np.stack([np.bincount(где, weights=q, minlength=h * w) for q in (None, np.broadcast_to(u[None, :], Xо.shape)[тут], путь[тут])], axis=-1).reshape(h, w, 3)   # сколько отсчётов легло в пиксель, сумма их мест поперёк кисти и пути
    дыры = S[..., 0] == 0.0                                                                  # между отсчётами: прядь и путь — от соседей
    if дыры.any():
        S = np.where(дыры[..., None], _соседи(S), S)
    есть = S[..., 0] > 0.0
    делить = np.where(есть, S[..., 0], 1.0)
    прядь = np.where(есть, np.rint(S[..., 1] / делить - u.min()), -1.0).astype(np.intp)
    return y0, x0, зона, прядь, S[..., 2] / делить


def _накоплено(a, ось):
    """Накопленная сумма вдоль оси с нулём впереди — для `_сумма_вдоль`."""
    c = np.zeros(a.shape[:ось] + (a.shape[ось] + 1,) + a.shape[ось + 1:])
    np.cumsum(a, axis=ось, out=c[(slice(None),) * ось + (slice(1, None),)])
    return c


def _сумма_вдоль(c, k0, k1, ось):
    """Сумма соседей от k0 до k1 (сдвиги, включительно) вдоль оси массива по его накопленной сумме `c` (`_накоплено`). За краем — ноль."""
    n = c.shape[ось] - 1
    i = np.arange(n)
    return np.take(c, зажать(i + k1 + 1, 0, n), axis=ось) - np.take(c, зажать(i + k0, 0, n), axis=ось)


def _среднее(a, R):
    """Среднее по квадрату (2R+1)², за краем — ноль. `a` — (h, w)."""
    return _сумма_вдоль(_накоплено(_сумма_вдоль(_накоплено(a, 0), -R, R, 0), 1), -R, R, 1) / (2 * R + 1) ** 2


def _соседи(a):
    """Сумма по квадрату 3×3 (за краем — ноль) по двум первым осям: счёт срезами, без накопленных сумм."""
    b = np.zeros((a.shape[0] + 2, a.shape[1] + 2) + a.shape[2:])
    b[1:-1, 1:-1] = a
    b = b[:-2] + b[1:-1] + b[2:]
    return b[:, :-2] + b[:, 1:-1] + b[:, 2:]


def _тело(V):
    """Толщина тела хода: медиана плёнки по краске (половина краски лежит тоньше), ком срезан на трёх медианах по
    пикселям — тонкая дымка у кромки и сам ком её не сдвигают."""
    п = V[V > 0.0]
    п = np.sort(np.minimum(п, 3.0 * np.median(п)))
    c = np.cumsum(п)
    return float(п[np.searchsorted(c, 0.5 * c[-1])])


def _осел(V, цвет, W, зона, одна=False):
    """П. 21: ком краски у конца хода оседает. Густая краска столбом не стоит: где свежая плёнка у конца хода (`зона`,
    `_зона_кома`) легла комом (выше `_КОМ[8]` толщин тела: вал остановки — `_вал_конца`, сгусток отрыва и срыва — `Сгус`,
    краска собранных в конце прядей), ком оплывает пологим валом вокруг места, где лёг. Счёт идёт по прядям — следам
    волосков (`_зона_кома`: у каждого пикселя номер пряди и путь вдоль неё; на кривом конце прядь гнётся с бороздой): всё,
    что у кома выше `_КОМ[6]` толщин своей пряди (борозды прядей идут сквозь вал), ложится
    вдоль пряди валом с плавным спадом от места кома — `_КОМ[2]` толщин тела на ширину кисти: гребень там, где стоял ком,
    к телу высота сходит без ступени. Вбок краска расходится только по соседним прядям своей полосы набора (не дальше
    `_КОМ[12]` ширины кисти; чему там места нет — вдвое и вчетверо дальше): чужую полосу ком не красит. Выше `_КОМ[0]`
    толщин тела (по плёнке без борозд — среднее на `_КОМ[3]` ширины кисти; гребень борозды — не выше `_КОМ[10]` этого)
    вал не растёт — большой ком ложится шире; тонкая плёнка кома не держит — слой на ней не толще `_КОМ[1]` её толщин,
    на дымку у кромки (тоньше `_КОМ[7]` тела), на голый грунт и из зоны конца краска не течёт. Чему места не нашлось —
    остаётся в своей пряди. Краски столько же (сумма та же), цвет идёт с краской. Тело меряется у конца хода (окно зоны
    с полем в половину `_КОМ[5]` ширины). Счёт — один проход: высота вала пряди находится делением пополам (`_КОМ[4]`
    раз). Случайных чисел нет. Ответ: V, цвет (те же массивы, если кома нет)."""
    К = Ч._КОМ
    if зона is None:
        return V, цвет
    V0, цвет0, (зy, зx, маска, P, Q), поле = V, цвет, зона, int(round(0.5 * К[5] * W))
    h, w = маска.shape
    oy, ox = max(зy - поле, 0), max(зx - поле, 0)                                            # счёт — в окне конца хода с полем: тело меряется рядом с концом, начало длинного хода конца не меняет
    V = V0[oy:зy + h + поле, ox:зx + w + поле]
    около = V[V > 0.0]
    if not len(около):
        return V0, цвет0
    тело = _тело(около)
    v, в_пряди = V0[зy:зy + h, зx:зx + w], P >= 0
    маска = маска & в_пряди
    ком = маска & (v > К[8] * тело)
    if not ком.any():                                                                        # ком — что стоит столбом; гребни борозд и валик бока у конца хода — не ком
        return V0, цвет0
    ц = None if одна else цвет0[зy:зy + h, зx:зx + w]                                         # ход в одну краску цвета не меняет — ком ложится краской своей плёнки
    n, p = int(P.max()) + 1, np.where(в_пряди, P, 0)

    def по_прядям(a, где=None):
        """Сумма по пикселям каждой пряди."""
        return np.bincount(P[в_пряди] if где is None else p[где], weights=a[в_пряди] if где is None else a[где], minlength=n)

    r = max(int(round(К[3] * W)), 2)
    у_кома = _среднее(ком * 1.0, r) > 0.5 / (2 * r + 1) ** 2
    ровно = (v >= К[7] * тело) & ~у_кома & в_пряди
    счёт = по_прядям(ровно * 1.0)
    прядь = np.where(счёт > 0, по_прядям(v * ровно) / np.maximum(счёт, 1), тело)              # толщина пряди у конца хода без кома: борозда — прядь тоньше, гребень — толще
    база = (К[6] * np.minimum(прядь, тело))[p]
    выше = маска & у_кома & (v > база)                                                       # оседает ком и то, что выше базы вплотную к нему
    плёнка = np.where(выше, база, v)
    Сл = v - плёнка                                                                          # ком: что выше базы своей пряди
    гладко = _среднее(плёнка, r)
    Ме = зажать(np.minimum(К[0] * тело - гладко - К[10] * (плёнка - гладко), К[1] * гладко), 0.0, None) * (маска & (v >= К[7] * тело))   # столько вала плёнка здесь держит
    E, вместит, где = по_прядям(Сл, выше), по_прядям(Ме), по_прядям(Сл * Q, выше)             # ком пряди: сколько краски, сколько места, где лежит (с весом краски)
    место = Ме > 0.0
    pm, qm, ме = p[место], Q[место], Ме[место]                                               # пиксели, куда ляжет вал: прядь, путь, сколько держит
    if ц is None:
        кр, полоса = np.zeros((n, 0)), np.zeros(n, dtype=np.intp)
    else:
        кр = np.stack([по_прядям(ц[..., k] * Сл, выше) for k in range(3)], axis=1)           # краска кома пряди по каналам
        тон = np.stack([np.bincount(pm, weights=ц[..., k][место], minlength=n) for k in range(3)], axis=1) / np.maximum(np.bincount(pm, minlength=n), 1)[:, None]   # цвет плёнки пряди там, куда ляжет вал
        полоса = np.cumsum(np.concatenate([[0], np.abs(np.diff(тон, axis=0)).max(axis=1) > К[11]]))        # полоса набора: соседние пряди одной краски

    def вбок(что, приёмник, rb):
        """Краска прядей расходится поровну по прядям своей полосы набора не дальше rb; некуда — остаётся в своей."""
        rb = min(rb, n - 1)                                                                  # у узкой кисти прядей меньше, чем шагов вбок
        сколько, срезы = np.zeros(n), [(slice(max(d, 0), n - max(-d, 0)), slice(max(-d, 0), n - max(d, 0))) for d in range(-rb, rb + 1)]
        for а, б in срезы:                                                                   # прядь б отдаёт пряди а
            сколько[б] += приёмник[а] & (полоса[а] == полоса[б])
        итог = [q * (сколько == 0.0).reshape((n,) + (1,) * (q.ndim - 1)) for q in что]
        for а, б in срезы:
            доля = (приёмник[а] & (полоса[а] == полоса[б])) / np.maximum(сколько[б], 1.0)
            for q, р in zip(что, итог):
                р[а] += q[б] * доля.reshape((-1,) + (1,) * (q.ndim - 1))
        return итог

    Hm, c = К[0] * тело, К[13] * тело

    def клин(A, от, верх):
        """Вал пряди: высота спадает от места кома ровным уклоном, подошва скруглена (излома у тела нет), не выше места (`верх`)."""
        z = np.maximum(A - от, 0.0)
        return np.minimum(np.where(z < c, z * z / (2.0 * c), z - 0.5 * c), верх)

    вал, ост, rb = np.zeros(len(pm)), E, max(int(round(К[12] * W)), 1)
    E, идёт = np.zeros(n), (ост, где, кр)
    где, кр = np.zeros(n), np.zeros(кр.shape)
    for круг in range(3):                                                                # вбок: сперва на соседние пряди; чему в них места нет — дальше
        e2, г2, к2 = вбок(идёт, вместит > E, rb << круг)
        E, где, кр = E + e2, где + г2, кр + к2
        есть = (E > 0.0)[pm]
        pe = pm[есть]
        от = np.abs(qm[есть] - (где / np.maximum(E, 1e-300))[pe]) * (К[2] * тело / W)        # спад вала от места кома
        верх = np.maximum(ме[есть] - К[14] * от, 0.0)                                         # столько держит место: потолок спадает от места кома
        lo, hi = np.zeros(n), np.full(n, Hm + c + (от.max() if len(от) else 0.0))
        for _ in range(int(К[4])):                                                           # высота вала пряди — делением пополам
            A = 0.5 * (lo + hi)
            мало = np.bincount(pe, weights=клин(A[pe], от, верх), minlength=n) < E
            lo, hi = np.where(мало, A, lo), np.where(мало, hi, A)
        кл = клин(hi[pe], от, верх)
        s = np.bincount(pe, weights=кл, minlength=n)
        вал[есть] = кл * np.minimum(E / np.maximum(s, 1e-300), 1.0)[pe]
        ост = np.where(E - s > 1e-6 * тело, E - s, 0.0)
        if not ост.any() or круг == 2:
            break
        доля = ост / np.maximum(E, 1e-300)                                                                       # лишнее уходит дальше вбок со своей долей краски
        идёт = (ост, где * доля, кр * доля[:, None])
        E, где, кр = E - ост, где - идёт[1], кр - идёт[2]
    лёг = np.bincount(pm, weights=вал, minlength=n)
    вал *= (E / np.maximum(лёг, 1e-300))[pm]                                                 # ровно объём кома; чему места не нашлось — тем же валом выше
    слой = np.zeros((h, w))
    слой[место] = вал
    пусто = ((лёг <= 0.0) & (E > 0.0))[p] & выше                                             # пряди без места вовсе: ком остаётся где лёг
    if пусто.any():
        слой[пусто] = (Сл * (E / np.maximum(по_прядям(Сл, выше), 1e-300))[p])[пусто]
    тронуто = (слой > 0.0) | выше
    V0 = V0.copy()
    V0[зy:зy + h, зx:зx + w] = np.where(тронуто, плёнка + слой, v)
    if ц is not None:
        цн = (ц * плёнка[..., None] + (кр / np.maximum(E, 1e-300)[:, None])[p] * слой[..., None]) / np.maximum(плёнка + слой, 1e-12)[..., None]
        цвет0 = цвет0.copy()
        цвет0[зy:зy + h, зx:зx + w] = np.where(тронуто[..., None], цн, ц)
    return V0, цвет0


def _вал_конца(наплыв, концы, с, s, вд, шир, ds, W):
    """П. 19: наплыв на остановке читается светом. Краски в наплыве столько же (`_наплыв`), но лежит она не пологой
    горкой на полширины кисти, а валом поперёк хода у кромки остановки: кисть гнала валик перед собой и оставила его
    там, где встала. `наплыв` — краска наплыва по выборкам профиля, как она легла бы горкой, (N, nm). У каждого места на
    кисти вся его краска собирается к кромке пятна касания (`_пятно`: кромка — овал, вал идёт по нему): гребень в
    `_ВАЛ_КОНЦА[0]` ширины от кромки, наружу — круто (`[2]` этой длины), к телу — полого. Объём по каждому месту на кисти тот же."""
    конец = [q for q in (концы or []) if q[0] == 1]
    if not конец or not наплыв.any():
        return наплыв
    _, s0, _, по_месту = конец[0][:4]
    l = max(Ч._ВАЛ_КОНЦА[0] * W, Ч._ВАЛ_КОНЦА[1])
    ж = np.nonzero(наплыв.any(axis=1))[0]                                                    # ряды пути, где наплыв есть
    d = ((s0 - s[ж])[:, None] - вд[ж][:, с.гребень] - по_месту[None, :]) / l - 1.0           # от гребня вала внутрь, в его длинах
    вес = np.exp(-(d / np.where(d < 0, Ч._ВАЛ_КОНЦА[2], 1.0)) ** 2) * (наплыв[ж] > 0)
    вал = np.zeros(наплыв.shape)
    вал[ж] = вес * (наплыв.sum(axis=0) / np.maximum(вес.sum(axis=0), 1e-9))[None, :]
    return вал


def _сплошь(xs, ys, веса, X, Y, D, ii, jj):
    """Д1б, строка 7: кончик гребня кладёт краску на всём пути, который прошёл за шаг. Отсчёт мазка — точка в конце
    шага пути; у тела хода шаг 0,5 px, и точки сливаются. Когда кончики догоняют остановленную кисть (`_дошла`,
    `_встал`), кончик за шаг уходит по холсту на 1–1,6 px, и точки ложились поперечными строками — лесенка у кромок
    торца. Отсчёт, чей кончик ушёл дальше `_СПЛОШЬ[0]` px от места на прошлом шаге (X, Y — места кончиков (N, nm),
    D — краска, ii, jj — свои отсчёты), делится поровну на отсчёты через `_СПЛОШЬ[1]` px назад по пройденному отрезку;
    сам он остаётся на своём месте (len(ii) первых отсчётов — свои, за ними дописанные плёнкой щелей и валом — не трогаются). Новые отсчёты — в конец: где делить нечего,
    поля складываются в прежнем порядке, бит в бит."""
    пред = np.maximum(ii - 1, 0); шёл = (ii > 0) & (D[пред, jj] > 0.0)                      # откуда кончик пришёл за шаг
    n0, dx, dy = len(ii), np.where(шёл, X[ii, jj] - X[пред, jj], 0.0), np.where(шёл, Y[ii, jj] - Y[пред, jj], 0.0)
    k = np.where(np.hypot(dx, dy) > Ч._СПЛОШЬ[0], np.ceil(np.hypot(dx, dy) / Ч._СПЛОШЬ[1]), 1.0)
    if (k <= 1.0).all():
        return xs, ys, веса
    ki = k.astype(np.intp)
    кто = np.repeat(np.arange(n0), ki - 1)
    t = (np.arange(len(кто)) - np.repeat(np.cumsum(ki - 1) - (ki - 1), ki - 1) + 1.0) / k[кто]
    доля = np.concatenate([1.0 / k, np.ones(len(xs) - n0)])
    return (np.concatenate([xs, xs[кто] - dx[кто] * t]), np.concatenate([ys, ys[кто] - dy[кто] * t]),
            [np.concatenate([w * доля, w[кто] / k[кто]]) for w in веса])


def _пусто(почему, что, X=None, Y=None):
    """v4, 1б: где мазок кончился без следа — в словарь `почему` (`положить_мазок`); X, Y — места кончиков: прямоугольник
    следа кисти. Ответ — None (мазок без следа)."""
    if почему is not None:
        почему['что'] = что
        if X is not None:
            почему['след'] = (int(np.floor(X.min())), int(np.floor(Y.min())), int(np.ceil(X.max())) + 1, int(np.ceil(Y.max())) + 1)
    return None


def _потоки(сид):
    """Потоки случая мазка из его сида, в прежнем порядке: главный; свой (прежние мазки те же); п. 2в — набор красок, углы;
    п. 2г — бок, торец, кромка; п. 2д — посадка кисти, узкая кисть; п. 4 — борозды, срез конца."""
    rng = np.random.default_rng(сид)
    return (rng,) + tuple(np.random.default_rng(rng.bit_generator.seed_seq.spawn(1)[0]) for _ in range(5))


def _стыки(номера0, с, rng_б, густо, красок, набор, p_к, шаг_к, W):
    """Стыки несмешанных густых красок на кисти (вынесено из `положить_мазок` как было): (номера гребней у стыка, щель,
    полуширина щели px), и доля капли, что прижатая кисть отдаёт соседу за шаг переноса (Nc,)."""
    стык0 = np.nonzero(номера0[:-1] != номера0[1:])[0]
    щель = зажать(rng_б.random(len(стык0)) * 1.7 - 0.6, 0.0, 1.0) * густо       # у каждого стыка своя; у трети нет
    пол_щели = 0.7 + 1.1 * rng_б.random(len(стык0))                               # px
    if набор:
        # п. 2г: щель узкую полосу не съедает — она не шире шестой части меньшей из двух полос у стыка
        # (у полосы в 6–7 px, зажатой двумя щелями, от краски оставалась нитка)
        шир_п = np.array([2.0 * с.полуш[номера0 == q].sum() for q in range(красок)])
        пол_щели = np.minimum(пол_щели, np.maximum(0.17 * np.minimum(шир_п[номера0[стык0]], шир_п[номера0[стык0 + 1]]), 0.7))
    return (стык0, щель, пол_щели), густо * зажать((p_к - 0.55) / 0.3, 0.0, 1.0) * (шаг_к / (1.5 * W))   # доля капли соседу за шаг


def _полная_кисть(к, H, Hг, запас_px, капля0, с, W, живая, скупо, рвёт):
    """Д-1-2: сколько краски в полной кисти — объём на единицу ширины гребня: (в ворсе, на кончике (nr,)). От хода не
    зависит: без случайного набора гребней (`заряд0`), без их неровного запаса и нагрузки (`с.запас`, `с.нагр`) и по
    толщине плёнки самой кисти, а не нагрузки хода. Доли `Загрузка` — доли этого объёма: та же полная кисть — та же
    краска, каким бы ходом её ни клали (долю множили на ёмкость хода с его случайным набором: мягкая 6 мм на ходе
    40 мм держала 7197, на ходе 240 мм — 3701, и краска бралась из ничего). H, Hг — плёнка хода и её гребней, запас_px —
    на сколько px хватает единицы заряда гребня, капля0 — капля, с которой садится свежая кисть (nr,)."""
    Hк = к.толщина_плёнки(); Hк = Hк if Hк > 0.0 else H
    if скупо is not None:
        ворс = Ч._СРЫВ[0] * скупо.ширин * Ч._СРЫВ[2] * W
    elif рвёт is not None and рвёт.сухая:
        ворс = _ПЕРЕГРУЗ * рвёт.заряд * к.запас * 32.0 * Ч._СУХАЯ[7]
    else:
        ворс = _ПЕРЕГРУЗ * (1.0 if рвёт is None else рвёт.заряд) * к.запас * W * (32.0 * Ч._ММ / W) ** 0.5 * _узкая_краска(живая, W)
    return Hк * ворс, капля0 * (Hк / np.maximum(Hг, 1e-12))


def _с_загрузки(загрузка, место, полная_кисть, капля0, ёмкость):
    """Д-1: ход начинает с того, что на кисти: в ворсе — доля краски полной кисти (`_полная_кисть`) по месту гребня
    поперёк кисти (`место` — номер корзины, (nr,)), на кончике — доля её капли. Пока кисть в воздухе, краска из ворса
    подходит к кончику: капля доливается до того, сколько держит кончик этого гребня с таким запасом (`капля0`; полная —
    пока в ворсе больше `_ЗАГРУЗКА[0]` полного), и столько же уходит из ворса (ёмкость (nr,) — объём единицы заряда
    гребня, в тех же единицах, что капля). Ответ: (заряд, заряд полной кисти, капля) — заряд в единицах этого хода,
    объём тот же (Д-1-2)."""
    ворс0, кончик0 = полная_кисть
    запас = загрузка.запас[место]
    ворс, капля = ворс0 * запас, кончик0 * загрузка.капля[место]
    долив = np.minimum(np.maximum(капля0 * зажать(запас / Ч._ЗАГРУЗКА[0], 0.0, 1.0) - капля, 0.0), ворс)
    ёмкость = np.maximum(ёмкость, 1e-12)
    return (ворс - долив) / ёмкость, ворс0 / ёмкость, капля + долив


def _в_загрузку(место, запас, капля):
    """Д-1: что осталось в ворсе и на кончиках после хода — по местам поперёк кисти (`_КОРЗИН`), как `Кисть._запомнить`:
    запас, капля (nr,) — доли краски полной кисти (`_полная_кисть`; на кончике гребня, набранного гуще, — и больше 1);
    пустое место берёт у ближнего. Ответ: (запас, капля) по корзинам."""
    есть = np.bincount(место, None, _КОРЗИН).astype(np.float64)
    ближ = np.abs(np.arange(_КОРЗИН)[:, None] - np.nonzero(есть)[0][None, :]).argmin(axis=1)
    return tuple((np.bincount(место, a, _КОРЗИН)[есть > 0] / есть[есть > 0])[ближ] for a in (зажать(запас, 0.0, 1.0), зажать(капля, 0.0, 2.0)))


def положить_мазок(слой, точки, краски, к, сид, непрозрачность=1.0, раскладка='полосы', нагрузка=None,
                   нижние=(), касание=None, окно=None, перед_записью=None, замер=None, зерно=None, мутность=1.0, под=(), пропуск=None, полосы=None, соседние=(), по_гребням=None, ровно=None, ровно_низ=((), 0.0), запас=None, отдача=None, волокна=None, рука=False, почему=None, разбавитель=0.0, загрузка=None):
    """Посчитать мазок и вписать его в слой.

    краски — список (линейный RGB (3,), доля). нижние — слои под этим, с сырой краской которых
    мазок тоже мешается (по умолчанию — только свой слой). окно (п. 9) — (x0, y0, ширина, высота) холста, если слой — участок с углом (x0, y0). зерно (п. 5б) — `Холст._зерно_под`: рельеф грунта под мазком, или None — грунт гладкий. полосы (п. 13) — (ширина полосы набора, длина куска краски в ней), px холста, любое — None: как было. мутность, под, пропуск (п. 10, инструмент 3) — вид краски (`краска.Краска`; 1 — кроющая, как было), слои под этим (их рельеф) и функция, дающая массив пропуска слоя. разбавитель (Г-1) — 0–1: у не кроющей краски тоже идёт `ровно` (нагрузку, мутность, ровно и запас жидкой краски даёт `краска.разбавить`). запас (п. 17) — на сколько ширин кисти хватает краски (сухой срыв, `_срыв`); None — как у кисти. перед_записью (11б) — зовётся до записи с прямоугольником холста, вне которого мазок ни в какой слой не пишет. Ответ — записанный прямоугольник холста (x0, y0, x1, y1) или None. почему (v4, 1б) — словарь: при ответе None в него пишется, где мазок кончился без следа (`"что"`: `вне` — след кисти весь за краем, `"след"` — его прямоугольник (x0, y0, x1, y1) в px холста; `нажим` — ни один гребень не коснулся; `чистая` — нагрузка 0 и сырого под кистью нет; `пусто` — касания были, краски не легло); на пиксели не влияет. замер (v4, 3г, К-1) — функция: зовётся после записи со словарём полей следа для ответа мазка (`ответ.Ответ`); на пиксели не влияет. загрузка (Д-1) — живая краска кисти (`инструмент.Загрузка`) или None: ход начинает с её запаса и капли, что осталось — в `к._расход`."""
    rng, rng_б, rng_в, rng_г, rng_д, rng_е = _потоки(сид)
    ox, oy, Ш, В = окно if окно is not None else (0, 0, слой.покрытие.shape[1], слой.покрытие.shape[0])
    путь = _путь(точки, к, rng)
    x, y, p, скор, угол, ds, N, L = путь['x'], путь['y'], путь['p'], путь['скор'], путь['угол'], путь['ds'], путь['N'], путь['L']
    W = float(к.ширина)
    запас_поля = W * 0.9 + 2 * _ПОЛЕ
    if (x.max() < -запас_поля or y.max() < -запас_поля or x.min() > Ш + запас_поля
            or y.min() > В + запас_поля or p.max() <= 0.0):
        return _пусто(почему, 'нажим 0' if p.max() <= 0.0 else 'вне')
    мастихин = к.форма == 'мастихин'
    с = _состав(к, rng)
    nr, ns, nm = с.nr, с.ns, с.nm
    H, чистая = М.чистая(к, нагрузка)                        # толщина плёнки полного мазка; п. 10, инструмент 5 (5а): нагрузка 0 — кисть вытерта, своей краски нет (`мягкая.чистая`)
    ровно = float(ровно) if ровно and (мутность >= 1.0 or разбавитель) and not чистая and not _сухая(к, нагрузка) else 0.0; скупо = _срыв(запас, мастихин or чистая or _сухая(к, нагрузка))   # п. 15: текучая кроющая краска; п. 17: краски набрано на `запас` ширин кисти
    мт = масштаб_толщины(W)
    густо = float(зажать((H / мт - 0.35) / 0.5, 0.0, 1.0))  # 0 — тонкая краска, 1 — пастозная
    тау = _ТАУ * мт / max(к.укрывистость, 1e-3)
    остр = float(к.остриё); rng_уз, узкий_набор = _узкий_набор(rng, краски, мастихин, W, раскладка, густо, остр)   # п. 10; п. 12: щетина в обойме (`остриё` 0) острого кончика не знает и узкой
    живая, p, p_руки = _дрожь(rng, p, W, ds, густо, мастихин or (len(краски) != 1 and not узкий_набор) or _сухая(к, нагрузка), остр)   # п. 10: нажим узкой кисти гуляет; полупустая каплей не садится
    if путь['на_месте'] and к.форма == 'круглая':
        p = p_руки   # касание-2: поставленную на месте кисть рука по холсту не ведёт — дрожи хода нет, а капля посадки садится тем же пятном, что пучок: нажим по хорде (`путь._отпечаток_пучка`) остаётся как дан, иначе капля держала все гребни на всей длине отпечатка и узкая круглая ставила брусок
    # густые несмешанные краски на кисти (п. 2в): набраны с палитры рядом и не размешаны
    набор, мяг = len(краски) > 1 and густо > 0 and not мастихин and раскладка in ('полосы', 'ряд') and not узкий_набор, Мягкая.для(к, с, rng, p, ds, N, W, М.сырое_под(к, слой, x, y, угол, с.центр, ox, oy, тау), отдача)   # п. 10, инструмент 4: мягкая кисть (`Кисть.кайма`); у щетины — None, и всё как было; 4б: по сырой плёнке соседнего мазка короткий волос достаёт
    краски_р = краски
    if набор:
        # доли из вызова — в среднем: с палитры кисть набирает каждый раз чуть по-своему, до ±30 %
        # (узкая кисть — меньше: у неё на полосу три-четыре гребня, и полоса пропала бы целиком)
        д = np.array([д for _, д in краски]) * np.exp(зажать(_ДОЛИ * min(W / 40.0, 1.0) * rng_в.standard_normal(len(краски)), -0.3, 0.3))
        краски_р = [(c, q / д.sum()) for (c, _), q in zip(краски, д)]

    # --- касание гребней
    # сколько кисти касается холста, решает не нажим, а то, как кисть поставлена: плашмя — всей шириной
    # и при лёгкой руке; на ребре — узко, и ширина растёт с нажимом. Нажим решает, насколько она втирает
    плашмя = float(зажать(к.касание if касание is None else касание, 0.0, 1.0)) if к.форма == 'плоская' else 0.0
    # поставленная плашмя кисть лежит всей шириной, пока рука держит свой нажим, каким бы лёгким он ни был;
    # когда руку поднимают (нажим падает против набранного в этом мазке), кисть встаёт на кончик:
    # дальние и короткие пряди отходят первыми, след сужается — как у кисти на ребре
    доля_нажима = p / np.maximum(np.maximum.accumulate(p), 1e-6)
    лежит = зажать((доля_нажима - 0.5) / 0.4, 0.0, 1.0)
    лежит = лежит * лежит * (3.0 - 2.0 * лежит)
    # сорванная кисть на кончик встать не успевает: нажим ушёл быстрее, чем за ширину кисти хода, —
    # она отходит от холста плашмя, вся разом, и след кончается обрывом, а не клином
    спад = np.maximum(-np.gradient(p, ds), 0.0) * W / np.maximum(np.maximum.accumulate(p), 1e-6)
    быстро = зажать((спад - 0.7) / 0.6, 0.0, 1.0)
    быстро = быстро * быстро * (3.0 - 2.0 * быстро)
    наиб = 0.0
    for i in range(N):                                        # начатый срыв держится до конца этого спада
        наиб = max(наиб, быстро[i]) if доля_нажима[i] < 0.97 else быстро[i]
        быстро[i] = наиб
    сорвана, быстро = быстро, быстро * густо                  # тонкая краска обойму не держит: её конец прежний
    лежит = плашмя * np.maximum(лежит, быстро)                       # (N,)
    p_р = p + (0.85 * доля_нажима ** 1.1 - p) * плашмя                      # нажим «на кончике»: доля от своего полного
    if к.форма == 'круглая':
        центр = np.zeros(N)
        расст = np.broadcast_to(с.расст[None, :], (N, nr))
    elif мастихин:
        центр = np.zeros(N)
        крен = rng.uniform(-1, 1)
        расст = np.broadcast_to(((0.5 + 0.5 * крен * с.центр / с.полуширина) * 0.25)[None, :], (N, nr))
    else:
        # кисть встаёт не точно серединой; место первого касания вдоль мазка не ползёт: рука кисть не перекатывает
        e0, e1 = rng.uniform(-0.7, 0.7, 2)
        центр = np.full(N, e0)
        # порог идёт больше от места пряди, чем от места гребня: прядь отрывается почти разом, хвост — прядью, а не иглой
        место = М.место_подъёма(к, чистая, с.центр, ((0.35 + 0.65 * _острая(W, остр)) * с.центр + 0.65 * (1.0 - _острая(W, остр)) * _ось_подъёма(с, ровно * (1.0 - плашмя)))) / с.полуширина   # 5а-2: вытертый мягкий пучок отходит от холста куполом, не прядями обоймы
        расст = np.abs(место[None, :] - центр[:, None]) / (1.0 + np.abs(центр))[:, None]
    порог, сход_о = _остриё(с, W, p_р, расст, мастихин, живая > 0, к.форма == 'круглая', остр, ровно * (1.0 - плашмя))   # п. 10: у узкой кисти — острый кончик
    if густо > 0 and not мастихин:
        # 4б: на медленном подъёме гребень, полный густой краски, держится за холст дольше соседа — концы гребней
        # стоят вразнобой, а не лесенкой от края к середине
        уходит = (np.arange(N) > int(np.argmax(p))) & (доля_нажима < 0.97)
        rng_ж = np.random.default_rng(rng.bit_generator.seed_seq.spawn(1)[0])      # свой поток: прежние не сдвигаются
        порог = порог + (_ПОДЪЁМ_ГР * густо * (rng_ж.random(nr) - 0.5))[None, :] * уходит[:, None]
    порог = порог - порог.min(axis=1, keepdims=True) + 0.04
    кас = зажать((запас_г := p_р[:, None] - порог) / _МЯГКОСТЬ, 0.0, 1.0)   # запас: нажим гребня сверх порога касания (6а-2: отрыв по сырому)
    кас = кас * кас * (3.0 - 2.0 * кас)                       # (N, nr)
    if плашмя > 0:
        # плашмя место пряди порога не даёт, а разница длин сказывается только у самого холста
        порог_пл = с.порог[None, :] * _ДЛИНЫ_ПЛАШМЯ
        порог_пл = порог_пл - порог_пл.min(axis=1, keepdims=True) + 0.04
        кас_пл = зажать((p[:, None] - порог_пл) / _МЯГКОСТЬ, 0.0, 1.0)
        кас = кас + (кас_пл * кас_пл * (3.0 - 2.0 * кас_пл) - кас) * лежит[:, None]
        запас_г = запас_г + (p[:, None] - порог_пл - запас_г) * лежит[:, None]
    # посадка и подъём кисти (п. 2д): плоская кисть, которую кладут плашмя, сначала касается серединой обоймы,
    # углы встают, когда нажим набран и щетину потащило; при подъёме углы уходят первыми. Кисть редко стоит ровно:
    # одна сторона встаёт раньше другой. Удар с коротким входом кладёт кисть разом — торец плоский
    посадка_м = держит = None
    if плашмя > 0 and nr > 2 and мяг is None:   # мягкий пучок обоймой не встаёт: его вход — купол и нажим волоска (`мягкая.py`)
        посадка_г, посадка_м = _посадка(с, путь, p, rng_д, W, rng_е, густо, p_руки if живая > 0 else None, держит := _держит(к, p, W, плашмя, скор, доля_нажима, сорвана, ровно, мастихин or чистая or скупо is not None or _сухая(к, нагрузка) or мутность < 1.0), рука, _впереди(к, с, путь, p, W, плашмя, густо, мастихин, скор) if раскрывает_рукой(p, рука) else None)   # п. 18в; К8.1: `рука` — ширина посадки по самому нажиму; К8б — и где лёг кончик
        if посадка_м is not None:
            кас = кас * (1.0 + (посадка_г - 1.0) * плашмя)
    сход_г, концы, встала = _концы(к, с, путь['s'], p, p_р[:, None] - порог, запас_г, лежит, W, густо, плашмя, скор, доля_нажима, быстро, ровно * (1.0 - плашмя), мастихин, чистая, сид, ровно) if мяг is None and мутность >= 1.0 else (None, None, 0.0)   # п. 18: концы следа — пятно касания и сход прядей; множители укладки, перенос краски прежний
    угол_м, кас = None, (кас if мяг is None else мяг.коснуться(кас, запас_г)); сход_г, кас_у, тонко_г = _хвост(к, с, p, p_р, p_р[:, None] - порог, лежит, W, густо, плашмя, скор, доля_нажима, быстро, ровно * (1.0 - плашмя), мастихин, чистая, _сухая(к, нагрузка) or скупо is not None, сход_г, кас, держит if посадка_м is not None else None)   # п. 18б: касание на укладке — с хвостом сходящего хода; перенос краски идёт по `кас`, как раньше   # мягкая кисть: короткий волос края достаёт до холста слабее или не достаёт
    кончик = np.zeros(nr)
    # густая кисть плашмя (п. 2г): бок, торец, углы, тонкое место. П. 2д: кисть в одну краску живёт так же — чем гуще
    # краска, тем полнее (пастозная — целиком, до нагрузки 0,55 — как раньше); смесь у кромки — только у набора
    одна_густая = len(краски) == 1 and not мастихин
    живёт = 1.0 if набор else (float(зажать((густо - 0.4) / 0.4, 0.0, 1.0)) if одна_густая else 0.0)
    толстая = живёт > 0 and плашмя > 0 and nr > 4
    if толстая:
        # углы входа скруглены (п. 2в, 2г): у самого края краски меньше, и кисть подходит к холсту серединой —
        # крайние полтора-два пикселя следа встают на 1–4 px позже; считается по месту на кисти, а не по гребню:
        # у каждого удара оба угла, середина торца не тронута
        край_сл = np.full(2, с.полуширина - _ЯДРО / 2)            # где кончается след: левый и правый край
        for кр, ст in ((0, 0), (nr - 1, 1)):
            if 2.0 * с.полуш[кр] < 2.0:                           # крайний гребень уже двух пикселей краски не кладёт
                край_сл[ст] -= 2.0 * с.полуш[кр]
        ст_м = (с.u > 0).astype(np.intp)
        от_кр = край_сл[ст_м] - np.abs(с.u)
        зад_м = rng_г.uniform(*_УГОЛ[:2], 2)[ст_м] * зажать((_УГОЛ[3] - от_кр) / (_УГОЛ[3] - _УГОЛ[2]), 0.0, 1.0) \
            * густо * живёт * плашмя * float(зажать(W / 24.0, 1.0, 1.7)) ** 0.4     # у широкой кисти слой толще и угол заплывает
        пройдено = путь['s'] - путь['s'][int(np.argmax(p > 0.02))]
        z = зажать(пройдено[:, None] - зад_м[None, :] + 0.5, 0.0, 1.0)
        угол_м = np.where(зад_м[None, :] > 0.05, z * z * (3.0 - 2.0 * z), 1.0)       # (N, nm)
        # торец — кончики щетины, а не линейка (п. 2г): гребни стоят вдоль хода неровно на 1–2 px ещё до того,
        # как их потащили
        # (вперёд из торца кончик не торчит: большинство стоит в ряд, часть отстаёт; у углов — своя задержка)
        кончик = _КОНЧИК * (1.0 if набор else 1.0 + 0.25 * float(зажать((W - 24.0) / 16.0, 0.0, 1.0))) * густо * живёт * плашмя * зажать(rng_г.uniform(-2.0, 1.0, nr), 0.0, None) ** 0.7 \
            * (с.полуширина - np.abs(с.центр) > 2.5)
    if not кас.any():
        return _пусто(почему, 'нажим')

    # --- место гребней и выборки профиля на холсте
    ax, ay, tx, ty = -np.sin(угол), np.cos(угол), np.cos(угол), np.sin(угол)   # широкая ось кисти; по ходу
    # при обычном нажиме 0,85 след — в ширину кисти; придавленная кисть расходится веером шире
    # «касание и короткий ход»: круглая кисть, поставленная на месте (`путь._отпечаток_пучка`), раскрыта нажимом руки на
    # всём отпечатке — по его длине идёт только пятно касания (порог гребней), а ворс вбок за ним не ходит: иначе крайние
    # пряди чертили дуги от оси к краю и обратно («усы» вместо пятна)
    p_шир, p_шир_р, сход_ш = (np.full(N, p.max()), np.full(N, p_р.max()), (np.full(N, сход_о[int(np.argmax(p))]) if isinstance(сход_о, np.ndarray) else сход_о)) if путь['на_месте'] and к.форма == 'круглая' else (p, p_р, сход_о)
    расп0 = расп = _расп(к, p_шир, быстро * плашмя, лежит, _брюшко(W, живая > 0 and к.форма == 'круглая', p_шир_р), сход_ш)
    if держит is not None: расп = _расп(к, p_шир, быстро * плашмя, лежит, _брюшко(W, живая > 0 and к.форма == 'круглая', p_шир_р), сход_ш, держит)   # п. 18в: рука сходит с кисти плашмя — ворс к оси не собирается
    ось = центр * с.полуширина
    бока = None
    if мастихин:
        расп = np.ones(N)
        липн = np.ones((N, ns))
        уход = np.zeros((N, ns))
    else:
        # пряди: при слабом нажиме собираются к своей оси (просветы открываются), при сильном смыкаются;
        # медленно дышат и уходят вбок вдоль пути — не больше пикселя на сотню
        дышит = _шум(rng, N, ns, 140.0 / ds)
        # полная кисть плашмя: густая краска держит пряди вместе, просветы открывает только пустеющая
        липн = 1.0 - с.липнет[None, :] * (1.0 - 0.85 * густо * лежит)[:, None] \
            * зажать(1.15 - (p_шир_р[:, None] / 0.85) ** 1.5 + 0.22 * дышит, 0.0, 1.0)
        # кромка мазка идёт за крайними прядями: крайняя прядь свободна с одной стороны, трение по холсту
        # то поджимает её к соседке (краска там ложится гуще), то отпускает — на пиксель-два на длине
        # в ширину кисти. Кисть встаёт на своё место, бок уходит только с ходом; у каждого бока своя жизнь
        с_ходом = 1.0 - np.exp(-np.maximum(путь['s'] - путь['s'][int(np.argmax(p > 0.02))], 0.0) / (0.3 * W))
        # тонкая краска кромку держит сухим следом и просветами, как раньше; поджатая прядь видна у густой
        размах = _БОК * (_БОК_НАБОР if набор else 1.0 + (_БОК_ОДНА - 1.0) * живёт * float(зажать((W - 16.0) / 8.0, 0.0, 1.0))) * густо * (0.6 + 2.0 * с.липнет[[0, ns - 1]] / max(к.клочки, 1e-3) * min(к.клочки, 1.0))
        # наружу за свою линию кисть не выходит: шире всего она там, где встала
        бока = зажать(_шум(rng_б, N, 2, float(зажать(0.45 * W, 7.0, 26.0)) / ds) + _БОК_СДВИГ, 0.0, None) \
            * размах[None, :] * ((с_ходом ** 2 if набор else с_ходом) * (1.0 - быстро))[:, None]   # сорванная кисть отходит плашмя, во всю ширину
        # (у набора в несколько красок бок гуляет сильнее, но у самого входа кисть ещё стоит во всю ширину: иначе
        # крайняя строка следа у входа пропадала и начиналась позже)
        уход = _шум(rng, N, ns, 260.0 / ds) * 0.5
        липн, уход = М.пучок(мяг, липн, _пряди_узкой(с, уход, живая, rng_уз, N, W, ds, к.форма == 'круглая'))   # п. 10; 4а-2: мягкий волос на пряди со щелями не расходится
    дрейф = None
    if набор:
        # пряди внутри густой кисти сходятся и расходятся, как крайняя у бока: граница пряди уходит вбок
        # на 1–3 px на длине в ширину кисти, плавно; гребни между границами раздвигаются и сжимаются
        # (поперечное место — гладкая функция места на кисти: пряди не перехлёстываются). Края кисти на месте
        узлы = (с.центр + с.полуш)[np.nonzero(с.прядь[1:] != с.прядь[:-1])[0]]
        узлы = узлы[np.abs(узлы) < с.полуширина - 2.0]
        if len(узлы):
            опоры = np.concatenate([[-с.полуширина], узлы, [с.полуширина]])
            K = len(опоры)
            поз = np.broadcast_to(опоры, (N, K)).copy()
            поз[:, 1:-1] += _шум(rng_в, N, K - 2, 0.8 * W / ds) * (_ДРЕЙФ * густо * min(W / 40.0, 1.0)) * с_ходом[:, None]
            зазор = np.diff(опоры)
            for q in range(1, K - 1):
                поз[:, q] = зажать(поз[:, q], поз[:, q - 1] + 0.65 * зазор[q - 1], поз[:, q - 1] + 1.5 * зазор[q - 1])
            for q in range(K - 2, 0, -1):
                поз[:, q] = зажать(поз[:, q], поз[:, q + 1] - 1.5 * зазор[q], поз[:, q + 1] - 0.65 * зазор[q])
            дрейф = (опоры, поз - опоры[None, :])
        # след густой кисти дышит по ширине на 5–10 %: лента постоянной ширины — штамп
        # (у входа и у отрыва — нет: там ширину держит торец, а сужение читалось бы скруглённым углом)
        от_концов = зажать(np.minimum(путь['s'] - путь['s'][int(np.argmax(p > 0.02))], путь['L'] - путь['s']) / W - 0.5, 0.0, 1.0)
        # (п. 2г: только внутрь — шире всего кисть там, где встала; иначе у бока вырастала строка, которой нет у входа)
        расп = расп * (1.0 - 1.6 * _ДЫШИТ * зажать(-_шум(rng_в, N, 1, W / ds)[:, 0], 0.0, None) * от_концов)
    вдоль_к = 1.0 + 2.0 * np.sin(np.radians(зажать(путь['наклон'], 0, 85)))
    if путь['азимут'] is not None:
        qx, qy = np.cos(путь['азимут']), np.sin(путь['азимут'])
    else:
        qx, qy = tx, ty

    # кисть встаёт на холст ровным торцом: пряди расходятся вдоль хода, только когда их потащили
    # (трение у каждой своё) — отставание набирается на первой ширине пути от касания
    коснулась = путь['s'][int(np.argmax(p > 0.02))]
    тащит = (1.0 - np.exp(-np.maximum(путь['s'] - коснулась, 0.0) / W)) * _встал(к, мастихин, плашмя, скор) * _дошла(встала, плашмя, скор)   # п. 16: остановленная на ребре кисть встаёт
    if мастихин or к.форма == 'круглая':
        тащит = np.ones(N)
    if путь['на_месте'] and к.форма == 'круглая':
        тащит = np.zeros(N)                                   # «касание и короткий ход»: поставленную на месте кисть не тащили — пряди вдоль хода не разошлись
    # густая краска у кисти плашмя держит пряди обоймой: вдоль хода они расходятся не дальше её доли ширины —
    # обрыв сорванной кисти не длиннее трети ширины, но у каждой пряди своё место в нём
    обойма = 0.0 if (мастихин or к.форма == 'круглая') else плашмя * густо
    предел = _ОБОЙМА * W

    if бока is not None:
        # крайняя прядь поджимается к своей внутренней границе — к соседке; у кисти в одну-две пряди — к середине; 11г: и не дальше неё — иначе узкая прядь выворачивалась и клала отрицательную краску (цвет слоя 10⁸, README)
        якорь_л, якорь_п = min(float((с.центр + с.полуш)[с.прядь == 0].max()), 0.0), max(float((с.центр - с.полуш)[с.прядь == ns - 1].min()), 0.0)
        бока = np.minimum(бока, np.array([якорь_л + с.полуширина, с.полуширина - якорь_п])[None, :])

    вдоль_х = lambda отст, конч: _вдоль_ворса(отст, конч, вдоль_к * тащит, обойма, предел)   # noqa: E731
    def на_холст(u, прядь, отст, конч, было=False):
        """Поперечные места u (их пряди, их отставания, места кончиков) -> координаты (N, len(u))."""
        ось_п = с.ось_пряди[прядь]
        бок = ось_п[None, :] + (u - ось_п)[None, :] * (липн0 if было else липн)[:, прядь]
        if дрейф is not None:
            опоры, сдв = дрейф
            j = зажать(np.searchsorted(опоры, u) - 1, 0, len(опоры) - 2)
            t = зажать((u - опоры[j]) / (опоры[j + 1] - опоры[j]), 0.0, 1.0)
            бок = бок + сдв[:, j] * (1.0 - t)[None, :] + сдв[:, j + 1] * t[None, :]
        бок = ось[:, None] + (бок - ось[:, None]) * (расп0 if было else расп)[:, None] + уход[:, прядь]
        if бока is not None:
            бок = бок + бока[:, :1] * зажать((якорь_л - u) / (якорь_л + с.полуширина), 0.0, 1.0)[None, :] \
                - бока[:, 1:] * зажать((u - якорь_п) / (с.полуширина - якорь_п), 0.0, 1.0)[None, :]
        вд = вдоль_х(отст, конч)   # отставание вдоль ворса; его же берёт перемычка (`Просвет.в_растр`)
        return М.за_кистью(мяг, x[:, None] + бок * ax[:, None], y[:, None] + бок * ay[:, None], вд, qx, qy)   # К5: с "load_along" кончик идёт за своим корнем

    прядь_м = с.прядь[с.гребень]
    # у густой кисти плашмя гребни внутри пряди рвутся с холста каждый в своём месте
    отст_г = с.отст + (_ОТСТ_ГР[0] + _ОТСТ_ГР[1] * W) * обойма * с.отст_гр
    (пятно_г, пятно_м), (пятно_г0, пятно_м0) = (_лёг(q, с, путь['s'], отст_г, вдоль_к * тащит, обойма, предел) for q in (концы, [q[:2] + q[4:] if len(q) > 4 else q for q in концы] if концы and any(len(q) > 4 for q in концы) else None))   # п. 18: пятно касания у концов — по холсту; Д1, строка 5: и оно же ровным овалом (мерка краски конца хода), если кромка остановки идёт по прядям
    просвет, липн0, липн = М.без_щелей(мяг, Просвет(np.random.default_rng(rng.bit_generator.seed_seq.spawn(1)[0]), с, липн, уход, 1.0 if мастихин else густо, N, ds, W)), липн, (липн if держит is None else _Плёнка.пряди(липн, держит * _Плёнка.густая(густо)))   # 6а, свой поток; 4а-2: у мягкой кисти щелей между прядями нет; п. 18в: пока рука сходит, пряди густой краски к своим осям не собираются (щели считаны как были)
    if раскрывает_рукой(p, рука) and isinstance(просвет, Просвет): просвет.оба = True   # К8б: плёнка щели — от обеих прядей
    X, Y = развести(мяг, *на_холст(с.u, прядь_м, отст_г[с.гребень], кончик[с.гребень]), ax, ay, с.гребень)   # мягкая кисть: крайний волос водит вбок
    if живая > 0 and просвет.есть: _сел(просвет, с, живая, p, ds, W, rng_уз)   # п. 10: у посадки щель закрыта, дальше пряди расходятся и сходятся
    # --- прямоугольник мазка (с полями), обрезанный холстом с запасом
    поле = _ПОЛЕ + (0 if мастихин else int(np.ceil(Ч._СРАСТ_ВАЛ[1] + Ч._СРАСТ_ВАЛ[2] * W)))   # 6а: за кромкой следа — место валу сырой краски
