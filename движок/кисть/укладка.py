    bw, bh = bx1 - bx0, by1 - by0; (почему if почему is not None else {})['рамка'] = М.с_осью(к, (bx0, by0, bx1, by1), x, y)   # 2б: вне её мазок холста не читает и не пишет (`Холст.прямоугольник_мазка`, `ядра.py`)
