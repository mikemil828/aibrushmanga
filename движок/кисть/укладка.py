def _брызги2(xs, ys, bw, bh, веса, кусок=1 << 20):
    """Разложить отсчёты (xs, ys — в пикселях прямоугольника мазка) на сетку вдвое мельче
    ядром 3x3 (квадратичный B-сплайн) и сложить 2x2. Ответ — список полей (bh, bw).
    Отсчёты идут кусками по `кусок` (v4, 1д): ядро 3x3 одного куска держит 9 × кусок чисел, а не 9 × все отсчёты мазка
    (спираль ореола R 440 — 24,7 млн отсчётов, 1,66 ГБ на одно поле). Складывает `np.add.at` по порядку отсчётов — те же
    суммы в том же порядке, что `np.bincount` всех разом: бит в бит."""
    fw, fh = 2 * bw, 2 * bh
    сдвиги = np.array([-fw - 1, -fw, -fw + 1, -1, 0, 1, fw - 1, fw, fw + 1], dtype=np.intp)
    поля = [np.zeros(fw * fh) for _ in веса]
    for a in range(0, len(xs), кусок):
        xr = xs[a:a + кусок] * 2.0 - 0.5
        yr = ys[a:a + кусок] * 2.0 - 0.5
        ix = np.rint(xr).astype(np.intp)
        iy = np.rint(yr).astype(np.intp)
        годные = (ix >= 1) & (ix < fw - 1) & (iy >= 1) & (iy < fh - 1)
        вк = [w[a:a + кусок] for w in веса]
        if not годные.all():
            ix, iy, xr, yr = ix[годные], iy[годные], xr[годные], yr[годные]
            вк = [w[годные] for w in вк]
        fx = xr - ix
        fy = yr - iy
        wx = np.stack([0.5 * (0.5 - fx) ** 2, 0.75 - fx * fx, 0.5 * (0.5 + fx) ** 2], axis=1)
        wy = np.stack([0.5 * (0.5 - fy) ** 2, 0.75 - fy * fy, 0.5 * (0.5 + fy) ** 2], axis=1)
        w9 = (wy[:, :, None] * wx[:, None, :]).reshape(-1, 9)
        idx = ((iy * fw + ix)[:, None] + сдвиги[None, :]).ravel()
        del xr, yr, ix, iy, fx, fy, wx, wy
        for i, w in enumerate(вк):
            if a == 0 and len(xs) <= кусок:              # Е-3: один кусок — `np.bincount` по нулям: те же суммы в том же порядке
                поля[i] = np.bincount(idx, (w9 * w[:, None]).ravel(), fw * fh)
            else:
                np.add.at(поля[i], idx, (w9 * w[:, None]).ravel())
    return [_сложить_2x2(f, bh, bw) for f in поля]


def _сложить_2x2(f, bh, bw):
    """`f.reshape(bh, 2, bw, 2).sum(axis=(1, 3))` бит в бит (Е-3): numpy при bw > 1 складывает пары строк, (a + b) + (c + d);
    при bw = 1 — своим порядком, там — им же."""
    if bw == 1:
        return f.reshape(bh, 2, bw, 2).sum(axis=(1, 3))
    g = f.reshape(bh, 2, bw, 2)
    return (g[:, 0, :, 0] + g[:, 0, :, 1]) + (g[:, 1, :, 0] + g[:, 1, :, 1])


def _рядом_с_плёнкой(плёнка):
    """Пиксели не дальше 2 px от плёнки (маска) — вынесено из `положить_мазок` как было."""
    bh, bw = плёнка.shape
    плотно = обложить(плёнка, 2)
    рядом = np.zeros((bh, bw), dtype=bool)
    for dy, dx in _КРУГ2:
        рядом |= плотно[2 + dy:2 + dy + bh, 2 + dx:2 + dx + bw]
    return рядом


def _сырое_ниже(нижние, взять, сыр_h, Cо):
    """Сырая краска, с которой мазок мешается: своя (сыр_h, цвет Cо) и нижних слоёв, если просили (`мешать_ниже`);
    схватившаяся плёнка подвижна лишь отчасти. Ответ — (толщина, цвет смеси по толщине, [(слой, толщина, сырая,
    цвет)] нижних). Вынесено из `положить_мазок` (Ф-1: функция на потолке строк)."""
    сыр_c, низ = Cо, []
    for нс in нижние:
        hн, wн = взять(нс.толщина), взять(нс.влажность)
        сн = hн * wн * (1.0 - _СХВАТ * взять(нс.схват))
        if сн.max() > 1e-4:
            низ.append((нс, hн, сн, взять(нс.цвет, True)))
    if низ:
        сумма = сыр_h.copy()
        цв = (Cо if Cо is not None else np.zeros(сыр_h.shape + (3,))) * сыр_h[..., None]
        for _, _, сн, cн in низ:
            сумма += сн
            цв += cн * сн[..., None]
        сыр_c = цв / np.maximum(сумма, 1e-9)[..., None]
        сыр_h = сумма
    return сыр_h, сыр_c, низ


def _цвет_без_покрытия(C, A, h, Cо, hо, ц, V, eps):
    """Ф-1: плёнка мутности 0 не кроет (покрытие 0), но лежит краской своего цвета: её подбирает и с ней мешается
    следующий ход. Где покрытия нет, а толщина есть, цвет — смесь лежащей и новой краски по толщине; там, где покрытие
    есть, цвет прежний."""
    пусто = (A <= eps) & (h > eps)
    if not пусто.any():
        return C
    C = C.copy()
    вл = hо[пусто] if Cо is not None else 0.0
    лежит = Cо[пусто] if Cо is not None else 0.0
    C[пусто] = (лежит * np.asarray(вл)[..., None] + ц[пусто] * V[пусто][:, None]) / np.maximum(np.asarray(вл) + V[пусто], eps)[:, None]
    return C


def _на_просвет(п, хол, лок, цвет, толщина, мутность, Cо):
    """П. 10, инструмент 3: не кроющая краска — мутная доля плёнки кроет своим цветом (покрытие), остальная темнит лежащее
    на просвет: и краску своего слоя (Cо — ответ), и то, что под слоем (п — массив пропуска слоя). Сколько — решает
    толщина плёнки в этом месте."""
    Т = пропуск_плёнки(цвет, толщина, мутность)
    п[хол] = п[хол] * Т[лок]
    return None if Cо is None else Cо * Т


def _просвет_за_толщиной(п, хол, лок, было, стало):
    """П. 10, инструмент 3 (3а-2): кисть сняла или разровняла сырую не кроющую краску слоя — её пропуск идёт за толщиной:
    где слой стал тоньше, нижнее светлеет, где толще — темнеет (пропуск — степень толщины, `краска.пропуск_плёнки`)."""
    доля = np.where(было > 1e-6, зажать(стало / np.maximum(было, 1e-6), 0.0, 2.0), 1.0)
    п[хол] = np.power(п[хол], доля[лок][..., None])


def _стекает(V, низ, жидкая=1.0):
    """П. 10, инструмент 3: жидкая (не кроющая) краска после кисти оплывает. Своё (3а-2): за ворсом она смыкается — щель
    в волосок шириной затягивается, борозды собственных волосков выравниваются (чем жиже, тем ровнее), широкие полосы
    хода остаются. Лежащее: с гребней рельефа `низ` стекает в его ямки — в ямке слой толще, на гребне тоньше. Ровняется
    толщина краски, краски столько же; за свой след не течёт."""
    всего = V.sum()
    есть = ((V > 0.0) | (_размыть((V > 0.0) * 1.0) >= 0.5)) * 1.0
    ровно = _размыть(V, Ч._ВИД[5]) / np.maximum(_размыть(есть, Ч._ВИД[5]), 1e-6)
    V = V + (ровно - V) * есть * жидкая
    верх = (низ + V) * есть
    ровно = _размыть(верх, Ч._ВИД[4]) / np.maximum(_размыть(есть, Ч._ВИД[4]), 1e-6)
    V2 = np.maximum(V + (ровно - верх) * есть * (Ч._ВИД[3] * жидкая), 0.0)
    return V2 * (всего / max(V2.sum(), 1e-12))


def _оплыть(V, цвет, низ, жидкая):
    """`_стекает` для плёнки мазка: в затянутую щель краска пришла от соседей — и цвет их (`цвет` правится на месте)."""
    V2 = _стекает(V, низ, жидкая)
    затянуло = (V2 > 0.0) & ~(V > 0.0)
    if затянуло.any():
        цвет[затянуло] = (np.stack([_размыть(цвет[..., i] * V) for i in range(3)], axis=-1)[затянуло]
                          / np.maximum(_размыть(V)[затянуло], 1e-9)[:, None])
    return V2


def _рамка(a, поле=0):
    """К4: срезы наименьшего прямоугольника с маской `a`, раздвинутого на `поле` px (в пределах массива); None — маска пуста."""
    ys, xs = np.flatnonzero(a.any(axis=1)), np.flatnonzero(a.any(axis=0))
    if not len(ys):
        return None
    return (slice(max(int(ys[0]) - поле, 0), int(ys[-1]) + 1 + поле), slice(max(int(xs[0]) - поле, 0), int(xs[-1]) + 1 + поле))


def _круг(a, R):
    """К4: маска `a`, раздвинутая кругом радиуса `R` px (пиксель в ответе, если в круге вокруг него есть пиксель маски).
    За краем — пусто. Считается только вокруг маски: по строке — расстояние до ближнего её пикселя, по столбцу — хорды
    круга."""
    итог = np.zeros(a.shape, dtype=bool)
    Ri = int(R)
    рамка = _рамка(a, Ri)
    if рамка is None:
        return итог
    a = a[рамка]
    H, Wд = a.shape
    далеко = min(Ri + 1, 255)
    if Ri:
        x = np.arange(Wд, dtype=np.int32)
        d = np.minimum(x - np.maximum.accumulate(np.where(a, x, -Wд - Ri - 2), axis=1),
                       np.minimum.accumulate(np.where(a, x, 2 * Wд + Ri + 2)[:, ::-1], axis=1)[:, ::-1] - x)
        d = np.minimum(d, далеко).astype(np.uint8 if Ri < 255 else np.int32)
    else:
        d = np.where(a, 0, 1).astype(np.uint8)
    b = np.full((H + 2 * Ri, Wд), далеко, dtype=d.dtype)
    b[Ri:Ri + H] = d
    часть = итог[рамка]
    for dy in range(-Ri, Ri + 1):
        часть |= b[Ri + dy:Ri + dy + H] <= int((R * R - dy * dy) ** 0.5)
    return итог


def _мениск(плёнка, R):
    """К4: плёнка текучей краски (маска), сомкнутая мениском радиуса `R` px: без плёнки остаётся только то место, куда
    встаёт круг такого радиуса, не задев её. Щель и дыра уже 2R затягиваются целиком; клин между двумя кромками залит до
    вогнутой дуги радиуса R; за общую касательную двух кромок и за наружную кромку краска не идёт."""
    m = int(R) + 1
    рамка = _рамка(плёнка, m)
    итог = np.zeros(плёнка.shape, dtype=bool)
    if рамка is None:
        return итог
    a = обложить(плёнка[рамка], m)
    итог[рамка] = ~_круг(~_круг(a, R), R)[m:-m, m:-m]
    return итог


def _разлить(зерно, где, проходов=64):
    """К4: связные куски маски `где`, в которых есть хоть один пиксель `зерно` (от него весь кусок): проходы по строкам и
    столбцам — отрезок маски, задетый зерном, берётся весь; не больше `проходов` пар проходов."""
    уже = зерно & где
    if not уже.any():
        return уже
    H, Wд = где.shape
    отрезки = []
    for ось in (1, 0):
        нач = np.cumsum(~где, axis=ось, dtype=np.int64)
        нач += (np.arange(H, dtype=np.int64)[:, None] * (Wд + 1)) if ось == 1 else (np.arange(Wд, dtype=np.int64)[None, :] * (H + 1))
        отрезки.append((нач, int(нач.max()) + 1))
    было = int(уже.sum())
    for _ in range(проходов):
        for нач, всего in отрезки:
            уже = где & (np.bincount(нач[уже], minlength=всего) > 0)[нач]
        стало = int(уже.sum())
        if стало == было:
            break
        было = стало
    return уже


def _шов(своя, чужая, след_св, след_ч, W):
    """К4: место между плёнкой своего текучего хода и лежащей сырой текучей плёнкой, которое затягивает краска. Решает не
    пиксель, а шов целиком: вдоль зоны, где обе кромки рядом, краска смыкается, если следы двух кистей (где ворс доставал
    до холста) хоть где-то сошлись вплотную, — от этого места мениск идёт по всему шву и заливает его карманы до ширины
    двух радиусов `_МЕНИСК`; где кромки расходятся клином, залив кончается вогнутой дугой. Шов, где следы не сошлись нигде
    (зазор оставлен рукой), остаётся зазором с кромками, как легли."""
    R = max(Ч._МЕНИСК[0] * W, Ч._МЕНИСК[1])
    обе = своя | чужая
    зона = _круг(своя, R + 1.0) & _круг(чужая, R + 1.0)
    встреча = _круг(след_св | своя, 1.5) & _круг(след_ч | чужая, 1.5)
    if not (встреча & зона).any():
        return None
    шов = _разлить(встреча, зона)
    щель = _мениск(обе, R) & ~обе
    щель = _разлить(шов, щель)                  # карман шва берётся весь, и там, где он отошёл от одной из кромок
    # дыра, замкнутая краской со всех сторон (выемка кромки одного хода против кромки другого), — не клин: наружу она не
    # открыта, краска идёт в неё с обоих берегов на длину выравнивания `_РОВНО`
    дыры = _дыры(обе | щель, max(Ч._РОВНО * W, R))
    if дыры is not None:
        щель |= _разлить(_круг(чужая, 1.5), _разлить(_круг(своя | щель, 1.5), дыры))     # дыра шва: у неё оба берега
    return щель if щель.any() else None


def _дыры(плёнка, R):
    """К4: дыры плёнки текучей краски, замкнутые ею со всех сторон (наружу, к грунту за кромкой, не открыты), — та их
    часть, куда не встаёт круг радиуса `R` px; None — таких нет."""
    фон = ~плёнка
    край = np.zeros_like(фон)
    край[0], край[-1], край[:, 0], край[:, -1] = True, True, True, True
    дыры = фон & ~_разлить(край, фон)
    if not дыры.any():
        return None
    рамка = _рамка(дыры, 2 * (int(R) + 1))        # мениск — только вокруг дыр
    дыры[рамка] &= _мениск(плёнка[рамка], R)
    return дыры if дыры.any() else None


def _сравнять_шов(V2, есть, щель, рядом, чужая, r, W, доля):
    """К4: текучая краска двух берегов расходится по шву до общего уровня. Своя плёнка (`V2`, маска `есть` — уже со швом
    `щель`) и лежащая (`рядом`, маска `чужая`, где её не накрыл свой ход) у шва — один слой: он ровняется теми же тремя
    средними, что своя плёнка, на длине не меньше поперечника мениска (шов такой ширины краска проходит с двух берегов), на
    `доля`. Провала в шве не остаётся: уровень в нём — общий с берегами, берега у шва на столько же ниже; краски в слое
    столько же. Считается только в досягаемости шва — круг в полторы такие длины вокруг него, к краю сила сходит на нет. Ответ: (своя плёнка, сколько отдала лежащая — None, если нисколько)."""
    rш = max(r, int(np.ceil(2.0 * max(Ч._МЕНИСК[0] * W, Ч._МЕНИСК[1]))))
    ш = _рамка(щель, 6 * rш)
    е, V = есть[ш] > 0.0, V2[ш]
    ч = чужая[ш] & ~е
    def трижды(a):
        return _коробка(_коробка(_коробка(a, rш), rш), rш)
    # досюда краска шва дотекает: круг вокруг шва, а не квадрат, и сходит на нет плавно — границы по осям холста нет
    rк = max(1, rш // 2)
    сила = _коробка(_коробка(_коробка(_круг(щель[ш], 1.5 * rш) * 1.0, rк), rк), rк) * (е | ч)
    U = np.where(е, V, рядом[ш] * ч)
    Uн = U + (трижды(U) / np.maximum(трижды((е | ч) * 1.0), 1e-6) - U) * сила * доля
    Uн = Uн - сила * U * ((Uн.sum() - U.sum()) / max((сила * U).sum(), 1e-12))     # краски столько же: остаток — туда же, по той же силе
    Uн = np.maximum(Uн, 0.0)
    V2 = V2.copy()
    V2[ш] = np.where(е, Uн, V)
    ушло = np.zeros(V2.shape)
    ушло[ш] = np.where(ч, U - Uн, 0.0)
    return V2, ушло


def _ровнять(V, цвет, W, доля, тау, рядом=None, ц_рядом=None, трогает=None, след=None, краски=None):
    """П. 15: слой текучей кроющей краски за ворсом ровняется на длине в `_РОВНО` ширины кисти (не меньше 2 px) —
    три средних по квадрату; краски столько же, за свою плёнку она не течёт. Пигмент течёт с ней: цвет сходится к среднему
    по той же длине (`цвет` правится на месте). Дыра в своей плёнке уже `_РОВНО_ЩЕЛЬ` затягивается (`_мениск`). К4: с
    лежащей сырой текучей плёнкой своего слоя (`рядом` — её толщина, `ц_рядом` — цвет, `след` — след текучей кисти в слое,
    `трогает` — след своего ворса) ход смыкается швом целиком (`_шов`) — своя краска затекает в него при выравнивании,
    пигмент в шве — обеих сторон; кромка у грунта — где легла."""
    r = max(2, int(round(Ч._РОВНО * W)))
    своя = V > 0.69 * тау                         # плёнка, что кроет хотя бы наполовину; редкая кайма тоньше лежит как легла
    n = max(2, int(round(Ч._РОВНО_ЩЕЛЬ * W)))       # дыра в своей плёнке не шире этого затягивается; кромка плёнки — где была
    есть = _мениск(своя, 0.5 * n)
    дыры = _дыры(есть, max(Ч._РОВНО * W, Ч._МЕНИСК[1]))       # дыра внутри своей плёнки: краска идёт в неё со всех сторон на длину выравнивания
    if дыры is not None: есть |= дыры
    чужая = ((рядом > 0.69 * тау) & (след > 0.5)) if рядом is not None and след is not None else None   # текучая с текучей: без следа текучей кисти лежащий ход — не берег
    щель = _шов(своя, чужая, трогает > Ч._МЕНИСК[2], след > Ч._МЕНИСК[2], W) if чужая is not None and чужая.any() else None
    if щель is not None:
        есть = есть | щель
        n = max(n, int(np.ceil(max(Ч._МЕНИСК[0] * W, Ч._МЕНИСК[1]))))
    есть = есть * 1.0
    def трижды(a):
        return _коробка(_коробка(_коробка(a, r), r), r)
    вес = np.maximum(трижды(есть), 1e-6)
    V2 = V + (трижды(V * есть) / вес - V) * есть * доля
    V2 = np.where(есть > 0.0, V2 * ((V * есть).sum() / max((V2 * есть).sum(), 1e-12)), V)
    ушло = None
    if щель is not None: V2, ушло = _сравнять_шов(V2, есть, щель, рядом, чужая, r, W, доля)
    if есть.any():
        # краска стекается вместе с пигментом: тон прядей и чужая краска в щели сходятся к общему (в пигментном состоянии);
        # считается только в рамке плёнки и только по ней
        rц = max(r, int(round(Ч._РОВНО_ТОН * W)))      # размешанная с маслом краска одного тона: тон сходится по всей ширине кисти
        рм = _рамка(есть > 0.0, rц)
        где, вес_ц, цв = есть[рм] > 0.0, (V * есть)[рм], цвет[рм]
        if краски is not None:
            _тон_набора(цв, где, вес_ц, V2[рм], краски, rц, r, доля)
        else:
            кс = np.zeros((2 * ПОЛОС,) + где.shape)
            кс[:, где] = (в_кс(цв[где]) * вес_ц[где][:, None]).T
            ц = из_кс(_коробка_цвет(_коробка_цвет(кс, rц), rц)[:, где].T / np.maximum(_коробка(_коробка(вес_ц, rц), rц)[где], 1e-9)[:, None])
            # на месте осталась доля своей краски, остальное притекло с общим тоном: в затянутую дыру (своей краски не было,
            # цвета у пикселя нет) краска приходит со своим пигментом целиком
            осталось = (V[рм][где] * (1.0 - доля))[:, None]
            пришло = np.maximum(V2[рм][где][:, None] - осталось, 0.0)
            цв[где] = (цв[где] * осталось + ц * пришло) / np.maximum(осталось + пришло, 1e-12)
        if щель is not None:
            # в шов краска пришла с обоих берегов: пигмент — своей плёнки и соседней по толщине у берегов (у каждого берега —
            # его краска возле шва, смешиваются два берега пигментом)
            ш = _рамка(щель, n)
            щ, в_с, в_ч, цв = щель[ш], V2[ш] * своя[ш], рядом[ш] * чужая[ш], цвет[ш]
            m_с, m_ч = _коробка(в_с, n)[щ][:, None], _коробка(в_ч, n)[щ][:, None]
            ц_с = _коробка_цвет(np.moveaxis(цв * в_с[..., None], -1, 0), n)[:, щ].T / np.maximum(m_с, 1e-9)
            ц_ч = _коробка_цвет(np.moveaxis(ц_рядом[ш] * в_ч[..., None], -1, 0), n)[:, щ].T / np.maximum(m_ч, 1e-9)
            цв[щ] = из_кс((в_кс(ц_с) * m_с + в_кс(ц_ч) * m_ч) / np.maximum(m_с + m_ч, 1e-9))
    return V2, ушло


def _доли_красок(ц, краски):
    """К7а: доли красок набора в цвете пикселя (N, 3) -> (N, n), в сумме 1. Растр кладёт краски в пиксель в линейном
    цвете, и цвет пикселя — их взвешенная сумма: доли — та смесь красок набора, что ближе всего к цвету пикселя
    (наименьшие квадраты, отрицательных долей нет). Порога «чья краска» нет: пиксель на стыке полос несёт обе."""
    к = np.asarray(краски, np.float64)
    u = (ц - к[-1]) @ np.linalg.pinv((к[:-1] - к[-1]).T).T
    w = np.maximum(np.concatenate([u, 1.0 - u.sum(1, keepdims=True)], axis=1), 0.0)
    return w / w.sum(1, keepdims=True)


def _тон_набора(цв, где, V, V2, краски, rц, r, доля):
    """К7, К7а: пигмент текучей плёнки набора в несколько красок (`цв` правится на месте; `где` — плёнка, `V` — краска до
    выравнивания, `V2` — после). Плёнка ровняет толщину, а пигмент идёт только с краской. Пиксель несёт доли красок набора
    (`_доли_красок`), и краска каждой полосы размешана с маслом сама по себе: её тон (отличие от набранного цвета) сходится
    к общему на длине `rц` по её же краске, доли в пикселе — как легли. Что лежало, лежит на месте; в борозду и щель
    (`V2` > `V`) притекает излишек соседей (`V` > `V2`) со своими долями красок: он расходится по плёнке кругами (три средних
    подряд, радиус от шага к шагу вдвое больше, в сумме не дальше длины выравнивания `r`), и место, куда краска прибывает, берёт её из дошедшего — ближний
    берег успевает первым. На стыке полос сходятся обе краски и мешаются пигментом."""
    есть, n, к = где & (V > 0.0), len(краски), np.asarray(краски, np.float64)
    w = np.zeros((n,) + где.shape)
    w[:, есть] = _доли_красок(цв[есть], к).T
    δ = np.zeros(цв.shape)
    δ[есть] = цв[есть] - w[:, есть].T @ к
    a = np.zeros((4 * n,) + где.shape)                 # на краску: её тон на её толщину (3) и толщина
    for q in range(n):
        a[4 * q:4 * q + 3], a[4 * q + 3] = np.moveaxis(δ, -1, 0) * (w[q] * V), w[q] * V
    b = _коробка_цвет(_коробка_цвет(a, rц), rц)
    def тон(q, м):
        return к[q] + (b[4 * q:4 * q + 3, м] / np.maximum(b[4 * q + 3, м], 1e-12)).T
    свой = np.zeros(цв.shape)
    свой[есть] = цв[есть] - δ[есть] * доля + sum((тон(q, есть) - к[q]) * w[q][есть][:, None] for q in range(n)) * доля
    осталось, пришло = np.minimum(V, V2) * есть, np.maximum(V2 - V * есть, 0.0) * где
    излишек, ждёт, дошло = w * (np.maximum(V - V2, 0.0) * есть), пришло.copy(), np.zeros(w.shape)
    путь2, ρ = 0.0, 1
    while True:
        путь2 += ρ * (ρ + 1.0)                          # три средних радиуса ρ разносят краску на √(ρ(ρ+1)) px; шаги складываются квадратами
        if ждёт.max() <= 1e-12 or путь2 > max(r * r, 2.0): break
        излишек = _коробка_цвет(_коробка_цвет(_коробка_цвет(излишек, ρ), ρ), ρ) * где
        всего = излишек.sum(0)
        взято = np.minimum(ждёт, всего) / np.maximum(всего, 1e-300)
        дошло += излишек * взято
        излишек *= 1.0 - взято
        ждёт -= взято * всего
        ρ *= 2
    дошло += w * ждёт                                   # чего излишек соседей не покрыл — своя же краска этого места
    ждёт = ждёт * ~есть                                 # голое место дальше длины выравнивания: краска та, что дошла, а нет её — та, что вокруг на длине тона
    if (ждёт > 1e-12).any():
        вокруг = np.where(дошло.sum(0) > 0.0, дошло, b[3::4])
        дошло += вокруг / np.maximum(вокруг.sum(0), 1e-300) * ждёт
    пришло = дошло.sum(0)
    цв[есть] = свой[есть]
    м = где & (пришло > 0.0)                           # пигментом мешается только то место, куда краска пришла
    кс = в_кс(зажать(свой[м], 0.0, 1.0)) * осталось[м][:, None]
    for q in range(n):
        кс += в_кс(зажать(тон(q, м), 0.0, 1.0)) * дошло[q][м][:, None]
    цв[м] = из_кс(кс / (осталось + пришло)[м][:, None])


def _коробка_цвет(a, r):
    """`_коробка` для поля (каналы, H, W) — все каналы разом, те же числа."""
    k = 2 * r + 1
    C, H, Wд = a.shape
    b = np.zeros((C, H + k, Wд))
    b[:, r + 1:r + 1 + H] = a
    c = np.cumsum(b, axis=1)
    a = (c[:, k:] - c[:, :-k]) / k
    b = np.zeros((C, H, Wд + k))
    b[:, :, r + 1:r + 1 + Wд] = a
    c = np.cumsum(b, axis=2)
    return (c[:, :, k:] - c[:, :, :-k]) / k


def _рельеф_плёнки(V, густо, бор):
    """Жидкая краска оплывает (п. 5): мелкий рельеф борозд после кисти сглаживается, густая держит гребень. Оплывает масло,
    а не пигмент (5в): рельеф ровнее, а просвет нижнего слоя на дне борозды и её тон — как легли. За кромку следа краска
    не течёт: сглаживание идёт только по закрашенному."""
    if not (густо < _БОР_РАСТЁК[1] and бор is not None):
        return V
    есть_V = (V > 0.0) * 1.0
    return V + (_размыть(V, 2) / np.maximum(_размыть(есть_V, 2), 1e-6) - V) * есть_V * (_БОР_РАСТЁК[0] * (1.0 - густо / _БОР_РАСТЁК[1]))


def _склон_кромки(есть, разбавитель):
    """v4, 5в: доля толщины плёнки у её края (маска `есть`) — smoothstep по расстоянию до края внутрь плёнки на длине
    `Ч._КРОМКА_ММ` в мм; None — склон короче пикселя или края нет."""
    м = float(разбавитель or 0.0)
    L = (Ч._КРОМКА_ММ[0] + (Ч._КРОМКА_ММ[1] - Ч._КРОМКА_ММ[0]) * м ** Ч._КРОМКА_ММ[2]) * 8.0 * Ч._ММ
    if L <= 1.0 + 1e-9 or not есть.any() or есть.all():
        return None
    from scipy.ndimage import distance_transform_edt
    t = зажать((distance_transform_edt(есть) - 0.5) / L, 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def _кромка(V_р, разбавитель, недолив=None):
    """v4, 5в: край плёнки хода — не обрыв в пиксель: рельеф плёнки у края спадает к нулю на длине `Ч._КРОМКА_ММ` в мм
    (густая — резко, жидкая — мягко, по разбавителю), smoothstep по расстоянию до края внутрь плёнки: ступенька высотой с
    плёнку становится склоном той же высоты. Масло края уходит в ход, за кромку не течёт; пигмент (цвет и покрытие)
    лежит как лёг. v4, 5д: и по сырой краске своего слоя — тем же склоном (`_срослась` обрыв в 1 px не снимала: светлая
    нить по контуру каждого хода с разбавителем, `проверка/ДИАГНОЗ_гребни_свода.md`). v4, 5д-2: по сырой склоном спадает
    только то, что встаёт над прежней поверхностью: `недолив` — сколько сырой краски под ходом убыло (снято кистью,
    вытеснено, ушло в шов); столько плёнка доливает в уровень без склона — иначе у края по сырому ложбина, и жидкая
    заливка рядами шьёт каждый ряд швом. По сухому `недолив` 0 — как в 5в. Короче пикселя — как было."""
    склон = _склон_кромки(V_р > 0.0, разбавитель)
    if склон is None:
        return V_р
    V2 = V_р * склон
    return V2 if недолив is None else V2 + (V_р - V2) * зажать(недолив / np.maximum(V_р, 1e-9), 0.0, 1.0)


def _вмешать(V, вмешано, ц_нов, Cо, eps):
    """Плёнка хода с вмешанной на месте лежащей сырой краской: (толщина, что красит, её цвет) — вынесено из
    `положить_мазок` как было (5в)."""
    M = V if вмешано is None else V + вмешано
    ц_верх = ц_нов
    if вмешано is not None:
        смесь = вмешано > 1e-5
        if смесь.any():
            ц_верх = ц_нов.copy()
            доля_нов = V[смесь] / (M[смесь] + eps)
            ц_верх[смесь] = из_кс(в_кс(Cо[смесь]) * (1.0 - доля_нов)[:, None] + в_кс(ц_нов[смесь]) * доля_нов[:, None])
    return M, ц_верх


def _текучая(V, цвет, W, ровно, тау, низ, рядом=None, ц_рядом=None, трогает=None, след=None, краски=None):
    """П. 15, поле мазка `ровно`: текучая кроющая краска (набрана густо, с маслом) за ворсом смыкается в ровный слой —
    щели и борозды своих волосков и полосы прядей затягиваются краской соседей (`_ровнять`); за свою плёнку не течёт —
    край как лёг. Рельеф слоёв под своим (`низ` — та его доля, что видна сквозь верхний слой, борозды подмалёвка) она
    заливает: в ямке слой толще, на гребне тоньше. Ответ: (пигмент плёнки, её рельеф)."""
    (V, ушло), V_р = _ровнять(V, цвет, W, ровно, тау, рядом, ц_рядом, трогает, след, краски), None
    V_р = V
    if np.ndim(низ):
        есть = (V > 0.0) * 1.0
        V_р = np.maximum(V - (низ - _размыть(низ * есть, 6) / np.maximum(_размыть(есть, 6), 1e-6)) * есть * ровно, 0.3 * V)
    return V, V_р, ушло


def _сомкнуть(V_р, низ, сух, текуче, разбавитель=0.0):
    """Ф-2: текучая плёнка хода (`V_р` — её рельеф) по сухой лежащей краске затекает в низины её рельефа: `низ` —
    поверхность под плёнкой (лежащая краска своего слоя и слоёв ниже), её никто не трогает. Течёт сама плёнка: от места,
    где её верх (`низ` + плёнка) выше, к соседу, где он ниже, — и тем охотнее, чем она толще (`_СМЫК[0]`, куб): плёнка в
    волосок держится за рельеф, толстая расходится в уровень. Отдаёт место только то, что на нём есть: с гребня выше
    плёнки она сходит вся, и гребень стоит как стоял — толстый мазок рельеф держит, рябь мелкого письма тонет. Краски
    столько же, за свой след не течёт; склон края плёнки (`_кромка`, по разбавителю) — её равновесная форма: к краю
    плёнка не стекает и стенкой у него не встаёт. `сух` — доля сухого в лежащем под плёнкой (по сырому своего слоя — как
    было); `текуче` — 0–1 (`ровно`, разбавитель): столько времени у плёнки до схватывания. Пигмент (цвет, покрытие)
    лежит как лёг."""
    V0, шагов, dt, степень, потолок = Ч._СМЫК
    n = int(min(np.ceil(шагов * float(текуче) * Ч._ММ ** 2), потолок))
    есть = V_р > 0.0
    рамка = _рамка(есть & (сух > 0.0), 2)
    if n <= 0 or рамка is None:
        return V_р
    склон = _склон_кромки(есть, разбавитель)
    V, b, м = V_р[рамка].copy(), низ[рамка], есть[рамка]
    e = None if склон is None else np.maximum(склон[рамка], 0.05)
    по_x, по_y = м[:, 1:] & м[:, :-1], м[1:] & м[:-1]      # течёт только по своему следу
    for _ in range(n):
        s = b + V if e is None else b + V / e              # верх плёнки, как если бы склона края не было
        подв = np.minimum(V / V0, 1.0) ** степень * dt
        if e is not None: подв = подв * e
        dx, dy = (s[:, :-1] - s[:, 1:]) * по_x, (s[:-1] - s[1:]) * по_y      # > 0 — течёт вправо, вниз
        вправо, влево = np.maximum(dx, 0.0) * подв[:, :-1], np.maximum(-dx, 0.0) * подв[:, 1:]
        вниз, вверх = np.maximum(dy, 0.0) * подв[:-1], np.maximum(-dy, 0.0) * подв[1:]
        ушло = np.zeros_like(V)
        ушло[:, :-1] += вправо; ушло[:, 1:] += влево; ушло[:-1] += вниз; ушло[1:] += вверх
        доля = np.minimum(V / np.maximum(ушло, 1e-12), 1.0)                 # больше, чем есть, место не отдаёт
        вправо, влево, вниз, вверх = вправо * доля[:, :-1], влево * доля[:, 1:], вниз * доля[:-1], вверх * доля[1:]
        V[:, :-1] += влево - вправо; V[:, 1:] += вправо - влево
        V[:-1] += вверх - вниз; V[1:] += вниз - вверх
    итог = V_р.copy()
    итог[рамка] = V_р[рамка] + (np.maximum(V, 0.0) - V_р[рамка]) * зажать(сух[рамка], 0.0, 1.0)
    return итог * (V_р.sum() / max(float(итог.sum()), 1e-12))


def _след_текучей(слой, хол, ровно, след, альфа):
    """К4: след текучей кисти в слое (`Слой.текучая`) — по нему следующий текучий ход найдёт этот: где ворс хода с `ровно`
    доставал до холста и где легла его краска. Не текучая краска, легшая поверх, след стирает на своё покрытие."""
    if ровно:
        if слой.текучая is None: слой.текучая = np.zeros(слой.толщина.shape, np.float32) if isinstance(слой.толщина, np.ndarray) else Плитки(слой.толщина.shape)
        слой.текучая[хол] = np.maximum(слой.текучая[хол], след)
    else:
        слой.текучая[хол] = слой.текучая[хол] * (1.0 - альфа)


def _срослась(h, w, V, ровно):
    """П. 15: с лежащей рядом сырой краской своего слоя текучая срастается — ступенька на шве двух ходов оплывает."""
    шов = (_размыть((V > 0.0) * 1.0, Ч._РОВНО_ШОВ) > 0.02) * (h > 1e-9) * зажать(w * 2.0 - 1.0, 0.0, 1.0)
    return h + (_размыть(h * шов, Ч._РОВНО_ШОВ) / np.maximum(_размыть(шов, Ч._РОВНО_ШОВ), 1e-6) - h) * шов * ровно


def _кроет(M, тау, мутность):
    """П. 10, инструмент 3: толщина, которой не кроющая плёнка кроет своим цветом, — её мутная доля; в плёнке тоньше
    кроющей толщины `тау` она кроет слабее своей доли: зёрна пигмента в один слой не смыкаются; в толстом месте (комок
    сухой кисти, пастозный слой) смыкаются, и краска кроет (3а-2)."""
    return M * мутность * зажать(M / тау, 0.0, 1.0) ** (Ч._ВИД[6] * (1.0 - мутность))


