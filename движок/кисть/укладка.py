        m = зажать(m * круть, 0.0, 1.0) if рвёт is None else рвёт.гребень(c, m, рвётся, капля / полная)   # п. 5б: гребень кладёт на бугорки нитей под собой
        if жилка is not None:
            m = m * обрыв[c]                                  # запас полосы кончился или прядь сорвалась
        if край_рвёт is not None:
            m = m * край_рвёт[c]
