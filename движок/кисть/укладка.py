    if перед_записью is not None: перед_записью((cx0, cy0, cx1, cy1))     # 11б: снимок холста копирует, что тут лежит

    def взять(массив, трёх=False):
        a = np.zeros((bh, bw, 3) if трёх else (bh, bw))
