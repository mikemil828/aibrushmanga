    неровн, густота = М.запас(мяг, *неровный_запас(с, к, rng, Nc, шаг_к, W, мастихин, _сухая(к, нагрузка)))       # запас гребней вдоль хода (`борозда.py`); 4а-2: у мягкого волоса комок запаса — на нескольких соседних волосках
