def _размыть(a, раз=1):
    """Размытие [1 2 1]/4 по обеим осям, раз проходов. За краем — ноль."""
    for _ in range(раз):
        b = a * 0.5
        b[1:] += a[:-1] * 0.25
        b[:-1] += a[1:] * 0.25
        a = b * 0.5
        a[:, 1:] += b[:, :-1] * 0.25
        a[:, :-1] += b[:, 1:] * 0.25
    return a


def _коробка(a, r):
    """Среднее по квадрату (2r+1)^2 через накопленные суммы. За краем — ноль."""
    k = 2 * r + 1
    c = np.cumsum(обложить(a, ((r + 1, r), (0, 0))), axis=0)
    a = (c[k:] - c[:-k]) / k
    c = np.cumsum(обложить(a, ((0, 0), (r + 1, r))), axis=1)
    return (c[:, k:] - c[:, :-k]) / k


