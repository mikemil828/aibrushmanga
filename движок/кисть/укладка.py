    к._набрано = 0.0 if чистая else float(((Hг * запас_px * заряд0 + Hг * лямбда * Ч.ноша_у_края(от_края)) * 2.0 * с.полуш).sum()); М.Обмен.запомнить(обмен, к, с.центр / W, кс_капли); М.Обмен.баланс(обмен, к, Hг * запас_px, заряд0, заряд, Hг * лямбда * Ч.ноша_у_края(от_края), 2.0 * с.полуш)   # 4в-4: баланс краски кисти

