def _зазор(p):
    """Множитель зазора под кромкой от нажима (N,): 1 при `_НОЖ[2]`, 0 при нажиме 1, не больше `_НОЖ[3]`."""
    return зажать((np.maximum(1.0 - p, 0.0) / (1.0 - Ч._НОЖ[2])) ** 1.2, 0.0, Ч._НОЖ[3])


def _ступень(a):
    a = зажать(a, 0.0, 1.0)
    return a * a * (3.0 - 2.0 * a)


def _откос(об, x, y, nx, ny, уклон, bw, bh, поля, предел):
    """Краска, выдавленная за кромку, встаёт откосом: объём `об` (n,) из точки (x, y) в сторону (nx, ny) ложится
    треугольником длиной sqrt(2·об/уклон) (сечение на 1 px кромки; не длиннее `предел` px — рамка мазка), выборками через 0,5 px. `поля` — (n, k) величины
    на единицу объёма. Ответ: поле объёма (bh, bw) и поля величин × объём (bh, bw, k)."""
    V, E = np.zeros(bh * bw), np.zeros((bh * bw, поля.shape[1]))
    есть = об > 1e-12
    if not есть.any():
        return V.reshape(bh, bw), E.reshape(bh, bw, -1)
    об, x, y, nx, ny, поля = об[есть], x[есть], y[есть], nx[есть], ny[есть], поля[есть]
    длина = зажать(np.sqrt(2.0 * об / уклон), 1.0, max(предел, 1.0))
    K = int(np.ceil(float(длина.max()) / 0.5)) + 1
    r = (np.arange(K) + 0.5) * 0.5
    вес = np.maximum(1.0 - r[None, :] / длина[:, None], 0.0)
    вес = вес / np.maximum(вес.sum(axis=1, keepdims=True), 1e-12) * об[:, None]
    ix = np.floor(x[:, None] + nx[:, None] * r[None, :]).astype(np.intp)
    iy = np.floor(y[:, None] + ny[:, None] * r[None, :]).astype(np.intp)
    ок = (ix >= 0) & (ix < bw) & (iy >= 0) & (iy < bh) & (вес > 0.0)
    q = (iy * bw + ix)[ок]
    V += np.bincount(q, weights=вес[ок], minlength=bh * bw)
    for k in range(поля.shape[1]):
        E[:, k] += np.bincount(q, weights=(вес * поля[:, k:k + 1])[ок], minlength=bh * bw)
    return V.reshape(bh, bw), E.reshape(bh, bw, -1)


def _сгладить(a):
    """[1 2 1]/4 по обеим осям, объём тот же (за край рамки не уходит)."""
    for ось in (0, 1):
        b = 0.5 * a
        с = [slice(None)] * a.ndim
        л, п = list(с), list(с)
        л[ось], п[ось] = slice(1, None), slice(None, -1)
        b[tuple(л)] += 0.25 * a[tuple(п)]
        b[tuple(п)] += 0.25 * a[tuple(л)]
        к0, к1 = list(с), list(с)
        к0[ось], к1[ось] = slice(0, 1), slice(-1, None)
        b[tuple(к0)] += 0.25 * a[tuple(к0)]
        b[tuple(к1)] += 0.25 * a[tuple(к1)]
        a = b
    return a


def ход_ножа(путь, W, H, чистая, мт, краски, касание, твёрдое_низ, hо, wо, схо, Cо, рамка, ширин=5.0, поле=7.0):
    """Ход ножа в рамке мазка — `_ход` (доводы и ответ — там). Рамка мазка обрезана у края холста (`_ЗА_КРАЕМ`), а нож
    тратит краску и несёт вал и там, где шёл за ней: счёт идёт в рамке всего следа (за рамкой мазка — голый гладкий
    грунт), ответ — вырезка рамки мазка. Так ход от края холста тот же, что на большом холсте. След длиннее `_НОЖ[18]`
    площадей рамки (и 4 млн px) считается в рамке мазка как есть."""
    bx0, by0, bw, bh = рамка
    x, y = путь['x'], путь['y']
    r = W / 2 + поле + 2.0
    vx0, vy0 = min(bx0, int(np.floor(x.min() - r))), min(by0, int(np.floor(y.min() - r)))
    vx1, vy1 = max(bx0 + bw, int(np.ceil(x.max() + r)) + 1), max(by0 + bh, int(np.ceil(y.max() + r)) + 1)
    vw, vh = vx1 - vx0, vy1 - vy0
    if (vw, vh) == (bw, bh) or (vw * vh > Ч._НОЖ[18] * bw * bh and vw * vh > 4_000_000):
        return _ход(путь, W, H, чистая, мт, краски, касание, твёрдое_низ, hо, wо, схо, Cо, рамка, ширин, поле)
    вырез = (slice(by0 - vy0, by0 - vy0 + bh), slice(bx0 - vx0, bx0 - vx0 + bw))

    def шире(a):
        if a is None:
            return None
        b = np.zeros((vh, vw) + a.shape[2:])
        b[вырез] = a
        return b

    р = _ход(путь, W, H, чистая, мт, краски, касание, шире(твёрдое_низ), шире(hо), шире(wо), шире(схо), шире(Cо), (vx0, vy0, vw, vh), ширин, поле)
    if р is None:
        return None
    return {k: (v[вырез] if isinstance(v, np.ndarray) else v) for k, v in р.items()}


def _ход(путь, W, H, чистая, мт, краски, касание, твёрдое_низ, hо, wо, схо, Cо, рамка, ширин=5.0, поле=7.0):
    """Ход ножа в рамке мазка (bx0, by0, bw, bh). путь — `путь._путь`; H — толщина плёнки ножа (h), чистая — нож без
    краски; мт — масштаб толщины; краски — [(линейный RGB, доля)]; касание — 1 плашмя, 0 ребро; ширин — на сколько ширин ножа набрано краски (`Кисть.запас`); поле — дальше стольких px от кромки валик и ком не идут; твёрдое_низ (bh, bw) —
    зерно грунта и слои ниже; hо, wо, схо (bh, bw), Cо (bh, bw, 3) или None — лежащая краска своего слоя.

    Ответ — None (нож холста не коснулся) или словарь: `h`, `w`, `сх` — лежащая краска после среза (до новой);
    `V`, `ц`, `wV`, `схV` — что легло из вала (толщина, цвет, влажность, схват); `мешано` — доля цвета вала в
    оставшейся плёнке и `ц_мешано` — его цвет; `касание` (bh, bw) — где шла кромка; `снято` — объём, срезанный с
    места; `на_ноже` — объём, ушедший с холста на нож; `сырое` — подвижная краска до хода."""
    bx0, by0, bw, bh = рамка
    Н = Ч._НОЖ
    мм = Ч._ММ
    x, y, p, угол, N = путь['x'], путь['y'], путь['p'], путь['угол'], путь['N']
    ax, ay, tx, ty = -np.sin(угол), np.cos(угол), np.cos(угол), np.sin(угол)
    плашмя = float(зажать(1.0 if касание is None else касание, 0.0, 1.0))
    Wэ = max(W * плашмя + Н[14] * 8.0 * мм * (1.0 - плашмя), 1.0)
    nb = max(1, int(round(Wэ)))
    шир = Wэ / nb
    # --- какой пиксель когда и каким местом кромки пройден (первое касание)
    nu = max(2, int(np.ceil(Wэ / 0.5)))
    uu = (np.arange(nu) + 0.5) * (Wэ / nu) - Wэ / 2
    ix = np.floor(x[:, None] + uu[None, :] * ax[:, None] - bx0).astype(np.intp)
    iy = np.floor(y[:, None] + uu[None, :] * ay[:, None] - by0).astype(np.intp)
    ок = (ix >= 0) & (ix < bw) & (iy >= 0) & (iy < bh) & (p >= Н[7])[:, None]
    if not ок.any():
        return None
    q = (iy * bw + ix)[ок]
    шаг = np.broadcast_to(np.arange(N)[:, None], (N, nu))[ок]
    первый = np.full(bh * bw, N, dtype=np.intp)
    np.minimum.at(первый, q, шаг)
    пикс = np.nonzero(первый < N)[0]
    ряд_п = первый[пикс] // 2
    порядок = np.argsort(ряд_п, kind='stable')
    пикс, ряд_п = пикс[порядок], ряд_п[порядок]
    mп = первый[пикс]                                           # доля пикселя под кромкой: у бока хода — часть (по месту его центра поперёк кромки)
    u_ц = (пикс % bw + 0.5 + bx0 - x[mп]) * ax[mп] + (пикс // bw + 0.5 + by0 - y[mп]) * ay[mп]
    покрыт = зажать(Wэ / 2 - np.abs(u_ц) + 0.5, 0.0, 1.0)
    место = зажать(np.floor((u_ц + Wэ / 2) / шир).astype(np.intp), 0, nb - 1)
    ряды, начала = np.unique(ряд_п, return_index=True)
    концы = np.append(начала[1:], len(пикс))
    n = len(пикс)

    # --- твёрдое и сырое
    w_подв = (wо * (1.0 - _СХВАТ * зажать(схо, 0.0, 1.0))).ravel()
    h_пл, w_пл, сх_пл = hо.ravel(), wо.ravel(), зажать(схо, 0.0, 1.0).ravel()
    сырое_поле = h_пл * w_подв
    T = (твёрдое_низ.ravel() + h_пл - сырое_поле)[пикс]
    сыр = сырое_поле[пикс]
    есть_сырое = bool(сыр.max() > 1e-4) if n else False
    if чистая and not есть_сырое:
        return None
    K = 2 * ПОЛОС
    кс_леж = в_кс(Cо.reshape(-1, 3)[пикс]) if Cо is not None else np.zeros((n, K))
    w_леж, сх_леж = w_пл[пикс], сх_пл[пикс]

    # --- нож: зазор, запас, вал
    Hэ = Н[0] * мт if чистая else H
    след = Н[1] * мт
    вал_полный = Н[8] * Hэ * (8.0 * мм * Н[15]) * шир          # объём вала на место кромки: плёнка в `_НОЖ[8]` толщин на длине `_НОЖ[15]` мм
    длина_вала = 8.0 * мм * Н[15]
    E = np.zeros((nb, K + 3))                                 # вал: объём, влажность·объём, схват·объём, К-М·объём
    запас = np.zeros(nb)
    кс_запаса = np.zeros((nb, K))
    запас0 = max(float(H * float(Н[16]) * float(ширин) * W * шир), 1e-12)
    горка = np.ones(nb)                                       # краска на ноже — горкой: к бокам кромки её меньше
    if not чистая:
        t_к = (np.arange(nb) + 0.5) / nb * 2.0 - 1.0
        горка = 1.0 - Н[20] * плашмя * t_к * t_к             # на ребре горки нет: краска — на самом ребре
        горка /= горка.mean()
        запас[:] = запас0 * горка
        доли = np.array([max(float(д), 0.0) for _, д in краски], dtype=np.float64)
        граница = np.cumsum(доли / max(доли.sum(), 1e-12))
        чья = np.minimum(np.searchsorted(граница, (np.arange(nb) + 0.5) / nb), len(краски) - 1)
        кс_запаса = np.stack([в_кс(np.asarray(c, dtype=np.float64)[None, :])[0] for c, _ in краски])[чья]
    уклон = Н[13] * мт / мм
    досяг_нажим = Н[4] * мт * зажать((p - Н[5]) / (1.0 - Н[5]) / 0.857, 0.0, 1.0) ** 2   # 0,857: полный досяг — при нажиме 0,9
    на_плоскость = _ступень((p - Н[9]) / 0.1)
    контакт = _ступень(p / 0.1)                                # едва касаясь, нож кладёт и срезает долей
    зазор = Hэ * _зазор(p)                                     # под кромкой — плёнка ножа; срезая сырое, нож оставляет ещё и след

    срезано = np.zeros(n)
    легло = np.zeros(n)
    кс_легло = np.zeros((n, K))
    w_легло, сх_легло = np.zeros(n), np.zeros(n)
    мешано = np.zeros(n)
    кс_мешано = np.zeros((n, K))
    на_ноже = 0.0
    nR = int(ряды[-1]) + 1
    бок = np.zeros((2, nR, 6))                                # валик у концов кромки: объём, w·объём, сх·объём, RGB·объём
    взято_запаса = 0.0
    села_посл = np.zeros(nb)
    бусина, доля_бусины, брошен = np.zeros((2, 6)), 1.0 / max(Н[25] * 8.0 * мм, 1.0), np.zeros(nb, dtype=bool)
    стоял = np.ones((len(ряды), nb), dtype=bool)             # где вал ножа с краской доставал до холста: там нож холста и касался
    выгиб = np.zeros(nb) if чистая else Н[27] * Hэ * плашмя * зажать((np.abs(t_к) - Н[28]) / (1.0 - Н[28]), 0.0, 1.0) ** 2
    комья = []                                               # (шаг пути, вал мест кромки, оставленный там комом)
    п0 = 0.0 if чистая else Н[21] * Н[3] / (Н[8] * float(горка.max()))   # ненажатый нож: горка стоит под лезвием сама и вершиной как раз достаёт до холста
    сход_б = [[], []]                                        # (ряд, комок 6), оставленный у бока целиком
    B_пред = Н[30] * Hэ * (8.0 * мм) ** 2                    # комок у бока, который ещё держит бок лезвия
    Tв = None if чистая else твёрдое_низ.ravel() + h_пл - сырое_поле     # твёрдое: об него за краем краски стирается комок у бока
    край_u = np.full((2, nR), np.nan)                        # где поперёк кромки шёл край краски под ножом (нож с краской)
    края = None
    # опора: нож лежит на вершинах твёрдого не только вдоль кромки, но и подошвой по ходу (`_НОЖ[17]` мм) — в борозду
    # поперёк хода кромка не проваливается
    z_ряд = np.empty(len(ряды))
    for n_р, (i0, i1) in enumerate(zip(начала, концы)):
        Tb = T[i0:i1]
        k = max(1, int(0.15 * len(Tb)))
        z_ряд[n_р] = float(np.partition(Tb, len(Tb) - k)[len(Tb) - k:].mean())
    полподошвы = max(1, int(round(0.5 * Н[17] * 8.0 * мм)))
    z_опора = z_ряд.copy()
    for сдвиг in range(1, полподошвы + 1):
        z_опора[сдвиг:] = np.maximum(z_опора[сдвиг:], z_ряд[:-сдвиг])
        z_опора[:-сдвиг] = np.maximum(z_опора[:-сдвиг], z_ряд[сдвиг:])
    if len(z_опора) > 2:                                        # на опору нож всходит и сходит с неё полого — на той же длине
        ядро = np.ones(2 * полподошвы + 1) / (2 * полподошвы + 1)
        z_опора = np.convolve(np.pad(z_опора, полподошвы, mode='edge'), ядро, mode='valid')
    n_р = -1
    for b, i0, i1 in zip(ряды, начала, концы):
        m = min(2 * int(b), N - 1)
        j = место[i0:i1]
        pb = float(p[m])
        прижат = плашмя * max(min(pb / Н[24], 1.0), п0 * (1.0 + min(pb / Н[24], 1.0))) + (1.0 - плашмя)                 # слабым нажимом горка краски до холста не дожата: касается её середина
        if not чистая:                                        # запас ножа кормит вал
            ур = зажать(запас / (Н[19] * запас0 * горка), 0.0, 1.0) ** 0.7   # место кромки, где краска на ноже кончается, держит вал тоньше — не обрывом
            достал_бы = (Н[8] * Hэ * горка * ур) * прижат >= Н[21] * (зазор[m] + выгиб * (1.0 - pb))   # вал встаёт там, где полный он до холста дожат
            стоял[n_р + 1] = достал_бы | (села_посл > 0.2)
            ия = np.nonzero(стоял[n_р + 1])[0]                # край краски под ножом — крайние места кромки, чей вал стоит на холсте
            края = (int(ия[0]), int(ия[-1])) if len(ия) else None
            надо = np.minimum(np.maximum(вал_полный * горка * ур - E[:, 0], 0.0), запас) * (достал_бы | (села_посл > 0.2))   # вал, что уже стоит на холсте, кормится, пока нож его не бросил
            if надо.any():
                запас -= надо
                E[:, 0] += надо
                E[:, 1] += надо
                E[:, 3:] += кс_запаса * надо[:, None]
                взято_запаса += float(надо.sum())
        Tb, sb = T[i0:i1], сыр[i0:i1]
        села = np.zeros(nb)
        n_р += 1
        z0 = float(z_опора[n_р])
        Tм = np.full(nb, -np.inf)
        np.maximum.at(Tм, j, Tb)
        if nb > 2:
            Tм = np.maximum(Tм, np.maximum(np.concatenate([Tм[1:], Tм[-1:]]), np.concatenate([Tм[:1], Tм[:-1]])))
        сыт = np.ones(nb) if чистая else np.full(nb, float(зажать(запас.sum() / (Н[19] * запас0 * nb), 0.0, 1.0)) ** 0.7)    # пустеющий нож кладёт тоньше: зазор держит краска на ноже
        зазор_р = (зазор[m] + выгиб * (1.0 - pb)) * сыт       # лезвие к концам кромки отогнуто от холста; нажим его распрямляет
        кромка = (np.maximum(Tм, z0 - Н[6] * мт * pb) + зазор_р)[j]
        # срез сырого выше кромки
        доля_п = покрыт[i0:i1] * контакт[m]
        лишнее = зажать(Tb + sb - кромка - след, 0.0, sb) * доля_п
        if лишнее.any():
            срезано[i0:i1] = лишнее
            в_вал = лишнее * (1.0 - на_плоскость[m])
            на_ноже += float((лишнее - в_вал).sum())
            sb = sb - лишнее
            if в_вал.any():
                np.add.at(E, j, np.concatenate([в_вал[:, None], (в_вал * w_леж[i0:i1])[:, None], (в_вал * сх_леж[i0:i1])[:, None],
                                                кс_леж[i0:i1] * в_вал[:, None]], axis=1))
        об = E[:, 0]
        есть_вал = об > 1e-12
        цв_вала = E[:, 3:] / np.where(есть_вал, об, 1.0)[:, None]
        # оставшаяся под кромкой сырая плёнка мешается с валом (объём у обоих тот же)
        if есть_вал.any() and sb.any():
            доля = Н[12] * зажать(об / max(вал_полный, 1e-12), 0.0, 1.0)[j] * контакт[m] * (sb > 1e-9)
            обмен = доля * np.minimum(sb, об[j] / np.maximum(np.bincount(j, minlength=nb)[j], 1))
            if обмен.any():
                мешано[i0:i1] = обмен / np.maximum(h_пл[пикс[i0:i1]] - лишнее, 1e-12)
                кс_мешано[i0:i1] = цв_вала[j]
                np.add.at(E, (j, slice(3, None)), (кс_леж[i0:i1] - цв_вала[j]) * обмен[:, None])
                цв_вала = E[:, 3:] / np.where(есть_вал, об, 1.0)[:, None]
        # вал ложится в пустое под кромкой — не глубже досяга
        глубина = кромка - Tb - sb
        досяг = (зазор_р + досяг_нажим[m])[j]
        просят = np.maximum(глубина, 0.0) * зажать(1.0 - (глубина - досяг) / max(0.2 * зазор[m], 1e-9), 0.0, 1.0) * доля_п   # глубже досяга краска с кромки до дна не достаёт: низина пуста
        if просят.any() and есть_вал.any():
            плёнка = (об * min(1.0 / (длина_вала * шир), 1.0))[j]   # краска вала у этого места — плёнкой на длине вала
            кладёт = np.minimum(просят, плёнка * доля_п)       # с вала на px холста сходит не больше его доли: пустеющий нож кладёт тоньше, а не обрывом
            if not чистая:
                # краска садится там, где вал достаёт до холста: тонкий вал касается только вершин (зазор над ними
                # мал), над низиной висит — край пустеющего ножа рвётся по зерну, а не бледнеет ровной полосой
                кладёт = кладёт * _ступень((плёнка / np.maximum(глубина, 1e-12) - Н[21]) / (1.0 - Н[21])) * (достал_бы | (села_посл > 0.2))[j]
            всего = np.bincount(j, weights=кладёт, minlength=nb)
            дам = np.minimum(всего, об)
            кладёт = кладёт * (дам / np.maximum(всего, 1e-12))[j]
            легло[i0:i1] = кладёт
            села = np.bincount(j, weights=кладёт, minlength=nb) / np.maximum(зазор_р * шир, 1e-12)   # где кромка краску не кладёт (висит над низиной), там и за конец её не выдавливает
            кс_легло[i0:i1] = цв_вала[j]
            w_вала, сх_вала = (E[:, 1] / np.where(есть_вал, об, 1.0)), (E[:, 2] / np.where(есть_вал, об, 1.0))
            w_легло[i0:i1], сх_легло[i0:i1] = w_вала[j], сх_вала[j]
            E *= (1.0 - дам / np.where(есть_вал, об, 1.0))[:, None]
        if not чистая:                                        # место кромки, что клало краску и перестало доставать до холста (нож
            села_посл = 0.7 * села_посл + 0.3 * np.minimum(села, 1.0)   # поднимают), оставляет свой вал на холсте комом
            порог_к = 0.7 * Н[21] * (зазор[m] + выгиб * (1.0 - pb))
            брошен = (E[:, 0] > 1e-12) & (((села_посл > 0.2) & ((Н[8] * Hэ * горка * ур) * прижат < порог_к)) | ((E[:, 0] * прижат / (длина_вала * шир) < порог_к) & (запас < 0.02 * запас0 * горка) & достал_бы))
            if брошен.any():
                комья.append((m, np.where(брошен[:, None], E, 0.0)))
                E[брошен] = 0.0
                села_посл[брошен] = 0.0
        # вал растекается вдоль кромки и выдавливается за её концы
        if nb > 1 and чистая:
            поток = Н[10] * (E[:-1] - E[1:])
            E[:-1] -= поток
            E[1:] += поток
        elif nb > 1:                                          # паста течёт вдоль кромки, пока перепад выше её предела текучести, и тем
            разн = E[:-1] - E[1:]                              # живее, чем сильнее нажим
            a = np.abs(разн[:, :1])
            поток = min(Н[29] * (pb / Н[2]) ** 2, 0.45) * np.maximum(a - Н[22] * вал_полный, 0.0) / np.maximum(a, 1e-30) * разн
            E[:-1] -= поток
            E[1:] += поток
        for сторона, край in ((0, 0), (1, nb - 1)):
            if чистая:
                лишек = max(float(E[край, 0]) - 0.75 * вал_полный, 0.0)
                д = Н[11] * лишек / float(E[край, 0]) if лишек > 0.0 else 0.0
                if лишек > 0.0:
                    ушло = E[край] * д
                    E[край] -= ушло
                    бок[сторона, int(b), :3] += ушло[:3]
                    бок[сторона, int(b), 3:] += из_кс((ушло[3:] / max(ушло[0], 1e-30))[None, :])[0] * ушло[0]
                continue
            if края is not None:
                # из-под края краски паста уходит за бок по зазору: поток — как куб зазора над холстом у края (над
                # нитью зазор мал — почти не течёт, над ямкой течёт) и квадрат нажима
                край = края[сторона]
                u_к = (край + сторона) * шир - Wэ / 2
                край_u[сторона, int(b)] = u_к
                кр = j == край
                зз = float(np.mean(np.maximum(глубина[кр], 0.0))) / max(float(зазор[m]), 1e-12) if кр.any() else 0.0
                лишек = float(E[край, 0]) * min(зз, 2.0) ** 3 * float(min(села[край], 1.0))
                д = min(Н[23] * (pb / Н[2]) ** 2 * лишек / max(float(E[край, 0]), 1e-30), 0.9)
                if лишек > 0.0:
                    ушло = E[край] * д
                    E[край] -= ушло
                    бусина[сторона, :3] += ушло[:3]
                    бусина[сторона, 3:] += из_кс((ушло[3:] / max(ушло[0], 1e-30))[None, :])[0] * ушло[0]
            if бусина[сторона, 0] > 1e-15:
                # выдавленное за бок — комок пасты: держится за бок ножа и едет с ним по холсту. Холст стирает с него
                # краску вершинами нитей (над низиной комок дна не касается) — валик у бока рвётся по зерну; комок, что
                # перерос удерживаемое ножом, остаётся на холсте целиком и тянется за ножом, — край выпирает
                if края is None or n_р == len(ряды) - 1:
                    сход_б[сторона].append((int(b), бусина[сторона].copy()))
                    бусина[сторона] = 0.0
                else:
                    знак = 2.0 * сторона - 1.0
                    qx = min(max(int(np.floor(x[m] + (u_к + знак) * ax[m] - bx0)), 0), bw - 1)
                    qy = min(max(int(np.floor(y[m] + (u_к + знак) * ay[m] - by0)), 0), bh - 1)
                    нить = float(зажать(1.0 - (z0 - Tв[qy * bw + qx]) / (Н[6] * мт), 0.0, 1.0))
                    след_б = бусина[сторона] * (доля_бусины * нить)
                    бок[сторона, int(b)] += след_б
                    бусина[сторона] -= след_б
                    if бусина[сторона, 0] * нить * нить > B_пред:
                        сход_б[сторона].append((int(b), бусина[сторона] * (1.0 - Н[31])))
                        бусина[сторона] *= Н[31]

    V = np.zeros(bh * bw)
    V[пикс] = легло
    # --- валики у боков хода: откосом наружу от конца кромки
    mб = np.minimum(2 * np.arange(nR), N - 1)
    Vв, Eв = np.zeros((bh, bw)), np.zeros((bh, bw, 5))
    внутрь = min(мм, Wэ / 8)                                  # валик стоит на краю плёнки: откос начинается чуть внутри кромки (у ребра — у самой кромки)
    for сторона, знак in ((0, -1.0), (1, 1.0)):
        об = бок[сторона, :, 0]
        u_б = знак * (Wэ / 2 - внутрь)                         # откуда наружу встаёт валик: у ножа без краски — конец кромки
        if not чистая:                                        # у ножа с краской — край краски под ним (где его не было — как в соседнем ряду)
            u_б = край_u[сторона]
            есть_u = np.nonzero(~np.isnan(u_б))[0]
            u_б = (u_б[есть_u[np.searchsorted(есть_u, np.arange(nR)).clip(0, len(есть_u) - 1)]] if len(есть_u) else np.full(nR, знак * Wэ / 2)) - знак * внутрь
        v, e = _откос(об, x[mб] + u_б * ax[mб] - bx0, y[mб] + u_б * ay[mб] - by0, знак * ax[mб], знак * ay[mб],
                      уклон if чистая else уклон * Н[26], bw, bh, бок[сторона, :, 1:] / np.maximum(об, 1e-30)[:, None], поле)
        Vв, Eв = Vв + v, Eв + e
        if сход_б[сторона]:                                   # комки: каждый лежит на длине своего размера, откосом кома
            ком_б = np.zeros((nR, 6))
            for ряд_к, B in сход_б[сторона]:
                разм = (float(B[0]) / уклон) ** (1.0 / 3.0)       # комок тянется за ножом: толст, где сидел, и сходит на нет по ходу на длине в три своих размера
                ряды_к = ряд_к + np.arange(-max(1, int(round(0.5 * разм))), max(2, int(round(3.0 * разм))) + 1)
                вес = np.maximum(1.0 - np.where(ряды_к < ряд_к, (ряд_к - ряды_к) / (0.5 * разм + 1.0), (ряды_к - ряд_к) / (3.0 * разм + 1.0)) ** 2, 0.0) ** 2
                ок_к = (ряды_к >= 0) & (ряды_к < nR)
                ком_б[ряды_к[ок_к]] += (вес / вес.sum())[ок_к, None] * B[None, :]
            об = ком_б[:, 0]
            v, e = _откос(об, x[mб] + u_б * ax[mб] - bx0, y[mб] + u_б * ay[mб] - by0, знак * ax[mб], знак * ay[mб],
                          уклон, bw, bh, ком_б[:, 1:] / np.maximum(об, 1e-30)[:, None], поле)
            Vв, Eв = Vв + v, Eв + e
    # --- ком: где нож оторван, вал остаётся на холсте
    на_холст = np.ones(nb, dtype=bool) if чистая else села_посл > 0.2      # вал мест, что холста не касались, и бусины у боков нож с краской унёс на себе
    унёс = 0.0 if чистая else float(E[~на_холст, 0].sum() + бусина[:, 0].sum())
    комья.append((min(2 * int(ряды[-1]) + 1, N - 1), E * на_холст[:, None]))
    uк = (np.arange(nb) + 0.5) * шир - Wэ / 2
    долей = max(1, int(round(шир / 0.5)))
    уклон_к = уклон if чистая else 2.0 * вал_полный * float(горка.max()) / шир / поле ** 2 / долей   # ком — вал, как стоял перед кромкой: где его больше, там длиннее
    for mк, Eк in комья:
        if Eк[:, 0].sum() <= 1e-12:
            continue
        об = Eк[:, 0] / шир
        поля = np.concatenate([Eк[:, 1:3], из_кс(Eк[:, 3:] / np.maximum(Eк[:, :1], 1e-30)) * Eк[:, :1]], axis=1) / np.maximum(Eк[:, :1], 1e-30)
        for доля_м in ((np.arange(долей) + 0.5) / долей - 0.5):
            v, e = _откос(об * шир / долей, x[mк] + (uк + доля_м * шир) * ax[mк] - bx0, y[mк] + (uк + доля_м * шир) * ay[mк] - by0,
                          np.full(nb, tx[mк]), np.full(nb, ty[mк]), уклон_к, bw, bh, поля, поле)
            Vв, Eв = Vв + v, Eв + e
    if Vв.any():
        for _ in range(max(1, int(round(мм * мм)))):            # откос оплывает на длине в мм, а не в px
            Vв, Eв = _сгладить(Vв), _сгладить(Eв)
        if not чистая:                                        # паста стоит тупым краем: тоньше следа ножа не растекается — подошва откоса подбирается в него
            тонко = Vв < след
            if тонко.any() and (~тонко).any():
                k = float(Vв.sum()) / max(float(Vв[~тонко].sum()), 1e-30)
                Eв = np.where(тонко[:, :, None], 0.0, Eв * k)
                Vв = np.where(тонко, 0.0, Vв * k)
    # --- поля ответа
    h1 = h_пл.copy()
    h1[пикс] -= срезано
    доля_сыр = np.ones(bh * bw)                               # что осталось от сырой доли: срезано только подвижное
    доля_сыр[пикс] = np.where(сыр > 1e-12, 1.0 - срезано / np.maximum(сыр, 1e-12), 1.0)
    w1 = np.where(h1 > 1e-12, w_пл * h_пл * доля_сыр / np.maximum(h1, 1e-12), 0.0)
    сх1 = np.where(h1 > 1e-12, сх_пл, 0.0)
    ц = np.zeros((bh * bw, 3))
    ц[пикс] = из_кс(кс_легло)
    wV, схV = np.zeros(bh * bw), np.zeros(bh * bw)
    wV[пикс], схV[пикс] = w_легло, сх_легло
    Vв_пл, Eв_пл = Vв.ravel(), Eв.reshape(-1, 5)
    всё = V + Vв_пл
    есть = всё > 1e-12
    знам = np.where(есть, всё, 1.0)
    ц = (ц * V[:, None] + Eв_пл[:, 2:]) / знам[:, None]
    wV = (wV * V + Eв_пл[:, 0]) / знам
    схV = (схV * V + Eв_пл[:, 1]) / знам
    доля_м = np.zeros(bh * bw)
    ц_м = np.zeros((bh * bw, 3))
    доля_м[пикс] = зажать(мешано, 0.0, 1.0)
    ц_м[пикс] = из_кс(кс_мешано)
    кас = np.zeros(bh * bw)
    кас[пикс] = контакт[np.minimum(2 * ряд_п, N - 1)] * покрыт * стоял[np.searchsorted(ряды, ряд_п), место]
    вид = lambda a: a.reshape(bh, bw)   # noqa: E731
    return dict(h=вид(h1), w=вид(зажать(w1, 0.0, 1.0)), сх=вид(зажать(сх1, 0.0, 1.0)), V=вид(всё), ц=ц.reshape(bh, bw, 3), wV=вид(wV), схV=вид(схV),
                мешано=вид(доля_м), ц_мешано=ц_м.reshape(bh, bw, 3), касание=вид(кас), снято=float(срезано.sum()), на_ноже=на_ноже,
                сырое=вид(сырое_поле) if есть_сырое else None, запас=float(запас.sum()) + унёс)
