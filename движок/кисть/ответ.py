"""v4, 3г (К-1): ответ мазка — прямоугольник и замер следа. Только читает: холст, кисть, сиды и журнал не меняются.

`Холст.мазок` отвечает `Ответ` — тем же кортежем (x0, y0, x1, y1), что и раньше, с полями замера. Сразу, в конце
самого мазка (на ядрах — в процессе мазка, числа те же, что на одном ядре), считается дешёвое: `цвет` — тон холста по
закрашенным пикселям следа, `тело`, `закрыто`, `сырое` — из полей мазка (покрытие новой плёнки, касание кисти, снятое
сырое). Дорогое — `ширина`, `просветы`, `разрывы`, `край` — по запросу: считается при первом обращении к любому из
них из полей следа, которые ответ несёт с собой (покрытие и касание в прямоугольнике, 1 байт на пиксель, и путь);
от того, что легло на холст после мазка, не зависит.

Развёртка следа: поля покрытия и касания берутся вдоль хода рядами поперёк него (ряд на 1 px хода, у кисти шире
32 px — на 1/32 ширины; отсчёт поперёк через 0,5 px, у кисти от 24 px — через 1 px); в ней меряются ширина, просветы,
разрывы и край. Уровень тела — 90-й процентиль покрытия под кистью; «краска легла» — покрытие от половины его.
"""
import math

import numpy as np

from . import глаз
from .краска import из_линейного

ПОД_КИСТЬЮ = 0.5        # касание, от которого пиксель — под кистью
ТЕЛО = 0.5              # доля уровня тела, от которой краска «легла» (край следа — по ней же)
КАЙМА_ОТ = 0.1          # кайма края: от этой доли уровня тела до ТЕЛО, px
РЯДОВ = 1500            # потолок рядов развёртки: длинный ход берётся реже
ТОН_ПО = 16384          # тон следа: не больше стольких закрашенных пикселей (у большого следа — каждый k-й)
_ПО_ЗАПРОСУ = ('ширина', 'просветы', 'разрывы', 'край')
_ЧИТАЮТ = _ПО_ЗАПРОСУ + ('цвет', 'тело', 'закрыто', 'сырое', 'слова')


class Ответ(tuple):
    """Ответ `Холст.мазок`: записанный прямоугольник (x0, y0, x1, y1) — как кортеж, и что вышло:

    цвет      — тон следа на холсте, как у `х.средний`: {'L', 'C', 'h', 'rgb', 'hex'}; среднее тона холста (без света
                рельефа, сквозь слои выше) по закрашенным пикселям следа — где покрытие новой плёнки не ниже половины
                уровня тела (если их больше 16 тыс. — по каждому k-му). None — следа не видно;
    тело      — 0–1: покрытие тела следа (90-й процентиль покрытия новой плёнки под кистью): кроющий ход ~1,
                протирка 0,2–0,4;
    закрыто   — 0–1: насколько новая краска закрыла лежавшее под кистью (среднее покрытие плёнки под кистью):
                кроющий ход ~1, протирка 0,2–0,4, сухая кисть — доля островов;
    просветы  — 0–1: доля места внутри следа (между его кромками, от первой краски хода до последней), где краска не
                легла — покрытие ниже половины уровня тела: борозды до грунта, острова сухой кисти, порванный ход;
    ширина    — px: ширина следа поперёк хода (медиана по ходу, от края до края);
    сырое     — {'по сырому': доля места под кистью, где лежала сырая краска, 'подобрано': какую долю её кисть сняла,
                'к положенному': снятое к положенному этим мазком (по объёму краски)};
    разрывы   — список мест, где ход порвался: {'от': (x, y), 'до': (x, y), 'длина': px, 'место': (доля хода от, до),
                'причина': 'нажим' — кисть оторвалась от холста, 'краска' — кисть шла, краска не легла}; вход и подъём
                кисти в начале и конце хода — не разрыв, а краска, что кончилась раньше хода, — разрыв до его конца;
    край      — {'кайма': px от 10 до 50 % уровня тела поперёк хода (медиана двух сторон), 'левый', 'правый' — то же
                по сторонам (слева и справа по ходу), 'рваность': px, насколько кромка гуляет вдоль хода, 'слово':
                'жёсткий' | 'мягкий' | 'рваный'}; None — следа не видно.
    осталось  — Д-1: сколько живой краски осталось в ворсе кисти после хода, доля полной кисти 0–1 (`к.набрать(цвет,
                количество)`, ход без цвета); None — краска не живая: кисть полна на каждом ходе.

    `цвет`, `тело`, `закрыто`, `сырое` сочтены вместе с мазком; `ширина`, `просветы`, `разрывы`, `край` — при первом
    обращении к любому из них (или `print(о)`): развёртка следа из его полей, что ответ несёт с собой.
    `print(о)` — строкой словами; `tuple(о)`, `о[0]`, `x0, y0, x1, y1 = о`, `о == (…)` — как у кортежа."""

    осталось = None

    def __new__(cls, прямоугольник, **поля):
        о = tuple.__new__(cls, прямоугольник)
        о.__dict__.update(поля)
        return о

    def __getnewargs__(self):
        return (tuple(self),)

    def __getattribute__(self, имя):
        if имя in _ЧИТАЮТ:                    # 5б: ответ прочитан — в счёт подсказок (С5)
            д = tuple.__getattribute__(self, '__dict__')
            у = д.get('_учёт')
            if у is not None:
                д['_учёт'] = None
                у.прочтён()
        return tuple.__getattribute__(self, имя)

    def __getattr__(self, имя):
        if имя in _ПО_ЗАПРОСУ and '_след' in self.__dict__:
            self.__dict__.update(_развернуть(self.__dict__.pop('_след')))
            return self.__dict__[имя]
        raise AttributeError(имя)

    @property
    def слова(self):
        ч = [f'{tuple(self)}']
        if self.цвет is None:
            ч.append('следа не видно')
        else:
            ч.append(f"цвет L {self.цвет['L']:.0f} C {self.цвет['C']:.3f} h {self.цвет['h']:.0f} {self.цвет['hex']}")
        ч.append(f'закрыто {self.закрыто:.2f}, просветы {self.просветы:.2f}')
        if self.ширина:
            ч.append(f'ширина {self.ширина:.0f} px')
        if self.сырое['по сырому'] > 0:
            ч.append(f"по сырому {self.сырое['по сырому']:.2f}, подобрано {self.сырое['подобрано']:.2f}")
        if self.разрывы:
            ч.append('разрывы: ' + '; '.join(f"{р['от']}–{р['до']} {р['длина']:.0f} px ({р['причина']})" for р in self.разрывы))
        if self.осталось is not None:
            ч.append(f'на кисти осталось {self.осталось:.2f}' + (' — краска кончилась, набрать' if self.осталось < 0.02 else ''))
        if self.край is not None:
            ч.append(f"край {self.край['слово']} (кайма {self.край['кайма']:.1f} px, рваность {self.край['рваность']:.1f} px)")
        return ' · '.join(ч)

    def __str__(self):
        return self.слова


def _тон(х, п, где):
    """Средний тон холста по пикселям `где` прямоугольника `п` — тем же счётом, что `глаз.средний` (L серой шкалы,
    a, b OKLab; тон без света рельефа)."""
    if not где.any():
        return None
    тон = х.картинка(свет=False, область=п)[где]
    if len(тон) > ТОН_ПО:
        тон = тон[::-(-len(тон) // ТОН_ПО)]
    lab = глаз.oklab(np.clip(из_линейного(тон) * 255.0, 0.0, 255.0))
    L, ma, mb = float(глаз._L(lab[:, 0]).mean()), float(lab[:, 1].mean()), float(lab[:, 2].mean())
    C = math.hypot(ma, mb)
    h = math.degrees(math.atan2(mb, ma)) % 360.0 if C >= 1e-6 else 0.0
    rgb = глаз.цвет(L, C, h)
    return {'L': round(L, 2), 'C': round(C, 4), 'h': round(h, 1), 'rgb': rgb, 'hex': глаз.шестн(rgb)}


def _взять(поля, X, Y):
    """Поля (одной формы) в точках (X, Y) их пикселей (центр пикселя — целое + 0,5), билинейно; вне поля — 0."""
    В, Ш = поля[0].shape
    u, v = X - 0.5, Y - 0.5
    j0, i0 = np.floor(u), np.floor(v)
    fu, fv = u - j0, v - i0
    j0, i0 = np.clip(j0.astype(np.int64) + 1, 0, Ш), np.clip(i0.astype(np.int64) + 1, 0, В)   # в поле с каймой нулей в 1 px
    внутри = (u > -1.0) & (u < Ш) & (v > -1.0) & (v < В)                                     # дальше каймы — ноль, а не край поля
    w00, w01, w10, w11 = (1 - fv) * (1 - fu) * внутри, (1 - fv) * fu * внутри, fv * (1 - fu) * внутри, fv * fu * внутри
    итог = []
    for a in поля:
        b = np.zeros((В + 2, Ш + 2))
        b[1:-1, 1:-1] = a
        итог.append(b[i0, j0] * w00 + b[i0, j0 + 1] * w01 + b[i0 + 1, j0] * w10 + b[i0 + 1, j0 + 1] * w11)
    return итог


def _развёртка(альфа, касание, x, y, W, угол):
    """Поля вдоль хода рядами поперёк: (покрытие, касание — (рядов, отсчётов), x и y рядов, длина хода до ряда px)."""
    x, y = np.asarray(x, np.float64), np.asarray(y, np.float64)
    шаги = np.hypot(np.diff(x), np.diff(y))
    длина = np.concatenate([[0.0], np.cumsum(шаги)])
    n = int(min(max(round(длина[-1] / max(1.0, W / 32.0)), 1), РЯДОВ)) + 1
    s = np.linspace(0.0, длина[-1], n)
    xs, ys = (np.interp(s, длина, x), np.interp(s, длина, y)) if длина[-1] > 0 else (x[:1].copy(), y[:1].copy())
    s = s[:len(xs)]
    d = max(2.0, 0.1 * W)                                    # касательная — по хорде ±d px: дрожь пути её не качает
    tx = np.interp(s + d, длина, x) - np.interp(s - d, длина, x) if длина[-1] > 0 else np.ones(1)
    ty = np.interp(s + d, длина, y) - np.interp(s - d, длина, y) if длина[-1] > 0 else np.zeros(1)
    норма = np.hypot(tx, ty)
    tx, ty = np.where(норма > 1e-9, tx / np.maximum(норма, 1e-9), 1.0), np.where(норма > 1e-9, ty / np.maximum(норма, 1e-9), 0.0)
    R, dt = 0.65 * W + 6.0, (0.5 if W < 24 else 1.0)         # поперёк: шире следа с запасом; отсчёт 0,5 px, у широкой кисти 1 px
    t = np.arange(-R, R + 0.5 * dt, dt)                      # t > 0 — справа по ходу (y вниз)
    X = xs[:, None] - ty[:, None] * t[None, :] - угол[0]
    Y = ys[:, None] + tx[:, None] * t[None, :] - угол[1]
    A, K = _взять((альфа, касание), X, Y)
    return A, K, xs, ys, s, t


def _ряды(м):
    """Участки подряд идущих True: [(от, до включительно), …]."""
    м = np.asarray(м, bool)
    if not м.any():
        return []
    к = np.flatnonzero(np.diff(np.concatenate([[False], м, [False]]).astype(np.int8)))
    return [(int(a), int(b) - 1) for a, b in zip(к[::2], к[1::2])]


def _бег_медианы(a, окно):
    """Бегущая медиана ряда (окно нечётное), края — зеркалом."""
    окно = int(окно) | 1
    if окно <= 1 or len(a) < 3:
        return a.copy()
    r = min(окно // 2, len(a) - 1)
    b = np.pad(a, r, mode='reflect')
    return np.median(np.lib.stride_tricks.sliding_window_view(b, 2 * r + 1), axis=1)


def _квантиль(a, q):
    """q-й квантиль ряда (ближайший по порядку) — без сортировки всего ряда."""
    k = int(round(q * (a.size - 1)))
    return float(np.partition(a, k)[k])


def замерить(х, прямоугольник, поля):
    """Ответ мазка по полям следа от `укладка.положить_мазок(замер=…)` и тону холста `х` в его прямоугольнике: дешёвое —
    сразу, развёртка следа (`_развернуть`) — по запросу, из полей, сложенных в ответ."""
    альфа, касание, W = поля['альфа'], поля['касание'], float(поля['W'])
    под = касание > ПОД_КИСТЬЮ
    под_кистью = альфа[под]
    место = под_кистью.size
    тело = _квантиль(под_кистью, 0.9) if место else 0.0
    порог = ТЕЛО * тело
    видно = место > 0 and тело >= 0.01
    сырое = поля['сырое']
    if сырое is not None and место:
        лежало = сырое[под]
        по_сырому, лежало = float((лежало > 1e-4).mean()), float(лежало.sum())
    else:
        лежало, по_сырому = 0.0, 0.0
    снято, положено = float(поля['снято']), float(поля['положено'])
    о = dict(цвет=_тон(х, прямоугольник, альфа >= порог) if видно else None, тело=round(тело, 4),
             закрыто=round(float(под_кистью.mean()), 4) if место else 0.0,
             сырое={'по сырому': round(по_сырому, 3), 'подобрано': round(min(снято / лежало, 1.0), 3) if лежало > 1e-9 else 0.0,
                    'к положенному': round(снято / положено, 3) if положено > 1e-9 else 0.0})
    if not видно:
        return Ответ(прямоугольник, ширина=0.0, просветы=1.0, разрывы=[], край=None, **о)
    x, y = np.asarray(поля['x']), np.asarray(поля['y'])
    k = max(1, int(len(x) / max(float(np.hypot(np.diff(x), np.diff(y)).sum()), 1.0)))      # путь с собой — точка на ~1 px хода
    к8 = lambda a: np.rint(np.clip(a, 0.0, 1.0) * 255.0).astype(np.uint8)
    return Ответ(прямоугольник, _след=dict(альфа=к8(альфа), касание=к8(касание), тело=тело, W=W, угол=tuple(поля['угол']),
                                           x=np.append(x[:-1:k], x[-1]).astype(np.float32), y=np.append(y[:-1:k], y[-1]).astype(np.float32)), **о)


def _развернуть(след):
    """Дорогая часть ответа — развёртка следа: {'ширина', 'просветы', 'разрывы', 'край'} из полей, что ответ несёт с собой."""
    W, тело = след['W'], след['тело']
    порог = ТЕЛО * тело
    о = dict(ширина=0.0, просветы=1.0, разрывы=[], край=None)
    A, K, xs, ys, s, t = _развёртка(след['альфа'] / 255.0, след['касание'] / 255.0, след['x'], след['y'], W, след['угол'])
    легло, кис = A >= порог, K > ПОД_КИСТЬЮ
    dt, шаг = float(t[1] - t[0]), (float(s[1] - s[0]) if len(s) > 1 else 1.0)     # отсчёт поперёк и ряд вдоль, px
    f = кис.sum(1) * dt                                       # ширина касания ряда, px
    g = (легло & кис).sum(1) * dt                             # из неё — с краской
    есть = легло.any(1)
    лев = np.where(есть, t[np.argmax(легло, 1)], np.nan)      # кромки следа ряда: первая и последняя точка с краской
    прав = np.where(есть, t[легло.shape[1] - 1 - np.argmax(легло[:, ::-1], 1)], np.nan)
    размах = np.where(есть, прав - лев + dt, 0.0)
    if есть.any():                                            # просветы — внутри следа: между кромками ряда, от первого ряда с краской до последнего
        a, b = int(np.argmax(есть)), len(есть) - 1 - int(np.argmax(есть[::-1]))
        внутри = кис[a:b + 1] & np.where(есть[a:b + 1, None], (t[None, :] >= лев[a:b + 1, None]) & (t[None, :] <= прав[a:b + 1, None]), True)
        о['просветы'] = round(float((внутри & ~легло[a:b + 1]).sum() / max(int(внутри.sum()), 1)), 4)
    f_тела = float(np.median(f[f > 0])) if (f > 0).any() else 0.0
    оторвана = f < 0.25 * f_тела
    доля = np.where(f > 0, g / np.maximum(f, dt), 0.0)
    доля = _бег_медианы(доля, max(3, min(int(round(0.25 * W / шаг)), 41)))
    обычно = float(np.percentile(доля[~оторвана], 75)) if (~оторвана).any() else 0.0
    пусто = ~оторвана & (доля < min(0.5, 0.5 * обычно))
    цел = ~оторвана & ~пусто
    if цел.any():
        о['ширина'] = round(float(np.median(размах[цел])), 1)
    # --- разрывы: кисть оторвалась между касаниями ('нажим') или шла без краски ('краска')
    короче = max(3.0, 0.2 * W)
    первый, последний = (int(np.flatnonzero(цел)[0]), int(np.flatnonzero(цел)[-1])) if цел.any() else (len(s), -1)
    L = float(s[-1]) if len(s) > 1 and s[-1] > 0 else 1.0
    for причина, маска in (('нажим', оторвана), ('краска', пусто)):
        for a, b in _ряды(маска):
            внутри = a > первый and b < последний
            хвост = причина == 'краска' and a > первый and s[b] - s[a] + шаг >= max(короче, 0.5 * W)   # краска кончилась до конца хода
            if s[b] - s[a] + шаг < короче or not (внутри or хвост):
                continue
            о['разрывы'].append({'от': (int(round(xs[a])), int(round(ys[a]))), 'до': (int(round(xs[b])), int(round(ys[b]))),
                                 'длина': round(float(s[b] - s[a] + шаг), 1), 'место': (round(float(s[a] / L), 3), round(float(s[b] / L), 3)),
                                 'причина': причина})
    о['разрывы'].sort(key=lambda р: р['место'])
    # --- край: кайма (10–50 % уровня тела) и рваность кромки вдоль хода, по сторонам
    if цел.sum() >= 3:
        низ = A >= КАЙМА_ОТ * тело
        лев10 = t[np.argmax(низ, 1)]
        прав10 = t[низ.shape[1] - 1 - np.argmax(низ[:, ::-1], 1)]
        каймы, рвань = [], []
        окно = max(5, min(int(round(W / шаг)), 41))
        for кромка, внешняя, знак in ((лев, лев10, 1.0), (прав, прав10, -1.0)):
            e = кромка[цел]
            каймы.append(float(np.median(знак * (e - внешняя[цел]))))
            ост = e - _бег_медианы(e, окно)
            рвань.append(float(np.percentile(ост, 90) - np.percentile(ост, 10)) / 2.563)
        кайма, рваность = max(0.0, 0.5 * (каймы[0] + каймы[1])), 0.5 * (рвань[0] + рвань[1])
        слово = 'рваный' if рваность >= max(1.5, 0.05 * W) else 'мягкий' if кайма >= max(2.0, 0.05 * W) else 'жёсткий'
        о['край'] = {'кайма': round(кайма, 1), 'левый': round(max(каймы[0], 0.0), 1), 'правый': round(max(каймы[1], 0.0), 1),
                     'рваность': round(рваность, 2), 'слово': слово}
    return о
