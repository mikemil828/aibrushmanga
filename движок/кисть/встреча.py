"""v4, Г-8: с чем встретился ход — сырая чужая краска под кистью и мягкая по сухому в новом слое.

Только читает: холст, кисть, сиды и журнал не меняются; файлы физики не тронуты. `Лежало` — то, что лежало на холсте
до хода: вид `перед_записью` у `укладка.положить_мазок` (в прямоугольнике мазка, до записи в слой). `разобрать` — после
хода, по полям следа ответа мазка: `о.чужое` и `о.серый` (`ответ.Ответ`), словами — в `print(о)` и подсказках С19, С20.

Чужое (С19). Сырое, с которым мешается ход (своего слоя, с `мешать_ниже` — и слоёв под ним; схватившееся — в меру
подвижности, как у физики мазка), под кистью: средний тон, взвешенный толщиной сырого. Говорится, когда всё вместе:
подобрано к положенному от `ПОДОБРАНО`, лежащее далеко от названного цвета (`ДАЛЕКО_L` или `ДАЛЕКО_AB`), тон следа
ушёл от названного к лежащему (`СДВИГ_L` или `СДВИГ_AB`).

Серый (С20). Мягкая кисть кроющей краской без разбавителя там, где в её слое краски ещё нет, а сырого под кистью нет ни
в одном слое, по лежащему далёкого тона: тон следа прошёл к названному меньше `ПУТЬ` пути от лежащего (OKLab, проекция).
Прозрачная и полукроющая краска и разбавитель — заказ просвета: не судим.

Пороги — из стенда (`тесты/test_встреча_Г8.py`, числа — справочник, «Stroke response»).
"""
import math

import numpy as np

from . import глаз
from .краска import из_линейного

ПОДОБРАНО = 0.1         # снято сырого к положенному (С13 — та же планка)
ДАЛЕКО_L = 20.0         # лежащее от названного: L серой шкалы
ДАЛЕКО_AB = 0.05        # … или a, b OKLab (длина)
СДВИГ_L = 8.0           # тон следа от названного к лежащему: L
СДВИГ_AB = 0.02         # … или a, b OKLab
ПУТЬ = 0.5              # С20: след прошёл к названному меньше такой доли пути от лежащего
СЫРО = 1e-4             # сырая толщина, от которой краска сырая (`ответ.замерить`)
ПУСТО = 0.02            # С20: покрытие своего слоя под кистью, ниже которого места в нём ещё нет
НЕ_МЕНЬШЕ = 0.1         # доля места под кистью с сырым, меньше которой встреча — край, а не ход по сырому
ПО = 16384              # тон лежащего — не больше чем по стольким пикселям (как `ответ.ТОН_ПО`)
НЕЙТРАЛЬ = 0.02         # насыщенность, ниже которой у цвета нет тона (h)


def _лаб(лин):
    """Линейный RGB (…, 3) -> (L серой шкалы, a, b OKLab) средним по пикселям, как `х.средний`."""
    lab = глаз.oklab(np.clip(из_линейного(np.asarray(лин, np.float64).reshape(-1, 3)) * 255.0, 0.0, 255.0))
    return np.stack([глаз._L(lab[:, 0]), lab[:, 1], lab[:, 2]], 1)


def названный(краски):
    """Названный цвет хода [(линейный RGB, доля)] -> (L, a, b)."""
    вес = np.array([float(д) for _, д in краски])
    return (_лаб([c for c, _ in краски]) * (вес / max(float(вес.sum()), 1e-12))[:, None]).sum(0)


def _тон(L, a, b):
    C = math.hypot(a, b)
    rgb = глаз.цвет(L, C, math.degrees(math.atan2(b, a)) % 360.0)
    return {'L': round(float(L), 2), 'C': round(C, 4), 'h': round(math.degrees(math.atan2(b, a)) % 360.0 if C >= 1e-6 else 0.0, 1),
            'rgb': rgb, 'hex': глаз.шестн(rgb)}


def _Δh(из, в):
    """Поворот тона из → в, °; None — один из цветов без тона."""
    if math.hypot(из[1], из[2]) < НЕЙТРАЛЬ or math.hypot(в[1], в[2]) < НЕЙТРАЛЬ:
        return None
    д = math.degrees(math.atan2(в[2], в[1]) - math.atan2(из[2], из[1]))
    return round((д + 180.0) % 360.0 - 180.0, 1)


class Лежало:
    """Что лежало в прямоугольнике мазка до записи. дальше — прежний вид `перед_записью` (снимки, скотч): зовётся следом."""

    def __init__(self, х, цель, нижние, мягкая, дальше=None):
        self.х, self.цель, self.нижние, self.мягкая, self.дальше = х, цель, нижние, мягкая, дальше
        self.п = self.сыро = self.цвет = self.своё = self.до = None
        self.сухо = False

    def __call__(self, п):
        self._взять(п)
        if self.дальше is not None:
            self.дальше(п)

    def _взять(self, п):
        from .укладка import _СХВАТ
        х = self.х
        x0, y0, x1, y1 = (int(v) for v in п)
        где = (slice(y0 - х.y0, y1 - х.y0), slice(x0 - х.x0, x1 - х.x0))
        сумма = цв = None
        for с in (self.цель,) + tuple(self.нижние):
            в = np.asarray(с.влажность[где])
            if not в.any():
                continue
            с_н = np.asarray(с.толщина[где], np.float64) * в * (1.0 - _СХВАТ * np.asarray(с.схват[где]))
            if с_н.max() <= СЫРО:
                continue
            c = np.asarray(с.цвет[где], np.float64) * с_н[..., None]
            сумма, цв = (с_н, c) if сумма is None else (сумма + с_н, цв + c)
        self.п = (x0, y0, x1, y1)
        if сумма is not None:
            self.сыро, self.цвет = сумма, цв / np.maximum(сумма, 1e-12)[..., None]
        if self.мягкая and self.сыро is None:
            self.своё = np.array(self.цель.покрытие[где])
            self.сухо = not any((np.asarray(с.толщина[где]) * np.asarray(с.влажность[где]) > СЫРО).any()
                                for с in х._слои.values() if с is not self.цель)
            if self.сухо and float(self.своё.min()) < ПУСТО:
                self.до = х._цвет(где[0].start, где[0].stop, где[1].start, где[1].stop)


def _доли(маска, *поля):
    """Значения полей в пикселях маски — не больше `ПО` штук (каждый k-й)."""
    н = np.flatnonzero(маска)
    if len(н) > ПО:
        н = н[::-(-len(н) // ПО)]
    return [a.reshape((-1,) + a.shape[маска.ndim:])[н] for a in поля]


def разобрать(л, о, поля, краски, кроющая):
    """Ответ мазка `о`, поля его следа, лежавшее `л`: `о.чужое`, `о.серый` (или None). кроющая — краска кроет и не разбавлена."""
    if л.п is None or о.цвет is None or not краски:
        return
    под = поля['касание'] > 0.5
    h = math.radians(float(о.цвет['h']))
    след = np.array([float(о.цвет['L']), float(о.цвет['C']) * math.cos(h), float(о.цвет['C']) * math.sin(h)])
    имя = названный(краски)
    место = int(под.sum())
    if л.сыро is not None:
        где = под & (л.сыро > СЫРО)
        n = int(где.sum())
        взято = float(о.сырое['к положенному'])
        if n < НЕ_МЕНЬШЕ * max(место, 1) or взято < ПОДОБРАНО:
            return
        вес, c = _доли(где, л.сыро, л.цвет)
        леж = (_лаб(c) * вес[:, None]).sum(0) / float(вес.sum())
        д, с = леж - имя, след - имя
        далеко = abs(д[0]) >= ДАЛЕКО_L or math.hypot(д[1], д[2]) >= ДАЛЕКО_AB
        # сдвиг — только в сторону лежащего: тон прядей и просвет другого слоя сюда не идут
        к_L = с[0] * math.copysign(1.0, д[0]) >= СДВИГ_L
        к_ab = (с[1] * д[1] + с[2] * д[2]) / max(math.hypot(д[1], д[2]), 1e-9) >= СДВИГ_AB      # проекция на путь к лежащему
        if далеко and (к_L or к_ab):
            о.__dict__['чужое'] = {'подобрано': взято, 'лежало': _тон(*леж), 'названо': _тон(*имя), 'ΔL': round(float(с[0]), 1),
                                   'Δh': _Δh(имя, след), 'Δab': round(math.hypot(с[1], с[2]), 3)}
        return
    if л.до is not None and кроющая and место:
        где = под & (л.своё < ПУСТО)
        if int(где.sum()) < 0.5 * место:
            return
        c, = _доли(где, л.до)
        леж = _лаб(c).mean(0)
        д = имя - леж
        if not (abs(д[0]) >= ДАЛЕКО_L or math.hypot(д[1], д[2]) >= ДАЛЕКО_AB):
            return
        м = np.array([1.0 / 255.0, 1.0, 1.0])            # L серой шкалы — в единицы a, b
        путь = float(((след - леж) * м * (д * м)).sum() / ((д * м) ** 2).sum())
        if путь < ПУТЬ:
            о.__dict__['серый'] = {'закрыто': о.__dict__['закрыто'], 'путь': round(путь, 2), 'лежало': _тон(*леж), 'названо': _тон(*имя)}


def слово_чужого(ч, коротко=False):
    """Факт С19: в `print(о)` — полностью, в подсказке — коротко (строка подсказки — до ~220 знаков)."""
    Δh = '' if ч['Δh'] is None else f" / Δh {ч['Δh']:+.0f}°"
    if коротко:
        if ч['Δh'] is None or abs(ч['Δh']) < 5.0:          # тон не повернулся — сдвиг насыщенности
            Δh = ''
        return (f"ход по сырому чужому цвету: подобрано {ч['подобрано']:.2f}, тон сдвинут на ΔL {ч['ΔL']:+.0f}"
                f"{Δh or ' / Δa, b ' + format(ч['Δab'], '.3f')} (лежало L {ч['лежало']['L']:.0f}, названо L {ч['названо']['L']:.0f})")
    return (f"ход по сырому чужому цвету: подобрано {ч['подобрано']:.2f} к положенному, тон сдвинут на ΔL {ч['ΔL']:+.0f}{Δh}, "
            f"Δa, b {ч['Δab']:.3f} (лежало L {ч['лежало']['L']:.0f} {ч['лежало']['hex']}, названо L {ч['названо']['L']:.0f} {ч['названо']['hex']})")


def слово_серого(с, L):
    """Факт С20 — и в `print(о)`, и в подсказке. L — тон следа."""
    return (f"мягкая по сухому в новом слое — серый: закрыто {с['закрыто']:.2f}, тон следа L {L:.0f} — {100 * с['путь']:.0f} % пути "
            f"от лежащего (L {с['лежало']['L']:.0f}) к названному (L {с['названо']['L']:.0f})")
