"""v4, М-1: палитра замесов — именованные цвета холста; мазок берёт цвет именем замеса.

`х.палитра` — палитра холста (`Палитра`): `х.палитра({'охра свет': (214, 168, 96), 'тень': цвет(60, 0.03, 40)})` —
завести или поправить замесы разом, `х.палитра.добавить(имя, цвет)` — один; каждая правка — строка журнала
{"palette": имя, "color": [r, g, b], "paint": …} (этап и объект — от пометки), её исполняет повтор. Замес — любой цвет
мазка одной краской: (r, g, b), `Краска(rgb, вид)`, `цвет(L, C, h)`, `смешать_srgb(…)`.

Мазок именем: `цвет='охра свет'` в `мазок`, `проба`, `перебор`, `варианты` (у участка — та же палитра); список имён —
набор (смесь замесов на кисти, `раскладка` — как у набора); элементы списка — имя, (имя, доля), rgb, (rgb, доля).
`к.набрать(х.палитра['охра свет'])` или `х.палитра.набрать(к, 'охра свет')` — кисть набирает замес. Нет имени —
KeyError с ближайшими именами. Мазок именем ложится теми же пикселями, что тем же цветом напрямую: имя меняет только
журнал — строка мазка несёт и цвет, и "swatch" (имя или список имён, null — краска без имени), а повтор берёт цвет
из строки палитры выше: правка строки замеса и `--resume` пересобирают мазки этого замеса, остальные — бит в бит.

`х.палитра_с(область, образец, n)` — n замесов по образцу черновиком (`Черновик`: словарь «имя → (r, g, b)»,
доли площади, замощение образца замесами в прищуре); ничего не заводит и не кладёт. Считается так: образец в
области слегка размыт, k средних по площади в светлоте серой шкалы (/255) и a, b OKLab; начало — ступени
светлоты поровну от тёмного края до светлого, так тёмное и светлое пятно малой площади остаются своими замесами.

Палитра не меняет цвет мазка сама: оттенок даёт кисть (грязь, `разброс_тона`, сырое под ходом).
"""
import difflib
import math
import os

import numpy as np

from .краска import Краска


class Замес(Краска):
    """Цвет замеса палитры: `Краска` с именем (`имя`). Идёт везде, где цвет; журнал пишет рядом с цветом имя."""
    def __new__(cls, rgb, вид='кроющая', имя=''):
        с = super().__new__(cls, rgb, вид)
        с.имя = str(имя)
        return с

    def __reduce__(self):
        return (Замес, (tuple(self), self.вид, self.имя))

    def __repr__(self):
        return f'Замес({self.имя!r}, ({", ".join(_число_строкой(v) for v in self)}))'


def _число_строкой(v):
    return str(int(v)) if float(v).is_integer() else repr(float(v))


def замес(имя, цвет):
    """Цвет одной краской -> `Замес` с именем (вид краски — от `Краска`). Набор и не цвет — ValueError."""
    if isinstance(имя, str) is False or not имя.strip():
        raise ValueError(f'палитра: имя замеса — непустая строка, а не {имя!r}')
    if isinstance(цвет, str):
        raise ValueError(f'палитра: замес «{имя}» — цвет (r, g, b), Краска или цвет(L, C, h), а не имя {цвет!r}')
    try:
        ц = [float(v) for v in np.asarray(цвет, np.float64).ravel()]
    except (TypeError, ValueError):
        ц = []
    if len(ц) != 3 or np.ndim(цвет) != 1:
        raise ValueError(f'палитра: замес «{имя}» — одна краска (r, g, b) 0–255, а не {цвет!r} (смесь двух замесов — '
                         'списком имён в мазке)')
    if not all(-1e-9 <= v <= 255.0 + 1e-9 for v in ц):
        raise ValueError(f'палитра: замес «{имя}» — sRGB 0–255, а не {tuple(ц)}')
    return Замес(ц, getattr(цвет, 'вид', 'кроющая'), имя)


def ближайшие(имя, имена, n=3):
    """Имена палитры, похожие на имя (для ошибки)."""
    имена = list(имена)
    б = difflib.get_close_matches(str(имя), имена, n=n, cutoff=0.4)
    if not б:
        б = [и for и in имена if str(имя).split()[0] in и][:n] if str(имя).split() else []
    return б


class НетЗамеса(KeyError):
    """Имени нет в палитре холста (KeyError с ближайшими именами)."""
    def __str__(self):
        return str(self.args[0])


def _нет(имя, замесы):
    б = ближайшие(имя, замесы)
    if not замесы:
        return НетЗамеса(f'палитра: замеса «{имя}» нет — палитра пуста (х.палитра({{имя: цвет}}), черновик — '
                         'х.палитра_с(область, образец, n))')
    return НетЗамеса(f'палитра: замеса «{имя}» нет' + (f'; ближайшие: {", ".join(repr(и) for и in б)}' if б else '')
                     + f' (в палитре {len(замесы)}: х.палитра)')


def есть_имена(цвет):
    """В цвете мазка есть имя замеса (строка или список с именами)."""
    if isinstance(цвет, str):
        return True
    if isinstance(цвет, (list, tuple)) and not isinstance(цвет, Краска):
        for э in цвет:
            if isinstance(э, str) or (isinstance(э, (list, tuple)) and len(э) == 2 and isinstance(э[0], str)):
                return True
    return False


def разрешить(цвет, замесы):
    """Цвет мазка с именами замесов -> тот же цвет замесами (`Замес`); без имён — как есть (тот же объект)."""
    if not есть_имена(цвет):
        return цвет

    def один(имя):
        з = замесы.get(имя)
        if з is None:
            raise _нет(имя, замесы)
        return з
    if isinstance(цвет, str):
        return один(цвет)
    итог = []
    for э in цвет:
        if isinstance(э, str):
            итог.append(один(э))
        elif isinstance(э, (list, tuple)) and len(э) == 2 and isinstance(э[0], str):
            итог.append((один(э[0]), э[1]))
        else:
            итог.append(э)
    return итог


def имена_цвета(цвет):
    """Имя замеса одной краски (str), список имён набора по краскам (None — краска без имени) или None — имён нет."""
    if цвет is None:
        return None
    if isinstance(цвет, Замес):
        return цвет.имя
    if isinstance(цвет, Краска):
        return None
    ц = list(цвет)
    from .инструмент import _число
    if ц and _число(ц[0]):
        return None
    имена = []
    for э in ц:
        if isinstance(э, Замес):
            имена.append(э.имя)
        elif isinstance(э, (list, tuple)) and len(э) == 2 and isinstance(э[0], Замес):
            имена.append(э[0].имя)
        else:
            имена.append(None)
    return имена if any(и is not None for и in имена) else None


def цвет_из_строки(з, замесы, цвет):
    """Повтор: цвет строки мазка или набора с "swatch" — замесы палитры повтора по имени; доли и краски без имени — из
    строки (`цвет` — то, что прочёл `повтор._цвет`)."""
    имена = з.get('swatch')
    if имена is None:
        return цвет
    if isinstance(имена, str):
        if имена not in замесы:
            raise _нет(имена, замесы)
        return замесы[имена]
    if not isinstance(цвет, list) or len(цвет) != len(имена):
        raise ValueError(f'"swatch" списком — по имени (или null) на каждую краску "colors" ({len(имена)} имён)')
    итог = []
    for э, имя in zip(цвет, имена):
        if имя is None:
            итог.append(э)
            continue
        if имя not in замесы:
            raise _нет(имя, замесы)
        if isinstance(э, (list, tuple)) and len(э) == 2 and not isinstance(э[0], (int, float)):
            доля = э[1]
        elif isinstance(э, (list, tuple)) and len(э) == 4:
            доля = э[3]
        else:
            доля = 1.0
        итог.append((замесы[имя], доля))
    return итог


class Палитра:
    """`х.палитра`: замесы холста по имени. `х.палитра({имя: цвет, …})` — завести или поправить разом (строки журнала),
    `добавить(имя, цвет)` — один, `х.палитра['имя']` — `Замес` (годится в `мазок`, `к.набрать`), `набрать(к, имя
    или [имена])` — кисть набирает замес; `имена`, `len`, `in`; `print(х.палитра)` — таблица: имя, rgb, L C h."""

    def __init__(self, холст):
        self._х = холст

    @property
    def _замесы(self):
        return self._х.__dict__.setdefault('_замесы', {})

    def __call__(self, замесы, этап=None, объект=None):
        if not isinstance(замесы, dict):
            raise ValueError('палитра: замесы — словарь {имя: цвет}')
        готовые = [замес(имя, ц) for имя, ц in замесы.items()]     # сперва все проверены: кривой — ни один не заведён
        for з in готовые:
            self._завести(з, этап, объект)
        return self

    def добавить(self, имя, цвет, этап=None, объект=None):
        """Завести замес или поправить: строка журнала {"palette": имя, "color": …}; мазки после неё — новым цветом,
        легшие раньше — прежним (повтор берёт цвет из строки выше мазка)."""
        self._завести(замес(имя, цвет), этап, объект)
        return self._замесы[str(имя)]

    def _завести(self, з, этап, объект):
        х = self._х
        self._замесы[з.имя] = з          # мазки, принятые раньше, уже взяли свой цвет: досчитывать их не нужно
        ж = х._пишет()
        if ж is not None:
            from .журнал import цвет_строки
            д = {'palette': з.имя}
            поля = цвет_строки(Краска(tuple(з), з.вид))
            д.update(поля)
            ж.строка(ж._намерение(д, этап, объект))

    def __getitem__(self, имя):
        з = self._замесы.get(имя)
        if з is None:
            raise _нет(имя, self._замесы)
        return з

    def __contains__(self, имя):
        return имя in self._замесы

    def __len__(self):
        return len(self._замесы)

    def __iter__(self):
        return iter(list(self._замесы))

    @property
    def имена(self):
        return list(self._замесы)

    def items(self):
        return list(self._замесы.items())

    def набрать(self, кисть, цвет, количество=None, раскладка='полосы'):
        """`кисть.набрать` именем замеса или списком имён (набор); количество (Д-1) — доля полной кисти, краска живая
        (то же — `х.набрать(кисть, цвет, количество)`)."""
        if isinstance(количество, str):       # прежний вызов: третий довод был раскладкой
            количество, раскладка = None, количество
        return кисть.набрать(разрешить(цвет, self._замесы), количество, раскладка)

    def __repr__(self):
        if not self._замесы:
            return 'палитра пуста: х.палитра({имя: цвет}); черновик по образцу — х.палитра_с(область, образец, n)'
        from .глаз import лцх
        с = [f'палитра: {len(self._замесы)} замесов']
        for имя, з in self._замесы.items():
            L, C, h = лцх(np.asarray(tuple(з)))
            вид = '' if з.вид == 'кроющая' else f', {з.вид}'
            с.append(f'  {имя}: ({", ".join(_число_строкой(round(v, 2)) for v in з)}) L {L:.0f} C {C:.3f} h {h:.0f}{вид}')
        return '\n'.join(с)

    __str__ = __repr__


# ---------------------------------------------------------------- черновик по образцу

ВЕС_L = 1.0          # светлота серой шкалы / 255 против a, b OKLab: тон и оттенок поровну
ТОЧЕК = 40000        # образец для счёта — не больше стольких пикселей (уменьшен средним)
ИТЕРАЦИЙ = 40


class Черновик(dict):
    """Ответ `палитра_с`: словарь «имя → (r, g, b)», светлые первыми (замеса, которому в образце не досталось площади, —
    нет: замесов бывает меньше n); `доли` — доля площади области у каждого,
    `замощение` — (В, Ш, 3) образец области, где каждый пиксель — ближайший замес, `прищур_dL` — средняя разность
    тона образца и замощения в прищуре (как `х.виды`), L; `лист` — uint8 «образец | замощение | плашки» (`путь` —
    PNG). В палитру — `х.палитра(ч)` или своей правкой."""

    def __repr__(self):
        from .глаз import лцх
        с = [f'черновик палитры: {len(self)} замесов, замощение образца в прищуре |dL| {self.прищур_dL:.1f}'.replace('.', ',')]
        for имя, ц in self.items():
            L, C, h = лцх(np.asarray(ц, np.float64))
            с.append(f'  {имя!r}: {tuple(ц)},  L {L:.0f} C {C:.3f} h {h:.0f}, площадь {100 * self.доли[имя]:.0f} %')
        return '\n'.join(с)

    __str__ = __repr__


_ТОНА = ((20, 'красный'), (45, 'оранжевый'), (75, 'охристый'), (110, 'жёлтый'), (165, 'зелёный'), (215, 'бирюзовый'),
         (290, 'синий'), (335, 'фиолетовый'), (361, 'красный'))


def имя_цвета(rgb):
    """Имя по тону и оттенку: «тёмный серо-синий 54» (число — L серой шкалы)."""
    from .глаз import лцх
    L, C, h = лцх(np.asarray(rgb, np.float64))
    свет = 'тёмный' if L < 85 else 'средний' if L < 170 else 'светлый'
    if C < 0.025:
        оттенок = 'серый тёплый' if (C > 0.008 and (h < 110 or h > 335)) else 'серый холодный' if C > 0.008 else 'серый'
    else:
        оттенок = next(слово for предел, слово in _ТОНА if h < предел)
        if C < 0.06:
            оттенок = 'серо-' + оттенок
    return f'{свет} {оттенок} {L:.0f}'


def _уменьшить(a, k):
    if k <= 1:
        return a
    в, ш = (a.shape[0] // k) * k, (a.shape[1] // k) * k
    return a[:в, :ш].reshape(в // k, k, ш // k, k, a.shape[2]).mean(axis=(1, 3))


def _прищур_L(rgb):
    """L прищура, как у `х.виды`: светлота, трижды размытая на ~1/120 длинной стороны."""
    from .глаз import oklab, _L, _размыть
    L = _L(oklab(rgb)[..., 0])
    r = max(1, int(round(max(L.shape) / 120)))
    for _ in range(3):
        L = _размыть(L, r)
    return L


def _в_точки(rgb):
    """sRGB -> точки кластеров: L серой шкалы / 255 (весом `ВЕС_L`), a, b OKLab."""
    from .глаз import oklab, _L
    lab = oklab(rgb)
    return np.concatenate([_L(lab[..., :1]) / 255.0 * ВЕС_L, lab[..., 1:]], -1)


def кластеры(p, n, итераций=ИТЕРАЦИЙ):
    """k средних по точкам `_в_точки` (N, 3); начало — n ступеней светлоты поровну от p1 до p99 (не по площади: светлое
    и тёмное пятно малой площади получают свой центр); пустой кластер берёт точку, дальнюю от своих центров. Ответ —
    центры (n, 3), номер центра каждой точки."""
    L = p[:, 0]
    lo, hi = np.percentile(L, [1, 99])
    ступени = lo + (hi - lo) * (np.arange(n) + 0.5) / n
    ц = np.empty((n, 3))
    for k, s in enumerate(ступени):                    # центр ступени — средняя точка у этой светлоты
        м = np.abs(L - s) <= max((hi - lo) / (2 * n), 1e-3)
        ц[k] = p[м].mean(0) if м.any() else p[np.abs(L - s).argmin()]
    for _ in range(итераций):
        d = ((p[:, None, :] - ц[None, :, :]) ** 2).sum(-1)
        j = d.argmin(1)
        новые = ц.copy()
        for k in range(n):
            м = j == k
            if м.any():
                новые[k] = p[м].mean(0)
            else:
                далёкая = int(d[np.arange(len(p)), j].argmax())
                новые[k] = p[далёкая]
                j[далёкая] = k
        if np.allclose(новые, ц, atol=1e-6):
            ц = новые
            break
        ц = новые
    d = ((p[:, None, :] - ц[None, :, :]) ** 2).sum(-1)
    return ц, d.argmin(1)


def _в_rgb(ц):
    from .глаз import из_oklab, _из_L
    lab = np.concatenate([_из_L(np.clip(ц[..., :1] / ВЕС_L, 0, 1) * 255.0), ц[..., 1:]], -1)
    return np.clip(np.round(из_oklab(lab)), 0, 255).astype(int)


def палитра_с(образец, n=12, путь=None):
    """Черновик палитры: n замесов по картинке образца (sRGB 0–255 (В, Ш, 3)) — `Черновик`. Ничего не заводит."""
    from .глаз import oklab, _размыть
    a = np.asarray(образец, np.float64)[..., :3]
    n = int(n)
    if a.ndim != 3 or a.shape[0] < 2 or a.shape[1] < 2:
        raise ValueError(f'палитра_с: образец — картинка (В, Ш, 3), а не {a.shape}')
    if not 1 <= n <= 64:
        raise ValueError(f'палитра_с: n — от 1 до 64 замесов, а не {n}')
    k = max(1, int(math.ceil(math.sqrt(a.shape[0] * a.shape[1] / ТОЧЕК))))
    м = _уменьшить(a, k)
    r = max(1, int(round(max(м.shape[:2]) / 240)))      # мелкий шум не делает замеса: размыто вчетверо слабее прищура
    м = np.stack([_размыть(м[..., i], r) for i in range(3)], -1)
    центры, _ = кластеры(_в_точки(м).reshape(-1, 3), min(n, м.shape[0] * м.shape[1]))
    rgb = _в_rgb(центры)
    т_ц = _в_точки(rgb.astype(np.float64))
    j = np.empty(a.shape[:2], np.intp)
    for y0 in range(0, a.shape[0], 256):                # ближайший замес каждому пикселю образца — кусками
        j[y0:y0 + 256] = ((_в_точки(a[y0:y0 + 256])[..., None, :] - т_ц) ** 2).sum(-1).argmin(-1)
    доли = np.bincount(j.ravel(), minlength=len(rgb)) / j.size
    порядок = sorted(range(len(rgb)), key=lambda i: -float(oklab(rgb[i].astype(np.float64))[0]))
    ч = Черновик()
    ч.доли = {}
    for i in порядок:
        if доли[i] <= 0 and len(ч) >= 1:
            continue
        имя = имя_цвета(rgb[i])
        while имя in ч:
            имя += "'"
        ч[имя] = tuple(int(v) for v in rgb[i])
        ч.доли[имя] = round(float(доли[i]), 4)
    ч.замощение = rgb[j].astype(np.float64)
    ч.прищур_dL = round(float(np.abs(_прищур_L(a) - _прищур_L(ч.замощение)).mean()), 2)
    ч.лист = лист_черновика(a, ч)
    if путь is not None:
        from PIL import Image
        Image.fromarray(ч.лист).save(os.path.expanduser(os.fspath(путь)))
    return ч


def лист_черновика(a, ч, ширина_плашек=260):
    """uint8: образец 1:1 | замощение замесами 1:1 | плашки замесов высотой по площади (не уже 18 px) с именем."""
    from PIL import Image, ImageDraw
    from .глаз import _шрифт, светлота
    В, Ш = a.shape[:2]
    лист = Image.new('RGB', (2 * Ш + ширина_плашек + 16, max(В, 18 * len(ч) + 8)), (128, 128, 128))
    лист.paste(Image.fromarray(np.clip(a + 0.5, 0, 255).astype(np.uint8)), (0, 0))
    лист.paste(Image.fromarray(np.clip(ч.замощение + 0.5, 0, 255).astype(np.uint8)), (Ш + 8, 0))
    д = ImageDraw.Draw(лист)
    шрифт = _шрифт(12)
    высоты = [max(18.0, ч.доли[и] * (лист.height - 8)) for и in ч]
    s = (лист.height - 8) / max(sum(высоты), 1.0)
    y = 4.0
    for (имя, ц), h in zip(ч.items(), высоты):
        h *= s if sum(высоты) > лист.height - 8 else 1.0
        д.rectangle((2 * Ш + 16, int(y), 2 * Ш + 16 + ширина_плашек - 4, int(y + h) - 2), fill=tuple(ц))
        тон = (0, 0, 0) if светлота(np.asarray(ц, np.float64)) > 140 else (255, 255, 255)
        д.text((2 * Ш + 20, int(y) + 2), f'{имя} {100 * ч.доли[имя]:.0f}%', fill=тон, font=шрифт)
        y += h
    return np.asarray(лист)


# ---------------------------------------------------------------- кисть.набрать с именем
def _обернуть_набрать():
    """`к.набрать('имя')` — ValueError словами (имя знает холст). Обёртка здесь, а не в `инструмент.py`: тот входит в
    хеш физики калибровки (`калибровка._ФИЗИКА`), правка его кода сделала бы таблицы чужими."""
    import functools
    from .инструмент import Кисть
    прежний = Кисть.набрать
    if getattr(прежний, '_палитра', False):
        return

    @functools.wraps(прежний)
    def набрать(self, цвет, количество=None, раскладка='полосы'):
        if есть_имена(цвет):
            raise ValueError(f'набрать: имя замеса {цвет!r} — у холста: х.набрать(к, имя или [имена][, количество]) или '
                             'к.набрать(х.палитра[имя])')
        return прежний(self, цвет, количество, раскладка)
    набрать._палитра = True
    Кисть.набрать = набрать


_обернуть_набрать()
