ПОТОЛОК = 16            # процессов — не больше (правило машины)
ОЧЕРЕДЬ = 512           # мазков в очереди: дальше вызов мазка ждёт счёта
_СЕТКА = 16             # px: шаг сетки, которой ищутся сырые пиксели-свидетели слоя
_СВИДЕТЕЛЕЙ = 256       # столько свидетелей держится на слой
С_МАЗКА = 48            # первые мазки холста — в главном процессе: короткий лист процессов не заводит
_ПРЕЖНЕЕ = '\0прежнее'   # поле кисти (`_остаток`, `_набрано`, `_баланс`), которого мазок не тронул
_НЕТ = object()         # рамка мазка ещё не считана
_ЖДЁТ = object()        # мягкой кисти ещё не сказано, есть ли в слое сырое
_СЛОТЫ = ('_цвет', '_покрытие', '_толщина', '_влажность', '_схват', '_пропуск', '_текучая')


def число_ядер(ядра=None):
    """Сколько процессов брать: число из вызова; None — переменная окружения `KIST_CORES`, без неё — ядра машины, не
    больше 16. 1 — счёт на одном ядре, как прежде."""
    if ядра is None:
        ядра = os.environ.get('KIST_CORES') or os.cpu_count() or 1
    ядра = int(ядра)
    if ядра < 1:
        raise ValueError('ядра: число процессов от 1')
    return min(ядра, ПОТОЛОК)


def можно():
    """Можно ли этому процессу заводить процессы счёта: потомку-демону (процесс пула) — нельзя, он считает сам."""
    return not multiprocessing.current_process().daemon


class ТесныйПрямоугольник(RuntimeError):
    """Мазок назвал рамку шире среза холста, который ему дан по его же рамке: на ядрах он не бит в бит."""


class _Почему(dict):
    """Словарь «почему пусто» мазка в процессе: рамку мазка (вне неё мазок холста не читает и не пишет) сверяет со срезом
    холста, как только мазок её назвал, — до первой записи. Шире среза — мазок бросается нетронутым."""

    def __init__(self, х, у):
        super().__init__()
        self.холст = (х.x0, х.y0, х.x0 + х.ширина, х.y0 + х.высота)
        self.срез = (у.x0, у.y0, у.x0 + у.ширина, у.y0 + у.высота)

    def __setitem__(self, ключ, v):
        if ключ == 'рамка':
            х, с = self.холст, self.срез
            r = (max(v[0], х[0]), max(v[1], х[1]), min(v[2], х[2]), min(v[3], х[3]))
            if r[2] > r[0] and r[3] > r[1] and (r[0] < с[0] or r[1] < с[1] or r[2] > с[2] or r[3] > с[3]):
                raise ТесныйПрямоугольник(f'рамка мазка {r} шире среза {с}')
        super().__setitem__(ключ, v)


class _СкажиРамку(dict):
    """Словарь «почему пусто» мазка, что идёт в процессе один раз, без счёта до рамки заранее: рамку, как только мазок
    её назвал, — главному процессу (по ней он пустит мазки после этого), и мазок кладётся дальше."""

    def __init__(self, труба, номер):
        super().__init__()
        self.труба, self.номер = труба, номер

    def __setitem__(self, ключ, v):
        if ключ == 'рамка':
            self.труба.send_bytes(pickle.dumps({'номер': self.номер, 'рамка': v, 'дальше': True}, pickle.HIGHEST_PROTOCOL))
        super().__setitem__(ключ, v)


class _Мазок:
    """Мазок очереди. рамка: `_НЕТ` — не считана; None — мазок кончился до рамки (холста не тронул); иначе — прямоугольник
    холста. до — что было на кисти перед мазком: подобранное или более ранний мазок очереди (тогда этот его ждёт);
    после — что на кисти после (когда досчитан). ось — у мягкой кисти по сырому: где её счёт до рамки читает холст."""
    __slots__ = ('очередь', 'номер', 'з', 'слои', 'слой', 'кисть', 'хозяин', 'до', 'после', 'сыро', 'ось', 'рамка', 'рамка_идёт',
                 'идёт', 'готов', 'ответ', 'метка', 'мешают', 'кому')      # мешают — более ранние недосчитанные мазки, чьи рамки пересекают эту; кому — кому мешает этот

    @property
    def ждёт_кисть(self):
        return self.до if isinstance(self.до, _Мазок) and not self.до.готов else None


class Отложенный:
    """Ответ `Холст.мазок` на ядрах: мазок принят (журнал, сид, счётчик — как на одном ядре), пиксели досчитаются
    позже. `взять()` — досчитать этот мазок и дать его ответ: записанный прямоугольник (x0, y0, x1, y1) или None
    (следа нет). Как кортеж — то же: `tuple(изм)`, `изм[0]`, `x0, y0, x1, y1 = изм`, `bool(изм)`, `изм == (…)`.
    Только `изм is None` не сработает: пустой мазок — `not изм` или `изм.взять() is None`."""
    __slots__ = ('_м',)

    def __init__(self, м):
        self._м = м

    def взять(self):
        м = self._м
        while not м.готов:
            м.очередь._принять()
        return м.ответ['изм']

    def __getattr__(self, имя):
        if имя.startswith('_'):
            raise AttributeError(имя)
        изм = self.взять()                 # 3г (К-1): замер следа — `изм.цвет`, `изм.закрыто`… — досчитает этот мазок
        if изм is None:
            raise AttributeError(f'мазок не оставил следа: его ответ — None, поля «{имя}» нет (проверка — `not изм`)')
        return getattr(изм, имя)

    def __str__(self):
        return str(self.взять())

    def _кортеж(self):
        изм = self.взять()
        if изм is None:
            raise TypeError('мазок не оставил следа: его ответ — None (проверка — `not изм` или `изм.взять() is None`)')
        return изм

    def __bool__(self):
        return self.взять() is not None

    def __iter__(self):
        return iter(self._кортеж())

    def __len__(self):
        return len(self._кортеж())

    def __getitem__(self, i):
        return self._кортеж()[i]

    def __eq__(self, другое):
        if isinstance(другое, Отложенный):
            другое = другое.взять()
        return self.взять() == другое

    def __ne__(self, другое):
        return not self == другое

    __hash__ = None

    def __repr__(self):
        return repr(self.взять())


def _вид(х, п, слои, сыро, цель):
    """Холст-срез: прямоугольник `п` холста `х` без копии — мазок на нём пишет прямо в общую память, но только здесь."""
    from .холст import Холст, Слой
    from .плитки import Плитки
    гy, гx = х._область(п)
    if гy.stop <= гy.start or гx.stop <= гx.start:
        # Рамка (ось) мимо холста — мазок холста не трогает, но идёт ради кисти. На одном ядре он идёт на целом холсте и
        # читает под волосками по маске «внутри холста» с индексом 0 вместо чужих мест; у пустого среза индекса 0 нет.
        # Срез — один пиксель холста у угла: волоски вне холста — вне и его, читается он только под маской, не пишется.
        y0, x0 = min(гy.start, х.высота - 1), min(гx.start, х.ширина - 1)
        гy, гx = slice(y0, y0 + 1), slice(x0, x0 + 1)
    у = Холст.__new__(Холст)
    у.__dict__.update(х.__dict__)
    у.x0, у.y0 = х.x0 + гx.start, х.y0 + гy.start
    у.ширина, у.высота = гx.stop - гx.start, гy.stop - гy.start
    у._снимки, у._повторы, у.журнал, у._вне_журнала, у._тихо, у._пустые, у._ядра, у._ядер = [], None, None, False, 1, {}, None, 1
    у._подсказки = None
    у._слои = {}
    for имя in слои:
        с = х._слои[имя]
        н = Слой.__new__(Слой)
        for слот in _СЛОТЫ:
            a = getattr(с, слот, None)
            if a is not None:
                setattr(н, слот, a.окно(гy, гx) if isinstance(a, Плитки) else a[гy, гx])
        if имя == цель and сыро is not None:
            н._сыро = сыро
        у._слои[имя] = н
    return у


def _работник(х, труба, чужие=()):
    """Процесс: берёт мазок и считает его на срезе холста — до рамки (отдаёт рамку) или целиком (отдаёт, что стало с
    кистью). Мазок, кончившийся до рамки, досчитан уже первым счётом."""
    from .холст import _Рамка, _ТолькоРамка
    for т in чужие:               # концы труб главного, взятые ветвлением: без них смерть главного видна как конец трубы
        т.close()
    while True:
        try:
            задача = труба.recv_bytes()
        except (EOFError, OSError):
            return
        if задача == b'':
            return
        номер, до_рамки, п, слои, сыро, кисть, з = pickle.loads(задача)
        ответ = {'номер': номер, 'до_рамки': до_рамки}
        t0 = time.perf_counter()
        try:
            у = _вид(х, п, слои, сыро, з['слой'])
            массивы = [(с, слот, getattr(с, слот, None)) for с in у._слои.values() for слот in _СЛОТЫ]
            почему = _ТолькоРамка() if до_рамки else _СкажиРамку(труба, номер) if п is None else _Почему(х, у)
            кисть._набрано = кисть._баланс = _ПРЕЖНЕЕ
            with warnings.catch_warnings(record=True) as слова:
                warnings.simplefilter('always')
                try:
                    изм, _ = у._положить(з, кисть, почему)
                except _Рамка as e:
                    ответ['рамка'] = e.args[0]
                else:
                    for с, слот, a in массивы:
                        if getattr(с, слот, None) is not a:
                            raise ТесныйПрямоугольник(f'мазок завёл или подменил массив слоя «{слот}» в процессе')
                    ответ.update(изм=изм, почему=dict(почему), остаток=сырое_поле(кисть, '_остаток'), набрано=сырое_поле(кисть, '_набрано'),
                                 баланс=сырое_поле(кисть, '_баланс'), слова=[(str(w.message), w.category) for w in слова])
        except BaseException as e:      # noqa: BLE001 — ошибка мазка идёт в главный процесс и звучит там
            ответ['ошибка'] = (e if isinstance(e, (ValueError, ТесныйПрямоугольник)) else None, traceback.format_exc())
        ответ['сек'] = time.perf_counter() - t0       # сколько шёл счёт: для замеров очереди
        try:
            труба.send_bytes(pickle.dumps(ответ, pickle.HIGHEST_PROTOCOL))
        except (BrokenPipeError, OSError):
            return


class Ядра:
    """Очередь мазков холста на ядрах. `мазок(запись, кисть, журнал)` — мазок, принятый холстом (`Холст._принять_мазок`):
    считается, когда дойдёт черёд; `граница()` — после неё холст и кисти — как после тех же мазков на одном ядре.
    Повтор журнала даёт холсту `_готово(метка, изм, слова)` — зовётся в порядке мазков, когда мазок досчитан (метка —
    `холст._метка` на миг вызова мазка, слова — предупреждения мазка, [(текст, вид)])."""

    def __init__(self, холст, ядра=None):
        self.х = холст
        self.ядра = число_ядер(ядра)
        self.pid = os.getpid()
        self._ждут = []           # мазки по порядку вызовов: не отданные и идущие; досчитанные с головы уходят
        self._процессы = []       # [процесс, труба, мазок или None]
        self._подпись = None      # слои и их массивы, какими их видят процессы
        self._номер = 0
        self._сырое = {}          # слой -> (ys, xs): сырые пиксели-свидетели, которых не тронул ни один мазок слоя с тех пор
        self._хвост = {}          # id(кисти) -> последний её мазок в очереди
        self._кистей = {}         # id(кисти) -> сколько её мазков в очереди
        self._сломана = None
        self.мазков = self.разом = 0     # сколько мазков ушло процессам и сколько из них — когда уже шёл другой

    # ------------------------------------------------------------ процессы
    def _слои_те_же(self):
        слои = self.х._слои
        if len(слои) != len(self._подпись):
            return False
        for (имя, с), (было, слой, массивы) in zip(слои.items(), self._подпись):
            if имя != было or с is not слой or any(getattr(с, слот, None) is not a for слот, a in zip(_СЛОТЫ, массивы)):
                return False
        return True

    def _пустить_процессы(self):
        if self._процессы:
            return
        from .холст import _в_общую
        for с in self.х._слои.values():
            for слот in _СЛОТЫ:
                a = getattr(с, слот, None)
                if a is not None:
                    setattr(с, слот, _в_общую(a))
            с._ждать = self.граница
        self._подпись = [(имя, с, [getattr(с, слот, None) for слот in _СЛОТЫ]) for имя, с in self.х._слои.items()]
        среда = get_context('fork')
        for _ in range(self.ядра):
            наша, его = среда.Pipe()
            п = среда.Process(target=_работник, args=(self.х, его, [з[1] for з in self._процессы] + [наша]), daemon=True)
            п.start()
            его.close()
            self._процессы.append([п, наша, None])

    def _остановить(self):
        for п, труба, _ in self._процессы:
            try:
                труба.send_bytes(b'')
            except (BrokenPipeError, OSError):
                pass
            труба.close()
        for п, _, _ in self._процессы:
            п.join(5)
            if п.is_alive():
                п.kill()
        self._процессы = []

    # --------------------------------------------------------------- мазок
    def мазок(self, з, кисть, ж=None):
        """Поставить принятый мазок в очередь. Ответ — `Отложенный`; мазок, посчитанный сразу (первые `С_МАЗКА`, при
        живом снимке, новый массив слоя), — его ответ как на одном ядре."""
        х = self.х
        if self._сломана:
            raise RuntimeError(self._сломана)
        self._номер += 1
        слой = з['слой']
        цель = х._слои[слой]
        _, мутность, ровно, _ = разбавить(з.get('разбавитель'), 0.0, getattr(з['краски'], 'мутность', 1.0), з['ровно'], None)
        if (self._номер <= С_МАЗКА or з.get('живая') or х._снимки or х.__dict__.get('_ленты') or (х.x0, х.y0, х.ширина, х.высота) != (0, 0, х.полная_ширина, х.полная_высота)
                or (мутность < 1.0 and getattr(цель, '_пропуск', None) is None)      # Г-1: разбавитель — тоже не кроющая и текучая
                or (ровно and getattr(цель, '_текучая', None) is None)):
            return self._сам(з, кисть, ж)                 # новый массив слоя, снимок холста — в главном; Н-3: и мазок по ленте скотча (затёк пишется ленте); Д-1: и ход живой краской — он начинает с остатка прошлого хода кисти, идёт по порядку
        if self._процессы and not self._слои_те_же():     # новый слой или массив: процессам он не виден — завести их заново
            self.досчитать(оставить=True)
            self._остановить()
        до = сырое_поле(кисть, '_остаток')
        if isinstance(до, _Мазок) and до.очередь is not self:
            до = кисть._остаток                           # кисть с недосчитанным мазком другого холста: досчитать его
        м = _Мазок()
        м.очередь, м.номер, м.з, м.слой, м.метка = self, self._номер, з, слой, х.__dict__.get('_метка')
        м.слои = tuple(х._слои)
        м.рамка, м.рамка_идёт, м.идёт, м.готов, м.ответ, м.после, м.сыро, м.ось = _НЕТ, False, False, False, None, None, None, None
        м.мешают, м.кому = set(), []
        if getattr(кисть, 'кайма', 0.0) > 0.0 and кисть.форма != 'мастихин':        # мягкая: есть ли в слое сырое вообще — ответ позже
            м.сыро = _ЖДЁТ
        м.до = до
        м.хозяин = кисть
        м.кисть = copy.copy(кисть)                  # кисть как она есть на этом вызове; подобранное — перед счётом
        м.кисть.__dict__.pop('_ждёт_ядра', None)
        м.кисть._остаток = _ПРЕЖНЕЕ
        кисть._остаток = м                          # до счёта: «что останется после этого мазка»
        кисть.__dict__['_ждёт_ядра'] = self
        self._хвост[id(кисть)] = м
        self._кистей[id(кисть)] = self._кистей.get(id(кисть), 0) + 1
        if ж is not None:
            ж.после_мазка(кисть)
        self._ждут.append(м)
        self._раздать()
        while len(self._ждут) >= ОЧЕРЕДЬ:
            self._принять()
        return Отложенный(м)

    def _сыро_ли(self, i):
        """Ответить мягкой кисти мазка `_ждут[i]`, есть ли в его слое сырое на его черёд (шапка модуля). Ответ: дан ли."""
        м, х = self._ждут[i], self.х
        слой = м.слой
        раньше = [д for д in self._ждут[:i] if д.слой == слой and not д.готов]
        if any(д.рамка is _НЕТ for д in раньше):      # рамки более ранних мазков слоя ещё не все известны: свидетели под ними не сняты
            return False
        с = self._сырое.get(слой)
        w = х._слои[слой]._влажность
        if с is None or not len(с[0]):
            ys, xs = np.nonzero(np.array(w[::_СЕТКА, ::_СЕТКА]))      # копия: под рамками недосчитанных мазков слой сейчас пишется
            ys, xs = ys * _СЕТКА, xs * _СЕТКА
            for д in self._ждут:                      # под рамкой мазка слоя из очереди — ещё пишется или будет: не свидетель
                if д.слой == слой and д.рамка is not _НЕТ and д.рамка is not None and not (д.готов and д.номер < м.номер) and len(ys):
                    r = д.рамка
                    вне = (xs < r[0]) | (xs >= r[2]) | (ys < r[1]) | (ys >= r[3])
                    ys, xs = ys[вне], xs[вне]
            шаг = len(ys) // _СВИДЕТЕЛЕЙ + 1
            с = self._сырое[слой] = (ys[::шаг], xs[::шаг])
        if len(с[0]):
            м.сыро = True
        elif раньше:                                  # свидетеля нет: ждать, пока более ранние мазки слоя досчитаются
            return False
        else:                                         # все мазки слоя до этого досчитаны, после него — не клались: слой как на его черёд
            м.сыро = bool(w.any())
        if м.сыро:                                    # по сырому мягкая кисть до рамки читает холст под волосками на оси хода
            from .путь import _путь
            к = м.кисть.в_пикселях(х.px_на_мм)
            путь = _путь(м.з['точки'], к, np.random.default_rng(м.з['сид']))
            r = 0.5 * float(к.ширина) + 1.0
            м.ось = (max(int(np.floor(путь['x'].min() - r)), 0), max(int(np.floor(путь['y'].min() - r)), 0),
                     min(int(np.ceil(путь['x'].max() + r)) + 1, х.ширина), min(int(np.ceil(путь['y'].max() + r)) + 1, х.высота))
            if м.ось[2] <= м.ось[0] or м.ось[3] <= м.ось[1]:
                м.ось = (0, 0, 0, 0)
        return True

    def _связать(self, м):
        """Рамка мазка стала известна: кто из более ранних недосчитанных ему мешает, кому из более поздних мешает он;
        сырые свидетели слоя под рамкой — сняты."""
        r = м.рамка
        с = self._сырое.get(м.слой)
        if с is not None and len(с[0]):
            вне = (с[1] < r[0]) | (с[1] >= r[2]) | (с[0] < r[1]) | (с[0] >= r[3])
            self._сырое[м.слой] = (с[0][вне], с[1][вне])
        if r[2] <= r[0] or r[3] <= r[1]:
            return
        r = по_сетке(r)                  # 2в: мазки, что идут разом, плиток полей не делят (плитку заводит тот, кто в неё пишет)
        раньше = True
        for д in self._ждут:
            if д is м:
                раньше = False
                continue
            q = д.рамка
            if д.готов or q is _НЕТ or q is None:
                continue
            q = по_сетке(q)
            if q[0] < r[2] and q[2] > r[0] and q[1] < r[3] and q[3] > r[1]:
                if раньше:
                    м.мешают.add(д)
                    д.кому.append(м)
                else:
                    д.мешают.add(м)
                    м.кому.append(д)

    def _сам(self, з, кисть, ж):
        """Мазок в главном процессе, как на одном ядре (до него всё досчитано)."""
        self.досчитать(оставить=True)
        х = self.х
        готово = х.__dict__.get('_готово')
        почему = {}
        try:
            with warnings.catch_warnings(record=True) as слова:
                warnings.simplefilter('always')
                try:
                    изм, к = х._положить(з, кисть, почему)
                finally:
                    if ж is not None:
                        ж.после_мазка(кисть)
                х._учесть_пустой(изм, з['точки'], к, з['непрозрачность'], з['нагрузка'], почему, з=з)
        finally:
            self._сырое.clear()
        if готово is not None:
            готово(х.__dict__.get('_метка'), изм, [(w.message, w.category) for w in слова])
        else:
            for w in слова:
                warnings.warn(w.message, w.category, stacklevel=4)
        return изм

    def _задача(self, м, до_рамки):
        кисть = м.кисть
        if до_рамки:
            п = м.ось if м.ось is not None else (0, 0, 0, 0)
            сырое_до = _ПРЕЖНЕЕ
        else:
            п = None if м.рамка is _НЕТ else м.рамка       # рамка не считана: мазок идёт один раз, на весь холст
            сырое_до = м.до.после if isinstance(м.до, _Мазок) else м.до
        кисть._остаток = сырое_до
        return pickle.dumps((м.номер, до_рамки, п, м.слои, м.сыро, кисть, м.з), pickle.HIGHEST_PROTOCOL)

    def _раздать(self):
        """Отдать свободным процессам работу: счёт до рамки — мазкам по порядку; мазок — тому, чья рамка известна, как и
        рамки всех более ранних недосчитанных, и ни одной из них не пересекает."""
        if not self._ждут:
            return
        if not self._процессы:
            self._пустить_процессы()
        свободны = [з for з in self._процессы if з[2] is None]
        if not свободны:
            return
        ждут = self._ждут
        n = len(ждут)
        известны = n                                   # до этого места очереди рамки всех недосчитанных известны
        ждут_ответа = set()
        for i, м in enumerate(ждут):
            if м.готов or м.рамка is not _НЕТ:
                continue
            if известны == n:
                известны = i
            if м.рамка_идёт:
                continue
            if м.сыро is _ЖДЁТ and (м.слой in ждут_ответа or not self._сыро_ли(i)):      # ответы мягким кистям слоя — по порядку
                ждут_ответа.add(м.слой)
                continue
            if м.ось is not None:                      # читает холст по оси хода: все раньше него — с рамками, и ось свободна
                if известны != i:
                    continue
                о = м.ось
                if any(not д.готов and д.рамка is not None and д.рамка[0] < о[2] and д.рамка[2] > о[0] and д.рамка[1] < о[3]
                       and д.рамка[3] > о[1] for д in ждут[:i]):
                    continue
            з = свободны.pop()
            if all(д.готов for д in ждут[:i]):         # раньше него недосчитанных нет: сразу весь мазок, рамку скажет по дороге
                з[1].send_bytes(self._задача(м, False))
                self.мазков += 1
                self.разом += any(д[2] is not None and not д[2].рамка_идёт for д in self._процессы)
                з[2], м.идёт, м.рамка_идёт = м, True, True
            else:
                з[1].send_bytes(self._задача(м, True))
                з[2], м.рамка_идёт = м, True
            if not свободны:
                return
        for i in range(известны):
            м = ждут[i]
            if м.готов or м.идёт or м.мешают or м.рамка is None or м.ждёт_кисть is not None:
                continue
            з = свободны.pop()
            з[1].send_bytes(self._задача(м, False))
            self.мазков += 1
            self.разом += any(д[2] is not None and not д[2].рамка_идёт for д in self._процессы)
            з[2], м.идёт = м, True
            if not свободны:
                return

    def _досчитан(self, м):
        """Мазок досчитан: что осталось на кисти — кисти (если после него её не трогали) и журналу."""
        о = м.ответ['остаток']
        if isinstance(о, str) and о == _ПРЕЖНЕЕ:
            о = м.до.после if isinstance(м.до, _Мазок) else м.до
        м.после, м.идёт, м.готов = о, False, True
        for д in м.кому:
            д.мешают.discard(м)
        м.кому = []
        хозяин = м.хозяин
        if сырое_поле(хозяин, '_остаток') is м:
            хозяин._остаток = о
        ж = getattr(self.х, 'журнал', None)
        if ж is not None:
            ж.досчитан(хозяин, м, о)
        if self._хвост.get(id(хозяин)) is м:
            del self._хвост[id(хозяин)]

    def _принять(self):
        """Дождаться ответа процесса: рамка мазка или досчитанный мазок; сказать `готово` по порядку."""
        if self._сломана:
            raise RuntimeError(self._сломана)
        идут = {з[1]: з for з in self._процессы if з[2] is not None}
        if not идут:
            self._раздать()
            идут = {з[1]: з for з in self._процессы if з[2] is not None}
            if not идут:
                raise RuntimeError('ядра: очередь стоит — мазки ждут, а ни один не идёт')
        х = self.х
        for труба in wait(list(идут)):
            з = идут[труба]
            м = з[2]
            try:
                ответ = pickle.loads(труба.recv_bytes())
            except (EOFError, OSError):
                self._сломана = f'ядра: процесс мазка {м.номер} умер (память?) — холст недосчитан; писать заново с ядра=1'
                self._остановить()
                raise RuntimeError(self._сломана) from None
            if ответ.get('дальше'):                    # мазок, что идёт один раз, назвал рамку и кладётся дальше
                r = ответ['рамка']
                r = (max(r[0], 0), max(r[1], 0), min(r[2], х.ширина), min(r[3], х.высота))
                м.рамка, м.рамка_идёт = (r if r[2] > r[0] and r[3] > r[1] else (0, 0, 0, 0)), False
                self._связать(м)
                continue
            з[2] = None
            if 'ошибка' in ответ:
                e, след = ответ['ошибка']
                м.рамка, м.рамка_идёт, м.идёт = None, False, False       # мазок с ошибкой следа не оставил: дальше очередь идёт без него
                м.ответ = dict(изм=None, почему={}, остаток=_ПРЕЖНЕЕ, набрано=_ПРЕЖНЕЕ, баланс=_ПРЕЖНЕЕ, слова=[], ошибка=True)
                if isinstance(e, ТесныйПрямоугольник):
                    self._сломана = f'{e}: на ядрах этот лист не бит в бит — считать с ядра=1 и сказать Движку'
                    self._остановить()
                    raise ТесныйПрямоугольник(self._сломана) from None
                if e is not None:
                    e.метка = м.метка
                    if м.метка is None:           # письмо из Python: ошибка звучит позже вызова мазка — сказать, какого
                        e.args = (f'{e} — это мазок № {м.номер} холста (слой «{м.слой}»), он считался на ядрах, ошибка звучит позже '
                                  'его вызова; с Холст(…, ядра=1) — сразу на нём',) + e.args[1:]
                    raise e
                self._сломана = f'ядра: мазок {м.номер} упал в процессе:\n{след}'
                self._остановить()
                raise RuntimeError(self._сломана)
            if ответ['до_рамки']:
                м.рамка_идёт = False
                if 'рамка' in ответ:
                    r = ответ['рамка']
                    r = (max(r[0], 0), max(r[1], 0), min(r[2], х.ширина), min(r[3], х.высота))
                    м.рамка = r if r[2] > r[0] and r[3] > r[1] else (0, 0, 0, 0)
                    self._связать(м)
                else:                                 # мазок кончился до рамки: холста не тронул, досчитан
                    м.рамка, м.ответ = None, ответ
            else:
                if м.рамка is _НЕТ:                   # шёл один раз и кончился до рамки: холста не тронул
                    м.рамка, м.рамка_идёт = None, False
                м.ответ = ответ
                self._досчитан(м)
        for м in self._ждут:                          # кончившиеся до рамки: досчитаны, когда досчитан прошлый мазок их кисти
            if not м.готов and м.рамка is None and м.ответ is not None and м.ждёт_кисть is None:
                self._досчитан(м)
        готово = х.__dict__.get('_готово')
        while self._ждут and self._ждут[0].готов:
            м = self._ждут.pop(0)
            о = м.ответ
            self._кистей[id(м.хозяин)] -= 1
            if not self._кистей[id(м.хозяин)]:           # мазков этой кисти в очереди больше нет
                del self._кистей[id(м.хозяин)]
                if м.хозяин.__dict__.get('_ждёт_ядра') is self:
                    del м.хозяин.__dict__['_ждёт_ядра']
            for поле in ('набрано', 'баланс'):       # что мазок оставил в кисти помимо остатка — в порядке вызовов
                if not (isinstance(о[поле], str) and о[поле] == _ПРЕЖНЕЕ):
                    setattr(м.хозяин, '_' + поле, о[поле])
            if о.get('ошибка'):
                continue
            к = м.кисть.в_пикселях(х.px_на_мм)
            with warnings.catch_warnings(record=True) as слова:
                warnings.simplefilter('always')
                х._учесть_пустой(о['изм'], м.з['точки'], к, м.з['непрозрачность'], м.з['нагрузка'], о['почему'], з=м.з, сразу=False)
            слова = list(о['слова']) + [(w.message, w.category) for w in слова]
            if готово is not None:
                готово(м.метка, о['изм'], слова)
            else:
                for текст, вид in слова:
                    warnings.warn(текст, вид, stacklevel=4)
        self._раздать()

    def к_кисти(self, кисть):
        """Досчитать мазки этой кисти: её подобранное, набранное и баланс — как после них на одном ядре."""
        if os.getpid() != self.pid:
            raise RuntimeError('кисть в процессе-потомке: при ветвлении её мазки ещё считались — до ветвления звать х.досчитать()')
        while self._кистей.get(id(кисть)):          # набранное и баланс идут кисти по порядку вызовов: до её последнего мазка
            self._принять()
        if кисть.__dict__.get('_ждёт_ядра') is self:
            del кисть.__dict__['_ждёт_ядра']

    def досчитать(self, оставить=False):
        """Все мазки очереди досчитаны, кисти — со своим остатком. оставить=False — и процессы остановлены (заведутся
        со следующим мазком)."""
        while self._ждут:
            self._принять()
        if not оставить:
            self._остановить()

    закрыть = досчитать

    def граница(self):
        """Перед тем, что читает или правит холст мимо мазка (картинка, массив слоя, сушка, снятие, сохранение): всё
        досчитано, счёт сырого слоёв забыт."""
        if os.getpid() != self.pid:
            if self._ждут:
                raise RuntimeError('холст в процессе-потомке: при ветвлении у родителя были недосчитанные мазки — до '
                                   'ветвления звать х.досчитать()')
            return
        if self._ждут:
            self.досчитать(оставить=True)
        if self._сырое:
            self._сырое.clear()
