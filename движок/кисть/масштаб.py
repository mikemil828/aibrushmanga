"""М-7, М-9: что на холсте не в `мм.РОДНОЙ` px/мм держит px и уходит от настройки физики — для строки черновика
`кисть.повтор --scale` < 1 и подсказки С15 «масштаб». Только читает кисть; физику (`мм.py`, `числа.py`) не трогает и в хеш
калибровки не входит."""
from .мм import РОДНОЙ, _k

УЗКАЯ_PX = 24.0     # px: у кисти уже стольких px холста работает физика узкой кисти, пороги которой в px (`числа._ТЫЧОК`
                    # 24, `_КРАЙ_ОДНА` 24, `_КРАЙ_УЗКАЯ` 20, `_ОСТРАЯ` 16, `_ПОЛ_ПЛЁНКИ` 14, `_ТРИ_УЗК` 12, `_ЩЕЛЬ_УЗК` 8)
ГУСТАЯ = 0.6        # нагрузка (число): с этой — кромка густой кисти (`_БОК` 1,3 px, `_УГОЛ`) в px; 'пастозная' — 0,9
ДЕРЖИТ_PX = ('узкая', 'мягкая', 'сухая', 'кромка густой')


def ширина_px(кисть, px_на_мм):
    """Ширина кисти в px холста `px_на_мм` (кисть в мм — по нему, кисть в px — как есть)."""
    if getattr(кисть, 'ширина_мм', None) is not None and px_на_мм:
        return float(кисть.ширина_мм) * float(px_на_мм)
    return float(кисть.ширина)


def держит_px(кисть, нагрузка=None, px_на_мм=None):
    """М-7, М-9: чем мазок этой кистью на холсте `px_на_мм` уходит от настройки физики (8 px/мм) — кортеж слов из
    `ДЕРЖИТ_PX`; на родном масштабе (и без `px_на_мм`) — пусто. 'узкая' — кисть уже `УЗКАЯ_PX` px на этом холсте или на
    родном (ширина в мм та же); 'мягкая' — `кайма` > 0, не мастихин; 'сухая' — нагрузка 'сухая'; 'кромка густой' —
    нагрузка 'пастозная' или число от `ГУСТАЯ`. Только читает кисть."""
    k = _k(px_на_мм)
    if k == 1.0:
        return ()
    н = getattr(кисть, 'нагрузка', None) if нагрузка is None else нагрузка
    ш = ширина_px(кисть, px_на_мм)
    что = []
    if min(ш, ш / k) < УЗКАЯ_PX:
        что.append('узкая')
    if getattr(кисть, 'кайма', 0.0) > 0.0 and getattr(кисть, 'форма', '') != 'мастихин':
        что.append('мягкая')
    if н == 'сухая':
        что.append('сухая')
    if н == 'пастозная' or (isinstance(н, (int, float)) and not isinstance(н, bool) and float(н) >= ГУСТАЯ):
        что.append('кромка густой')
    return tuple(что)
