def таблица(файл=ФАЙЛ):
    """Таблица из файла (раз на процесс); снятая с другой физики — предупреждение, числа те, что в файле."""
    if файл not in _ТАБЛИЦА:
        if not os.path.exists(файл):
            raise FileNotFoundError(f'калибровка: нет таблицы {файл} — python3 -m кисть.калибровка --пересчитать')
        with open(файл, encoding='utf-8') as f:
            т = json.load(f)
        for пр in т['пресеты'].values():
            for п in list(т['поля']) + list(т.get('поля_цвета', ())):
                пр[п] = np.asarray(пр[п], np.float64)
            if 'сдвиг' in пр:
                # сдвиг тона жидкой — только потемнение светлой краски (замер: 0…−0,115). Где ход почти не кроет (просвет
                # белой и серой exp(−0,4) разнится меньше 0,002), поиск сдвига упирается в свои границы: просвет от него
                # не зависит — там сдвига нет; вверх (светлее белой) сдвига не бывает
                скв = пр['сквозь']
                пусто = (скв[..., 0] - скв[..., СЕТКА.index(-0.4)]) < 0.002
                пр['сдвиг как снят'] = пр['сдвиг']               # для сверки с живым узлом
                пр['сдвиг'] = np.where(пусто[..., None], 0.0, np.clip(пр['сдвиг'], -0.2, 0.0))
        if т.get('хеш') != хеш_физики():
            warnings.warn(f'калибровка: таблица снята с другой физики (хеш {т.get("хеш")}, ядро {хеш_физики()}) — '
                          'числа могут разойтись с мазком; python3 -m кисть.калибровка --пересчитать', stacklevel=3)
        _ТАБЛИЦА[файл] = т
    return _ТАБЛИЦА[файл]


