# ----------------------------------------------------------------- замер узла
def _плёнка(пк, цв, пр, краска):
    """5е-2: что в полосе хода от цвета краски не зависит — (голое место 1 − покрытие, показатель плёнки e, ln тона).
    пк, цв (линейный), пр — покрытие, цвет и пропуск слоя, краска — линейный цвет, которым ход положен. Плёнка
    пропускает `цвет ** e` (`краска.пропуск_плёнки`), e — по толщине, один на все каналы; цвет плёнки в пикселе —
    краска × тон пряди. Кроющая густая (пр None) света сквозь плёнку не пускает: e = 0."""
    from .краска import _ПОЛ
    голо = 1.0 - пк
    if пр is None:
        return голо, np.zeros(пк.shape), np.zeros(цв.shape)
    лц = np.log(np.clip(цв, _ПОЛ, 1.0)).sum(axis=-1)
    e = np.where(лц < -1e-9, np.log(np.maximum(пр, 1e-300)).sum(axis=-1) / np.minimum(лц, -1e-9), 0.0)
    return голо, e, np.log(np.maximum(цв, 1e-12) / np.maximum(np.asarray(краска, np.float64), 1e-12))


def _сквозь(плёнка, s):
    """5е-2: просвет полосы хода (`_плёнка`) для краски с ln линейного света s (число — серая, тройка — по каналам) —
    той же формулой, что `х.просвет`: голое место × яркость пропуска плёнки."""
    from .краска import _ПОЛ
    from .просвет import ЯРКОСТЬ
    голо, e, лтон = плёнка
    return float((голо * (np.exp(e[..., None] * np.clip(np.asarray(s, np.float64) + лтон, math.log(_ПОЛ), 0.0))
                          @ ЯРКОСТЬ.astype(np.float64))).mean())


def _ход_узла(пресет, ширина_мм, нагрузка, нажим, вид, разбавитель, сид, цвет):
    """Один ход стенда краской `цвет` (sRGB) на своём чистом холсте: None (не лёг) или словарь — 'покрытие' (1 − просвет
    `х.просвет`), 'толщина', 'доля' и 'плёнка' (`_плёнка` полосы замера)."""
    from .холст import Холст
    from .кисть import Кисть, путь_с_нажимом
    from .краска import Краска, в_линейный
    ш = float(ширина_мм) * ПХ_НА_ММ
    х = Холст(ХОЛСТ[0], ХОЛСТ[1], грунт=ГРУНТ, px_на_мм=ПХ_НА_ММ, ядра=1, подсказки=False)
    к = Кисть.из_файла(os.path.join(_ПРЕСЕТЫ, пресет + '.json'), ширина=ш)
    yc = ХОЛСТ[1] // 2
    точки = путь_с_нажимом([(ХОД[0], yc), (ХОД[1], yc)], ш, нажим=float(нажим), вход=ш / 2, сход=ш / 2, сид=сид)
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        о = х.мазок(точки, Краска(цвет, вид), к, слой='узел', сид=сид, нагрузка=float(нагрузка),
                   разбавитель=float(разбавитель) if разбавитель else None)
    if not о:
        return None
    w = о.ширина or ш
    y0 = max(0, int(round(yc - ПОПЕРЁК / 2 * w)))
    y1 = min(ХОЛСТ[1], max(y0 + 1, int(round(yc + ПОПЕРЁК / 2 * w)) + 1))
    п = х.просвет((ОКНО[0], y0, ОКНО[1], y1), дыр=0)
    сл = х.слои['узел']
    пк = np.asarray(сл.покрытие[y0:y1, ОКНО[0]:ОКНО[1]], np.float64)
    тл = np.asarray(сл.толщина[y0:y1, ОКНО[0]:ОКНО[1]], np.float64)
    цв = np.asarray(сл.цвет[y0:y1, ОКНО[0]:ОКНО[1]], np.float64)
    пр = None if сл.пропуск is None else np.asarray(сл.пропуск[y0:y1, ОКНО[0]:ОКНО[1]], np.float64)
    тело = float(np.percentile(пк, 90))
    return {'покрытие': float(1.0 - п.сводка['просвет']), 'толщина': float(тл.mean()),
            'доля': float((пк >= 0.5 * тело).mean()) if тело > 0 else 0.0,
            'плёнка': _плёнка(пк, цв, пр, в_линейный(цвет))}


def _серая(s):
    """sRGB 0–255 серой краски с ln линейного света s."""
    from .краска import из_линейного
    return tuple(float(v) for v in из_линейного(np.full(3, math.exp(s))) * 255.0)


def замер_узла(пресет, ширина_мм, нагрузка, нажим, вид, разбавитель, сид=1, цвет=ЦВЕТ, сдвиг=False):
    """Один ход узла: покрытие, толщина, доля полосы с краской, `сквозь` (просвет по `СЕТКА`) — словарь. Холст свой,
    чистый. цвет — краска хода (таблица снята с `ЦВЕТ`; другой — живой ход для сверки). сдвиг — у жидкой краски
    (разбавитель 1) ещё и `сдвиг`: тон прядей жидкой краски сходится к общему в пигментном состоянии
    (`укладка._текучая`), и светлая краска от этого темнеет (белая — на ~10 %), а тёмная нет — этого по ходу тёмной
    краской не узнать. Поэтому ход повторяется серыми красками `УРОВНИ`, и для каждой ищется сдвиг ln света, с которым
    счёт по плёнке хода даёт живой просвет."""
    р = _ход_узла(пресет, ширина_мм, нагрузка, нажим, вид, разбавитель, сид, цвет)
    if р is None:
        д = {'покрытие': 0.0, 'толщина': 0.0, 'доля': 0.0, 'сквозь': [1.0] * len(СЕТКА)}
    else:
        плёнка = р.pop('плёнка')
        д = dict(р, сквозь=[_сквозь(плёнка, s) for s in СЕТКА])
    if сдвиг:
        д['сдвиг'] = [0.0] * len(УРОВНИ)
        for k, s in enumerate(УРОВНИ if р is not None and разбавитель else ()):
            ж = _ход_узла(пресет, ширина_мм, нагрузка, нажим, вид, разбавитель, сид, _серая(s))
            if ж is None:
                continue
            цель, lo, hi = 1.0 - ж['покрытие'], -1.0, 0.3
            for _ in range(24):                      # просвет растёт со светом краски — делением пополам
                d = 0.5 * (lo + hi)
                lo, hi = (lo, d) if _сквозь(плёнка, s + d) > цель else (d, hi)
            д['сдвиг'][k] = 0.5 * (lo + hi)
    return д


def сиды_узла(ширина_мм):
    return СИДЫ_УЗКОЙ if float(ширина_мм) < УЗКАЯ_ММ else СИДЫ


def _узел(задача):
    пресет, ш, н, нж, вид, р = задача
    рр = [замер_узла(пресет, ш, н, нж, вид, р, сид, сдвиг=сид in СИДЫ_СДВИГА) for сид in сиды_узла(ш)]
    д = {п: float(np.mean([r[п] for r in рр])) for п in ЗАМЕР}
    д['разброс'] = float(np.std([r['покрытие'] for r in рр]))            # одиночный ход по сиду: σ покрытия
    д['разброс_толщины'] = float(np.std([r['толщина'] for r in рр]))
    скв = np.array([r['сквозь'] for r in рр])
    д['сквозь'], д['разброс_сквозь'] = [float(v) for v in скв.mean(axis=0)], [float(v) for v in скв.std(axis=0)]
    д['сдвиг'] = [float(v) for v in np.mean([r['сдвиг'] for r in рр if 'сдвиг' in r], axis=0)]
    return д


# ----------------------------------------------------------------- хеш физики
def _код_без_слов(текст, без_импорта=False):
    """Код без комментариев и строк описания: правка слов хеш не меняет, правка числа или строки кода — меняет.
    без_импорта — и без строк import (у замера узла: что он зовёт, хешируется своими файлами)."""
    дерево = ast.parse(текст)
    if без_импорта:
        for узел in ast.walk(дерево):
            тело = getattr(узел, 'body', None)
            if isinstance(тело, list):
                узел.body = [у for у in тело if not isinstance(у, (ast.Import, ast.ImportFrom))] or [ast.Pass()]
    for узел in ast.walk(дерево):
        тело = getattr(узел, 'body', None)
        if isinstance(тело, list) and тело and isinstance(тело[0], ast.Expr) \
                and isinstance(getattr(тело[0], 'value', None), ast.Constant) and isinstance(тело[0].value.value, str):
            узел.body = тело[1:] or [ast.Pass()]
    return ast.dump(дерево, include_attributes=False)


def хеш_физики(папка=None):
    """sha256 (первые 16 знаков) кода физики хода, замера узла, сетки и пресетов; папка — пакет `кисть/` (своя копия —
    для сторожа), пресеты — рядом с ней."""
    папка = папка or _ПАКЕТ
    h = hashlib.sha256()
    for имя in _ФИЗИКА:
        with open(os.path.join(папка, имя), encoding='utf-8') as f:
            h.update(имя.encode() + b'\0' + _код_без_слов(f.read()).encode() + b'\0')
    for ф in (замер_узла, _ход_узла, _плёнка, _сквозь, _серая, _узел):
        h.update(_код_без_слов(textwrap.dedent(inspect.getsource(ф)), без_импорта=True).encode())
    h.update(json.dumps([ПХ_НА_ММ, ГРУНТ, ХОЛСТ, ХОД, ОКНО, ПОПЕРЁК, ЦВЕТ, СИДЫ, СИДЫ_УЗКОЙ, УЗКАЯ_ММ, СЕТКА, УРОВНИ, БЕЗ_СДВИГА, СИДЫ_СДВИГА]).encode())
    пресеты = os.path.join(os.path.dirname(папка), 'пресеты')
    for имя in sorted(ШИРИНЫ_ММ):
        with open(os.path.join(пресеты, имя + '.json'), encoding='utf-8') as f:
            h.update(json.dumps(json.load(f), sort_keys=True, ensure_ascii=False).encode())
    return h.hexdigest()[:16]


# ----------------------------------------------------------------- пересчёт
def _задачи():
    for пресет, шш in ШИРИНЫ_ММ.items():
        for вид in ВИДЫ:
            for р in РАЗБАВИТЕЛИ:
                for ш in шш:
                    for нж in НАЖИМЫ:
                        for н in НАГРУЗКИ:
                            yield (пресет, ш, н, нж, вид, р)


def пересчитать(процессов=16, файл=ФАЙЛ, печать=print):
    """Снять всю таблицу заново (в процессах, не больше 16) и записать `файл`. Отвечает секундами счёта."""
    import multiprocessing as mp
    import time
    процессов = max(1, min(16, int(процессов)))
    задачи = list(_задачи())
    t = time.time()
    with mp.get_context('fork').Pool(процессов) as пул:
        числа = пул.map(_узел, задачи, chunksize=8)
    сек = time.time() - t
    по = {(з[0], з[1], з[2], з[3], з[4], з[5]): ч for з, ч in zip(задачи, числа)}
    пресеты = {}
    for пресет, шш in ШИРИНЫ_ММ.items():
        д = {'ширины_мм': list(шш)}
        for п in ПОЛЯ:     # [вид][разбавитель][ширина][нажим][нагрузка]
            д[п] = [[[[[round(по[(пресет, ш, н, нж, вид, р)][п], 5) for н in НАГРУЗКИ] for нж in НАЖИМЫ]
                      for ш in шш] for р in РАЗБАВИТЕЛИ] for вид in ВИДЫ]
        for п in ПОЛЯ_ЦВЕТА:     # то же — списками
            д[п] = [[[[[[round(v, 4) for v in по[(пресет, ш, н, нж, вид, р)][п]] for н in НАГРУЗКИ] for нж in НАЖИМЫ]
                      for ш in шш] for р in РАЗБАВИТЕЛИ] for вид in ВИДЫ]
        пресеты[пресет] = д
    т = {'хеш': хеш_физики(), 'узлов': len(задачи),
         'ходов': sum(len(сиды_узла(з[1])) + (len(УРОВНИ) * len(СИДЫ_СДВИГА) if з[5] else 0) for з in задачи), 'секунд': round(сек, 1),
         'процессов': процессов,
         'стенд': {'px_на_мм': ПХ_НА_ММ, 'грунт': ГРУНТ, 'холст': ХОЛСТ, 'ход_x': ХОД, 'окно_x': ОКНО,
                   'поперёк': ПОПЕРЁК, 'цвет': ЦВЕТ, 'сиды': СИДЫ, 'сиды_узкой': СИДЫ_УЗКОЙ, 'узкая_мм': УЗКАЯ_ММ},
         'оси': {'вид': ВИДЫ, 'разбавитель': РАЗБАВИТЕЛИ, 'нажим': НАЖИМЫ, 'нагрузка': НАГРУЗКИ, 'сквозь': СЕТКА, 'сдвиг': УРОВНИ},
         'поля': ПОЛЯ, 'поля_цвета': ПОЛЯ_ЦВЕТА, 'пресеты': пресеты}
    with open(файл, 'w', encoding='utf-8') as f:
        json.dump(т, f, ensure_ascii=False, separators=(',', ':'))
    печать(f'калибровка: {len(задачи)} узлов, {т["ходов"]} ходов, {процессов} процессов — {сек:.0f} с → {файл}')
    return сек


