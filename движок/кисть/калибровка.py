def _пресет_кисти(кисть, px_на_мм):
    """(пресет, ширина в мм) кисти; кисть с полями не как у пресета — предупреждение с их именами."""
    from dataclasses import asdict
    from .кисть import Кисть
    if isinstance(кисть, str):
        if кисть not in ШИРИНЫ_ММ:
            raise ValueError(f'калибровка: пресет {кисть!r} — в таблице {", ".join(ШИРИНЫ_ММ)}')
        raise ValueError('калибровка: нужна кисть (`Кисть.из_файла(…, ширина=…)`), а не имя пресета — ширина берётся из неё')
    пресет = _имена_пресетов().get(кисть.имя)
    if пресет is None:
        raise ValueError(f'калибровка: кисть «{кисть.имя}» не из пресетов ({", ".join(ШИРИНЫ_ММ)}) — таблицы для неё нет; '
                         'нагрузку — пробником или `х.перебор`')
    if кисть.ширина_мм is not None:
        ш = float(кисть.ширина_мм)
    else:
        ш = float(кисть.ширина) / float(px_на_мм or ПХ_НА_ММ)
    обр = asdict(Кисть.из_файла(os.path.join(_ПРЕСЕТЫ, пресет + '.json')))
    своё = asdict(кисть)
    иные = sorted(п for п in обр if п not in ('ширина', 'ширина_мм', 'нагрузка') and своё[п] != обр[п])
    if иные:
        warnings.warn(f'калибровка: у кисти «{пресет}» не как у пресета: {", ".join(иные)} — таблица снята с пресета, '
                      'ход может лечь иначе; проверь пробником', stacklevel=3)
    return пресет, ш


def _индекс(оси, v, лог):
    """(i, доля) — между узлами i и i+1; v внутри [оси[0], оси[-1]]."""
    оо = np.log(оси) if лог else np.asarray(оси, np.float64)
    vv = math.log(v) if лог else float(v)
    if len(оо) == 1:
        return 0, 0.0
    i = int(np.clip(np.searchsorted(оо, vv) - 1, 0, len(оо) - 2))
    return i, float(np.clip((vv - оо[i]) / (оо[i + 1] - оо[i]), 0.0, 1.0))


def _в_пределах(имя, v, оси, где):
    if not (оси[0] - 1e-9 <= v <= оси[-1] + 1e-9):
        ближ = min(max(v, оси[0]), оси[-1])
        raise ValueError(f'калибровка: {имя} {v:g} вне таблицы{где} — в ней {оси[0]:g}…{оси[-1]:g}; ближайшее — {ближ:g}')


def _разбавитель(р):
    р = 0.0 if р is None else float(р)
    if р not in РАЗБАВИТЕЛИ:
        raise ValueError(f'калибровка: разбавитель {р:g} — в таблице только 0 (густая) и 1 (жидкая); '
                         'между ними ход не линеен — пробником или `х.перебор(…, разбавитель=[…])`')
    return РАЗБАВИТЕЛИ.index(р)


def _вид(вид):
    вид = 'лессировочная' if вид == 'лессировка' else вид
    if вид == 'лессировочная':
        raise ValueError("калибровка: вид 'лессировочная' — мутность 0: не кроет, покрытие 0 при любой нагрузке; "
                         'под покрытие её в таблице нет; толщину плёнки — `нагрузка_для(кисть, толщина=…, вид=\'лессировочная\')` (как у прозрачной)')
    if вид not in ВИДЫ:
        raise ValueError(f'калибровка: вид {вид!r} — в таблице {", ".join(ВИДЫ)}; мутность числом — пробником')
    return ВИДЫ.index(вид)


def _кривая(т, пресет, ш, нажим, iв, iр, поле):
    """Значения поля по узлам нагрузки при ширине ш и нажиме — интерполяцией по ширине (log) и нажиму."""
    пр = т['пресеты'][пресет]
    шш = пр['ширины_мм']
    _в_пределах('ширина', ш, шш, f' «{пресет}» (мм)')
    _в_пределах('нажим', нажим, НАЖИМЫ, '')
    i, a = _индекс(шш, ш, True)
    j, b = _индекс(НАЖИМЫ, нажим, False)
    м = пр[поле][iв, iр]
    j1 = min(j + 1, len(НАЖИМЫ) - 1)
    i1 = min(i + 1, len(шш) - 1)
    return ((1 - a) * ((1 - b) * м[i, j] + b * м[i, j1]) + a * ((1 - b) * м[i1, j] + b * м[i1, j1]))


ЛИНЕЙНО = ('толщина', 'разброс_толщины')    # плёнка идёт за нагрузкой прямо — между узлами по самой нагрузке, прочее — по log


def _глубина(покрытие):
    """ln оптической глубины плёнки: покрытие = 1 − exp(−глубина). У не кроющей краски глубина идёт за нагрузкой
    степенью (тонкая плёнка — покрытие ∝ нагрузка^p, толстая — насыщается), и между узлами нагрузки она точнее прямой
    по log нагрузки вдвое (5е-2, замер по узлам через один)."""
    return np.log(-np.log(1.0 - np.clip(покрытие, 1e-6, 1.0 - 1e-6)))


def _по_нагрузке(кривая, нагрузка, поле='покрытие', глубиной=False):
    i, a = _индекс(НАГРУЗКИ, нагрузка, поле not in ЛИНЕЙНО)
    ни, ве = кривая[i], кривая[min(i + 1, len(НАГРУЗКИ) - 1)]
    if глубиной and min(ни, ве) > 1e-6:
        return float(1.0 - math.exp(-math.exp((1 - a) * _глубина(ни) + a * _глубина(ве))))
    return float((1 - a) * ни + a * ве)


def _мутность_ноль(вид):
    if isinstance(вид, str):
        return вид in ('лессировочная', 'лессировка')
    return isinstance(вид, (int, float, np.floating)) and not isinstance(вид, bool) and float(вид) == 0.0


def _лессировка(вид, цвет):
    """О-1, хвост Ф-1: краска мутности 0 (`'лессировочная'`, мутность 0 числом — доводом `вид` или видом `цвет`) под
    `толщина=`: толщина плёнки от мутности не зависит — берётся строка `'прозрачная'` (плоская 24 px, нагрузка 0,0189 —
    толщина 0,00567 у обеих). Под `покрытие=` — прежняя ошибка `_вид`: мутность 0 не кроет."""
    вк = getattr(цвет, 'вид', None)
    if вид is not None:
        if not _мутность_ноль(вид):
            return False
        if вк is not None and not _мутность_ноль(вк):
            raise ValueError(f'калибровка: вид={вид!r}, а краска цвет= — {вк!r}; оставь одно')
        return True
    return _мутность_ноль(вк)


def _вид_краски(вид, цвет):
    """Вид словом: довод `вид` или вид краски `цвет` (`Краска(rgb, 'прозрачная')`); оба и разные — ошибка."""
    вк = getattr(цвет, 'вид', None)
    вк = 'кроющая' if вк == 1.0 else вк
    if вид is None:
        return 'кроющая' if вк is None else вк
    if вк is not None and (not isinstance(вк, str) or _вид(вк) != _вид(вид)):
        raise ValueError(f'калибровка: вид={вид!r}, а краска цвет= — {вк!r}; оставь одно')
    return вид


def _цвет(цвет):
    """Цвет краски (sRGB 0–255: кортеж, `Краска`, ответ `цвет(L, C, h)`) -> ln линейного света по каналам; None — None."""
    if цвет is None:
        return None
    from .краска import в_линейный, _ПОЛ
    try:
        ц = np.asarray(tuple(цвет), np.float64)
    except (TypeError, ValueError):
        ц = np.zeros(0)
    if ц.shape != (3,) or not np.all(np.isfinite(ц)) or ц.min() < 0.0 or ц.max() > 255.0:
        raise ValueError(f'калибровка: цвет={цвет!r} — нужен sRGB (r, g, b) 0–255, как у `Краска`, или `цвет(L, C, h)`')
    return np.log(np.clip(в_линейный(ц), _ПОЛ, 1.0))


def _просвет_цвета(кр, s, лог=True, сдвиг=None):
    """Просвет краски с ln каналов s по кривым `сквозь` кр (узлы нагрузки, точки `СЕТКА`): по каналу — между точками
    сетки (просвет — по логарифму: у ровной плёнки он exp(e·s); σ — прямо), каналы — с весом яркости, как у
    `х.просвет`. сдвиг (узлы нагрузки, `УРОВНИ`) — жидкая краска: светлый канал темнее на сдвиг своего уровня."""
    from .просвет import ЯРКОСТЬ
    x = -np.asarray(СЕТКА)
    кр = np.asarray(кр, np.float64)
    ряды = np.arange(len(кр))
    итог = np.zeros(len(кр))
    for вес, sc in zip(ЯРКОСТЬ.astype(np.float64), s):
        ss = np.full(len(кр), float(sc))
        if сдвиг is not None:
            уу = [-u for u in УРОВНИ] + [-БЕЗ_СДВИГА]
            ss = np.minimum(ss + np.array([np.interp(-sc, уу, list(ряд) + [0.0]) for ряд in сдвиг]), 0.0)
        xx = np.clip(-ss, x[0], x[-1])
        i = np.clip(np.searchsorted(x, xx) - 1, 0, len(x) - 2)
        a = (xx - x[i]) / (x[i + 1] - x[i])
        ни, ве = кр[ряды, i], кр[ряды, i + 1]
        if лог:
            v = np.exp((1 - a) * np.log(np.maximum(ни, 1e-6)) + a * np.log(np.maximum(ве, 1e-6)))
            v = np.where(np.maximum(ни, ве) <= 1e-6, 0.0, v)
        else:
            v = (1 - a) * ни + a * ве
        итог = итог + вес * v
    return итог


НУЖЕН_ЦВЕТ = ('{кто}: нужен цвет=…: покрытие не кроющей зависит от цвета — {где} пропускает свет сквозь плёнку, светлая '
              'кроет слабее тёмной в 2–5 раз; дай краску хода: цвет=(r, g, b), `Краска` или `цвет(L, C, h)`')


def _покрытие(т, пресет, ш, нажим, iв, iр, s):
    """Кривая покрытия по узлам нагрузки и её σ: кроющая густая — поля таблицы, не кроющая — по `сквозь` и цвету."""
    if iв == 0 and iр == 0:
        return _кривая(т, пресет, ш, нажим, iв, iр, 'покрытие'), _кривая(т, пресет, ш, нажим, iв, iр, 'разброс')
    if 'сквозь' not in т['пресеты'][пресет]:
        raise ValueError('калибровка: таблица снята до 5е-2, цвета в ней нет — python3 -m кисть.калибровка --пересчитать')
    сдвиг = _кривая(т, пресет, ш, нажим, iв, iр, 'сдвиг') if iр else None
    return (1.0 - _просвет_цвета(_кривая(т, пресет, ш, нажим, iв, iр, 'сквозь'), s, сдвиг=сдвиг),
            _просвет_цвета(_кривая(т, пресет, ш, нажим, iв, iр, 'разброс_сквозь'), s, лог=False, сдвиг=сдвиг))


def _что_за_краска(iв, iр):
    return f'{ВИДЫ[iв]}{" с разбавителем 1" if iр else ""} краска'


def по_таблице(кисть, нагрузка, нажим=0.6, вид=None, разбавитель=None, px_на_мм=None, цвет=None):
    """Что даст одиночный ход по сухому грунту: {'покрытие', 'толщина', 'доля', 'разброс', 'разброс_толщины'} по
    таблице. цвет — краска хода (sRGB 0–255, `Краска` — с неё и вид, `цвет(L, C, h)`): не кроющей (прозрачная,
    полукроющая, любая с разбавителем 1) он обязателен — её покрытие зависит от цвета; кроющей густой не нужен.
    Вне таблицы и не кроющая без цвета — ValueError."""
    т = таблица()
    пресет, ш = _пресет_кисти(кисть, px_на_мм)
    from .инструмент import НАГРУЗКИ as ИМЕНА
    н = ИМЕНА[нагрузка] if isinstance(нагрузка, str) else float(нагрузка)
    _в_пределах('нагрузка', н, НАГРУЗКИ, '')
    iв, iр = _вид(_вид_краски(вид, цвет)), _разбавитель(разбавитель)
    s = _цвет(цвет)
    if (iв or iр) and s is None:
        raise ValueError(НУЖЕН_ЦВЕТ.format(кто='по_таблице', где=_что_за_краска(iв, iр)))
    ответ = {п: round(_по_нагрузке(_кривая(т, пресет, ш, нажим, iв, iр, п), н, п), 4) for п in ПОЛЯ}
    if iв or iр:
        кр, σ = _покрытие(т, пресет, ш, нажим, iв, iр, s)
        ответ['покрытие'], ответ['разброс'] = round(_по_нагрузке(кр, н, глубиной=True), 4), round(_по_нагрузке(σ, н), 4)
    return ответ


def нагрузка_для(кисть, покрытие=None, нажим=0.6, вид=None, разбавитель=None, толщина=None, px_на_мм=None, цвет=None):
    """В-2: нагрузка числом, при которой одиночный ход этой кистью по сухому грунту кроет на `покрытие` (1 − просвет
    грунта, как у `х.просвет`) или кладёт плёнку `толщина` (h, как `Слой.толщина`) — по таблице `калибровка.json`.

    Кисть — из пресета (`Кисть.из_файла`), ширина в мм или px (px — при `px_на_мм`, по умолчанию 8). Вид — `'кроющая'`
    (умолчание), `'полукроющая'`, `'прозрачная'`; `'лессировочная'` (мутность 0, и числом) — только под `толщина=`, строкой
    `'прозрачная'` (толщина плёнки от мутности не зависит), под `покрытие=` — `ValueError` (не кроет); разбавитель — 0 или 1. цвет — краска хода (sRGB
    0–255, `Краска` — с неё берётся и вид, `цвет(L, C, h)`): под `покрытие` не кроющей (прозрачная, полукроющая, любая
    с разбавителем 1) обязателен — светлая кроет слабее тёмной при той же нагрузке; кроющей густой и под `толщина`
    не нужен. Недостижимое (покрытие выше, чем у нагрузки 0,9, ниже, чем у 0,002), вне таблицы и не кроющая без
    цвета — `ValueError` словами."""
    if (покрытие is None) == (толщина is None):
        raise ValueError('нагрузка_для: одно из двух — покрытие= или толщина=')
    поле, цель = ('покрытие', float(покрытие)) if покрытие is not None else ('толщина', float(толщина))
    т = таблица()
    пресет, ш = _пресет_кисти(кисть, px_на_мм)
    лесс = поле == 'толщина' and _лессировка(вид, цвет)
    iв, iр = (ВИДЫ.index('прозрачная') if лесс else _вид(_вид_краски(вид, цвет))), _разбавитель(разбавитель)
    s = _цвет(цвет)
    if поле == 'покрытие':
        if (iв or iр) and s is None:
            raise ValueError(НУЖЕН_ЦВЕТ.format(кто='нагрузка_для', где=_что_за_краска(iв, iр)))
        кр = _покрытие(т, пресет, ш, нажим, iв, iр, s)[0]
    else:
        кр = _кривая(т, пресет, ш, нажим, iв, iр, поле)
    кр = np.maximum.accumulate(кр)      # не убывает: первая нагрузка, что даёт цель
    где = f'«{пресет}» {ш:g} мм, нажим {нажим:g}, {"лессировочная (толщина — как у прозрачной)" if лесс else ВИДЫ[iв]}, разбавитель {РАЗБАВИТЕЛИ[iр]:g}'
    if поле == 'покрытие' and (iв or iр):
        где += ', цвет ({:g}, {:g}, {:g})'.format(*tuple(цвет)[:3])
    if цель > кр[-1] + 1e-9:
        raise ValueError(f'нагрузка_для: {поле} {цель:g} недостижимо — {где}: наибольшее {кр[-1]:.3f} при нагрузке '
                         f'{НАГРУЗКИ[int(np.argmax(кр >= кр[-1] - 1e-9))]:g}; больше — шире кисть, плотнее (кроющая, без '
                         'разбавителя) или темнее краска, или второй ход по высохшему')
    if цель < кр[0] - 1e-9:
        raise ValueError(f'нагрузка_для: {поле} {цель:g} недостижимо — {где}: наименьшее {кр[0]:.4f} при нагрузке '
                         f'{НАГРУЗКИ[0]:g}; тоньше — вытертая кисть (нагрузка 0) по сырому или прозрачнее краска')
    k = int(np.argmax(кр >= цель - 1e-12))
    if k == 0:
        return float(НАГРУЗКИ[0])
    a = (цель - кр[k - 1]) / (кр[k] - кр[k - 1]) if кр[k] > кр[k - 1] else 1.0
    if поле == 'покрытие' and (iв or iр) and кр[k] > кр[k - 1] > 1e-6:      # не кроющая: между узлами — по глубине плёнки
        a = float(np.clip((_глубина(цель) - _глубина(кр[k - 1])) / (_глубина(кр[k]) - _глубина(кр[k - 1])), 0.0, 1.0))
    if поле in ЛИНЕЙНО:
        return round(float(НАГРУЗКИ[k - 1] + a * (НАГРУЗКИ[k] - НАГРУЗКИ[k - 1])), 5)
    лo, лв = math.log(НАГРУЗКИ[k - 1]), math.log(НАГРУЗКИ[k])
    return round(float(math.exp(лo + a * (лв - лo))), 5)


# ----------------------------------------------------------------- сверка
def сверить(узлов=8, узлы=None, файл=ФАЙЛ, печать=print):
    """Хеш и живые ходы на узлах против таблицы: `узлы` — список (пресет, ширина_мм, нагрузка, нажим, вид, разбавитель)
    или `узлов` через равный шаг по сетке. Отвечает списком расхождений словами (пустой — сходится)."""
    т = таблица(файл)
    беды = []
    if т['хеш'] != хеш_физики():
        беды.append(f'хеш таблицы {т["хеш"]} ≠ хеш ядра {хеш_физики()}')
    if узлы is None:
        задачи = list(_задачи())
        шаг = max(1, len(задачи) // узлов)
        узлы = задачи[шаг // 2::шаг][:узлов]
    for з in узлы:
        пресет, ш, н, нж, вид, р = з
        пр = т['пресеты'][пресет]
        и = (ВИДЫ.index(вид), РАЗБАВИТЕЛИ.index(р), пр['ширины_мм'].index(ш), НАЖИМЫ.index(нж), НАГРУЗКИ.index(н))
        живое = _узел(з)
        for п in ПОЛЯ + ПОЛЯ_ЦВЕТА:
            if п not in пр:
                беды.append(f'в таблице нет поля «{п}» — снята до 5е-2')
                break
            for k, (v, ж) in enumerate(zip(np.atleast_1d(пр['сдвиг как снят' if п == 'сдвиг' else п][и]), np.atleast_1d(живое[п]))):
                if abs(ж - v) > 1e-4 + 1e-4 * abs(v):
                    беды.append(f'узел {з}: {п}{f" [{k}]" if п in ПОЛЯ_ЦВЕТА else ""} в таблице {v:.5f}, '
                                f'живой ход {ж:.5f}')
    печать('калибровка: сходится с ядром' if not беды else 'калибровка: разошлась с ядром —\n  ' + '\n  '.join(беды))
    return беды


def main(argv=None):
    import argparse
    ап = argparse.ArgumentParser(prog='python3 -m кисть.калибровка', description=__doc__.split('\n')[0])
    ап.add_argument('--пересчитать', action='store_true', help='снять таблицу заново')
    ап.add_argument('--процессов', type=int, default=16, help='процессов счёта, не больше 16')
    ап.add_argument('--сверить', action='store_true', help='хеш и живые узлы против таблицы')
    а = ап.parse_args(argv)
    if а.пересчитать:
        пересчитать(а.процессов)
        _ТАБЛИЦА.clear()
    if а.сверить or not а.пересчитать:
        return 1 if сверить() else 0
    return 0


if __name__ == '__main__':
    sys.exit(main())
