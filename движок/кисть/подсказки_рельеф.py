"""v4, М-2 (`ТРЕБОВАНИЯ_палитра.md`, РЕШЕНИЕ DEN 18.11 21:09 +04 «да»): подсказки про рельеф — счёт по слоям холста.

Читает толщину и покрытие слоёв и тон холста без света — только на границе, где холст досчитан (`х.сохранить`,
`х.закрыть`), и только слои, в которые с прошлого счёта легли мазки; на мазке нового счёта по пикселям нет. Факты
(спецификация — `проверка/КАРТА_АБ_подсказки.md`, «Б», строки С10–С12):

    С10 «толстый слой»      — слой там, где под ним лежат нижние, по медиане толще их суммы в `ТОЛЩЕ_В` раз и больше;
    С11 «валы по границам»  — гребни рельефа слоя (выше соседей на `ВАЛ_ГРЕБЕНЬ` его средней толщины) в полосе
                              ±`ВАЛ_ПОЛОСА_ММ` у границ тона занимают долю места в `ВАЛ_ВО_СКОЛЬКО` раз больше, чем в теле;
    С12 «пастозно»          — у объекта (без пометок — у слоя) толщина его слоёв от `ПАСТОЗНО_ММ` на `ПАСТОЗНО_ДОЛЯ`
                              площади и больше.

Пороги — замером (сдача `проверка/СДАЧА_v4_М-2+М-4.md`)."""

import numpy as np

ТОЛЩЕ_В = 4.0            # С10: пастозная по протирке ×4,5–6,2; обычная по протирке ×2,4–2,5; пастозная жидкая ×2,5
ТОЛЩЕ_НИЗ_ММ = 0.01      # С10: нижние тоньше — отношение не считается (почти голый грунт)
ТОЛЩЕ_МЕСТА = 0.25       # С10: нижние лежат хотя бы под четвертью места слоя
ВАЛ_ГРЕБЕНЬ = 0.3        # С11: гребень — выше обоих соседей (на 0,75 и 1,5 мм поперёк) на эту долю средней толщины слоя
ВАЛ_ПОЛОСА_ММ = 2.0      # С11: полоса у границ тона, ± мм
ВАЛ_ПЕРЕПАД = 24.0       # С11: граница тона — перепад L на 4 мм (прищур 1 мм клетки, как `края` у `х.виды`)
ВАЛ_ВО_СКОЛЬКО = 2.0     # С11
ВАЛ_МИН = 0.05           # С11: гребней в полосе — не меньше 5 % её места
ВАЛ_ВИДНО = 0.25         # С11: слой, укрытый слоями выше больше чем на 3/4 своего места, — не считается
ПАСТОЗНО_ММ = 0.3        # С12: толще любой одной «обычной» (у кисти 80 px p90 0,24 мм)
ПАСТОЗНО_ДОЛЯ = 0.25     # С12
PX_НА_ММ = 4.0           # холст без px_на_мм — считать так


def _клетками(a, k):
    from .глаз import _клетками as к
    return к(np.asarray(a, np.float32), k) if k > 1 else np.asarray(a, np.float32)


def _гребни(h, d):
    """Насколько точка выше обоих соседей на расстоянии d (по x или по y — где больше); за краем — сама точка."""
    итог = None
    for ось in (0, 1):
        п = np.pad(h, [(d, d) if i == ось else (0, 0) for i in (0, 1)], mode='edge')
        вперёд = np.take(п, range(2 * d, п.shape[ось]), ось)
        назад = np.take(п, range(0, п.shape[ось] - 2 * d), ось)
        a = np.minimum(h - вперёд, h - назад)
        итог = a if итог is None else np.maximum(итог, a)
    return итог


def _расширить(м, r):
    """Маска, расширенная кругом радиуса r клеток."""
    п = np.pad(м, r)
    итог = np.zeros_like(п)
    for dy in range(-r, r + 1):
        for dx in range(-r, r + 1):
            if dy * dy + dx * dx <= r * r:
                итог |= np.roll(np.roll(п, dy, 0), dx, 1)
    return итог[r:-r, r:-r]


def _границы_тона(х, клетка, ppm, кроет):
    """Клетки (`клетка` px) у границ тона: перепад прищуренного L ≥ `ВАЛ_ПЕРЕПАД`, расширенный на полосу. Граница краски
    с голым грунтом (кромка пятна) — не граница цвета двух красок: в счёт идут только клетки, вокруг которых на 4 клетки
    краска есть везде (`кроет` — наибольшее покрытие по слоям)."""
    from .глаз import oklab, _L, _srgb, _размыть, _края
    рис = np.asarray(х.картинка(свет=False), np.float32)
    лин = np.stack([_клетками(рис[..., i], клетка) for i in range(3)], -1)
    L = _размыть(_L(oklab(_srgb(лин))[..., 0]).astype(np.float32), 2)
    перепад = _края(L, ВАЛ_ПЕРЕПАД)[0]
    голо = кроет[:L.shape[0], :L.shape[1]] <= 0.5
    край = (перепад >= ВАЛ_ПЕРЕПАД) & ~_расширить(голо, 4)
    r = max(1, int(round(ВАЛ_ПОЛОСА_ММ * ppm / клетка)))
    return _расширить(край, r) if край.any() else край


def счёт(х, слои, объекты):
    """Факты рельефа для слоёв `слои` (имена) и объектов `объекты` ({ключ: (слои объекта, клетки — множество номеров
    y·100000 + x клеток `КЛЕТКА`)}). Ответ — [(вид, ключ, факт, инструменты)]."""
    from .глаз import ММ_НА_H
    from .подсказки import КЛЕТКА, _ч
    имена = list(х.слои)
    if not имена:
        return []
    ppm = float(х.px_на_мм or PX_НА_ММ)
    шаг = max(1, int(round(ppm / 4.0)))              # ~0,25 мм — для гребней
    клетка = 4 * шаг                                  # ~1 мм
    итог = []
    толщ, кроет = {}, {}

    def т(и):
        if и not in толщ:
            с = х.слои[и]
            толщ[и] = _клетками(с.толщина[:, :], клетка) * ММ_НА_H
            кроет[и] = _клетками(с.покрытие[:, :], клетка)
        return толщ[и], кроет[и]

    полоса = None
    for и in имена:
        if и not in слои:
            continue
        h, п = т(и)
        своё = п > 0.5
        if not своё.any():
            continue
        # С10 — толстый слой
        i = имена.index(и)
        if i:
            низ = sum(т(j)[0] for j in имена[:i])
            низ_кроет = np.maximum.reduce([т(j)[1] for j in имена[:i]])
            общее = своё & (низ_кроет > 0.5)
            if общее.sum() >= ТОЛЩЕ_МЕСТА * своё.sum():
                верх_м, низ_м = float(np.median(h[общее])), float(np.median(низ[общее]))
                if низ_м >= ТОЛЩЕ_НИЗ_ММ and верх_м >= ТОЛЩЕ_В * низ_м:
                    итог.append(('С10', 'С10:с:' + и,
                                 f'слой «{и}» — толщина {_ч(верх_м, 2)} мм, под ним {_ч(низ_м, 2)} мм, ×{_ч(верх_м / низ_м)} '
                                 f'(на {100.0 * общее.sum() / своё.sum():.0f} % его места)',
                                 ["х.виды(область).массивы['толщина слоёв']", 'нагрузка_для(кисть, толщина=)', 'х.мазок(…, разбавитель=)']))
        # С11 — валы по границам тона
        H = _клетками(х.слои[и].толщина[:, :], шаг) * ММ_НА_H
        средняя = float(h[своё].mean())
        if средняя > 1e-6:
            гр = np.maximum(_гребни(H, max(1, int(round(0.75 * ppm / шаг)))), _гребни(H, max(1, int(round(1.5 * ppm / шаг)))))
            вал = _клетками(гр, 4)[:h.shape[0], :h.shape[1]] > ВАЛ_ГРЕБЕНЬ * средняя     # гребень в среднем по клетке ~1 мм
            if полоса is None:
                полоса = _границы_тона(х, клетка, ppm, np.maximum.reduce([т(j)[1] for j in имена]))[:h.shape[0], :h.shape[1]]
            видно = своё
            if i + 1 < len(имена):                       # гребни под чужой краской сверху — не обводы этого слоя
                видно = своё & (np.maximum.reduce([т(j)[1] for j in имена[i + 1:]]) <= 0.5)
            в_полосе, в_теле = видно & полоса, видно & ~полоса
            if видно.sum() >= ВАЛ_ВИДНО * своё.sum() and в_полосе.sum() >= max(16, 0.01 * видно.sum()) and в_теле.any():
                N, M = float(вал[в_полосе].mean()), float(вал[в_теле].mean())
                if N >= ВАЛ_МИН and N >= ВАЛ_ВО_СКОЛЬКО * M:
                    итог.append(('С11', 'С11:с:' + и,
                                 f'слой «{и}» — гребни вала на {100 * N:.0f} % места в полосе ±{ВАЛ_ПОЛОСА_ММ:.0f} мм у границ тона, '
                                 f'в теле — на {100 * M:.0f} %',
                                 ['х.взгляд(область, свет=)', "х.виды(область).массивы['края']", 'х.проба']))
    # С12 — пастозно (объект; без пометок — слой)
    крупно = {}
    for ко, (сл, клетки) in объекты.items():
            сл = [s for s in сл if s in х.слои]
            if not сл or not клетки:
                continue
            for s in сл:
                if s not in крупно:
                    крупно[s] = _крупно(х, s, КЛЕТКА)
            h = sum(крупно[s][0] for s in сл)
            п = np.maximum.reduce([крупно[s][1] for s in сл])
            c = np.asarray(sorted(клетки), np.int64)
            cy, cx = c // 100000 - х.y0 // КЛЕТКА, c % 100000 - х.x0 // КЛЕТКА
            м = (cy >= 0) & (cx >= 0) & (cy < h.shape[0]) & (cx < h.shape[1])
            hh, пп = h[cy[м], cx[м]], п[cy[м], cx[м]]
            hh = hh[пп > 0.5]
            if len(hh) < 4:
                continue
            доля = float((hh >= ПАСТОЗНО_ММ).mean())
            if доля >= ПАСТОЗНО_ДОЛЯ:
                имя = f'объект «{ко[2:]}»' if ко.startswith('о:') else f'слой «{ко[2:]}»'
                итог.append(('С12', 'С12:' + ко, f'{имя} — толще {_ч(ПАСТОЗНО_ММ)} мм на {100 * доля:.0f} % его площади '
                             f'(медиана {_ч(float(np.median(hh)), 2)} мм, до {_ч(float(hh.max()), 2)} мм)',
                             ["х.виды(область).массивы['толщина']", 'нагрузка_для(кисть, толщина=)', 'х.мазок(…, разбавитель=)']))
    return итог


def _крупно(х, слой, клетка):
    """Толщина (мм) и покрытие слоя средними по клеткам `клетка` px (неполная клетка у края — по своим пикселям)."""
    from .глаз import ММ_НА_H
    с = х.слои[слой]
    В, Ш = х.высота, х.ширина
    ny, nx = -(-В // клетка), -(-Ш // клетка)
    итог = []
    for a in (с.толщина[:, :], с.покрытие[:, :]):
        b = np.zeros((ny * клетка, nx * клетка), np.float32)
        b[:В, :Ш] = a
        n = np.zeros_like(b)
        n[:В, :Ш] = 1.0
        s = b.reshape(ny, клетка, nx, клетка).sum((1, 3))
        итог.append(s / np.maximum(n.reshape(ny, клетка, nx, клетка).sum((1, 3)), 1.0))
    return итог[0] * ММ_НА_H, итог[1]
