"""О-1 (Д-1, К-13 баланса): на сколько мм пути хватит того, что на кисти, — `к.хватит(…)`, до кладки.

Живая краска (`к.набрать(цвет, количество)`) тратится от хода к ходу; модель узнавала, когда добирать, только пробой.
Здесь проба — на своём стенде в памяти, копией кисти: кисть модели, её холст и журнал не трогаются.

Почему стенд, а не таблица. Путь кисти зависит не только от пресета и ширины: от нагрузки, нажима, того, сколько на
кисти и что на кончиках. Таблица на каждую кисть не снимется; серия ходов стенда — 0,05–0,2 с на ход. От px холста путь
в мм не зависит (Р-1: запас ворса — в мм; `плоская` 6 мм — 174, 178 и 179 мм при 4, 8 и 16 px/мм), кроме кисти, узкой
на этом холсте (уже 24 px: её физика держит px — `круглая` 3 мм проходит 51 мм при 4 px/мм и 132 при 8 и 16).

Стенд: чистый гладкий грунт `ГРУНТ`, масштаб — холста модели (`холст=` или `px_на_мм=`); ходы прямо по `ход_мм`
(умолчание 40 мм) один за другим без добора, каждый своим рядом (сырое прошлого хода под следующим не лежит); сид
серии — один на все её ходы (`СИДЫ`, 12 серий). Мерка — `о.закрыто` хода. Порог — `доля` (умолчание 0,5) от закрытого
первым ходом той же кисти полной свежей загрузкой (`набрать(…, 1)`) той же нагрузкой и нажимом. «Хватит на N мм» —
путь до места, где закрыто ходов переходит порог: закрыто хода стоит в его середине, между серединами — линейно; до
середины первого — от закрытого свежей кистью. Ответ — среднее серий, разброс — их σ.
"""
import math
import warnings

import numpy as np

ГРУНТ = (235, 232, 225)
СИДЫ = tuple(7 * s + 3 for s in range(12))     # сид серии (тот же, что у стенда Приёмки 277 `путь12с.py`)
ДОЛЯ = 0.5
ХОД_ММ = 40.0
ХОДЫ_ММ = (5.0, 400.0)
ДО_ММ = 2000.0                                  # дальше не меряется: «хватит больше 2000 мм»
ПОЛЕ_ММ = 4.0                                   # от края стенда до хода, мм
РЯДОВ = 12                                      # рядов на одном холсте стенда (дальше — новый)


def _px(кисть, холст, px_на_мм):
    if холст is not None and getattr(холст, 'px_на_мм', None):
        return float(холст.px_на_мм)
    if px_на_мм:
        return float(px_на_мм)
    raise ValueError('хватит: дай холст= (или px_на_мм=) — стенд кладёт ходы в px холста, а кисть, узкая на нём '
                     '(уже 24 px), держит px: `круглая` 3 мм полной загрузкой проходит 51 мм при 4 px/мм и 132 при 8')


def _ширина_px(к, px):
    return float(к.ширина_мм) * px if к.ширина_мм is not None else float(к.ширина)


class _Стенд:
    """Ряды ходов одной серии: холст за холстом по `РЯДОВ` рядов, кисть — своя копия."""

    def __init__(self, кисть, px, ход_мм, нажим, нагрузка, разбавитель, сид):
        self.к, self.px, self.L, self.нажим, self.сид = кисть, px, float(ход_мм), нажим, int(сид)
        self.д = {}
        if нагрузка is not None:
            self.д['нагрузка'] = нагрузка
        if разбавитель:
            self.д['разбавитель'] = float(разбавитель)
        self.ш = _ширина_px(кисть, px)
        self.шаг = max(self.ш * 1.6, 3.0 * px)
        self.х, self.ряд = None, РЯДОВ

    def ход(self):
        from .холст import Холст
        from .путь import путь_с_нажимом
        if self.ряд >= РЯДОВ:
            поле = ПОЛЕ_ММ * self.px + self.ш
            self.х = Холст(int(round(self.L * self.px + 2 * поле)), int(round(РЯДОВ * self.шаг + 2 * поле)), грунт=ГРУНТ,
                           px_на_мм=self.px, ядра=1, подсказки=False)
            self.поле, self.ряд = поле, 0
        y = self.поле + (self.ряд + 0.5) * self.шаг
        self.ряд += 1
        т = [(self.поле, y), (self.поле + self.L * self.px, y)]
        if self.нажим is not None:
            т = путь_с_нажимом(т, self.ш, нажим=float(self.нажим), сид=self.сид)
        with warnings.catch_warnings():
            warnings.simplefilter('ignore')
            о = self.х.мазок(т, None, self.к, сид=self.сид, **self.д)
        return 0.0 if о is None else float(о.закрыто)


def _свежая(кисть):
    """Та же кисть с той же краской полной свежей загрузкой, без подобранного на кончиках."""
    from .инструмент import Загрузка
    from .числа import _КОРЗИН
    н = кисть.с()
    кр = кисть._краска
    н._краска = Загрузка(tuple(кр), np.ones(_КОРЗИН), np.ones(_КОРЗИН))
    return н


def _путь(з, порог, L, з0):
    """мм до места, где закрыто переходит порог: з — закрыто ходов по порядку (последний — ниже порога или нет)."""
    xs = [0.0] + [(i + 0.5) * L for i in range(len(з))]
    ys = [з0] + list(з)
    for i in range(1, len(ys)):
        if ys[i] < порог:
            a, b = ys[i - 1], ys[i]
            t = (a - порог) / (a - b) if a > b else 0.0
            return xs[i - 1] + min(max(t, 0.0), 1.0) * (xs[i] - xs[i - 1]), True
    return None, False


def хватит(кисть, нажим=None, доля=ДОЛЯ, нагрузка=None, ход_мм=ХОД_ММ, разбавитель=None,
           холст=None, px_на_мм=None):
    """О-1: `к.хватит(…)` — на сколько мм пути хватит живой краски, что сейчас на кисти, — до кладки; кисть, холст и
    журнал не трогаются. Ходы по `ход_мм` этой кистью, этим нажимом (None — как ход точками (x, y)) и нагрузкой (None —
    кисти) без добора, пока `закрыто` хода не упадёт ниже `доля` закрытого свежей полной кистью той же нагрузки. Масштаб
    — холста (`холст=` или `px_на_мм=`, обязателен: стенд — в px холста). Ответ — словарь: 'мм', 'ходов', 'разброс_мм',
    'закрыто_свежей', 'порог', 'закрыто_ходов' (среднее серий по ходам), 'осталось', 'больше' (если за `ДО_ММ` не
    кончилась), … Справочник «Краска на кисти»."""
    from .инструмент import Загрузка
    кр = кисть._краска
    if not isinstance(кр, Загрузка):
        raise ValueError('хватит: краска на кисти не живая — ' + (
            'кисть не набрана: `к.набрать(цвет, количество)`' if кр is None else
            'набрана без количества (или ход с цветом): кисть полна на каждом ходе, хватит её всегда; '
            'живая — `к.набрать(цвет, 1)`'))
    if кисть.форма == 'мастихин':
        raise ValueError('хватит: мастихин краску не тратит ворсом — путь не меряется')
    px = _px(кисть, холст, px_на_мм)
    L = float(ход_мм)
    if not (ХОДЫ_ММ[0] <= L <= ХОДЫ_ММ[1]):
        raise ValueError(f'хватит: ход_мм {L:g} — от {ХОДЫ_ММ[0]:g} до {ХОДЫ_ММ[1]:g}; ближайшее — '
                         f'{min(max(L, ХОДЫ_ММ[0]), ХОДЫ_ММ[1]):g}')
    д = float(доля)
    if not 0.0 < д < 1.0:
        raise ValueError(f'хватит: доля {доля} — от 0 до 1, не включая (0,5 — вдвое беднее свежей кисти)')
    if нажим is not None and not (0.05 <= float(нажим) <= 1.0):
        raise ValueError(f'хватит: нажим {float(нажим):g} — от 0,05 до 1; None — как ход точками (x, y)')
    if разбавитель is not None and not (0.0 <= float(разбавитель) <= 1.0):
        raise ValueError(f'хватит: разбавитель {float(разбавитель):g} — от 0 до 1')
    до = int(math.ceil(ДО_ММ / L))
    серии = []                                  # (стенд, закрыто свежей, закрыто ходов, мм или None)
    for сид in СИДЫ:
        з0 = _Стенд(_свежая(кисть), px, L, нажим, нагрузка, разбавитель, сид).ход()
        ст, з, n = _Стенд(кисть.копия(), px, L, нажим, нагрузка, разбавитель, сид), [], None
        while n is None and len(з) < до:
            з.append(ст.ход())
            n = _путь(з, д * з0, L, з0)[0]
        серии.append([ст, з0, з, n])
    длиннее = max(len(с[2]) for с in серии)     # закрыто по ходам — у всех серий до одного хода
    for с in серии:
        while len(с[2]) < длиннее:
            с[2].append(с[0].ход())
    дошли = sum(с[3] is not None for с in серии)
    мм = [до * L if с[3] is None else с[3] for с in серии]
    свежие, ряды = [с[1] for с in серии], [с[2] for с in серии]
    м = np.asarray(мм)
    по_ходам = [round(float(v), 4) for v in np.mean(np.asarray(ряды), axis=0)]
    with np.errstate(all='ignore'):
        о = {'мм': round(float(м.mean()), 1), 'ходов': round(float(м.mean()) / L, 2), 'разброс_мм': round(float(м.std()), 1),
             'закрыто_свежей': round(float(np.mean(свежие)), 4), 'порог': round(д * float(np.mean(свежие)), 4), 'доля': д,
             'закрыто_ходов': по_ходам, 'осталось': кисть.осталось, 'ход_мм': L, 'px_на_мм': px,
             'нажим': None if нажим is None else float(нажим), 'сидов': len(СИДЫ)}
    if дошли < len(СИДЫ):
        о['больше'] = (f'в {len(СИДЫ) - дошли} сериях из {len(СИДЫ)} закрыто не упало ниже порога за {ДО_ММ:g} мм: '
                       f'хватит больше {ДО_ММ:g} мм')
    return о


class Нагрузка(float):
    """О-1: ответ `нагрузка_для` у кисти с живой краской — то же число (им и кладут) с полями остатка."""
    хватит = хватит_мм = на_ход = None

    def __reduce__(self):
        return float, (float(self),)


ПХ_ПРОГНОЗА = 8.0                               # px холста прогнозов без `px_на_мм` (как у калибровки)


def с_остатком(ответ, кисть, нажим, разбавитель, px_на_мм, длина, план=False):
    """О-1: прогноз (`нагрузка_для` — число, `план_покрытия` — словарь) и остаток кисти: у кисти без живой краски — ответ
    как есть (бит в бит), иначе — с путём остатка `хватит` этой нагрузкой и нажимом. длина — мм хода (ряда)."""
    from .инструмент import Загрузка
    if длина is not None and not float(длина) > 0.0:
        raise ValueError(f'длина {длина} — мм хода (ряда), больше 0')
    if not isinstance(getattr(кисть, '_краска', None), Загрузка):
        return ответ
    н = ответ['нагрузка'] if план else float(ответ)
    х = хватит(кисть, нажим=нажим, нагрузка=н, разбавитель=разбавитель or None, px_на_мм=px_на_мм or ПХ_ПРОГНОЗА)
    мм = х['мм']
    if план:
        ответ = dict(ответ, хватит_мм=мм, хватит=х)
        if длина is not None:
            ответ['рядов_до_добора'] = int(мм // float(длина))
        return ответ
    о = Нагрузка(н)
    о.хватит, о.хватит_мм = х, мм
    if длина is not None:
        о.на_ход = bool(мм >= float(длина))
    return о
