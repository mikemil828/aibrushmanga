"""Модель кисти и мазка, версия 2.

Мазок — это поперечный профиль плёнки, который кисть тянет вдоль пути:

  ведущие волоски  стоят через 2–3 px; под кончиком каждого — борозда (плёнка тонкая),
  гребни           между ведущими: здесь краска гуще. Гребень — носитель краски: у него свой запас,
                   своя краска, своя капля на кончике (то, что он несёт и кладёт);
  пряди            по 3–7 гребней: у пряди общая длина (когда оторвётся), нагрузка, тон, отставание.

Ход расчёта одного мазка:
  1. путь: точки -> сплайн -> равный шаг <= 0,5 px; нажим, скорость, угол кисти с отставанием;
  2. состав кисти заново от сида мазка: ведущие, гребни, пряди;
  3. касание гребня — когда нажим выше порога его пряди; след распластывается и пряди расходятся с нажимом;
  4. перенос краски (шаг 2 px, по гребням): запас -> капля на кончике -> холст; по сырому в каплю
     попадает лежащая краска (объём с холста снимается), смешивается со своей в K/S и кладётся дальше;
  5. растр: профиль кисти берётся через 0,5 px поперёк и кладётся на сетку вдвое мельче холста
     (ядро 3x3), потом сетка складывается 2x2 — кромка борозды в пиксель, без «бисера» на косом ходе;
  6. слой: толщина красит (покрытие плавно растёт с толщиной плёнки), сырая краска под мазком
     частью снята кистью, частью вмешана в новую плёнку.

Код разведён по швам (поведение то же, имена отсюда берутся как раньше):
  числа.py       пороги, доли и размеры модели — одно место, где они правятся;
  инструмент.py  класс Кисть: пресет, нагрузка, набранная краска; разбор цвета из вызова;
  путь.py        путь и жесты: путь_с_нажимом, жест, равный шаг, угол кисти (шаг 1);
  пряди.py       состав кисти, шум, кромка следа, посадка и подъём (шаги 2 и 3);
  набор.py       набор краски: раскладка по гребням, неровный набор, прожилки, тонкие места;
  борозда.py     живая борозда: запас кончика волоска, проскок, слипание — профиль плёнки вдоль хода (шаг 5);
  укладка.py     положить_мазок: перенос краски, растр, запись в слой (шаги 4–6).
Что умеет мазок и откуда что взялось — README.md, «Что умеет мазок»; история по сменам — в git.
"""

