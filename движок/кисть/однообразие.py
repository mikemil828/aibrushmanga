def _ч(v, n=2):
    return f'{v:.{n}f}'.replace('.', ',')


class Однообразие:
    """Отчёт зеркала: `оценка` 0–1 («один приём с дрожанием»), `слова` — строка, что узко; `сводка` — числа по
    признакам ('длина', 'наклон', 'изгиб', 'ширина', 'нажим', 'кисть', 'конец', 'цвета', 'нагрузка' и 'узость' каждого),
    `регулярность` — Б-9 (`регулярность_мазков`), `мазков`, `номера` — строки журнала зоны. `о['длина']` — то же, что
    `о.сводка['длина']`; print(о) — слова."""
    __slots__ = ('оценка', 'слова', 'сводка', 'регулярность', 'мазков', 'номера', 'зона', 'места', 'объекты', 'клетки',
                 'клетка', 'карта', 'холст_размер')

    def __getitem__(self, ключ):
        return self.сводка[ключ]

    def __repr__(self):
        return self.слова


def отчёт(мазки, зона='', образец=None, px_мм=None):
    """Однообразие мазков (список от `мазки_журнала` / `отобрать`). образец — `Однообразие` другой зоны (меркой
    образца, К-4): к словам — во сколько раз у образца разброс (n_эфф) шире по каждому узкому признаку. px_мм — px/мм
    журнала: площадь хода в мм² (М-12)."""
    о = Однообразие()
    о.зона, о.мазков, о.номера = зона, len(мазки), [м['номер'] for м in мазки]
    о.места, о.объекты, о.клетки, о.клетка, о.карта = None, None, None, None, None
    n = len(мазки)
    if n == 0:
        о.оценка, о.сводка, о.регулярность = 0.0, {}, регулярность_мазков([])
        о.слова = f'{зона}: мазков нет' if зона else 'мазков нет'
        return о
    п = [_признаки_мазка(м) for м in мазки]
    лог2 = lambda v: np.floor(np.log2(np.maximum(v, 1e-3))).astype(int)
    с = {'длина': _непрерывный(_по_линиям(п, 'длина'), лог2),
         'наклон': _угловой([q['наклон'] for q in п]),
         'изгиб': _непрерывный([q['изгиб'] for q in п], lambda v: np.floor(np.log(v) / math.log(1.1)).astype(int)),
         'ширина': _непрерывный(_по_линиям(п, 'ширина'), лог2),
         'нажим': _категории(_нажим_по_линиям(п)),
         'кисть': _категории([м['кисть'] for м in мазки]),
         'цвета': _цвета([м['цвет'] for м in мазки]),
         'замесы': _замесы(мазки),
         'нагрузка': _непрерывный([q['нагрузка'] for q in п], lambda v: np.floor(v / 0.1).astype(int))}
    узость = {к: (_узость(v['эфф'], v['n']) if v is not None else None) for к, v in с.items() if к not in ('цвета', 'замесы')}
    с['узость'] = {к: (round(v, 3) if v is not None else None) for к, v in узость.items()}
    есть = [узость[к] for к in ПРИЗНАКИ if узость[к] is not None]
    о.оценка = round(float(np.mean(есть)) if есть else 0.0, 3)
    с['ход'] = _ход(п, px_мм)
    с_линиями = [len(q['линии']) for q in п if q['линии'] is not None]
    с['линии'] = ({'ходов': len(с_линиями), 'линий': int(sum(с_линиями)),
                   'на ход': tuple(round(float(v), 1) for v in np.percentile(с_линиями, [10, 50, 90]))} if с_линиями else None)
    о.регулярность = регулярность_мазков(мазки)
    о.сводка = с
    о.слова = _слова(о, образец)
    return о


def _точки(п):
    """М-12: (длина / ширина, площадь следа px²) каждого хода (у кисти из пучков — каждой линии пучка) — массивы."""
    дл = np.asarray(_по_линиям(п, 'длина'), np.float64)       # К-14б: у кисти из пучков ход — линии пучков
    ш = np.maximum(np.asarray(_по_линиям(п, 'ширина'), np.float64), 1e-6)
    return дл / ш, дл * ш + math.pi * ш * ш / 4.0


def _ход(п, px_мм=None):
    """М-12: сводка `'ход'` — 'длина/ширина' (p10, p50, p90), 'короче 1,5 ширины' (доля ходов короче `КОРОТКИЙ` своей
    ширины), 'площадь px²' и 'площадь мм²' (p50; без px/мм журнала — None)."""
    r, пл = _точки(п)
    p10, p50, p90 = (round(float(v), 2) for v in np.percentile(r, [10, 50, 90]))
    a = float(np.median(пл))
    return {'длина/ширина': (p10, p50, p90), 'короче 1,5 ширины': round(float((r < КОРОТКИЙ).mean()), 3),
            'площадь px²': round(a, 1), 'площадь мм²': round(a / px_мм ** 2, 3) if px_мм else None}


def слово_точек(доля):
    """М-12: «N % ходов короче 1,5 своей ширины» — зеркалу, месту и подсказке одним словом."""
    return f'{100 * доля:.0f} % ходов короче {_ч(КОРОТКИЙ, 1)} своей ширины'


def _слова(о, образец):
    с, у, n = о.сводка, о.сводка['узость'], о.мазков
    узкие, широкие = [], []

    def раз(к):
        if образец is None or not с.get(к):
            return ''
        if isinstance(образец, Однообразие):
            э, по = (образец.сводка[к] or {}).get('эфф') if образец.сводка.get(к) else None, ''
        else:                                              # мерка манеры образца (К-4): по картинке
            м = getattr(образец, 'образец', None) or образец
            э = {'наклон': ('направления',), 'длина': ('штрих', 'длина'), 'ширина': ('ширина мазка',)}.get(к)
            if э is None or not hasattr(м, 'сводка'):
                return ''
            d = м.сводка
            for ч in э:
                d = d.get(ч, {})
            if d.get('на полу', 0) > 0.5:                 # штрих уже первого сдвига линейки — не различается
                return ''
            э, по = d.get('эфф'), ' (образец — по картинке)'
        if not э:
            return ''
        k = э / max(с[к]['эфф'], 1e-9)
        return f'; у образца вариантов в {_ч(k, 1)} раза больше{по}' if k >= 1.2 else ''
    for к in ('нажим', 'кисть', 'длина', 'наклон', 'ширина', 'нагрузка'):
        v = с.get(к)
        if v is None or у.get(к) is None:
            continue
        if к in ('нажим', 'кисть'):
            if к == 'кисть':
                t = 'одна кисть' if v['разных'] == 1 else f'кистей {v["разных"]}, у частой {_ч(100 * v["доля частого"], 0)} %'
            else:
                t = ', '.join(f'{м} — {_ч(100 * д, 0)} %' for м, д in v['главные'][:2])
                t = f'профиль нажима {t}'
        elif к == 'наклон':
            t = 'наклон ' + ', '.join(f'{г}°±15 — {_ч(100 * д, 0)} %' for г, д in v['главные'][:2] if д >= 0.1)
        else:
            ед = {'длина': ' px', 'ширина': ' px', 'нагрузка': ''}[к]
            з = 2 if к == 'нагрузка' else 1
            t = f'{к} {_ч(v["p10"], з)}–{_ч(v["p90"], з)}{ед} (σ/ср {_ч(v["σ/ср"] or 0)})'
        t += f', вариантов {_ч(v["эфф"], 1)}' + раз(к)
        (узкие if у[к] >= 0.6 else широкие).append((к, t))
    if о.оценка >= ПОРОГ:
        голова = f'мазков {n} — похоже на один приём с дрожанием ({_ч(о.оценка)})'
    else:
        голова = f'мазков {n} — разные приёмы ({_ч(о.оценка)})'
    части = [(о.зона + ': ' if о.зона else '') + голова]
    лн = с.get('линии')
    if лн:
        части.append(f'ходов кистью из пучков {лн["ходов"]}, линий в них {лн["линий"]} (на ход p50 {_ч(лн["на ход"][1], 0)}) — '
                     'длина, ширина и нажим таких ходов считаны по линиям пучков')
    х = с.get('ход')
    if х and х['короче 1,5 ширины'] >= ДОЛЯ_ТОЧЕК:
        пл = (f'{_ч(х["площадь мм²"])} мм²' if х['площадь мм²'] is not None else f'{х["площадь px²"]:.0f} px²')
        части.append(слово_точек(х['короче 1,5 ширины']) + ' — похоже на раскраску точками, а не мазки (длина/ширина '
                     f'p10–p50–p90 {_ч(х["длина/ширина"][0])}–{_ч(х["длина/ширина"][1])}–{_ч(х["длина/ширина"][2])}, '
                     f'площадь хода p50 {пл})')
    if узкие:
        части.append('узко: ' + '; '.join(t for _, t in узкие))
    if широкие:
        части.append('разнообразно: ' + ', '.join(к for к, _ in широкие))
    ц = с.get('цвета')
    if ц:
        t = f'цветов {ц["разных"]} разных, на глаз {ц["на глаз"]}'
        з = с.get('замесы')
        if з:
            t += f'; замесов {з["замесов"]}, не с палитры {_ч(100 * з["не с палитры"], 0)} %'
        if з and з['без имени'] >= 20 and з['разных без имени'] >= 0.8 * з['без имени']:
            t += ' — цвет формулой на каждый мазок, не замесами (под рукой: х.палитра_с, х.палитра)'
        части.append(t)
        if з and з.get('первые') is not None:
            from .подсказки import факт_формулы, ИНСТРУМЕНТЫ_ФОРМУЛЫ
            ф = з['первые']
            части.append('подсказка: ' + факт_формулы(о.зона or 'зона', *ф) + ' — под рукой: ' + ', '.join(ИНСТРУМЕНТЫ_ФОРМУЛЫ))
    части.append(о.регулярность['слово'])
    return '. '.join(части)


