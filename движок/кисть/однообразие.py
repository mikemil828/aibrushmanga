def _cv(v):
    v = np.asarray(v, np.float64)
    v = v[np.isfinite(v)]
    return float(v.std() / v.mean()) if v.size and v.mean() > 1e-9 else 0.0


def _у(признак, разброс):
    край, ход = УЗОСТЬ_МЕСТА[признак]
    return float(np.clip((разброс - край) / -ход if ход < 0 else (край - разброс) / ход, 0.0, 1.0))


def мерка_места(мазки):
    """Зеркало места: узость кисти (доля частой), нагрузки, ширины, длины (σ/ср), наклона (σ, °) ходов — 0–1 по
    `УЗОСТЬ_МЕСТА`; 'оценка' — их среднее; 'узко' — словами признаки с узостью от 0,6 и вытирание перед ходом (от
    `ВЫТЕРТА` ходов; в оценку не идёт) и раскраска точками (от `ДОЛЯ_ТОЧЕК` ходов короче `КОРОТКИЙ` своей ширины, М-12; в
    оценку не идёт); 'узко по' — те же [(признак, узость, слова)], узкие первыми; 'числа' — из чего.
    Нагрузка — числом (σ/ср) или словом (доля частого); у ходов без нагрузки в строке — не меряется."""
    n = len(мазки)
    п = [_признаки_мазка(м) for м in мазки]
    кисти = {}
    for м in мазки:
        кисти.setdefault(м['кисть'], []).append(м.get('имя кисти') or '?')
    имена = max(кисти.values(), key=len)
    имя = max(sorted(set(имена)), key=имена.count)
    доля = len(имена) / n
    нг = [м['запись'].get('load') for м in мазки]
    есть = [v for v in нг if v is not None]
    ш = np.asarray(_по_линиям(п, 'ширина'))                  # К-14б: у кисти из пучков — по линиям пучков
    дл = np.asarray(_по_линиям(п, 'длина'))
    нк = _угловой([q['наклон'] for q in п])
    у, ч, по = {}, {}, []
    у['кисть'] = _у('кисть', доля)
    ч['кисть'] = (имя, round(доля, 3))
    по.append(('кисть', у['кисть'], f'одной кистью «{имя}» — {100 * доля:.0f} %'))
    if есть and len(есть) >= 0.9 * n:
        if all(isinstance(v, (int, float)) for v in есть):
            v = np.asarray(есть, np.float64)
            у['нагрузка'] = _у('нагрузка', _cv(v))
            p10, p90 = np.percentile(v, [10, 90])
            ч['нагрузка'] = (round(float(p10), 3), round(float(p90), 3), round(_cv(v), 3))
            по.append(('нагрузка', у['нагрузка'], f'нагрузка {_ч(p10)}' + ('' if p90 - p10 < 0.005 else f'–{_ч(p90)}')))
        else:
            с = [str(v) for v in есть]
            частая = max(sorted(set(с)), key=с.count)
            д = с.count(частая) / len(с)
            у['нагрузка'] = _у('кисть', д)
            ч['нагрузка'] = (частая, round(д, 3))
            по.append(('нагрузка', у['нагрузка'], f'нагрузка «{частая}» — {100 * д:.0f} %'))
    for к, v in (('ширина', ш), ('длина', дл)):
        у[к] = _у(к, _cv(v))
        p10, p50, p90 = np.percentile(v, [10, 50, 90])
        ч[к] = (round(float(p10), 1), round(float(p50), 1), round(float(p90), 1), round(_cv(v), 3))
        по.append((к, у[к], f'{к} {p50:.0f} px' if p90 - p10 < 0.5 else f'{к} {p10:.0f}–{p90:.0f} px'))
    if нк is not None:
        у['наклон'] = _у('наклон', нк['σ'])
        ч['наклон'] = (нк['ср'], нк['σ'])
        по.append(('наклон', у['наклон'], f'наклон {нк["ср"]:.0f}°±{max(нк["σ"], 0.0):.0f}°'))
    по = [т for т in по if т[1] >= 0.6]
    r, _ = _точки(п)
    тч = float((r < КОРОТКИЙ).mean())
    ч['короче 1,5 ширины'] = round(тч, 3)
    if тч >= ДОЛЯ_ТОЧЕК:                               # М-12: в оценку не идёт, как вытирание
        по.append(('точки', тч, слово_точек(тч)))
    вт = float(np.mean([bool(м.get('вытерта')) for м in мазки]))
    ч['вытерта'] = round(вт, 3)
    if вт >= ВЫТЕРТА:
        по.append(('вытерта', вт, 'вытерта перед каждым ходом' if вт >= 0.995 else f'вытерта перед {100 * вт:.0f} % ходов'))
    return {'мазков': n, 'оценка': round(float(np.mean(list(у.values()))), 3), 'узость': {к: round(v, 3) for к, v in у.items()},
            'узко': [т[2] for т in по], 'узко по': sorted(по, key=lambda т: -т[1]), 'числа': ч}


def _клетка_px(мета, клетка):
    px = (мета or {}).get('px_на_мм')
    if клетка is None:
        return float(КЛЕТКА_ММ * px) if px else float(КЛЕТКА_PX)
    return float(клетка * px) if px else float(клетка * КЛЕТКА_PX / КЛЕТКА_ММ)


def _имя_зоны(м):
    return ('объект', str(м['объект'])) if м['объект'] is not None else ('слой', str(м['слой']))


def места_мазков(мазки, клетка_px=КЛЕТКА_PX, зоны=None):
    """Места: мазки каждого объекта (без пометки объекта — слоя) по клеткам `клетка_px` (по центру хода); место — зона ×
    клетка от `МЕСТО_ХОДОВ` ходов. Ответ — (места, объекты, клетки): места — список словарей ('объект' или 'слой', 'клетка',
    'рамка' — ходы места в клетке, x0, y0, x1, y1 px, 'мазков', 'оценка', 'узость', 'узко', 'числа', 'номера'), худшие
    первыми; объекты — {(вид, имя): {'мазков', 'мест', 'худших' (от `ПОРОГ_МЕСТА`), 'оценка' — худшего места}};
    клетки — клетки листа, каждая своим худшим местом (тем же словарём), худшие первыми. зоны — только эти (вид, имя)."""
    гр = {}
    for м in мазки:
        з = _имя_зоны(м)
        if зоны is not None and з not in зоны:
            continue
        c = _признаки_мазка(м)['центр']
        к = (int(math.floor(c[0] / клетка_px)), int(math.floor(c[1] / клетка_px)))
        гр.setdefault((з, к), []).append(м)
    с_палитрой = any(м.get('замес') is not None for м in мазки)     # М-1: лист с палитрой — у места доля не с палитры

    def место(мм, к):
        x0, y0 = к[0] * клетка_px, к[1] * клетка_px
        р = np.asarray([_признаки_мазка(м)['рамка'] for м in мм])
        рамка = (max(x0, float(р[:, 0].min())), max(y0, float(р[:, 1].min())),
                 min(x0 + клетка_px, float(р[:, 2].max())), min(y0 + клетка_px, float(р[:, 3].max())))
        д = мерка_места(мм)
        д.update({'клетка': (round(x0), round(y0), round(x0 + клетка_px), round(y0 + клетка_px)),
                  'рамка': tuple(int(round(max(v, 0.0))) for v in рамка), 'номера': [м['номер'] for м in мм]})
        цв = [м for м in мм if м['цвет'] is not None]
        if с_палитрой and цв:
            д['не с палитры'] = round(sum(м.get('замес') is None for м in цв) / len(цв), 3)
        return д
    места, объекты = [], {}
    for (з, к), мм in гр.items():
        о = объекты.setdefault(з, {'мазков': 0, 'мест': 0, 'худших': 0, 'оценка': None})
        о['мазков'] += len(мм)
        if len(мм) < МЕСТО_ХОДОВ:
            continue
        д = место(мм, к)
        д[з[0]] = з[1]
        места.append(д)
        о['мест'] += 1
        о['худших'] += д['оценка'] >= ПОРОГ_МЕСТА
        о['оценка'] = д['оценка'] if о['оценка'] is None else max(о['оценка'], д['оценка'])
    ключ = lambda д: (-д['оценка'], -д['мазков'], д['клетка'][1], д['клетка'][0])
    места.sort(key=ключ)
    клетки = {}
    for д in места:                                   # клетка листа — её худшим местом
        клетки.setdefault(д['клетка'], д)
    return места, объекты, list(клетки.values())


def слово_места(д):
    """Место одной строкой: «объект «фон», рамка (x0, y0, x1, y1): N ходов, оценка — узко: …»."""
    з = f'объект «{д["объект"]}»' if 'объект' in д else f'слой «{д["слой"]}»' if 'слой' in д else 'клетка листа'
    return (f'{з}, рамка {tuple(д["рамка"])}: {д["мазков"]} ходов, {_ч(д["оценка"])}'
            + (' — ' + ', '.join(д['узко']) if д['узко'] else '')
            + (f'; не с палитры {_ч(100 * д["не с палитры"], 0)} %' if д.get('не с палитры') else ''))


def _слова_точек_мест(о, ед):
    """М-12: строка «точками» — места, где от `ДОЛЯ_ТОЧЕК` ходов короче `КОРОТКИЙ` своей ширины, больше всего точек
    первыми (до трёх рамками); таких мест нет — пусто."""
    т = sorted((д for д in о.места if д['числа'].get('короче 1,5 ширины', 0) >= ДОЛЯ_ТОЧЕК),
               key=lambda д: (-д['числа']['короче 1,5 ширины'], -д['мазков'], д['клетка'][1], д['клетка'][0]))
    if not т:
        return ''
    return (f'\nточками (от {100 * ДОЛЯ_ТОЧЕК:.0f} % ходов короче {_ч(КОРОТКИЙ, 1)} своей ширины) — мест {len(т)} из '
            f'{len(о.места)} (клетка {ед}); больше всего: '
            + '; '.join(f'{"объект «" + д["объект"] if "объект" in д else "слой «" + д["слой"]}», рамка {tuple(д["рамка"])} — '
                        f'{100 * д["числа"]["короче 1,5 ширины"]:.0f} % из {д["мазков"]}' for д in т[:3]))


def _слова_мест(о, клетка_мм):
    ед = f'{клетка_мм:.0f} мм' if клетка_мм else f'{о.клетка:.0f} px'
    return _слова_мест_оценки(о, ед) + _слова_точек_мест(о, ед)


def _слова_мест_оценки(о, ед):
    худшие = [д for д in о.места if д['оценка'] >= ПОРОГ_МЕСТА]
    if not о.места:
        return f'мест нет: ни в одной клетке {ед} у зоны (объект, без пометки — слой) нет {МЕСТО_ХОДОВ} ходов'
    if not худшие:
        return (f'мест {len(о.места)} (объект × клетка {ед}, от {МЕСТО_ХОДОВ} ходов); от {_ч(ПОРОГ_МЕСТА)} — ни одного, '
                f'наибольшая оценка {_ч(о.места[0]["оценка"])}: ' + слово_места(о.места[0]))
    ч = [f'места (объект × клетка {ед}, от {МЕСТО_ХОДОВ} ходов): {len(о.места)}, из них от {_ч(ПОРОГ_МЕСТА)} — {len(худшие)}; '
         f'худшие:']
    ч += [f'  {i}. ' + слово_места(д) for i, д in enumerate(худшие[:МЕСТ], 1)]
    зоны = sorted(((з, v) for з, v in о.объекты.items() if v['худших']), key=lambda t: (-t[1]['худших'], -t[1]['мазков']))
    ч.append('по зонам — мест от порога из мест: ' + ', '.join(f'{з[1]} {v["худших"]}/{v["мест"]}' for з, v in зоны[:12])
             + (f' и ещё {len(зоны) - 12}' if len(зоны) > 12 else ''))
    return '\n'.join(ч)


def _слова_замесов(мазки, зон=12):
    """М-1: строка «замесы по зонам» — у каждой зоны (объект, без пометки — слой) замесов и доля не с палитры."""
    гр = {}
    for м in мазки:
        гр.setdefault(_имя_зоны(м), []).append(м)
    if not any(м.get('замес') is not None for м in мазки):
        return '\nзамесы по зонам: палитры нет — все ходы с краской не с палитры' if any(м['цвет'] is not None for м in мазки) else ''
    ч = []
    for з, мм in sorted(гр.items(), key=lambda t: -len(t[1])):
        с = _замесы(мм)
        if с is not None:
            ч.append(f'{з[1]} {с["замесов"]} (не с палитры {_ч(100 * с["не с палитры"], 0)} %)')
    if not ч:
        return ''
    return '\nзамесы по зонам: ' + ', '.join(ч[:зон]) + (f' и ещё {len(ч) - зон}' if len(ч) > зон else '')


def карта_мест(о, путь, фон=None, размер=1600):
    """PNG: лист (фон — sRGB (В, Ш, 3) холста; без него — серый), клетки листа подкрашены оценкой своего худшего места
    (от 0,4 — жёлтым к красному), места от `ПОРОГ_МЕСТА` — рамками, худшие `МЕСТ` — толще и номерами, как в словах.
    Ответ — массив uint8."""
    from PIL import Image, ImageDraw
    from .глаз import _шрифт
    Ш, В = о.холст_размер
    k = min(1.0, float(размер) / max(Ш, В))
    ш, в = max(1, int(round(Ш * k))), max(1, int(round(В * k)))
    if фон is None:
        осн = Image.new('RGB', (ш, в), (128, 128, 128))
    else:
        осн = Image.fromarray(np.clip(np.asarray(фон) + 0.5, 0, 255).astype(np.uint8)).resize((ш, в), Image.LANCZOS)
    осн = Image.blend(осн, Image.new('RGB', (ш, в), (255, 255, 255)), 0.35)
    слой = Image.new('RGBA', (ш, в), (0, 0, 0, 0))
    д = ImageDraw.Draw(слой)
    for c in о.клетки:
        t = (c['оценка'] - 0.4) / (1.0 - 0.4)
        if t <= 0:
            continue
        x0, y0, x1, y1 = (v * k for v in c['клетка'])
        д.rectangle((x0, y0, x1 - 1, y1 - 1), fill=(255, int(200 * (1 - t)), 0, int(15 + 65 * t)))
    осн = Image.alpha_composite(осн.convert('RGBA'), слой).convert('RGB')
    д = ImageDraw.Draw(осн)
    шрифт = _шрифт(max(12, int(round(в / 40))))
    худшие = [м for м in о.места if м['оценка'] >= ПОРОГ_МЕСТА]
    for i, м in enumerate(худшие):
        x0, y0, x1, y1 = (v * k for v in м['рамка'])
        д.rectangle((x0, y0, x1, y1), outline=(200, 0, 0) if i < МЕСТ else (150, 40, 0), width=4 if i < МЕСТ else 1)
    for i, м in enumerate(худшие[:МЕСТ], 1):
        x0, y0 = м['рамка'][0] * k, м['рамка'][1] * k
        д.rectangle((x0 + 2, y0 + 2, x0 + 4 + шрифт.getlength(str(i)), y0 + 4 + шрифт.size), fill=(200, 0, 0))
        д.text((x0 + 3, y0 + 2), str(i), fill=(255, 255, 255), font=шрифт)
    if путь is not None:
        осн.save(os.path.expanduser(str(путь)))
    return np.asarray(осн)


def однообразие(журнал, объект=None, этап=None, область=None, мазки=None, слой=None, образец=None, путь=None,
                клетка=None, фон=None):
    """К-12: зеркало однообразия зоны журнала (путь .jsonl, строки или байты). Зона — объект, этап, слой, область
    (центр мазка в (x0, y0, x1, y1)), мазки (номера строк журнала или сами строки-словари); не задано — весь журнал.
    образец — `Однообразие` зоны образца (или словарь тех же отборов по этому журналу) или мерка манеры картины
    (`манера.мерка`, `х.манера(…, образец=…)`, К-4: наклон, длина штриха и ширина мазка — по картинке): во сколько раз у него
    вариантов больше. Ответ — `Однообразие`.
    Без отбора объекта, этапа, слоя и мазков (область — можно) — и с адресом: `места` — каждый объект (без пометки —
    слой) по клеткам листа `клетка` мм (без неё — `КЛЕТКА_ММ`), худшие первыми, с рамкой, оценкой и словами, что узко
    (`мерка_места`); `объекты` — по зонам: мест и худших; `клетки` — клетки листа худшим местом; `путь` — PNG-карта
    (`карта_мест`, фон — sRGB холста); худшие места — и в `слова`."""
    мета = {}
    if мазки is not None and len(мазки) and isinstance(next(iter(мазки)), dict):
        все = мазки_журнала([json.dumps(з, ensure_ascii=False) for з in мазки], мета=мета)
        номера = None
    else:
        все = мазки_журнала(журнал, мета=мета)
        номера = мазки
    зона = ', '.join(f'{к} {v}' for к, v in (('объект', объект), ('этап', этап), ('слой', слой), ('область', область))
                     if v is not None)
    if isinstance(образец, dict):
        образец = отчёт(отобрать(все, **образец), ', '.join(f'{к} {v}' for к, v in образец.items()))
    зона_мазков = отобрать(все, объект, этап, слой, область, номера)
    о = отчёт(зона_мазков, зона, образец, мета.get('px_на_мм'))
    if объект is None and этап is None and слой is None and мазки is None:
        о.клетка = _клетка_px(мета, клетка)
        о.места, о.объекты, о.клетки = места_мазков(зона_мазков, о.клетка)
        о.слова += '.\n' + _слова_мест(о, клетка or (КЛЕТКА_ММ if мета.get('px_на_мм') else None))
        о.слова += _слова_замесов(зона_мазков)
        if путь is not None:
            р = мета.get('холст')
            if р is None:
                xs = [_признаки_мазка(м)['рамка'] for м in зона_мазков] or [(0, 0, 1, 1)]
                р = (int(max(r[2] for r in xs)) + 1, int(max(r[3] for r in xs)) + 1)
            о.холст_размер = р
            о.карта = карта_мест(о, путь, фон)
    elif путь is not None or клетка is not None:
        raise ValueError('однообразие: путь= и клетка= — у зеркала без отбора (места по всему листу или области)')
    return о


def регулярность(журнал, объект=None, этап=None, область=None, мазки=None, слой=None):
    """Б-9: мерка регулярности зоны журнала (отбор — как у `однообразие`) — словарь `регулярность_мазков`."""
    return однообразие(журнал, объект, этап, область, мазки, слой).регулярность
