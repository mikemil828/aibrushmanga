def _строки(журнал):
    if isinstance(журнал, (str, os.PathLike)):
        with open(os.path.expanduser(os.fspath(журнал)), encoding='utf-8') as f:
            for номер, s in enumerate(f, 1):
                yield номер, s
    else:
        for номер, s in enumerate(журнал, 1):
            yield номер, (s.decode('utf-8') if isinstance(s, bytes) else s)


class _Чтец:
    """Разбор журнала по строкам с памятью (кисти, набранное, пометка, вытертые) — `мазки_журнала` разом, `Дочитка`
    — по мере роста файла."""

    def __init__(self, кисти=None, мета=None):
        self.кисти = {} if кисти is None else кисти
        self.мета = {} if мета is None else мета
        self.набрано, self.мазки, self.px_мм, self.чистые = {}, [], None, set()
        self.замесы, self.замес_кисти = {}, {}      # М-1: палитра по строкам "palette" и замес, набранный кистью
        self.тек = {'stage': None, 'object': None}

    def строки(self, пары):
        кисти, набрано, тек, чистые = self.кисти, self.набрано, self.тек, self.чистые
        for номер, s in пары:
            s = s.strip()
            if not s or s.startswith('#'):
                continue
            з = json.loads(s)
            if 'canvas' in з:
                self.px_мм = з.get('px_per_mm')
                self.мета['холст'], self.мета['px_на_мм'] = tuple(з['canvas'][:2]), self.px_мм
            if isinstance(з.get('brush'), str) and ('wipe' in з or 'def' in з) and 'ctrl' not in з \
                    and 'points' not in з and 'core' not in з:
                чистые.add(з['brush'])
            if 'mark' in з:
                тек = self.тек = {п: з.get(п, тек[п]) for п in тек}
            if 'def' in з and isinstance(з.get('brush'), str):
                д, px_мм = з['def'], self.px_мм
                ш = (д['ширина_мм'] * px_мм) if д.get('ширина_мм') and px_мм else д.get('ширина')
                кисти[з['brush']] = (json.dumps({к: v for к, v in д.items() if к not in _БЕЗ}, sort_keys=True), ш)
            if 'palette' in з:
                self.замесы[з['palette']] = з.get('color')
                continue
            if 'pick' in з and isinstance(з.get('brush'), str):
                набрано[з['brush']] = з['pick']
                self.замес_кисти[з['brush']] = з.get('swatch')
            if isinstance(з.get('load_brush'), str):          # Д-1: набор живой краски — как "pick"
                набрано[з['load_brush']] = з.get('color', з.get('colors'))
                self.замес_кисти[з['load_brush']] = з.get('swatch')
            if 'layer_drop' in з:
                self.мазки = [м for м in self.мазки if м['слой'] != з['layer_drop']]
            сырые = з.get('ctrl', з.get('points', з.get('core')))
            if сырые is None or 'tool' in з or 'mark' in з:
                continue
            имя = з.get('brush')
            ключ, ш0 = кисти.get(имя, (str(имя), None))
            ц = з.get('color', з.get('colors'))
            замес = з.get('swatch')
            if ц is None:
                ц = набрано.get(имя)
                замес = self.замес_кисти.get(имя)
            if isinstance(замес, str) and self.замесы.get(замес) is not None:
                ц = self.замесы[замес]                   # правленый замес: цвет — из строки палитры, как у повтора
            if isinstance(замес, list) and any(и is None for и in замес):
                замес = None                             # набор, где не всё с палитры, — не с палитры
            if ц is not None and len(ц) and isinstance(ц[0], (list, tuple)):
                ц = ц[0]
            вытерта = имя in чистые or bool(з.get('wipe'))
            чистые.discard(имя)
            self.мазки.append({'номер': номер, 'запись': з, 'этап': з.get('stage', тек['stage']),
                               'объект': з.get('object', тек['object']), 'слой': з.get('layer', 'основа'), 'кисть': ключ,
                               'имя кисти': str(имя), 'вытерта': вытерта, 'ширина': float(з.get('size') or ш0 or 1.0),
                               'цвет': None if ц is None else tuple(float(v) for v in list(ц)[:3]),
                               'замес': (замес if isinstance(замес, str) else None if замес is None
                                         else ' + '.join(sorted(set(замес))))})
        return self.мазки


def мазки_журнала(журнал, кисти=None, мета=None):
    """Мазки журнала (путь, строки или байты) — список словарей: 'номер' (строка журнала), 'запись' (сама строка),
    'этап', 'объект', 'слой', 'кисть' (ключ полей кисти), 'имя кисти', 'ширина', 'цвет' (sRGB первой краски или None),
    'вытерта' (кисть вытерта или заведена между прошлым своим ходом и этим). кисти — {имя: (ключ, ширина px)} из начала
    журнала (для куска, чьи кисти заведены раньше); дополняется. мета — словарь: в него 'холст' (ширина, высота) и
    'px_на_мм' из строки "canvas"."""
    if isinstance(журнал, (bytes, bytearray)):
        журнал = bytes(журнал).decode('utf-8').splitlines()
    return _Чтец(кисти, мета).строки(_строки(журнал))


class Дочитка:
    """Журнал листа, что растёт по ходу письма (подсказка С14): каждый `мазки()` дочитывает только новые полные строки.
    Файл переписан (перезапуск с сохранения обрезал его, лист с начала) — последняя прочитанная строка не на месте, —
    читается с начала. Признаки мазков (`_признаки_мазка`) считаются раз."""

    def __init__(self, путь):
        self.путь = os.fspath(путь)
        self._сначала()

    def _сначала(self):
        self.чтец, self.место, self.номер, self.хвост = _Чтец(), 0, 0, b''

    def мазки(self):
        with open(self.путь, 'rb') as f:
            if self.место:
                f.seek(self.место - len(self.хвост))
                if f.read(len(self.хвост)) != self.хвост:
                    self._сначала()
                    f.seek(0)
            новое = f.read()
        конец = новое.rfind(b'\n') + 1
        if конец:
            строки = новое[:конец].split(b'\n')[:-1]
            n0 = self.номер
            self.чтец.строки((n0 + i, s.decode('utf-8')) for i, s in enumerate(строки, 1))
            self.номер += len(строки)
            self.место += конец
            self.хвост = строки[-1][-64:] + b'\n'
        return self.чтец.мазки

    @property
    def мета(self):
        return self.чтец.мета


def отобрать(мазки, объект=None, этап=None, слой=None, область=None, номера=None):
    """Мазки зоны: "object", "stage", "layer" (сравнение строкой; список — любой из), центр в области (x0, y0, x1,
    y1), номера строк журнала."""
    def да(v, нужно):
        if нужно is None:
            return True
        нужно = нужно if isinstance(нужно, (list, tuple, set)) else [нужно]
        return str(v) in {str(н) for н in нужно}
    номера = None if номера is None else set(int(н) for н in номера)
    ответ = []
    for м in мазки:
        if not (да(м['объект'], объект) and да(м['этап'], этап) and да(м['слой'], слой)):
            continue
        if номера is not None and м['номер'] not in номера:
            continue
        if область is not None:
            c = _признаки_мазка(м)['центр']
            x0, y0, x1, y1 = область
            if not (x0 <= c[0] < x1 and y0 <= c[1] < y1):
                continue
        ответ.append(м)
    return ответ


def _признаки_мазка(м):
    п = м.get('_п')
    if п is not None:
        return п
    з = м['запись']
    сырые = з.get('ctrl', з.get('points', з.get('core')))
    a = np.asarray([list(q) for q in сырые], np.float64)
    a = a.reshape(len(a), -1) if a.size else np.zeros((0, 2))
    т = a[:, :2]
    сег = np.hypot(*np.diff(т, axis=0).T) if len(т) > 1 else np.zeros(0)
    дл = float(сег.sum())
    if дл > 1e-9:
        d = np.concatenate([[0.0], np.cumsum(сег)])
        центр = np.array([np.interp(дл / 2, d, т[:, 0]), np.interp(дл / 2, d, т[:, 1])])
    else:
        центр = т.mean(0) if len(т) else np.zeros(2)
    хорда = т[-1] - т[0] if len(т) > 1 else np.zeros(2)
    х_дл = float(np.hypot(*хорда))
    наклон = float(np.degrees(np.arctan2(хорда[1], хорда[0])) % 180.0) if х_дл > 1e-6 else math.nan
    if 'core' in з and 'ctrl' not in з and a.shape[1] >= 3 and len(a) > 1:
        d = np.concatenate([[0.0], np.cumsum(сег)])
        нп = np.interp(np.linspace(0, d[-1], 5), d, a[:, 2])
        нажим = 'точки ' + ' '.join(f'{v:.1f}' for v in нп)
    else:
        р = з.get('pressure')
        нажим = (f'{float(р):.2f}' if isinstance(р, (int, float)) else ('вдоль' if р is not None else '—'))
        нажим += f' «{з["end"]}»' if з.get('end') else ''
        нажим += f' вход {з["entry"]}' if з.get('entry') is not None else ''
    р = м['ширина'] / 2.0
    рамка = ((float(т[:, 0].min()) - р, float(т[:, 1].min()) - р, float(т[:, 0].max()) + р, float(т[:, 1].max()) + р)
             if len(т) else (0.0, 0.0, 0.0, 0.0))
    линии = з.get('lines') or None                   # К-14б: ход кистью из пучков — линии пучков [[длина px, ширина px, нажим], …]
    п = {'линии': None if линии is None else np.asarray(линии, np.float64).reshape(len(линии), -1),
         'длина': дл, 'наклон': наклон, 'изгиб': дл / х_дл if х_дл > 1e-6 else math.nan, 'ширина': м['ширина'], 'рамка': рамка,
         'нажим': нажим, 'нагрузка': float(з['load']) if isinstance(з.get('load'), (int, float)) else math.nan,
         'центр': центр}
    м['_п'] = п
    return п


def _по_линиям(п, поле):
    """К-14б: значения признака серии — у хода кистью из пучков (`Кисть.просветы`, строка с "lines") по одному на линию
    пучка (длина касания, ширина пучка), у остальных — одно на ход. поле — 'длина' или 'ширина'."""
    k = {'длина': 0, 'ширина': 1}[поле]
    v = []
    for q in п:
        if q['линии'] is None:
            v.append(q[поле])
        else:
            v.extend(q['линии'][:, k].tolist())
    return v


def _нажим_по_линиям(п):
    """К-14б: профили нажима серии; у линии пучка — профиль хода и её нажим сверх порога касания пучка ступенями 0,1."""
    v = []
    for q in п:
        if q['линии'] is None:
            v.append(q['нажим'])
        else:
            v.extend(f'{q["нажим"]} · пучок {н:.1f}' for н in q['линии'][:, 2])
    return v


