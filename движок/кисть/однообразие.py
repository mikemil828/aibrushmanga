def _эфф(метки):
    """exp(энтропия) меток: сколько вариантов на деле."""
    _, n = np.unique(np.asarray(метки), return_counts=True)
    p = n / n.sum()
    return float(math.exp(-(p * np.log(p)).sum()))


def _узость(эфф, n):
    ref = min(ВАРИАНТОВ, n)
    if ref <= 1:
        return 1.0
    return float(np.clip(1.0 - math.log(max(эфф, 1.0)) / math.log(ref), 0.0, 1.0))


def _непрерывный(v, корзины):
    v = np.asarray(v, np.float64)
    v = v[np.isfinite(v)]
    if not v.size:
        return None
    p10, p50, p90 = np.percentile(v, [10, 50, 90])
    ср, σ = float(v.mean()), float(v.std())
    return {'ср': round(ср, 3), 'σ': round(σ, 3), 'σ/ср': round(σ / ср, 3) if ср > 1e-9 else None,
            'p10': round(float(p10), 3), 'p50': round(float(p50), 3), 'p90': round(float(p90), 3),
            'эфф': round(_эфф(корзины(v)), 2), 'n': int(v.size)}


def _угловой(v):
    v = np.asarray(v, np.float64)
    v = v[np.isfinite(v)]
    if not v.size:
        return None
    z = np.exp(2j * np.radians(v)).mean()
    ср = float(np.degrees(np.angle(z)) / 2 % 180.0)
    R = float(abs(z))
    σ = float(np.degrees(math.sqrt(max(-2 * math.log(max(R, 1e-12)), 0.0))) / 2)
    к = np.floor(((v + 15.0) % 180.0) / 30.0).astype(int)              # 6 корзин по 30°, 0° — в середине первой
    _, n = np.unique(к, return_counts=True)
    главные = sorted(((int(c), int(m)) for c, m in zip(*np.unique(к, return_counts=True))), key=lambda t: -t[1])
    return {'ср': round(ср, 1), 'σ': round(σ, 1), 'R': round(R, 3), 'эфф': round(_эфф(к), 2), 'n': int(v.size),
            'главные': [(c * 30, round(m / v.size, 3)) for c, m in главные[:3]]}


def _категории(v):
    # М-11: счёт словарём, не массивом строк numpy (ширина — по длиннейшей строке ×4 байта: ключи кистей на 210 тыс.
    # ходов — 1,3 ГБ); порядок значений — тот же, что у np.unique (по кодам), счёт и argsort — те же
    счёт = {}
    for x in v:
        x = str(x)
        счёт[x] = счёт.get(x, 0) + 1
    знач = sorted(счёт)
    n = np.asarray([счёт[x] for x in знач])
    i = np.argsort(-n)
    p = n / n.sum()
    return {'разных': int(len(знач)), 'частое': str(знач[i[0]]), 'доля частого': round(float(n[i[0]] / n.sum()), 3),
            'эфф': round(float(math.exp(-(p * np.log(p)).sum())), 2), 'n': int(n.sum()),
            'главные': [(str(знач[j]), round(float(n[j] / n.sum()), 3)) for j in i[:3]]}


def _замесы(мазки):
    """М-1: замесы зоны — сколько разных имён замесов у ходов с краской, доля ходов не с палитры (цвет без имени
    замеса), сколько таких и разных цветов у них; 'первые' — (ходов, не с палитры, разных) первых `подсказки.ФОРМУЛА_ХОДОВ`
    ходов с краской, если по ним звучит подсказка «цвет формулой» (С16), иначе None."""
    from .подсказки import ФОРМУЛА_ХОДОВ, ФОРМУЛА_ДОЛЯ
    с_краской = [м for м in мазки if м['цвет'] is not None]
    if not с_краской:
        return None
    без = [м for м in с_краской if м.get('замес') is None]
    имена = set()
    for м in с_краской:
        if м.get('замес') is not None:
            имена.update(м['замес'].split(' + '))
    первые = None
    п = с_краской[:ФОРМУЛА_ХОДОВ]
    if len(п) >= ФОРМУЛА_ХОДОВ:
        пб = [м for м in п if м.get('замес') is None]
        р = len({json.dumps(м['запись'].get('color', м['запись'].get('colors', м['цвет']))) for м in пб})
        if len(пб) >= ФОРМУЛА_ДОЛЯ * len(п) and р >= ФОРМУЛА_ДОЛЯ * len(пб):
            первые = (len(п), len(пб), р)
    return {'замесов': len(имена), 'не с палитры': round(len(без) / len(с_краской), 3), 'без имени': len(без),
            'разных без имени': len({м['цвет'] for м in без}), 'n': len(с_краской), 'первые': первые}


