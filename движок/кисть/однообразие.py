СОСЕДЕЙ = 8             # М-11: сколько ближайших брать у дерева разом; равных дальше — шаром


def _соседи(c):
    """Расстояние до ближайшего соседа и вектор к нему — точно как полный перебор (np.hypot, из равных — меньший
    номер), но деревом (scipy cKDTree): n·log n и память на n, а не n² (М-11: журнал 590 тыс. строк перебором кусками
    просил 11 ГБ). Дерево даёт кандидатов, расстояние пересчитывается тем же np.hypot; если у кандидатов последний не
    дальше ближайшего (равных больше, чем взято), — все в шаре этого радиуса."""
    from scipy.spatial import cKDTree
    n = len(c)
    if n < 2:
        return np.full(n, np.inf), np.zeros_like(c)
    k = min(n, СОСЕДЕЙ + 1)
    jj = cKDTree(c).query(c, k=k)[1]
    свои = np.arange(n)[:, None]
    h = np.hypot(c[:, None, 0] - c[jj, 0], c[:, None, 1] - c[jj, 1])
    h[jj == свои] = np.inf
    d = h.min(1)
    j = np.where(h == d[:, None], jj, n).min(1)
    if k < n:
        мало = np.flatnonzero(h[np.arange(n), (np.where(np.isfinite(h), h, -1.0)).argmax(1)] <= d * (1 + 1e-9) + 1e-12)
        нуль = мало[d[мало] == 0]
        if нуль.size:                                     # центры в одной точке: сосед — меньший номер той же точки
            _, гр = np.unique(c, axis=0, return_inverse=True)
            гр = гр.ravel()
            п = np.lexsort((np.arange(n), гр))           # по группе, внутри — по номеру
            нач = np.r_[0, np.flatnonzero(np.diff(гр[п])) + 1]
            перв = np.empty(n, int)
            втор = np.full(n, n)
            перв[гр[п[нач]]] = п[нач]
            ещё = нач[(нач + 1 < n) & (np.r_[нач[1:], n] > нач + 1)]
            втор[гр[п[ещё]]] = п[ещё + 1]
            j[нуль] = np.where(перв[гр[нуль]] == нуль, втор[гр[нуль]], перв[гр[нуль]])
            мало = мало[d[мало] > 0]
        if мало.size:                                     # равных ближайшему больше, чем взято: шаром
            шары = cKDTree(c).query_ball_point(c[мало], d[мало] * (1 + 1e-9) + 1e-9)
            for i, ш in zip(мало, шары):
                ш = np.asarray([q for q in ш if q != i], int)
                hh = np.hypot(c[i, 0] - c[ш, 0], c[i, 1] - c[ш, 1])
                d[i] = hh.min()
                j[i] = ш[hh == d[i]].min()
    return d, c[j] - c


def _площадь(c):
    """Площадь выпуклой оболочки точек (монотонная цепь)."""
    p = sorted(set(map(tuple, np.round(c, 6))))
    if len(p) < 3:
        return 0.0
    def крест(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])
    низ, верх = [], []
    for q in p:
        while len(низ) >= 2 and крест(низ[-2], низ[-1], q) <= 0:
            низ.pop()
        низ.append(q)
    for q in reversed(p):
        while len(верх) >= 2 and крест(верх[-2], верх[-1], q) <= 0:
            верх.pop()
        верх.append(q)
    о = np.asarray(низ[:-1] + верх[:-1])
    return float(abs(np.dot(о[:, 0], np.roll(о[:, 1], 1)) - np.dot(о[:, 1], np.roll(о[:, 0], 1))) / 2)


def _ровность(v):
    """Насколько значения равномерны на своём размахе, 0–1: D — Колмогоров против равномерного; сверх шума выборки
    (0,87/√n — столько даёт сам равномерный случай) каждые 0,25 D снимают единицу."""
    v = np.sort(np.asarray(v, np.float64)[np.isfinite(v)])
    n = len(v)
    if n < 5 or v[-1] - v[0] < 1e-9:
        return 0.0
    u = (v - v[0]) / (v[-1] - v[0])
    i = np.arange(1, n + 1) / n
    D = float(max(np.abs(i - u).max(), np.abs(u - (i - 1 / n)).max()))
    return float(np.clip(1.0 - max(D - 0.87 / math.sqrt(n), 0.0) / 0.25, 0.0, 1.0))


def регулярность_мазков(мазки):
    """Б-9: по центрам, наклонам, длинам и шагу (порядок журнала) — похоже ли на сетку с дрожанием или на равномерный
    случай. Ответ — словарь: 'сетка', 'случай' 0–1, 'итог' — большее из них, 'слово', и из чего они:
      'сосед σ/ср' — разброс расстояний до ближайшего соседа (сетка ~0,1–0,3, случай ~0,5, рука по форме — выше);
      'сетка' — большее из 'шаг повторён' и среднего двух: соседи на равных расстояниях (σ/ср от 0,35 к 0,1) и
          порядок (от 0,3 к 0,8) — рука, что кроет место ровно, даёт σ/ср ~0,4 и порядок ~0,3; 'случай' — среднее
          (R около 1, прыжки шага, ровность мест x, y, ровность наклона и длины);
      'R' — Кларк–Эванс: ср. расстояние до соседа / 0,5·√(площадь оболочки / n) (сетка 1,4–2, случай ~1, кучно < 1);
      'порядок' — |⟨e^{imφ}⟩| векторов к соседу, наибольший по m = 2, 4, 6 (ряд, квадрат, соты — 1);
      'шаг/сосед' — медиана шага от мазка к следующему по журналу / ср. расстояние до соседа (рука и ряд ~1–2, случай —
          прыжки через всю зону); 'шаг повторён' — доля шагов, что повторяют прошлый вектор с точностью 25 %;
      'ровность x', 'ровность y', 'ровность наклона', 'ровность длины' — 1, когда значения ровно размазаны по размаху
          (так даёт равномерный случай), 0 — когда сбиты к местам."""
    n = len(мазки)
    if n < 5:
        return {'мазков': n, 'сетка': 0.0, 'случай': 0.0, 'итог': 0.0, 'слово': f'мазков {n} — мало для мерки (от 5)'}
    п = [_признаки_мазка(м) for м in мазки]
    c = np.asarray([q['центр'] for q in п])
    d, к_соседу = _соседи(c)
    ср_d = float(d.mean())
    cv = float(d.std() / ср_d) if ср_d > 1e-9 else 0.0
    S = _площадь(c)
    R = ср_d / (0.5 * math.sqrt(S / n)) if S > 1e-9 else 0.0
    φ = np.arctan2(к_соседу[:, 1], к_соседу[:, 0])
    порядок = max(float(abs(np.exp(1j * m * φ).mean())) for m in (2, 4, 6))
    шаг = np.diff(c, axis=0)
    дш = np.hypot(*шаг.T)
    шаг_сосед = float(np.median(дш) / ср_d) if ср_d > 1e-9 else 0.0
    повтор = np.hypot(*(шаг[1:] - шаг[:-1]).T) <= 0.25 * np.maximum(дш[1:], 1e-9)
    шаг_повторён = float(повтор.mean()) if len(повтор) else 0.0
    ровн = {'x': _ровность(c[:, 0]), 'y': _ровность(c[:, 1]),
            'наклона': _ровность([q['наклон'] for q in п]), 'длины': _ровность([q['длина'] for q in п])}
    if ср_d < 1e-9:                           # все в одной точке: сетка вырождена
        сетка = 1.0
    else:
        сетка = max(шаг_повторён, float(np.mean([np.clip((0.35 - cv) / 0.25, 0, 1), np.clip((порядок - 0.3) / 0.5, 0, 1)])))
    случай = float(np.mean([1.0 - np.clip(abs(R - 1.0) / 0.35, 0, 1), np.clip((шаг_сосед - 2.0) / 4.0, 0, 1),
                            (ровн['x'] + ровн['y']) / 2, (ровн['наклона'] + ровн['длины']) / 2]))
    итог = max(сетка, случай)
    if итог < ПОРОГ:
        слово = 'места не сетка и не равномерный случай'
    elif сетка >= случай:
        почему = (f'шаг к следующему повторяет прошлый у {_ч(100 * шаг_повторён, 0)} % — ряды' if шаг_повторён >= 0.5
                  else f'соседи на ровных расстояниях (σ/ср {_ч(cv)}), порядок {_ч(порядок)}')
        слово = f'места похожи на сетку с дрожанием ({_ч(сетка)}): {почему}'
    else:
        слово = (f'места похожи на равномерный случай ({_ч(случай)}): R {_ч(R)}, шаг к следующему — '
                 f'{_ч(шаг_сосед, 1)} расстояния до соседа (прыжки)')
    return {'мазков': n, 'сетка': round(сетка, 3), 'случай': round(случай, 3), 'итог': round(итог, 3), 'слово': слово,
            'сосед ср': round(ср_d, 2), 'сосед σ/ср': round(cv, 3), 'R': round(R, 3), 'порядок': round(порядок, 3),
            'шаг/сосед': round(шаг_сосед, 3), 'шаг повторён': round(шаг_повторён, 3),
            **{f'ровность {к}': round(v, 3) for к, v in ровн.items()}}


