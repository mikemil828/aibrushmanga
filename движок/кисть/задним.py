def _пересекает(r, рамки):
    return any(q[0] < r[2] and q[2] > r[0] and q[1] < r[3] and q[3] > r[1] for q in рамки)


def _разбор(строки, начало, пресет, масштаб):
    """Строки после основы: номер -> (вид, ключ кисти, вытирает, запись)."""
    ответ, живые = {}, set()
    for номер, строка in enumerate(строки, 1):
        с = строка.strip()
        if not с or с.startswith('#'):
            continue
        з = json.loads(с)
        дело = _дело_кисти(з)
        if дело is not None:
            живые.add(з[дело])
        if номер < начало:
            continue
        if any(к in з for к in п_.СВОБОДНЫЕ):
            ответ[номер] = ('пометка' if 'mark' in з else 'заметка', None, False, з)
        elif 'canvas' in з or 'physics' in з:
            ответ[номер] = ('холст', None, False, з)
        elif any(к in з for к in ('tape', 'untape', 'layer_drop', 'layer_order')) or ('tool' in з and any(к in з for к in МАЗОК)):
            ответ[номер] = ('граница', None, False, з)
        elif 'palette' in з:
            ответ[номер] = ('замес', None, False, з)
        elif дело is not None:
            ответ[номер] = ('загрузка', ('имя', з[дело]), дело != 'load_brush', з)
        elif isinstance(з.get('brush'), str) and not any(к in з for к in МАЗОК):
            # строка кисти: подобранное с холста сбрасывают только "wipe" и "dirt" (вид и набор — нет)
            ответ[номер] = ('кисть', ('имя', з['brush']), bool(з.get('wipe')) or 'dirt' in з, з)
        elif not any(к in з for к in МАЗОК):
            ответ[номер] = ('сушка', None, False, з)
        else:
            if isinstance(з.get('brush'), str):
                ключ = ('имя', з['brush'])
            else:
                р = round(float(з.get('size', 12.0)) * масштаб, 2)
                ключ = ('кэш', з.get('preset', пресет), р, None if з.get('brush_tone') is None else float(з['brush_tone']))
            ответ[номер] = ('мазок', ключ, bool(з.get('wipe')), з)
    for номер, (вид, ключ, вытирает, з) in list(ответ.items()):      # живая краска: вытирание грязи запаса не трогает
        if вид in ('мазок', 'кисть') and ключ[0] == 'имя' and ключ[1] in живые:
            ответ[номер] = (вид, ключ, False, з)
    return ответ


def _затронуто(разбор, правлены, рамки_было, предсказ, полная, масштаб=1.0):
    """Вперёд по журналу: затронутые мазки (номера), область затронутого (рамки), кисти, грязные к концу."""
    D, грязные, замесы, A = [], set(), set(), set()
    for номер in sorted(разбор):
        вид, ключ, вытирает, з = разбор[номер]
        правлена = номер in правлены
        if вид == 'замес':
            if правлена:
                замесы.add(з['palette'])
            else:
                замесы.discard(з['palette'])
        elif вид == 'сушка' and правлена:
            о = з.get('area')
            D.append(полная if о is None else tuple(int(math.floor(float(v) * масштаб)) + (1 if i > 1 else 0) for i, v in enumerate(о)))
        elif вид in ('кисть', 'загрузка'):
            if правлена or (вид == 'загрузка' and ключ in грязные):
                грязные.add(ключ)
            elif вид == 'кисть' and вытирает:
                грязные.discard(ключ)
        elif вид == 'мазок':
            рр = [r for r in рамки_было.get(номер, []) + предсказ.get(номер, []) if r is not None]
            if 'dry' in з or 'set' in з:
                if правлена:
                    D.append(полная)
            по_кисти = not вытирает and ключ in грязные
            по_замесу = isinstance(з.get('swatch'), str) and з['swatch'] in замесы or (
                isinstance(з.get('swatch'), list) and any(и in замесы for и in з['swatch'] if и))
            if правлена or по_кисти or по_замесу or _пересекает_любой(рр, D):
                A.add(номер)
                D.extend(рр)
                грязные.add(ключ)
            else:
                грязные.discard(ключ)
    return A, D, грязные


def _пересекает_любой(рр, D):
    return any(_пересекает(r, D) for r in рр)


def _зависимые(разбор, A, рамки):
    """Назад по журналу: что ещё класть, чтобы затронутые легли как в полном повторе (рамки и кисти раньше них)."""
    R, N, нужны = set(), [], set()
    for номер in sorted(разбор, reverse=True):
        вид, ключ, вытирает, з = разбор[номер]
        if вид == 'кисть':
            if вытирает:
                нужны.discard(ключ)
            continue
        if вид == 'удалён':                  # удалённый мазок: под его прежней рамкой — то, что лежало до него
            if номер in A:
                N.extend(r for r in рамки.get(номер, []) if r is not None)
            continue
        if вид != 'мазок':
            continue
        рр = [r for r in рамки.get(номер, []) if r is not None]
        if номер in A or ключ in нужны or _пересекает_любой(рр, N):
            R.add(номер)
            N.extend(рр)
            if вытирает:
                нужны.discard(ключ)
            else:
                нужны.add(ключ)
    return R


