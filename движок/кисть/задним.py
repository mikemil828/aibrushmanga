def _параметры(ширина, высота, грунт, масштаб, пресет, сид):
    return {'physics': ФИЗИКА, 'ширина': ширина, 'высота': высота, 'грунт': [float(v) for v in грунт],
            'масштаб': float(масштаб), 'пресет': пресет, 'сид': int(сид), 'отбор': None}


def _конец_строки(строки):
    return max((i for i, с in enumerate(строки, 1) if с.strip() and not с.strip().startswith('#')), default=0)


class _Честно(Exception):
    pass


def пересобрать(старые, новые, папка, правлены, ширина=4800, высота=3000, грунт=(150, 141, 126), масштаб=1.0,
                пресет=None, сид=0, ядра=None, печать=None, конец_сост=None, рамки=None, кадр_до=False):
    """Пересобрать правленый журнал (`новые` — строки) после `старые`: затронутое — поверх холста конца прежнего,
    точка конца и рамки — в `папка`. Живой холст (`папка` None): конец прежнего — `конец_сост` (состояние повтора:
    'холст', 'кисти', …), рамки его мазков — `рамки`, основа — чистый холст, точек нет. кадр_до — в числах '_до':
    (рамка, картинка) холста до правки по рамке затронутого с полем 16 px. Ответ — (состояние конца, словарь чисел,
    рамка затронутого или None); рамки мазков правленого журнала — в состоянии, 'рамки_мазков'."""
    t0 = time.perf_counter()
    скажи = печать or (lambda s: None)
    хс, хн = _хеши_строк(старые), _хеши_строк(новые)
    параметры = _параметры(ширина, высота, грунт, масштаб, пресет, сид)
    правлены = sorted(set(правлены))
    f = правлены[0] if правлены else len(новые) + 1
    мазков_всего = sum(1 for с in новые if any(f'"{к}"' in с for к in МАЗОК) and '"note"' not in с)
    числа = {'правлено': len(правлены), 'всего': мазков_всего}

    def честно(почему):
        if папка is None:                # живой холст: повтор правленого журнала целиком, рамки — по пути
            состояние_ = {'рамки': {}}
            п_.повторить(новые, ширина, высота, грунт, масштаб, пресет, сид, состояние=состояние_, ядра=ядра)
            состояние_['рамки_мазков'] = состояние_.pop('рамки')
            начало = 1
        else:
            х, n, состояние_, начало = собрать(новые, папка, ширина, высота, грунт, масштаб, пресет, сид, продолжить=True, ядра=ядра)
        числа.update(пересчитано=sum(1 for i, с in enumerate(новые, 1) if i >= начало and any(f'"{к}"' in с for к in МАЗОК)
                                     and '"note"' not in с),
                     как=f'честный повтор: {почему}', основа=начало - 1, площадь=1.0)
        return состояние_, None

    точки = [] if папка is None else [т for т in точки_папки(папка) if т[2].get('параметры') == параметры]
    конец_с = _конец_строки(старые)
    конец = [т for т in точки if т[0] == конец_с and т[2].get('хеш') == хс[конец_с]]
    if конец_сост is not None:
        конец = [(конец_с, None, None)]
    основы = [т for т in точки if т[0] < f and т[0] < len(хн) and т[2].get('хеш') == хн[т[0]]]
    основа = max(основы, key=lambda т: т[0]) if основы else None
    s0 = основа[0] if основа else 0
    try:
        if not конец:
            raise _Честно('нет точки конца прежнего журнала (собрать его повтором с точками)')
        разбор = _разбор(новые, s0 + 1, пресет, масштаб)
        было = _разбор(старые, s0 + 1, пресет, масштаб)
        for номер, д in list(разбор.items()) + list(было.items()):
            if д[0] == 'граница' or (д[0] in ('пометка', 'холст') and номер in правлены):
                raise _Честно(f'строка {номер}: {"скотч, слои, нож или снятие" if д[0] == "граница" else "правка пометки или холста"}'
                              ' — зависимость не по рамкам')
        рамки_было = dict(рамки) if папка is None else _прочесть_рамки(папка, хс)
        нет = [н for н, д in было.items() if д[0] == 'мазок' and н not in рамки_было]
        if нет:
            raise _Честно(f'рамок прежнего повтора нет у {len(нет)} мазков (строка {нет[0]}) — '
                          + ('холст взят из .npz или мазки легли мимо этого холста' if папка is None else 'повтор с точками их пишет'))
        шапка = next((json.loads(с) for с in новые if '"canvas"' in с and not с.strip().startswith('#')), {})
        ш, в = шапка.get('canvas', (ширина, высота))
        полная = (0, 0, int(ш * масштаб), int(в * масштаб))
        for н in правлены:                                   # удалённый мазок — его прежняя рамка и кисть
            if н in было and было[н][0] == 'мазок' and разбор.get(н, ('',))[0] != 'мазок':
                разбор[н] = ('удалён',) + было[н][1:]
        предсказ = {}
        for н in правлены:
            if н in разбор and разбор[н][0] == 'мазок':
                рр = [r for r in рамки_было.get(н, []) if r is not None]
                зн, зс = разбор[н][3], было.get(н, (None,) * 4)[3] or {}
                сд = _сдвиг_строки(зс, зн, масштаб)
                if сд is not None and рр:
                    рр = рр + [(r[0] + сд[0], r[1] + сд[1], r[2] + сд[0], r[3] + сд[1]) for r in рр]
                предсказ[н] = рр
        for попытка in range(4):
            разбор_A = {н: (('мазок',) + д[1:] if д[0] == 'удалён' else д) for н, д in разбор.items()}
            A, D, грязные = _затронуто(разбор_A, set(правлены), рамки_было, предсказ, полная, масштаб)
            рамки_R = {н: [r for r in рамки_было.get(н, []) + предсказ.get(н, []) if r is not None] for н in разбор}
            R = _зависимые(разбор, A, рамки_R)
            мимо = {н for н, д in разбор.items() if д[0] == 'мазок' and н not in R}
            if попытка == 0 and len(R) >= ПОЧТИ_ВСЁ * max(len(R) + len(мимо), 1):
                raise _Честно(f'затронуто почти всё ({len(R)} мазков из {len(R) + len(мимо)} после основы) — честный повтор '
                              'дешевле прохода со склейкой')
            ответ = _проход(новые, основа, s0, мимо, параметры, ядра, рамки_было)
            if ответ is None:
                raise _Честно('мягкой кисти не видно сырого слоя вне непосчитанного')
            сост, рамки_н = ответ
            новое = False
            for н in R:
                факт = [r for r in рамки_н.get(н, []) if r is not None]
                if н in A:
                    if not all(any(q[0] <= r[0] and q[1] <= r[1] and r[2] <= q[2] and r[3] <= q[3] for q in рамки_R[н]) for r in факт):
                        предсказ[н] = предсказ.get(н, []) + факт
                        новое = True
                elif факт != [r for r in рамки_было.get(н, []) if r is not None]:
                    raise _Честно(f'строка {н}: рамка незатронутого мазка разошлась с прежней')
            if not новое:
                break
            скажи(f'правка: рамки затронутого шире прежних — попытка {попытка + 2}')
        else:
            raise _Честно('рамки затронутого не сошлись за 4 попытки')
        итог = конец_сост if конец_сост is not None else загрузить_состояние(конец[0][1])
        if кадр_до:
            рр = [r for r in D if r[2] > r[0] and r[3] > r[1]]
            if рр:
                числа['_до'] = _кадр(итог['холст'], (min(r[0] for r in рр), min(r[1] for r in рр),
                                                     max(r[2] for r in рр), max(r[3] for r in рр)))
        рамка = _сложить(итог, сост, D, грязные)
    except _Честно as e:
        скажи(f'правка: {e} — честный повтор')
        if кадр_до and конец and конец[0][1] is not None:     # «до» — весь лист с точки конца прежнего, пока она есть
            х0 = загрузить_состояние(конец[0][1])['холст']
            числа['_до'] = _кадр(х0, (0, 0, х0.ширина, х0.высота), 0)
        сост, _ = честно(str(e))
        числа['время'] = time.perf_counter() - t0
        числа['доля'] = числа['пересчитано'] / max(мазков_всего, 1)
        return сост, числа, None
    рамки = dict(рамки_было)
    for н in list(рамки):
        if н > s0 and (н not in разбор or разбор[н][0] != 'мазок'):
            del рамки[н]
    for н in правлены:
        рамки.pop(н, None)
    рамки.update({н: v for н, v in рамки_н.items() if н is not None})
    for н in A - set(рамки_н):
        рамки.pop(н, None)
    итог['строка'] = сост['строка']
    итог['рамки_мазков'] = рамки
    if папка is not None:
        for стр, путь, д in точки_папки(папка):         # точки после правки — не этого журнала
            if стр >= f:
                _убрать([путь[:-4] + '.json', путь])
        _записать_точку(папка, итог['строка'], {к: v for к, v in итог.items() if к != 'рамки_мазков'}, хн[итог['строка']],
                        параметры, 'конец журнала (правка)')
        _записать_рамки(папка, хн, рамки)
    площадь = _площадь(D, полная)
    числа.update(пересчитано=len(R), как='затронутое', основа=s0, площадь=площадь, время=time.perf_counter() - t0,
                 доля=len(R) / max(мазков_всего, 1))
    return итог, числа, рамка


def _сдвиг_строки(зс, зн, масштаб):
    for к in МАЗОК:
        if к in зс and к in зн and len(зс[к]) == len(зн[к]) and зс[к]:
            dx, dy = (зн[к][0][0] - зс[к][0][0]) * масштаб, (зн[к][0][1] - зс[к][0][1]) * масштаб
            return (int(math.floor(dx)), int(math.floor(dy))) if (dx or dy) else None
    return None


def _проход(строки, основа, s0, мимо, параметры, ядра, рамки_было):
    """Повтор правленого журнала с основы: мазки `мимо` — учтены, не положены. Ответ (состояние, рамки) или None —
    мягкой кисти ответ «есть ли в слое сырое» не виден вне рамок непосчитанного."""
    состояние = загрузить_состояние(основа[1]) if основа else {}
    рамки, пропущено, сомнение = {}, [], []
    разбор = {}

    def перед(номер, х, кисть, слой):
        if getattr(кисть, 'кайма', 0.0) > 0.0 and кисть.форма != 'мастихин' and not сомнение:
            х._граница()
            с = х._слои.get(слой)
            w = None if с is None else с._влажность
            if w is None:
                сомнение.append(номер)
                return
            сыро = np.array(w[0:х.высота, 0:х.ширина]) > 0
            for k in пропущено:
                for r in рамки_было.get(k, []):
                    if r is not None:
                        сыро[r[1]:r[3], r[0]:r[2]] = False
            if not сыро.any():
                сомнение.append(номер)

    пропущено.extend(sorted(мимо))       # консервативно: рамки всех непосчитанных мазков после основы
    состояние.update(рамки=рамки, мимо=мимо, перед=перед)
    п_.повторить(строки, параметры['ширина'], параметры['высота'], параметры['грунт'], параметры['масштаб'],
                 параметры['пресет'], параметры['сид'], состояние=состояние, начало=s0 + 1, ядра=ядра)
    for к in ('рамки', 'мимо', 'перед'):
        состояние.pop(к, None)
    if сомнение:
        return None
    return состояние, рамки


def _сложить(итог, сост, D, грязные):
    """Холст конца прежнего журнала, в рамках затронутого — пересобранный; кисти, грязные от затронутого, — пересобранные;
    палитра, счётчики и сиды — пересборки (она шла по всем строкам)."""
    from .холст import Слой
    хи, хп = итог['холст'], сост['холст']
    хп._граница()
    if list(хи._слои) != list(хп._слои):
        raise _Честно(f'слои разошлись: {list(хи._слои)} и {list(хп._слои)}')
    рр = [r for r in D if r[2] > r[0] and r[3] > r[1]]
    маска = None
    for имя, сп in хп._слои.items():
        си = хи._слои[имя]
        for поле in Слой._ВСЕ:
            a, b = getattr(си, поле), getattr(сп, поле)
            if b is None and a is None:
                continue
            if b is None or a is None:
                # массив по надобности (`пропуск`, `текучая`) заводит мазок, которому он нужен. Нет у пересборки, есть у
                # прежнего: его завели мазки вне пересчитанного (тогда вне затронутого он не пуст — берётся прежний, в
                # затронутом пуст) или только прежние затронутые (вне затронутого пуст — у полного повтора его нет).
                # Есть у пересборки, нет у прежнего: завели только затронутые — заводится пустым, в затронутом — новый.
                пусто = Слой._ПУСТО.get(поле)
                if пусто is None:
                    raise _Честно(f'слой «{имя}»: массив «{поле}» есть только в одном холсте')
                форма = (a if b is None else b).shape[:2]
                if маска is None or маска.shape != форма:
                    маска = np.zeros(форма, bool)
                    for r in рр:
                        маска[max(r[1], 0):r[3], max(r[0], 0):r[2]] = True
                if b is None:
                    вне = np.asarray(a)[~маска]
                    if not (вне != пусто).any():
                        setattr(си, поле, None)              # завели только прежние затронутые: у полного повтора его нет
                        continue
                    for r in рр:
                        a[r[1]:r[3], r[0]:r[2]] = пусто
                    continue
                a = хи._пропуск(си) if поле == 'пропуск' else хи._текучая(си)
            for r in рр:
                a[r[1]:r[3], r[0]:r[2]] = b[r[1]:r[3], r[0]:r[2]]
    for поле in ('_повторы', '_счётчик', '_этап', '_объект', '_замесы'):
        if поле in хп.__dict__:
            setattr(хи, поле, copy.deepcopy(хп.__dict__[поле]))
    for ключ, к in сост['кэш'].items():
        мой = ('кэш', ключ[0], ключ[1], ключ[2] if len(ключ) > 2 else None)
        if мой in грязные or ключ not in итог['кэш']:
            итог['кэш'][ключ] = к
    for имя, к in сост.get('кисти', {}).items():
        if ('имя', имя) in грязные or имя not in итог.get('кисти', {}):
            итог.setdefault('кисти', {})[имя] = к
    if not рр:
        return None
    return (min(r[0] for r in рр), min(r[1] for r in рр), max(r[2] for r in рр), max(r[3] for r in рр))


def _площадь(D, полная):
    if not D:
        return 0.0
    ш, в = полная[2], полная[3]
    m = np.zeros((в, ш), bool)
    for r in D:
        m[max(int(r[1]), 0):int(r[3]), max(int(r[0]), 0):int(r[2])] = True
    return float(m.mean())


def _кадр(х, рамка, поле=16):
    """Холст в рамке (с полем, по холсту) со светом, sRGB uint8: (рамка с полем, картинка)."""
    from .глаз import _вид
    x0, y0, x1, y1 = рамка
    r = (max(x0 - поле, 0), max(y0 - поле, 0), min(x1 + поле, х.ширина), min(y1 + поле, х.высота))
    return r, np.round(_вид(х, r, True)).astype(np.uint8)


def до_после(до, стало, путь):
    """PNG «до | после» 1:1: до — (рамка, картинка) от `_кадр`, стало — холст после правки."""
    from .варианты import _png
    r, a = до
    b = _кадр(стало, r, 0)[1]
    шов = np.full((a.shape[0], 4, 3), 255, np.uint8)
    _png(путь, np.concatenate([a, шов, b], 1))
    return путь


def править(журнал, out=None, папка=None, ширина=4800, высота=3000, грунт=(150, 141, 126), масштаб=1.0, пресет=None,
            сид=0, ядра=None, печать=None, путь_png=None, **правка):
    """Правка журнала-файла по фильтру и пересборка затронутого (шапка модуля). папка — точки повтора (без неё —
    `<out>.точки/`); out — PNG листа после правки. `**правка` — доводы `править_строки`. Ответ — `Правка`."""
    if папка is None:
        if out is None:
            raise ValueError('правка: нужна папка точек или out (точки — в <out>.точки/)')
        папка = os.path.splitext(out)[0] + '.точки'
    with open(журнал, encoding='utf-8') as f:
        старые = f.readlines()
    новые, правлены, что = править_строки(старые, **правка)
    if not правлены:
        raise ValueError(f'правка: под фильтр {что} не попал ни один мазок — журнал не тронут')
    if новые and not новые[-1].endswith('\n'):
        новые[-1] += '\n'
    новые.append(json.dumps({'note': 'правка задним числом', 'edit': что, 'lines': len(правлены)}, ensure_ascii=False) + '\n')
    запас = _запас(журнал)
    os.replace(журнал, запас)
    with open(журнал, 'w', encoding='utf-8') as f:
        f.writelines(новые)
    сост, числа, рамка = пересобрать(старые, новые, папка, правлены, ширина, высота, грунт, масштаб, пресет, сид, ядра, печать,
                                     кадр_до=bool(путь_png))
    сост.pop('рамки_мазков', None)
    до = числа.pop('_до', None)
    ответ = Правка(числа, запас=запас, журнал=журнал, правлены=правлены)
    ответ['рамка'] = рамка
    if out:
        сост['холст'].png(out)
    if до is not None:
        ответ['путь'] = до_после(до, сост['холст'], путь_png)
    ответ['состояние'] = сост
    return ответ


def _перенести(х, хп):
    """Честный повтор живого холста: поля слоёв, слои и счёт повтора `хп` — в холст `х` (на месте: его процессы и
    общая память те же)."""
    from .холст import Слой, _в_общую
    х._граница(пишу=True)
    хп._граница()
    общая = х.__dict__.get('_ядер', 1) != 1
    слои = {}
    for имя, сп in хп._слои.items():
        си = х._слои.get(имя)
        if си is None:
            си = сп
            if общая:
                for поле in Слой._ВСЕ:
                    setattr(си, поле, _в_общую(getattr(си, поле)))
        else:
            for поле in Слой._ВСЕ:
                a, b = getattr(си, поле), getattr(сп, поле)
                if b is None:
                    setattr(си, поле, None)
                elif a is None or a.shape != b.shape:
                    setattr(си, поле, _в_общую(b) if общая else b)
                else:
                    a[...] = np.asarray(b)
        слои[имя] = си
    х._слои = слои
    for поле in ('_повторы', '_счётчик', '_этап', '_объект', '_замесы', '_ленты'):
        if поле in хп.__dict__:
            setattr(х, поле, copy.deepcopy(хп.__dict__[поле]))
        else:
            х.__dict__.pop(поле, None)


def править_холст(х, ядра=None, путь_png=None, печать=None, **правка):
    """`Холст.править`: правка журнала живого холста (`журнал=`) по фильтру и пересборка затронутого на нём самом.
    Рамки мазков холст помнит сам по номеру строки журнала; основа — чистый холст (точек нет), мазки вне затронутого
    только учитываются. Кисти пользователя — те же объекты: что на них после правки, — как в полном повторе."""
    ж = getattr(х, 'журнал', None)
    if ж is None:
        raise ValueError('править: у холста нет журнала — правка идёт по нему (Холст(…, журнал=путь)); '
                         'журнал-файл — python -m кисть.задним')
    if х.__dict__.get('_только_в') is not None:
        raise ValueError('править: в куске `варианты` нельзя — править до варианты или после взять')
    х._граница(пишу=True)
    ж._ф.flush()
    with open(ж.путь, encoding='utf-8') as f:
        старые = f.readlines()
    новые, правлены, что = править_строки(старые, **правка)
    if not правлены:
        raise ValueError(f'править: под фильтр {что} не попал ни один мазок — журнал не тронут')
    if новые and not новые[-1].endswith('\n'):
        новые[-1] += '\n'
    новые.append(json.dumps({'note': 'правка задним числом', 'edit': что, 'lines': len(правлены)}, ensure_ascii=False) + '\n')
    кисти = {з[1]: з[0] for з in ж.кисти.values()}
    конец = {'холст': х, 'кэш': {}, 'кисти': dict(кисти), 'масштаб': 1.0, 'сид': 0, 'пресет': None,
             'строка': _конец_строки(старые)}
    рамки = {н: v for н, v in х.__dict__.get('_рамки', {}).items() if isinstance(н, int)}
    до = None
    сост, числа, рамка = пересобрать(старые, новые, None, правлены, х.полная_ширина, х.полная_высота, х.грунт_srgb, 1.0,
                                     None, 0, ядра, печать, конец_сост=конец, рамки=рамки, кадр_до=bool(путь_png))
    if сост is not конец:                             # честный повтор: его холст — в этот
        if путь_png:
            до = _кадр(х, (0, 0, х.ширина, х.высота), 0)
        _перенести(х, сост['холст'])
    for имя, к in сост.get('кисти', {}).items():      # кисти пользователя — те же объекты, с тем, что на них теперь
        моя = кисти.get(имя)
        if моя is not None and к is not моя:
            к._остаток, к._набрано                       # чтение досчитывает мазки кисти на ядрах
            for поле in {п for п in (*к.__dict__, *моя.__dict__) if п.startswith('_')}:      # грязь, краска, набор — как лежат
                if поле in к.__dict__:
                    моя.__dict__[поле] = к.__dict__[поле]
                else:
                    моя.__dict__.pop(поле, None)
    х._рамки = {н: v for н, v in сост.get('рамки_мазков', {}).items() if н is not None}
    х.__dict__.pop('_метка', None)
    х._снимки = []                                    # снимки до правки — не этого журнала
    х.__dict__['_правок'] = х.__dict__.get('_правок', 0) + 1
    запас = _запас(ж.путь)
    ж._ф.close()
    os.replace(ж.путь, запас)
    with open(ж.путь, 'w', encoding='utf-8') as f:
        f.writelines(новые)
    ж._ф = open(ж.путь, 'r+b')
    ж._ф.seek(0, os.SEEK_END)
    ж.строк = len(новые)
    if числа.get('_до') is not None:
        до = числа.pop('_до')
    числа.pop('_до', None)
    ответ = Правка(числа, запас=запас, журнал=ж.путь, правлены=правлены)
    ответ['рамка'] = рамка
    if путь_png and до is not None:
        ответ['путь'] = до_после(до, х, путь_png)
    return ответ


