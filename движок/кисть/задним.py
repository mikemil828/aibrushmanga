def _сдвиг_тона(rgb, dL=0.0, dC=0.0, dh=0.0, теплее=0.0):
    from .глаз import oklab, из_oklab
    L, a, b = oklab(np.asarray(rgb[:3], np.float64))
    C, h = math.hypot(a, b), math.atan2(b, a) + math.radians(dh)
    C = max(C + dC, 0.0)
    lab = np.array([min(max(L + dL, 0.0), 1.0), C * math.cos(h), C * math.sin(h) + теплее])
    return [round(float(v), 2) for v in из_oklab(lab)]


def _в_области(з, область, масштаб=1.0):
    т = np.asarray(з.get('core', з.get('points', з.get('ctrl'))), np.float64)
    if т.ndim != 2 or т.shape[1] < 2:
        return False
    x0, y0, x1, y1 = область
    return bool(((т[:, 0] >= x0) & (т[:, 0] <= x1) & (т[:, 1] >= y0) & (т[:, 1] <= y1)).any())


def _строки_диапазон(v):
    if v is None:
        return None
    if isinstance(v, str):
        a, _, b = v.partition('-')
        return int(a), int(b or a)
    if isinstance(v, int):
        return v, v
    return int(v[0]), int(v[1])


def править_строки(строки, строки_с=None, слой=None, этап=None, объект=None, замес=None, область=None, удалить=False,
                   цвет=None, новый_замес=None, dL=0.0, dC=0.0, dh=0.0, теплее=0.0, сдвиг=None, нагрузка=None,
                   нажим=None, нажим_в=None, ширина=None):
    """Правка строк журнала (список строк) у мазков по фильтру. Ответ — (новые строки, номера правленых, описание).
    Мазок — строка с "ctrl", "points" или "core"; фильтр — диапазон строк ("4-200" или (4, 200)), слой, этап и объект
    (без своих полей — от пометки выше), замес ("swatch"), область (точка пути внутри). Тон (dL, dC — OKLab, dh — °,
    теплее — b OKLab) у мазка с замесом — от цвета замеса на его месте журнала, замес снимается."""
    диапазон = _строки_диапазон(строки_с)
    if not any([удалить, цвет is not None, новый_замес, dL, dC, dh, теплее, сдвиг, нагрузка is not None, нажим is not None,
                нажим_в is not None, ширина is not None]):
        raise ValueError('правка: не сказано, что править (удалить, цвет, замес, dL/dC/dh/теплее, сдвиг, нагрузка, нажим, ширина)')
    новые, правлено, тек, замесы = list(строки), [], {'stage': None, 'object': None}, {}
    for номер, строка in enumerate(строки, 1):
        с = строка.strip()
        if not с or с.startswith('#'):
            continue
        з = json.loads(с)
        if 'mark' in з:
            тек = {к: з.get(к, тек[к]) for к in тек}
        if 'palette' in з:
            замесы[з['palette']] = п_._цвет(з)
        if not any(к in з for к in МАЗОК):
            continue
        if диапазон and not диапазон[0] <= номер <= диапазон[1]:
            continue
        if слой is not None and str(з.get('layer', 'основа')) != str(слой):
            continue
        if этап is not None and str(з.get('stage', тек['stage'])) != str(этап):
            continue
        if объект is not None and str(з.get('object', тек['object'])) != str(объект):
            continue
        if замес is not None and з.get('swatch') != замес:
            continue
        if область is not None and not _в_области(з, область):
            continue
        было = dict(з)
        if удалить:
            з = {'note': 'правка задним числом: мазок удалён', 'deleted': было}
        else:
            if цвет is not None:
                з.pop('colors', None)
                з.pop('swatch', None)
                з['color'] = [float(v) for v in цвет]
            if новый_замес is not None:
                з['swatch'] = str(новый_замес)
            if dL or dC or dh or теплее:
                if isinstance(з.get('swatch'), str):
                    if з['swatch'] not in замесы:
                        raise ValueError(f'правка, строка {номер}: замес {з["swatch"]} выше не заведён')
                    з['color'] = [float(v) for v in np.asarray(замесы[з['swatch']], float)[:3]]
                    del з['swatch']
                if 'swatch' in з:
                    raise ValueError(f'правка, строка {номер}: тон у набора с замесами — править замесы')
                if 'colors' in з:
                    з['colors'] = [[_сдвиг_тона(c[0], dL, dC, dh, теплее), c[1]] if isinstance(c[0], (list, tuple))
                                   else _сдвиг_тона(c[:3], dL, dC, dh, теплее) + list(c[3:]) for c in з['colors']]
                elif 'color' in з:
                    з['color'] = _сдвиг_тона(з['color'], dL, dC, dh, теплее)
                else:
                    raise ValueError(f'правка, строка {номер}: у мазка нет цвета (краска кисти) — тон не сдвинуть')
            if сдвиг is not None:
                for к in МАЗОК:
                    if к in з:
                        з[к] = [[round(p[0] + сдвиг[0], 4), round(p[1] + сдвиг[1], 4)] + list(p[2:]) for p in з[к]]
            if нагрузка is not None:
                з['load'] = нагрузка
            if нажим is not None:
                if 'ctrl' not in з:
                    raise ValueError(f'правка, строка {номер}: нажим числом — у мазка с "ctrl"; у точек — нажим_в (множитель)')
                з['pressure'] = float(нажим)
            if нажим_в is not None:
                if 'ctrl' in з:
                    з['pressure'] = round(min(float(з.get('pressure', 0.85)) * нажим_в, 1.0), 6)
                for к in ('points', 'core'):
                    if к in з:
                        з[к] = [list(p[:2]) + [round(min(max(p[2] * нажим_в, 0.0), 1.0), 6)] + list(p[3:]) for p in з[к]]
            if ширина is not None:
                if isinstance(з.get('brush'), str):
                    raise ValueError(f'правка, строка {номер}: ширина именной кисти — в её строке "def"')
                з['size'] = float(ширина)
        if з != было:
            if нагрузка is not None or нажим is not None or нажим_в is not None or ширина is not None:
                з.pop('lines', None)                         # К-14б: линии пучков хода сняты до правки — с новым нажимом они другие; зеркало возьмёт ход целиком
            новые[номер - 1] = json.dumps(з, ensure_ascii=False, separators=(',', ':')) + ('\n' if строка.endswith('\n') else '')
            правлено.append(номер)
    что = {к: v for к, v in dict(строки=строки_с, слой=слой, этап=этап, объект=объект, замес=замес, область=область,
                                 удалить=удалить or None, цвет=цвет, новый_замес=новый_замес, dL=dL or None, dC=dC or None,
                                 dh=dh or None, теплее=теплее or None, сдвиг=сдвиг, нагрузка=нагрузка, нажим=нажим,
                                 нажим_в=нажим_в, ширина=ширина).items() if v is not None}
    return новые, правлено, что


def _запас(путь):
    for i in range(1, 1000):
        з = f'{путь}.до_правки' + ('' if i == 1 else f'.{i}')
        if not os.path.exists(з):
            return з
    raise RuntimeError(f'{путь}: прежних журналов больше 999')


