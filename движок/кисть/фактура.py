"""В-5: рельеф числом — `борозды_для`: σ и размах борозд одного хода (`х.борозды`, со светом и без) до кладки, и
нагрузка (или `ровно`, разбавитель) под заказ σ.

Таблица `фактура.json` рядом с модулем (смена Движка 187). Узел — прямой ход 45 мм (`путь_с_нажимом`, вход и сход
в полширины) на чистом холсте 600×400 при 8 px/мм, грунт (166, 146, 129); мерка — `х.борозды` тела следа: средняя
половина длины хода, средняя половина ширины следа (`о.ширина`). Оси: пресет × ширина (мм) × нагрузка × нажим ×
вид × (разбавитель, `ровно`) × светлота краски L (серые 30 … 245) → средние по сидам σ и размах без света, со светом
0,4 и 0,8, σ по сиду и доля тона. Сидов на узел — по ширине (`СИДЫ_ПО_ШИРИНЕ`): σ одиночного хода по сиду у кисти
уже 2 мм гуляет на 30–60 %, у широкой — на 5–10 % (окно мерки шире, борозд в нём больше).

Разбавитель r кладёт ход с ровно max(ровно, r) (`краска.разбавить`); у полукроющей и прозрачной `ровно` без
разбавителя мазок не берёт. Поэтому узлы — пары (r, ровно от r до 1), `СОЧЕТАНИЯ`.

`разброс_тона`: узел снят с 1 (как у пресетов); с 0 — те же первые сиды при нажиме 0,8, доля «тон» = σ²(0) / σ²(1)
парой одних сидов (рябь тона прядей — своя, поверх борозд), и σ²(рт) = σ²(1) · (тон + (1 − тон) · рт²).

Цвет краски. Укладка хода от цвета не зависит (5е-2): покрытие и толщина слоя те же бит в бит, цвет слоя — краска
× тон прядей. Поэтому ход узла кладётся один раз серой краской 110, а для серых 30–225 цвет и пропуск слоя
пересчитываются в рамке окна (σ того же хода живой краской — тот же до 2 %); у 245 тон прядей упирается в белое, и ход
кладётся живой краской. Счёт идёт по светлоте OKLab краски (`светлота`): хрома σ почти не меняет — у кроющей
до 5 %, у прозрачной насыщенная на 10–15 % спокойнее серой той же светлоты (замер 40 цветов).

Между узлами — по log нагрузки, log ширины, нажиму, разбавителю, `ровно` и L прямо; сила света s —
σ² = σ₀² + (σ₀,₄² − σ₀²)·(s/0,4)^p, p — по узлу 0,8. Вне осей — `ValueError` с ближайшим. Пересчёт —
`python3 -m кисть.фактура --пересчитать [--процессов 16]` (~25 мин: ПК на 16 процессах считает ~в 4 раза быстрее
одного — упор в память); хеш — хеш физики одиночного хода (`калибровка.хеш_физики`), код света и мерки, код замера
узла этого модуля.

Только счёт: холст, кисть и журнал не трогаются, ничего не кладётся.
"""
import inspect
import json
import math
import os
import sys
import textwrap
import warnings

import numpy as np

from . import калибровка as кал

ФАЙЛ = os.path.join(кал._ПАКЕТ, 'фактура.json')

# ----------------------------------------------------------------- стенд узла
ХОЛСТ = (600, 400)
ХОД = (120, 480)                 # x хода, px (45 мм при 8 px/мм); y — середина холста
# сидов на узел по ширине кисти, мм: σ одиночного хода по сиду у узкой — 30–60 %, у широкой — 5–10 % (окно шире)
СИДЫ_ПО_ШИРИНЕ = ((9.0, 3), (4.0, 5), (2.5, 7), (1.5, 9), (0.0, 10))
СИДЫ_ТОНА = (1, 2, 3)            # те же сиды с `разброс_тона` 0 — парой к 1: доля тона в σ²
# мягкая и круглая от 1,5 до 3,5 мм переходят от острого кончика к плашмя: σ по ширине идёт волной — узлы чаще;
# у плоской с `ровно` σ от 4 до 6 мм падает вдвое
ШИРИНЫ_ММ = {'плоская': (2.0, 4.0, 5.0, 6.5, 9.0, 13.0, 18.0), 'мягкая': (1.0, 1.5, 2.0, 3.0, 3.5, 5.0, 15.0),
             'круглая': (1.0, 1.5, 2.0, 2.5, 3.5, 7.0),
             'плоская_узкая': (0.75, 1.5, 2.5)}
НАГРУЗКИ = (0.03, 0.08, 0.18, 0.35, 0.6, 0.9)
НАЖИМЫ = (0.3, 0.8)
ТОН_НАЖИМ = 0.8                  # нажим, при котором снимается доля тона
# Разбавитель r кладёт ход с ровно = max(ровно, r) (`краска.разбавить`; у не кроющей ровно без разбавителя не идёт).
# Узлы — пары (r, ровно мазка): по каждому r — свои узлы ровно от r до 1
РАЗБАВИТЕЛИ = (0.0, 0.35, 0.7, 1.0)
РОВНО_ПРИ = {0.0: (0.0, 0.5, 1.0), 0.35: (0.35, 1.0), 0.7: (0.7, 1.0), 1.0: (1.0,)}
СОЧЕТАНИЯ = tuple((р, ро) for р in РАЗБАВИТЕЛИ for ро in РОВНО_ПРИ[р])
СВЕТЛОТЫ = (30, 70, 110, 150, 190, 225, 245)        # серые краски узла; до 225 — перекраской хода серой 110
ПЕРЕКРАСКА = 225
БАЗА = 110
СИЛЫ = (0.4, 0.8)
ПОЛЯ = ('σ0', 'σ4', 'σ8', 'р0', 'р4', 'р8', 'сσ0', 'сσ4', 'тон')   # σ и размах без света, со светом 0,4 и 0,8;
# σ по сиду без света и со светом 0,4; тон — σ² хода кисти с `разброс_тона` 0 к σ² с 1 (со светом 0,4, пары сидов)


def _ровно_мазка(вид, разбавитель, ровно):
    """Ровно, с которым ляжет ход: max(ровно, разбавитель); у не кроющей без разбавителя — 0."""
    р = float(разбавитель or 0.0)
    if вид != 'кроющая' and р <= 0.0:
        return 0.0
    return max(float(ровно or 0.0), р)


def _ход(пресет, ширина_мм, нагрузка, нажим, вид, разбавитель, ровно, рт, сид, серая):
    """Один ход узла серой краской: (холст, окно тела следа)."""
    from .холст import Холст
    from .кисть import Кисть, путь_с_нажимом
    from .краска import Краска
    ш = float(ширина_мм) * кал.ПХ_НА_ММ
    х = Холст(ХОЛСТ[0], ХОЛСТ[1], грунт=кал.ГРУНТ, px_на_мм=кал.ПХ_НА_ММ, ядра=1, подсказки=False)
    к = Кисть.из_файла(os.path.join(кал._ПРЕСЕТЫ, пресет + '.json'), ширина=ш, разброс_тона=float(рт))
    yc = ХОЛСТ[1] // 2
    точки = путь_с_нажимом([(ХОД[0], yc), (ХОД[1], yc)], ш, нажим=float(нажим), вход=ш / 2, сход=ш / 2, сид=сид)
    д = {}
    if ровно:
        д['ровно'] = float(ровно)
    if разбавитель:
        д['разбавитель'] = float(разбавитель)
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        о = х.мазок(точки, Краска((серая,) * 3, вид), к, слой='узел', сид=сид, нагрузка=float(нагрузка), **д)
    w = (о.ширина if о and о.ширина else 0) or ш
    дл = ХОД[1] - ХОД[0]
    окно = (ХОД[0] + дл // 4, max(0, int(round(yc - w / 4))), ХОД[1] - дл // 4, min(ХОЛСТ[1], int(round(yc + w / 4)) + 1))
    return х, окно


def _мерка(х, окно):
    """σ и размах борозд окна: без света, со светом `СИЛЫ`."""
    б = [х.борозды(окно, свет=False)] + [х.борозды(окно, свет=True, сила=s) for s in СИЛЫ]
    return [r['σ'] for r in б] + [r['размах'] for r in б]


def _перекрасить(сл, ц, пр, k, рамка):
    """Цвет и пропуск слоя хода в рамке (y0, y1, x0, x1) — как у того же хода краской, светлее в k раз (линейный свет):
    цвет слоя — краска × тон прядей, пропуск — цвет в степени показателя плёнки (`калибровка._плёнка`). ц, пр —
    массивы хода как лёг (вне рамки краска не меряется)."""
    from .краска import _ПОЛ
    y0, y1, x0, x1 = рамка
    ц0 = ц[y0:y1, x0:x1]
    ц2 = ц0 * k
    if пр is not None:
        лц = np.log(np.clip(ц0, _ПОЛ, 1.0)).sum(axis=-1)
        e = np.where(лц < -1e-9, np.log(np.maximum(пр[y0:y1, x0:x1], 1e-300)).sum(axis=-1) / np.minimum(лц, -1e-9), 0.0)
        сл.пропуск[y0:y1, x0:x1] = np.exp(e[..., None] * np.log(np.clip(ц2, _ПОЛ, 1.0)))
    сл.цвет[y0:y1, x0:x1] = ц2


def _замеры(пресет, ширина_мм, нагрузка, нажим, вид, р, ро, рт, сид):
    """Один сид: [L][6] — мерка хода всеми серыми `СВЕТЛОТЫ`."""
    from .краска import в_линейный
    х, окно = _ход(пресет, ширина_мм, нагрузка, нажим, вид, р, ро, рт, сид, БАЗА)
    сл = х.слои['узел']
    ц = np.array(сл.цвет[:], np.float32)
    пр = None if сл.пропуск is None else np.array(сл.пропуск[:], np.float32)
    сл.цвет = ц.copy()
    if пр is not None:
        сл.пропуск = пр.copy()
    поле = 40                                       # свет и мерка берут соседей окна не дальше нескольких px
    рамка = (max(0, окно[1] - поле), min(ХОЛСТ[1], окно[3] + поле), max(0, окно[0] - поле), min(ХОЛСТ[0], окно[2] + поле))
    лин = lambda v: float(в_линейный(np.array([float(v)], np.float64))[0])
    ряд = []
    for L in СВЕТЛОТЫ:
        if L <= ПЕРЕКРАСКА:
            _перекрасить(сл, ц, пр, лин(L) / лин(БАЗА), рамка)
            ряд.append(_мерка(х, окно))
        else:
            ряд.append(_мерка(*_ход(пресет, ширина_мм, нагрузка, нажим, вид, р, ро, рт, сид, L)))
    return ряд


def замер_узла(пресет, ширина_мм, нагрузка, нажим, вид, разбавитель, ровно):
    """Узел (кисть с `разброс_тона` 1): [L][поле `ПОЛЯ`] — средние по сидам; у нажима `ТОН_НАЖИМ` — и доля тона."""
    сиды = сиды_для(ширина_мм)
    по = np.array([_замеры(пресет, ширина_мм, нагрузка, нажим, вид, разбавитель, ровно, 1.0, с) for с in сиды])
    тон = np.ones(len(СВЕТЛОТЫ))                    # (сиды, L, 6)
    if float(нажим) == ТОН_НАЖИМ:
        тс = [с for с in СИДЫ_ТОНА if с in сиды]
        без = np.array([_замеры(пресет, ширина_мм, нагрузка, нажим, вид, разбавитель, ровно, 0.0, с) for с in тс])
        с1 = (по[:len(тс), :, 1] ** 2).mean(axis=0)
        тон = np.where(с1 > 1e-6, (без[:, :, 1] ** 2).mean(axis=0) / np.maximum(с1, 1e-6), 1.0)
    ср, сσ = по.mean(axis=0), по[:, :, :2].std(axis=0)
    return [[round(float(v), 3) for v in list(ср[i]) + list(сσ[i]) + [тон[i]]] for i in range(len(СВЕТЛОТЫ))]


def сиды_для(ширина_мм):
    n = next(n for ш, n in СИДЫ_ПО_ШИРИНЕ if float(ширина_мм) >= ш)
    return tuple(range(1, n + 1))


def _узел(з):
    return замер_узла(*з)


def _задачи():
    for пресет, шш in ШИРИНЫ_ММ.items():
        for вид in кал.ВИДЫ:
            for р, ро in СОЧЕТАНИЯ:
                if вид != 'кроющая' and р == 0.0 and ро > 0.0:
                    continue                           # не кроющей ровно без разбавителя не идёт
                for ш in шш:
                    for нж in НАЖИМЫ:
                        for н in НАГРУЗКИ:
                            yield (пресет, ш, н, нж, вид, р, ро)


def хеш():
    """Хеш физики одиночного хода, света и мерки борозд, кода замера узла с осями — 16 знаков."""
    import hashlib
    h = hashlib.sha256(кал.хеш_физики().encode())
    for имя in ('свет.py', 'глаз.py'):
        with open(os.path.join(кал._ПАКЕТ, имя), encoding='utf-8') as f:
            h.update(кал._код_без_слов(f.read()).encode())
    from . import холст
    for ф in (холст.Холст.картинка, холст.Холст._цвет, холст.Холст.рельеф, _ход, _мерка, _перекрасить, _замеры,
              замер_узла, сиды_для):
        h.update(кал._код_без_слов(textwrap.dedent(inspect.getsource(ф)), без_импорта=True).encode())
    h.update(json.dumps([ХОЛСТ, ХОД, СИДЫ_ПО_ШИРИНЕ, СИДЫ_ТОНА, ШИРИНЫ_ММ, НАГРУЗКИ, НАЖИМЫ, ТОН_НАЖИМ, СОЧЕТАНИЯ,
                         СВЕТЛОТЫ, ПЕРЕКРАСКА, БАЗА, СИЛЫ], ensure_ascii=False).encode())
    return h.hexdigest()[:16]


def пересчитать(процессов=16, файл=ФАЙЛ, печать=print):
    """Снять таблицу заново (не больше 16 процессов) и записать `файл`. Отвечает секундами счёта."""
    import multiprocessing as mp
    import time
    процессов = max(1, min(16, int(процессов)))
    х = хеш()                       # до счёта: исходник модуля, правленный во время счёта, хеша не собьёт
    задачи = list(_задачи())
    задачи.sort(key=lambda з: -з[1] * len(сиды_для(з[1])))         # тяжёлые — первыми
    t = time.time()
    with mp.get_context('fork').Pool(процессов) as пул:
        числа = пул.map(_узел, задачи, chunksize=2)
    сек = time.time() - t
    по = dict(zip(задачи, числа))
    пресеты = {}
    for пресет, шш in ШИРИНЫ_ММ.items():
        # [вид][сочетание (разбавитель, ровно)][ширина][нажим][нагрузка][L][поле]; не кроющей ровно без разбавителя не
        # идёт — там узел (0, 0)
        пресеты[пресет] = {'ширины_мм': list(шш), 'узлы': [[[[[по[(пресет, ш, н, нж, вид, р, ро if (вид == 'кроющая' or р) else 0.0)]
                                                             for н in НАГРУЗКИ] for нж in НАЖИМЫ] for ш in шш]
                                                          for р, ро in СОЧЕТАНИЯ] for вид in кал.ВИДЫ]}
    т = {'хеш': х, 'узлов': len(задачи), 'секунд': round(сек, 1), 'процессов': процессов,
         'оси': {'нагрузка': НАГРУЗКИ, 'нажим': НАЖИМЫ, 'сочетания': СОЧЕТАНИЯ, 'L': СВЕТЛОТЫ, 'сила': СИЛЫ,
                 'поля': ПОЛЯ},
         'пресеты': пресеты}
    with open(файл, 'w', encoding='utf-8') as f:
        json.dump(т, f, ensure_ascii=False, separators=(',', ':'))
    печать(f'фактура: {len(задачи)} узлов за {сек:.0f} с на {процессов} процессах → {файл}')
    _ТАБЛИЦА.clear()
    return сек


# ----------------------------------------------------------------- чтение
_ТАБЛИЦА = {}


def таблица(файл=ФАЙЛ):
    if файл not in _ТАБЛИЦА:
        if not os.path.exists(файл):
            raise FileNotFoundError(f'борозды_для: нет таблицы {файл} — python3 -m кисть.фактура --пересчитать')
        with open(файл, encoding='utf-8') as f:
            т = json.load(f)
        for пр in т['пресеты'].values():
            пр['узлы'] = np.asarray(пр['узлы'], np.float64)
        if т.get('хеш') != хеш():
            warnings.warn(f'борозды_для: таблица фактуры снята с другой физики (хеш {т.get("хеш")}, ядро {хеш()}) — '
                          'python3 -m кисть.фактура --пересчитать', stacklevel=3)
        _ТАБЛИЦА[файл] = т
    return _ТАБЛИЦА[файл]


def _веса(оси, v, лог=False):
    """[(индекс, вес)] линейной интерполяции по оси (v уже в пределах)."""
    i, a = кал._индекс(оси, v, лог)
    return [(i, 1.0 - a)] + ([(i + 1, a)] if a > 0 and i + 1 < len(оси) else [])


def _в_пределах(имя, v, оси, где=''):
    if not (оси[0] - 1e-9 <= v <= оси[-1] + 1e-9):
        ближ = min(max(v, оси[0]), оси[-1])
        raise ValueError(f'борозды_для: {имя} {v:g} вне таблицы{где} — в ней {оси[0]:g}…{оси[-1]:g}; ближайшее — {ближ:g}')


def _точка(т, пресет, ш, нагрузка, нажим, iв, разб, ровно, рт, L):
    """Поля σ и размаха (`ПОЛЯ` без «тон») в точке. Разбавитель r кладёт ход с ровно max(ровно, r): у узла r — узлы
    ровно от r; по `разброс_тона` — σ² = σ²(1) · (тон + (1 − тон) · рт²), тон — у узла нажима `ТОН_НАЖИМ`."""
    пр = т['пресеты'][пресет]
    у = пр['узлы']
    iт = НАЖИМЫ.index(ТОН_НАЖИМ)
    итог = np.zeros(len(ПОЛЯ) - 1)
    for iр, wр in _веса(РАЗБАВИТЕЛИ, разб):
        rn = РАЗБАВИТЕЛИ[iр]
        оси = РОВНО_ПРИ[rn] if (iв == 0 or rn > 0) else (0.0,)
        ро = min(max(float(ровно or 0.0), rn), оси[-1]) if (iв == 0 or rn > 0) else 0.0
        for iо, wо in _веса(оси, ро):
            k = СОЧЕТАНИЯ.index((rn, оси[iо]))
            for iш, wш in _веса(пр['ширины_мм'], ш, True):
                for iг, wг in _веса(НАГРУЗКИ, нагрузка, True):
                    for iL, wL in _веса(СВЕТЛОТЫ, L):
                        тон = у[iв, k, iш, iт, iг, iL, -1]
                        м = тон + (1.0 - тон) * рт ** 2
                        for iн, wн in _веса(НАЖИМЫ, нажим):
                            w = wр * wо * wш * wг * wL * wн
                            if w:
                                итог += w * у[iв, k, iш, iн, iг, iL, :-1] * math.sqrt(max(м, 0.0))
    return итог


def _со_светом(п, сила):
    """(σ, размах) при силе света: σ² = σ₀² + (σ₀,₄² − σ₀²)·(s/0,4)^p, p — по узлу 0,8; размах — тем же законом."""
    if сила <= 0:
        return п[0], п[3]
    def закон(в0, в4, в8):
        d4, d8 = в4 ** 2 - в0 ** 2, в8 ** 2 - в0 ** 2
        if d4 <= 1e-9:
            return math.sqrt(max(в0 ** 2 + max(d8, 0.0) * (сила / СИЛЫ[1]) ** 2, 0.0))
        p = float(np.clip(math.log(max(d8, 1e-9) / d4, 2.0), 0.5, 3.0))
        return math.sqrt(max(в0 ** 2 + d4 * (сила / СИЛЫ[0]) ** p, 0.0))
    return закон(п[0], п[1], п[2]), закон(п[3], п[4], п[5])


def _ось_краски(кисть, вид, разбавитель, ровно, цвет, px_на_мм):
    from .глаз import светлота
    пресет, ш = кал._пресет_кисти(кисть, px_на_мм)
    if пресет not in ШИРИНЫ_ММ:
        raise ValueError(f'борозды_для: кисть «{пресет}» — таблица фактуры для {", ".join(ШИРИНЫ_ММ)}; борозды этой '
                         'кисти — пробником и `х.борозды`')
    _в_пределах('ширина', ш, ШИРИНЫ_ММ[пресет], f' «{пресет}» (мм)')
    iв = кал._вид(кал._вид_краски(вид, цвет))
    if цвет is None:
        raise ValueError('борозды_для: нужен цвет=… — σ борозд идёт за светлотой краски: на этом грунте тёмная (L 30) '
                         'рябит почти вдвое сильнее средней (L 90); дай краску хода: (r, g, b), `Краска` или `цвет(L, C, h)`')
    кал._цвет(цвет)                                    # проверка вида цвета
    L = float(светлота(np.asarray(tuple(цвет)[:3], np.float64)))
    рт = float(кисть.разброс_тона)
    _в_пределах('разброс_тона кисти', рт, (0.0, 1.0))
    return пресет, ш, iв, L, рт


КРОЕТ = 0.2      # заказ σ: нагрузка не ниже этой — плёнка, а не протирка; ниже — только если иначе заказ не взять


def борозды_для(кисть, σ=None, нагрузка=None, нажим=0.6, вид=None, разбавитель=None, ровно=None, сила=None,
                цвет=None, свет=True, px_на_мм=None):
    """В-5: борозды одного хода числом — то, что `х.борозды` тела следа покажет после кладки, до неё.

    С нагрузкой (без σ) — прогноз: {'σ', 'размах' — со светом силы `сила` (умолчание — рабочая 0,4), 'σ_без_света',
    'размах_без_света', 'разброс' и 'разброс_без_света' — σ по сиду (один ход гуляет вокруг среднего на столько)}.
    С заказом σ= (со светом; `свет=False` — без него) — то, что дало бы это σ: {'нагрузка', 'ровно', 'разбавитель'} и
    прогноз в этой точке. Заданные `ровно` и `разбавитель` не трогаются — подбирается нагрузка (а с данной нагрузкой —
    `ровно` у кроющей или разбавитель); не заданные: сперва нагрузка без `ровно` и разбавителя (из нескольких —
    наибольшая: кроет плотнее); нет её или она ниже 0,2 (`КРОЕТ`: протирка, сквозь неё грунт) — `ровно` (кроющая), затем
    разбавитель: наименьшие, при которых заказ берётся нагрузкой от 0,2, иначе — с наибольшей нагрузкой.

    Кисть — пресет `плоская`, `мягкая`, `круглая`, `плоская_узкая` (ширина в мм или px при `px_на_мм`); `разброс_тона`
    берётся из неё (0–1). цвет — краска хода (sRGB, `Краска` — с неё и вид, `цвет(L, C, h)`), обязателен. Стенд таблицы —
    чистый грунт (166, 146, 129), 8 px/мм, ход 45 мм; по своему грунту, по лежащей краске, рядами — ближе к пробнику.
    Вне осей и недостижимое — `ValueError` с ближайшим. Только счёт: ничего не кладёт."""
    т = таблица()
    пресет, ш, iв, L, рт = _ось_краски(кисть, вид, разбавитель, ровно, цвет, px_на_мм)
    _в_пределах('нажим', float(нажим), НАЖИМЫ)
    сила = 0.4 if сила is None else float(сила)
    _в_пределах('сила', сила, (0.0, СИЛЫ[1]))
    for имя, v, оси in (('разбавитель', разбавитель, РАЗБАВИТЕЛИ), ('ровно', ровно, (0.0, 1.0))):
        if v is not None:
            _в_пределах(имя, float(v), оси)
    кроющая = iв == 0

    def прогноз(н, р, ро):
        п = _точка(т, пресет, ш, н, float(нажим), iв, р, ро, рт, L)
        с, рз = _со_светом(п, сила)
        сб = math.sqrt(max(п[6] ** 2 + (п[7] ** 2 - п[6] ** 2) * (сила / СИЛЫ[0]) ** 2, 0.0)) if сила < СИЛЫ[0] else п[7]
        return {'σ': round(float(с), 2), 'размах': round(float(рз), 1), 'σ_без_света': round(float(п[0]), 2),
                'размах_без_света': round(float(п[3]), 1), 'разброс': round(float(сб), 2),
                'разброс_без_света': round(float(п[6]), 2)}

    if σ is None:
        if нагрузка is None:
            raise ValueError('борозды_для: дай нагрузка= (прогноз) или σ= (заказ)')
        н = _нагрузка(нагрузка)
        return прогноз(н, float(разбавитель or 0.0), float(ровно or 0.0))

    цель, поле = float(σ), ('σ' if свет else 'σ_без_света')
    мера = lambda н, р, ро: прогноз(н, р, ро)[поле]
    сетка_н = np.exp(np.linspace(math.log(НАГРУЗКИ[0]), math.log(НАГРУЗКИ[-1]), 61))
    сетка_п = np.linspace(0.0, 1.0, 41)

    def корни(f, xs):
        """x, где f(x) = цель (линейно между точками сетки), по возрастанию."""
        v = np.array([f(x) - цель for x in xs])
        к = []
        for i in range(len(xs) - 1):
            if v[i] == 0 or v[i] * v[i + 1] < 0:
                к.append(float(xs[i] + (xs[i + 1] - xs[i]) * v[i] / (v[i] - v[i + 1])) if v[i] != v[i + 1] else float(xs[i]))
        if v[-1] == 0:
            к.append(float(xs[-1]))
        return к, v + цель

    где = f'«{пресет}» {ш:g} мм, нажим {float(нажим):g}, {кал.ВИДЫ[iв]}, L краски {L:.0f}, разброс_тона {рт:g}'
    if нагрузка is not None:                     # нагрузка дана — подобрать ровно или разбавитель
        н = _нагрузка(нагрузка)
        if кроющая and ровно is None:
            имя, f = 'ровно', (lambda x: мера(н, float(разбавитель or 0.0), x))
        elif разбавитель is None:
            имя, f = 'разбавитель', (lambda x: мера(н, x, float(ровно or 0.0)))
        else:
            raise ValueError('борозды_для: с σ= и нагрузка= оставь свободным ровно= (кроющая) или разбавитель=')
        к, v = корни(f, сетка_п)
        if not к:
            raise ValueError(f'борозды_для: σ {цель:g} L недостижимо нагрузкой {н:g} ({где}): {имя} 0…1 даёт '
                             f'{v.min():.1f}…{v.max():.1f} L; другая нагрузка — без нагрузка=')
        x = к[0]
        р = x if имя == 'разбавитель' else float(разбавитель or 0.0)
        ро = x if имя == 'ровно' else float(ровно or 0.0)
        return dict(нагрузка=н, ровно=round(ро, 3), разбавитель=round(р, 3), **прогноз(н, р, ро))

    р0, ро0 = float(разбавитель or 0.0), float(ровно or 0.0)
    к, v = корни(lambda x: мера(x, р0, ро0), сетка_н)
    лучшее = (к[-1], р0, ро0) if к else None                 # (нагрузка, разбавитель, ровно): из корней — наибольшая нагрузка
    наим, наиб = float(v.min()), float(v.max())
    свободные = [п for п in (('ровно',) if кроющая and ровно is None else ()) + (('разбавитель',) if разбавитель is None else ())]
    for имя in свободные:
        if лучшее is not None and лучшее[0] >= КРОЕТ:
            break
        for x in сетка_п[1:]:
            р, ро = (x, ро0) if имя == 'разбавитель' else (р0, x)
            к, vv = корни(lambda н: мера(н, р, ро), сетка_н)
            наим, наиб = min(наим, float(vv.min())), max(наиб, float(vv.max()))
            if not к or (лучшее is not None and к[-1] <= лучшее[0]):
                continue
            # между узлами сетки — точнее: тот же поиск по самому полю при найденной нагрузке
            н = к[-1]
            кк, _ = корни((lambda y: мера(н, y, ро0)) if имя == 'разбавитель' else (lambda y: мера(н, р0, y)),
                          np.linspace(max(0.0, x - 0.025), x, 6))
            x = кк[0] if кк else x
            лучшее = (н, x, ро0) if имя == 'разбавитель' else (н, р0, x)
            if н >= КРОЕТ:
                break
    if лучшее is not None:
        н, р, ро = round(лучшее[0], 4), round(лучшее[1], 3), round(лучшее[2], 3)
        return dict(нагрузка=н, ровно=ро, разбавитель=р, **прогноз(н, р, ро))
    ближ = наим if цель < наим else наиб
    чем = ' и '.join(свободные) or 'нагрузка'
    raise ValueError(f'борозды_для: σ {цель:g} L{"" if свет else " без света"} недостижимо ({где}; подбиралось: '
                     f'нагрузка{", " + чем if свободные else ""}): в таблице {наим:.1f}…{наиб:.1f} L; ближайшее — '
                     f'{ближ:.1f} L' + ('; ровнее — шире кисть, мягче волос или светлее/ближе к грунту краска'
                                        if цель < наим else '; рябее — темнее краска, уже щетина, легче рука'))


def _нагрузка(нагрузка):
    from .инструмент import НАГРУЗКИ as ИМЕНА
