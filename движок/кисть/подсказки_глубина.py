"""Подсказка С23 «глубина» (РЕШЕНИЕ DEN 26.11 17:38 +04 «Подсказки - решение»): лист без глубины — по картинке.

Только на `х.сохранить` и только по картинке холста со светом рельефа (`СВЕТ`), без нейросети; картинка не вывод:
подсказку С4 не трогает. Объекты — места их
мазков с краской (клетки `подсказки.КЛЕТКА` px, счёт подсказок `о['места']`); клетку, где писали несколько объектов,
берёт меньший из них (предмет поверх фона, подмалёвка). Объект в счёте — от `КЛЕТОК` своих клеток. У каждого:

- **жёстких краёв** — доля жёстких среди краёв (L клетками `КРАЙ_ММ` 0,5 мм, перепад на 2 мм от `КРАЙ_L`, жёсткий — больше 60 %
  перепада на один шаг: `глаз._края`, та же мерка, что «края» у `х.манера`);
- **размах тона** — L серой шкалы, средние по его клеткам (~4 мм) внутри объекта (четыре соседа клетки — тоже его:
  у кромки клетка наполовину чужая): p90 − p10; внутри меньше `ВНУТРИ` клеток — не меряется.

Факт — от `ОБЪЕКТОВ` объектов в счёте, если резкость у всех одна (p10 доли жёстких по объектам — от `ЖЁСТКИХ`) или тон
внутри объектов плоский (медиана размаха — до `РАЗМАХ`): «похоже на аппликацию». Пороги — замером по листам прогонов
(сдача `проверка/СДАЧА_подсказки_прямота_глубина.md`)."""
import numpy as np

ОБЪЕКТОВ = 3         # объектов в счёте — не меньше
КЛЕТОК = 12          # своих клеток (32 px) у объекта — от стольких он в счёте
ВНУТРИ = 4           # клеток внутри объекта (все четыре соседа — его) — от стольких меряется размах тона
КРАЁВ = 0.05         # доля краёв в клетках объекта — меньше: доля жёстких у него не считается
КРАЙ_ММ = 0.5        # мм: клетка мерки краёв
КРАЙ_L = 8.0         # L: перепад на 2 мм, от которого место — край (как `манера.ПОРОГ_КРАЯ`)
ЖЁСТКИХ = 0.66       # p10 доли жёстких краёв по объектам — от неё «резкость одна» (портреты 0,57, 0,63; «автопортрет» 0,69–0,75, экспрессии 0,72–0,74)
РАЗМАХ = 45.0        # L: медиана размаха тона внутри объекта — до неё «тон плоский» (портреты 48, 49; «автопортрет» 40–43, этюд Нт 43)
ХОДОВ = 300          # новых мазков с прошлой мерки — меньше: мерка не повторяется
PX_НА_ММ = 4.0       # холст без px_на_мм — считать так
СВЕТ = True          # картинка — со светом рельефа, как её видят: без света края ворса гаснут («автопортрет» 22.11
                     # повтором: жёстких p10 без света 0,63, со светом 0,69; его PNG — 0,75); 2400×3000 — 2,3 с


def _своё(объекты):
    """{ключ: множество клеток} -> {ключ: массив своих клеток}: общую клетку берёт объект с меньшим числом клеток."""
    хозяин = {}
    for ко, клетки in sorted(объекты.items(), key=lambda t: (-len(t[1]), t[0])):
        for c in клетки:
            хозяин[c] = ко
    своё = {}
    for c, ко in хозяин.items():
        своё.setdefault(ко, []).append(c)
    return {ко: np.asarray(sorted(v), np.int64) for ко, v in своё.items()}


def мерка(х, объекты, клетка):
    """Мерка по объектам: {ключ: (своих клеток, доля жёстких краёв или None, размах тона L)}. объекты — {ключ: клетки
    (номера y·100000 + x клеток `клетка` px холста целиком)}."""
    from .глаз import oklab, _L, _srgb, _края
    ppm = float(х.px_на_мм or PX_НА_ММ)
    к = max(1, int(round(КРАЙ_ММ * ppm)))                     # px на клетку краёв
    лин = х._картинка(СВЕТ, None, None, 0.0, None)           # не вывод: С4 его не считает
    В, Ш = лин.shape[0] // к * к, лин.shape[1] // к * к
    лин = лин[:В, :Ш].reshape(В // к, к, Ш // к, к, 3).mean((1, 3), dtype=np.float32)
    L = _L(oklab(_srgb(лин))[..., 0]).astype(np.float32)
    _, жёст, мягк = _края(L, КРАЙ_L)
    ny, nx = L.shape
    # клетка 0,5 мм -> клетка счёта (её номер в сетке холста целиком)
    гy = (np.arange(ny) * к + х.y0) // клетка
    гx = (np.arange(nx) * к + х.x0) // клетка
    ky, kx = int(гy.max()) + 1, int(гx.max()) + 1
    номер = (гy[:, None] * kx + гx[None, :]).ravel()
    n = np.bincount(номер, minlength=ky * kx).astype(np.float64)
    сред = np.bincount(номер, L.ravel().astype(np.float64), ky * kx) / np.maximum(n, 1)
    nj = np.bincount(номер, жёст.ravel().astype(np.float64), ky * kx)
    nm = np.bincount(номер, мягк.ravel().astype(np.float64), ky * kx)
    итог = {}
    for ко, c in _своё(объекты).items():
        cy, cx = c // 100000, c % 100000
        м = (cy < ky) & (cx < kx)
        i = cy[м] * kx + cx[м]
        i = i[n[i] > 0]
        if len(i) < КЛЕТОК:
            continue
        j, s = float(nj[i].sum()), float(nm[i].sum())
        доля = j / (j + s) if (j + s) >= КРАЁВ * float(n[i].sum()) else None
        есть = set(c.tolist())                              # тон — по клеткам внутри объекта: у кромки клетка
        внутри = [v for v in c[м].tolist()                   # наполовину чужая или голый грунт
                  if {v - 1, v + 1, v - 100000, v + 100000} <= есть]
        t = сред[[(v // 100000) * kx + v % 100000 for v in внутри]] if len(внутри) >= ВНУТРИ else None
        итог[ко] = (int(len(i)), доля, None if t is None else float(np.percentile(t, 90) - np.percentile(t, 10)))
    return итог


def счёт(х, объекты, клетка, образец=None):
    """Факт С23 или None: (ключ, факт, инструменты). образец — [жёстких краёв холста, образца] из `х.манера(…, образец=)`
    или None."""
    from .подсказки import _ч, _мн
    м = мерка(х, объекты, клетка)
    if len(м) < ОБЪЕКТОВ:
        return None
    доли = np.asarray([v[1] for v in м.values() if v[1] is not None], np.float64)
    размах = np.asarray([v[2] for v in м.values() if v[2] is not None], np.float64)
    одна = len(доли) >= ОБЪЕКТОВ and float(np.percentile(доли, 10)) >= ЖЁСТКИХ
    плоско = len(размах) >= ОБЪЕКТОВ and float(np.median(размах)) <= РАЗМАХ
    if not (одна or плоско):
        return None
    ч = []
    if len(доли):
        ч.append(f'жёстких краёв {100 * np.percentile(доли, 10):.0f}–{100 * np.percentile(доли, 90):.0f} %'
                 + (' — резкость одна' if одна else ''))
    if len(размах):
        ч.append(f'тон внутри p50 {np.median(размах):.0f} L' + (' — плоский' if плоско else ''))
    у = ''
    if образец and образец[0] is not None and образец[1] is not None:
        у = f'; у образца жёстких {_ч(100 * образец[1], 0)} %'
    и = ['х.переход(область)', 'край_для(кисть, кайма_мм=)', "Краска(rgb, 'лессировочная')"]
    голова = f'{_мн(len(м), "объект", "объекта", "объектов")}: ' + '; '.join(ч)
    return 'С23:холст', голова + у + '; похоже на аппликацию', и      # до 230 знаков строкой (5г): 39 объектов, образец — 229
