"""Свет по рельефу краски: нормаль из наклона карты толщины, свет сверху слева,
матовая часть и слабый блик; Г-2 — переотражение светлой краски, перелив света, что выше белого, к соседям, и
поверхность (матовое, полуматовое, лак) ключом вывода. Всё в линейном свете."""
import numpy as np

from .числа import _ТЕНЬ

СИЛА_ПО_УМОЛЧАНИЮ = 0.40   # сдержанно: на тонкой краске рельеф едва виден, на пастозной читается
ВЫСОТА_РЕЛЬЕФА = 2.4       # во сколько пикселей «высоты» идёт единица толщины h
_СВЕТ = np.array([-0.55, -0.62, 0.56])       # сверху слева (y растёт вниз)
_СВЕТ = _СВЕТ / np.linalg.norm(_СВЕТ)
_ПОЛУВЕКТОР = _СВЕТ + np.array([0.0, 0.0, 1.0])
_ПОЛУВЕКТОР = _ПОЛУВЕКТОР / np.linalg.norm(_ПОЛУВЕКТОР)
_БЛЕСК = 24.0
_БЛИК_ПЛОСКИЙ = float(_ПОЛУВЕКТОР[2] ** _БЛЕСК)
# п. 20, падающая тень: луч идёт от точки к свету; в плоскости холста — на 1 px, вверх — на столько px высоты
_К_СВЕТУ = (float(_СВЕТ[0] / np.hypot(_СВЕТ[0], _СВЕТ[1])), float(_СВЕТ[1] / np.hypot(_СВЕТ[0], _СВЕТ[1])))
_ПОДЪЁМ_ЛУЧА = float(_СВЕТ[2] / np.hypot(_СВЕТ[0], _СВЕТ[1]))
ТЕНЬ_ПО_УМОЛЧАНИЮ = 0.0    # выключена; рабочая сила, когда её зовут без числа, — `ТЕНЬ_РАБОЧАЯ`
ТЕНЬ_РАБОЧАЯ = _ТЕНЬ[7]
_СТУПЕНЕЙ = 4              # ступеней сглаживания рельефа для дальних преград: σ, 2σ, 4σ, 8σ
# Г-2, белила под светом. Шершавая грань отдаёт зрителю сверху меньше света, чем плоская: с наклона свет уходит вбок,
# на соседние грани, а у граней к свету матовый множитель упирается в белое. Светлая краска возвращает ушедшее:
# недостача света окна D = 1 − (матовый множитель, сглаженный гауссом σ ПЕРЕЛИВ px) (не меньше 0) приходит назад на
# долю альбедо — цвет c светит c · (м + ПЕРЕОТРАЖЕНИЕ · c · D). ПЕРЕОТРАЖЕНИЕ 1 — белое возвращает всю недостачу
# (свет окна сохраняется, светлее плоского шершавое не станет); тёмная краска (c → 0) почти ничего, тень борозд прежняя.
ПЕРЕОТРАЖЕНИЕ = 1.0
# Свет выше белого (1 в линейном) экран не покажет; обрезанный, он пропадал, а тёмные грани оставались — белила серели
# (−6,4 L под светом 0,4, тычки в три слоя −12). Избыток каждого канала переливается поровну в соседние пиксели, где
# до белого есть место (гаусс σ ПЕРЕЛИВ px; на холсте 8 px/мм — 1 мм): разница тонов между ними не сжимается, тычки
# отдельные, свет окна сохраняется, белое не выше белого.
ПЕРЕЛИВ = 8.0
# Г-2, поверхность ключом вывода: (блеск — показатель блика, доля блика на силу света, насыщение — степень цвета
# в линейном (масло и лак убирают рассеяние с поверхности: цвет глубже), дымка — доля рассеяния с сухой поверхности
# (белёсый налёт матового)). None — умолчание: слабый узкий блик без дымки (на глаз сухое, как 'матовое'); журнал и слои ключ не трогает.
ПОВЕРХНОСТИ = {
    None: (24.0, 0.10, 1.0, 0.0),
    'матовое': (6.0, 0.02, 1.0, 0.035),
    'полуматовое': (16.0, 0.40, 1.06, 0.0),
    'лак': (40.0, 1.20, 1.12, 0.0),
}
ПОЛЕ_ТЕНИ = int(_ТЕНЬ[6]) + sum(int(np.ceil(3.0 * v)) for v in [_ТЕНЬ[1]] + [_ТЕНЬ[1] * 2 ** k * np.sqrt(3.0) for k in range(_СТУПЕНЕЙ - 1)]) + 1   # px: столько соседей нужно точке, чтобы её тень не зависела от обреза


def _сгладить(a, σ):
    """Гауссово сглаживание (В, Ш) с повтором края; ядро обрезано на 3σ.
    М-9: суммы копятся кусками по `_СТРОК` строк — кусок с ядром лежит в кэше процессора; порядок сложения у каждого
    пикселя прежний, значения те же бит в бит, а счёт широкой полосы вчетверо быстрее."""
    r = int(np.ceil(3.0 * σ))
    if r < 1:
        return a
    я = np.exp(-0.5 * (np.arange(-r, r + 1) / σ) ** 2)
    я = (я / я.sum()).astype(np.float32)
    В, Ш = a.shape
    п = np.pad(a, ((0, 0), (r, r)), mode='edge')
    b = np.zeros_like(a)
    for y in range(0, В, _СТРОК):
        бб, пп = b[y:y + _СТРОК], п[y:y + _СТРОК]
        for i in range(2 * r + 1):
            бб += пп[:, i:i + Ш] * я[i]
    п = np.pad(b, ((r, r), (0, 0)), mode='edge')
    a = np.zeros_like(b)
    for y in range(0, В, _СТРОК):
        аа = a[y:y + _СТРОК]
        н = аа.shape[0]
        for i in range(2 * r + 1):
            аа += п[y + i:y + i + н] * я[i]
    return a


_СТРОК = 8     # М-9: строк в куске `_сгладить`


def тень_рельефа(h, сила):
    """П. 20. Множитель падающей тени по карте толщины h (В, Ш): 1 — точка видит свет, 1 − сила — в полной тени.

    Точка темнеет, когда на луче от неё к свету (`_СВЕТ`) рельеф стоит выше луча; полутень — по тому, на сколько
    преграда выше луча, и шире с расстоянием до преграды. Считается только из h; на плоском — ровно 1.
    За краем массива преград нет; чтобы кусок совпал с тем же местом целого, вызывающий даёт поле
    `ПОЛЕ_ТЕНИ` px (или край холста)."""
    h = np.asarray(h, dtype=np.float32)
    одна = np.ones(h.shape, np.float32)
    if not сила or h.size == 0:
        return одна
    px_на_толщину, σ, порог, мягкость, рост, вбок, предел = _ТЕНЬ[:7]
    H = _сгладить(h * np.float32(px_на_толщину), σ)
    шагов = min(int(предел), int(np.ceil(float(H.max() - H.min()) / _ПОДЪЁМ_ЛУЧА)))
    if шагов < 1:
        return одна
    В, Ш = H.shape
    # источник света не точка: чем дальше преграда, тем шире её полутень и вбок — дальние преграды берутся
    # с рельефа, сглаженного сильнее (σ, 2σ, 4σ, …; между ступенями — по прямой)
    ступени, поля = [H], []
    while σ * 2 ** (len(ступени) - 1) < σ + вбок * шагов and len(ступени) < _СТУПЕНЕЙ:
        k = len(ступени)
        ступени.append(_сгладить(ступени[-1], σ * 2 ** (k - 1) * np.sqrt(3.0)))
    for a in ступени:
        поля.append(np.pad(a, шагов + 1, mode='constant', constant_values=-1e6))   # за краем преград нет
    выше = np.zeros_like(H)                     # наибольшая доля тени по лучу
    for t in range(1, шагов + 1):
        ox, oy = t * _К_СВЕТУ[0], t * _К_СВЕТУ[1]
        ix, iy = int(np.floor(ox)), int(np.floor(oy))
        fx, fy = np.float32(ox - ix), np.float32(oy - iy)
        y0, x0 = шагов + 1 + iy, шагов + 1 + ix
        ур = min(float(np.log2(1.0 + вбок * t / σ)), len(ступени) - 1.0)
        k = min(int(ур), len(ступени) - 2) if len(ступени) > 1 else 0
        с = None
        for п, вес in ((поля[k], 1.0 - (ур - k)),) + (((поля[k + 1], ур - k),) if len(ступени) > 1 else ()):
            if вес <= 0.0:
                continue
            v = (п[y0:y0 + В, x0:x0 + Ш] * ((1 - fx) * (1 - fy)) + п[y0:y0 + В, x0 + 1:x0 + 1 + Ш] * (fx * (1 - fy))
                 + п[y0 + 1:y0 + 1 + В, x0:x0 + Ш] * ((1 - fx) * fy) + п[y0 + 1:y0 + 1 + В, x0 + 1:x0 + 1 + Ш] * (fx * fy))
            v *= np.float32(вес)
            с = v if с is None else с + v
        с -= H
        с -= np.float32(t * _ПОДЪЁМ_ЛУЧА + порог)   # на столько преграда выше луча, px высоты; ниже порога тени не кладёт
        с *= np.float32(1.0 / (мягкость + рост * t))   # полутень шире с расстоянием
        np.clip(с, 0.0, 1.0, out=с)
        с *= np.float32(1.0 - t / (предел + 1.0))   # дальняя тень слабее, к пределу сходит на нет
        np.maximum(выше, с, out=выше)
    выше = выше * выше * (3.0 - 2.0 * выше)
    return (1.0 - np.float32(сила) * выше).astype(np.float32)


def поверхность_вывода(поверхность):
    """Г-2: (блеск, доля блика, насыщение, дымка) ключа поверхности; неизвестный ключ — ValueError с перечнем."""
    if поверхность not in ПОВЕРХНОСТИ:
        raise ValueError(f"поверхность={поверхность!r}: одно из {[к for к in ПОВЕРХНОСТИ if к]} или None (умолчание: слабый узкий блик без дымки)")
    return ПОВЕРХНОСТИ[поверхность]


def множители(h, сила=СИЛА_ПО_УМОЛЧАНИЮ, тень=ТЕНЬ_ПО_УМОЛЧАНИЮ, без=None, поверхность=None):
    """По карте толщины h (В, Ш) — матовый множитель (1 на плоском) и добавка блика (0 на плоском).
    тень — сила падающей тени (п. 20): 0 — её нет, всё как было; больше — матовый множитель и блик темнеют там,
    куда рельеф кладёт тень (`свет.тень_рельефа`; куску нужно поле `ПОЛЕ_ТЕНИ` px).
    без — (по x, по y), К9: наклон, которого в h быть не должно (ступень у кромки верхнего слоя над толщей нижних,
    `Холст._без_канавы`), — вычитается из наклона h; None — нечего вычитать.

    поверхность — Г-2, ключ вывода (`ПОВЕРХНОСТИ`): блеск и доля блика; None — умолчание: слабый узкий блик без дымки.

    Края массива считаются односторонней разностью; вызывающий даёт поле в 1 px,
    если режет картинку полосами."""
    h = np.asarray(h, dtype=np.float32)
    gx = np.empty_like(h)
    gy = np.empty_like(h)
    gx[:, 1:-1] = (h[:, 2:] - h[:, :-2]) * 0.5
    gx[:, 0] = h[:, 1] - h[:, 0]
    gx[:, -1] = h[:, -1] - h[:, -2]
    gy[1:-1] = (h[2:] - h[:-2]) * 0.5
    gy[0] = h[1] - h[0]
    gy[-1] = h[-1] - h[-2]
    if без is not None:
        gx -= без[0]
        gy -= без[1]
    gx *= ВЫСОТА_РЕЛЬЕФА
    gy *= ВЫСОТА_РЕЛЬЕФА
    норма = 1.0 / np.sqrt(gx * gx + gy * gy + 1.0)
    nx = -gx * норма
    ny = -gy * норма
    nz = норма
    матовый = (nx * _СВЕТ[0] + ny * _СВЕТ[1] + nz * _СВЕТ[2]) / _СВЕТ[2]
    np.clip(матовый, 0.0, 3.0, out=матовый)
    матовый = 1.0 + сила * (матовый - 1.0)
    np.clip(матовый, 0.05, None, out=матовый)
    nh = nx * _ПОЛУВЕКТОР[0] + ny * _ПОЛУВЕКТОР[1] + nz * _ПОЛУВЕКТОР[2]
    np.clip(nh, 0.0, 1.0, out=nh)
    if поверхность is None:
        блик = (nh ** _БЛЕСК - _БЛИК_ПЛОСКИЙ) * (0.10 * сила)
    else:
        блеск, доля = поверхность_вывода(поверхность)[:2]
        блик = (nh ** блеск - float(_ПОЛУВЕКТОР[2] ** блеск)) * (доля * сила)
    np.clip(блик, 0.0, None, out=блик)
    if тень:
        т = тень_рельефа(h, тень)
        матовый = матовый * т
        блик = блик * т
    return матовый.astype(np.float32), блик.astype(np.float32)


def поле_перелива():
    """px: радиус гаусса `ПЕРЕЛИВ` (по нынешнему значению). Картинке куска нужно поле в два таких радиуса сверх поля
    света (`вывести` — недостача окна, `перелить` — перелив), чтобы кусок совпал с тем же местом целого."""
    return int(np.ceil(3.0 * ПЕРЕЛИВ))


def перелить(к):
    """Г-2. к (В, Ш, 3) линейный свет -> тот же, но не выше 1: избыток над белым каждого канала уходит поровну в
    соседние пиксели этого канала, где до 1 есть место (гаусс σ `ПЕРЕЛИВ` px). Свет в окне сохраняется, пока места
    хватает; разница тонов у непереполненных не меняется. Без избытка — тот же массив; дальше `поле_перелива()` px от
    избытка — бит в бит."""
    if not (к > 1.0).any():
        return к
    о = np.minimum(к, np.float32(1.0))
    for i in range(к.shape[2]):
        e = к[..., i] - о[..., i]
        if not e.any():
            continue
        E = _сгладить(e, ПЕРЕЛИВ)
        есть = о[..., i] < 1.0
        N = _сгладить(есть.astype(np.float32), ПЕРЕЛИВ)
        д = np.zeros_like(E)
        np.divide(E, N, out=д, where=(E > 0.0) & (N > 1e-6) & есть)
        np.minimum(о[..., i] + д, np.float32(1.0), out=о[..., i])
    return о


def недостача(м):
    """Г-2. Недостача света окна по матовому множителю м (В, Ш): 1 − м, сглаженный гауссом σ `ПЕРЕЛИВ` px, не меньше 0
    (меньше 1e-5 — 0: на плоском ровно 0)."""
    D = np.float32(1.0) - _сгладить(np.asarray(м, np.float32), ПЕРЕЛИВ)
    D[D < 1e-5] = 0.0
    return D


def вывести(цвет, м, б, D, поверхность=None):
    """Г-2. Освещённый цвет до перелива: цвет (В, Ш, 3) линейный, м, б — из `множители`, D — `недостача(м)`.
    Переотражение светлой краски (`ПЕРЕОТРАЖЕНИЕ`), насыщение и дымка поверхности, блик."""
    насыщение, дымка = поверхность_вывода(поверхность)[2:]
    if насыщение != 1.0:
        цвет = np.power(np.clip(цвет, 0.0, None), np.float32(насыщение))
    м3 = м[..., None]
    if ПЕРЕОТРАЖЕНИЕ and D.any():
        м3 = м3 + цвет * (np.float32(ПЕРЕОТРАЖЕНИЕ) * D)[..., None]
    к = цвет * м3
    if дымка:
        к = к * np.float32(1.0 - дымка) + (np.float32(дымка) * м)[..., None]
    к = к + б[..., None]
    return к.astype(np.float32)


def осветить(цвет, h, сила=СИЛА_ПО_УМОЛЧАНИЮ, тень=ТЕНЬ_ПО_УМОЛЧАНИЮ, поверхность=None):
    """цвет (В, Ш, 3) линейный, h (В, Ш) -> освещённый цвет, не выше белого (Г-2: переотражение, перелив,
    поверхность). тень — сила падающей тени (п. 20), 0 — нет. Как `Холст.картинка`, но края массива без соседей."""
    м, б = множители(h, сила, тень, поверхность=поверхность)
    return перелить(вывести(np.asarray(цвет, np.float32), м, б, недостача(м), поверхность))


def слой_света(h, сила=СИЛА_ПО_УМОЛЧАНИЮ, тень=ТЕНЬ_ПО_УМОЛЧАНИЮ, без=None):
    """Серый слой света в гамме sRGB 0..1, нейтраль 0,5 — класть поверх цвета
    в режиме «Жёсткий свет» (Hard Light): ниже 0,5 — умножение (точно наш матовый
    множитель), выше — осветление (точно на среднем тоне, на прочих приближённо).
    тень — сила падающей тени (п. 20), 0 — нет: тень входит в тот же слой. без — как у `множители` (К9)."""
    м, б = множители(h, сила, тень, без)
    полный = м + б * 4.0                       # блик на среднем тоне
    гамма = np.power(np.clip(полный, 0.0, None), 1.0 / 2.2)
    return np.clip(0.5 * гамма, 0.0, 1.0).astype(np.float32)
