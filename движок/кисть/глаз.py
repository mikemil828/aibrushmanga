    п_теп = 128.0 + np.where(тн > 0, тн * (np.array([255, 140, 30]) - 128.0), -тн * (np.array([40, 110, 255]) - 128.0))
    п_кр = np.zeros((ny, nx, 3))
    п_кр[мягкие] = np.array([90, 170, 255]) * np.clip(перепад[мягкие] / 40.0, 0.35, 1.0)[:, None]
    п_кр[жёсткие] = 255.0
    tmax = max(0.05, float(np.percentile(толщина, 99.5)))
    п_тол = _серо(толщина, 0, tmax)
    п_сыр = 255.0 - np.clip(сыро, 0, 1)[..., None] * (255.0 - np.array([30, 80, 200]))
    есть = ~np.isnan(угол)
    уг = np.radians(np.nan_to_num(угол))
    п_нап = np.full((ny, nx, 3), 235.0)
    if есть.any():
        оттенок = цвет(np.full(угол.shape, 200.0), np.full(угол.shape, 0.07), np.degrees(2 * уг))
