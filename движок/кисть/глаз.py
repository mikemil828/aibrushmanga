# ---------------------------------------------------------------- Б-10 издали и вблизи

def обзор(х, цель, область=None, кропов=4, окно=300, размер=800, путь=None, свет=True, без=None, до=None):
    """Б-10: издали и вблизи одним листом. Сверху — область целиком, длинная сторона `размер` px, на ней рамками с
    номерами — `кропов` (3–5) мест наибольшего расхождения с целью: квадраты стороной `окно` px холста по наибольшему
    |среднему dL| (`разность`, тон без света, не налегают); ниже — эти места 1:1, «холст | цель», по два в ряд, над
    каждым номер, рамка и dL. свет — у картинок листа (как у `взгляд`); без, до — Б-5. путь — PNG листа. Ответ —
    {'лист' (uint8), 'худшие' [(x0, y0, x1, y1, dL)], 'сводка' (сводка `разность`)}."""
    from PIL import Image, ImageDraw
    х = без_слоёв(х, без, до)
    рамка = _рамка(х, область)
    x0, y0, x1, y1 = рамка
    р = разность(х, цель, рамка, окно=min(int(окно), x1 - x0, y1 - y0), худших=int(кропов))
    м = min(1.0, размер / max(x1 - x0, y1 - y0))
    издали = Image.fromarray(взгляд(х, рамка, масштаб=м, свет=свет))
    д = ImageDraw.Draw(издали)
    шрифт = _шрифт(16)
    for i, (a, b, c, e, _) in enumerate(р.сводка['худшие'], 1):
        q = [(a - x0) * м, (b - y0) * м, (c - x0) * м, (e - y0) * м]
        д.rectangle(q, outline=(255, 0, 0), width=2)
        д.text((q[0] + 3, q[1] + 1), str(i), fill=(255, 0, 0), font=шрифт)
    кропы = [Image.fromarray(взгляд(х, w[:4], свет=свет, рядом=цель)) for w in р.сводка['худшие']]
    шк, вк = (max(к.width for к in кропы), max(к.height for к in кропы)) if кропы else (0, 0)
    поле, шапка = 6, 24
    ш = max(издали.width, 2 * шк + поле) + 2 * поле
    в = издали.height + 2 * поле + ((len(кропы) + 1) // 2) * (вк + шапка + поле)
    лист = Image.new('RGB', (ш, в), (255, 255, 255))
    лист.paste(издали, (поле, поле))
    д = ImageDraw.Draw(лист)
    for i, (к, w) in enumerate(zip(кропы, р.сводка['худшие'])):
        x, y = поле + (i % 2) * (шк + поле), издали.height + 2 * поле + (i // 2) * (вк + шапка + поле)
        д.text((x + 2, y + 3), f'{i + 1}: {w[:4]}  dL {_ч(w[4])}  холст | цель', fill=(0, 0, 0), font=шрифт)
        лист.paste(к, (x, y + шапка))
    if путь is not None:
        лист.save(os.path.expanduser(str(путь)))
    return {'лист': np.asarray(лист), 'худшие': р.сводка['худшие'], 'сводка': р.сводка}


# ---------------------------------------------------------------- М-6 сетка и укладка образца

УКЛАДКИ = ('как есть', 'вписать', 'обрезать', 'растянуть')


def уложить(образец, ширина, высота, укладка='как есть'):
    """М-6: образец (путь к картинке или массив (В, Ш, 3) sRGB 0–255) в координатах холста ширина × высота — массив
    (высота, ширина, 3) float64 sRGB и словарь укладки. укладка: 'как есть' — пиксель образца = пиксель холста от угла
    (0, 0), как `рядом` у `взгляд` (где образца нет — серый 128); 'вписать' — целиком, пропорция та же, поля серым по
    центру; 'обрезать' — покрывает холст, пропорция та же, лишнее по краям срезано поровну; 'растянуть' — в размер
    холста, пропорция образца теряется. Словарь: 'укладка', 'масштаб' (sx, sy — px холста на px образца), 'сдвиг' (dx, dy):
    точка образца (u, v) — на холсте (dx + u·sx, dy + v·sy); 'образец' — его ширина и высота. Ответ годится как
    `рядом=` и цель глаз. Холст не нужен и не трогается."""
    from PIL import Image
    if укладка not in УКЛАДКИ:
        raise ValueError(f'укладка {укладка!r}: есть {", ".join(repr(у) for у in УКЛАДКИ)}')
    a = _загрузить(образец) if isinstance(образец, (str, os.PathLike)) else np.asarray(образец)
    if a.ndim != 3 or a.shape[2] < 3:
        raise ValueError(f'уложить: образец — картинка (В, Ш, 3) sRGB 0–255 или путь к ней; дано {a.shape}')
    a = np.asarray(a[..., :3], np.float64)
    во, шо = a.shape[:2]
    ширина, высота = int(ширина), int(высота)
    п = np.full((высота, ширина, 3), float(СЕРЫЙ_ВНЕ))
    if укладка == 'как есть':
        sx = sy = 1.0
        dx = dy = 0.0
        п[:min(во, высота), :min(шо, ширина)] = a[:высота, :ширина]
    else:
        if укладка == 'растянуть':
            sx, sy = ширина / шо, высота / во
        else:
            s = (min if укладка == 'вписать' else max)(ширина / шо, высота / во)
            sx = sy = s
        нш, нв = max(1, int(round(шо * sx))), max(1, int(round(во * sy)))
        dx, dy = (ширина - нш) / 2.0, (высота - нв) / 2.0
        im = Image.fromarray(_в_8(a)).resize((нш, нв), Image.LANCZOS)
        b = np.asarray(im, np.float64)
        x0, y0 = int(math.floor(dx)), int(math.floor(dy))
        # кусок b, что ложится на холст
        bx0, by0 = max(0, -x0), max(0, -y0)
        cx0, cy0 = max(0, x0), max(0, y0)
        w = min(нш - bx0, ширина - cx0)
        h = min(нв - by0, высота - cy0)
        п[cy0:cy0 + h, cx0:cx0 + w] = b[by0:by0 + h, bx0:bx0 + w]
        dx, dy = float(x0), float(y0)
    return п, {'укладка': укладка, 'масштаб': (round(sx, 6), round(sy, 6)), 'сдвиг': (dx, dy), 'образец': (шо, во)}


def _шаг_сетки(длина):
    for ш in (10, 20, 25, 50, 100, 200, 250, 500, 1000, 2000, 2500, 5000):
        if длина / ш <= 12:
            return ш
    return 10000


def _нарисовать_сетку(a8, рамка, шаг, масштаб, шрифт):
    """Линии каждые `шаг` px холста — пунктир белый/чёрный (виден на любом тоне), подписи в px холста с обводкой."""
    from PIL import Image, ImageDraw
    x0, y0, x1, y1 = рамка
    im = Image.fromarray(a8)
    д = ImageDraw.Draw(im)
    В, Ш = a8.shape[:2]
    пунктир = (np.arange(max(В, Ш)) // 4) % 2 == 0
    a = np.asarray(im).copy()
    xs = [x for x in range(int(math.ceil(x0 / шаг)) * шаг, x1, шаг)]
    ys = [y for y in range(int(math.ceil(y0 / шаг)) * шаг, y1, шаг)]
    for x in xs:
        с = int(round((x - x0) * масштаб))
        if 0 <= с < Ш:
            a[:, с] = np.where(пунктир[:В, None], 255, 0)
    for y in ys:
        с = int(round((y - y0) * масштаб))
        if 0 <= с < В:
            a[с, :] = np.where(пунктир[:Ш, None], 255, 0)
    im = Image.fromarray(a)
    д = ImageDraw.Draw(im)
    for x in xs:
        с = int(round((x - x0) * масштаб))
        if 0 <= с < Ш:
            д.text((с + 3, 2), str(x), fill=(255, 255, 255), font=шрифт, stroke_width=2, stroke_fill=(0, 0, 0))
    for y in ys:
        с = int(round((y - y0) * масштаб))
        if 0 <= с < В and с > 0:
            д.text((3, с + 2), str(y), fill=(255, 255, 255), font=шрифт, stroke_width=2, stroke_fill=(0, 0, 0))
    return np.asarray(im)


def сетка(х, образец=None, шаг=None, область=None, масштаб=1.0, укладка='как есть', рядом=False, путь=None, свет=True):
    """М-6: сетка в px холста с подписями — поверх холста (образец None) или образца, уложенного на холст (`уложить`:
    'как есть' — как `рядом` у `взгляд`, 'вписать', 'обрезать', 'растянуть'); рядом=True — «холст | образец», обе с
    сеткой. шаг — px холста между линиями (None — круглое, ~6–12 линий на длинную сторону области); область, масштаб, свет
    — как у `взгляд`: линия x — левый край пикселя x холста. Только картинка: холст, журнал и сиды не трогает. Ответ —
    uint8 ряд; путь — PNG; у ответа (`Ряд`) поле `укладка` — словарь `уложить` (или None без образца)."""
    from .холст import Ряд
    рамка = _рамка(х, область)
    x0, y0, x1, y1 = рамка
    шаг = _шаг_сетки(max(x1 - x0, y1 - y0)) if шаг is None else int(шаг)
    if шаг < 1:
        raise ValueError('сетка: шаг — px холста, от 1')
    части, ук = [], None
    if образец is None or рядом:
        части.append(_вид(х, рамка, свет))
    if образец is not None:
        о, ук = уложить(образец, х.полная_ширина, х.полная_высота, укладка)
        части.append(о[y0:y1, x0:x1])
    шрифт = _шрифт(max(11, min(16, int(12 * max(1.0, масштаб)))))
    кадры = [_нарисовать_сетку(_масштаб(_в_8(ч), масштаб), рамка, шаг, масштаб, шрифт) for ч in части]
    if len(кадры) > 1:
        поле = np.full((кадры[0].shape[0], 6, 3), 255, np.uint8)
        ряд = np.concatenate([кадры[0], поле, кадры[1]], 1)
    else:
        ряд = кадры[0]
    if путь is not None:
        from PIL import Image
        Image.fromarray(ряд).save(os.path.expanduser(str(путь)))
    ряд = np.ascontiguousarray(ряд).view(Ряд)
    ряд.укладка = ук
    ряд.подсказки = []
    return ряд
