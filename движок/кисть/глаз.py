def _прореди(т, шаг):
    """Точки пути, между которыми не меньше `шаг` px (первая и последняя — всегда)."""
    if len(т) <= 2:
        return т
    d = np.concatenate([[0.0], np.cumsum(np.hypot(*np.diff(т, axis=0).T))])
    i = np.unique(np.searchsorted(d, np.arange(0.0, d[-1], шаг)))
    return т[np.unique(np.concatenate([i, [len(т) - 1]]))]


def _ходы(мазки, слои, рамка, k, n, покрытие, порог=0.3):
    """Мазки на сетке клеток. В клетке — верхний мазок самого верхнего слоя, чья краска кроет клетку не меньше чем на
    `порог` (`покрытие` — {слой: доля клетки}); в слое верхний — позже по журналу. Клетка, где мазки прошли, а краски
    нет ни у одного (тонкая мгла, сухой ход), берёт верхний мазок с наибольшим покрытием. Ответ — (направление °
    0–180 (0 — вдоль x, 90 — вдоль y вниз; NaN — мазка нет), ширина px, длина px, номер строки журнала (0 — нет)) —
    массивы (n_y, n_x), и сколько мазков задели область."""
    from PIL import Image, ImageDraw
    ny, nx = n
    x0, y0, x1, y1 = рамка
    по_слою = {с: [] for с in слои}
    for м in мазки:
        if м[1] not in по_слою:
            continue
        т = м[3]
        r = м[2] / 2 + 1
        if т[:, 0].max() + r < x0 or т[:, 0].min() - r > x1 or т[:, 1].max() + r < y0 or т[:, 1].min() - r > y1:
            continue
        по_слою[м[1]].append(м)
    углы, ширины, длины, номера = [np.nan], [np.nan], [np.nan], [0]
    ид = np.zeros((ny, nx), np.int64)
    лучшее = np.full((ny, nx), -1.0, np.float32)       # покрытие слоя, давшего мазок клетке; 2 — слой кроет
    for слой in reversed(слои):
        if not по_слою[слой]:
            continue
        im = Image.new('I', (nx, ny), 0)
        д = ImageDraw.Draw(im)
        for номер, _, ш, т in по_слою[слой]:
            т = _прореди(т, max(2.0 * k, ш / 4))
            дл = float(np.hypot(*np.diff(т, axis=0).T).sum()) if len(т) > 1 else 0.0
            p = (т - (x0, y0)) / k
            w = max(1, int(round(ш / k)))
            if len(т) == 1 or дл < 1e-6:
                углы.append(np.nan); ширины.append(ш); длины.append(дл); номера.append(номер)
                c = p[0]
                д.ellipse((c[0] - w / 2, c[1] - w / 2, c[0] + w / 2, c[1] + w / 2), fill=len(углы) - 1)
                continue
            for a, b in zip(p[:-1], p[1:]):
                углы.append(float(np.degrees(np.arctan2(b[1] - a[1], b[0] - a[0])) % 180.0))
                ширины.append(ш); длины.append(дл); номера.append(номер)
                д.line([tuple(a), tuple(b)], fill=len(углы) - 1, width=w)
        и = np.asarray(im)
        пок = np.where(покрытие[слой] >= порог, 2.0, покрытие[слой])
        где = (и > 0) & (пок > лучшее)
        ид[где], лучшее[где] = и[где], пок[где]
    return (np.asarray(углы, np.float32)[ид], np.asarray(ширины, np.float32)[ид], np.asarray(длины, np.float32)[ид],
            np.asarray(номера, np.int64)[ид], sum(len(v) for v in по_слою.values()))


def _сдвиг(a, d, ось):
    """a, сдвинутый на d клеток по оси (за краем — крайнее значение): ответ[i] = a[i + d]."""
    n = a.shape[ось]
    i = np.clip(np.arange(n) + d, 0, n - 1)
    return np.take(a, i, ось)


def _края(L, порог):
    """Края по L клеток: перепад — |L(+2) − L(−2)| по той оси, где он больше; жёсткий — больше 60 % перепада приходится
    на один шаг клетки (переход уже ~2 клеток), мягкий — растянут."""
    лучш, доля = np.zeros_like(L), np.zeros_like(L)
    for ось in (0, 1):
        п = np.abs(_сдвиг(L, 2, ось) - _сдвиг(L, -2, ось))
        шаг = np.maximum.reduce([np.abs(_сдвиг(L, d + 1, ось) - _сдвиг(L, d, ось)) for d in (-2, -1, 0, 1)])
        q = np.where(п > 1e-6, шаг / np.maximum(п, 1e-6), 0.0)
        где = п > лучш
        лучш, доля = np.where(где, п, лучш), np.where(где, q, доля)
    край = лучш >= порог
    return лучш.astype(np.float32), край & (доля > 0.6), край & (доля <= 0.6)


