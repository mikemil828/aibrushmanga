def без_слоёв(х, без=None, до=None):
    """Холст для глаз без слоёв `без` (имя или список имён) и только со слоями ниже слоя `до` (сам `до` не входит) —
    копия полей холста, слои — те же объекты, только читать: `х.слои`, журнал, пиксели не меняются. Без `без` и `до` —
    сам холст. Нет такого слоя — KeyError со списком слоёв."""
    if без is None and до is None:
        return х
    х.досчитать()
    имена = list(х.слои)
    без = [] if без is None else [без] if isinstance(без, str) else list(без)
    for и in без + ([] if до is None else [до]):
        if и not in имена:
            raise KeyError(f'глаз: слоя {и!r} нет (слои снизу вверх: {имена})')
    оставить = имена[:имена.index(до)] if до is not None else имена
    from .холст import Холст
    в = object.__new__(Холст)
    в.__dict__.update(х.__dict__)
    в.__dict__.update(_слои={и: х.слои[и] for и in оставить if и not in без}, _ядра=None, _ядер=1, журнал=None, _снимки=[],
                     _подсказки=None)
    return в


