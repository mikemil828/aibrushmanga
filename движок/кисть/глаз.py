def _клетками(a, k):
    """Средние a (В, Ш[, …]) в клетках k×k; остаток края (меньше k) отброшен."""
    if k == 1:
        return a.astype(np.float32)
    h, w = a.shape[0] // k * k, a.shape[1] // k * k
    return a[:h, :w].reshape(h // k, k, w // k, k, *a.shape[2:]).mean((1, 3), dtype=np.float32)


