def разница_физики(версия):
    """Что сказать, когда журнал записан физикой `версия`, а у движка `ФИЗИКА`: что поменялось с тех пор."""
    имена = [в for в, _ in ИСТОРИЯ_ФИЗИКИ]
    if версия not in имена:
        return (f'журнал записан физикой {версия}, у движка {ФИЗИКА}: этой версии движок не знает (журнал с другого '
                'движка или новее этого) — пиксели могут разойтись с листом')
    после = ИСТОРИЯ_ФИЗИКИ[имена.index(версия) + 1:]
    return (f'журнал записан физикой {версия}, у движка {ФИЗИКА}: пиксели разойдутся с листом; с тех пор — '
            + '; '.join(f'{в}: {что}' for в, что in после))


def _в_json(v):
    """Числа numpy и кортежи -> то, что json пишет точно (float — repr, назад тот же бит)."""
    if isinstance(v, np.ndarray):
        return v.tolist()
    if isinstance(v, (np.floating,)):
        return float(v)
    if isinstance(v, (np.integer,)):
        return int(v)
    if isinstance(v, (list, tuple)):
        return [_в_json(x) for x in v]
    if isinstance(v, dict):
        return {str(к): _в_json(x) for к, x in v.items()}
    return v


def _вид(rgb):
    вид = getattr(rgb, 'вид', None)
    return None if вид is None else _в_json(вид)


def цвет_строки(цвет):
    """Цвет вызова (`мазок`, `набрать`) -> поля строки журнала: "color" или "colors" и "paint" (вид краски одной или
    списком — по краске набора). None — "color": null (мазок набранной краской)."""
    if цвет is None:
        return {'color': None}
    from .палитра import имена_цвета
    имена = имена_цвета(цвет)         # М-1: мазок замесом палитры — рядом с цветом имя ("swatch")
    д = _цвет_строки(цвет)
    if имена is not None:
        д['swatch'] = имена
    return д


def _цвет_строки(цвет):
    ц = list(цвет)
    from .инструмент import _число
    if ц and _число(ц[0]):
        д = {'color': [_в_json(v) for v in ц]}
        вид = _вид(цвет)
        if вид is not None and вид != 'кроющая':
            д['paint'] = вид
        return д
    краски, виды = [], []
    for э in ц:
        э = list(э)
        if len(э) == 2 and not _число(э[0]):
            rgb, доля = э
        elif len(э) == 4:
            rgb, доля = э[:3], э[3]
        else:
            rgb, доля = э, 1.0
        краски.append([_в_json(v) for v in list(rgb)[:3]] + [_в_json(доля)])
        виды.append(_вид(rgb) or 'кроющая')
    д = {'colors': краски}
    if any(в != 'кроющая' for в in виды):
        д['paint'] = виды[0] if all(в == виды[0] for в in виды) else виды
    return д


class Журнал:
    """Файл журнала одного холста. Пишет строки, помнит кисти (имя, поля, что на кончиках по журналу), место для отката."""

    def __init__(self, путь, холст, продолжить=None):
        self.путь = os.fspath(путь)
        self.пауза = 0
        self.кисти = {}          # id(кисть) -> [кисть, имя, поля, остаток по журналу, краска по журналу]
        self.номер = 0           # последняя выданная кисть «кN»
        self.этап = self.объект = None
        if продолжить is None:
            self._ф = open(self.путь, 'wb')
            заголовок = {'canvas': [холст.полная_ширина, холст.полная_высота], 'ground': list(холст.грунт_srgb)}
            if холст.px_на_мм is not None:
                заголовок['px_per_mm'] = холст.px_на_мм
            if холст.зерно is not None:
                заголовок['grain'] = list(холст.зерно)
            заголовок['physics'] = ФИЗИКА
            if холст.сид:
                заголовок['seed'] = холст.сид
            заголовок['seeds'] = 'tree'      # А-9: строка без "seed" берёт сид из листа, этапа, объекта и своих точек
            self.строка(заголовок)
        else:
            self._продолжить(*продолжить)

    def _продолжить(self, npz, счётчик):
        """Журнал холста, взятого из `npz`: обрезать после строки {"saved": имя файла, "counter": счётчик} (последней
        такой) и писать дальше."""
        if not os.path.exists(self.путь):
            raise ValueError(f'журнал {self.путь}: файла нет — продолжать нечего')
        имя = os.path.basename(os.fspath(npz))
        место, первая = None, None
        with open(self.путь, 'rb') as f:
            байт = 0
            for сырая in f:
                байт += len(сырая)
                if первая is None:
                    первая = json.loads(сырая)
                if b'"saved"' in сырая:
                    з = json.loads(сырая)
                    if з.get('saved') == имя and з.get('counter') == счётчик:
                        место = (байт, з)
        if (первая or {}).get('physics') != ФИЗИКА:
            raise ValueError(f'журнал {self.путь}: физика {(первая or {}).get("physics")}, у движка {ФИЗИКА} — '
                             'продолжать этот лист этим движком нельзя')
        if место is None:
            raise ValueError(f'журнал {self.путь}: нет строки {{"saved": "{имя}"}} со счётчиком {счётчик} — '
                             'холст сохранён не с этим журналом или журнал обрезан раньше')
        байт, з = место
        self._сберечь_хвост(байт, имя)
        self._ф = open(self.путь, 'r+b')
        self._ф.truncate(байт)
        self._ф.seek(байт)
        self.номер = int(з.get('brushes', 0))
        self.этап, self.объект = з.get('stage'), з.get('object')

    def _сберечь_хвост(self, байт, имя):
        """М-12: строки журнала после точки сохранения `имя` (с байта `байт`) — до обрезки в `<журнал>.до_отката` (есть —
        `.до_отката.2`, `.3`, …: прежняя копия не затирается) байт в байт и строка в stderr. Хвоста нет — ничего."""
        if os.path.getsize(self.путь) <= байт:
            return None
        with open(self.путь, 'rb') as f:
            f.seek(байт)
            хвост = f.read()
        копия, k = self.путь + '.до_отката', 2
        while os.path.exists(копия):
            копия, k = f'{self.путь}.до_отката.{k}', k + 1
        with open(копия, 'xb') as f:
            f.write(хвост)
            f.flush()
            os.fsync(f.fileno())
        строк = sum(1 for s in хвост.splitlines() if s.strip())
        сл = 'строка' if строк % 10 == 1 and строк % 100 != 11 else \
            'строки' if 2 <= строк % 10 <= 4 and not 12 <= строк % 100 <= 14 else 'строк'
        print(f'журнал обрезан до {имя}: {строк} {сл} после неё — в {копия}', file=sys.stderr, flush=True)
        return копия

    # ------------------------------------------------------------------ запись
    def строка(self, д):
        self._ф.write(json.dumps(д, ensure_ascii=False, separators=(', ', ': ')).encode('utf-8') + b'\n')
        self._ф.flush()

    def _намерение(self, д, этап=None, объект=None, намерение=None):
        э = self.этап if этап is None else этап
        о = self.объект if объект is None else объект
        if э is not None:
            д['stage'] = _в_json(э)
        if о is not None:
            д['object'] = _в_json(о)
        if намерение is not None:
            д['intent'] = _в_json(намерение)
        return д

    def кисть(self, к):
        """Имя кисти в журнале; перед мазком — строки, без которых повтор не придёт к той же кисти: определение (первый
        раз и после правки полей), вытирание, грязь с другого холста, набранная краска."""
        з = self.кисти.get(id(к))
        поля = asdict(к)
        if з is None:
            self.номер += 1
            з = [к, f'к{self.номер}', None, None, None]
            self.кисти[id(к)] = з
        if з[2] != поля:
            self.строка({'brush': з[1], 'def': _в_json(поля)})
            з[2] = поля
        кр = к._краска
        if кр is not з[4] and (isinstance(кр, Загрузка) or isinstance(з[4], Загрузка)):      # Д-1: живая краска — своими строками
            if кр is None and к._остаток is None:
                self.строка({'rinse': з[1]})
                з[3] = з[4] = None
            elif isinstance(кр, Загрузка):
                набор = getattr(к, '_набор', None)
                с_набора = bool(кр.дела) and кр.дела[0][0] in ('load', 'rinse') and набор is not None and набор[2] is кр   # дела начаты набором (или промывкой перед ним): от прежнего на кисти не зависят
                if с_набора or (кр.дела and кр.от is з[4]):
                    for дело in кр.дела:
                        if дело[0] == 'load':
                            поля_цвета = цвет_строки(набор[0])
                            д = {'load_brush': з[1]}
                            д.update(поля_цвета)
                            д.update(amount=_в_json(дело[1]), layout=набор[1])
                            self.строка(д)
                        else:
                            self.строка({дело[0]: з[1]})
                            if сырое_поле(к, '_остаток') is None:
                                з[3] = None
                else:                             # загрузка пришла не делами после хода этого журнала (ход на другом холсте, откат чужого снимка): как есть
                    краски, раскладка = кр
                    self.строка({'brush': з[1], 'pick_linear': [[_в_json(c), float(д)] for c, д in краски],
                                 'pick_cover': getattr(краски, 'мутность', None), 'layout': раскладка,
                                 'left': [_в_json(кр.запас), _в_json(кр.капля)]})
            if isinstance(кр, Загрузка):
                з[4] = кр
        if сырое_поле(к, '_остаток') is not з[3]:        # 2б: мазок этого холста, что ещё считается на ядрах, — тот же объект-метка
            ост = к._остаток                             # (мазок другого холста — досчитывается)
            if ост is None:
                self.строка({'brush': з[1], 'wipe': True})
            else:
                self.строка({'brush': з[1], 'dirt': [_в_json(np.asarray(a, np.float64)) for a in ост]})
            з[3] = ост
        if к._краска is not з[4]:
            набор = getattr(к, '_набор', None)
            if к._краска is None:
                self.строка({'brush': з[1], 'pick': None})
            elif набор is not None and набор[2] is к._краска:
                поля_цвета = цвет_строки(набор[0])
                пик = {'brush': з[1], 'pick': поля_цвета.pop('color', None) if 'color' in поля_цвета else поля_цвета.pop('colors')}
                пик.update(поля_цвета)
                пик['layout'] = набор[1]
                self.строка(пик)
            else:                                 # краска на кисти пришла не через `набрать` (откат чужого снимка): как есть
                краски, раскладка = к._краска
                self.строка({'brush': з[1], 'pick_linear': [[_в_json(c), float(д)] for c, д in краски],
                             'pick_cover': getattr(краски, 'мутность', None), 'layout': раскладка})
            з[4] = к._краска
        return з[1]

    def после_мазка(self, к):
        з = self.кисти[id(к)]
        з[3], з[4] = сырое_поле(к, '_остаток'), к._краска

    def досчитан(self, к, метка, остаток):
        """2б: мазок кисти досчитан на ядрах — вместо его метки журнал помнит то, что осталось на кисти."""
        з = self.кисти.get(id(к))
        if з is not None and з[3] is метка:
            з[3] = остаток

    # ------------------------------------------------------------------ откат
    def место(self):
        """Где журнал сейчас: для снимка холста."""
        return (self._ф.tell(), self.номер, self.этап, self.объект,
                {к: list(з) for к, з in self.кисти.items()})

    def откатить(self, место):
        байт, self.номер, self.этап, self.объект, кисти = место
        self._ф.truncate(байт)
        self._ф.seek(байт)
        self._ф.flush()
        self.кисти = {к: list(з) for к, з in кисти.items()}

    def сохранён(self, путь, счётчик):
        """Строка {"saved": имя файла, "counter": счётчик мазков, "brushes": сколько кистей названо}: с неё
        `Холст.загрузить(…, журнал=)` продолжит журнал. Повтор её пропускает."""
        self.строка(self._намерение({'saved': os.path.basename(os.fspath(путь)), 'counter': int(счётчик), 'brushes': self.номер}))

    def закрыть(self):
        ф = getattr(self, '_ф', None)
        if ф is not None and not ф.closed:
            ф.close()

    __del__ = закрыть
