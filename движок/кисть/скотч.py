"""Н-3: скотч-трафарет — малярная лента на холсте (`Холст.скотч`, `Холст.снять_скотч`).

Лента лежит на холсте там, где маска истинна. Краска мазков поверх неё ложится на ленту: под лентой слои
холста (все или один — `слой`) на это время пусты, а что в них было, лента держит у себя. Кромка ленты — ступенька
её высоты: кисть видит её тем же рельефом, что зерно грунта (`зерно.по_зерну`), — с ленты волосок сходит не
обрывом, у кромки на холсте он до дна не достаёт, пока нажим слаб; густая полная кисть кроет и тут.

Снятие: под лентой — что было до неё, бит в бит; краска на ленте уходит с ней. Физика у кромки:
- затёк — текучая краска (разбавитель, `ровно`), легшая у самой кромки, затекает под ленту на доли мм, тем глубже,
  чем больше нажим; густая и сухая не затекает. Глубину каждый мазок пишет ленте у своей кромки (`Лента.затекло`);
- разрыв — сырой пастоз, лёгший через кромку одной плёнкой, при снятии рвётся: у кромки часть его тела уходит с
  лентой, на глубину по толщине моста; сухое (`подсушить`) и схватившееся режется ровно.

Ни шума формы, ни случайного разброса здесь нет: неровность кромки — от борозд и толщины самой краски."""
import base64
import zlib

import numpy as np

from .холст import ММ_НА_H, Слой
from .мм import РОДНОЙ

ВЫСОТА_ММ = 0.1        # толщина малярной ленты по умолчанию, мм (0,25 h)
_ЗАТЁК = (0.2, 0.5, 0.5, 0.08)   # затёк: до стольких мм под ленту; доля от нажима (0,5 + 0,5·нажим); текучесть (разбавитель, ровно), с которой затёк полный; столько h свежей краски у кромки — затёк полный
_РАЗРЫВ = (0.25, 0.30, 0.50, 0.7, 0.5)   # разрыв: до стольких мм от кромки; мост тоньше стольких h не рвётся; на столько h сверх — разрыв полный; столько свежего тела уходит с лентой у самой кромки; на столько падает покрытие там, где тело ушло целиком
_ОБРЫВ = (0.15, 0.7, 0.35, 0.6)   # волосок, сходящий с ленты, касается холста не сразу: на стольких мм за кромкой при нажиме 0,6 и ленте 0,1 мм (с нажимом — короче, как 1,3 − нажим); столько тела и столько покрытия хода нет у самой кромки; густая краска висит на кончиках и мост держит, текучая затягивает щель — на эту долю короче
_ВАЛИК = (0.2, 0.35, 2.0, 0.15, 0.45)   # кисть, идущая на ленту, о её стенку сгребает краску кончиков: валик шириной столько мм у кромки на холсте; столько краски, что легла бы на ленту в первых px (их столько) за кромкой, сгребается при густой краске и нажиме 1; густота — тело свежей краски сверх стольких h, полная — ещё на столько
_ПОЛЕ = 6              # px вокруг ленты, что она держит у себя (сырой разрыв и сверка)
_КОЛЬЦО = 2.0          # px снаружи у кромки: краска, легшая сюда, затекает под ленту
_ВВЕРХ = 3.0           # px: откуда пришёл волосок — столько назад по ходу (на ленте ли он был)
_СГЛАДИТЬ = 1.0        # σ px: кромка ленты — линия, а не лесенка пикселей маски (доля ленты в пикселе кромки)


def _edt(маска, индексы=False):
    from scipy import ndimage
    return ndimage.distance_transform_edt(маска, return_indices=индексы)


def маска_в_строку(маска):
    """bool H×W -> строка журнала: zlib(packbits) в base64."""
    return base64.b64encode(zlib.compress(np.packbits(np.asarray(маска, bool), axis=None).tobytes(), 9)).decode('ascii')


def маска_из_строки(строка, форма):
    в, ш = (int(v) for v in форма)
    биты = np.frombuffer(zlib.decompress(base64.b64decode(строка)), np.uint8)
    return np.unpackbits(биты, count=в * ш).astype(bool).reshape(в, ш)


def в_размер(маска, высота, ширина):
    """Маска журнала другого масштаба (повтор `--scale`) — ближайшим пикселем."""
    if маска.shape == (высота, ширина):
        return маска
    iy = np.minimum((np.arange(высота) + 0.5) * маска.shape[0] / высота, маска.shape[0] - 1).astype(np.intp)
    ix = np.minimum((np.arange(ширина) + 0.5) * маска.shape[1] / ширина, маска.shape[1] - 1).astype(np.intp)
    return маска[iy][:, ix]


class Лента:
    """Одна лента: имя, маска (bool, весь холст), слой (None — все слои), высота (h), рамка поля (y0, y1, x0, x1 холста),
    что было в слоях в рамке до ленты (`под`), затёк по кромке (px, в рамке)."""

    def __init__(self, имя, маска, слой, высота_мм):
        self.имя, self.слой = str(имя), слой
        self.маска = np.asarray(маска, bool)
        self.высота_мм = float(высота_мм)
        self.высота = self.высота_мм / ММ_НА_H
        ys, xs = np.nonzero(self.маска)
        в, ш = self.маска.shape
        self.рамка = (max(int(ys.min()) - _ПОЛЕ, 0), min(int(ys.max()) + 1 + _ПОЛЕ, в),
                      max(int(xs.min()) - _ПОЛЕ, 0), min(int(xs.max()) + 1 + _ПОЛЕ, ш))
        y0, y1, x0, x1 = self.рамка
        м = self.маска[y0:y1, x0:x1]
        d_вне, (iy, ix) = _edt(~м, индексы=True)
        d_под = _edt(м)
        self.кольцо = ~м & (d_вне <= _КОЛЬЦО)
        self.к_ленте = (iy.astype(np.int32), ix.astype(np.int32))      # снаружи — ближайший пиксель ленты
        from scipy import ndimage
        b = np.where(м, -(d_под - 0.5), d_вне - 0.5).astype(np.float32)   # px от кромки: снаружи +, под лентой −
        self.от_кромки = b
        bs = ndimage.gaussian_filter(b, _СГЛАДИТЬ, mode='nearest')
        gy, gx = np.gradient(bs)
        н = np.maximum(np.hypot(gx, gy), 1e-6)
        self.нормаль = ((-gx / н).astype(np.float32), (-gy / н).astype(np.float32))   # к ленте
        # доля ленты в пикселе кромки — по сглаженной линии, только в пикселях маски: краска за кромкой — вся, а пиксель
        # ленты на лесенке маски — часть его вне ленты, она несёт краску (кромка — линия, а не лесенка)
        self.доля = np.where(м, np.clip(0.5 - bs, 0.0, 1.0), 0.0).astype(np.float32)
        self.затёк = np.zeros(м.shape, np.float32)
        self.под = {}          # имя слоя -> {поле: массив рамки}; слоя, которого не было, нет

    def __repr__(self):
        return (f'лента «{self.имя}»: {int(self.маска.sum())} px, высота {self.высота_мм:g} мм, '
                + ('все слои' if self.слой is None else f'слой «{self.слой}»'))

    def ловит(self, слой):
        return self.слой is None or слой == self.слой

    def м(self):
        y0, y1, x0, x1 = self.рамка
        return self.маска[y0:y1, x0:x1]

    def рельеф(self, x0, y0, x1, y1):
        """Высота ленты (h) в прямоугольнике холста (может выходить за край)."""
        t = np.zeros((y1 - y0, x1 - x0), np.float32)
        в, ш = self.маска.shape
        xa, ya, xb, yb = max(x0, 0), max(y0, 0), min(x1, ш), min(y1, в)
        if xb > xa and yb > ya:
            t[ya - y0:yb - y0, xa - x0:xb - x0] = self.маска[ya:yb, xa:xb] * np.float32(self.высота)
        return t

    def затекло(self, прямоугольник, до, после, текучесть, нажим, px_на_мм):
        """После мазка: свежая краска (после − до, h) в прямоугольнике холста (y0, y1, x0, x1) у кромки снаружи
        затекает под ленту — глубина (px) в кольцо кромки."""
        if текучесть <= 0.0:
            return
        y0, y1, x0, x1 = прямоугольник
        ry0, ry1, rx0, rx1 = self.рамка
        ya, yb, xa, xb = max(y0, ry0), min(y1, ry1), max(x0, rx0), min(x1, rx1)
        if yb <= ya or xb <= xa:
            return
        с = (slice(ya - y0, yb - y0), slice(xa - x0, xb - x0))
        р = (slice(ya - ry0, yb - ry0), slice(xa - rx0, xb - rx0))
        свежая = np.maximum(после[с] - до[с], 0.0)
        глубь = (_ЗАТЁК[0] * (px_на_мм or РОДНОЙ) * (0.5 + 0.5 * float(нажим)) * min(float(текучесть) / _ЗАТЁК[2], 1.0)
                 * np.clip(свежая / _ЗАТЁК[3], 0.0, 1.0))
        глубь = np.where(self.кольцо[р], глубь, 0.0).astype(np.float32)
        np.maximum(self.затёк[р], глубь, out=self.затёк[р])


def _направления(точки):
    т = np.asarray(точки, np.float64)
    if т.ndim != 2 or len(т) < 2:
        return None
    д = np.gradient(т[:, :2], axis=0)
    н = np.hypot(д[:, 0], д[:, 1])
    if not (н > 1e-9).any():
        return None
    д = np.where(н[:, None] > 1e-9, д / np.maximum(н, 1e-12)[:, None], 0.0)
    return т, д


def у_кромки(лента, с, прям, до_h, до_a, точки, px_на_мм, разбавитель, текучесть=0.0, угол=(0, 0)):
    """После мазка в слой `с`, у кромки ленты на холсте: обрыв — волосок, сошедший с ленты, касается холста не сразу
    (щель короче с нажимом и у густой краски); валик — кисть, идущая на ленту, сгребает краску кончиков о её стенку
    к кромке (больше с нажимом и густотой). Откуда и куда шёл волосок — по ходу кисти у этого места."""
    нд = _направления(точки)
    if нд is None:
        return
    т, д = нд
    y0, y1, x0, x1 = прям
    ry0, ry1, rx0, rx1 = лента.рамка
    ya, yb, xa, xb = max(y0, ry0), min(y1, ry1), max(x0, rx0), min(x1, rx1)
    if yb <= ya or xb <= xa:
        return
    сл = (slice(ya - y0, yb - y0), slice(xa - x0, xb - x0))
    р = (slice(ya - ry0, yb - ry0), slice(xa - rx0, xb - rx0))
    м, b = лента.м()[р], лента.от_кромки[р]
    полоса = ~м & (b < 3.0)
    if not полоса.any():
        return
    оy, оx = угол                                                     # угол массивов слоя на холсте (участок)
    м_ = (slice(ya - оy, yb - оy), slice(xa - оx, xb - оx))
    h = np.array(с.толщина[м_]); a = np.array(с.покрытие[м_])
    h0, a0 = до_h[сл], до_a[сл]
    свежая = np.maximum(h - h0, 0.0)
    свежее_а = np.maximum(a - a0, 0.0)
    if not (свежая[полоса] > 0.0).any():
        return
    мм = px_на_мм or РОДНОЙ
    py, px = np.nonzero(полоса)
    X, Y = px + xa + 0.5, py + ya + 0.5
    # ближайшая точка хода — его направление и нажим здесь
    ближ = np.empty(len(X), np.intp)
    for i in range(0, len(X), 4096):
        dx = X[i:i + 4096, None] - т[None, :, 0]
        dy = Y[i:i + 4096, None] - т[None, :, 1]
        ближ[i:i + 4096] = np.argmin(dx * dx + dy * dy, axis=1)
    dx_, dy_ = д[ближ, 0], д[ближ, 1]
    нажим = т[ближ, 2] if т.shape[1] > 2 else np.full(len(X), 0.85)
    в, ш = лента.маска.shape
    def на_ленте(x, y):
        ix = np.clip(np.floor(x).astype(np.intp), 0, ш - 1)
        iy = np.clip(np.floor(y).astype(np.intp), 0, в - 1)
        return лента.маска[iy, ix] & (x >= 0) & (x < ш) & (y >= 0) & (y < в)
    пришёл = на_ленте(X - dx_ * _ВВЕРХ, Y - dy_ * _ВВЕРХ)      # волосок пришёл с ленты
    уходит = на_ленте(X + dx_ * _ВВЕРХ, Y + dy_ * _ВВЕРХ)      # волосок идёт на ленту
    нх, ну = лента.нормаль[0][р][py, px], лента.нормаль[1][р][py, px]
    кос = np.abs(dx_ * нх + dy_ * ну)
    iy_л, ix_л = лента.к_ленте[0][р][py, px] - (ya - ry0), лента.к_ленте[1][р][py, px] - (xa - rx0)
    есть_л = (iy_л >= 0) & (iy_л < yb - ya) & (ix_л >= 0) & (ix_л < xb - xa)
    iy_л, ix_л = np.clip(iy_л, 0, yb - ya - 1), np.clip(ix_л, 0, xb - xa - 1)
    тело_л = np.where(есть_л, свежая[iy_л, ix_л], 0.0)                 # краска хода на ленте у этого места
    тело = np.maximum(свежая[py, px], тело_л)
    густо = np.clip((тело - _ВАЛИК[3]) / _ВАЛИК[4], 0.0, 1.0) * (1.0 - float(разбавитель or 0.0))
    bb = b[py, px]
    dh = np.zeros(len(X)); da = np.zeros(len(X))
    # обрыв: сошедший с ленты волосок касается холста за щелью
    течёт = min(float(текучесть) / _ЗАТЁК[2], 1.0)                  # текучая краска щель затягивает
    щель = (_ОБРЫВ[0] * мм * (лента.высота_мм / 0.1) * np.clip(1.3 - нажим, 0.1, 1.0) / 0.7 * (1.0 - _ОБРЫВ[3] * густо)
            * (1.0 - _ОБРЫВ[3] * течёт))
    s_о = np.where(пришёл & ~уходит, np.clip(1.0 - bb / np.maximum(щель, 1e-6), 0.0, 1.0) * кос, 0.0)
    dh -= свежая[py, px] * _ОБРЫВ[1] * s_о
    da -= свежее_а[py, px] * _ОБРЫВ[2] * s_о
    # валик: идущая на ленту кисть сгребает краску о стенку к кромке
    r = max(_ВАЛИК[0] * мм, 1.0)
    s_в = np.where(уходит & ~пришёл & (bb < r), 2.0 * (1.0 - bb / r) * кос, 0.0)
    вал = _ВАЛИК[1] * густо * np.clip(нажим, 0.0, 1.0) * тело_л * (_ВАЛИК[2] / r) * s_в
    dh += вал
    da += (1.0 - a[py, px]) * np.clip(вал / 0.15, 0.0, 1.0)
    if not (dh != 0.0).any():
        return
    ц = np.array(с.цвет[м_])
    if (вал > 0).any():
        цв = ц[iy_л, ix_л]
        w = (вал / np.maximum(h[py, px] + вал, 1e-9))[:, None]
        ц[py, px] = ц[py, px] * (1.0 - w) + цв * w
        с.цвет[м_] = ц.astype(np.float32)
    h[py, px] = np.maximum(h[py, px] + dh, h0[py, px])
    a[py, px] = np.clip(a[py, px] + da, a0[py, px], 1.0)
    с.толщина[м_] = h.astype(np.float32)
    с.покрытие[м_] = a.astype(np.float32)


def _поля(с):
    return [п for п in Слой._ВСЕ if getattr(с, п) is not None]


def положить(х, лента):
    """Лента ложится: что было в её слоях в рамке — ей; под маской слои пусты."""
    y0, y1, x0, x1 = (лента.рамка[0] - х.y0, лента.рамка[1] - х.y0, лента.рамка[2] - х.x0, лента.рамка[3] - х.x0)
    где = (slice(y0, y1), slice(x0, x1))
    м = лента.м()
    for имя, с in х._слои.items():
        if not лента.ловит(имя):
            continue
        лента.под[имя] = {п: np.array(getattr(с, п)[где]) for п in _поля(с)}
        for п in _поля(с):
            a = np.array(getattr(с, п)[где])
            пусто = Слой._ПУСТО.get(п, 0.0)
            a[м] = пусто
            getattr(с, п)[где] = a


def _поверх(низ, верх, w):
    """Краска `верх` (поля слоя) долей w поверх `низ` — тот же слой: покрытие и цвет «поверх», тело в сумме."""
    a_в = верх['покрытие'] * w
    a_н = низ['покрытие']
    a = a_в + a_н * (1.0 - a_в)
    о = {'покрытие': a, 'толщина': низ['толщина'] + верх['толщина'] * w,
         'цвет': (верх['цвет'] * a_в[..., None] + низ['цвет'] * (a_н * (1.0 - a_в))[..., None]) / np.maximum(a, 1e-6)[..., None],
         'влажность': np.where(a_в > 0.0, np.maximum(низ['влажность'], верх['влажность']), низ['влажность']),
         'схват': np.where(a_в > 0.0, np.minimum(низ['схват'], верх['схват']), низ['схват'])}
    о['цвет'] = np.where((a > 0.0)[..., None], о['цвет'], низ['цвет'])
    if 'пропуск' in низ:
        о['пропуск'] = низ['пропуск'] * (1.0 - a_в[..., None]) + верх['пропуск'] * a_в[..., None]
    if 'текучая' in низ:
        о['текучая'] = np.where(a_в > 0.0, np.maximum(низ['текучая'], верх['текучая']), низ['текучая'])
    return о


def снять(х, лента):
    """Лента уходит: краска на ней — с ней; под ней — что было, бит в бит; у кромки — затёк и разрыв (`скотч.py`).
    Ответ — {'затёк': px площади под лентой с затёком, 'разрыв': px у кромки, где сырой пастоз ушёл с лентой}."""
    ry0, ry1, rx0, rx1 = лента.рамка
    где = (slice(ry0 - х.y0, ry1 - х.y0), slice(rx0 - х.x0, rx1 - х.x0))
    м = лента.м()
    мм = х.px_на_мм or РОДНОЙ
    # до снятия: что лежит на ленте и у кромки; расстояния и ближайшие пиксели через кромку
    d_вне, (iy_в, ix_в) = _edt(~м, индексы=True)          # снаружи — до ближайшего пикселя ленты
    d_под, (iy_н, ix_н) = _edt(м, индексы=True)            # под лентой — до ближайшего пикселя снаружи
    итог = {'затёк': 0, 'разрыв': 0}
    затёк = лента.затёк[iy_н, ix_н]                         # глубина затёка у ближайшей точки кромки снаружи
    в_затёке = м & (затёк > 0.0) & (d_под - 0.5 < затёк)
    сила_затёка = np.where(в_затёке, np.clip(1.0 - (d_под - 0.5) / np.maximum(затёк, 1e-6), 0.0, 1.0), 0.0)
    разрыв_px = _РАЗРЫВ[0] * мм
    рядом = ~м & (d_вне - 0.5 < разрыв_px)
    затронуто_разрывом = np.zeros(м.shape, bool)
    затронуто_затёком = np.zeros(м.shape, bool)
    for имя, с in х._слои.items():
        if not лента.ловит(имя):
            continue
        поля = _поля(с)
        сейчас = {п: np.array(getattr(с, п)[где]) for п in поля}
        было = лента.под.get(имя)
        if было is None:                                     # слой заведён по ленте: под ней не было ничего
            было = {п: np.full(сейчас[п].shape, Слой._ПУСТО.get(п, 0.0), np.float32) for п in поля}
        else:
            было = {п: (было[п] if п in было else np.full(сейчас[п].shape, Слой._ПУСТО.get(п, 0.0), np.float32)) for п in поля}
        h, h0 = сейчас['толщина'], было['толщина']
        свежая = np.where(м, h, np.maximum(h - h0, 0.0))     # что легло после ленты: снаружи — сверх прежнего, на ленте — всё
        свежее_а = np.where(м, сейчас['покрытие'], (сейчас['покрытие'] - было['покрытие']).clip(0.0))
        сыро = свежая * сейчас['влажность'] * (1.0 - сейчас['схват'])
        новое = {п: сейчас[п].copy() for п in поля}
        # разрыв: сырой мост через кромку — тоньше из двух сторон
        if рядом.any():
            мост = np.minimum(сыро, сыро[iy_в, ix_в])
            глубь = разрыв_px * np.clip((мост - _РАЗРЫВ[1]) / _РАЗРЫВ[2], 0.0, 1.0)
            f = np.where(рядом & (глубь > 0.0), np.clip(1.0 - (d_вне - 0.5) / np.maximum(глубь, 1e-6), 0.0, 1.0), 0.0)
            if f.any():
                ушло = _РАЗРЫВ[3] * f
                новое['толщина'] = h - свежая * ушло
                новое['покрытие'] = сейчас['покрытие'] - свежее_а * _РАЗРЫВ[4] * ушло * ушло
                затронуто_разрывом |= f > 0.0
        # под лентой — что было; пиксель кромки — по доле ленты в нём (кромка — линия, не лесенка маски): его доля
        # вне ленты под маской несёт краску, что легла на ленту, поверх прежнего
        t = лента.доля
        кромка_под = м & (t < 1.0)
        if кромка_под.any():
            лег = _поверх(было, сейчас, 1.0)
            for п in поля:
                кп = кромка_под[..., None] if новое[п].ndim == 3 else кромка_под
                новое[п] = np.where(кп, лег[п], новое[п])
        for п in поля:
            tt = t[..., None] if новое[п].ndim == 3 else t
            смесь = было[п] * tt + новое[п] * (1.0 - tt)
            новое[п] = np.where(tt >= 1.0, было[п], np.where(tt <= 0.0, новое[п], смесь))
        # затёк: свежая краска у кромки снаружи — под ленту, на долю по глубине
        if в_затёке.any():
            w = сила_затёка
            a_с = свежее_а[iy_н, ix_н] * w
            h_с = свежая[iy_н, ix_н] * w
            есть = в_затёке & (h_с > 0.0) & (a_с > 0.0)
            if есть.any():
                a = новое['покрытие']
                a_нов = a + a_с * (1.0 - a)
                ц_с = сейчас['цвет'][iy_н, ix_н]
                ц = (новое['цвет'] * (a * (1.0 - a_с))[..., None] + ц_с * a_с[..., None]) / np.maximum(a_нов, 1e-6)[..., None]
                новое['цвет'] = np.where(есть[..., None], ц, новое['цвет'])
                новое['покрытие'] = np.where(есть, a_нов, a)
                новое['толщина'] = np.where(есть, новое['толщина'] + h_с, новое['толщина'])
                новое['влажность'] = np.where(есть, np.maximum(новое['влажность'], сейчас['влажность'][iy_н, ix_н]), новое['влажность'])
                новое['схват'] = np.where(есть, np.minimum(новое['схват'], сейчас['схват'][iy_н, ix_н]), новое['схват'])
                if 'пропуск' in новое:
                    п_с = сейчас['пропуск'][iy_н, ix_н]
                    новое['пропуск'] = np.where(есть[..., None], новое['пропуск'] * (1.0 - a_с[..., None]) + п_с * a_с[..., None], новое['пропуск'])
                if 'текучая' in новое:
                    новое['текучая'] = np.where(есть, np.maximum(новое['текучая'], сейчас['текучая'][iy_н, ix_н]), новое['текучая'])
                затронуто_затёком |= есть
        for п in поля:
            getattr(с, п)[где] = новое[п].astype(np.float32)
    итог['затёк'] = int(затронуто_затёком.sum())
    итог['разрыв'] = int(затронуто_разрывом.sum())
    return итог
