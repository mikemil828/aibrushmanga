НАМЕШАНО = 'намешано'     # Нт-5: раскладка набора — краски смешаны на кисти до хода, каждый волосок несёт смесь по долям


def намешать(краски):
    """Нт-5, раскладка 'намешано': краски набора, размешанные на кисти, -> одна краска (список из одной пары, доля 1).
    Цвет — смесь пигментов по долям тем же счётом, что `краска.смешать` (Кубелка — Мунк: K и S красок складываются по
    долям); для двух красок — ровно `смешать(a, b, доля_b)`. Вид — по долям, как у набора (`инструмент._с_видом`:
    мутность — средняя по долям). Медиум (`краска.МЕДИУМ`, без пигмента) в цвет не идёт — разбавляет: цвет — смесь
    остальных по их долям, мутность ниже на его долю; набор из одних медиумов — медиум."""
    from .краска import в_кс, из_кс
    if len(краски) <= 1:
        return краски
    медиум = getattr(краски, 'без_пигмента', None) or (False,) * len(краски)
    доли = np.array([0.0 if м else д for (_, д), м in zip(краски, медиум)], dtype=np.float64)
    if доли.sum() <= 0.0:                                # одни медиумы: бесцветная плёнка, как один медиум
        цвет, доли = np.asarray(краски[0][0], np.float64), None
    else:
        доли = доли / доли.sum()
        кс = sum(д * в_кс(np.asarray(c, np.float64)) for (c, _), д in zip(краски, доли))
        цвет = из_кс(кс)
    if hasattr(краски, 'мутность'):                       # не кроющая в наборе: та же средняя мутность (`_с_видом`)
        итог = type(краски)([(цвет, 1.0)])
        итог.мутность = краски.мутность
        if доли is None:
            итог.медиум = True
        return итог
    return [(цвет, 1.0)]


def _раскладка(краски, раскладка, с, Nc, ds_к, rng, густо=0.0, ширина_полос=None):
    """Какая краска на каком гребне в каждой точке пути: номера (Nc, nr).

    густо — насколько краска густая (0..1): густая с гребня на гребень по кисти не переползает,
    граница полос стоит на своём волоске весь мазок; у жидкой она плывёт вдоль хода."""
    n = len(краски)
    nr = с.nr
    if n == 1:
        return np.zeros((Nc, nr), dtype=np.intp)
    доли = np.array([д for _, д in краски])
    W = с.W
    if раскладка == 'смесь':
        # волоски несут случайную из красок по долям; соседние чаще одну
        номера = np.empty(nr, dtype=np.intp)
        номера[0] = rng.choice(n, p=доли)
        for k in range(1, nr):
            номера[k] = номера[k - 1] if rng.random() < 0.55 else rng.choice(n, p=доли)
        return np.broadcast_to(номера, (Nc, nr))
    if раскладка == 'кончик':
        # первая краска — на всей кисти; остальные набраны углом: только с одного края
        знак = 1.0 if rng.random() < 0.5 else -1.0
        место = (знак * с.центр / W + 0.5)                    # 0 — «тот» край, 1 — дальний
        край = np.cumsum(доли[:0:-1])[::-1] if n > 1 else np.zeros(0)
        ход = _шум(rng, Nc, n - 1, 90.0 / ds_к) * 0.035
        границы = np.concatenate([край[None, :] + ход + 0.03 * rng.standard_normal(n - 1)[None, :],
                                  np.zeros((Nc, 1))], axis=1)   # убывают: [доля 2..n, доля 3..n, ..., 0]
        номера = np.zeros((Nc, nr), dtype=np.intp)
        for q in range(1, n):
            номера[место[None, :] < границы[:, q - 1:q]] = q
        return номера
    if раскладка not in ('полосы', 'ряд'):
        raise ValueError(f"раскладка: 'полосы', 'ряд', 'смесь', 'кончик' или {НАМЕШАНО!r}")
    # полосы поперёк кисти: в случайном порядке ('полосы') или в заданном, слева направо по ходу ('ряд');
    # границы неровные и плывут вдоль мазка
    if ширина_полос:
        # п. 13: кисть набрана не по разу каждой краской, а мелко — краски лежат на ворсе полосками заданной ширины
        # (px холста), чередуясь; ширина полоски гуляет, у краски с меньшей долей полоски уже. Граница стоит на своём
        # гребне весь мазок (густая краска по ворсу не ползёт); рвётся полоска вдоль хода — в `_набор` (`кусок`)
        номера = np.empty(nr, dtype=np.intp)
        q = int(rng.choice(n, p=доли / доли.sum())) if раскладка == 'полосы' else n - 1
        край = -W / 2
        до = край + ширина_полос * n * доли[q] / доли.sum() * float(np.exp(0.35 * rng.standard_normal())) * rng.uniform(0.3, 1.0)
        for k in np.argsort(с.центр):
            while с.центр[k] > до:
                q = (q + (1 + int(rng.integers(0, n - 1)) if раскладка == 'полосы' and n > 2 else 1)) % n if раскладка == 'полосы' else (q - 1) % n
                до += max(ширина_полос * n * доли[q] / доли.sum() * float(np.exp(0.35 * rng.standard_normal())), 1.0)
            номера[k] = q
        return np.broadcast_to(номера, (Nc, nr))
    порядок = rng.permutation(n) if раскладка == 'полосы' else np.arange(n)[::-1]
    границы = np.cumsum(доли[порядок])[:-1]
    границы = границы[None, :] + _шум(rng, Nc, n - 1, 110.0 / ds_к) * (0.05 * (1.0 - густо)) \
        + 0.03 * rng.standard_normal(n - 1)[None, :]
    место = с.центр / W + 0.5 + 0.02 * rng.standard_normal(nr)
    полоса = (место[None, :, None] > границы[:, None, :]).sum(axis=2)
    return порядок[полоса]


def _сход_по(sc, a, b, кромка):
    """К7б: доля хода sc, где краски пряди нет, — от a до b (b = inf — до конца хода), со сходом на длине кромка (px)
    на каждом краю, серединой там, где был бы срез. Разность двух гладких ступеней: площадь — ровно b − a, и разрыв
    короче кромки до полной соседней краски не доходит, а редеет. a, b — числа или по гребням (nr,): ответ (Nc, nr)."""
    h = 0.5 * max(float(кромка), 1e-6)
    a, b = np.asarray(a, dtype=np.float64), np.asarray(b, dtype=np.float64)
    s = np.asarray(sc, dtype=np.float64).reshape((-1,) + (1,) * max(a.ndim, b.ndim))

    def ступень(x):                                           # гладкая ступень 0→1 на [−h, h]
        t = зажать((x + h) / (2.0 * h), 0.0, 1.0)
        return t * t * (3.0 - 2.0 * t)

    return ступень(s - a) - ступень(s - b)


def _штрих(с, sc, rng, W, порог, внутри_к=None):
    """Тонкое место гребня (п. 2г): запас пустеет и возвращается на длине 0,35 ширины (не короче 9 px) — штрих вдоль
    хода, 0..1 по (Nc, nr). Сытая кисть у самого входа кроет: первые 3–6 px тонкого места нет. Крайние гребни —
    отдельно (`_край`)."""
    Nc = len(sc)
    шаг_к = max(float(sc[1] - sc[0]), 1e-3) if Nc > 1 else 2.0
    if внутри_к is None:
        внутри_к = с.расст * W / 2 < W / 2 - 3.0
    штрих = зажать((_шум(rng, Nc, с.nr, max(0.35 * W, 9.0) / шаг_к) - порог) / _ШТРИХ[1], 0.0, 1.0)
    return штрих * штрих * (3.0 - 2.0 * штрих) * внутри_к[None, :] * зажать((sc - 3.0) / 3.0, 0.0, 1.0)[:, None]


def _набор(полоса, с, путь, ic, p, rng, W, n, доли, rng_д, кусок=None, расход=None):
    """Как густые несмешанные краски набраны на кисть (версия 3, п. 2в). Краски взяты с палитры рядом и не
    размешаны: у прядей одной полосы запас разный, узкая полоса кончается раньше удара или рвётся (её место
    занимает соседняя краска или борозда до лежащего слоя); в прядях есть гребни соседней краски — прожилки;
    слой гребня вдоль хода то толще, то тоньше. На дуге снаружи слой тоньше и рвётся раньше, внутри гуще.
    П. 2г: прожилка — в главной полосе (краска с наибольшей долей в вызове, от 45 %) и уже у входа; тонкое
    место — штрих. доли — доли красок из вызова.

    полоса — номер краски на каждом гребне в начале мазка. Ответ, всё (Nc, nr), кроме соседа:
    жилка — насколько гребень кладёт соседнюю краску вместо своей; сосед — её номер (nr,);
    обрыв — 1, где гребень кладёт, 0 — где его краска кончилась и под ним борозда; тонко — множитель слоя.
    К7б: прядь кончается не срезом поперёк хода, а сходом: краски на волосе становится меньше на той длине, на которой
    пустеющий слой тоньшает (конец запаса — 0,5 ширины, разрыв — край `редеет`, 0,3 ширины; комок — 0,3 его длины), и
    соседняя краска (или борозда) входит по мере того, как своя тает. Сход стоит серединой там, где был срез (`_сход_по`):
    соседней краски в куске столько же, у каждого гребня свой край — по его запасу."""
    nr, ns = с.nr, с.ns
    Nc = len(ic)
    s0 = путь['s'][int(np.argmax(p > 0.02))]
    sc = путь['s'][ic] - s0                                   # px пути от касания
    L = max(float(sc[-1]), 1.0)
    шаг_к = max(float(sc[1] - sc[0]), 1e-3) if Nc > 1 else 2.0
    # соседние краски слева и справа: прожилка — чаще ближней
    лев = np.full(nr, -1)
    прав = np.full(nr, -1)
    дл = np.full(nr, 1e9)
    дп = np.full(nr, 1e9)
    for r in range(nr):
        i = np.nonzero(полоса[:r] != полоса[r])[0]
        if len(i):
            лев[r], дл[r] = полоса[i[-1]], с.центр[r] - с.центр[i[-1]]
        i = np.nonzero(полоса[r + 1:] != полоса[r])[0]
        if len(i):
            прав[r], дп[r] = полоса[r + 1 + i[0]], с.центр[r + 1 + i[0]] - с.центр[r]
    вл = np.where(лев >= 0, np.exp(-дл / (0.3 * W)), 0.0)
    вп = np.where(прав >= 0, np.exp(-дп / (0.3 * W)), 0.0)
    сосед = np.where(rng.random(nr) * (вл + вп) < вл, лев, прав)
    сосед = np.where(сосед >= 0, сосед, полоса)
    ширина_пол = np.array([2.0 * с.полуш[полоса == q].sum() for q in range(n)]) / W
    узкая = ширина_пол[полоса] < 0.15
    # дуга: + — внутренняя сторона (гребень сдвинут к центру поворота)
    ds = путь['ds']
    кр = _окно(np.gradient(путь['ход'], ds), int(0.5 * W / ds))
    кр_ср = float(np.mean(кр[p > 0.1])) if (p > 0.1).any() else 0.0
    внутрь = кр[ic][:, None] * с.центр[None, :]
    # слой гребня вдоль хода: запас на прядях лежит неровно
    # у входа кисть сыта и кроет; неровность запаса проступает, когда краска с гребней сходит
    сход = (0.6 + 0.4 * зажать(sc / (3.0 * W), 0.0, 1.0))[:, None]
    тонко = 1.0 + сход * (0.40 * _шум(rng, Nc, ns, W / шаг_к)[:, с.прядь] + 0.28 * _шум(rng, Nc, nr, 0.4 * W / шаг_к))
    тонко *= зажать(1.0 + 1.0 * внутрь, 0.55, 1.45)
    # на сколько хватает краски полосы у каждой пряди, px
    u = rng.random(ns)[с.прядь]
    длина = np.where(узкая, W * (0.6 + 1.6 * u), W * (3.0 + 6.0 * u)) * np.exp(0.15 * rng.standard_normal(nr))
    длина *= зажать(1.0 + 2.5 * кр_ср * с.центр, 0.35, 1.3)
    # К7б: своя краска гребня сходит на той же длине, на которой пустеющий слой тоньшает (0,5 ширины), серединой — у конца запаса
    пропуск = _сход_по(sc, длина, np.inf, 0.5 * W)
    тонко *= зажать((длина[None, :] - sc[:, None]) / (0.5 * W), 0.3, 1.0)     # пустея, слой тоньше
    # прядь рвётся: узкая полоса где угодно, широкая — когда сытость у входа прошла (больше ширины хода)
    редеет = np.zeros((Nc, nr))
    for q in range(ns):
        свои = np.nonzero(с.прядь == q)[0]
        узко = узкая[свои].any()
        с_какого = 0.15 * L if узко else max(0.15 * L, 1.2 * W)
        if с_какого >= 0.8 * L:
            continue
        for _ in range(rng.poisson((0.8 * L - с_какого) / (2.0 * W) * (0.7 if узко else 0.3))):
            a = rng.uniform(с_какого, 0.8 * L)
            b = min(a + W * rng.uniform(0.15, 0.6), L - 0.3 * W)
            for r in свои:                                    # гребни пряди рвутся не по линейке
                ar, br = a + rng.normal(0.0, 0.12 * W), b + rng.normal(0.0, 0.12 * W)
                пропуск[:, r] = np.maximum(пропуск[:, r], _сход_по(sc, ar, br, 0.3 * W))   # К7б: сходит на краю `редеет`
                редеет[:, r] = np.maximum(редеет[:, r], _окно_по(sc, ar - 0.35 * W, br + 0.15 * W, 0.3 * W))
    тонко *= 1.0 - 0.75 * редеет                              # к разрыву слой тоньше: сквозь него лежащее
    # где краски нет: у одних прядей соседняя полоса занимает место, у других открывается борозда
    борозда = (rng.random(ns) < 0.4)[с.прядь]
    обрыв = 1.0 - пропуск * борозда[None, :]
    жилка = пропуск * (~борозда)[None, :]
    if кусок:
        # п. 13б: у кисти, набранной комками, запас пряди кончается не разом на весь остаток хода (нить соседней краски
        # или борозда до конца удара), а комками: за своей длиной комки пряди мельче и реже (ниже)
        обрыв, жилка = np.ones((Nc, nr)), np.zeros((Nc, nr))
        # п. 13: краска полосы лежит на ворсе комками, а не ровным слоем по всей длине волоса: комок сошёл на холст —
        # гребень кладёт то, что под ним (краску, набранную раньше, — соседнюю) или ничего (борозда до лежащего слоя),
        # пока по волосу не подошёл следующий. Комок — на всех гребнях своей полосы (п. 13б), у каждого гребня свой край:
        # кусок краски в следе рваный. Длина куска `кусок` (px холста) — в среднем, при обычном нажиме: комок сходит
        # по отданной краске (`расход` — что кисть отдала к шагу, px пути обычной руки), лёгкая рука тянет его дольше
        ход = sc if расход is None else расход
        Lх = max(float(ход[-1]), 1.0)
        кромка = 0.3 * кусок                                  # К7б: комок сходит на трети своей длины, а не срезом
        r = 0
        while r < nr:
            # п. 13б: комок сидит на всей ширине своей полосы — на всех её гребнях подряд
            вместе = 1
            while r + вместе < nr and полоса[r + вместе] == полоса[r]:
                вместе += 1
            # комки полосы вдоль волоса: начало и длина каждого; длина — сколько в комке краски (в среднем `кусок`)
            комки = []
            a = -кусок * rng.uniform(0.0, 1.5)
            хватит = float(np.interp(float(np.mean(длина[r:r + вместе])), sc, ход))   # где запас полосы на исходе
            while a < Lх:
                мало = float(зажать((a - хватит) / (4.0 * кусок), 0.0, 1.0))
                есть = кусок * float(np.exp(0.5 * rng.standard_normal())) * (1.0 - 0.45 * мало)
                комки.append((a, есть, rng.random() < 0.5))
                a += есть + кусок * rng.uniform(0.25, 1.1) * float(np.exp(0.4 * rng.standard_normal())) * (1.0 + 0.8 * мало)
            # край комка у каждого гребня свой, спереди и сзади: комок — капля, к бокам полосы короче, лежит на ворсе
            # косо, и каждый гребень несёт свою долю — больше или меньше соседа; крайнему гребню достаётся не всякий комок
            nk = len(комки)
            поперёк = (с.центр[r:r + вместе] - с.центр[r:r + вместе].mean()) / max(с.полуш[r:r + вместе].sum(), 1e-6)   # −1…1
            короче = 0.5 * (1.0 - np.sqrt(зажать(1.0 - 0.8 * поперёк ** 2, 0.0, 1.0)))[None, :] * np.array([е for _, е, _ in комки])[:, None]
            косо = rng.normal(0.0, 0.18 * кусок, (nk, 2, 1)) * поперёк[None, None, :]
            перед = короче + косо[:, 0] + rng.normal(0.0, 0.10 * кусок, (nk, вместе))
            зад = -короче + косо[:, 1] + rng.normal(0.0, 0.10 * кусок, (nk, вместе))
            мимо = np.zeros((nk, вместе), dtype=bool)
            if вместе > 2:
                мимо[:, [0, -1]] = rng.random((nk, 2)) < 0.2
            for i, j in enumerate(range(r, r + вместе)):
                конец_пред = -1e9
                for k, (a, есть, щель) in enumerate(комки):
                    if мимо[k, i]:
                        continue
                    нач = a + перед[k, i]
                    кон = max(a + есть + зад[k, i], нач + 0.35 * кусок)
                    if нач - конец_пред > 0.0 and конец_пред > -1e8:
                        w = _сход_по(ход, конец_пред, нач, кромка)
                        if щель:
                            обрыв[:, j] = обрыв[:, j] * (1.0 - w)
                        else:
                            жилка[:, j] = np.maximum(жилка[:, j], w)
                    конец_пред = max(кон, конец_пред)
                if конец_пред > -1e8 and конец_пред < Lх:
                    w = _сход_по(ход, конец_пред, np.inf, кромка)
                    if комки[-1][2]:
                        обрыв[:, j] = обрыв[:, j] * (1.0 - w)
                    else:
                        жилка[:, j] = np.maximum(жилка[:, j], w)
            r += вместе
    # прожилки (п. 2г): краска на кисти не размешана ещё до касания — гребень соседней краски кладёт её с первого
    # пикселя, а не когда своя сошла. У одних прядей примеси почти нет, у других до половины гребней. Прожилка
    # тянется вдоль хода (не короче четырёх своих ширин), начало и конец сходят на нет — на четверти её длины (К7б: не 3 px); потом гребень опять свой
    # в полосе уже трёх гребней чужой гребень или тонкое место — уже разрыв полосы (он считается выше)
    гребней = np.array([np.count_nonzero(полоса == q) for q in range(n)])[полоса]
    широкая = гребней >= 3
    внутри_к = (с.расст * W / 2 < W / 2 - 3.0) & широкая        # не у самого края кисти: край — в `_край`
    # прожилки — в главной полосе (краска, которой в вызове больше всех и не меньше 45 % кисти): она набрана
    # поверх прежних красок, и те в ней остались. Прожилка — в гребень (до 3,6 px), не у самого края кисти
    главная = (полоса == int(np.argmax(доли))) & (max(доли) >= 0.45)
    годные = (сосед != полоса) & (2.0 * с.полуш <= 3.6) & внутри_к & главная
    # краски набраны рядом: чужого больше у границы полос, к середине широкой полосы — меньше
    # (на втором-третьем гребне от неё; сам пограничный гребень чужим — это уже ступенька границы)
    до_гр = np.minimum(дл, дп)
    у_границы = np.where(до_гр < 3.5, 0.04, np.exp(-np.maximum(до_гр - 7.0, 0.0) / (0.12 * W)))
    сосед = np.where(дл < дп, лев, прав)
    сосед = np.where(сосед >= 0, сосед, полоса)
    # у одних прядей примеси почти нет, у других до половины гребней; какие гребни — решает место у границы
    примесь = 0.6 * rng.random(ns) ** 1.5
    сколько = sum(int(np.floor(примесь[q] * np.count_nonzero((с.прядь == q) & годные) + rng.random())) for q in range(ns))
    свои = np.nonzero(годные)[0]
    жилы = []
    if len(свои):
        вес = у_границы[свои] / у_границы[свои].sum()
        # в главной полосе чужой гребень есть всегда: чистой полосы с палитры не набрать
        n_пр = min(сколько, len(свои))
        жилы = [int(r) for r in rng.choice(свои, size=max(n_пр, 1), replace=False, p=вес)]
        if кусок:
            жилы = []                                         # п. 13б: чужую краску в полосе несут комки, нитью во весь ход она не идёт
    else:
        n_пр = 0
    for i, r in enumerate(жилы):
        ш = 2.0 * с.полуш[r]
        # гребень набрал чужую краску до касания: прожилка чаще идёт от самого входа
        с_входа = i >= n_пр or rng.random() < 0.65
        a = -rng.uniform(0.0, 0.2 * W) if с_входа else rng.uniform(0.0, 0.9 * W)
        while a < L:
            дл_ж = max(4.0 * ш, W * (rng.uniform(0.6, 1.4) if с_входа else rng.uniform(0.3, 1.0)))
            жилка[:, r] = np.maximum(жилка[:, r], _сход_по(sc, a, a + дл_ж, 0.25 * дл_ж))   # К7б: чужая на гребне кончается сходом
            a += дл_ж + W * rng.uniform(0.6, 2.5)
            с_входа = False
    # тонкое место (п. 2г): запас гребня пустеет и возвращается на длине хода, а не в одном пикселе — слой
    # сходит почти на нет штрихом вдоль хода, и сквозь него видно лежащее. Крайние гребни — отдельно (`_край`)
    тонко = зажать(тонко, 0.08, 1.5) * (1.0 - _ШТРИХ[2] * _штрих(с, sc, rng, W, _ШТРИХ[0], внутри_к))
    return зажать(жилка, 0.0, 1.0), сосед, обрыв, тонко, None if кусок else _жилы_по_месту(полоса, с, sc, rng_д, W, n, главная, широкая)


def _жилы_по_месту(полоса, с, sc, rng, W, n, главная, широкая):
    """Прожилка и тонкое место в часть гребня (версия 3, п. 2д). У узкой кисти на полосу два-три гребня, и чужой
    гребень целиком — уже разрыв полосы; в боковой полосе широкой кисти то же. Здесь прожилка соседней краски
    занимает 1,2–2,6 px поперёк (часть гребня), идёт вдоль хода как у широкой кисти (чаще от самого входа) и лежит
    в ближней к соседке трети полосы, не вплотную к границе; тонкое место — штрих в 1–1,8 px поперёк. Берутся
    полосы шире 5 px, кроме главной полосы широкой кисти (её прожилки — целым гребнем, в `_набор`); крайние 2 px
    кисти — дело `_край`. Ответ: (прожилка (Nc, nm), номер её краски (nm,), тонкое место (Nc, nm)) или None."""
    Nc, nm = len(sc), с.nm
    L = max(float(sc[-1]), 1.0)
    жил = np.zeros((Nc, nm))
    чья = np.zeros(nm, dtype=np.intp)
    тонк = np.zeros((Nc, nm))
    есть = False

    def поперёк(u0, ш):
        z = зажать((с.u - u0) / 0.5 + 0.5, 0.0, 1.0) * зажать((u0 + ш - с.u) / 0.5 + 0.5, 0.0, 1.0)
        return z * z * (3.0 - 2.0 * z)

    for q in range(n):
        свои = np.nonzero(полоса == q)[0]
        if len(свои) == 0:
            continue
        лев, прав = float((с.центр - с.полуш)[свои[0]]), float((с.центр + с.полуш)[свои[-1]])
        a, b = max(лев, -W / 2 + 2.0), min(прав, W / 2 - 2.0)
        if прав - лев <= 5.0 or b - a < 2.5:
            continue
        if главная[свои].any() and широкая[свои].all() and len(свои) >= 4:
            continue                                          # главная полоса широкой кисти: прожилки целым гребнем
        соседки = [(int(полоса[свои[0] - 1]), -1)] if свои[0] > 0 else []
        соседки += [(int(полоса[свои[-1] + 1]), 1)] if свои[-1] < len(полоса) - 1 else []
        if соседки and (главная[свои].any() or rng.random() < _ЖИЛА_МЕСТА[0]):
            кр, сторона = соседки[int(rng.integers(len(соседки)))]
            ш = float(зажать(rng.uniform(0.15, 0.25) * (прав - лев), 1.0, 2.6))
            отступ = rng.uniform(1.0, max(0.4 * (b - a) - ш, 1.0 + 1e-6))
            u0 = (лев + отступ) if сторона < 0 else (прав - отступ - ш)
            u0 = float(зажать(u0, a, max(b - ш, a)))
            окно_u = поперёк(u0, ш)
            # в главной полосе прожилка чаще идёт от самого входа (как у широкой кисти), в боковой — короче и реже от входа
            с_входа = rng.random() < (0.65 if главная[свои].any() else 0.3)
            x = -rng.uniform(0.0, 0.2 * W) if с_входа else rng.uniform(0.0, 0.9 * W)
            while x < L:
                дл = max(4.0 * ш, W * (rng.uniform(0.6, 1.4) if с_входа and главная[свои].any() else rng.uniform(0.3, 0.9)))
                жил = np.maximum(жил, _сход_по(sc, x, x + дл, 0.25 * дл)[:, None] * окно_u[None, :])   # К7б: сходом
                x += дл + W * rng.uniform(0.6, 2.5)
                с_входа = False
            чья[окно_u > 0] = кр
            есть = True
        if not (широкая[свои].all() and len(свои) >= 3):
            # тонкое место: у полосы в два-три гребня — часть гребня по ширине и часть хода
            x = rng.uniform(4.0, 4.0 + _ЖИЛА_МЕСТА[1] * W)
            while x < L:
                ш = rng.uniform(1.0, 1.8)
                дл = max(0.35 * W, 6.0) * rng.uniform(0.7, 1.5)
                u0 = rng.uniform(a, max(b - ш, a + 1e-6))
                тонк = np.maximum(тонк, _окно_по(sc, x, x + дл, 2.0)[:, None] * поперёк(u0, ш)[None, :])
                x += дл + rng.uniform(0.5, 1.0) * _ЖИЛА_МЕСТА[1] * W
                есть = True
    return (жил, чья, тонк) if есть else None
