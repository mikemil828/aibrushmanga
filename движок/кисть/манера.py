def _гаусс(a, σ):
    from scipy import ndimage
    return ndimage.gaussian_filter(a, σ, mode='reflect') if σ > 0 else a


class _Размытия:
    """Размытая светлота: одна σ считается один раз."""
    def __init__(self, L):
        self.L, self.было = L, {}

    def __call__(self, σ):
        if σ not in self.было:
            self.было[σ] = _гаусс(self.L, σ)
        return self.было[σ]


def _к_рабочему(rgb, px_на_мм):
    """sRGB 0–255 (В, Ш, 3) при px_на_мм -> sRGB float рабочего масштаба."""
    from PIL import Image
    k = РАБОЧИЙ / float(px_на_мм)
    a8 = np.clip(np.round(rgb), 0, 255).astype(np.uint8)
    if abs(k - 1.0) < 1e-6:
        return a8.astype(np.float64)
    ш, в = max(8, int(round(a8.shape[1] * k))), max(8, int(round(a8.shape[0] * k)))
    return np.asarray(Image.fromarray(a8).resize((ш, в), Image.LANCZOS), np.float64)


def _эфф(доли):
    p = np.asarray(доли, np.float64)
    p = p[p > 0] / p.sum()
    return float(math.exp(-(p * np.log(p)).sum())) if p.size else 0.0


def _пц(v, n=2):
    v = np.asarray(v, np.float64).ravel()
    v = v[np.isfinite(v)]
    if not v.size:
        return None
    p10, p50, p90 = np.percentile(v, [10, 50, 90])
    ср = float(v.mean())
    return {'p10': round(float(p10), n), 'p50': round(float(p50), n), 'p90': round(float(p90), n), 'ср': round(ср, n),
            'σ/ср': round(float(v.std()) / ср, 3) if ср > 1e-9 else None}


def _палитра(rgb, lab):
    сглаж = np.stack([_гаусс(lab[..., i], 0.5 * РАБОЧИЙ) for i in range(3)], -1)
    ключ = np.floor(сглаж / СТУПЕНЬ).astype(np.int64).reshape(-1, 3)
    низ = ключ.min(0)
    ряд = ключ.max(0) - низ + 1
    обр = ((ключ[:, 0] - низ[0]) * ряд[1] + ключ[:, 1] - низ[1]) * ряд[2] + ключ[:, 2] - низ[2]   # порядок — по L, a, b
    n = np.bincount(обр)
    есть = np.flatnonzero(n)
    n = n[есть]
    порядок = np.argsort(-n, kind='stable')
    доли = n[порядок] / n.sum()
    замесов = int(np.searchsorted(np.cumsum(доли), 0.9) + 1)
    главные = []
    суммы = [np.bincount(обр, rgb[..., i].ravel())[есть] for i in range(3)]      # целые: порядок суммы не важен
    for j in порядок[:8]:
        главные.append((round(float(n[j] / n.sum()), 3), глаз.шестн(np.array([с[j] for с in суммы]) / n[j])))
    return {'замесов': замесов, 'ступеней': int(len(n)), 'эфф': round(_эфф(n), 1), 'главные': главные}


def _направления(L, окно_px, размытая=None):
    Lg = (размытая or _Размытия(L))(0.5 * РАБОЧИЙ)
    gy, gx = np.gradient(Lg)
    σ = окно_px / 2.0
    шаг = max(1, int(окно_px // 2))
    сетка = скоро.Сетка(gx, σ, шаг // 2, шаг)
    Jxx, Jyy, Jxy = (сетка.размыть(v) for v in (gx * gx, gy * gy, gx * gy))
    перепад = 0.5 * np.degrees(np.arctan2(2 * Jxy, Jxx - Jyy))
    θ = (перепад + 90.0) % 180.0                                       # ход — поперёк перепада
    с = np.sqrt((Jxx - Jyy) ** 2 + 4 * Jxy ** 2) / np.maximum(Jxx + Jyy, 1e-9)
    к = np.floor(((θ + 15.0) % 180.0) / 30.0).astype(int)
    веса = np.bincount(к.ravel(), weights=с.ravel(), minlength=6)
    доли = веса / max(веса.sum(), 1e-12)
    главные = [(int(i) * 30, round(float(доли[i]), 3)) for i in np.argsort(-доли, kind='stable')[:3] if доли[i] > 0]
    z = (с * np.exp(2j * np.radians(θ))).sum() / max(с.sum(), 1e-12)
    R = float(abs(z))
    разн = []
    for a, b, ca, cb in ((θ[:, 2:], θ[:, :-2], с[:, 2:], с[:, :-2]), (θ[2:], θ[:-2], с[2:], с[:-2])):   # через окно
        d = np.abs(a - b) % 180.0
        d = np.minimum(d, 180.0 - d)
        разн.append(d[(ca > ПОРЯДОК) & (cb > ПОРЯДОК)])
    разн = np.concatenate(разн)
    сводка = {'главные': главные, 'эфф': round(_эфф(веса), 2), 'порядок': round(float(np.median(с)), 3),
              'σ': round(float(np.degrees(math.sqrt(max(-2 * math.log(max(R, 1e-12)), 0.0))) / 2), 1),
              'у соседей': round(float(np.median(разн)), 1) if разн.size else None, 'мест': int(θ.size)}
    return сводка, θ, с, шаг


def _штрих(L, θ, окно_px, шаг, предел=0.0, размытая=None):
    """Длина и ширина штриха в каждом месте: расстояние, на котором корреляция фактуры (светлота минус размытая на
    пятно) вдоль направления места и поперёк него падает до половины; сдвиги — `ЛАГИ` мм по 6 направлениям через 30°."""
    размытая = размытая or _Размытия(L)
    h = размытая(0.25 * РАБОЧИЙ) - размытая(ПЯТНО * РАБОЧИЙ / 2.0)
    σ = окно_px / 2.0
    сетка = скоро.Сетка(h, σ, шаг // 2, шаг)
    E = np.maximum(сетка.сдвиг(0, 0), 1e-9)
    C = np.ones((6, len(ЛАГИ)) + E.shape)
    вдоль_i = np.round(θ / 30.0).astype(int) % 6
    поперёк_i = (вдоль_i + 3) % 6
    for i in range(6):
        u = math.radians(30 * i)
        ждут = [вдоль_i == i, поперёк_i == i]                         # места, где корреляция ещё не упала до половины
        for j, d in enumerate(ЛАГИ):
            узлы = ждут[0] | ждут[1]
            if not узлы.any():
                break
            dx, dy = int(round(d * РАБОЧИЙ * math.cos(u))), int(round(d * РАБОЧИЙ * math.sin(u)))
            C[i, j] = сетка.сдвиг(dy, dx, узлы) / E
            ждут = [м & (C[i, j] >= 0.5) for м in ждут]
    лаг = np.log(np.asarray(ЛАГИ))

    def до_половины(c):                                    # c (лаги, …) -> мм, где корреляция падает до 0,5
        ниже = c < 0.5
        первый = np.where(ниже.any(0), np.argmax(ниже, 0), len(ЛАГИ))
        ответ = np.full(c.shape[1:], ЛАГИ[-1] * 1.0)
        for j in range(len(ЛАГИ)):
            где = первый == j
            if j == 0:
                ответ[где] = ЛАГИ[0]                     # короче первого сдвига — «до 0,5 мм»
            else:
                a, b = c[j - 1][где], c[j][где]
                t = np.clip((a - 0.5) / np.maximum(a - b, 1e-9), 0, 1)
                ответ[где] = np.exp(лаг[j - 1] + t * (лаг[j] - лаг[j - 1]))
        return ответ
    дл = до_половины(np.take_along_axis(C, вдоль_i[None, None], 0)[0])
    шир = до_половины(np.take_along_axis(C, поперёк_i[None, None], 0)[0])
    лог2 = lambda v: np.floor(np.log2(v) + 1e-9).astype(int).ravel()
    с = {'длина': _пц(дл), 'ширина': _пц(шир)}
    for к, v in (('длина', дл), ('ширина', шир)):
        с[к]['эфф'] = round(_эфф(np.unique(лог2(v), return_counts=True)[1]), 2)
        с[к]['на полу'] = round(float((v <= max(ЛАГИ[0], предел) + 1e-9).mean()), 3)
        с[к]['пол'] = max(ЛАГИ[0], round(предел, 2))
        if предел > ЛАГИ[0] and с[к]['на полу'] > НА_ПОЛУ:               # пиксель снимка, а не штрих: числа нет
            с[к].update({и: None for и in ('p10', 'p50', 'p90', 'ср', 'σ/ср', 'эфф')})
    с['до'] = ЛАГИ[-1]
    return с, дл, шир


def _ширина_мазка(L, lab, θ, ког, шаг, предел=0.0, размытая=None):
    """Ширина мазка по картинке: хорды между краями по линиям поперёк хода места (через `ЛИНИИ` мм, 6 направлений
    через 30°). Край — местный максимум перепада |c(t + 1 мм) − c(t − 1 мм)| светлоты L и a, b OKLab ×255 от
    `ПОРОГ_КРАЯ` (как у «края»), по цвету, размытому на `РАЗМЫВ`. Края, по обе стороны которых один замес (`скоро.замесы`, порог `ЗАМЕС_L`),
    хорду не рвут: ходы одного замеса внахлёст меряются одним пятном. Хорда идёт в счёт, если место у её середины — с ходом этого направления (порядок
    от `ПОРЯДОК`), её края есть и на соседней линии (±0,5 мм — лента вдоль хода) и фактура мельче `ФАКТУРА` в середине хорды
    не ровнее `ФОН`."""
    from scipy import ndimage
    В, Ш = L.shape
    размытая = размытая or _Размытия(L)
    кан = [размытая(РАЗМЫВ * РАБОЧИЙ)] + [_гаусс(lab[..., i] * 255.0, РАЗМЫВ * РАБОЧИЙ) for i in (1, 2)]
    фак, мел = (np.sqrt(_гаусс((размытая(0.25 * РАБОЧИЙ) - размытая(р * РАБОЧИЙ)) ** 2, р / 2 * РАБОЧИЙ))
                for р in (1.0, ФАКТУРА))
    k = int(round(ПЕРЕПАД * РАБОЧИЙ))
    доп = int(round(0.5 * РАБОЧИЙ))
    lo, hi = ШИРИНА_МАЗКА
    R = math.hypot(В, Ш)
    t = np.arange(-R / 2, R / 2, 1.0)
    оф = np.arange(-R / 2, R / 2, ЛИНИИ * РАБОЧИЙ)
    шир, шире, хорды = [], 0, []
    for i in range(6):
        u = math.radians(30 * i + 90)                                  # линия — поперёк хода 30·i°
        ux, uy = math.cos(u), math.sin(u)
        ряд = оф[np.abs(оф) <= 0.5 * (В * abs(ux) + Ш * abs(uy)) + 1.0, None]   # прочие линии картинки не задевают
        X = Ш / 2 + ряд * -uy + t[None] * ux
        Y = В / 2 + ряд * ux + t[None] * uy
        внутри = (X >= 0) & (X <= Ш - 1) & (Y >= 0) & (Y <= В - 1)
        годно = np.zeros_like(внутри)
        годно[:, k:-k] = внутри[:, 2 * k:] & внутри[:, :-2 * k]
        г = np.flatnonzero(годно)
        квадрат, проф = 0.0, []
        for c in кан:
            п = ndimage.map_coordinates(c, [Y.ravel(), X.ravel()], order=1, mode='nearest')
            проф.append(п)
            квадрат = квадрат + (п[г + k] - п[г - k]) ** 2
        перепад = np.zeros(X.shape)
        перепад.ravel()[г] = np.sqrt(квадрат)
        пик = (перепад >= ПОРОГ_КРАЯ) & (перепад >= ndimage.maximum_filter1d(перепад, 2 * k + 1, axis=1))
        пик[:, 1:] &= ~пик[:, :-1]                                     # из подряд — первый
        строка, e = np.nonzero(пик)
        n = X.shape[1]
        жив = скоро.замесы(проф, строка, e, k, n, ЗАМЕС, ЗАМЕС_L)
        строка, e = строка[жив], e[жив]
        r, a, b = строка[:-1], e[:-1], e[1:]
        да = (строка[1:] == r) & ((b - a) / РАБОЧИЙ >= lo)
        r, a, b = r[да], a[да], b[да]
        m = (a + b) // 2
        gi = np.clip(np.rint((Y[r, m] - шаг // 2) / шаг).astype(np.int64), 0, θ.shape[0] - 1)
        gj = np.clip(np.rint((X[r, m] - шаг // 2) / шаг).astype(np.int64), 0, θ.shape[1] - 1)
        да = (np.rint(θ[gi, gj] / 30.0).astype(np.int64) % 6 == i) & (ког[gi, gj] >= ПОРЯДОК)
        r, a, b = r[да], a[да], b[да]
        рядом = np.zeros((пик.shape[0] + 2, n), bool)                  # где на линии край ближе `доп`
        рядом[1:-1] = ndimage.maximum_filter1d(пик.astype(np.uint8), 2 * доп + 1, axis=1, mode='constant') > 0
        да = (рядом[r, a] & рядом[r, b]) | (рядом[r + 2, a] & рядом[r + 2, b])      # строка q — в `рядом` строкой q + 1
        r, a, b = r[да], a[да], b[да]
        if not len(r):
            continue
        дл = b - a > 2 * k + 2
        с0, с1 = np.where(дл, a + k, a), np.where(дл, b - k + 1, b + 1)
        чей = np.repeat(np.arange(len(r)), с1 - с0)
        ном = r[чей] * n + с0[чей] + np.arange(len(чей)) - np.r_[0, np.cumsum(с1 - с0)[:-1]][чей]
        середина = ndimage.map_coordinates(мел, [Y.ravel()[ном], X.ravel()[ном]], order=1, mode='nearest')
        да = скоро.медианы(середина, чей, len(r)) >= ФОН
        r, a, b = r[да], a[да], b[да]
        w = (b - a) / РАБОЧИЙ
        шире += int((w > hi).sum())
        да = w <= hi
        w, r, a, b = w[да], r[да], a[да], b[да]
        шир += list(w)
        хорды += list(zip(w, X[r, a], Y[r, a], X[r, b], Y[r, b]))
    шир = np.asarray(шир)
    с = _пц(шир) if шир.size else {'p10': None, 'p50': None, 'p90': None, 'ср': None, 'σ/ср': None}
    с['эфф'] = round(_эфф(np.unique(np.floor(np.log2(шир) + 1e-9), return_counts=True)[1]), 2) if шир.size else None
    с['хорд'] = int(шир.size)
    с['шире'] = round(шире / max(шир.size + шире, 1), 3)
    с['фон'] = round(float((фак < ФОН).mean()), 3)
    с['шкала'] = ШИРИНА_МАЗКА
    пол = max(ПОЛ_ХОРДЫ, предел)
    с['пол'] = round(пол, 2)
    с['на полу'] = round(float((шир <= пол + 0.25).mean()), 3) if шир.size else 0.0
    if предел > ЛАГИ[0] and с['на полу'] > НА_ПОЛУ_ХОРД:                 # низ шкалы и пиксель снимка, а не мазок
        с.update({и: None for и in ('p10', 'p50', 'p90', 'ср', 'σ/ср', 'эфф')})
    return с, хорды


def _доля(v, w, q):
    """Взвешенный квантиль: у мазков с весом `w` доля `q` веса лежит не выше ответа."""
    i = np.argsort(v, kind='stable')
    c = np.cumsum(w[i])
    return float(v[i][min(int(np.searchsorted(c, q * c[-1])), len(i) - 1)])


def _пц_в(v, w, n=2):
    return {и: round(_доля(v, w, q), n) for и, q in (('p10', 0.1), ('p50', 0.5), ('p90', 0.9))}


def _целые(р):
    """Номера обычных мазков разбора и их медиана ширины по площади: целых (без полей), не у́же её половины. Мало — None."""
    о = р['области']
    ц = np.flatnonzero(~о['у края'] & (о['вес'] > 0) & р['мазки'])
    if len(ц) < Р.МАЛО_МАЗКОВ:
        return None
    return ц[о['ширина'][ц] >= 0.5 * _доля(о['ширина'][ц], (о['вес'] * о['площадь'])[ц], 0.5)]


def _размеры(р, px, сторона):
    """Обычный мазок разбора: длина, ширина, длина к ширине — процентилями по числу целых мазков (без полей) не у́же половины
    ширины, на которую приходится половина площади мазков: мельче — клочки, и сколько их, решает предел снимка, а не картина.
    'в долях' — длина и ширина в долях длинной стороны картины (`сторона` px), 'в ширинах' — в ширинах кисти (p50 ширины):
    от масштаба мм не зависят. 'размах' — на сколько медиана может стоять иначе из-за малого числа мазков (σ ранга медианы
    при их весах), доля. Мало мазков — None."""
    г = _целые(р)
    if г is None:
        return None
    д, ш, вес, пл = (р['области'][и][г] for и in ('длина', 'ширина', 'вес', 'площадь'))
    размах = 0.0
    for v, w in ((д, вес), (ш, вес), (ш, вес * пл)):             # и порог W/2 стоит на медиане по площади
        σ = 0.5 * math.sqrt(float((w * w).sum())) / float(w.sum())
        м = _доля(v, w, 0.5)
        размах = max(размах, *(abs(_доля(v, w, min(max(0.5 + з * σ, 0.0), 1.0)) / м - 1.0) for з in (-1, 1)))
    W = _доля(ш, вес, 0.5)
    return {'длина': _пц_в(д / px, вес), 'ширина': _пц_в(ш / px, вес), 'длина к ширине': _пц_в(д / ш, вес), 'размах': размах,
            'в долях': {'длина': _пц_в(д / сторона, вес, 5), 'ширина': _пц_в(ш / сторона, вес, 5)},
            'в ширинах': {'длина': _пц_в(д / W, вес), 'ширина': _пц_в(ш / W, вес)}}


РАЗМЕРЫ = ('длина', 'ширина', 'длина к ширине', 'в долях', 'в ширинах')
ФОРМА_БЛИЗКО = 0.1        # ширины: p50 формы на снимке в √2 раз мельче — в этом или в `ПОДТВЕРЖДЕНО` доле: форма подтверждена


def _форма(ф):
    """Форма обычного мазка по замерам `Р.формы`: вход и сход — длина и тупость p10–p50–p90 (ширин кисти), доли концов по
    именам (`рука.торец`), прядей на рваном, изгиб. Мазков с видными концами меньше `Р.МАЛО_МАЗКОВ` — None."""
    from . import рука
    ф = [з for з in ф if з['W'] >= рука.ВИДНО and з['длина к ширине'] >= рука.КОРОТОК]
    if len(ф) < Р.МАЛО_МАЗКОВ:
        return None
    вес = np.array([з['вес'] for з in ф])
    с = {'мазков': len(ф), 'изгиб': _пц_в(np.array([з['изгиб'] for з in ф]), вес, 3)}
    for и in ('вход', 'сход'):
        с[и] = {к: _пц_в(np.array([з[и][к] for з in ф]), вес, 3) for к in ('длина', 'тупость')}
        с[и]['сужен'] = round(float((вес * [рука.сужен(з[и]) for з in ф]).sum() / вес.sum()), 3)
        т = np.array([з['W'] >= рука.ВИДНО_ТОРЕЦ for з in ф])    # торцы — только у мазков, где зуб шире предела снимка
        с[и]['торцы'] = None
        if т.sum() >= Р.МАЛО_МАЗКОВ:
            имена = np.array([рука.торец(з[и], з['W']) for з in ф])
            с[и]['торцы'] = {н: round(float((вес * т * (имена == н)).sum() / (вес * т).sum()), 3)
                             for н in ('прямой', 'круглый', 'сужен', 'рваный')}
    с['торцы видны у'] = int(sum(з['W'] >= рука.ВИДНО_ТОРЕЦ for з in ф))
    return с


def _форма_разошлась(a, b):
    """Что в форме на снимке мельче вышло другим: строка «сход 0,3 вместо 0,5 ширины» или ''."""
    нет = []
    for и, к, слово in (('вход', 'длина', 'вход'), ('сход', 'длина', 'сход'),
                        ('вход', 'тупость', 'тупость входа'), ('сход', 'тупость', 'тупость схода')):
        v, w = a[и][к]['p50'], b[и][к]['p50']
        if abs(v - w) > max(ФОРМА_БЛИЗКО, ПОДТВЕРЖДЕНО * v):
            нет.append(f'{слово} {_ч(w, 2)} вместо {_ч(v, 2)} ширины')
    return ', '.join(нет)


def _почему(разм, разм2, размах, пред):
    """Чем размер не подтвердился на снимке в √2 раз мельче — только то, что на самом деле разошлось. Про предел — когда
    ширина мазка у него (полоса самого мелкого уровня разбора) и ушла вместе с ним."""
    if разм2 is None:
        return f'на снимке в 1,4 раза мельче целых мазков меньше {Р.МАЛО_МАЗКОВ}'
    ушло = {и: разм2[и]['p50'] / разм[и]['p50'] - 1.0 for и in ('ширина', 'длина')}
    не = [и for и in ушло if abs(ушло[и]) > ПОДТВЕРЖДЕНО]
    чем = ', '.join(f'{и} {_ч(разм2[и]["p50"])} вместо {_ч(разм[и]["p50"])} мм' for и in не or
                    [max(ушло, key=lambda и: abs(ушло[и]))])
    ответ = f'на снимке в 1,4 раза мельче {чем}'
    if not не:                                                    # по отдельности в доле, не сошлась сумма ошибок
        ответ += (f' ({_ч(100 * max(abs(v) for v in ушло.values()), 0)} %), и мазков мало — медиана гуляет на '
                  f'{_ч(100 * размах, 0)} %; вместе больше {_ч(100 * ПОДТВЕРЖДЕНО, 0)} %')
    elif размах > 0.5 * ПОДТВЕРЖДЕНО:
        ответ += f'; мазков мало — медиана гуляет на {_ч(100 * размах, 0)} %'
    if ушло['ширина'] > ПОДТВЕРЖДЕНО and разм['ширина']['p50'] <= пред * Р.ПОЛОСА[1] / Р.ПОЛОСА[0]:
        ответ = f'ширина у предела снимка ({_ч(пред)} мм) и уходит вместе с ним: {ответ}'
    return ответ


def _разбором(снимок, px_на_мм, предел=None, сторона=None):
    """Мазки-кандидаты и края пятен снимка: (сводка мазков, сводка краёв, разбор). `предел` мм грубее предела снимка —
    лестница разбора кончается на нём (у двух картинок разного разрешения — один счёт). `сторона` px — длинная сторона всей
    картины, если снимок — её кусок. Размер — число, только если его подтверждает сама картинка: тот же разбор снимка в √2
    раз мельче (предел — во столько же раз грубее) даёт p50 длины и ширины в `ПОДТВЕРЖДЕНО` и медиана не держится на горстке
    областей; иначе — слово с тем, что не сошлось. Форма — так же, своим подтверждением (`_форма`)."""
    px = float(px_на_мм)
    пред_px = max(float(предел or 0.0) * px, Р.ПРЕДЕЛ_PX)
    пред = пред_px / px
    сторона = float(сторона or max(снимок.shape[:2]))
    р = Р.разобрать(снимок, пред_px)
    р['px_на_мм'] = px
    о = р['области']
    р['мазки'] = Р.обычная_ширина(о)[1]
    всё = float(снимок.shape[0] * снимок.shape[1])
    вес = о['вес'] * р['мазки']
    число = float(вес.sum())
    с = {'мазков': int(round(число)), 'предел': round(пред, 3), 'слово': None, 'сторона': round(сторона / px, 1),
         'на дм²': round(число / (всё / (px * 100.0) ** 2), 1),
         'без мазков': round(float(np.clip(1.0 - (вес * о['площадь']).sum() / всё, 0.0, 1.0)), 3),
         'поля': round(float(np.clip((о['вес'] * ~р['мазки'] * о['площадь']).sum() / всё, 0.0, 1.0)), 3)}
    прот = float(вес[о['вид'] == 'протяжка'].sum())
    с['доли'] = {'протяжек': round(прот / max(число, 1e-9), 3), 'ударов': round(1.0 - прот / max(число, 1e-9), 3)}
    с.update({и: None for и in РАЗМЕРЫ + ('форма',)})
    разм = _размеры(р, px, сторона)
    целые = _целые(р)
    р['формы'] = [] if целые is None else Р.формы(р, целые)
    форма = _форма(р['формы'])
    р2, разм2 = None, None
    if (разм is not None and разм['размах'] <= ПОДТВЕРЖДЕНО) or форма is not None:
        # снимок мельче и предел его грубее: размер, который идёт от предела, уйдёт вместе с ним
        мельче = Р._к_уровню(р['картинка'], math.sqrt(2.0))
        р2 = Р.разобрать(мельче, пред_px) if min(мельче.shape[:2]) >= Р.СТОРОНА_МИН else None
        if р2 is not None:
            р2['мазки'] = Р.обычная_ширина(р2['области'])[1]
            разм2 = _размеры(р2, px / math.sqrt(2.0), сторона / math.sqrt(2.0))
    if разм is None:
        с['слово'] = (f'целых мазков {int((~о["у края"] & (о["вес"] > 0) & р["мазки"]).sum())} — мало, размеры не называются; мазок уже '
                      f'{_ч(пред)} мм или ближе к соседу, чем ступень краски, не различается')
    elif разм['размах'] > ПОДТВЕРЖДЕНО:
        с['слово'] = (f'размер держится на горстке крупных областей (медиана гуляет на {разм["размах"] * 100:.0f} %): мазков, '
                      'по которым назвать размер, мало — размеры не числом')
    else:
        ушло = None if разм2 is None else max(abs(разм2[и]['p50'] / разм[и]['p50'] - 1.0) for и in ('длина', 'ширина'))
        if ушло is not None:                                      # две независимые ошибки: от предела и от малого числа мазков
            ушло = math.hypot(ушло, разм['размах'])
        с['подтверждено'] = None if ушло is None else round(ушло, 3)
        if ушло is None or ушло > ПОДТВЕРЖДЕНО:
            с['слово'] = f'размер мазка не подтвердился: {_почему(разм, разм2, разм["размах"], пред)} — размеры не числом'
        else:
            с.update({и: разм[и] for и in РАЗМЕРЫ})
    с['слово формы'] = None
    if форма is None:
        с['слово формы'] = f'мазков с видными концами меньше {Р.МАЛО_МАЗКОВ}'
    else:
        ц2 = _целые(р2) if р2 is not None else None
        ф2 = _форма(Р.формы(р2, ц2)) if ц2 is not None else None
        разошлась = 'мазков с видными концами мало' if ф2 is None else _форма_разошлась(форма, ф2)
        if разошлась:
            с['слово формы'] = f'не подтвердилась: на снимке в 1,4 раза мельче {разошлась}'
        else:
            с['форма'] = форма
    if пред > Р.ПРЕДЕЛ_PX / px * (1 + 1e-6):                             # края — на снимке, уменьшенном до общего предела
        снимок = Р._к_уровню(р['картинка'], пред_px / Р.ПРЕДЕЛ_PX)
        px = Р.ПРЕДЕЛ_PX / пред
    к = Р.края_пятен(снимок)
    п = к['переход']
    край = {'прямых': None if к['прямых'] is None else round(к['прямых'], 3), 'границ': round(к['границ'], 4),
            'переход': None, 'на полу': None, 'пол': round(пред, 3)}
    if п.size:
        край['на полу'] = round(float((п <= Р.ПРЕДЕЛ_PX).mean()), 3)
        if край['на полу'] <= НА_ПОЛУ:
            край['переход'] = round(float(np.median(п)) / px, 2)
    return с, край, р


def _тон_в_пятне(L, размытая=None):
    """Разброс светлоты вокруг размытого на пятно: (карта, p10–p50–p90)."""
    σп = ПЯТНО * РАБОЧИЙ / 2.0
    размытая = размытая or _Размытия(L)
    Lf, Lc = размытая(0.25 * РАБОЧИЙ), размытая(σп)
    тон = np.sqrt(np.maximum(_гаусс((Lf - Lc) ** 2, σп), 0.0))
    return тон, {к: v for к, v in _пц(тон).items() if к != 'σ/ср'}


def _края_места(L, px_на_мм):
    """Края по клеткам 0,5 мм: (доли, карта жёстких, карта мягких); снимок грубее `ШАГ_КРАЯ` жёстких от мягких не различает."""
    _, жёст, мягк = глаз._края(глаз._клетками(L, 2), ПОРОГ_КРАЯ)
    края = жёст | мягк
    с = {'доля': round(float(края.mean()), 3), 'жёстких': round(float(жёст.sum() / max(края.sum(), 1)), 3),
         'мягких': round(float(мягк.sum() / max(края.sum(), 1)), 3)}
    if Р.ПРЕДЕЛ_PX / float(px_на_мм) > ШАГ_КРАЯ:
        с.update({'жёстких': None, 'мягких': None})
    return с, жёст, мягк


def мерка(картинка, px_на_мм=None, окно=8.0, что='картинка', область=None, свет=True, предел=None,
          сторона=None, файлом=True):
    """К-4: мерка манеры картинки — sRGB 0–255 (В, Ш, 3), путь к PNG/JPG, `Холст` или путь к `.npz`; `px_на_мм` —
    сколько px на мм картины (у холста — его, у картинки без него — 8 и слово об этом в отчёте), `область` — кусок
    (x0, y0, x1, y1) в px картины, `свет` — холст со светом рельефа (как на снимке картины), `окно` — мм, окно
    направлений и штриха; `предел` — мм: мазки разбором не мельче этого (сравнить два снимка разного разрешения —
    с пределом грубого, `м['предел']`); `сторона` — px длинной стороны всей картины, если картинка — её вырезка
    (с `область` и у холста — сама): от неё доли мазка. Ответ — `Мерка`; годится в `х.манера(образец=…)` и `х.однообразие(образец=…)`.
    Мерка картинки, данной путём, пишется рядом с ней файлом и в другой раз читается из него (`мерка_файл`); `файлом=False` — нет."""
    from .холст import Холст
    файл = None
    if isinstance(картинка, (str, bytes)) or hasattr(картинка, '__fspath__'):
        путь = os.fsdecode(картинка)
        картинка = глаз._загрузить(путь)
        файл = Файл(путь) if файлом and not isinstance(картинка, Холст) else None
    сказ, угол = '', (0, 0)
    if isinstance(картинка, Холст):
        угол = глаз._рамка(картинка, область)[:2]
        px_на_мм = px_на_мм or картинка.px_на_мм or 8.0
        сторона = сторона or max(картинка.ширина, картинка.высота)
        rgb = глаз._вид(картинка, глаз._рамка(картинка, область), свет)
    else:
        rgb = np.asarray(картинка, np.float64)
        сторона = сторона or max(rgb.shape[:2])
        if область is not None:
            x0, y0, x1, y1 = (int(v) for v in область)
            rgb, угол = rgb[y0:y1, x0:x1], (x0, y0)
        if not px_на_мм:
            px_на_мм, сказ = 8.0, ' (масштаб не дан — взято 8 px/мм)'
    if rgb.ndim != 3 or rgb.shape[2] < 3:
        raise ValueError(f'мерка: картинка — (В, Ш, 3) sRGB 0–255, а пришло {rgb.shape}')
    снимок = np.clip(np.round(rgb[..., :3]), 0, 255).astype(np.uint8)
    предел_мм = Р.ПРЕДЕЛ_PX / float(px_на_мм)
    доводы = [float(px_на_мм), float(окно), None if область is None else [int(v) for v in область],
              None if предел is None else float(предел), float(сторона)]
    м = файл and _из_файла(файл, доводы, снимок, float(px_на_мм), что, сказ)
    if м:
        return м
    rgb = _к_рабочему(rgb[..., :3], px_на_мм)
    окно_px = окно * РАБОЧИЙ
    if min(rgb.shape[:2]) < окно_px:
        raise ValueError(f'мерка: картинка {rgb.shape[1] / РАБОЧИЙ:.0f}×{rgb.shape[0] / РАБОЧИЙ:.0f} мм меньше окна '
                         f'{окно} мм — окно= меньше или кусок больше')
    lab = скоро.oklab(rgb.astype(np.uint8))                       # `_к_рабочему` — целые
    L = глаз._L(lab[..., 0])
    с = {'палитра': _палитра(rgb, lab)}
    σп = ПЯТНО * РАБОЧИЙ / 2.0
    размытая = _Размытия(L)
    тон, с['тон в пятне'] = _тон_в_пятне(L, размытая)
    ab = 0.0
    for i in (1, 2):
        ab = ab + (_гаусс(lab[..., i], 0.25 * РАБОЧИЙ) - _гаусс(lab[..., i], σп)) ** 2
    ab = np.sqrt(np.maximum(_гаусс(ab, σп), 0.0))
    с['цвет в пятне'] = {к: v for к, v in _пц(ab, 4).items() if к != 'σ/ср'}
    с['края'], жёст, мягк = _края_места(L, px_на_мм)
    с['предел'] = round(предел_мм, 3)
    с['направления'], θ, ког, шаг = _направления(L, окно_px, размытая)
    с['штрих'], дл, шир = _штрих(L, θ, окно_px, шаг, предел_мм, размытая)
    с['ширина мазка'], хорды = _ширина_мазка(L, lab, θ, ког, шаг, предел_мм, размытая)
    с['мазки разбором'], с['края пятен'], разбор = _разбором(снимок, px_на_мм, предел, сторона)
    м = Мерка()
    м.файл = файл
    м.сводка, м.что, м.px_на_мм, м.размер = с, что, float(px_на_мм), (rgb.shape[1] / РАБОЧИЙ, rgb.shape[0] / РАБОЧИЙ)
    м.откуда = {'угол': tuple(int(v) for v in угол), 'сторона': float(сторона), 'предел': предел, 'окно': float(окно)}
    м.массивы = _Массивы({'картинка': rgb, 'направление': θ, 'порядок': ког, 'шаг': шаг, 'жёсткие': жёст, 'мягкие': мягк,
                 'тон в пятне': тон, 'длина': дл, 'ширина': шир, 'хорды': хорды, 'снимок': снимок, 'разбор': разбор, 'px_на_мм': float(px_на_мм)})
    if файл:
        сам = ('картинка', 'тон в пятне', 'снимок', 'px_на_мм', 'хорды', 'разбор')
        файл.записать('мерка', доводы, {
            'сводка': с, 'размер': м.размер, 'откуда': м.откуда, 'массивы': {и: v for и, v in м.массивы.items() if и not in сам},
            'хорды': np.array(хорды, np.float64).reshape(-1, 5), 'разбор': {и: v for и, v in разбор.items() if и != 'картинка'}})
    м.слова = _слова_мерки(м) + сказ
    return м


def _из_файла(файл, доводы, снимок, px_на_мм, что, сказ):
    """Мерка из файла рядом с картинкой или None."""
    д = файл.взять('мерка', доводы)
    try:
        if д is None or д['разбор']['метки'].shape != снимок.shape[:2]:
            return None
        м = Мерка()
        м.файл, м.что, м.px_на_мм = файл, что, px_на_мм
        м.сводка, м.размер, м.откуда = д['сводка'], д['размер'], д['откуда']
        м.массивы = _Массивы(д['массивы'], хорды=[tuple(х) for х in д['хорды']], снимок=снимок,
                             разбор=dict(д['разбор'], картинка=снимок), px_на_мм=px_на_мм)
        м.слова = _слова_мерки(м) + сказ
        return м
    except (KeyError, TypeError, AttributeError):                  # не наш файл
        return None


def _разбор_на_пределе(м, предел, сторона):
    """Сводки мазков и краёв пятен мерки `м` на другом пределе; у мерки с файлом — тоже файлом."""
    файл, снимок = getattr(м, 'файл', None), м.массивы['снимок']
    x, y = м.откуда['угол']
    доводы = [м.px_на_мм, [x, y, x + снимок.shape[1], y + снимок.shape[0]], float(предел), float(сторона)]
    ответ = файл and файл.взять('мазки', доводы)
    if not ответ:
        ответ = _разбором(снимок, м.px_на_мм, предел, сторона)[:2]
        if файл:
            файл.записать('мазки', доводы, ответ)
    return ответ


# ---------------------------------------------------------------- слова и разница

def _ч(v, n=1):
    if v is None:
        return '—'
    v = 0.0 if abs(v) < 0.5 * 10 ** -n else float(v)                  # без «-0»
    return f'{v:.{n}f}'.replace('.', ',')


def _слова_штриха(к, v):
    if v.get('на полу', 0) > НА_ПОЛУ:
        return f'{к} уже {_ч(v.get("пол", ЛАГИ[0]))} мм в {_ч(100 * v["на полу"], 0)} % мест — не различается'
    return f'{к} {_ч(v["p10"])}–{_ч(v["p90"])} мм (σ/ср {_ч(v["σ/ср"], 2)}, эфф {_ч(v["эфф"])})'


def _слова_мазка(в):
    фон = f', фон без фактуры {_ч(100 * в["фон"], 0)} % места' if в['фон'] >= 0.05 else ''
    if not в['хорд']:
        return f'ширина мазка по картинке: лент между краями нет{фон}'
    if в['p50'] is None:
        return (f'ширина мазка по хордам: {_ч(100 * в["на полу"], 0)} % хорд не шире {_ч(в["пол"])} мм — снимок слишком мелкий, '
                f'не различается{фон}')
    мало = f' — мало, в разницу не идёт' if в['хорд'] < МАЛО_ХОРД else ''
    шире = f', шире {_ч(в["шкала"][1], 0)} мм — {_ч(100 * в["шире"], 0)} % хорд' if в['шире'] >= 0.05 else ''
    return (f'ширина пятна-хода по хордам {_ч(в["p10"])}–{_ч(в["p50"])}–{_ч(в["p90"])} мм (p10–p50–p90, σ/ср '
            f'{_ч(в["σ/ср"], 2)}, хорд {в["хорд"]}{мало}{шире}{фон})')


def _слова_разбора(р, к):
    д, тр = р['доли'], lambda v, n=1: f'{_ч(v["p10"], n)}–{_ч(v["p50"], n)}–{_ч(v["p90"], n)}'
    счёт = (f'не мельче {_ч(р["предел"])} мм — {р["мазков"]}, на дм² {_ч(р["на дм²"], 0)}; протяжек {_ч(100 * д["протяжек"], 0)} %, '
            f'ударов {_ч(100 * д["ударов"], 0)} %; без мазков {_ч(100 * р["без мазков"], 0)} % площади, из них поля (шире '
            f'{_ч(Р.ПОЛЕ, 0)} ширин мазка) — {_ч(100 * р["поля"], 0)} %')
    if р['слово']:
        мз = f'мазки разбором: {р["слово"]}; {счёт}'
    else:
        мз = (f'мазки разбором: длина {тр(р["длина"])} мм, ширина {тр(р["ширина"])} мм (p10–p50–p90), '
              f'длина к ширине {_ч(р["длина к ширине"]["p50"])}; в ширинах кисти (p50 ширины) длина {тр(р["в ширинах"]["длина"])}, ширина '
              f'{тр(р["в ширинах"]["ширина"], 2)}; от длинной стороны картины {_ч(р["сторона"], 0)} мм длина '
              f'{_ч(100 * р["в долях"]["длина"]["p50"], 2)} %, ширина {_ч(100 * р["в долях"]["ширина"]["p50"], 2)} %; {счёт}')
    мз += f'; {_слова_формы(р)}'
    if к['прямых'] is None:
        return мз + '; краёв пятен нет'
    пер = (f'переход {_ч(к["переход"])} мм' if к['переход'] is not None else
           f'переход у {_ч(100 * к["на полу"], 0)} % не шире {_ч(к["пол"])} мм — резче не различается')
    return f'{мз}; края пятен: прямых {_ч(100 * к["прямых"], 0)} %, {пер}'


def _слова_формы(р):
    ф = р['форма']
    if ф is None:
        return f'форма мазка: {р["слово формы"]}'
    т = []
    for и in ('вход', 'сход'):
        к = ф[и]
        имена = ('' if к['торцы'] is None else
                 ' (' + ', '.join(f'{н} {_ч(100 * v, 0)} %' for н, v in к['торцы'].items() if v >= 0.005) + ')')
        т.append(f'{и} {_ч(к["длина"]["p50"])} (p90 {_ч(к["длина"]["p90"])}), тупость {_ч(к["тупость"]["p50"], 2)}, сужен у '
                 f'{_ч(100 * к["сужен"], 0)} %{имена}')
    видно = (f'; торцы по именам — у {ф["торцы видны у"]} мазков' if ф['вход']['торцы'] is not None else
             '; рваный торец от ровного не различается: мазки уже 12 px снимка')
    return (f'форма мазка в ширинах кисти ({ф["мазков"]} мазков; вход — где больше сплошной краски, рука по картинке не видна): '
            f'{"; ".join(т)}; изгиб {_ч(ф["изгиб"]["p50"], 2)} длины{видно}')


