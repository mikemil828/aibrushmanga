def _доли_на_общем(х, о, общие, предел):
    """Сводки мазков для сравнения в долях стороны: предел — общий в долях, а не в мм (у картины 1 м и холста 25 см он в мм
    разный). Грубая картинка — её мерка; тонкая, если у грубой размер числом, — разбором с тем же пределом в долях."""
    ст = [м['мазки разбором']['сторона'] for м in (х, о)]
    отн = [м['предел'] / с for м, с in zip((х, о), ст)]
    и = int(отн[1] > отн[0])                                      # грубая
    ответ = [м['мазки разбором'] for м in (х, о)]
    if ответ[и]['слово'] is None and отн[1 - и] < 0.99 * отн[и]:
        м = (х, о)[1 - и]
        п = отн[и] * ст[1 - и]
        ответ[1 - и] = (общие[1 - и]['мазки разбором'] if abs(п - предел) < 0.01 * предел else
                        _разбор_на_пределе(м, п, ст[1 - и] * м.px_на_мм)[0])
    return ответ


def _разница(х, о):
    """Штрих, у которого на любой стороне больше `НА_ПОЛУ` мест на первом сдвиге, — 'во сколько' None и 'на полу';
    ширина мазка, где у любой стороны хорд меньше `МАЛО_ХОРД`, — 'во сколько' None и 'хорд'. Мазки разбором и края пятен —
    на общем пределе (грубом из двух): картинка резче меряется уменьшенной, и её числа здесь другие, чем в её мерке."""
    р = {}
    предел = max(х['предел'], о['предел'])
    общие = [м.сводка if abs(м['предел'] - предел) < 0.01 * предел else
             dict(zip(НА_ОБЩЕМ, _разбор_на_пределе(м, предел, м['мазки разбором']['сторона'] * м.px_на_мм)))
             for м in (х, о)]
    доли = _доли_на_общем(х, о, общие, предел)
    for имя, (раздел, ключ, *_ ) in ПРИЗНАКИ.items():
        a, b = (_взять((общ if раздел in НА_ОБЩЕМ else м.сводка)[раздел], ключ) for м, общ in zip((х, о), общие))
        if 'в долях' in ключ:
            a, b = (_взять(д, ключ) for д in доли)
        k = (b / a) if a not in (None, 0) and b is not None else None
        р[имя] = {'холст': a, 'образец': b, 'во сколько': round(k, 2) if k is not None else None}
        if раздел == 'ширина мазка':
            мало = min(м.сводка[раздел]['хорд'] for м in (х, о))
            if мало < МАЛО_ХОРД:
                р[имя].update({'во сколько': None, 'хорд': мало})
        if раздел == 'штрих':
            пол = max(_взять(м.сводка['штрих'], (ключ[0], 'на полу')) or 0.0 for м in (х, о))
            if пол > НА_ПОЛУ:
                р[имя].update({'во сколько': None, 'на полу': пол})
    return р


def _слова_разницы(р):
    уже, шире = [], []
    for имя, (_, _, слово, ед, n) in ПРИЗНАКИ.items():
        v = р[имя]
        k = v['во сколько']
        if k is None:
            continue
        t = f'{слово}: холст {_ч(v["холст"], n)}{ед}, образец {_ч(v["образец"], n)}{ед}'
        if k >= ВО_СКОЛЬКО:
            уже.append(f'{t} — у образца в {_ч(k)} раза больше')
        elif k == 0:
            шире.append(f'{t} — у образца нет вовсе')
        elif k <= 1 / ВО_СКОЛЬКО:
            шире.append(f'{t} — у холста в {_ч(1 / k)} раза больше')
    части = []
    if уже:
        части.append('у холста меньше, чем у образца: ' + '; '.join(уже))
    if шире:
        части.append('у холста больше, чем у образца: ' + '; '.join(шире))
    if not части:
        части.append(f'по всем признакам холст и образец ближе, чем в {_ч(ВО_СКОЛЬКО)} раза')
    return '. '.join(части)


