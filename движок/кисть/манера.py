def _мазки(х, журнал, рамка, объект, этап, слой):
    from . import однообразие as О
    путь = журнал if журнал is not None else (х._журнал_для_чтения() if hasattr(х, '_журнал_для_чтения') else None)   # М-10 (а)
    if путь is None:
        return None
    все = О.мазки_журнала(путь)
    зона = О.отобрать(все, объект, этап, слой, None if (объект or этап or слой) else рамка)
    if not зона:
        return {'мазков': 0}
    о = О.отчёт(зона)
    мм = 1.0 / float(getattr(х, 'px_на_мм', None) or 8.0)
    def в_мм(v):
        return {к: (round(z * мм, 2) if к in ('ср', 'σ', 'p10', 'p50', 'p90') and z is not None else z)
                for к, z in v.items()}
    return {'мазков': len(зона), 'длина': в_мм(о['длина']), 'ширина': в_мм(о['ширина']), 'наклон': о['наклон']}


def манера(х, область=None, образец=None, область_образца=None, px_на_мм_образца=None, объект=None, этап=None,
           слой=None, журнал=None, свет=True, окно=8.0, путь=None, без=None, до=None):
    """К-4: мерка манеры холста в `область` (картинкой, со светом рельефа по умолчанию — как на снимке картины) и, если
    дан `образец` (путь к картинке, массив sRGB, `Холст` или `.npz`, или готовая `Мерка`), — его мерка той же линейкой и
    разница. `px_на_мм_образца` — сколько px на мм у картины образца (без него — как у холста, и отчёт это говорит);
    `область_образца` — кусок образца в его px. Мазки холста — по журналу (`объект`, `этап`, `слой` или центром в
    области). `путь` — PNG «картинка | направления | края | мазки» холста и образца. Холст только читается."""
    from .холст import Холст
    х = глаз.без_слоёв(х, без, до)
    рамка = глаз._рамка(х, область)
    px = float(getattr(х, 'px_на_мм', None) or 8.0)
    мх = мерка(глаз._вид(х, рамка, свет), px, окно, 'холст')
    мх.сводка['мазки'] = _мазки(х, журнал, рамка, объект, этап, слой) or {'мазков': None}
    мх.слова = _слова_мерки(мх)
    мо, сказ = образец, ''
    if образец is not None and not isinstance(образец, Мерка):
        if isinstance(образец, (str, bytes)) or hasattr(образец, '__fspath__'):
            образец = глаз._загрузить(образец)
        pxо = px_на_мм_образца
        if not pxо and not isinstance(образец, Холст):
            pxо, сказ = px, f' (масштаб образца не дан — взят как у холста, {_ч(px, 1)} px/мм; px_на_мм_образца=)'
        мо = мерка(образец, pxо, окно, 'образец', область_образца, свет)
        мо.слова += сказ
    м = Манера()
    м.холст, м.образец = мх, мо
    м.разница = _разница(мх, мо) if мо is not None else {}
    м.места, сл = места_манеры(мх, мо, рамка, px) if мо is not None else ([], '')
    м.слова = мх.слова + ('.\n' + мо.слова + '.\n' + сл + '.\n' + _слова_разницы(м.разница) if мо is not None else '')
    м.лист = _лист([мх] + ([мо] if мо is not None else []), путь)
    return м


# ---------------------------------------------------------------- по клеткам (зеркало с адресом)

КЛЕТКА_МАНЕРЫ = 50.0      # мм: клетка холста; у образца меньше клетки — клетка по его меньшей стороне
МЕСТ_МАНЕРЫ = 8           # худших клеток в словах


def _по_клеткам(м, клетка_мм):
    """Клетки мерки (рабочий масштаб): [(x0, y0, x1, y1 в мм от угла картинки, тон в пятне p50, замесов)]; клетка у
    края меньше половины — не идёт."""
    rgb, тон = м.массивы['картинка'], м.массивы['тон в пятне']
    в, ш = тон.shape
    k = max(8, int(round(клетка_мм * РАБОЧИЙ)))
    lab = глаз.oklab(rgb)
    итог = []
    for y0 in range(0, в, k):
        for x0 in range(0, ш, k):
            y1, x1 = min(в, y0 + k), min(ш, x0 + k)
            if (y1 - y0) * (x1 - x0) < 0.5 * k * k:
                continue
            итог.append((x0 / РАБОЧИЙ, y0 / РАБОЧИЙ, x1 / РАБОЧИЙ, y1 / РАБОЧИЙ, float(np.median(тон[y0:y1, x0:x1])),
                         _палитра(rgb[y0:y1, x0:x1], lab[y0:y1, x0:x1])['замесов']))
    return итог


def места_манеры(мх, мо, рамка, px_на_мм, клетка=КЛЕТКА_МАНЕРЫ):
    """Холст по клеткам `клетка` мм против образца той же клеткой (медиана его клеток): разброс тона в пятне (p50 клетки)
    и замесы (90 % площади клетки). Место — клетка, где холст пестрее или однообразнее образца в `ВО_СКОЛЬКО` раз и
    больше по любому из двух. Ответ — (места, слова): места — словари 'рамка' (px холста), 'тон в пятне' и 'замесов' —
    (холст, образец), 'во сколько' — образец / холст по каждому, 'слово' ('однообразнее' / 'пестрее'); худшие первыми."""
    кл = min(клетка, мо.размер[0], мо.размер[1])
    о = _по_клеткам(мо, кл)
    if not о:
        return [], f'по клеткам: образец {_ч(мо.размер[0], 0)}×{_ч(мо.размер[1], 0)} мм — клеток нет'
    тон_о, зам_о = float(np.median([c[4] for c in о])), float(np.median([c[5] for c in о]))
    места = []
    for x0, y0, x1, y1, тон, зам in _по_клеткам(мх, кл):
        кт = тон_о / max(тон, 1e-3)
        кз = зам_о / max(зам, 1)
        к = max((кт, кз, 1 / max(кт, 1e-9), 1 / max(кз, 1e-9)))
        if к < ВО_СКОЛЬКО:
            continue
        одно = max(кт, кз) >= ВО_СКОЛЬКО
        пёстро = min(кт, кз) <= 1 / ВО_СКОЛЬКО
        слово = 'однообразнее и пестрее' if одно and пёстро else 'однообразнее' if одно else 'пестрее'
        места.append({'рамка': (int(round(рамка[0] + x0 * px_на_мм)), int(round(рамка[1] + y0 * px_на_мм)),
                                int(round(рамка[0] + x1 * px_на_мм)), int(round(рамка[1] + y1 * px_на_мм))),
                      'тон в пятне': (round(тон, 2), round(тон_о, 2)), 'замесов': (зам, round(зам_о, 1)),
                      'во сколько': (round(кт, 2), round(кз, 2)), 'слово': слово, '_к': к})
    места.sort(key=lambda д: -д['_к'])
    for д in места:
        del д['_к']
    n_о = sum(1 for д in места if 'однообразнее' in д['слово'])
    n_п = sum(1 for д in места if 'пестрее' in д['слово'])
    ч = [f'по клеткам {_ч(кл, 0)} мм (образец — медиана своих клеток: тон в пятне {_ч(тон_о)} L, замесов {_ч(зам_о, 0)}): '
         f'однообразнее образца в {_ч(ВО_СКОЛЬКО)} раза и больше — {n_о}, пестрее — {n_п}']
    for i, д in enumerate(места[:МЕСТ_МАНЕРЫ], 1):
        кт, кз = д['во сколько']
        раз = lambda k: f'в {_ч(1 / k)} раза больше' if k < 1 else f'в {_ч(k)} раза меньше'
        ч.append(f'  {i}. рамка {д["рамка"]}: {д["слово"]} — тон в пятне {_ч(д["тон в пятне"][0])} L ({раз(кт)}), '
                 f'замесов {д["замесов"][0]} ({раз(кз)})')
    return места, '\n'.join(ч)


