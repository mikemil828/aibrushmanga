ПАНЕЛЬ = (420, 340)


def _вписать(a, рамка=ПАНЕЛЬ):
    from PIL import Image
    ш, в = рамка
    k = min(ш / a.shape[1], в / a.shape[0])
    im = Image.fromarray(np.clip(np.round(a), 0, 255).astype(np.uint8))
    im = im.resize((max(1, int(a.shape[1] * k)), max(1, int(a.shape[0] * k))), Image.LANCZOS)
    поле = Image.new('RGB', (ш, в), (128, 128, 128))
    поле.paste(im, (0, 0))
    return поле, k


def _лист(мерки, путь):
    from PIL import ImageDraw
    панели, подписи = [], []
    for м in мерки:
        a = м.массивы
        кар, k = _вписать(a['картинка'])
        панели.append(np.asarray(кар, np.float64))
        подписи.append(f'{м.что}: картинка')
        тень, _ = _вписать(a['картинка'] * 0.35 + 80)
        д = ImageDraw.Draw(тень)
        θ, с, шаг = a['направление'], a['порядок'], a['шаг']
        р = max(1, math.ceil(max(θ.shape) / 32))                        # не гуще 32 штрихов по длинной стороне
        for i in range(0, θ.shape[0], р):
            for j in range(0, θ.shape[1], р):
                cx, cy = (шаг // 2 + j * шаг) * k, (шаг // 2 + i * шаг) * k
                r = 0.5 * р * шаг * k * (0.3 + 0.7 * min(1.0, float(с[i, j]) / 0.6))
                dx, dy = r * math.cos(math.radians(θ[i, j])), r * math.sin(math.radians(θ[i, j]))
                д.line([(cx - dx, cy - dy), (cx + dx, cy + dy)], fill=(255, 230, 120), width=1)
        панели.append(np.asarray(тень, np.float64))
        подписи.append(f'{м.что}: направления (длина — порядок)')
        к = np.zeros(a['жёсткие'].shape + (3,))
        к[a['мягкие']] = (40, 70, 115)                              # края приглушены: поверх — хорды
        к[a['жёсткие']] = (115, 115, 115)
        кр, _ = _вписать(к)
        д = ImageDraw.Draw(кр)
        lo, hi = ШИРИНА_МАЗКА
        for w, x0, y0, x1, y1 in a.get('хорды', ()):              # хорды ширины мазка: жёлтые узкие — пурпурные широкие
            t = min(1.0, math.log(w / lo) / math.log(hi / lo))
            д.line([(x0 * k, y0 * k), (x1 * k, y1 * k)], fill=(255, int(230 * (1 - t)), int(255 * t)), width=1)
        панели.append(np.asarray(кр, np.float64))
        подписи.append(f'{м.что}: края (светлее — жёсткие), хорды мазка')
        р = a['разбор']
        S = np.r_[0, np.where(р['мазки'], np.arange(len(р['мазки'])) + 1, 0)][р['метки']]   # без полей; мелкие уровни
                                                                # большого снимка — только в плитках
        б = np.zeros(S.shape, bool)
        б[1:] |= S[1:] != S[:-1]
        б[:, 1:] |= S[:, 1:] != S[:, :-1]
        к = np.array(р['картинка'], np.uint8)
        к[б] = (255, 0, 255)
        панели.append(np.asarray(_вписать(к)[0], np.float64))
        подписи.append(f'{м.что}: мазки разбором')
    return глаз._лист(панели, подписи, путь)
