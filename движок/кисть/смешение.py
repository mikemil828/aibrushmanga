"""В-4 (К-17 баланса): смешение по сырому числом — `смешение_для`: какой станет след одного хода по лежащей сырой
краске (цвет тела следа, доля тона лежащего в нём, `о.сырое`, `о.цвет`) до кладки, и нагрузка (и, если нужно, нажим)
под заказ доли.

Почему не таблица (замер смены Движка 188). Цвет следа по сырому идёт не за одним числом: кисть набирает лежащую
краску (смесь K/S), кладёт её борозды и пряди с тоном прядей, вмешивает на месте и перекрывает лежащее покрытием —
каждый пиксель следа своя смесь, а `х.средний` берёт среднее L по пикселям. Одна доля смеси K/S на узел, снятая одной
парой красок, на другой паре того же хода ошибается до 30 L (светлое по тёмному и тёмное по светлому — доли 0,04 и
0,36 одного хода); семья пикселя «смесь K/S, лежащее, грунт», подогнанная по 8 парам красок попиксельно, — до 4,5 L
на прозрачной. Цвет вне таблицы краски не держит. Поэтому счёт — сам ход на своём стенде: холст стенда в памяти,
не холст модели; ход 0,07 с, 24 сида и подмалёвок — 2–3 с; заказ доли — 8–40 с.

Стенд (в мм — тот же при любом `px_на_мм`; при 8 px/мм — 600×400): чистый грунт (166, 146, 129), гладкий; подмалёвок —
сырая заливка 50×25 мм одной кроющей краской `лежит`, `плоская` 5 мм, `ровно=1`, нажим 0,6, ряды вдоль короткой стороны
шагом 3,25 мм (сиды `СИДЫ_ЗАЛИВКИ`); его толщина — нагрузкой заливки (`подмалёвок=`) или сырой толщиной (`толщина=`,
единицы `Слой.толщина`; нагрузка заливки под неё — по кривой толщины заливки). Поверх — ход `путь_с_нажимом` прямо
(45 мм или `длина=` 10–200 мм: по сырому кисть пачкается по ходу — тело длинного хода темнее и ближе к лежащему) поперёк
рядов кистью модели (её копией: память кисти не трогается), сиды `СИДЫ` 101–124 (не 1–12 — те у живой
сверки).

Мерка — тело следа: средняя половина длины хода, средняя половина ширины следа (`о.ширина`), без света. Цвет — как у
`х.средний` (L — среднее L серой шкалы по пикселям, C и h — из средних a, b OKLab). Доля тона лежащего — где цвет тела
следа лёг на отрезке «краска хода → лежащее» в OKLab (проекция; 0 — чистая краска хода, 1 — тон лежащего; у прозрачной
сюда входит и просвет лежащего сквозь плёнку). Лежащее — цвет заливки стенда в том же окне до хода.

Только счёт: холст, кисть и журнал модели не трогаются.
"""
import math
import warnings

import numpy as np

ГРУНТ = (166, 146, 129)
ПХ = 8.0                                   # px/мм стенда по умолчанию
ДЛИНА = 45.0                               # ход стенда по умолчанию, мм (`длина=`: 10–200)
ДЛИНЫ = (10.0, 200.0)
ПОЛЯ_ММ = (15.0, 12.5)                     # от края стенда до хода и до заливки, мм
ВЫСОТА_ММ = 50.0                           # стенд: (длина + 30) × 50 мм; заливка — от 12,5 мм с краёв (при 45 мм —
                                           # 600×400 и 400×200 px при 8 px/мм)
РЯДЫ_ММ = (5.0, 3.25, 1.25)                # ширина `плоская` заливки, шаг рядов, вход и сход
СИДЫ = tuple(range(101, 125))              # сиды прогноза: в крутом месте один ход гуляет на 5–15 L
СИДЫ_ПОИСКА = СИДЫ[:8]                     # сиды перебора нагрузки под заказ доли (итог — всеми `СИДЫ`)
СИДЫ_ЗАЛИВКИ = 1000                        # сид ряда заливки — 1000 + номер ряда
НАГРУЗКИ_ЗАЛИВКИ = (0.1, 0.2, 0.3, 0.45, 0.6, 0.8, 1.0)   # кривая толщины заливки (под `толщина=`)
НАГРУЗКИ = (0.03, 1.0)                     # пределы нагрузки хода
СЕТКА_НАГРУЗКИ = tuple(float(v) for v in np.round(np.exp(np.linspace(math.log(0.03), 0.0, 11)), 4))
НАЖИМЫ = (0.35, 0.5, 0.65, 0.8)            # перебор нажима под заказ доли, если нажим не дан (ближние к 0,6 — первыми)
НАЖИМ = 0.6

СЛОЙ_ЛЕЖИТ = 'подмалёвок'                 # слой заливки стенда
СЛОЙ_ХОДА = 'ход'                         # слой хода стенда, когда ход — не в слой лежащего (над ним)
СЛОЙ_НИЗ = 'низ'                          # В-4-3: нижняя заливка стенда, когда сырое и в слое хода, и под ним
РАСКЛАДКИ = ('свой', 'ниже', 'поверх', 'два')   # ход в слой лежащего; в слой выше с `мешать_ниже`; в слой выше без
                                           # смешения; в слой лежащего с `мешать_ниже` над второй сырой заливкой
СИДЫ_ЗАЛИВКИ_ВЕРХ = 2000                   # 'два': сид ряда верхней заливки — 2000 + номер ряда
СЫРО = 1e-4                                # сырая толщина, ниже которой сырого нет
_ЗАЛИВКИ = {}                              # (rgb, нагрузка, px) -> Холст стенда с заливкой (память процесса)
_ТОЛЩИНЫ = {}                              # px -> {как: кривая (нагрузка заливки, толщина)}
КАК_ЗАЛИВКИ = ('ровно', 'рядами', 'дважды')   # заливки стенда по толщине: `ровно=1`; без `ровно`; два прохода
НЕРОВНО = 0.2                              # В-4-3: σ/среднее сырой толщины слоя места выше — слой бороздами (ряды без
                                           # `ровно`: 0,35–0,45; ряды `ровно=1`: 0,07–0,09) — заливка стенда 'рядами'


def _px(v, px):
    return float(v) * px


def _геом(дл):
    """Стенд под ход длиной дл мм: (ширина стенда, (x0, y0, x1, y1) заливки, (x от, x до) хода), мм."""
    ш = float(дл) + 2 * ПОЛЯ_ММ[0]
    з = ПОЛЯ_ММ[1]
    return ш, (з, з, ш - з, ВЫСОТА_ММ - з), (ПОЛЯ_ММ[0], ПОЛЯ_ММ[0] + float(дл))


def _холст(px, дл=ДЛИНА):
    from .холст import Холст
    return Холст(int(round(_геом(дл)[0] * px)), int(round(ВЫСОТА_ММ * px)), грунт=ГРУНТ, px_на_мм=px, ядра=1,
                 подсказки=False)


def _ряды(х, rgb, нагрузка, px, сид, дл, как, слой):
    """Ряды заливки стенда на холст `х` (кладёт на `х`!): `плоская` 5 мм, нажим 0,6, сиды `сид` + номер ряда."""
    from .кисть import Кисть
    from .путь import путь_с_нажимом
    from .краска import Краска
    from . import калибровка as кал
    import os
    ш, шаг, вх = (_px(v, px) for v in РЯДЫ_ММ)
    к = Кисть.из_файла(os.path.join(кал._ПРЕСЕТЫ, 'плоская.json'), ширина=ш)
    x0, y0, x1, y1 = (_px(v, px) for v in _геом(дл)[1])
    i = 0
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        for проход in range(2 if как == 'дважды' else 1):
            x = x0 + ш / 4 + проход * шаг / 2
            while x <= x1 - ш / 4 + 1e-6:
                т = путь_с_нажимом([(x, y0), (x, y1)], ш, нажим=0.6, вход=вх, сход=вх, сид=сид + i)
                х.мазок(т, Краска(rgb, 'кроющая'), к, слой=слой, сид=сид + i,
                        нагрузка=float(нагрузка), **({'ровно': 1.0} if как == 'ровно' else {}))
                x, i = x + шаг, i + 1


def _ключ(лежит, нагрузка, как):
    return tuple(round(float(v), 3) for v in tuple(лежит)[:3]), round(float(нагрузка), 4), str(как)


def _в_память(ключ, строить):
    import copy
    if ключ not in _ЗАЛИВКИ:
        х = строить()
        if len(_ЗАЛИВКИ) >= 24:
            _ЗАЛИВКИ.pop(next(iter(_ЗАЛИВКИ)))
        _ЗАЛИВКИ[ключ] = х
    return copy.deepcopy(_ЗАЛИВКИ[ключ])


def заливка(лежит, нагрузка, px=ПХ, сид=СИДЫ_ЗАЛИВКИ, дл=ДЛИНА, как='ровно'):
    """Холст стенда с сырым подмалёвком в слое `СЛОЙ_ЛЕЖИТ`: краска `лежит` (sRGB), нагрузка заливки `нагрузка`, сид
    ряда — `сид` + номер ряда, стенд под ход длиной `дл` мм; `как` — 'ровно': ряды с `ровно=1` (сырая толщина до 0,75),
    'рядами': без `ровно`, как обычный подмалёвок (до 1,05), 'дважды': два прохода рядами без `ровно`, второй со
    сдвигом на полшага (густой подмалёвок). Из памяти процесса — копией (холст памяти не меняется)."""
    rgb, н, к = _ключ(лежит, нагрузка, как)
    ключ = (rgb, н, float(px), int(сид), round(float(дл), 2), к)

    def строить():
        х = _холст(px, дл)
        _ряды(х, rgb, float(нагрузка), px, int(сид), дл, к, СЛОЙ_ЛЕЖИТ)      # нагрузка — как дана (ключ — округлённая)
        return х
    return _в_память(ключ, строить)


def заливка_два(низ, верх, px=ПХ, дл=ДЛИНА):
    """В-4-3: стенд с сырым в двух слоях — `низ` и `верх` = (rgb, нагрузка заливки, как): нижняя заливка в слое
    `СЛОЙ_НИЗ` (сиды `СИДЫ_ЗАЛИВКИ`), по ней сырой — верхняя в `СЛОЙ_ЛЕЖИТ` (сиды `СИДЫ_ЗАЛИВКИ_ВЕРХ`, без смешения
    с нижней: ряды без `мешать_ниже`). Ход 'два' — в `СЛОЙ_ЛЕЖИТ` с `мешать_ниже=True`. Копией из памяти процесса."""
    н, в = _ключ(*низ), _ключ(*верх)
    ключ = ('два', н, в, float(px), round(float(дл), 2))

    def строить():
        х = _холст(px, дл)
        _ряды(х, н[0], float(низ[1]), px, СИДЫ_ЗАЛИВКИ, дл, н[2], СЛОЙ_НИЗ)
        _ряды(х, в[0], float(верх[1]), px, СИДЫ_ЗАЛИВКИ_ВЕРХ, дл, в[2], СЛОЙ_ЛЕЖИТ)
        return х
    return _в_память(ключ, строить)


def сырая_толщина(х, область):
    """Средняя сырая толщина краски в прямоугольнике (x0, y0, x1, y1): сумма по слоям толщина × влажность × (1 − 0,85 ×
    схват) — то, что кисть может взять (`укладка`, сырая краска под мазком); единицы `Слой.толщина`."""
    from .числа import _СХВАТ
    где = х._область(область)
    всего = None
    for с in х.слои.values():
        h = np.asarray(с.толщина[где], np.float64) * np.asarray(с.влажность[где], np.float64)
        h = h * (1.0 - _СХВАТ * np.asarray(с.схват[где], np.float64))
        всего = h if всего is None else всего + h
    return 0.0 if всего is None or всего.size == 0 else float(всего.mean())


def _окно_хода(px, w, дл=ДЛИНА):
    yc = ВЫСОТА_ММ * px / 2
    a, b = (_px(v, px) for v in _геом(дл)[2])
    дл = b - a
    return (int(round(a + дл / 4)), int(round(yc - w / 4)), int(round(b - дл / 4)), int(round(yc + w / 4)) + 1)


def толщина_заливки(нагрузка, px=ПХ, как='ровно'):
    """Сырая толщина подмалёвка стенда (нагрузка заливки) в окне мерки хода."""
    х = заливка((128, 128, 128), нагрузка, px, как=как)
    w = РЯДЫ_ММ[0] * px
    return сырая_толщина(х, _окно_хода(px, w))


def _кривые(px):
    if px not in _ТОЛЩИНЫ:
        _ТОЛЩИНЫ[px] = {как: [(н, толщина_заливки(н, px, как)) for н in НАГРУЗКИ_ЗАЛИВКИ] for как in КАК_ЗАЛИВКИ}
    return _ТОЛЩИНЫ[px]


def _низ_стенда(px):
    """Самая тонкая сырая заливка стенда (ряды `ровно=1`, нагрузка 0,1)."""
    return _кривые(px)[КАК_ЗАЛИВКИ[0]][0][1]


def _нагрузка_заливки(толщина, px, неровно=False):
    """(нагрузка заливки, как) под сырую толщину: до верха рядов `ровно=1` (0,75 при нагрузке 1) — ими (числа В-4 те
    же), толще — рядами без `ровно` (до 1,05: обычный подмалёвок плоской 5 мм нагрузкой 1), ещё толще — двумя проходами
    рядами (`КАК_ЗАЛИВКИ`)."""
    кр = _кривые(px)
    низ, верх = кр[КАК_ЗАЛИВКИ[0]][0][1], кр[КАК_ЗАЛИВКИ[-1]][-1][1]
    if not (низ - 1e-9 <= толщина <= верх + 1e-9):
        ближ = float(np.clip(толщина, низ, верх))
        раз = ', '.join(f'{к} до {кр[к][-1][1]:.3g}' for к in КАК_ЗАЛИВКИ)
        raise ValueError(f'смешение_для: сырая толщина лежащего {толщина:.3g} вне стенда — заливка даёт '
                         f'{низ:.3g}…{верх:.3g} ({раз}; нагрузки {НАГРУЗКИ_ЗАЛИВКИ[0]:g}…{НАГРУЗКИ_ЗАЛИВКИ[-1]:g}); '
                         f'ближайшее — {ближ:.3g}')
    for как in КАК_ЗАЛИВКИ[1:] if неровно else КАК_ЗАЛИВКИ:      # В-4-3: слой бороздами — без `ровно`
        hh = [h for _, h in кр[как]]
        if неровно and как == КАК_ЗАЛИВКИ[1] and толщина < hh[0]:
            return float(np.interp(толщина, [h for _, h in кр[КАК_ЗАЛИВКИ[0]]], [н for н, _ in кр[КАК_ЗАЛИВКИ[0]]])), КАК_ЗАЛИВКИ[0]
        if толщина <= hh[-1] + 1e-9 or как == КАК_ЗАЛИВКИ[-1]:
            return float(np.interp(толщина, hh, [н for н, _ in кр[как]])), как


def _лаб(х, окно):
    """Средние по пикселям окна: (L серой шкалы, L, a, b OKLab)."""
    from .глаз import _вид, _рамка, oklab, _L
    lab = oklab(_вид(х, _рамка(х, окно), False)).reshape(-1, 3)
    return float(_L(lab[:, 0]).mean()), lab.mean(axis=0)


def доля_тона(lab_след, lab_краска, lab_лежит):
    """Где цвет следа на отрезке «краска хода → лежащее» в OKLab: 0 — краска, 1 — лежащее (проекция, не обрезана)."""
    d = np.asarray(lab_лежит, np.float64) - np.asarray(lab_краска, np.float64)
    n = float(d @ d)
    if n < 1e-10:
        return float('nan')
    return float((np.asarray(lab_след, np.float64) - lab_краска) @ d / n)


def замер_хода(х, кисть, краска, нагрузка, нажим, сид, разбавитель=None, ровно=None, px=ПХ, дл=ДЛИНА, раскладка='свой'):
    """Один ход стенда по холсту стенда `х` (кладёт на `х`!): {'L', 'lab', 'окно', 'ответ'} — мерка тела следа и
    ответ мазка. Раскладка: 'свой' — ход в слой заливки, 'ниже' — в слой над ней с `мешать_ниже=True`, 'поверх' — в
    слой над ней без смешения, 'два' — в слой верхней заливки `заливка_два` с `мешать_ниже=True`. Им же меряется живое
    в тесте пункта."""
    from .путь import путь_с_нажимом
    ш = float(кисть.ширина)
    yc = ВЫСОТА_ММ * px / 2
    a, b = (_px(v, px) for v in _геом(дл)[2])
    т = путь_с_нажимом([(a, yc), (b, yc)], ш, нажим=float(нажим), вход=ш / 2, сход=ш / 2, сид=сид)
    д = {}
    if разбавитель:
        д['разбавитель'] = float(разбавитель)
    if ровно:
        д['ровно'] = float(ровно)
    if раскладка in ('ниже', 'два'):
        д['мешать_ниже'] = True
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        о = х.мазок(т, краска, кисть.копия(), слой=СЛОЙ_ЛЕЖИТ if раскладка in ('свой', 'два') else СЛОЙ_ХОДА, сид=сид,
                    нагрузка=нагрузка, **д)
    w = (о.ширина if о is not None and о.ширина else 0) or ш
    окно = _окно_хода(px, w, дл)
    L, lab = _лаб(х, окно)
    return {'L': L, 'lab': lab, 'окно': окно, 'ответ': о}


def _средний_цвет(Ls, labs):
    from .глаз import цвет, шестн
    L = float(np.mean(Ls))
    a, b = float(np.mean([v[1] for v in labs])), float(np.mean([v[2] for v in labs]))
    C = math.hypot(a, b)
    h = math.degrees(math.atan2(b, a)) % 360.0 if C >= 1e-6 else 0.0
    rgb = цвет(L, C, h)
    return {'L': round(L, 2), 'C': round(C, 4), 'h': round(h, 1), 'rgb': rgb, 'hex': шестн(rgb)}


def _ответ_среднее(ответы):
    from .глаз import цвет, шестн
    цв = [о.цвет for о in ответы if о is not None and о.цвет is not None]
    if цв:
        L = float(np.mean([c['L'] for c in цв]))
        a = float(np.mean([c['C'] * math.cos(math.radians(c['h'])) for c in цв]))
        b = float(np.mean([c['C'] * math.sin(math.radians(c['h'])) for c in цв]))
        C = math.hypot(a, b)
        h = math.degrees(math.atan2(b, a)) % 360.0 if C >= 1e-6 else 0.0
        rgb = цвет(L, C, h)
        цвет_о = {'L': round(L, 2), 'C': round(C, 4), 'h': round(h, 1), 'rgb': rgb, 'hex': шестн(rgb)}
    else:
        цвет_о = None
    сыр = {к: round(float(np.mean([о.сырое[к] for о in ответы if о is not None])), 3)
           for к in ('по сырому', 'подобрано', 'к положенному')}
    return {'цвет': цвет_о, 'сырое': сыр}


def _краска(цвет, вид):
    from .краска import Краска
    from . import калибровка as кал
    if цвет is None:
        raise ValueError('смешение_для: нужен цвет=… — краска хода: (r, g, b), `Краска` или `цвет(L, C, h)`')
    кал._цвет(цвет)
    return Краска(tuple(int(round(float(v))) for v in tuple(цвет)[:3]), кал._вид_краски(вид, цвет))


def _прогноз(кисть, краска, лежит_rgb, заливки, нагрузка, нажим, разбавитель, ровно, px, дл, сиды=СИДЫ, раскладка='свой'):
    from .глаз import oklab
    if раскладка == 'два':
        база = заливка_два(заливки[0], заливки[1], px, дл)
    else:
        нагрузка_заливки, как_з = заливки
        база = заливка(лежит_rgb, нагрузка_заливки, px, дл=дл, как=как_з)
    w0 = РЯДЫ_ММ[0] * px
    Lл, lab_л = _лаб(база, _окно_хода(px, max(float(кисть.ширина), 1.0), дл))
    lab_к = oklab(np.asarray(tuple(краска)[:3], np.float64))
    с = база.снимок()
    Ls, labs, доли, ответы = [], [], [], []
    for сид in сиды:
        з = замер_хода(база, кисть, краска, нагрузка, нажим, сид, разбавитель, ровно, px, дл, раскладка)
        Ls.append(з['L'])
        labs.append(з['lab'])
        доли.append(доля_тона(з['lab'], lab_к, lab_л))
        ответы.append(з['ответ'])
        база.откатить(с)
    итог = _средний_цвет(Ls, labs)
    итог.update(доля=round(float(np.mean(доли)), 3), разброс_L=round(float(np.std(Ls)), 2),
                разброс_доли=round(float(np.std(доли)), 3), сидов=len(сиды))
    итог['ответ'] = _ответ_среднее(ответы)
    if раскладка == 'два':
        сл = _сырое_слоёв(заливка_два(заливки[0], заливки[1], px, дл), _окно_хода(px, w0, дл))
        итог['лежит'] = {'rgb': tuple(int(v) for v in лежит_rgb), 'L': round(Lл, 2), 'длина_мм': float(дл),
                         'толщина': round(сл[СЛОЙ_НИЗ][0] + сл[СЛОЙ_ЛЕЖИТ][0], 4),
                         'два': [{'слой': и, 'rgb': tuple(int(v) for v in з[0]), 'нагрузка_заливки': round(float(з[1]), 3),
                                  'заливка': з[2], 'толщина': round(сл[и][0], 4)}
                                 for и, з in ((СЛОЙ_НИЗ, заливки[0]), (СЛОЙ_ЛЕЖИТ, заливки[1]))]}
        return итог
    итог['лежит'] = {'rgb': tuple(int(v) for v in лежит_rgb), 'L': round(Lл, 2), 'нагрузка_заливки': round(нагрузка_заливки, 3),
                     'толщина': round(сырая_толщина(заливка(лежит_rgb, нагрузка_заливки, px, дл=дл, как=как_з),
                                                    _окно_хода(px, w0, дл)), 4),
                     'длина_мм': float(дл)}
    if как_з != 'ровно':
        итог['лежит']['заливка'] = как_з
    return итог


def _нагрузка(нагрузка):
    from .инструмент import НАГРУЗКИ as ИМЕНА
    if isinstance(нагрузка, str):
        if нагрузка not in ИМЕНА or нагрузка == 'сухая':
            raise ValueError(f'смешение_для: нагрузка {нагрузка!r} — числом или {", ".join(к for к in ИМЕНА if к != "сухая")}')
        return float(ИМЕНА[нагрузка])
    н = float(нагрузка)
    if not (НАГРУЗКИ[0] - 1e-9 <= н <= НАГРУЗКИ[1] + 1e-9):
        ближ = min(max(н, НАГРУЗКИ[0]), НАГРУЗКИ[1])
        raise ValueError(f'смешение_для: нагрузка {н:g} вне стенда — {НАГРУЗКИ[0]:g}…{НАГРУЗКИ[1]:g}; ближайшее — {ближ:g}')
    return н


def _неровность(х, область, слой):
    """В-4-3: σ/среднее сырой толщины слоя в области — борозды рядов (0 — ровный)."""
    где = х._область(область)
    с = х.слои[слой]
    h = np.asarray(с.толщина[где], np.float64) * np.asarray(с.влажность[где], np.float64)
    return float(h.std() / h.mean()) if h.size and h.mean() > 1e-9 else 0.0


def _сырое_слоёв(х, область):
    """Сырая толщина места по слоям: имя -> (сырая, вся толщина) — как `сырая_толщина`, слой за слоем."""
    from .числа import _СХВАТ
    где = х._область(область)
    итог = {}
    for и, с in х.слои.items():
        т = np.asarray(с.толщина[где], np.float64)
        h = т * np.asarray(с.влажность[где], np.float64) * (1.0 - _СХВАТ * np.asarray(с.схват[где], np.float64))
        итог[и] = (float(h.mean()) if h.size else 0.0, float(т.mean()) if т.size else 0.0)
    return итог


def _цвета_слоёв(х, место, слой):
    """В-4-3: (sRGB краски слоя `слой` в месте — среднее его цвета по покрытию, sRGB того, что под ним — грунт и слои
    ниже, как их видит глаз без света), 0–255."""
    from .краска import из_линейного
    где = х._область(место)
    имена = list(х.слои)
    к = np.empty(np.asarray(х.слои[имена[0]].покрытие[где]).shape + (3,), np.float64)
    к[:] = х.грунт
    for и in имена[:имена.index(слой)]:
        с = х.слои[и]
        a = np.asarray(с.покрытие[где], np.float64)[..., None]
        if с.пропуск is not None:
            к *= np.asarray(с.пропуск[где], np.float64)
        к += (np.asarray(с.цвет[где], np.float64) - к) * a
    с = х.слои[слой]
    a = np.asarray(с.покрытие[где], np.float64)[..., None]
    свой = (np.asarray(с.цвет[где], np.float64) * a).reshape(-1, 3).sum(0) / max(float(a.sum()), 1e-9)
    в8 = lambda lin: tuple(int(round(v)) for v in np.clip(из_линейного(lin) * 255.0, 0, 255))
    return в8(свой), в8(к.reshape(-1, 3).mean(0))


def _раскладка_холста(х, место, слой, мешать_ниже):
    """Слои места против слоя хода — как их увидит `х.мазок(…, слой=слой, мешать_ниже=…)`: ход мешается с сырой краской
    своего слоя, с `мешать_ниже` — и слоёв под ним. Ответ: (раскладка стенда, сырая толщина, с которой мешается
    (или — для 'поверх' — сырая под ходом), {'ход', 'мешается', 'не_мешается', 'выше'}, слово или None)."""
    по = _сырое_слоёв(х, место)
    имена = list(по)
    if слой in имена:
        ниже, выше = имена[:имена.index(слой)], имена[имена.index(слой) + 1:]
    else:
        ниже, выше = имена, []                     # слоя нет — мазок заведёт его наверху
    свой = по.get(слой, (0.0, 0.0))[0]
    под = sum(по[и][0] for и in ниже)
    слои = {'ход': слой, 'мешать_ниже': bool(мешать_ниже),
            'мешается': [и for и in ([слой] if слой in по else []) + (ниже if мешать_ниже else []) if по[и][0] > СЫРО],
            'не_мешается': [и for и in ([] if мешать_ниже else ниже) if по[и][0] > СЫРО],
            'выше': [и for и in выше if по[и][1] > СЫРО]}
    слова = []
    if слои['выше']:
        слова.append(f'над слоем {слой!r} в месте лежит краска слоёв {", ".join(map(repr, слои["выше"]))} — на холсте '
                     'след будет под ней (прогноз — цвет самого следа, без неё)')
    мешается = свой + (под if мешать_ниже else 0.0)
    if мешать_ниже and свой > СЫРО and под > СЫРО:     # В-4-3: стенд в два слоя — лежащее своего над лежащим нижних
        if len(слои['мешается']) > 2:
            слова.append(f'сырое в {len(слои["мешается"])} слоях — стенд кладёт два: свой и всё под ним одной заливкой '
                         '(цвет — как видно под слоем хода)')
        return 'два', (свой, под), слои, ('; '.join(слова) or None)
    if мешается > СЫРО:
        раскладка = 'свой' if свой >= (под if мешать_ниже else 0.0) else 'ниже'
        return раскладка, мешается, слои, ('; '.join(слова) or None)
    if под > СЫРО:
        слова.insert(0, f'ход ляжет поверх: в слое {слой!r} сырого нет, а сырое под ним (слои '
                        f'{", ".join(map(repr, слои["не_мешается"]))}) ход не берёт — нужно мешать_ниже=True '
                        'или слой лежащего; доля — просвет и непокрытое, не смешение')
        return 'поверх', под, слои, '; '.join(слова)
    raise ValueError(f'смешение_для: в месте {tuple(место)} сырой краски нет (толщина × влажность ≈ 0) — по сухому '
                     'смешения нет: след ляжет поверх (`нагрузка_для`, `о.цвет`)')


def _лежит(лежит, холст, толщина, подмалёвок, px, слой=None, мешать_ниже=False, лежит_в=None):
    """(rgb лежащего, (нагрузка заливки стенда, как), раскладка, слои, слово)."""
    if (толщина is not None) and (подмалёвок is not None):
        raise ValueError('смешение_для: толщина лежащего — одно из двух: толщина= (сырая, как `Слой.толщина`) или '
                         'подмалёвок= (нагрузка заливки)')
    try:
        т = tuple(float(v) for v in tuple(лежит))
    except (TypeError, ValueError):
        т = ()
    слой_х = 'основа' if слой is None else str(слой)
    if len(т) == 4:                                  # место холста модели
        if холст is None:
            raise ValueError('смешение_для: лежит=(x0, y0, x1, y1) — место холста: дай и холст=х')
        if лежит_в is not None:
            raise ValueError('смешение_для: лежит_в= — только без холста; с холст= слои места берутся с холста')
        rgb = tuple(холст.средний(т, свет=False)['rgb'])
        раскладка, сыро, слои, слово = _раскладка_холста(холст, т, слой_х, мешать_ниже)
        if раскладка == 'два':
            if толщина is not None or подмалёвок is not None:
                raise ValueError('смешение_для: сырое места в двух слоях (слой хода и под ним, мешать_ниже) — толщины '
                                 'берутся с холста слой за слоем; толщина= и подмалёвок= не давай')
            низ = _низ_стенда(px)
            if min(сыро) >= низ:
                свой_rgb, под_rgb = _цвета_слоёв(холст, т, слой_х)
                имена = list(холст.слои)
                под_н = [и for и in имена[:имена.index(слой_х)] if и in слои['мешается']]
                нер_под = any(_неровность(холст, т, и) > НЕРОВНО for и in под_н)
                нер_свой = _неровность(холст, т, слой_х) > НЕРОВНО
                if нер_под or нер_свой:
                    слово = '; '.join([с for с in (слово,) if с] + [
                        f'прогноз мимо до 10 L: сырое в двух слоях бороздами (σ/среднее толщины > {НЕРОВНО:g}) — '
                        'стенд кладёт оба своими рядами поперёк хода, борозды места не повторяет (на пробах — 1–10 L, '
                        'больше у толстого слоя хода бороздами вдоль хода); по ровному сырому — в 2 L; точнее — х.проба'])
                слои['раскладка'] = раскладка
                return rgb, ((под_rgb,) + _нагрузка_заливки(сыро[1], px, нер_под),
                             (свой_rgb,) + _нагрузка_заливки(сыро[0], px, нер_свой)), раскладка, слои, слово
            мало = слой_х if сыро[0] < низ else 'под ним'
            раскладка = 'свой' if сыро[0] >= сыро[1] else 'ниже'
            слово = '; '.join([с for с in (слово,) if с] + [
                f'сырое в двух слоях, но {"в слое " + repr(мало) if мало == слой_х else мало} его мало '
                f'({min(сыро):.3g} < {низ:.3g} — тоньше заливки стенда): стенд кладёт всё ({sum(сыро):.3g}) одной '
                'заливкой цвета места'])
            толщина = sum(сыро)
        elif толщина is None and подмалёвок is None:
            толщина = сыро
    elif len(т) == 3:
        from . import калибровка as кал
        кал._цвет(т)
        rgb = tuple(int(round(v)) for v in т)
        лв = слой_х if лежит_в is None else str(лежит_в)
        if лв == слой_х:
            раскладка, слово = 'свой', None
        elif мешать_ниже:
            раскладка, слово = 'ниже', None
        else:
            раскладка = 'поверх'
            слово = (f'ход ляжет поверх: лежащее в слое {лв!r}, ход — в {слой_х!r} без мешать_ниже — с сырым под собой '
                     'не мешается; доля — просвет и непокрытое, не смешение')
        слои = {'ход': слой_х, 'мешать_ниже': bool(мешать_ниже), 'мешается': [] if раскладка == 'поверх' else [лв],
                'не_мешается': [лв] if раскладка == 'поверх' else [], 'выше': []}
    else:
        raise ValueError(f'смешение_для: лежит={лежит!r} — цвет сырой краски (r, g, b) или место холста (x0, y0, x1, y1) '
                         'с холст=')
    слои['раскладка'] = раскладка
    if подмалёвок is not None:
        н = float(подмалёвок)
        if not (НАГРУЗКИ_ЗАЛИВКИ[0] - 1e-9 <= н <= НАГРУЗКИ_ЗАЛИВКИ[-1] + 1e-9):
            ближ = min(max(н, НАГРУЗКИ_ЗАЛИВКИ[0]), НАГРУЗКИ_ЗАЛИВКИ[-1])
            raise ValueError(f'смешение_для: подмалёвок {н:g} вне стенда — нагрузка заливки {НАГРУЗКИ_ЗАЛИВКИ[0]:g}…'
                             f'{НАГРУЗКИ_ЗАЛИВКИ[-1]:g}; ближайшее — {ближ:g}')
        return rgb, (н, 'ровно'), раскладка, слои, слово
    if толщина is None:
        raise ValueError('смешение_для: сколько лежит — толщина= (сырая толщина, как `Слой.толщина`; с места холста — '
                         'сама) или подмалёвок= (нагрузка заливки рядами `плоская` 5 мм, `ровно=1`)')
    return rgb, _нагрузка_заливки(float(толщина), px), раскладка, слои, слово


def _уточнить(прогноз, цель, н, a, b, нж, шагов=4, точно=0.02):
    """Корень перебора (сиды `СИДЫ_ПОИСКА`) — всеми сидами `СИДЫ`: ложное положение внутри отрезка сетки [a, b] по log
    нагрузки; в крутом месте 8 сидов и 24 расходятся на 0,05–0,1 доли. Ответ — прогноз в лучшей точке."""
    def в(x):
        п = прогноз(round(float(x), 4))
        п.update(нагрузка=round(float(x), 4), нажим=нж)
        return п
    лучший = в(н)
    if abs(лучший['доля'] - цель) <= точно or a == b:
        return лучший
    la, lb = math.log(a), math.log(b)
    fa, fb = в(a)['доля'] - цель, в(b)['доля'] - цель
    for _ in range(шагов):
        if fa * fb > 0:
            break
        x = la + (lb - la) * fa / (fa - fb) if fa != fb else (la + lb) / 2
        п = в(math.exp(x))
        f = п['доля'] - цель
        if abs(f) < abs(лучший['доля'] - цель):
            лучший = п
        if abs(f) <= точно:
            break
        if f * fa < 0:
            lb, fb = x, f
        else:
            la, fa = x, f
    return лучший


def смешение_для(кисть, лежит, цвет=None, доля=None, нагрузка=None, нажим=None, вид=None, разбавитель=None, ровно=None,
                 толщина=None, подмалёвок=None, длина=None, холст=None, px_на_мм=None, слой=None, мешать_ниже=False,
                 лежит_в=None):
    """В-4: один ход по лежащей сырой краске числом — до кладки.

    лежит — сырая краска под ходом: цвет (r, g, b) с толщиной (`толщина=` — сырая, единицы `Слой.толщина`, или
    `подмалёвок=` — нагрузка заливки стенда 0,1–1) или место холста (x0, y0, x1, y1) с `холст=х`: цвет — `х.средний`
    места без света, толщина — сырая краска места (сумма слоёв толщина × влажность × (1 − 0,85 × схват)), если не дана.
    цвет — краска хода (sRGB, `Краска` — с неё и вид, `цвет(L, C, h)`), обязателен. Кисть — любая, как есть (копией). длина — ход, мм.

    С нагрузкой — прогноз: {'доля' — доля тона лежащего в теле следа (0 — краска хода, 1 — лежащее; OKLab),
    'L', 'C', 'h', 'rgb', 'hex' — цвет тела следа (как `х.средний` средней половины хода и ширины), 'разброс_L',
    'разброс_доли' — по сиду (один ход гуляет на столько), 'ответ' — среднее `о.цвет` и `о.сырое` хода, 'лежит' —
    цвет, L и сырая толщина подмалёвка стенда, 'нагрузка', 'нажим'}. С заказом `доля=` — нагрузка под неё (нажим дан —
    при нём; нет — сперва 0,6, затем ближние 0,5, 0,65, 0,35, 0,8) и прогноз в этой точке; из нескольких нагрузок —
    наибольшая (кроет плотнее). Недостижимое и вне стенда — `ValueError` с ближайшим.

    Слой (В-4-2) — как у `х.мазок`: `слой=` — слой хода (умолчание 'основа', как у мазка), `мешать_ниже=` — мешать и с
    сырым слоёв под ним. Ход берёт сырое только своего слоя (с `мешать_ниже` — и нижних). С `холст=` слои места
    читаются с холста: толщина — сырое тех слоёв, с которыми ход смешается; стенд кладёт заливку в свой слой, ход —
    в тот же слой ('свой'), в слой над ней с `мешать_ниже` ('ниже') или без смешения ('поверх': сырое только под ходом,
    а он его не берёт — прогноз цвета есть, но 'слово' и предупреждение: «ход ляжет поверх»). Без холста лежащее —
    в слое хода, иначе `лежит_в=` — имя его слоя (под слоем хода). В ответе 'слои': {'ход', 'мешать_ниже', 'мешается',
    'не_мешается', 'выше', 'раскладка'}; 'слово' — когда прогноз не о смешении или над ходом лежит чужой слой.

    Счёт — ход на своём стенде (`кисть/смешение.py`): гладкий грунт (166, 146, 129), подмалёвок — заливка рядами одной
    кроющей краской (сырая толщина 0,07–0,75 — ряды `ровно=1`, до 1,05 — без `ровно`, толще — два прохода), ход прямо поперёк рядов длиной
    `длина=` (мм, умолчание 45), 24 сида. Свой путь, зерно, прозрачный или многослойный подмалёвок,
    лежащее пятнами — ближе к `х.проба`. Только счёт: холст модели, кисть и журнал не меняются."""
    px = float(холст.px_на_мм) if (холст is not None and холст.px_на_мм) else float(px_на_мм or ПХ)
    краска = _краска(цвет, вид)
    дл = ДЛИНА if длина is None else float(длина)
    if not (ДЛИНЫ[0] <= дл <= ДЛИНЫ[1]):
        ближ = min(max(дл, ДЛИНЫ[0]), ДЛИНЫ[1])
        raise ValueError(f'смешение_для: длина хода {дл:g} мм — стенд {ДЛИНЫ[0]:g}…{ДЛИНЫ[1]:g} мм; ближайшее — {ближ:g}')
    лежит_rgb, нз, рк, слои, слово = _лежит(лежит, холст, толщина, подмалёвок, px, слой, мешать_ниже, лежит_в)

    def готово(п):
        п['слои'] = dict(слои)
        if слово:
            п['слово'] = слово
            warnings.warn('смешение_для: ' + слово, stacklevel=3)
        return п
    if разбавитель is not None and not (0.0 <= float(разбавитель) <= 1.0):
        raise ValueError(f'смешение_для: разбавитель {float(разбавитель):g} — от 0 до 1')
    if нажим is not None and not (0.05 <= float(нажим) <= 1.0):
        ближ = min(max(float(нажим), 0.05), 1.0)
        raise ValueError(f'смешение_для: нажим {float(нажим):g} — от 0,05 до 1; ближайшее — {ближ:g}')
    if доля is None:
        if нагрузка is None:
            raise ValueError('смешение_для: дай нагрузка= (прогноз) или доля= (заказ)')
        н = _нагрузка(нагрузка)
        нж = НАЖИМ if нажим is None else float(нажим)
        п = _прогноз(кисть, краска, лежит_rgb, нз, н, нж, разбавитель, ровно, px, дл, раскладка=рк)
        п.update(нагрузка=н, нажим=нж)
        return готово(п)
    if нагрузка is not None:
        raise ValueError('смешение_для: с доля= нагрузку не давай — она и подбирается (нажим — можно)')
    цель = float(доля)
    if not (0.0 < цель < 1.0):
        raise ValueError(f'смешение_для: доля {цель:g} — от 0 до 1 (доля тона лежащего в следе)')
    нажимы = (float(нажим),) if нажим is not None else (НАЖИМ,) + tuple(sorted(НАЖИМЫ, key=lambda v: abs(v - НАЖИМ)))
    сетка = СЕТКА_НАГРУЗКИ
    наим, наиб, где = 2.0, -1.0, None
    for нж in нажимы:
        v = np.array([_прогноз(кисть, краска, лежит_rgb, нз, н, нж, разбавитель, ровно, px, дл, СИДЫ_ПОИСКА, рк)['доля']
                      for н in сетка]) - цель
        if np.all(np.isfinite(v)):
            if наим > v.min() + цель:
                наим = float(v.min() + цель)
            if наиб < v.max() + цель:
                наиб = float(v.max() + цель)
        корни = []                                   # (нагрузка по сетке, отрезок сетки)
        for i in range(len(сетка) - 1):
            if v[i] == 0 or v[i] * v[i + 1] < 0:
                a, b = math.log(сетка[i]), math.log(сетка[i + 1])
                t = v[i] / (v[i] - v[i + 1]) if v[i] != v[i + 1] else 0.0
                корни.append((math.exp(a + (b - a) * t), (сетка[i], сетка[i + 1])))
        if v[-1] == 0:
            корни.append((сетка[-1], (сетка[-1], сетка[-1])))
        if корни:
            н, (a, b) = корни[-1]
            return готово(_уточнить(lambda x: _прогноз(кисть, краска, лежит_rgb, нз, x, нж, разбавитель, ровно, px, дл,
                                                       раскладка=рк), цель, float(н), a, b, нж))
    if наиб < 0:
        raise ValueError('смешение_для: у краски хода и лежащего один цвет — доли тона нет')
    ближ = наим if цель < наим else наиб
    чем = f'нажим {нажимы[0]:g}' if len(нажимы) == 1 else f'нажимы {", ".join(f"{v:g}" for v in нажимы)}'
    raise ValueError(f'смешение_для: доля {цель:g} недостижима ({чем}, нагрузка {сетка[0]:g}…{сетка[-1]:g}): ход берёт '
                     f'{наим:.2f}…{наиб:.2f} тона лежащего; ближайшее — {ближ:.2f}' +
                     ('; меньше лежащего — гуще краска, легче рука, подсушить лежащее (`х.подсушить`)' if цель < наим
                      else '; больше лежащего — тоньше краска и сильнее нажим, мягкая кисть или растушёвка вытертой'))
