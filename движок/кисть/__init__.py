def план_покрытия(кисть, покрытие, шаг_рядов=0.8, сушка=False, нажим=0.6, вид=None, разбавитель=None, цвет=None,
                  px_на_мм=None, проходов=None, длина=None):
    """В-3: сколько проходов серии параллельных рядов и какая нагрузка дадут покрытие — по таблице одиночного хода и
    закону накопления; ничего не кладёт. Подробно — `кисть.ряды.план_покрытия`, справочник «Калибровка покрытия».
    О-1: у кисти с живой краской в ответе ещё 'хватит_мм' (путь остатка нагрузкой плана — `к.хватит`), 'хватит' и, с
    `длина=` (мм ряда), 'рядов_до_добора'; px холста — `px_на_мм` (без него 8). Без живой краски — ответ прежний."""
    from .ряды import план_покрытия as п
    from .хватит import с_остатком
    ответ = п(кисть, покрытие, шаг_рядов=шаг_рядов, сушка=сушка, нажим=нажим, вид=вид, разбавитель=разбавитель, цвет=цвет,
              px_на_мм=px_на_мм, проходов=проходов)
    return с_остатком(ответ, кисть, нажим, разбавитель, px_на_мм, длина, план=True)



