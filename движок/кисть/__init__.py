def нагрузка_для(кисть, покрытие=None, нажим=0.6, вид=None, разбавитель=None, толщина=None, px_на_мм=None, цвет=None,
                длина=None):
    """5е, 5е-2 (В-2): нагрузка под покрытие или толщину одиночного хода по сухому — по таблице; не кроющей краске нужен
    `цвет=`. Подробно — `кисть.калибровка.нагрузка_для`, справочник «Калибровка покрытия». О-1: у кисти с живой краской
    (`к.набрать(цвет, количество)`) ответ — то же число с полями `.хватит_мм` (на сколько мм пути хватит остатка этой
    нагрузкой и нажимом — `к.хватит`), `.хватит` (весь ответ) и, с `длина=` (мм хода), `.на_ход` (True — хватит);
    px холста — `px_на_мм` (без него 8). У кисти без живой краски — прежнее число, как было."""
    from .калибровка import нагрузка_для as н
    from .хватит import с_остатком
    ответ = н(кисть, покрытие=покрытие, нажим=нажим, вид=вид, разбавитель=разбавитель, толщина=толщина, px_на_мм=px_на_мм,
              цвет=цвет)
    return с_остатком(ответ, кисть, нажим, разбавитель, px_на_мм, длина)


