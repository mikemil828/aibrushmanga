"""Кисть как инструмент: пресет, нагрузка, набранная краска; разбор цвета из вызова."""
import json
import os
from dataclasses import dataclass, fields, asdict

import numpy as np

from .быстро import зажать



from .числа import _ПОЛ_ПЛЁНКИ, _СУХАЯ
from . import числа as Ч

НАГРУЗКИ = {'протирка': 0.10, 'обычная': 0.28, 'пастозная': 0.90, 'сухая': _СУХАЯ[0]}   # 'сухая' (п. 10, инструмент 2) — полупустая кисть: `укладка`, `числа._СУХАЯ`


def масштаб_толщины(ширина):
    """Узкая кисть несёт меньше: толщина плёнки идёт как ширина в степени 0,8 (1 при 40 px). У кисти уже
    `_ПОЛ_ПЛЁНКИ` px (п. 10) плёнка дальше не тоньшает: тонкая кисть кладёт краску кончиком, слой у неё как у кисти
    этой ширины, иначе след в 3–6 px по сырому тонет в лежащей краске."""
    return (max(float(ширина), _ПОЛ_ПЛЁНКИ) / (40.0 * Ч._ММ)) ** 0.8      # Д-8: 40 px и пол — px холста 8 px/мм (`мм.в_мм`)


def _после_мазков(к, поле):
    """Поле кисти, которое пишет мазок: если мазки этой кисти ещё считаются на ядрах — сперва досчитать их."""
    д = к.__dict__
    ждёт = д.get('_ждёт_ядра')
    if ждёт is not None:
        ждёт.к_кисти(к)
    return д.get(поле + '·')


def сырое_поле(к, поле):
    """То же поле как лежит, без досчёта мазков на ядрах (в нём может стоять метка мазка очереди) — для `ядра.py` и журнала."""
    return к.__dict__.get(поле + '·')


@dataclass
class Кисть:
    имя: str = 'кисть'
    форма: str = 'плоская'            # 'плоская' | 'круглая' | 'мастихин'
    ширина: float = 32.0              # px, ширина следа при полном нажиме
    нагрузка: object = 'обычная'      # 'протирка' | 'обычная' | 'пастозная' или число: толщина плёнки при ширине 40 px
    толщина: float = 1.0              # множитель к толщине от нагрузки (оставлен от версии 1)
    шаг: float = 2.5                  # px между ведущими волосками (шаг борозд), в среднем
    неровность_шага: float = 0.46     # разброс шага (лог-нормальный); 0 — гребёнка
    ряды: int = 3                     # рядов ворса: больше — мельче борозды (задние ряды заглаживают)
    разброс_длин: float = 0.34        # на какую долю нажима короткая прядь касается позже длинной
    разброс_жёсткости: float = 0.45   # разброс нажима кончиков: от него глубина борозд разная
    запас: float = 14.0               # на сколько ширин кисти хватает краски
    вязкость: float = 0.6             # 0..1: глубина борозд, сгусток на отрыве, падение отдачи на скорости
    подбор: float = 0.5               # 0..1: какую долю сырой краски под собой берёт волосок
    укрывистость: float = 1.0         # >1 — кроет более тонким слоем
    отставание: float = 0.55          # поворот плоской кисти отстаёт на столько ширин пути
    распластывание: float = 0.5       # доля ширины следа при нулевом нажиме
    клочки: float = 0.6               # 0..1: насколько пряди живут врозь (просветы, разная длина хвостов)
    разброс_тона: float = 1.0         # недомешанная краска: 1 — соседние пряди расходятся на 3–6 уровней светлоты
    тон_кисти: float = 0.0            # 11а/11в: 0 (умолчание) — среднее тона по кисти равно набранной краске; 1 — вся порция ещё и светлее или темнее набранной (σ 7 %, до 17 %), просить явно
    сухость: float = 0.0              # сдвиг порога сухой кисти: 0 — нагруженная, 0.3 — полусухая
    валик: float = 0.6                # валик с одной стороны пастозного мазка и сгусток на отрыве
    вынос: float = 1.0                # на сколько ширин кисть несёт подобранную краску
    бродяги: float = 0.0              # (не используется в версии 2; оставлен, чтобы читались старые пресеты)
    касание: float = 1.0              # плоская кисть: 1 — плашмя (вся ширина и при лёгком нажиме), 0 — на ребре/уголке
    ширина_мм: object = None          # п. 9: ширина в мм — тогда `ширина` берётся из неё по px_на_мм холста; None — в px
    шаг_мм: object = None             # п. 9: шаг ведущих волосков в мм; None — `шаг` в px (не масштабируется)
    остриё: float = 1.0               # п. 12: узкая кисть (до 12 px, к 16 px сходит на нет) собрана в острый кончик: след идёт за нажимом, концы клином (травинка, линия); 0 — щетина в обойме: и узкая лежит плашмя всей шириной, серия ходов внахлёст сходится в массу (пресет `плоская`)
    неровность_запаса: float = 1.0    # К8.3: насколько краска на волоске лежит неровно вдоль хода (`борозда.неровный_запас`): щетина — 1; мягкий длинный волос лайнера набирает её ровно — след не рвётся и не худеет на сотне px
    кайма: float = 0.0                # п. 10, инструмент 4: мягкая кисть — доля ширины с каждого бока, где волос к краю пучка короче, реже и беднее краской (`мягкая.py`); 0 — щетина, как было
    пучок_мм: object = None           # Д-7: толщина пучка плоской, мм: на ребре (`касание` 0) след — полоса этой толщины; None — по ширине кисти (`укладка.толщина_пучка`: 0,225 ширины, 0,5–3 мм); 0 — толщины нет (как до Д-7)
    просветы: float = 0.0             # К-14б: доля ширины кисти без волоса (0–0,9): ворс стоит пучками, между ними пусто — ход кладёт не полосу, а линии пучков, у каждого своя длина, нагрузка и жёсткость (веерная, растрёпанная); 0 — сплошной ворс, как было
    в_пучке: float = 1.0              # К-14б: сколько гребней ворса в пучке в среднем (работает с `просветы`): 1 — пучок в один гребень, линия шириной в `шаг`; 4 — клок старой кисти
    веер: float = 0.0                 # К-14б: ворс разложен веером — кончики стоят дугой: середина кисти выдаётся за края на эту долю ширины (веерная — 0,15–0,25); начало и конец следа и отпечаток тычка идут дугой; 0 — кончики в линию, как было

    def __setattr__(self, имя, v):
        """Правка поля кисти (`к.разброс_тона = 0.3`) — только известного: опечатка — ошибка с ближайшим именем (Е-7), а не
        новый атрибут, которого не видят ни мазок, ни журнал. Своё (`_остаток`, `_краска`…) — с подчёркиванием."""
        if not имя.startswith('_') and имя not in _ПОЛЯ_КИСТИ:
            raise AttributeError(f'кисть: {подсказка(имя, _ПОЛЯ_КИСТИ)} (поля — `python -m кисть.справка кисть`)')
        object.__setattr__(self, имя, v)

    # 2б: что мазок оставляет в кисти (подобранное, набранное, баланс). Мазок на ядрах (`ядра.py`) досчитывается позже
    # вызова: чтение такого поля сперва досчитывает мазки этой кисти — снаружи кисть всегда та же, что на одном ядре
    _остаток = property(lambda self: _после_мазков(self, '_остаток'), lambda self, v: self.__dict__.__setitem__('_остаток·', v))
    _набрано = property(lambda self: _после_мазков(self, '_набрано'), lambda self, v: self.__dict__.__setitem__('_набрано·', v))
    _баланс = property(lambda self: _после_мазков(self, '_баланс'), lambda self, v: self.__dict__.__setitem__('_баланс·', v))

    def __post_init__(self):
        self._остаток = None          # что осталось на кончиках после прошлого мазка: (K/S по местам, есть ли)
        self._краска = None           # набранная краска: (список (линейный RGB, доля), раскладка)
        self._набор = None            # как её набрали: (цвет вызова, раскладка, тот же объект _краска) — для журнала (А-1)

    # ---------------------------------------------------------------- файлы
    @classmethod
    def из_файла(cls, путь, **замены):
        if not os.path.exists(путь):
            рядом = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), путь)
            if os.path.exists(рядом):
                путь = рядом
        with open(путь, encoding='utf-8') as f:
            д = json.load(f)
        д.update(замены)
        return cls.из_словаря(д)

    @classmethod
    def из_словаря(cls, д):
        имена = {f.name for f in fields(cls)}
        лишние = set(д) - имена
        if лишние:
            raise ValueError('неизвестные параметры кисти: ' + '; '.join(подсказка(л, имена) for л in sorted(лишние)))
        return cls(**д)

    def в_файл(self, путь):
        with open(путь, 'w', encoding='utf-8') as f:
            json.dump(asdict(self), f, ensure_ascii=False, indent=2)

    def с(self, **замены):
        """Копия кисти с другими параметрами. Копия чистая: подобранная краска не переходит."""
        д = asdict(self)
        д.update(замены)
        return type(self).из_словаря(д)

    # ------------------------------------------------------- краска на кисти
    def вытереть(self):
        """Вытереть кисть о тряпку: следующий мазок начнётся чистой краской (подобранного на кончиках нет). У кисти с
        живой краской (Д-1, `набрать(цвет, количество)`) тряпка снимает и краску: с кончиков — всю, из ворса — большую
        часть (`числа._ЗАГРУЗКА`): следующий ход — бедный, протиркой."""
        self._остаток = None
        кр = self._краска
        if isinstance(кр, Загрузка):
            self._сменить(кр.после('wipe', кр.запас * Ч._ЗАГРУЗКА[1], кр.капля * 0.0))
        return self

    def промыть(self):
        """Д-1: промыть кисть — чистая и пустая: ни подобранного, ни набранной краски; мазок без цвета — после `набрать`."""
        self._остаток = self._краска = self._набор = None
        self._промыта = True              # для журнала: следующий набор живой краски — после промывки (строка "rinse")
        return self

    def набрать(self, цвет, количество=None, раскладка='полосы'):
        """Взять краску (sRGB 0..255 или список [(rgb, доля), ...]) поверх того, что осталось на кончиках.
        Мазок без цвета (`цвет=None`) пишет набранной.

        количество (Д-1) — сколько краски взято, в долях полной кисти: 1 — кисть полна, 0,5 — половина. Полная кисть —
        один и тот же объём краски, каким бы ходом её ни клали (Д-1-2; свежая кисть хода с цветом в вызове набрана со
        случаем хода — вокруг того же объёма). С количеством краска на кисти живая: ход без цвета тратит её, следующий начинается с
        остатка — кисть пустеет от хода к ходу, след беднеет и рвётся; сколько осталось — `к.осталось` и поле ответа
        мазка `осталось`. None — как было: кисть полна на каждом ходе. Имя замеса палитры — `х.набрать(к, 'имя', …)`."""
        from .краска import в_линейный
        if isinstance(количество, str):       # прежний вызов `набрать(цвет, 'смесь')`: второй довод был раскладкой
            количество, раскладка = None, количество
        пара = (разобрать_цвет(цвет, в_линейный), раскладка)
        if количество is not None:
            q = float(количество)
            if not 0.0 < q <= 1.0:
                raise ValueError(f'набрать: количество {количество} — доля полной кисти, больше 0 и не больше 1 (None — кисть полна на каждом ходе)')
            пара = Загрузка(пара, np.full(Ч._КОРЗИН, q), np.full(Ч._КОРЗИН, min(q / Ч._ЗАГРУЗКА[0], 1.0)),
                            ((('rinse',),) if self.__dict__.get('_промыта') and self._остаток is None else ()) + (('load', q),))
        self.__dict__.pop('_промыта', None)
        self._краска = пара
        self._набор = (цвет, раскладка, self._краска)
        return self

    @property
    def осталось(self):
        """Д-1: сколько набранной краски осталось в ворсе, в долях полной кисти (0–1); None — краска не живая
        (`набрать` без количества: кисть полна на каждом ходе) или не набрана."""
        кр = self._краска
        return round(float(кр.запас.mean()), 4) if isinstance(кр, Загрузка) else None

    def _сменить(self, новая):
        """Д-1: то, что на кисти, стало другим (ход потратил, тряпка сняла) — набор остаётся тем же набором."""
        if self._набор is not None and self._набор[2] is self._краска:
            self._набор = (self._набор[0], self._набор[1], новая)
        self._краска = новая

    def _запомнить(self, места, кс_капли):
        """Что осталось на кончиках — в память кисти (следующий мазок начнётся с этого). места — место гребня поперёк
        кисти в долях ширины (−0,5…0,5), кс_капли — K/S капель гребней. Перенесено из `укладка.py` как было."""
        from .числа import _КОРЗИН
        место = зажать(((места + 0.5) * _КОРЗИН).astype(np.intp), 0, _КОРЗИН - 1)
        кс_капли = np.asarray(кс_капли, np.float64)       # Е-3: `np.bincount` — те же суммы в том же порядке, что `np.add.at`
        C = кс_капли.shape[1]
        кс_ост = np.bincount((место[:, None] * C + np.arange(C)).ravel(), кс_капли.ravel(), _КОРЗИН * C).reshape(_КОРЗИН, C)
        есть_ост = np.bincount(место, None, _КОРЗИН).astype(np.float64)
        пусто = есть_ост == 0
        if пусто.any():
            ближ = np.abs(np.arange(_КОРЗИН)[:, None] - np.nonzero(~пусто)[0][None, :]).argmin(axis=1)
            кс_ост[пусто] = кс_ост[~пусто][ближ[пусто]]
            есть_ост[пусто] = есть_ост[~пусто][ближ[пусто]]
        self._остаток = (кс_ост / есть_ост[:, None], np.ones(_КОРЗИН))

    def копия(self):
        """Копия с тем, что на кисти (подобранное, набранное): мазок копией не пачкает эту кисть (проба, процессы)."""
        import copy
        н = self.с()
        н._остаток = copy.deepcopy(self._остаток)
        н._краска = copy.deepcopy(self._краска)
        if self._набор is not None and self._набор[2] is self._краска:
            н._набор = (self._набор[0], self._набор[1], н._краска)
        return н

    def в_пикселях(self, px_на_мм):
        """Кисть в пикселях холста с масштабом px_на_мм (п. 9). Без размеров в мм — она сама; иначе — копия
        с `ширина` и `шаг` в px и с тем же, что на кончиках (что подобрала копия, `Холст.мазок` вернёт сюда)."""
        if self.ширина_мм is None and self.шаг_мм is None:
            return self
        if px_на_мм is None:
            raise ValueError('кисть в мм: у холста не задан px_на_мм')
        з = {'ширина_мм': None, 'шаг_мм': None}
        if self.ширина_мм is not None:
            з['ширина'] = float(self.ширина_мм) * float(px_на_мм)
        if self.шаг_мм is not None:
            з['шаг'] = float(self.шаг_мм) * float(px_на_мм)
        н = self.с(**з)
        н._остаток, н._краска = self._остаток, self._краска      # Д-1: и живая краска — та же (`Загрузка`)
        return н

    def грязная(self):
        return self._остаток is not None

    def толщина_плёнки(self, нагрузка=None):
        """Толщина плёнки полного мазка этой кистью, единицы h."""
        н = self.нагрузка if нагрузка is None else нагрузка
        if isinstance(н, str):
            if н not in НАГРУЗКИ:
                raise ValueError(f'нагрузка: {sorted(НАГРУЗКИ)} или число, а не {н!r}')
            н = НАГРУЗКИ[н]
        # п. 10: пол плёнки — для тонкой краски (не толще «обычной»); пастозная у узкой кисти идёт по ширине, как раньше
        по_ширине = (max(float(self.ширина), Ч._ММ) / (40.0 * Ч._ММ)) ** 0.8
        return float(self.толщина) * max(float(н) * по_ширине, min(float(н), НАГРУЗКИ['обычная']) * масштаб_толщины(self.ширина))

    def набрана(self, нагрузка=None):
        """П. 13в: насколько кисть набрана — сама нагрузка числом (с множителем `толщина`). У кисти от `_ПОЛ_ПЛЁНКИ` px и
        у тонкой краски (до «обычной») это то же, что плёнка в долях `масштаб_толщины`; у густой краски на кисти уже —
        больше: плёнку узкая кисть кладёт тоньше, а набрана так же полно, как широкая."""
        н = self.нагрузка if нагрузка is None else нагрузка
        return float(self.толщина) * float(НАГРУЗКИ[н] if isinstance(н, str) else н)


_ПОЛЯ_КИСТИ = frozenset(f.name for f in fields(Кисть))


def подсказка(имя, известные):
    """Е-7: «нет поля lvel, может быть level?» — ближайшее известное имя, если оно есть."""
    import difflib
    б = difflib.get_close_matches(str(имя), sorted(известные), n=1, cutoff=0.6)
    return f'нет поля {имя}' + (f', может быть {б[0]}?' if б else '')


def _число(v):
    return isinstance(v, (int, float, np.integer, np.floating))


def разобрать_цвет(цвет, в_линейный):
    """Одна краска (r, g, b) или список [(rgb, доля), ...] -> список (линейный RGB (3,), доля), доли в сумме 1."""
    ц = list(цвет)
    if len(ц) == 0:
        raise ValueError('цвет: пусто')
    if _число(ц[0]):
        if len(ц) != 3:
            raise ValueError('цвет: нужны три числа (r, g, b) или список [(rgb, доля), ...]')
        краски = _с_видом([(np.asarray(в_линейный(ц), dtype=np.float64), 1.0)], [getattr(цвет, 'мутность', 1.0)])
        if getattr(цвет, 'вид', None) == 'медиум':
            краски.медиум = True          # Ф-2: плёнка без пигмента — недомеса прядей у неё нет (`Холст._положить`)
        return краски
    краски, мутн = [], []
    for э in ц:
        э = list(э)
        if len(э) == 2 and not _число(э[0]):
            rgb, доля = э
        elif len(э) == 4:
            rgb, доля = э[:3], э[3]
        elif len(э) == 3:
            rgb, доля = э, 1.0
        else:
            raise ValueError('цвет: элемент списка — (rgb, доля), [r, g, b, доля] или [r, g, b]')
        if float(доля) > 0:
            краски.append((np.asarray(в_линейный(list(rgb)), dtype=np.float64), float(доля)))
            мутн.append(getattr(rgb, 'мутность', 1.0))
    if not краски:
        raise ValueError('цвет: все доли нулевые')
    сумма = sum(д for _, д in краски)
    return _с_видом([(c, д / сумма) for c, д in краски], мутн)


class Загрузка(tuple):
    """Д-1: живая краска на кисти — та же пара (краски, раскладка), что `Кисть._краска`, и сколько её: запас — краска в
    ворсе по местам поперёк кисти (`_КОРЗИН` мест), капля — на кончиках; обе — в долях объёма полной кисти
    (`укладка._полная_кисть`: от хода и его случая не зависит, Д-1-2). Ход без цвета начинает с них и оставляет новые (`укладка._с_загрузки`, `_в_загрузку`). дела — что с кистью
    делали после последнего хода (для журнала): ('load', количество), ('wipe',); от — с какой загрузки они начаты."""

    def __new__(cls, пара, запас=None, капля=None, дела=(), от=None):
        о = tuple.__new__(cls, пара)
        if запас is not None:
            о.запас, о.капля, о.дела, о.от = np.asarray(запас, np.float64), np.asarray(капля, np.float64), tuple(дела), от
        return о

    def после(self, дело, запас, капля):
        """Та же краска с другим количеством. дело None — ход (дела с чистого листа), иначе — имя дела кисти."""
        if дело is None:
            return Загрузка(tuple(self), запас, капля)
        return Загрузка(tuple(self), запас, капля, self.дела + ((дело,),), self.от if self.дела else self)

    def __deepcopy__(self, memo):
        import copy
        return Загрузка(copy.deepcopy(tuple(self), memo), self.запас.copy(), self.капля.copy(), self.дела, None)


class _Краски(list):
    """Краски набора с видом (п. 10, инструмент 3): `мутность` — средняя по долям (набор на кисти мешается в одну плёнку)."""


def _с_видом(краски, мутн):
    if all(m >= 1.0 for m in мутн):
        return краски                       # кроющие — как было, простой список
    к = _Краски(краски)
    к.мутность = float(sum(m * д for m, (_, д) in zip(мутн, краски)))
    return к
