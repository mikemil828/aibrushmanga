"""v4, Св-1: сводка этапа — факты этапа числами, не длиннее 12 строк: на `х.сохранить` и на смене этапа пометкой, файлом
рядом с сохранением (`<путь>.сводка.txt`) и вызовом `х.сводка()`. Только читает: холст, кисти, сиды и журнал не меняются.

Счёт этапа — на мазок, по полям его ответа (`учесть`), и лежит в счёте подсказок (`подсказки.Подсказки.счёт['э']`): откат
снимка и `загрузить` возвращают его вместе с ним. Развёртка следа (`ширина`, `просветы`, `разрывы`, `край`) при
включённых подсказках считается вместе с мазком — по тем же полям и тем же счётом, что ответу по запросу: числа сводки —
те же, что у ответов по одному; сам ответ по-прежнему ленив. Глушится тем же, чем подсказки: `подсказки=False`, `KIST_HINTS=0`, `х.подсказки.выключить()`.
"""
import math
import re

from . import под_верхом as Н

ПРОСВЕТЫ = 0.10         # след с `о.просветы` от стольких — в счёт
ΔL, ΔAB = 8.0, 0.02     # тон следа ушёл от названного: L серой шкалы или a, b OKLab (длина) — как С13
СТРОК = 12
_ПОД_РУКОЙ = 'под рукой: print(о), х.пустые, х.просвет(область), х.взгляд(область, без=[…]), х.однообразие(этап=…), х.подсказки'


class Сводка(str):
    """Текст сводки; `.числа` — её числа словарём (пустая сводка — пустой словарь)."""
    числа = {}

    def __new__(cls, текст='', числа=None):
        с = str.__new__(cls, текст)
        с.числа = dict(числа or {})
        return с


def новый():
    return {'мазков': 0, 'прочитано': 0, 'следов': 0, 'без замера': 0, 'без следа': {}, 'порван': 0, 'край рваный': 0,
            'просветы': 0, 'просветы худший': None, 'с цветом': 0, 'ушло': 0, 'ушло дальше': None, 'невидимые': 0, 'закрыли': {},
            'сказано': 0}


def учесть(э, изм, тон, вид):
    """Мазок досчитан: изм — `ответ.Ответ`, прямоугольник без замера или None; тон — названный (L, a, b) или None;
    вид — вид причины пустого. Поля берутся из `__dict__`: в «ответ прочитан» чтение сводкой не идёт."""
    э['мазков'] += 1
    if изм is None:
        if вид is not None:
            э['без следа'][вид] = э['без следа'].get(вид, 0) + 1
        return
    д = getattr(изм, '__dict__', {})
    if 'закрыто' not in д:
        э['без замера'] += 1
        return
    рамка = [int(v) for v in изм]
    р = д.pop('_св', д)                # развёртка следа, сочтённая с мазком (`Холст._положить`)
    цвет = д.get('цвет')
    if д.get('видно', 1.0) < Н.ЗАКРЫТ:
        э['невидимые'] += 1
        if д.get('закрыл') is not None:
            э['закрыли'][д['закрыл']] = э['закрыли'].get(д['закрыл'], 0) + 1
    if цвет is None:
        return
    э['следов'] += 1
    э['порван'] += bool(р.get('разрывы'))
    э['край рваный'] += (р.get('край') or {}).get('слово') == 'рваный'
    п = float(р.get('просветы', 0.0))
    if п >= ПРОСВЕТЫ:
        э['просветы'] += 1
        if э['просветы худший'] is None or п > э['просветы худший'][0]:
            э['просветы худший'] = [п, рамка]
    if тон is None or д.get('видно', 1.0) < Н.ЗАКРЫТ:      # невидимый: тон его места — чужой краски сверху
        return
    э['с цветом'] += 1
    C, h = float(цвет['C']), math.radians(float(цвет['h']))
    dL, dab = float(цвет['L']) - тон[0], math.hypot(C * math.cos(h) - тон[1], C * math.sin(h) - тон[2])
    if abs(dL) >= ΔL or dab >= ΔAB:
        э['ушло'] += 1
        мера = max(abs(dL) / ΔL, dab / ΔAB)
        if э['ушло дальше'] is None or мера > э['ушло дальше'][0]:
            э['ушло дальше'] = [мера, dL, dab, рамка]


def _место(п, этап):
    """Худшее место однообразия среди ходов этапа по журналу листа (`однообразие.места_мазков`) или None."""
    from . import однообразие as О
    р = п.мазки_листа()
    if р is None:
        return None
    мазки, мета = р
    свои = [м for м in мазки if ('' if м['этап'] is None else str(м['этап'])) == этап]
    места = О.места_мазков(свои, О._клетка_px(мета, None))[0]
    if not места:
        return None
    д = места[0]
    return {'рамка': tuple(д['рамка']), 'мазков': д['мазков'], 'оценка': float(д['оценка']),
            'узко': [т[2] for т in д['узко по'] if т[0] != 'вытерта'][:3]}


def собрать(п, этап):
    """Сводка этапа (ключ счёта) по счёту подсказок `п`; этап без мазков — пустая."""
    from .подсказки import ВИДЫ, _мн, _ч
    э = п.счёт.get('э', {}).get(этап)
    if э is None or not э['мазков']:
        return Сводка()
    пустых = sum(э['без следа'].values())
    место, ждут = _место(п, этап), п.неотвеченные()
    ч = {к: э[к] for к in ('мазков', 'прочитано', 'следов', 'без замера', 'порван', 'край рваный', 'просветы', 'с цветом', 'ушло',
                           'невидимые')}
    ч.update({'этап': этап or None, 'без следа': пустых, 'место': место, 'неотвеченные': [х['вид'] for х in ждут]})
    т = [f'сводка этапа «{этап}»' if этап else 'сводка (этапа нет)']
    т[0] += f': {_мн(э["мазков"], "мазок", "мазка", "мазков")}, ответов прочитано {э["прочитано"]} из {э["мазков"] - пустых}'
    if э['без замера']:
        т[0] += f', без замера {э["без замера"]}'
    if э['следов']:
        т.append(f'рваные: порван ход у {э["порван"]}, рваный край у {э["край рваный"]} из {э["следов"]}')
        х = э['просветы худший']
        т.append(f'просветы от {_ч(ПРОСВЕТЫ, 2)}: {э["просветы"]} из {э["следов"]}'
                 + (f', больше всех {_ч(х[0], 2)} — рамка {tuple(х[1])}' if х else ''))
    if э['с цветом']:
        х = э['ушло дальше']
        т.append(f'тон следа от названного (ΔL от {_ч(ΔL, 0)} или Δa, b от {_ч(ΔAB, 2)}): {э["ушло"]} из {э["с цветом"]}'
                 + (f', дальше всех ΔL {"+" if х[1] > 0 else "−"}{_ч(abs(х[1]), 0)}, Δa, b {_ч(х[2], 3)} — рамка {tuple(х[3])}' if х else ''))
    слои = sorted(э['закрыли'].items(), key=lambda q: (-q[1], q[0]))
    т.append(f'невидимые (видно меньше {_ч(Н.ЗАКРЫТ, 2)}, под верхним слоем): {э["невидимые"]}'
             + (' — закрыл ' + ', '.join(f'«{и}» {n}' for и, n in слои[:3]) if слои else ''))
    т.append(f'без следа: {пустых}' + (' — ' + ', '.join(
        f'{в[:40]} {n}' for в, n in sorted(э['без следа'].items(), key=lambda q: (-q[1], q[0]))[:2]) if пустых else ''))
    if место is not None:
        т.append(f'самое однообразное место: рамка {место["рамка"]}, {_мн(место["мазков"], "ход", "хода", "ходов")}, оценка '
                 f'{_ч(место["оценка"], 2)}' + (' — ' + ', '.join(место['узко']) if место['узко'] else ''))
    if ждут:
        имена = {}
        for х in ждут:
            имена[ВИДЫ[х['вид']]] = имена.get(ВИДЫ[х['вид']], 0) + 1
        и = [k + (f' ×{n}' if n > 1 else '') for k, n in имена.items()]
        т.append(f'подсказки, чьих инструментов после них не звали: {len(ждут)} — ' + ', '.join(и[:6]) + ('…' if len(и) > 6 else ''))
    т.append(_ПОД_РУКОЙ)
    return Сводка('\n  '.join(т[:СТРОК]), ч)


_ИНСТРУМЕНТ = re.compile(r'х\.(мазок\([^)]*\)|\w+)|\b(?:[ок]\.)(\w+)|\b(print|нагрузка_для|смешение_для|мерка)\(|(кисть\.повтор)')


def инструменты(текст):
    """Имена инструментов строки подсказки («под рукой: …») — как их считает `Подсказки.взят`."""
    _, _, хвост = текст.partition(' — под рукой: ')
    имена = set()
    for м in _ИНСТРУМЕНТ.finditer(хвост):
        х, поле, функция, _ = м.groups()
        if х is not None:
            имена.add('разбавитель' if х.startswith('мазок') and 'разбавитель' in х else 'новый слой' if х.startswith('мазок') else х)
        elif поле is not None:
            имена.add('кисть' if м.group(0).startswith('к.') else 'ответ')
        elif функция is not None:
            имена.add('ответ' if функция == 'print' else функция)
    if 'варианты' in имена:
        имена |= {'взять'}
    return имена
