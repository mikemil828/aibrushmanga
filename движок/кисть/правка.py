"""М-3: правка высохшей краски — `размочить` и `прижать` (в журнале — строка {"wet": …} и строка с "tool": "нож").

Высохшее ни кисть, ни нож без краски, ни тряпка не берут (Ф-3: сухое не мнётся). У живописца на это два приёма.

**Размочить** — масло (или растворитель) поверх сухого: верх плёнки набухает и снова берётся кистью, тряпкой и ножом.
Масло входит сверху и неглубоко: за раз сырым становится не больше `_РАЗМОЧ[0]` толщины (h) от поверхности — у тонкого
письма это весь слой, у пастозного вала только кожа, тело под ней стоит твёрдым. Влажность слоя — доля его толщины,
что сыра и лежит сверху (так её читают нож и снятие): размоченное — `доля` × достигнутая глубина. Повторный вызов
глубже не идёт (масло стоит на той же коже), слой выше забирает глубину на свою толщину. Схват (`схватить`) снимается
в ту же меру: корка размягчается на достигнутой доле толщины.

**Прижать** — ход ножа плашмя по сухому: нож срезает то, что выше его плоскости, и оставляет ровную площадку.
Плоскость — не линия под рукой, а лезвие: оно лежит на холсте подошвой (`_ПРИЖИМ[1]` мм по ходу × ширина кромки).
Опора лезвия — краска под подошвой, а не грунт рядом (М-3-2): точка от четверти самой высокой под подошвой держит
лезвие в полную меру, тоньше — в меру своей толщины, голый грунт не держит и вниз лезвие не тянет. Слабый нажим — нож
едет по вершинам (среднее высот верхних 15 % опоры) и ничего не берёт; с нажимом лезвие садится к телу краски под
собой (медиана высот опоры): нажим 0,6 — полпути от вершин к телу, от 0,9 — до тела. Тело мазка нож не срывает: ниже
этой медианы лезвие не идёт, сколько ни дави, — и там, где кромка косо сходит с вала и большей частью висит над
грунтом, оно стоит на вале. Тонкий слой рядом с валом опора слабая: вал на ровном слое срезается до него, вал на
голом грунте — до своей середины. `глубина` (мм) — осторожный ход: ниже самой высокой точки под подошвой больше чем
на столько лезвие за ход не садится. Слой, названный в `слой`, под целой краской другого слоя не режется. Всё, что выше плоскости, — сухое и сырое — уходит
на нож и с холста: сухая крошка валика не даёт. Цвет остаётся цветом слоя (срез открывает нутро того же мазка), где
слой срезан насквозь — открывается то, что под ним; грунт и зерно нож не режет. Случайных чисел нет."""
import numpy as np

from .быстро import зажать
from .снятие import _шагом, _убрать

ММ_НА_H = 0.4                # мм краски в единице толщины h (`холст.ММ_НА_H`)
_РАЗМОЧ = (0.25,)            # на столько h от поверхности масло размягчает сухое (0,1 мм — кожа плёнки)
_ПРИЖИМ = (None, 4.0, 0.3, 0.9, 0.03, 0.15, 0.02, 0.25)   # [0] глубина по умолчанию, мм: ниже самой высокой точки под подошвой нож за ход не идёт (None — предела нет: глубину ведёт нажим); [1] длина подошвы ножа по ходу, мм; [2] нажим, до которого нож едет по вершинам; [3] нажим, с которого лезвие сидит на теле; [4] нажим, ниже которого нож холста не касается (как `_НОЖ[7]`); [5] доля высот под подошвой, чьё среднее — «вершины»; [6] h, тоньше которого срез не считается следом; [7] доля самой высокой точки под подошвой, от которой краска держит лезвие в полную меру (тоньше — в меру толщины, голый грунт не держит)
_КУСОК = 256


def размочить(холст, доля, слой=None, область=None):
    """Вернуть сухому верху краски влажность (шапка модуля). доля 0–1; слой — имя или None (все: глубина считается
    от поверхности, верхние слои её забирают); область — (x0, y0, x1, y1) или None. Ответ: площадь, где влажность
    выросла, px."""
    доля = float(зажать(доля, 0.0, 1.0))
    if доля <= 0.0:
        return 0
    гy, гx = холст._область(область)
    имена = list(холст.слои)
    if слой is not None and слой not in имена:
        return 0
    выросло = 0
    for y0 in range(гy.start, гy.stop, _КУСОК):
        for x0 in range(гx.start, гx.stop, _КУСОК):
            где = (slice(y0, min(y0 + _КУСОК, гy.stop)), slice(x0, min(x0 + _КУСОК, гx.stop)))
            выше = None                                           # толщина слоёв над текущим
            for имя in имена[::-1]:
                с = холст.слои[имя]
                h = np.asarray(с.толщина[где], np.float64)
                if not h.any():
                    continue
                if слой is None or имя == слой:
                    глубина = _РАЗМОЧ[0] if выше is None else np.maximum(_РАЗМОЧ[0] - выше, 0.0)
                    достал = np.minimum(h, глубина)               # толщина слоя, до которой дошло масло
                    w = np.asarray(с.влажность[где], np.float64)
                    сыро = np.maximum(h * w, доля * достал)
                    w2 = np.where(h > 1e-9, зажать(сыро / np.maximum(h, 1e-9), 0.0, 1.0), w)
                    мягче = доля * np.where(h > 1e-9, достал / np.maximum(h, 1e-9), 0.0)
                    сх = np.asarray(с.схват[где], np.float64)
                    сх2 = сх * (1.0 - мягче)
                    стало = (w2 > w + 1e-7)
                    if стало.any() or (сх2 < сх - 1e-7).any():
                        выросло += int(стало.sum())
                        с.влажность[где] = w2.astype(np.float32)
                        с.схват[где] = сх2.astype(np.float32)
                выше = h if выше is None else выше + h
    return выросло


class Прижато:
    """Ответ `х.прижать`: `прямоугольник` (x0, y0, x1, y1) хода ножа; `под_ножом` — px под лезвием; `срезано` — px, где
    нож снял краску; `на_нож` — объём срезанного, h·px² (ушёл с холста), `мм3` — он же в мм³; `доля` — срезанное к
    краске, лежавшей под ножом; `глубже` — самый глубокий срез, мм; `сырого` — доля сырой краски в срезанном;
    `почему` — слово, если нож ничего не снял."""
    __slots__ = ('прямоугольник', 'под_ножом', 'срезано', 'на_нож', 'мм3', 'доля', 'глубже', 'сырого', 'почему', '_клетки')

    def __init__(self, **поля):
        for имя in self.__slots__:
            setattr(self, имя, поля.get(имя))

    def __bool__(self):
        return bool(self.срезано)

    def __repr__(self):
        if not self.срезано:
            return f'Прижато(ничего не срезано: {self.почему})'
        return (f'Прижато(срезано {self.срезано} px из {self.под_ножом} под ножом, на нож {self.на_нож:.1f} h·px² '
                f'({self.мм3:.2f} мм³, {self.доля:.0%} краски под ножом), глубже всего {self.глубже:.2f} мм'
                + (f', сырого в срезанном {self.сырого:.0%}' if self.сырого else '') + ')')


def _плоскость(S, p, глубина_h, px_на_мм):
    """Высота лезвия на каждом шаге хода (N,). S (N, nu) — толщина краски под кромкой по шагам (шаг 0,5 px),
    p (N,) — нажим. Подошва — окно шагов длиной `_ПРИЖИМ[1]` мм вокруг кромки. Опора лезвия — краска под подошвой:
    голый грунт рядом не держит и не тянет вниз. Тело — высота, ниже
    которой лежит половина опоры (медиана высот с весом точки: от `_ПРИЖИМ[7]` самой высокой — 1, тоньше — в меру
    толщины), вершины — среднее высот верхних `_ПРИЖИМ[5]` опоры. Где нож оторван (нажим ниже `_ПРИЖИМ[4]`) или под подошвой краски нет — +inf.
    Окна читаются через px (каждый второй шаг и каждая вторая точка кромки) и считаются кусками шагов: память хода —
    десятки МБ при любой длине."""
    N, nu = S.shape
    пол = max(1, int(round(0.5 * _ПРИЖИМ[1] * px_на_мм / 0.5)))
    пол += пол % 2                                                 # чётная: окно через шаг симметрично вокруг кромки
    касается = p >= _ПРИЖИМ[4]
    Sк = np.where(касается[:, None], S, 0.0)[:, ::2]               # под оторванным ножом краска в опору не идёт
    Sк = np.pad(Sк, ((пол, пол), (0, 0)))
    m = (пол + 1) * Sк.shape[1]                                    # точек в окне
    верх, тело, пик = np.full(N, np.inf), np.full(N, np.inf), np.full(N, np.inf)
    кусок = max(1, int(4e6 // m))
    for i0 in range(0, N, кусок):
        i1 = min(i0 + кусок, N)
        окна = np.lib.stride_tricks.sliding_window_view(Sк[i0:i1 + 2 * пол], 2 * пол + 1, axis=0)[:, :, ::2].reshape(i1 - i0, m)
        ряд = np.sort(окна, axis=1)
        держит = зажать(ряд / np.maximum(_ПРИЖИМ[7] * ряд[:, -1:], 1e-12), 0.0, 1.0)   # вес точки в опоре: от четверти самой высокой — полный, тоньше — в меру толщины, грунт — ноль
        копится = np.cumsum(держит, axis=1)
        всего = копится[:, -1]
        есть = ряд[:, -1] > 1e-9
        j = (копится >= 0.5 * всего[:, None]).argmax(axis=1)
        вес = np.where(копится > (1.0 - _ПРИЖИМ[5]) * всего[:, None], держит, 0.0)
        тело[i0:i1] = np.where(есть, ряд[np.arange(i1 - i0), j], np.inf)
        верх[i0:i1] = np.where(есть, (вес * ряд).sum(axis=1) / np.maximum(вес.sum(axis=1), 1e-12), np.inf)
        пик[i0:i1] = np.where(есть, ряд[:, -1], np.inf)
    сила = зажать((p - _ПРИЖИМ[2]) / (_ПРИЖИМ[3] - _ПРИЖИМ[2]), 0.0, 1.0)
    with np.errstate(invalid='ignore'):
        z = np.maximum(тело + (верх - тело) * (1.0 - сила), np.where(сила > 0.0, пик - глубина_h * np.maximum(сила, 1e-9), np.inf))   # глубже `глубина` под самой высокой точкой под подошвой лезвие за ход не садится
    return np.where(касается & (сила > 0.0) & np.isfinite(тело), z, np.inf)


def прижать(холст, точки, ширина, слой=None, глубина=None):
    """Ход ножа плашмя по лежащей краске: срезать всё выше плоскости лезвия (шапка модуля). точки — (x, y, нажим, …);
    ширина — длина кромки, px; слой — имя (режется только он и только там, где над ним нет краски другого слоя) или None (сверху вниз все); глубина — мм, не глубже
    стольких под самой высокой точкой под ножом за ход (None — предела нет, глубину ведёт нажим). Ответ — `Прижато`."""
    if not ширина > 0:
        raise ValueError('прижать: ширина ножа — больше нуля')
    глубина_мм = _ПРИЖИМ[0] if глубина is None else float(глубина)
    if глубина_мм is not None and not глубина_мм > 0:
        raise ValueError('прижать: глубина — мм, больше нуля')
    пм = float(холст.px_на_мм or 8.0)
    путь, d = _шагом(точки, 0.5)
    x, y, p = путь[:, 0] - холст.x0, путь[:, 1] - холст.y0, путь[:, 2]
    N = len(путь)
    W = float(ширина)
    r = W / 2 + 2.0
    bx0, by0 = max(int(np.floor(x.min() - r)), 0), max(int(np.floor(y.min() - r)), 0)
    bx1, by1 = min(int(np.ceil(x.max() + r)) + 1, холст.ширина), min(int(np.ceil(y.max() + r)) + 1, холст.высота)
    пусто = lambda почему: Прижато(прямоугольник=(bx0 + холст.x0, by0 + холст.y0, bx1 + холст.x0, by1 + холст.y0), под_ножом=0, срезано=0,   # noqa: E731
                                   на_нож=0.0, мм3=0.0, доля=0.0, глубже=0.0, сырого=0.0, почему=почему)
    if bx1 <= bx0 or by1 <= by0:
        return пусто('ход мимо холста')
    if not (p >= _ПРИЖИМ[4]).any():
        return пусто('нож холста не коснулся (нажим 0)')
    где = (slice(by0, by1), slice(bx0, bx1))
    bh, bw = by1 - by0, bx1 - bx0
    имена = list(холст.слои)
    режется = [имя for имя in имена if слой is None or имя == слой]
    if not режется:
        return пусто(f'слоя {слой!r} нет' if слой is not None else 'краски на холсте нет')
    поверхность = np.asarray(холст.рельеф(by0, by1, bx0, bx1, полный=True), np.float64)
    # --- кромка по шагам: какие пиксели под ней и на какой высоте она идёт
    nu = max(2, int(np.ceil(W / 0.5)))
    uu = (np.arange(nu) + 0.5) * (W / nu) - W / 2
    ax, ay = -d[:, 1], d[:, 0]
    ix = np.floor(x[:, None] + uu[None, :] * ax[:, None] - bx0).astype(np.intp)
    iy = np.floor(y[:, None] + uu[None, :] * ay[:, None] - by0).astype(np.intp)
    ок = (ix >= 0) & (ix < bw) & (iy >= 0) & (iy < bh)
    S = np.where(ок, поверхность[зажать(iy, 0, bh - 1), зажать(ix, 0, bw - 1)], np.nan)
    S = np.where(np.isnan(S), 0.0, S)                              # за краем холста краски нет
    z = _плоскость(S, p, np.inf if глубина_мм is None else глубина_мм / ММ_НА_H, пм)
    Z = np.full(bh * bw, np.inf)
    q = (iy * bw + ix)[ок]
    np.minimum.at(Z, q, np.broadcast_to(z[:, None], (N, nu))[ок])
    под = np.zeros(bh * bw, bool)
    под[q[np.broadcast_to((p >= _ПРИЖИМ[4])[:, None], (N, nu))[ок]]] = True
    Z, под = Z.reshape(bh, bw), под.reshape(bh, bw)
    лишнее = np.where(np.isfinite(Z), np.maximum(поверхность - Z, 0.0), 0.0)
    if not (лишнее > 1e-9).any():
        о = пусто('нож едет по вершинам: выше плоскости лезвия ничего нет (нажим от 0,3 сажает лезвие ниже; '
                  'ровное место срезать нечем)' if лишнее.size and под.any() else 'под ножом пусто')
        о.под_ножом = int(под.sum())
        return о
    # --- срез: сверху вниз по слоям, не больше толщины слоя
    холст._до_записи((bx0 + холст.x0, by0 + холст.y0, bx1 + холст.x0, by1 + холст.y0))
    лежало = 0.0
    снято_всего, сырого = np.zeros((bh, bw)), 0.0
    остаток = лишнее.copy()
    выше = np.zeros((bh, bw))                                     # толщина слоёв над текущим, которые не режутся
    for имя in имена[::-1]:
        с = холст.слои[имя]
        h = np.asarray(с.толщина[где], np.float64)
        if имя not in режется:
            выше = выше + h
            continue
        лежало += float(h[под].sum())
        снять = np.where(выше > 1e-6, 0.0, np.minimum(остаток, h))   # под целой краской другого слоя нож не достаёт: там слой не режется
        if (снять > 0.0).any():
            сырого += float(np.minimum(снять, h * np.asarray(с.влажность[где], np.float64)).sum())
            if с.пропуск is not None:                             # не кроющая плёнка тоньше — светлее
                доля = np.where(h > 1e-6, зажать((h - снять) / np.maximum(h, 1e-6), 0.0, 1.0), 1.0)
                с.пропуск[где] = np.power(np.asarray(с.пропуск[где], np.float64), доля[..., None]).astype(np.float32)
            _убрать(с, где, снять.astype(np.float32))
            снято_всего += снять
            остаток = остаток - снять
    объём = float(снято_всего.sum())
    след = снято_всего > _ПРИЖИМ[6]
    if объём <= 0.0:
        о = пусто('выше плоскости лезвия краски слоя нет — там грунт или другой слой')
        о.под_ножом = int(под.sum())
        return о
    ys, xs = np.nonzero(след)                                    # зеркалу С18: срезано px по клеткам 32 px (`подсказки.КЛЕТКА`)
    номера, сколько = np.unique(((ys + by0 + холст.y0) // 32) * 100000 + (xs + bx0 + холст.x0) // 32, return_counts=True)
    return Прижато(_клетки=dict(zip(номера.tolist(), сколько.tolist())),
                   прямоугольник=(bx0 + холст.x0, by0 + холст.y0, bx1 + холст.x0, by1 + холст.y0), под_ножом=int(под.sum()),
                   срезано=int(след.sum()), на_нож=объём, мм3=объём * ММ_НА_H / (пм * пм), доля=объём / max(лежало, 1e-12),
                   глубже=float(снято_всего.max()) * ММ_НА_H, сырого=сырого / объём, почему=None)
