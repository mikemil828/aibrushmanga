def _гаусс(a, σ):
    return ndimage.gaussian_filter(a, (σ, σ, 0) if a.ndim == 3 else σ, mode='reflect') if σ > 0 else a


def _сила(lab, σ):
    E = 0.0
    for k in range(3):
        E = E + ndimage.gaussian_filter(lab[k], σ, order=(1, 0)) ** 2 + ndimage.gaussian_filter(lab[k], σ, order=(0, 1)) ** 2
    return np.sqrt(E)


def _зерно(lab0, мало=-1.0):
    """Зерно снимка в каждом пикселе, единицы разбора: σ остатка лапласиана (Иммеркер) в окнах 9 px, по ступеням светлоты
    (у OKLab зерно тёмного крупнее) — 20-й процентиль окон ступени: самые ровные места, фактура краски в него не входит.
    Везде не больше `мало` — 0.0: порогу места оно безразлично."""
    ядро = np.array([[1, -2, 1], [-2, 4, -2], [1, -2, 1]], np.float64) / 6.0
    э = 0.0
    for k in range(3):
        э = э + ndimage.convolve(lab0[k], ядро, mode='reflect') ** 2
    σ = np.sqrt(np.maximum(ndimage.uniform_filter(э, 9, mode='reflect'), 0.0))
    ст = np.clip(np.floor(lab0[0] / СТУПЕНЬ_ЗЕРНА), 0, 11).astype(np.int64)
    # 20-й процентиль ступени не больше `мало`, если таких окон хватает на оба числа, между которыми он стоит
    хватит = lambda n, k: k >= (0.2 * (n - 1)).astype(np.int64) + 2
    n_ст = np.bincount(ст.ravel(), minlength=12)
    к_ст = np.bincount(ст.ravel()[(σ <= мало).ravel()], minlength=12)
    if (хватит(n_ст, к_ст) | (n_ст < 400)).all() and хватит(np.array([σ.size]), np.array([к_ст.sum()]))[0]:
        return 0.0
    общ = float(np.percentile(σ, 20))
    плоско, по = σ.ravel(), np.argsort(ст.ravel().astype(np.uint8), kind='stable')
    общие, i0 = np.full(12, общ), 0
    for j, n in enumerate(n_ст):
        if n >= 400:
            общие[j] = np.percentile(плоско[по[i0:i0 + n]], 20)
        i0 += n
    карта = общие[ст]
    return _гаусс(карта, 3.0)


def _размах(lab, σ, q=3):
    """Местный размах краски (σ в окне `σ` px). Окно в разы шире пикселя, поэтому размытия считаются на клетках q×q px и
    возвращаются к пикселям по прямой: то же с точностью до сотых долей, в q² раз дешевле."""
    from PIL import Image
    В, Ш = lab.shape[1:]
    п = np.pad(lab, ((0, 0), (0, -В % q), (0, -Ш % q)), mode='edge')
    h, w = п.shape[1] // q, п.shape[2] // q
    клетки = lambda a: a.reshape(h, q, w, q).mean((1, 3))
    назад = lambda a: np.asarray(Image.fromarray(a.astype(np.float32)).resize((w * q, h * q), Image.BILINEAR), np.float64)
    д2 = 0.0
    for j in range(len(п)):
        д2 = д2 + (п[j] - назад(_гаусс(клетки(п[j]), σ / q))) ** 2
    return np.sqrt(np.maximum(назад(_гаусс(клетки(д2), σ / q)), 0.0))[:В, :Ш]


def _подряд(м, N):
    """Номера 0…N-1 с пропусками — подряд, порядок тот же."""
    есть = np.zeros(N, np.int64)
    есть[м] = 1
    return (np.cumsum(есть) - 1)[м]


def _бассейны(E):
    """Водораздел силы перепада: каждый пиксель стекает к нижнему из 8 соседей (при равенстве — к первому) до местного
    минимума; кусок — все пиксели одного минимума, граница — на гребне перепада."""
    В, Ш = E.shape
    П = np.pad(E, 1, constant_values=np.inf)
    лучше, сосед = E.copy(), np.zeros((В, Ш), np.uint8)
    СОСЕДИ = ((-1, 0), (0, -1), (0, 1), (1, 0), (-1, -1), (-1, 1), (1, -1), (1, 1))
    for j, (dy, dx) in enumerate(СОСЕДИ):
        v = П[1 + dy:1 + dy + В, 1 + dx:1 + dx + Ш]
        np.copyto(сосед, j + 1, where=v < лучше)
        np.minimum(лучше, v, out=лучше)
    сосед = сосед.ravel()
    куда = np.arange(В * Ш) + np.array([0] + [dy * Ш + dx for dy, dx in СОСЕДИ])[сосед]
    while True:
        дальше = куда[куда]
        if (дальше == куда).all():
            break
        куда = дальше
    return _подряд(куда, В * Ш).reshape(В, Ш)


def _пары(метки):
    """Соседние по стороне пиксели разных кусков: (номер a, номер b) и плоские адреса обоих."""
    В, Ш = метки.shape
    п, плоско = [], метки.ravel()
    for р, шаг in ((метки[:, :-1] != метки[:, 1:], 1), (метки[:-1] != метки[1:], Ш)):
        i = np.flatnonzero(р)
        if шаг == 1:                                              # строка короче на px: номер px — с учётом строк
            i = i + i // (Ш - 1)
        п.append((плоско[i], плоско[i + шаг], i, i + шаг))
    return tuple(np.concatenate(x) for x in zip(*п))


def _сумма(ключ, n, v):
    return np.stack([np.bincount(ключ, v[:, k], n) for k in range(v.shape[1])], 1)


def _слить(метки, lab, порог_карта, вес):
    """Слияние кругами, от ближних красок к дальним (`СТУПЕНИ` порога): каждый кусок сливается с соседом наименьшей
    разницы красок у стыка, пока она меньше порога. Стык копит суммы красок обеих сторон по своим пикселям (краска
    стороны — средняя её первичного куска), поэтому разница — по всей длине стыка. Ответ — метки 0…N-1."""
    N = int(метки.max()) + 1
    плоско = метки.ravel()
    w = np.maximum(np.bincount(плоско, вес.ravel(), N), 1e-9)
    краска = np.stack([np.bincount(плоско, (lab[k] * вес).ravel(), N) for k in range(3)], 1) / w[:, None]
    a, b, ia, ib = _пары(метки)
    порог_п = 0.5 * (порог_карта.ravel()[ia] + порог_карта.ravel()[ib])
    lo, hi = np.minimum(a, b), np.maximum(a, b)
    d = краска[lo] - краска[hi]
    ключ, обр = скоро.уникальные(lo * np.int64(N) + hi)
    n = np.bincount(обр).astype(np.float64)
    с = np.concatenate([_сумма(обр, len(ключ), d), np.bincount(обр, порог_п)[:, None], n[:, None]], 1)
    lo, hi = ключ // N, ключ % N
    нов, первый = np.arange(N), np.zeros(N, np.int64)             # глава куска; его лучший стык
    лучшая, тронут = np.zeros(N), np.zeros(N, bool)
    ступень = 0
    # кусок зовётся наименьшим номером своих первичных: порядок номеров и ключей — как у плотных. Пересчитываются только
    # стыки слитых кусков; сумма стыков — в порядке прежних ключей
    отн = np.sqrt((с[:, :3] ** 2).sum(1)) / np.maximum(с[:, 3], 1e-12)          # разница в долях порога
    while len(lo) and ступень < len(СТУПЕНИ):
        е = np.flatnonzero(отн < СТУПЕНИ[ступень])
        if not len(е):
            ступень += 1
            continue
        # лучший сосед куска: наименьшая разница; при равенстве — первый по номеру стыка. Цепочки лучших — одним куском
        е = е[np.argsort(ключ[е])]
        ст = np.concatenate([е, е])
        кто = np.concatenate([hi[е], lo[е]])                      # стыки, где кусок второй, — ключом раньше
        о = отн[ст]
        лучшая[кто] = np.inf
        np.minimum.at(лучшая, кто, о)
        да = np.flatnonzero(о == лучшая[кто])[::-1]
        первый[кто[да]] = ст[да]                                  # в обратном порядке: остаётся первый
        ст = первый[кто]
        a, b = lo[ст], hi[ст]
        while True:                                               # глава цепочки — её наименьший номер
            ра, рб = нов[a], нов[b]
            л2 = ра < рб
            л3 = рб < ра
            if not (л2.any() or л3.any()):
                break
            np.minimum.at(нов, рб[л2], ра[л2])
            np.minimum.at(нов, ра[л3], рб[л3])
            х = np.concatenate([a, b])
            while True:
                г = нов[нов[х]]
                if (г == нов[х]).all():
                    break
                нов[х] = г
        узлы = np.concatenate([a, b])
        тронут[узлы] = True
        i = np.flatnonzero(тронут[lo] | тронут[hi])
        тронут[узлы] = False
        i = i[np.argsort(ключ[i])]
        l2, h2 = нов[lo[i]], нов[hi[i]]
        жив = l2 != h2
        l2, h2, сп = l2[жив], h2[жив], с[i[жив]]
        пер = l2 > h2
        сп[пер, :3] *= -1.0
        l2, h2 = np.minimum(l2, h2), np.maximum(l2, h2)
        кл, обр = скоро.уникальные(l2 * np.int64(N) + h2)
        сп = _сумма(обр, len(кл), сп)
        j, лишние = i[:len(кл)], i[len(кл):]                      # места новых стыков — места прежних
        ключ[j], lo[j], hi[j], с[j] = кл, кл // N, кл % N, сп
        отн[j] = np.sqrt((сп[:, :3] ** 2).sum(1)) / np.maximum(сп[:, 3], 1e-12)
        отн[лишние] = np.inf
        lo[лишние] = hi[лишние] = 0                               # пустое место: кусок 0 с собой
        ж = lo != hi
        if 4 * np.count_nonzero(ж) < 3 * len(lo):
            ключ, lo, hi, с, отн = ключ[ж], lo[ж], hi[ж], с[ж], отн[ж]
    while True:
        дальше = нов[нов]
        if (дальше == нов).all():
            break
        нов = дальше
    return _подряд(нов[плоско], N).reshape(метки.shape)


def _кромка(метки):
    край = np.zeros(метки.shape, bool)
    р = метки[:, 1:] != метки[:, :-1]
    край[:, 1:] |= р
    край[:, :-1] |= р
    р = метки[1:] != метки[:-1]
    край[1:] |= р
    край[:-1] |= р
    return край


def _толщина(метки, N, до=None):
    """Ширина области по расстоянию до её края: у полосы ширины w среднее расстояние ≈ (w + 2) / 4, px. `до` — нужна точно
    только у областей у́же стольких px: у остальных — не меньше `до`."""
    край, м = _кромка(метки), метки.ravel()
    n = np.maximum(np.bincount(м, minlength=N), 1)
    дт = (скоро.расстояния(край) if до is None else скоро.близко(край)) + 1.0
    тол = 4.0 * np.bincount(м, дт.ravel(), N) / n - 2.0
    if до is not None and (тол[м[дт.ravel() == 5.0]] < до).any():   # узкая по усечённому расстоянию, а есть и дальние px
        return _толщина(метки, N)
    return тол, n


def _между(a, b, краска, пор, N):
    """Какие куски a — переход: краска лежит на отрезке между красками двух его соседей b (в сторону — меньше порога
    места), а соседи разные. Так выходит размытая кромка двух масс снимка и тонкий край мазка."""
    да = np.zeros(N, bool)
    if not len(a):
        return да
    п = скоро.по_ключу(a * np.int64(N) + b)
    a, b = a[п], b[п]
    нач = np.flatnonzero(np.r_[True, a[1:] != a[:-1]])
    сколько = np.diff(np.r_[нач, len(a)])
    j = np.repeat(np.arange(len(a)), np.repeat(сколько, сколько))   # пары соседей одного куска: j и q
    пр = сколько * сколько
    q = np.arange(len(j)) - np.repeat(np.r_[0, np.cumsum(пр)[:-1]], пр)
    q = np.repeat(нач, пр) + q % np.repeat(сколько, пр)
    i, kj = a[j], краска[b[j]]
    d = (краска[i] - kj).T                                       # от соседа j к куску
    g = (краска[b[q]] - kj).T                                    # от соседа j к соседу q
    ск = lambda u, v: u[0] * v[0] + u[1] * v[1] + u[2] * v[2]
    gg = ск(g, g)
    t = ск(d, g) / np.maximum(gg, 1e-9)
    r = d - t * g
    мимо = np.sqrt(ск(r, r))
    да[i[(t > 0.05) & (t < 0.95) & (мимо < пор[i]) & (gg > пор[i] ** 2)]] = True
    return да


def _долить(метки, lab, порог_карта, кисть):
    """Узкое и мелкое — к соседу, ближнему по краске среди тех, с кем у него стык не короче 0,3 самого длинного; узкое,
    контрастное к соседу на 2 порога и больше, — свой мазок (белый удар, тонкая черта)."""
    стыки = None                                                  # длины стыков и суммы красок меняются только у слитых
    каналы = [c.ravel() for c in lab] + [порог_карта.ravel()]
    for _ in range(6):
        N = int(метки.max()) + 1
        тол, n = _толщина(метки, N, max(ТОНКОЕ * кисть, УЗКОЕ * кисть, 4.0))
        мелко = n < max(МЕЛКОЕ * кисть * кисть, 12.0)
        тонко = тол < max(ТОНКОЕ * кисть, 4.0)
        узко = (тол < max(УЗКОЕ * кисть, 2.0)) | мелко | тонко
        if not узко.any():
            break
        плоско = метки.ravel()
        if стыки is None:
            суммы = [np.bincount(плоско, v, N) for v in каналы]
            a, b, _, _ = _пары(метки)
            стыки = скоро.уникальные_счёт(np.minimum(a, b) * np.int64(N) + np.maximum(a, b))
            a, b, дл = стыки[0] // N, стыки[0] % N, стыки[1]
        краска = np.stack(суммы[:3], 1) / n[:, None]
        пор = суммы[3] / n
        a, b, дл = np.concatenate([a, b]), np.concatenate([b, a]), np.concatenate([дл, дл])
        п = скоро.по_ключу(a * np.int64(N) + b)
        все = a, b, дл = a[п], b[п], дл[п]
        длинный = np.zeros(N)
        np.maximum.at(длинный, a, дл)
        годно = узко[a] & (дл >= 0.3 * длинный[a])
        a, b = a[годно], b[годно]
        решает = (тонко & ~мелко)[a]
        между = _между(a[решает], b[решает], краска, пор, N)
        dE = np.sqrt(((краска[a] - краска[b]) ** 2).sum(1))
        п = np.lexsort((b, dE, a))
        a, b, dE = a[п], b[п], dE[п]
        перв = np.r_[True, a[1:] != a[:-1]] if len(a) else np.zeros(0, bool)
        a, b, dE = a[перв], b[перв], dE[перв]
        льём = мелко[a] | ((тол[a] < max(УЗКОЕ * кисть, 2.0)) & (dE < 2.0 * пор[a])) | между[a]
        a, b = a[льём], b[льём]
        # в круг — только к соседу, который сам не льётся (или льётся позже): цепочек и петель нет
        занят = np.zeros(N, bool)
        нов = np.arange(N)
        for i in np.argsort(n[a], kind='stable'):
            x, y = a[i], b[i]
            if not занят[x] and нов[y] == y:
                нов[x] = y
                занят[y] = True
        if (нов == np.arange(N)).all():
            break
        куда = _подряд(нов, N)                                    # нов[нов] == нов: номера живых — подряд
        слит = np.zeros(int(куда.max()) + 1, bool)
        слит[куда[нов != np.arange(N)]] = True
        метки = куда[метки]
        плоско = метки.ravel()
        i = np.flatnonzero(слит[плоско])
        прежние, суммы = суммы, []
        for v, было in zip(каналы, прежние):
            с = np.bincount(плоско[i], v[i], len(слит))
            с[куда] = np.where(слит[куда], с[куда], было)
            суммы.append(с)
        a, b, дл = (куда[все[0]], куда[все[1]], все[2])
        да = a < b
        ключ, обр = скоро.уникальные(a[да] * np.int64(len(слит)) + b[да])
        a, b, дл = ключ // len(слит), ключ % len(слит), np.bincount(обр, дл[да], len(ключ)).astype(np.int64)
    return метки


def _ровное(метки, L, кого):
    """У каких областей из `кого` медианное отклонение светлоты меньше `ФАКТУРА`."""
    ном = np.cumsum(кого) - 1
    i = np.flatnonzero(кого[метки])
    ответ = np.zeros(len(кого), bool)
    if len(i):
        м, v = ном[метки[i]], L[i]
        n = int(ном[-1]) + 1
        ответ[кого] = скоро.медианы(np.abs(v - скоро.медианы(v, м, n)[м]), м, n) < ФАКТУРА
    return ответ


def _области(метки, L_сырая, кисть, полосы=None):
    """Свойства областей массивом: длина, ширина, ось, вид — по моментам и сечениям поперёк длинной оси. `полосы` —
    ширины (от, до) px: у областей заведомо у́же — только 'у края' (лестница их не берёт), 'ровное' ищется среди полос такой
    ширины. Ответ — (области, (номера областей, px) посчитанного)."""
    В, Ш = метки.shape
    всего = N = int(метки.max()) + 1
    м = метки.ravel()
    тут, берём = slice(None), None
    if полосы is None:
        тол, _ = _толщина(метки, N)
    else:                                                         # ширина — не больше 1,35 толщины или она сама
        край = _кромка(метки)
        дт = скоро.близко(край).ravel() + 1.0                     # дальше 4 px — «не меньше»
        тол = 4.0 * np.bincount(м, дт, N) / np.maximum(np.bincount(м, minlength=N), 1) - 2.0
        дальние = np.zeros(N, bool)
        дальние[м[дт == 5.0]] = True
        берём = np.flatnonzero((1.35 * тол >= 0.999 * полосы[0]) | дальние)
        ном = np.full(N, -1)
        ном[берём] = np.arange(len(берём))
        м = ном[м]
        тут = np.flatnonzero(м >= 0)
        м, тол, N = м[тут], тол[берём], len(берём)
    n = np.bincount(м, minlength=N).astype(np.float64)
    ys, xs = np.divmod(np.arange(В * Ш)[тут], Ш)
    xs, ys = xs.astype(np.float64), ys.astype(np.float64)
    cx, cy = np.bincount(м, xs, N) / n, np.bincount(м, ys, N) / n
    dx, dy = xs - cx[м], ys - cy[м]
    xx, xy, yy = (np.bincount(м, v, N) / n for v in (dx * dx, dx * dy, dy * dy))
    угол = 0.5 * np.arctan2(2 * xy, xx - yy)
    c, s = np.cos(угол), np.sin(угол)
    вдоль = dx * c[м] + dy * s[м]
    поп = -dx * s[м] + dy * c[м]
    # сечения шагом 2 px вдоль оси
    ном = np.floor(вдоль / 2.0).astype(np.int64)
    ном0 = np.full(N, np.iinfo(np.int64).max)
    np.minimum.at(ном0, м, ном)
    ном1 = np.full(N, np.iinfo(np.int64).min)
    np.maximum.at(ном1, м, ном)
    число = ном1 - ном0 + 1
    нач = np.r_[0, np.cumsum(число)]
    k = нач[м] + (ном - ном0[м])
    K = int(нач[-1])
    в_сеч = np.bincount(k, minlength=K)
    lo, hi = np.full(K, np.inf), np.full(K, -np.inf)
    np.minimum.at(lo, k, поп)
    np.maximum.at(hi, k, поп)
    чей = np.repeat(np.arange(N), число)
    есть = в_сеч >= 2
    шир_с = np.where(есть, hi - lo + 1.0, 0.0)
    плотн = np.where(есть, в_сеч / 2.0 / np.maximum(шир_с, 1.0), 0.0)
    ширина, разброс, заполн = np.ones(N), np.ones(N), np.ones(N)
    пор = np.lexsort((шир_с, чей))
    пор = пор[есть[пор]]
    чн = np.bincount(чей[пор], minlength=N)
    нн = np.r_[0, np.cumsum(чн)]
    for j, имя in ((0.5, 0), (0.9, 1), (0.1, 2)):
        i = нн[:-1] + np.minimum((чн * j).astype(np.int64), np.maximum(чн - 1, 0))
        v = np.where(чн > 0, шир_с[пор][np.minimum(i, max(len(пор) - 1, 0))], 1.0)
        if имя == 0:
            ширина = v
        elif имя == 1:
            p90 = v
        else:
            p10 = v
    разброс = p90 / np.maximum(p10, 1.0)
    заполн = np.bincount(чей[есть], плотн[есть], N) / np.maximum(np.bincount(чей[есть], minlength=N), 1)
    длина = число * 2.0 - 1.0
    if полосы is not None:                                        # толщина точно — у кого она решает
        точно = дальние[берём] & ~((ширина > полосы[1]) & (тол > полосы[1] + 0.001))
        if точно.any():
            чьи = np.zeros(всего, bool)
            чьи[берём[точно]] = True
            дт = скоро.расстояния(край | ~чьи[метки]) + 1.0
            тол = np.where(точно, 4.0 * np.bincount(м, дт.ravel()[тут], N) / np.maximum(n, 1) - 2.0, тол)
    # изогнутая полоса: сечения прямой оси берут прогиб за ширину — ширина по расстоянию до края, длина по площади
    # дуга пересекает каждое сечение один раз: её длина по площади — не больше `СГИБ` хорд (полуокружность — 1,6; шпилька
    # и сеть — от двух: сечение идёт через них дважды и больше)
    по_площади = n / np.maximum(тол, 1.0)
    дуга = (заполн < 0.8) & (по_площади > 1.15 * длина) & (по_площади <= СГИБ * длина)
    ширина = np.where(дуга, тол, np.minimum(ширина, np.maximum(1.35 * тол, 1.0)))
    длина = np.where(дуга, n / np.maximum(тол, 1.0), длина)
    отн = длина / np.maximum(ширина, 1.0)
    # одна полоса: сечения сплошные и ширина держится; у дуги — площадь ≈ длина × толщина по построению
    полоса = np.where(дуга, тол > 0.5 * (n / np.maximum(длина, 1)), (заполн >= ПЛОТНО) & (разброс <= РАЗБРОС))
    кого = np.ones(N, bool) if полосы is None else полоса & (ширина >= полосы[0]) & (ширина < полосы[1])
    ровно = _ровное(м, L_сырая.ravel()[тут], кого)
    вид = np.full(N, 'удар', dtype=object)
    вид[отн >= ПРОТЯЖКА] = 'протяжка'
    вид[~полоса] = 'пятно'
    вид[~полоса & (отн >= ПРОТЯЖКА)] = 'поле'
    вид[(ширина > ПОЛЕ * кисть) | (n > 3.0 * ПОЛЕ * ПОЛЕ * кисть * кисть)] = 'поле'
    вид[ровно] = 'ровное'
    вид[((вид == 'протяжка') | (вид == 'удар')) & (np.minimum(ширина, тол) < ПРЕДЕЛ_PX)] = 'мельче предела'
    у_края = np.zeros(всего, bool)
    for срез in (метки[0], метки[-1], метки[:, 0], метки[:, -1]):
        у_края[срез] = True
    о = {'вид': вид, 'площадь': n, 'x': cx, 'y': cy, 'угол': np.degrees(угол) % 180.0, 'длина': длина, 'ширина': ширина,
         'толщина': тол, 'полоса': полоса, 'заполнение': заполн, 'разброс': разброс}
    т = м, тут
    if берём is not None:
        for и, v in о.items():
            о[и] = np.full(всего, 'мельче' if и == 'вид' else 0, v.dtype)
            о[и][берём] = v
        т = берём[м], тут
    о['у края'] = у_края
    return о, т


def _проход(rgb, кисть, окно=ОКНО_РАЗМАХА, полосы=None):
    """Один разбор рабочей картинки с кистью `кисть` px: (метки, области). `окно` — окно местного размаха, кистей."""
    lab0 = np.ascontiguousarray(np.moveaxis(в_единицы(rgb), -1, 0))   # каналы — подряд
    lab = np.stack([_гаусс(c, max(СГЛАДИТЬ, 0.11 * кисть)) for c in lab0])
    размах = _размах(lab, окно * кисть / 2.0)
    порог = np.maximum(np.maximum(ТОН_МИН, ТОН_ДОЛЯ * размах), ЗЕРНО * _зерно(lab0, ТОН_МИН / ЗЕРНО * (1 - 1e-9)))
    E = _сила(lab, max(0.7, 0.08 * кисть))
    метки = _бассейны(E)
    вес = 1.0 / (1.0 + (E / np.maximum(0.25 * порог, 1e-6)) ** 2)
    метки = _слить(метки, lab, порог, вес)
    метки = _долить(метки, lab, порог, кисть)
    метки = _слить(метки, lab, порог, вес)
    # пиксель у стыка — к той стороне, чья краска ближе, после слияния делает водораздел: стык уже на гребне перепада
    о, (м, тут) = _области(метки, lab0[0], кисть, полосы)
    n = np.maximum(о['площадь'], 1.0)
    о['краска'] = np.stack([np.bincount(м, lab[j].ravel()[тут], len(n)) for j in range(3)], 1) / n[:, None]
    о['порог'] = np.bincount(м, порог.ravel()[тут], len(n)) / n
    return метки, о, порог


def мазок(вид):
    return (вид == 'протяжка') | (вид == 'удар')


