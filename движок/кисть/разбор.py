def _к_уровню(a, k):
    """Картинка уровня k: в k раз мельче снимка (k < 1 — крупнее)."""
    from PIL import Image
    if abs(k - 1.0) < 1e-9:
        return a
    return np.asarray(Image.fromarray(a).resize((max(8, int(round(a.shape[1] / k))), max(8, int(round(a.shape[0] / k)))),
                                                Image.LANCZOS))


def _уровни(В, Ш, предел_px):
    """Лестница уменьшений от грубого к мелкому, шаг √2. Самый мелкий — тот, где нижний край полосы ширин равен пределу
    снимка; самый грубый — где короткая сторона ещё `СТОРОНА_МИН` рабочих px."""
    k0 = предел_px / ПОЛОСА[0]
    n = int(math.floor(2.0 * math.log2(max(min(В, Ш) / СТОРОНА_МИН / k0, 1.0))))
    return [k0 * 2.0 ** (i / 2.0) for i in range(n, -1, -1)]


def _с_дырами(метки, кто):
    """У каких областей из `кто` внутри чужого больше `ДЫРЫ` своей площади: это сеть (грунт между ходами, фон вокруг
    мазков), а не полоса, какой бы ровной ни вышла её ширина."""
    да = np.zeros(len(кто), bool)
    срезы = ndimage.find_objects(метки + 1)
    for i in np.flatnonzero(кто):
        if срезы[i] is None:
            continue
        m = метки[срезы[i]] == i
        свое = int(m.sum())
        if m.size - свое <= ДЫРЫ * свое:                          # чужого во всей рамке меньше
            continue
        с_краской = m.any(1)                                      # и внутри строк, от края до края
        меж = m.shape[1] - m[:, ::-1].argmax(1) - m.argmax(1)
        if int(меж[с_краской].sum()) - свое <= ДЫРЫ * свое:
            continue
        да[i] = int(ndimage.binary_fill_holes(m).sum()) - свое > ДЫРЫ * свое
    return да


def _окна(В, Ш, k):
    """Окна снимка, по которым считается уровень k: весь снимок, пока рабочая картинка уровня не больше `БЮДЖЕТ` px (и
    самого снимка); иначе — 9 плиток сеткой 3×3, подобных снимку, с теми же центрами на всех уровнях (плитка мелкого
    уровня лежит в плитке грубого). Ответ — [(y0, y1, x0, x1)]."""
    доля = max(БЮДЖЕТ, float(В * Ш)) * k * k / float(В * Ш)
    if доля >= 0.98:
        return [(0, В, 0, Ш)]
    f = math.sqrt(доля) / 3.0
    h, w = max(int(round(В * f)), 8), max(int(round(Ш * f)), 8)
    return [(y, y + h, x, x + w) for y in (int(round(В * t - h / 2.0)) for t in (1 / 6, 1 / 2, 5 / 6))
            for x in (int(round(Ш * t - w / 2.0)) for t in (1 / 6, 1 / 2, 5 / 6))]


def обычная_ширина(о):
    """Ширина обычного мазка картинки и какие полосы — мазки, а какие поля: (ширина, маска мазков). Поле — полоса шире
    `ПОЛЕ` ширин мазка этой же картинки (масса снимка, слившаяся на грубом уровне: стена, небо). Ширина мазка — медиана по
    площади ширины самих мазков: ищется сверху, от медианы всех полос, пока не сойдётся (полосы шире `ПОЛЕ` медиан
    уходят в поля, медиана оставшихся — снова). Обрезанное краем ширины не знает."""
    ш, w = о['ширина'], о['вес'] * о['площадь'] * ~о['у края']
    свои, W = w > 0, np.inf
    for _ in range(64):
        if not свои.any():
            break
        i = np.argsort(ш[свои], kind='stable')
        c = np.cumsum(w[свои][i])
        W = float(ш[свои][i][min(int(np.searchsorted(c, 0.5 * c[-1])), len(i) - 1)])
        дальше = свои & (ш <= ПОЛЕ * W)
        if дальше.sum() == свои.sum():
            break
        свои = дальше
    return W, свои | ((w <= 0) & (ш <= ПОЛЕ * W))


def _пряди(о):
    """Ход растрёпанной кисти — несколько полос одной краски, разделённых грунтом. Пряди одного хода: краска одна (ближе
    порога места), направление одно (`ВДОЛЬ`), короткая лежит вдоль длинной и за её концы выходит не больше общей
    ширины, просвет между ними у́же `ПРОСВЕТ` общей ширины, а вместе они не шире `ХОД` обычных мазков этой картинки
    (половина площади мазков — в мазках не шире) — соседние мазки полной ширины в один не собираются. Ответ: у каждой
    области номер хода (её номер — сама)."""
    n = len(о['x'])
    чья = np.arange(n)
    if n < 2 or not (о['вес'] > 0).any():
        return чья
    предел = ХОД * обычная_ширина(о)[0]
    xy = np.stack([о['x'], о['y']], 1)
    у = np.radians(о['угол'])
    ось, поп = np.stack([np.cos(у), np.sin(у)], 1), np.stack([-np.sin(у), np.cos(у)], 1)
    низ, верх = -0.5 * о['ширина'], 0.5 * о['ширина']              # поперечник хода от его главной пряди
    for j in np.argsort(-о['площадь'], kind='stable'):              # от крупных к мелким: мелкая — к крупной
        if чья[j] != j or о['длина'][j] < ПРОТЯЖКА * о['ширина'][j]:
            continue
        while True:                                                 # прядь за прядью, от ближней
            d = xy - xy[j]
            вдоль, вбок = d @ ось[j], d @ поп[j]
            п0, п1 = вбок - 0.5 * о['ширина'], вбок + 0.5 * о['ширина']
            общая = np.maximum(верх[j], п1) - np.minimum(низ[j], п0)
            щель = np.maximum(п0 - верх[j], низ[j] - п1)
            откл = np.abs((о['угол'] - о['угол'][j] + 90.0) % 180.0 - 90.0)
            д = (чья == np.arange(n)) & (о['площадь'] <= о['площадь'][j]) & (np.arange(n) != j) & (общая <= предел)
            д &= (щель <= ПРОСВЕТ * общая) & (откл <= ВДОЛЬ) & (о['длина'] >= ПРОТЯЖКА * о['ширина'])
            д &= np.abs(вдоль) + 0.5 * о['длина'] <= 0.5 * о['длина'][j] + общая
            д &= np.sqrt(((о['краска'] - о['краска'][j]) ** 2).sum(1)) < np.minimum(о['порог'], о['порог'][j])
            к = np.flatnonzero(д)
            if not len(к):
                break
            к = к[np.argmin(щель[к])]
            чья[к] = j
            чья[чья == к] = j
            низ[j], верх[j] = min(низ[j], п0[к]), max(верх[j], п1[к])
    о['ширина'] = np.where(чья == np.arange(n), np.maximum(о['ширина'], верх - низ), о['ширина'])
    о['площадь'] = np.bincount(чья, о['площадь'], n)
    return чья


def _собрать(нов, о, чья):
    """Области, чей номер в `чья` — другая область, уходят в неё: (номера меток, области)."""
    ход = чья == np.arange(len(чья))
    return np.r_[0, np.cumsum(ход)[чья]].astype(np.int64)[нов], {и: v[ход] for и, v in о.items()}


def разобрать(rgb, предел_px=None):
    """Мазки снимка по лестнице уменьшений. `_проход` своего масштаба не имеет: мазок у него всегда 4–6 рабочих px, какую
    картинку ни дай. Поэтому мазок берётся с того уровня лестницы, где он шире этого пола — `ПОЛОСА` рабочих px, — а не с
    одного рабочего масштаба. Уровни идут от грубого к мелкому. Полоса мелкого уровня, больше чем на `ВНУТРИ` лежащая на
    уже принятом мазке, — его часть. Часть той же краски — борозда или клочок внутри хода, мазком не считается. Часть
    другой краски (дальше от краски целого, чем порог места, с которым оно принято) — мазок поверх него. Если такие
    части одного уровня (две и больше) закрывают `ДЕЛИТ` принятого, оно было не мазком, а их группой (ряд ударов,
    слившийся на грубом уровне) — снимается. Принятое, от которого на следующем уровне не осталось того же целого (пересечение
    к объединению меньше `ТО_ЖЕ`), снимается тоже: мазок держится на двух соседних уровнях, слившаяся масса распадается.
    Тонкое вдоль хода обычной ширины (`ПРОСВЕТ`, `ВДОЛЬ`) — борозда, блик или просвет грунта, на поле — мазок. Мелкие уровни большой картинки считаются по плиткам (`_окна`): у их мазков
    `'вес'` > 1 — скольких мазков снимка стоит один найденный (площадь снимка к площади, где такой мазок мог лечь в плитку
    целиком); у мазка, обрезанного краем плитки, вес 0, краем снимка — 1.

    Ответ: 'метки' — номер мазка + 1 в px снимка (0 — не мазок; мелкие уровни — только в плитках); 'области' — массивы по
    мазкам: 'длина', 'ширина', 'x', 'y', 'площадь' (px снимка), 'угол', 'вид', 'у края', 'уровень', 'вес'; 'уровни'."""
    a = np.clip(np.round(rgb), 0, 255).astype(np.uint8)
    В, Ш = a.shape[:2]
    метки_с = np.zeros((В, Ш), np.int64)
    около_с = np.zeros((В, Ш), np.int64)                          # то же с запасом в рабочий px уровня: край принятого
    поля = ('длина', 'ширина', 'x', 'y', 'угол', 'площадь', 'у края', 'уровень', 'вес', 'краска', 'порог', 'просвет в')
    итог = {и: [] for и in поля}
    жив, уровни = [], []
    ждёт = np.zeros(1, bool)                                      # принятые прошлым уровнем: распадутся ли на этом
    предел = предел_px or ПРЕДЕЛ_PX
    for k in _уровни(В, Ш, предел):
        окна = _окна(В, Ш, k)
        плитки = len(окна) > 1
        взято = 0
        виды = []
        общее, все_пр, все_обл = np.zeros(len(ждёт)), np.zeros(len(ждёт)), np.zeros(len(ждёт))
        for y0, y1, x0, x1 in окна:
            b = _к_уровню(a[y0:y1, x0:x1], k)
            if min(b.shape[:2]) < 24:
                continue
            метки, о, _ = _проход(b, КИСТЬ, ОКНО_ЛЕСТНИЦЫ, ПОЛОСА)
            h, w = y1 - y0, x1 - x0
            yi = np.minimum((np.arange(h) * (b.shape[0] / h)).astype(np.int64), b.shape[0] - 1)
            xi = np.minimum((np.arange(w) * (b.shape[1] / w)).astype(np.int64), b.shape[1] - 1)
            м_с = метки[yi][:, xi]                                # метки уровня в px снимка
            N, M = len(о['вид']), len(ждёт)
            n_с = np.maximum(np.bincount(м_с.ravel(), minlength=N), 1).astype(np.float64)
            виды.append((y0, y1, x0, x1, метки, о, yi, xi, м_с, n_с))
            if ждёт.any():                                        # какая область уровня ближе всех к принятому целиком
                точ = метки_с[y0:y1, x0:x1]
                где = ждёт[точ]
                ключ, общ = скоро.уникальные_счёт(точ[где] * np.int64(N) + м_с[где])
                чей, обл = ключ // N, ключ % N
                пор = np.lexsort((-общ, чей))
                перв = np.r_[True, чей[пор][1:] != чей[пор][:-1]] if len(чей) else np.zeros(0, bool)
                чей, обл, общ = чей[пор][перв], обл[пор][перв], общ[пор][перв]
                сеть = _с_дырами(метки, np.isin(np.arange(N), обл))
                np.add.at(общее, чей, np.where(сеть[обл], 0, общ))
                np.add.at(все_пр, чей, np.bincount(точ[где], minlength=M)[чей])
                np.add.at(все_обл, чей, n_с[обл])
        # принятое, которое на следующем уровне не то же целое, — масса, слившаяся на грубом уровне, а не мазок
        распалось = ждёт & (все_пр > 0) & (общее < ТО_ЖЕ * (все_пр + все_обл - общее))
        for j in np.flatnonzero(распалось):
            жив[j - 1] = False
        if распалось.any():
            метки_с[распалось[метки_с]] = 0
            около_с[распалось[около_с]] = 0
        с_этого = len(жив)
        for y0, y1, x0, x1, метки, о, yi, xi, м_с, n_с in виды:
            h, w = y1 - y0, x1 - x0
            мс, точно = около_с[y0:y1, x0:x1], метки_с[y0:y1, x0:x1]   # виды: правятся на месте
            N, M = len(о['вид']), len(жив) + 1
            годно = о['полоса'] & (о['вид'] != 'ровное') & (о['ширина'] >= ПОЛОСА[0]) & (о['ширина'] < ПОЛОСА[1])
            годно &= ~_с_дырами(метки, годно)
            где = годно[м_с] & (мс > 0)                           # перекрытие полос уровня с принятыми
            ключ, общ = скоро.уникальные_счёт(м_с[где] * np.int64(M) + мс[где])
            кто, чей = ключ // M, ключ % M
            на_принятом = np.bincount(кто, общ, N) / n_с
            пор = np.lexsort((-общ, кто))
            перв = np.r_[True, кто[пор][1:] != кто[пор][:-1]] if len(кто) else np.zeros(0, bool)
            хозяин = np.zeros(N, np.int64)
            хозяин[кто[пор][перв]] = чей[пор][перв]
            часть = годно & (на_принятом >= ВНУТРИ)
            пл_прин = np.bincount(мс.ravel(), minlength=M).astype(np.float64)
            # часть другой краски, чем целое (дальше от его краски, чем порог места, с которым целое принято), — мазок
            # поверх него; той же краски — борозда или клочок внутри хода
            кр_прин = np.concatenate([np.zeros((1, 3))] + итог['краска'])
            пор_прин = np.concatenate([np.full(1, np.inf)] + итог['порог'])
            чужая = часть & (np.sqrt(((о['краска'] - кр_прин[хозяин]) ** 2).sum(1)) >= пор_прин[хозяин])
            закрыто = np.bincount(хозяин[чужая], (на_принятом * n_с)[чужая], M) / np.maximum(пл_прин, 1.0)
            группа = (закрыто >= ДЕЛИТ) & (np.bincount(хозяин[чужая], minlength=M) >= 2)
            группа[0] = False
            if плитки and группа.any():                                            # принятое шире плитки по ней одной группой не назвать
                группа &= пл_прин >= np.bincount(около_с.ravel(), minlength=M) * 0.999
            # вдоль целого и в разы у́же его (или короче его ширины) — борозда, блик её гребня, просвет грунта
            ш_пр = np.concatenate([np.full(1, 1.0)] + итог['ширина'])[хозяин]
            у_пр = np.concatenate([np.zeros(1)] + итог['угол'])[хозяин]
            откл = np.abs((о['угол'] - у_пр + 90.0) % 180.0 - 90.0)
            просвет = чужая & (о['ширина'] * k <= ПРОСВЕТ * ш_пр) & ((откл <= ВДОЛЬ) | (о['длина'] * k <= ш_пр))
            просвет &= ~группа[хозяин]                            # просвет в ходе или мазок на массе — решается в конце
            беру = годно & (~часть | чужая)
            for j in np.flatnonzero(группа):
                жив[j - 1] = False
            if группа.any():
                мс[группа[мс]] = 0
                точно[группа[точно]] = 0
            ном = np.zeros(N, np.int64)
            ном[беру] = M + np.arange(int(беру.sum()))
            нов = ном[метки]
            шире = ndimage.grey_dilation(нов, size=3)[yi][:, xi]  # край области уровня известен до его рабочего px
            нов = нов[yi][:, xi]
            np.copyto(точно, нов, where=нов > 0)                  # мазок мелкого уровня — поверх принятого
            np.copyto(мс, нов, where=нов > 0)
            np.copyto(мс, шире, where=(шире > 0) & (мс == 0))
            n = int(беру.sum())
            жив += [True] * n
            взято += n
            д, ш, у = о['длина'][беру] * k, о['ширина'][беру] * k, np.radians(о['угол'][беру])
            вес = np.ones(n)
            if плитки:                                            # где мазок мог лечь в плитку целиком; длиннее половины
                # плитки — как половина её: вес одного случайного куска не растёт без края (счёт таких — снизу)
                bx = np.abs(np.cos(у)) * д + np.abs(np.sin(у)) * ш
                by = np.abs(np.sin(у)) * д + np.abs(np.cos(у)) * ш
                место = np.maximum(w - bx, 0.5 * w) * np.maximum(h - by, 0.5 * h) * len(окна)
                вес = np.where(о['у края'][беру] | (место <= 0), 0.0, В * Ш / np.maximum(место, 1e-9))
            for и, v in (('длина', д), ('ширина', ш), ('x', о['x'][беру] * k + x0), ('y', о['y'][беру] * k + y0),
                         ('площадь', о['площадь'][беру] * k * k), ('угол', о['угол'][беру]),
                         ('у края', о['у края'][беру]), ('уровень', np.full(n, k)), ('вес', вес),
                         ('краска', о['краска'][беру]), ('порог', о['порог'][беру]),
                         ('просвет в', np.where(просвет, хозяин, 0)[беру])):
                итог[и].append(v)
        ждёт = np.zeros(len(жив) + 1, bool)
        ждёт[с_этого + 1:] = True
        ждёт[1:] &= np.array(жив, bool)
        уровни.append({'k': k, 'плитки': плитки, 'взято': взято,
                       'доля': sum((y1 - y0) * (x1 - x0) for y0, y1, x0, x1 in окна) / float(В * Ш)})
    жив = np.array(жив, bool)
    for j in range(len(уровни)):                                  # по горстке кусков на всю картину не пересчитать: сколько видно
        if уровни[j]['плитки']:
            вес, ур = итог['вес'], np.concatenate(итог['уровень'])
            вес = np.concatenate(вес)
            этот = (ур == уровни[j]['k']) & (вес > 0)
            if (этот & жив).sum() < МАЛО_МАЗКОВ:
                вес[этот] = 1.0
            итог['вес'] = [вес]
    нов = np.r_[0, np.where(жив, np.cumsum(жив), 0)]
    о = {и: (np.concatenate(v) if v else np.zeros((0, 3) if и == 'краска' else 0))[жив] for и, v in итог.items()}
    о['у края'] = о['у края'].astype(bool)
    # тонкое вдоль принятого: в ходе обычной ширины и поштучно — борозда или просвет, на поле — мазок поверх него
    в_ком = нов[о.pop('просвет в').astype(np.int64)]
    не_поле = np.r_[False, обычная_ширина(о)[1]]
    сколько = np.bincount(в_ком, minlength=len(не_поле))          # мазков хватает на свой размер — это мазки на массе
    чья = np.where((в_ком > 0) & не_поле[в_ком] & (сколько < МАЛО_МАЗКОВ)[в_ком], в_ком - 1, np.arange(len(в_ком)))
    for _ in range(len(уровни)):
        чья = чья[чья]
    нов, о = _собрать(нов, о, чья)
    нов, о = _собрать(нов, о, _пряди(о))
    о['вид'] = np.where(о['длина'] >= ПРОТЯЖКА * о['ширина'], 'протяжка', 'удар').astype(object)
    for у in уровни:
        у['осталось'] = int((о['уровень'] == у['k']).sum())
    return {'метки': нов[метки_с], 'области': о, 'уровни': уровни, 'картинка': a}


# ---------------------------------------------------------------- форма одного мазка (Мн-2)

def форма(р, j, срез=None):
    """Форма мазка `j` разбора `р` в ширинах его кисти (`рука.замер`) с местом: 'номер', 'x', 'y', 'концы' — (y, x) кончиков
    входа и схода, 'слово'; px снимка. Краску мазка от соседей отделяет снимок, а не ступенька рабочего px. None — мазка не видно."""
    from . import рука
    S, о = р['метки'], р['области']
    if срез is None:
        где = np.argwhere(S == j + 1)
        if not len(где):
            return None
        срез = tuple(slice(int(a), int(b) + 1) for a, b in zip(где.min(0), где.max(0)))
    w = float(о['ширина'][j])
    k, поле = max(1, int(w // рука.ОТСЧЁТОВ)), int(math.ceil(w)) + 3
    y0, x0 = (max(0, с.start - поле) for с in срез)
    y1, x1 = (min(n, с.stop + поле) for с, n in zip(срез, S.shape))
    h, ш = (y1 - y0) // k * k, (x1 - x0) // k * k
    клетки = lambda a: a[:h, :ш].reshape((h // k, k, ш // k, k) + a.shape[2:]).mean((1, 3)) if k > 1 else a
    маска = клетки((S[y0:y1, x0:x1] == j + 1).astype(np.float64)) > 0.5
    if маска.sum() < 12:
        return None
    з = рука.замер(рука.след(в_единицы(клетки(р['картинка'][y0:y1, x0:x1].astype(np.float64))), маска, w / k), w / k)
    if з is None:
        return None
    з['W'] *= k
    з['концы'] = [(y0 + a * k + 0.5 * (k - 1), x0 + b * k + 0.5 * (k - 1)) for a, b in з['концы']]
    з.update({'номер': int(j), 'x': float(о['x'][j]), 'y': float(о['y'][j]), 'вес': float(о['вес'][j]), 'слово': рука.слова(з)})
    return з


ФОРМ = 200                # мазков меряется не больше: картина крупнее — каждый n-й по порядку разбора


def формы(р, целые):
    """Форма целых мазков (номера `целые`), чья ширина различает концы; не больше `ФОРМ`."""
    from . import рука
    е = целые[р['области']['ширина'][целые] >= рука.ВИДНО]
    if len(е) > ФОРМ:
        е = е[np.linspace(0, len(е) - 1, ФОРМ).round().astype(np.int64)]
    срезы = ndimage.find_objects(р['метки'], max(int(р['метки'].max()), 1))
    return [з for з in (форма(р, j, срезы[j]) for j in е if j < len(срезы) and срезы[j] is not None) if з is not None]


# ---------------------------------------------------------------- края пятен

КРАЙ_ПЛЕЧО = 8            # px: полудлина прямого отрезка края
МЕЛКАЯ, КРУПНАЯ = 0.7, 3.0  # px: сигмы пары, по которой меряется переход края


def края_пятен(rgb):
    """Границы пятен (наследник `архив/анализатор/край.py`): гребень силы перепада краски выше ступени `ТОН_МИН`.
    Ответ — {'границ': доля площади, 'прямых': доля пикселей границы на прямом отрезке ±`КРАЙ_ПЛЕЧО` px, 'переход':
    массив — ширина перехода 20–80 % в каждом пикселе границы, px}. Переход — по отношению силы перепада на двух
    сигмах: у ступени, размытой на s, сила на сигме σ идёт как 1/√(s² + σ²)."""
    lab = np.ascontiguousarray(np.moveaxis(в_единицы(rgb), -1, 0))
    σ = 1.5
    сила, угол = _тензор(lab, σ)
    c, s = np.cos(угол), np.sin(угол)
    гр = сила > ТОН_МИН / (σ * math.sqrt(2 * math.pi))
    y, x = np.nonzero(гр)                                         # гребень ищется там, где перепад не мал
    вз = lambda i: ndimage.map_coordinates(сила, [y + i * s[y, x], x + i * c[y, x]], order=1, mode='nearest')
    гр[y, x] = (сила[y, x] >= вз(1)) & (сила[y, x] > вз(-1))
    if not гр.any():
        return {'границ': 0.0, 'прямых': None, 'переход': np.zeros(0)}
    y, x = np.nonzero(гр)
    толще = ndimage.binary_dilation(гр, np.ones((3, 3))).astype(np.float32)
    cc, ss = c[y, x], s[y, x]
    д = np.r_[-КРАЙ_ПЛЕЧО:0, 1:КРАЙ_ПЛЕЧО + 1].astype(np.float64)
    Y, X = y[:, None] + д * cc[:, None], x[:, None] - д * ss[:, None]        # касательная — поперёк перепада
    внутри = (Y >= 0) & (Y <= гр.shape[0] - 1) & (X >= 0) & (X <= гр.shape[1] - 1)
    попал = ndimage.map_coordinates(толще, [Y, X], order=0, mode='constant') > 0.5
    угл = ndimage.map_coordinates(угол, [Y, X], order=0, mode='nearest')
    ровно = np.abs(np.cos(угл - угол[y, x][:, None])) > math.cos(math.radians(20.0))
    прямо = (попал & ровно & внутри).mean(1) >= 0.9
    r2 = (_тензор(lab, МЕЛКАЯ, (y, x))[0] / np.maximum(_тензор(lab, КРУПНАЯ, (y, x))[0], 1e-6)) ** 2
    верх = (КРУПНАЯ / МЕЛКАЯ) ** 2
    r2 = np.clip(r2, 1.02, верх)
    s2 = np.maximum((КРУПНАЯ ** 2 - r2 * МЕЛКАЯ ** 2) / (r2 - 1.0), 0.0)
    return {'границ': float(гр.mean()), 'прямых': float(прямо.mean()), 'переход': 1.683 * np.sqrt(s2)}


def _тензор(lab, σ, где=None):
    """(сила, угол) тензора структуры по трём каналам `lab` (3, В, Ш); `где` — только в этих px."""
    xx = yy = xy = 0.0
    for c in lab:
        gx, gy = (ndimage.gaussian_filter(c, σ, order=о) for о in ((0, 1), (1, 0)))
        if где is not None:
            gx, gy = gx[где], gy[где]
        xx, yy, xy = xx + gx * gx, yy + gy * gy, xy + gx * gy
    return (np.sqrt(np.maximum(0.5 * (xx + yy + np.sqrt((xx - yy) ** 2 + 4 * xy * xy)), 0.0)),
            0.5 * np.arctan2(2 * xy, xx - yy))
