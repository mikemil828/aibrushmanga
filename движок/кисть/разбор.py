ТОН_ДОЛЯ = 0.6            # доля местного размаха краски (σ в окне `ОКНО_РАЗМАХА` кистей): меньше — борозды, не край
ОКНО_РАЗМАХА = 3.0
ЗЕРНО, СТУПЕНЬ_ЗЕРНА = 2.0, 8.0   # порог — не меньше стольких σ зерна снимка (замер — ровное с зерном: мазков нет) · ступень L
УЗКОЕ = 0.35              # кисти: уже — борозда или кромка, доливается к соседу
МЕЛКОЕ = 0.6              # площади кисти²: мельче — клочок
ТОНКОЕ = 0.65             # кисти: уже и с краской между двумя соседями — переход (размытая кромка), не мазок
ПОЛЕ = 4.0                # кистей: шире — поле, а не мазок
ПРОТЯЖКА = 2.5            # длина к ширине
