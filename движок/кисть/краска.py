"""Смешение пигментов: цвет -> кривая отражения (12 полос) -> Кубелка–Мунк -> цвет.

Своя модель, без чужих таблиц:
  * три гладких базисных спектра (синий, зелёный, красный участки 400–700 нм),
    в сумме дающих единицу: белый = ровная кривая, любой RGB = их взвешенная сумма;
  * каждая краска описывается парой (K, S) на полосу: поглощение и рассеяние.
    Рассеяние растёт с отражением (светлый пигмент рассеивает сильнее — как белила),
    поэтому чёрный не «съедает» белый с первой капли;
  * K и S смешиваются линейно по долям красок, отражение смеси — по Кубелке–Мунку;
  * обратно в RGB — наименьшие квадраты на те же базисные спектры
    (ход «цвет -> спектр -> цвет» без смешения возвращает цвет точно).
"""
import numpy as np

from .быстро import зажать

from .числа import _ВИД, _РАЗБАВИТЕЛЬ

ПОЛОС = 12
_ЛЯМБДА = np.linspace(400.0, 700.0, ПОЛОС)


def _сигмоида(x):
    return 1.0 / (1.0 + np.exp(-x))


_Б_СИН = _сигмоида((492.0 - _ЛЯМБДА) / 13.0)
_Б_КРА = _сигмоида((_ЛЯМБДА - 588.0) / 13.0)
_Б_ЗЕЛ = 1.0 - _Б_СИН - _Б_КРА
БАЗИС = np.stack([_Б_КРА, _Б_ЗЕЛ, _Б_СИН], axis=1)          # (12, 3)
ОБРАТНО = np.linalg.pinv(БАЗИС)                              # (3, 12)

_ПОЛ = 0.008      # самое тёмное отражение (идеально чёрных красок нет)
_ПОТОЛОК = 0.985  # самое светлое
_РАССЕЯНИЕ0 = 0.15  # рассеяние самой тёмной краски (у белой 1 + это)


def в_линейный(srgb):
    """sRGB 0..255 (или массив) -> линейный свет 0..1."""
    c = np.asarray(srgb, dtype=np.float64) / 255.0
    return np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)


def из_линейного(lin):
    """линейный свет 0..1 -> sRGB 0..1 (гамма)."""
    c = зажать(np.asarray(lin, dtype=np.float64), 0.0, 1.0)
    return np.where(c <= 0.0031308, c * 12.92, 1.055 * c ** (1.0 / 2.4) - 0.055)


def отражение(rgb):
    """линейный RGB (..., 3) -> кривая отражения (..., 12)."""
    rgb = зажать(np.asarray(rgb, dtype=np.float64), 0.0, 1.0)
    return _ПОЛ + (_ПОТОЛОК - _ПОЛ) * (rgb @ БАЗИС.T)


def в_кс(rgb):
    """линейный RGB (..., 3) -> пигментное состояние (..., 24): K на 12 полос и S на 12 полос."""
    r = отражение(rgb)
    s = r + _РАССЕЯНИЕ0
    k = (1.0 - r) ** 2 / (2.0 * r) * s
    return np.concatenate([k, s], axis=-1)


def из_кс(кс):
    """пигментное состояние (..., 24) -> линейный RGB (..., 3)."""
    кс = np.asarray(кс, dtype=np.float64)
    q = np.maximum(кс[..., :ПОЛОС], 0.0) / np.maximum(кс[..., ПОЛОС:], 1e-9)
    r = 1.0 + q - np.sqrt(q * q + 2.0 * q)
    rgb = ((r - _ПОЛ) / (_ПОТОЛОК - _ПОЛ)) @ ОБРАТНО.T
    return зажать(rgb, 0.0, 1.0)


def смешать(a, b, доля_b=0.5):
    """Смесь двух красок (линейный RGB). доля_b — доля второй краски, число или массив (...)."""
    t = np.asarray(доля_b, dtype=np.float64)[..., None]
    return из_кс(в_кс(a) * (1.0 - t) + в_кс(b) * t)


def смешать_srgb(a, b, доля_b=0.5):
    """То же для цветов sRGB 0..255; ответ — sRGB 0..255 (дробные)."""
    return из_линейного(смешать(в_линейный(a), в_линейный(b), доля_b)) * 255.0


# ---------------------------------------------------------------- вид краски (п. 10, инструмент 3)
ВИДЫ = {'кроющая': 1.0, 'полукроющая': _ВИД[0], 'прозрачная': _ВИД[1], 'лессировочная': 0.0, 'медиум': 0.0}   # мутность: доля плёнки, что кроет своим цветом; Ф-1: лессировочная — чистая лессировка, не кроет вовсе


class Краска(tuple):
    """Краска с видом: `Краска((r, g, b), 'прозрачная')` — идёт везде, где цвет (в `мазок`, `набрать`, в список красок).

    вид — 'кроющая' (как просто (r, g, b)), 'полукроющая', 'прозрачная', 'лессировочная' (мутность 0: тёмное не
    высветляет), 'медиум' (Ф-2: масло или лак без пигмента — плёнка без цвета, `МЕДИУМ`; цвет лежащего не меняет, кладёт
    только толщину) или число-мутность 0..1. Сколько нижнего видно
    сквозь слой, решает толщина плёнки в этом месте: мутная доля кроет своим цветом (покрытие растёт с толщиной),
    прозрачная темнит лежащее на просвет — свет идёт сквозь слой дважды, пропуск = цвет ** (толщина / `_ВИД[2]`)."""
    def __new__(cls, rgb=(255, 255, 255), вид='кроющая'):
        с = super().__new__(cls, (255.0, 255.0, 255.0) if вид == 'медиум' else (float(v) for v in tuple(rgb)[:3]))
        if isinstance(вид, str):
            if вид not in ВИДЫ:
                raise ValueError(f'вид краски: {sorted(ВИДЫ)} или число 0..1, а не {вид!r}')
            с.мутность = ВИДЫ[вид]
        else:
            с.мутность = float(зажать(вид, 0.0, 1.0))
        с.вид = вид
        return с

    def __reduce__(self):
        return (Краска, (tuple(self), self.вид))


МЕДИУМ = Краска(вид='медиум')      # Ф-2: бесцветная плёнка — `х.мазок(путь, МЕДИУМ, кисть, разбавитель=1)`


def пропуск_плёнки(цвет, толщина, мутность):
    """Пропуск света плёнкой не кроющей краски (туда и обратно): цвет (..., 3) линейный, толщина (...) в единицах h."""
    return np.power(зажать(цвет, _ПОЛ, 1.0), ((1.0 - мутность) / _ВИД[2]) * np.maximum(толщина, 0.0)[..., None])


def разбавить(разбавитель, нагрузка, мутность, ровно, запас):
    """Г-1: краска с разбавителем (0–1) — доводы мазка, которыми она ложится: (толщина-нагрузка числом, мутность, ровно, запас).
    нагрузка — 'протирка', 'обычная', 'пастозная' или число (как у мазка; None сюда не идёт — нагрузка кисти). Жидкая
    плёнка тоньше и прозрачнее, течёт, как с `ровно` (и у не кроющей), сухой срыв тянется дольше; 0 — всё как дано."""
    from .инструмент import НАГРУЗКИ
    м = float(разбавитель or 0.0)
    if м <= 0.0:
        return нагрузка, мутность, ровно, запас
    н = НАГРУЗКИ[нагрузка] if isinstance(нагрузка, str) else float(нагрузка)
    return (н * (1.0 - _РАЗБАВИТЕЛЬ[0] * м), float(мутность) * (1.0 - _РАЗБАВИТЕЛЬ[1] * м), max(float(ровно or 0.0), м),
            None if запас is None else float(запас) * (1.0 + _РАЗБАВИТЕЛЬ[2] * м))


def проверить_разбавитель(разбавитель, нагрузка):
    """Г-1: разбавитель мазка — 0–1, не с полупустой ('сухая') и не с вытертой (0) кистью; иначе ValueError."""
    if разбавитель is None:
        return None
    м = float(разбавитель)
    if not 0.0 <= м <= 1.0:
        raise ValueError(f'мазок: разбавитель ("medium") — от 0 до 1, а не {разбавитель!r}')
    if м and (нагрузка == 'сухая' or (not isinstance(нагрузка, str) and float(нагрузка) <= 0.0)):
        raise ValueError('мазок: разбавитель ("medium") — краске на кисти; с нагрузкой \'сухая\' (полупустая) и 0 (вытертая) не идёт')
    return м
