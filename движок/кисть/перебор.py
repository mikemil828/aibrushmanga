"""v4, 3д (Б-8): перебор — пачка мазков с одним (или несколькими разом) параметром на нескольких значениях; лист
вариантов рядом и замеры каждого; холст не тронут.

`х.перебор(мазки, нагрузка=[0.006, 0.012, 0.025])` — поверх `х.варианты` (2г): каждое значение — свой вариант в
своём процессе, на холсте, каким он был при вызове; мазки варианта — те же мазки, у которых параметр заменён этим
значением. Мазок — словарь доводов `х.мазок` (`{'точки': …, 'цвет': …, 'кисть': …, 'слой': …, …}`) или кортеж
`(точки, цвет, кисть)` / `(точки, цвет, кисть, {доводы})`. Параметр — довод `х.мазок` (нагрузка, касание, запас,
цвет, кисть, слой…) или поле кисти (ширина, сухость, кайма…: тогда мазок идёт копией своей кисти с этим полем).
Несколько параметров — списки одной длины, вариант k берёт k-е значение каждого.

Сиды мазков у всех вариантов одни (из сида листа, этапа, объекта и точек) — варианты различаются только параметром.
Выбранный ложится в холст и журнал `х.взять(п[k])`, как если бы его мазки писались прямо.

Замеры варианта (на его участке, тон без света рельефа, как у мерок «Глаз»): 'средний' — `х.средний` области;
'след' — где L изменилось от 0,5: 'доля' области, 'dL' (среднее изменения), 'dL p5', 'dL p95', 'L' (тон там);
'просвет' — `х.просвет` области сквозь нижний слой мазков: 'просвет', 'доля', 'дыр'; 'мазки' — ответы мазков
(L, тело, закрыто, просветы; пустой — None); с `цель` — 'разность' (`х.разность`: среднее, σ, dab); с `мера` — 'своё'
(что вернула `мера(участок, область)`); 'однообразие' — оценка зеркала мазков варианта.
"""
import copy
import warnings
from dataclasses import fields

import numpy as np

from .глаз import oklab, шестн, _L, _в_8, _лист as лист_панелей, _масштаб, _ч
from .инструмент import Кисть
from .краска import из_линейного

_ДОВОДЫ = ('точки', 'цвет', 'кисть', 'слой', 'сид', 'непрозрачность', 'раскладка', 'нагрузка', 'мешать_ниже', 'касание',
           'полосы', 'по_гребням', 'ровно', 'запас', 'ломаная', 'нагрузка_вдоль', 'волокна', 'нажим_руки', 'этап', 'объект',
           'намерение', 'разбавитель')
_ПОЛЯ_КИСТИ = tuple(f.name for f in fields(Кисть))
ИЗМЕНЕНО = 0.5          # след варианта — где L изменилось хотя бы на столько


class Перебор:
    """Ответ `х.перебор`: `.варианты` — `Вариант` 2г (`п[k]` — то же; `х.взять(п[k])` кладёт его в холст и журнал),
    `.значения` — словарь параметров каждого, `.замеры` — словарь замеров каждого (модуль), `.область`, `.лист` —
    uint8 «до | вариант 0 | вариант 1 …» по три в ряд с подписью значения и главных замеров (`путь` — PNG);
    `print(п)` — таблица."""
    __slots__ = ('варианты', 'значения', 'замеры', 'область', 'лист')

    def __getitem__(self, k):
        return self.варианты[k]

    def __len__(self):
        return len(self.варианты)

    def __iter__(self):
        return iter(self.варианты)

    def __str__(self):
        строки = [f'перебор {self.область}: {len(self)} вар.']
        for k, (з, м) in enumerate(zip(self.значения, self.замеры)):
            с, пр = м['след'], м['просвет']
            т = (f'{k}: {_значения(з)} · L {м["средний"]["L"]:.1f} · след {с["доля"]:.3f} dL {с["dL"]:+.1f} '
                 f'(p5 {с["dL p5"]:+.1f}, p95 {с["dL p95"]:+.1f}) · просвет {пр["просвет"]:.3f}, дыр {пр["дыр"]}')
            if 'разность' in м:
                т += f' · к цели dL {м["разность"]["среднее"]:+.1f} σ {м["разность"]["σ"]:.1f}'
            строки.append(т)
        return '\n'.join(строки)

    __repr__ = __str__


def _значения(з):
    def одно(v):
        if isinstance(v, Кисть):
            return f'{v.имя} {v.ширина:g}'
        if hasattr(v, 'вид'):                           # Краска
            return f'{v.вид} {шестн(tuple(int(round(c)) for c in v))}'
        if isinstance(v, float):
            return f'{v:g}'
        if isinstance(v, tuple) and len(v) == 3 and all(isinstance(c, (int, float)) for c in v):
            return шестн(tuple(int(round(c)) for c in v))
        return str(v)
    return ', '.join(f'{к}={одно(v)}' for к, v in з.items())


def _мазок(м, j):
    """Мазок пачки -> словарь доводов `х.мазок`."""
    if isinstance(м, dict):
        д = dict(м)
    elif isinstance(м, (tuple, list)) and len(м) in (3, 4) and (len(м) == 3 or isinstance(м[3], dict)):
        д = {'точки': м[0], 'цвет': м[1], 'кисть': м[2], **(м[3] if len(м) == 4 else {})}
    else:
        raise TypeError(f'перебор: мазок {j} — словарь доводов х.мазок или (точки, цвет, кисть[, {{доводы}}])')
    чужие = [к for к in д if к not in _ДОВОДЫ]
    if чужие:
        raise TypeError(f'перебор: мазок {j}: доводов {чужие} у х.мазок нет (есть: {", ".join(_ДОВОДЫ)})')
    if 'точки' not in д or д.get('кисть') is None:
        raise TypeError(f'перебор: мазок {j}: нужны точки и кисть')
    return д


def _с_значением(д, параметр):
    д = dict(д)
    for имя, v in параметр.items():
        if имя in _ДОВОДЫ:
            д[имя] = v
        else:                                            # поле кисти: мазок идёт копией своей кисти с этим полем
            к = copy.copy(д['кисть'])
            setattr(к, имя, v)
            д['кисть'] = к
    return д


def _L_области(у, область):
    return _L(oklab(np.clip(из_линейного(у.картинка(свет=False, область=область)) * 255.0, 0.0, 255.0))[..., 0])


def перебор(х, мазки, область=None, цель=None, путь=None, масштаб=1, ядра=None, мера=None, **параметр):
    """Б-8: подробно — модуль."""
    from .просвет import просвет
    if not параметр:
        raise TypeError('перебор: параметр — довод х.мазок или поле кисти списком значений: перебор(мазки, нагрузка=[0.01, 0.02])')
    for имя, зн in параметр.items():
        if имя not in _ДОВОДЫ and имя not in _ПОЛЯ_КИСТИ:
            from .инструмент import подсказка
            raise TypeError(f'перебор: {имя!r} — не довод х.мазок и не поле кисти ({подсказка(имя, _ДОВОДЫ + _ПОЛЯ_КИСТИ)})')
        if имя in ('точки',):
            raise TypeError('перебор: точки не перебираются — другие места кладёт `х.варианты` с куском')
        if isinstance(зн, (str, bytes)) or not hasattr(зн, '__len__') or len(зн) < 1:
            raise TypeError(f'перебор: {имя} — список значений, например {имя}=[a, b, c]')
    длины = {len(v) for v in параметр.values()}
    if len(длины) > 1:
        raise ValueError(f'перебор: списки параметров разной длины {[(к, len(v)) for к, v in параметр.items()]} — '
                         'вариант k берёт k-е значение каждого')
    n = длины.pop()
    пачка = [_мазок(м, j) for j, м in enumerate(мазки)]
    if not пачка:
        raise ValueError('перебор: мазков нет')
    значения = [{имя: зн[k] for имя, зн in параметр.items()} for k in range(n)]
    наборы = [[_с_значением(д, з) for д in пачка] for з in значения]
    if область is None:                                  # рамка всех мазков всех значений: место, что они читают и пишут
        рамки = []
        рука = х.__dict__.get('_рука')                   # Рм: включённая рука уводит ход от намерения — рамка с её запасом
        for набор in наборы:
            for д in набор:
                как = {к: v for к, v in д.items() if к not in ('точки', 'кисть', 'сид', 'касание', 'цвет', 'этап', 'объект', 'намерение')}
                р = х.прямоугольник_мазка(д['точки'], д['кисть'], сид=д.get('сид'), касание=д.get('касание'),
                                          цвет=д.get('цвет'), **как)
                if р is not None:
                    з = 0 if рука is None else рука.запас(х, д['кисть'])
                    рамки.append((max(р[0] - з, х.x0), max(р[1] - з, х.y0), min(р[2] + з, х.x0 + х.ширина),
                                  min(р[3] + з, х.y0 + х.высота)) if з else р)
        if not рамки:
            raise ValueError('перебор: ни один мазок холста не тронет (все вне холста)')
        область = (min(р[0] for р in рамки), min(р[1] for р in рамки), max(р[2] for р in рамки), max(р[3] for р in рамки))
    слои = list(х.слои)
    слой_мазков = None
    for д in пачка:                                      # нижний слой мазков: сквозь него — просвет
        с = д.get('слой', 'основа')
        if слой_мазков is None or (с in слои and (слой_мазков not in слои or слои.index(с) < слои.index(слой_мазков))):
            слой_мазков = с

    def кусок(у, k):
        обл = (max(область[0], у.x0), max(область[1], у.y0), min(область[2], у.x0 + у.ширина), min(область[3], у.y0 + у.высота))
        до = _L_области(у, обл)
        ответы = []
        for д in наборы[k]:
            о = у.мазок(**д)
            if not о or not hasattr(о, 'тело'):          # пустой мазок или холст без замера (`замер=False`)
                ответы.append(None)
            else:
                ответы.append({'L': None if о.цвет is None else о.цвет['L'], 'тело': о.тело, 'закрыто': о.закрыто,
                               'просветы': о.просветы})
        у.досчитать()
        после = _L_области(у, обл)
        d = после - до
        след = np.abs(d) >= ИЗМЕНЕНО
        if след.any():
            дс = d[след]
            с = {'доля': round(float(след.mean()), 4), 'dL': round(float(дс.mean()), 2),
                 'dL p5': round(float(np.percentile(дс, 5)), 2), 'dL p95': round(float(np.percentile(дс, 95)), 2),
                 'L': round(float(после[след].mean()), 2)}
        else:
            с = {'доля': 0.0, 'dL': 0.0, 'dL p5': 0.0, 'dL p95': 0.0, 'L': None}
        пр = просвет(у, обл, слой=слой_мазков if слой_мазков in у.слои else None, площадь=4, дыр=None)
        внутри = [д for д in пр.дыры if not д['у края']]   # дыра у края области — чаще место мимо мазков, не дыра
        замер = {'средний': у.средний(обл), 'след': с,
                 'просвет': {'просвет': round(float(пр.карта[след].mean()), 4) if след.any() else 1.0,
                             'доля': round(float((пр.карта[след] >= пр['порог']).mean()), 4) if след.any() else 1.0,
                             'дыр': len(внутри), 'видно': пр['видно'],
                             'дыры': [(д['центр'], д['площадь']) for д in внутри[:5]]},
                 'мазки': ответы}
        if цель is not None:
            р = у.разность(цель, обл).сводка
            замер['разность'] = {'среднее': р['среднее'], 'σ': р['σ'], 'dab': р['dab']}
        if мера is not None:
            замер['своё'] = мера(у, обл)
        return замер

    with warnings.catch_warnings(record=True) as слова:
        warnings.simplefilter('always')
        вв = х.варианты(кусок, n, область, ядра)
    for w in слова:                                      # «одинаковые картинки» варианты говорят о куске — здесь своё слово
        if not str(w.message).startswith('варианты: одинаковые картинки'):
            warnings.warn(w.message, stacklevel=2)
    одинаковые = {}
    for в in вв:
        одинаковые.setdefault(в.картинка.tobytes(), []).append(в.номер)
    пары = [[_значения(значения[i]) for i in г] for г in одинаковые.values() if len(г) > 1]
    if пары:
        warnings.warn(f'перебор: значения {пары} дали одну картинку — {", ".join(параметр)} здесь ничего не меняет',
                      stacklevel=2)
    п = Перебор()
    п.варианты, п.значения, п.область = вв, значения, вв[0].область
    п.замеры = []
    for в in вв:
        з = dict(в.ответ)
        з['однообразие'] = round(float(в.однообразие.оценка), 3)
        п.замеры.append(з)
    from .глаз import взгляд
    панели = [взгляд(х, п.область, масштаб=масштаб)]
    подписи = ['до']
    for в, з, м in zip(вв, значения, п.замеры):
        панели.append(_масштаб(_в_8(np.clip(из_линейного(в.картинка) * 255.0, 0.0, 255.0)), масштаб))
        с = м['след']
        подписи.append(f'{в.номер}: {_значения(з)} · dL {_ч(с["dL"])} · просвет {_ч(м["просвет"]["просвет"], 3)}')
    п.лист = лист_панелей(панели, подписи, путь)
    return п
