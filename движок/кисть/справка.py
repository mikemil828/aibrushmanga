"""Поиск по справочнику движка: python -m кисть.справка <слово> [слово …].

Печатает строки `СПРАВОЧНИК.md`, где есть все слова (без учёта регистра), с заголовком раздела над ними.
Без слов — список разделов. Справочник по-английски, имена кода и вывод движка в нём — по-русски: русское слово, которого
в тексте нет, ищется английским из таблицы `словарь_справки.py`; нет и там — ответ «ищи по-английски или именем из кода»."""
import os
import re
import sys

from .словарь_справки import ПАРЫ

СПРАВОЧНИК = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'СПРАВОЧНИК.md')
РУССКОЕ = re.compile('[а-яё]', re.I)


def _ровно(слово):
    return слово.lower().replace('ё', 'е')


def _форма(а, б):
    """Одно слово в разных формах: «борозды» и «борозда» — да, «край» и «краска» — нет."""
    общее = len(os.path.commonprefix([а, б]))
    return общее >= 3 and max(len(а), len(б)) - общее <= 2 and общее >= 0.6 * max(len(а), len(б))


def перевод(слово):
    """Английские слова справочника для русского: точное слово таблицы, иначе его форма, иначе слово внутри оборота."""
    слово = _ровно(слово)
    ряды = [(_ровно(р), а) for р, а in ПАРЫ]
    for годится in (lambda р: р == слово, lambda р: ' ' not in р and _форма(р, слово),
                    lambda р: слово in р.split(), lambda р: слово in р and ' ' in слово):
        ответ = list({а.lower(): а for р, а in ряды if годится(р)})       # «Blending» и «blending» — одно
        if ответ:
            return ответ
    return []


def _искать(слова, путь=СПРАВОЧНИК):
    """(найденное, {русское слово: английские}) — переводы тех слов, что пришлось искать по таблице."""
    слова = [с.lower() for с in слова]
    with open(путь, encoding='utf-8') as ф:
        строки = ф.read().split('\n')
    весь = '\n'.join(строки).lower()

    def пройти(условия):
        раздел, ответ = '', []
        for строка in строки:
            if строка.startswith('#'):
                раздел = строка.lstrip('# ').strip()
                if not условия:
                    ответ.append((раздел, строка))
                    continue
            if условия and строка.strip() and all(у(строка.lower()) for у in условия):
                ответ.append((раздел, строка))
        return ответ

    def условие(слово, английские):
        # английское — с начала слова («set» не находит «offset»); русское и код — как есть
        образцы = [re.compile(r'(?<![a-z])' + re.escape(а.lower())) for а in английские]
        return lambda строка: слово in строка or any(о.search(строка) for о in образцы)

    переводы = {с: перевод(с) for с in слова if РУССКОЕ.search(с) and с not in весь}
    найдено = пройти([условие(с, переводы.get(с, ())) for с in слова])
    if not найдено and len(слова) > 1:            # каждое слово есть, вместе — нигде: русские — и английскими
        переводы = {с: перевод(с) for с in слова if РУССКОЕ.search(с)}
        найдено = пройти([условие(с, переводы.get(с, ())) for с in слова])
    return найдено, переводы


def найти(слова, путь=СПРАВОЧНИК):
    """Список (раздел, строка) со всеми словами; без слов — заголовки разделов. Русское слово, которого нет в тексте, —
    английским из таблицы."""
    return _искать(слова, путь)[0]


def main(argv=None):
    слова = sys.argv[1:] if argv is None else argv
    найдено, переводы = _искать(слова)
    if not найдено:
        русские = any(РУССКОЕ.search(с) for с in слова)
        print(f'нет в справочнике: {" ".join(слова)}' + (' — ищи по-английски или именем из кода' if русские else ''))
        return 1
    for слово, английские in переводы.items():
        if английские:                            # что искалось вместо русского
            print(f'«{слово}» в справочнике: {", ".join(английские)}')
    был = None
    for раздел, строка in найдено:
        if слова and раздел != был:
            print(f'\n## {раздел}')
            был = раздел
        print(строка)
    for слово in слова:                           # нашлось русским — только код и имена: проза о том же — по-английски
        if РУССКОЕ.search(слово) and слово not in переводы and (английские := перевод(слово)):
            print(f'\n«{слово}» в прозе справочника: {", ".join(английские)} — ищи и так')
    return 0


if __name__ == '__main__':
    sys.exit(main())
