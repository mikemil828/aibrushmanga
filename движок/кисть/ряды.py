def таблица(файл=ФАЙЛ):
    if файл not in _ТАБЛИЦА:
        if not os.path.exists(файл):
            raise FileNotFoundError(f'план_покрытия: нет таблицы {файл} — python3 -m кисть.ряды --пересчитать')
        т = кал.прочесть_части(файл, lambda т: ПОЛЯ)
        if т.get('хеш') != хеш():
            warnings.warn(f'план_покрытия: таблица рядов снята с другой физики (хеш {т.get("хеш")}, ядро {хеш()}) — '
                          'python3 -m кисть.ряды --пересчитать', stacklevel=3)
        _ТАБЛИЦА[файл] = т
    return _ТАБЛИЦА[файл]


def _узла(т, пресет, ш, нажим, нагрузка, iв, р):
    """Профиль и снятие в точке — интерполяцией по log ширины, нажиму, log нагрузки (вне осей — по краю) и разбавителю."""
    части = [(w, _узла_р(т, пресет, ш, нажим, нагрузка, iв, iр)) for iр, w in кал.веса_разбавителя(т, р)]
    return [sum(w * ч[k] for w, ч in части) for k in range(len(ПОЛЯ))]


def _узла_р(т, пресет, ш, нажим, нагрузка, iв, iр):
    """То же в узле разбавителя номер iр."""
    пр = т['пресеты'][пресет]
    шш = пр['ширины_мм']
    i, a = кал._индекс(шш, min(max(ш, шш[0]), шш[-1]), True)
    j, b = кал._индекс(НАЖИМЫ, min(max(нажим, НАЖИМЫ[0]), НАЖИМЫ[-1]), False)
    k, c = кал._индекс(НАГРУЗКИ, min(max(нагрузка, НАГРУЗКИ[0]), НАГРУЗКИ[-1]), True)
    i1, j1, k1 = min(i + 1, len(шш) - 1), min(j + 1, len(НАЖИМЫ) - 1), min(k + 1, len(НАГРУЗКИ) - 1)
    out = []
    for поле in ПОЛЯ:
        м = пр[поле][iв, iр]
        v = 0.0
        for ii, wa in ((i, 1 - a), (i1, a)):
            for jj, wb in ((j, 1 - b), (j1, b)):
                for kk, wc in ((k, 1 - c), (k1, c)):
                    v = v + wa * wb * wc * м[ii, jj, kk]
        out.append(v)
    return out


def _серия(профиль, снятие, поверх, шаг, проходов, сушка, поверх_сырого=None):
    """Покрытие середины поля после каждого прохода: 1D счёт глубины поперёк рядов (сетка — 1/40 ширины кисти).
    профиль — глубина одиночного хода по `U`; снятие идёт по доле глубины нового хода к его середине (0–1); поверх —
    во сколько раз глубже ложится ход на краску прежних проходов (в полную силу там, где их глубина — не меньше
    глубины одного хода, меньше — долей)."""
    f = np.asarray(профиль, np.float64)
    середина_хода = float(f[np.abs(np.asarray(U)) <= 0.3].mean())
    касание = np.clip(f / середина_хода, 0.0, 1.0) if середина_хода > 1e-9 else np.zeros_like(f)
    n = int(round(1.0 / 0.025))
    d = шаг * n                                           # шаг рядов в отсчётах сетки
    полу = (len(f) - 1) // 2
    рядов = int(math.ceil((2 * полу + 4 * n) / d)) + 4
    L = int(рядов * d + 2 * полу + 2)
    оси = [полу + 1 + k * d for k in range(рядов)]
    x = np.arange(L, dtype=np.float64)
    uu = np.arange(-полу, полу + 1)
    сл = [(np.interp(x - о, uu, f, left=0.0, right=0.0), np.interp(x - о, uu, касание, left=0.0, right=0.0)) for о in оси]
    сухо, сыро = np.zeros(L), np.zeros(L)
    середина = (x >= оси[рядов // 2 - 1]) & (x < оси[рядов // 2 - 1] + d)    # один период в середине поля
    итог = []
    for p in range(проходов):
        г = поверх if сушка or поверх_сырого is None else поверх_сырого     # проход по высохшему или по сырому прежнему
        for s, к in сл:
            сыро = сыро * (1.0 - снятие * к) + s * (1.0 + (г - 1.0) * np.minimum(сухо / max(середина_хода, 1e-9), 1.0)) \
                if p else сыро * (1.0 - снятие * к) + s
        итог.append(float(1.0 - np.exp(-(сухо + сыро)[середина]).mean()))
        # следующий проход снимает только с рядов своего прохода: и по высохшему, и по сырому (живые серии по сырому
        # 2–3 прохода — в 0,05 от этого счёта; снятие и с прежних проходов занижало их до 0,15)
        сухо, сыро = сухо + сыро, np.zeros(L)
    return итог


def план_покрытия(кисть, покрытие, шаг_рядов=0.8, сушка=False, нажим=0.6, вид=None, разбавитель=None, цвет=None,
                  px_на_мм=None, проходов=None):
    """В-3: сколько проходов серии параллельных рядов и какая нагрузка дадут `покрытие` (1 − просвет грунта, как у
    `х.просвет`, в середине поля без крайних рядов) — по таблице профилей хода и закону накопления (модуль).

    шаг_рядов — расстояние между осями рядов в долях ширины кисти (`кисть.ширина`), 0,4–1,2; сушка — False: все
    проходы подряд по сырому, True: каждый следующий — по высохшему предыдущему (`х.подсушить(1.0)` между проходами);
    проходов — число проходов (None — наименьшее, при котором покрытие достижимо, до 8). Кисть, нажим, вид,
    разбавитель, цвет, px_на_мм — как у `нагрузка_для` (не кроющей краске нужен `цвет=`).

    Ответ — словарь: 'проходов', 'нагрузка' (на каждый ход), 'покрытие' (список: после каждого прохода),
    'разброс' (σ покрытия поля по сиду, оценка), 'шаг_px' (шаг рядов на холсте), 'одним_ходом' (покрытие одного хода
    этой нагрузкой — `по_таблице`). Недостижимое, вне таблицы и шаг вне 0,4–1,2 — `ValueError` с ближайшим
    достижимым. Ничего не кладёт."""
    цель = float(покрытие)
    if not 0.0 < цель < 1.0:
        raise ValueError(f'план_покрытия: покрытие {цель:g} — от 0 до 1, не включая')
    шаг = float(шаг_рядов)
    if not ШАГ[0] - 1e-9 <= шаг <= ШАГ[1] + 1e-9:
        raise ValueError(f'план_покрытия: шаг_рядов {шаг:g} вне {ШАГ[0]:g}…{ШАГ[1]:g} ширины кисти — ближайшее '
                         f'{min(max(шаг, ШАГ[0]), ШАГ[1]):g}; реже 1,2 ряды не смыкаются (полосы грунта), чаще 0,4 — '
                         'закон не снят')
    if проходов is not None and not (1 <= int(проходов) <= ПРОХОДОВ):
        raise ValueError(f'план_покрытия: проходов {проходов} — от 1 до {ПРОХОДОВ}')
    т = таблица()
    тк = кал.таблица()
    пресет, ш = кал._пресет_кисти(кисть, px_на_мм)
    if пресет not in т['пресеты']:
        raise ValueError(f'план_покрытия: для «{пресет}» рядов не снято — пробником')
    iв, р = кал._вид(кал._вид_краски(вид, цвет)), кал._разбавитель(разбавитель)
    s = кал._цвет(цвет)
    if (iв or р) and s is None:
        raise ValueError(кал.НУЖЕН_ЦВЕТ.format(кто='план_покрытия', где=кал._что_за_краска(iв, р)))
    глубиной = bool(iв or р)
    кр, σк = кал._покрытие(тк, пресет, ш, нажим, iв, р, s)
    кр = np.maximum.accumulate(np.asarray(кр, np.float64))
    if глубиной:      # профили сняты тёмно-синей краской узла: глубина краски цвета — во столько раз, во сколько у одиночного хода
        кр_узла = np.maximum.accumulate(np.asarray(кал._покрытие(тк, пресет, ш, нажим, iв, р, кал._цвет(кал.ЦВЕТ))[0], np.float64))

    def один(н):
        return кал._по_нагрузке(кр, н, глубиной=глубиной), кал._по_нагрузке(σк, н)

    def _D(c):
        return -math.log(max(1.0 - c, 1e-9))

    def серия(н, P, c=None):
        проф, сн, пв, пвс = _узла(т, пресет, ш, нажим, н, iв, р)
        k = 1.0
        if глубиной or c is not None:
            c0 = кал._по_нагрузке(кр_узла, н, глубиной=True) if глубиной else один(н)[0]
            k = _D(один(н)[0] if c is None else c) / _D(c0) if _D(c0) > 1e-9 else 1.0
        return _серия(проф * k, сн, пв, шаг, P, сушка, пвс)

    сетка = np.exp(np.linspace(math.log(кал.НАГРУЗКИ[0]), math.log(кал.НАГРУЗКИ[-1]), 61))
    где = f'«{пресет}» {ш:g} мм, нажим {нажим:g}, {кал.ВИДЫ[iв]}, разбавитель {р:g}, шаг {шаг:g}, ' + \
          ('по высохшему' if сушка else 'по сырому')
    if (iв or р) and цвет is not None:
        где += ', цвет ({:g}, {:g}, {:g})'.format(*tuple(цвет)[:3])
    PP = [int(проходов)] if проходов is not None else list(range(1, ПРОХОДОВ + 1))
    for P in PP:
        кривая = np.maximum.accumulate(np.array([серия(н, P)[-1] for н in сетка]))
        if кривая[-1] + 1e-9 < цель:
            if P == PP[-1]:
                raise ValueError(f'план_покрытия: покрытие {цель:g} недостижимо — {где}: {P} '
                                 f'{"проход" if P == 1 else "проходов"} при нагрузке {кал.НАГРУЗКИ[-1]:g} дают '
                                 f'{кривая[-1]:.3f}; больше — чаще ряды, больше проходов, плотнее или темнее краска')
            continue
        if кривая[0] > цель + 1e-9:
            raise ValueError(f'план_покрытия: покрытие {цель:g} недостижимо — {где}: {P} '
                             f'{"проход" if P == 1 else "проходов"} при нагрузке {кал.НАГРУЗКИ[0]:g} дают уже '
                             f'{кривая[0]:.3f}; меньше — реже ряды (шаг до 1,2) или прозрачнее краска')
        k = int(np.argmax(кривая >= цель - 1e-12))
        lo, hi = (сетка[k - 1], сетка[k]) if k else (сетка[0], сетка[0])
        for _ in range(30 if k else 0):                       # делением пополам по log нагрузки
            m = math.sqrt(lo * hi)
            lo, hi = (m, hi) if серия(m, P)[-1] < цель else (lo, m)
        н = round(float(hi), 5)
        ряд = серия(н, P)
        c, σ = один(н)
        # σ поля: сдвиг одиночного хода на его σ, поделённый на корень числа независимых ходов в точке
        вверх = серия(н, P, c=min(c + σ, 0.999))[-1]
        разброс = abs(вверх - ряд[-1]) / math.sqrt(max(1.0, P / шаг))
        return {'проходов': P, 'нагрузка': н, 'покрытие': [round(v, 4) for v in ряд], 'разброс': round(разброс, 4),
                'шаг_px': round(шаг * ш * float(px_на_мм or кал.ПХ_НА_ММ), 1),
                'одним_ходом': round(c, 4)}


