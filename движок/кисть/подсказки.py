def _разница(старое, новое):
    """Нт-2: что сделать с `новое` (счёт или его часть), чтобы вышло `старое`; поровну — {}, None — проще взять `старое`
    целиком. У dict — {'=': {ключ: значение}, '-': {ключ: 1}, '~': {ключ: разница глубже}} (порядок ключей сохраняется:
    другой — None); у списка той же длины — {'[': {номер: разница}} (поменялась больше половины — None); у множества —
    {'s': что убрать, 'a': что добавить}; целиком — {'*': значение}. Снимки только читаются."""
    if старое is новое:
        return {}
    if type(старое) is not type(новое):
        return None
    if isinstance(старое, dict):
        уйти = [к for к in новое if к not in старое]
        if [к for к in новое if к in старое] + [к for к in старое if к not in новое] != list(старое):
            return None
        з, г = {}, {}
        for к, v in старое.items():
            if к not in новое:
                з[к] = v
                continue
            р = _разница(v, новое[к])
            if р is None:
                з[к] = v
            elif р:
                г[к] = р
        р = {}
        if з:
            р['='] = з
        if уйти:
            р['-'] = {к: 1 for к in уйти}
        if г:
            р['~'] = г
        return р
    if isinstance(старое, (list, tuple)):
        if len(старое) != len(новое):
            return None
        г = {}
        for i, (v, н) in enumerate(zip(старое, новое)):
            р = _разница(v, н)
            if р is None:
                г[i] = {'*': v}
            elif р:
                г[i] = р
        if 2 * len(г) > len(старое):              # поменялась большая часть — целиком короче
            return None
        return {'[': г} if г else {}
    if isinstance(старое, (set, frozenset)):
        if старое == новое:
            return {}
        return {'s': _по_порядку(новое - старое), 'a': _по_порядку(старое - новое)}
    return {} if старое == новое else None


def _вид_файла(v):
    """Нт-2: счёт так, как его прочтёт файл памяти: ключи dict — строкой, как их пишет json (повтор ключа — значение
    последнего), кортежи — списками; множества — множествами (файл пишет их списком по порядку). Разница снимков
    считается на этом виде: развёрнутый снимок — тот же, что прочёлся бы из файла целиком."""
    if isinstance(v, dict):
        д = {}
        for к, x in v.items():
            д[_ключ_json(к)] = _вид_файла(x)
        return д
    if isinstance(v, (list, tuple)):
        return [_вид_файла(x) for x in v]
    return v


