    """`х.подсказки`: что сказано и что ждёт; `выключить()`, `выключить('серия')`. `print(х.подсказки)` — всё строками."""

    def __init__(self, холст=None, вкл=True, журнал=None, новый=True):
        self._х = None if холст is None else weakref.ref(холст)
        self.вкл = bool(вкл)
        self.выключены = set()
        self.сказано = []           # [{'вид', 'ключ', 'текст', 'счётчик'}]: счётчик — мазков холста, когда факт сосчитан
        self.ждут = []
        self.забыты = []            # ключи забытых (`забыть`): пара не звучит снова
        self.отдано = set()         # ключи, уже отданные полем `подсказки` (`новые`)
        self.пуски = {}             # ключ пуска -> {'n', 'прошлый': [мазков, с], 'идёт': [мазков, с]}
        self.снимки = {}            # 'файл#счётчик' -> счёт на миг сохранения
        self._разницы = {}          # Нт-2: ключ снимка -> (снимок, следующий, разница к нему) — для файла памяти
        self._виды = {}             # Нт-2: ключ снимка -> (снимок, он же видом файла, `_вид_файла`)
        self.взято = {}             # Св-1: вызовов инструментов подсказок за лист (`взят`)
        self.глаза = {}             # вызовов каждого глаза и мерки за лист
        self.образец = None         # С9: «цвет в пятне» p50 [холст, образец] последней `х.манера(…, образец=)`
        self.счёт = _свежий_счёт()
        self.путь = None
        self._журнал = None         # С14: зеркало мест читает журнал листа
        self._пуск = None           # (ключ, счётчик холста, время)
        self._первая = False        # новый журнал: пуск считается с первой пометки
        if журнал is not None and self.вкл:
            self._журнал = os.path.abspath(os.fspath(журнал))
            self.путь = self._журнал + '.подсказки.json'   # конец процесса может прийти из другой папки
            self._прочесть()
            self._первая = True
            if self.вкл and новый:
                self.забыть(0)          # журнал пишется с начала: всё сосчитанное по прежним мазкам — стёрто
        self._pid = os.getpid()     # процесс-ветвь (ядра, варианты) с копией холста молчит и файл не пишет
        if self.вкл:
            _живые.add(self)

    # ------------------------------------------------------------ снаружи
    def выключить(self, вид=None):
        """Выключить все подсказки (вид None) или один вид: 'серия', 'пуск этапа', 'глаза', 'ответы', 'первый мазок
        слоя', 'по одному месту', …, 'срезано ножом' (или 'С1'…'С18'). У холста с журналом выключенное помнит файл листа."""
        if вид is None:
            self.вкл = False
        else:
            к = вид if вид in ВИДЫ else {v: k for k, v in ВИДЫ.items()}.get(вид)
            if к is None:
                raise ValueError(f'подсказки.выключить: вида {вид!r} нет (есть: {", ".join(ВИДЫ.values())})')
            self.выключены.add(к)
            self.ждут = [п for п in self.ждут if п['вид'] != к]
        self._записать(всегда=True)

    def новые(self):
        """Канал: тексты подсказок (сказанных и ждущих), которых ещё не было в поле `подсказки` ответа; каждая — раз на
        лист. Поле `подсказки` ответа `х.взгляд` и `х.сохранить`."""
        if not self.вкл:
            return []
        н = [п for п in self.сказано + self.ждут if п['ключ'] not in self.отдано]
        if н:
            for п in н:
                п.setdefault('взято', self._сколько(п))
            self.отдано.update(п['ключ'] for п in н)
            self._записать()
        return [п['текст'] for п in н]

    # ------------------------------------------------------------ Св-1: сводка этапа
    def взят(self, имя):
        self.взято[имя] = self.взято.get(имя, 0) + 1

    def _сколько(self, п):
        from .сводка import инструменты
        return sum(self.взято.get(и, 0) for и in инструменты(п['текст']))

    def неотвеченные(self):
        """Сказанные (или отданные полем `подсказки`), после которых ни одного их инструмента «под рукой» не позвано."""
        return [п for п in self.сказано + self.ждут if 'взято' in п and self._сколько(п) == п['взято']]

    def мазки_листа(self):
        """Мазки журнала листа (дочитанного) и его мета: (мазки, мета); журнала нет или он не читается — None."""
        if self._журнал is None:
            return None
        from . import однообразие as О
        д = self.__dict__.get('_дочитка')
        if д is None or д.путь != self._журнал:
            д = self.__dict__['_дочитка'] = О.Дочитка(self._журнал)
        try:
            return д.мазки(), д.мета
        except (OSError, ValueError):
            self.__dict__.pop('_дочитка', None)
            return None

    def сводка(self, этап, вслух=False):
        """Св-1: сводка этапа (None — без этапа). вслух — и в stdout, если с прошлой сводки этапа легли новые мазки."""
        from . import сводка as С
        ключ = '' if этап is None else str(этап)
        т = С.собрать(self, ключ)
        if т and вслух:
            э = self.счёт['э'][ключ]
            if э['мазков'] > э['сказано']:
                э['сказано'] = э['мазков']
                try:
                    print(т, flush=True)
                except (OSError, ValueError):
                    pass
        return т

    def этап_сводки(self, х):
        """Этап, о котором сводка сейчас: текущий; в нём мазков нет (этап дан у самих мазков) — этап последнего мазка, если
        о нём ещё не сказано."""
        э = self.счёт.get('э', {})
        ключ = '' if х._этап is None else str(х._этап)
        if not э.get(ключ, {}).get('мазков'):
            к = self.счёт.get('э последний')
            if к in э and э[к]['мазков'] > э[к]['сказано']:
                return к
        return ключ

    def забыть(self, счётчик):
        """Сверка с журналом: подсказки, сосчитанные после `счётчик` мазков (или без отметки счёта), — по мазкам, которых
        в журнале больше нет (перезапуск этапа с сохранения, лист с начала): из сказанных и ждущих уходят, ключ — в
        `забыты`; счёт на сохранения позже этого — тоже."""
        стёрто = lambda п: п.get('счётчик') is None or п['счётчик'] > счётчик
        for сп in (self.сказано, self.ждут):
            for п in [п for п in сп if стёрто(п)]:
                сп.remove(п)
                if п['ключ'] not in self.забыты:
                    self.забыты.append(п['ключ'])
                self.отдано.discard(п['ключ'])
        for к in [к for к in self.снимки if int(к.rsplit('#', 1)[1]) > счётчик]:
            del self.снимки[к]

    def __iter__(self):
        return iter([п['текст'] for п in self.сказано + self.ждут])

    def __len__(self):
        return len(self.сказано) + len(self.ждут)

    def __str__(self):
        if not self.вкл and not len(self):
            return 'подсказки выключены'
        ч = [f'подсказки: сказано {len(self.сказано)}, ждут {len(self.ждут)}' + ('' if self.вкл else ' (выключены)')
             + (f'; выключены виды: {", ".join(ВИДЫ[к] for к in sorted(self.выключены))}' if self.выключены else '')]
        ч += ['  сказана: ' + п['текст'] for п in self.сказано]
        ч += ['  ждёт:    ' + п['текст'] for п in self.ждут]
        return '\n'.join(ч)

    __repr__ = __str__

    # ------------------------------------------------------------ память
    def _прочесть(self):
        try:
            with open(self.путь, encoding='utf-8') as f:
                д = json.load(f)
        except (OSError, ValueError):
            return
        self.сказано, self.ждут = list(д.get('сказано', [])), list(д.get('ждут', []))
        self.пуски, self.глаза = dict(д.get('пуски', {})), dict(д.get('глаза', {}))
        self.образец = д.get('образец')
        self.взято = dict(д.get('взято', {}))
        self.снимки = self._снимки_файла(д)
        self.выключены = set(д.get('выключены', []))
        self.забыты, self.отдано = list(д.get('забыты', [])), set(д.get('отдано', []))
        if д.get('выключены_все'):
            self.вкл = False

    def _снимки_файла(self, д):
        """Нт-2: снимки счёта из файла памяти. "снимки" — последний целиком (у файла до Нт-2 — все целиком),
        "снимки_назад" — [[ключ, разница], …] прежних по порядку: каждый — разницей к следующему за ним (`_разница`)."""
        полные = д.get('снимки', {})
        назад = д.get('снимки_назад', [])
        if not назад or len(полные) != 1:
            return {к: _из_json(v) for к, v in полные.items()}
        (к_посл, тек), = полные.items()
        цепь = [(к_посл, тек)]
        for к, р in reversed(назад):
            тек = _с_разницей(тек, р)
            цепь.append((к, тек))
        цепь.reverse()
        for (к, с), (_, сл), (_, р) in zip(цепь, цепь[1:], назад):
            self._разницы[к] = (с, сл, р)         # уже посчитаны: запись их не считает заново
        снимки = {к: _из_json(с) for к, с in цепь}
        self._виды = {к_посл: (снимки[к_посл], снимки[к_посл])}     # прочтённое из файла — уже его вида
        return снимки

    def _снимки_в_файл(self):
        """Нт-2: снимки для файла памяти — последний целиком, прежние разницей к следующему (файл не растёт как
        «сохранений × полный счёт»). Разница пары считается раз: снимки после сохранения не правятся."""
        ключи = list(self.снимки)
        if len(ключи) < 2:
            self._разницы, self._виды = {}, {}
            return {к: self.снимки[к] for к in ключи}, None
        виды = self._виды

        def вид(к):                               # вид файла — раз на снимок, и только для пары, что считается
            с, было = self.снимки[к], виды.get(к)
            if было is None or было[0] is not с:
                было = виды[к] = (с, _вид_файла(с))
            return было[1]
        назад, разницы = [], {}
        for к, сл in zip(ключи, ключи[1:]):
            с, н = self.снимки[к], self.снимки[сл]
            было = self._разницы.get(к)
            if было is not None and было[0] is с and было[1] is н:
                р = было[2]
            else:
                р = _разница(вид(к), вид(сл))
                if р is None:
                    р = {'*': с}
            разницы[к] = (с, н, р)
            назад.append([к, р])
        self._разницы = разницы
        self._виды = {ключи[-1]: виды[ключи[-1]]} if ключи[-1] in виды else {}    # следующей паре нужен только последний
        return {ключи[-1]: self.снимки[ключи[-1]]}, назад

    def _записать(self, всегда=False):
        if self.путь is None or (not self.вкл and not всегда) or self._pid != os.getpid():
            return
        снимки, назад = self._снимки_в_файл()
        д = {'сказано': self.сказано, 'ждут': self.ждут, 'пуски': self.пуски, 'глаза': self.глаза,
             'выключены': sorted(self.выключены), 'выключены_все': not self.вкл, 'снимки': снимки, 'образец': self.образец,
             'забыты': self.забыты, 'отдано': sorted(self.отдано), 'взято': self.взято}
        if назад:
            д['снимки_назад'] = назад
        часть = f'{self.путь}.часть{os.getpid()}'
        try:
            with open(часть, 'w', encoding='utf-8') as f:
                json.dump(д, f, ensure_ascii=False, default=_в_json, separators=(',', ':'))
            os.replace(часть, self.путь)
        except OSError:
            pass

    # ------------------------------------------------------------ служебное
    def _холст(self):
        return None if self._х is None else self._х()

    def тихо(self, х):
        return not self.вкл or self._pid != os.getpid() or х.__dict__.get('_тишина', 0) or х.__dict__.get('_тихо', 0)

    def _добавить(self, вид, ключ, факт, инструменты):
        if вид in self.выключены or ключ in self.забыты or any(п['ключ'] == ключ for п in self.сказано + self.ждут):
            return
        х = self._холст()
        и = list(инструменты)
        random.Random(f'{0 if х is None else х.сид}:{len(self)}').shuffle(и)   # правило 3: первый не становится тропинкой
        self.ждут.append({'вид': вид, 'ключ': ключ, 'текст': f'подсказка: {факт} — под рукой: ' + ', '.join(и),
                          'счётчик': 0 if х is None else int(х._счётчик)})

    def _сказать(self):
        """Граница: одна строка — старшая из ждущих; не больше `НА_ПРОЦЕСС` строк на процесс."""
        if not self.вкл or not self.ждут or _в_процессе[0] >= НА_ПРОЦЕСС:
            return
        self.ждут.sort(key=lambda п: СТАРШИНСТВО.index(п['вид']))
        п = self.ждут.pop(0)
        self.сказано.append(п)
        п.setdefault('взято', self._сколько(п))
        _в_процессе[0] += 1
        текст = п['текст'] + (f' (ещё {len(self.ждут)}: х.подсказки)' if self.ждут else '')
        warnings.warn(Подсказка(текст), stacklevel=2, skip_file_prefixes=(_ПАПКА,))
        if not _в_конце[0]:            # конец процесса: stdout скрипта уже кончился (его последнюю строку читают) —
            _в_stdout(текст)           # там только stderr, а полю ответа строка достанется в следующем процессе

    @staticmethod
    def _имя(ключ):
        return f'объект «{ключ[2:]}»' if ключ.startswith('о:') else f'слой «{ключ[2:]}»'

    @staticmethod
    def _отбор(ключ):
        return f'объект={ключ[2:]!r}' if ключ.startswith('о:') else f'слой={ключ[2:]!r}'

    # ------------------------------------------------------------ мазок
    def мазок_принят(self, х, точки, кисть, нагрузка, слой, объект, новый_слой, краски, имя_кисти=None, замес=False, этап=None):
        """`Холст._принять_мазок`: С1 (серия), С4 (мазков без глаз); слои и места объекта (С10–С12); метка мазка для
        `мазок_лёг` (С5, С6, С8, С13)."""
        с = self.счёт
        с['после_глаз'] += 1
        ко = ('о:' + str(объект)) if объект is not None else ('с:' + str(слой))
        о = с['о'].setdefault(ко, {'ходов': 0, 'серии': {}, 'пустые': {}, 'прочтено': 0})
        о['ходов'] += 1
        н = кисть.нагрузка if нагрузка is None else нагрузка
        try:
            вытертая = кисть.толщина_плёнки(н) <= 0.0
        except Exception:                                    # noqa: BLE001 — нагрузка, которой мазок всё равно не примет
            вытертая = False
        т = np.asarray(точки, np.float64)
        т = т[:, :2] if т.ndim == 2 and т.shape[1] >= 2 else np.zeros((0, 2))
        ш = float(кисть.ширина_мм * х.px_на_мм) if кисть.ширина_мм is not None and х.px_на_мм else float(кисть.ширина)
        мягкая = getattr(кисть, 'кайма', 0.0) > 0.0 and кисть.форма != 'мастихин'
        if not вытертая and len(т):
            from dataclasses import asdict
            поля = {к: v for к, v in asdict(кисть).items() if к not in ('имя', 'ширина', 'ширина_мм')}
            хорда = т[-1] - т[0]
            if math.hypot(*хорда) > 1e-6:
                наклон = math.degrees(math.atan2(хорда[1], хорда[0])) % 180.0
                сектор = int(((наклон + 15.0) % 180.0) // 30.0)
            else:
                сектор = -1
            нг = f'{int(math.floor(float(н) / 0.1))}' if isinstance(н, (int, float)) else str(н)
            ключ = json.dumps([поля, int(math.floor(math.log2(max(ш, 1e-3)))), сектор, нг], sort_keys=True, ensure_ascii=False)
            s = о['серии'].get(ключ)
            if s is None:
                слово_нг = (f'нагрузкой {_ч(int(нг) / 10)}–{_ч(int(нг) / 10 + 0.1)}' if isinstance(н, (int, float))
                            else f'нагрузкой «{н}»')
                s = о['серии'][ключ] = [0, f'{"мягкая" if мягкая else кисть.форма} {ш:.0f} px', сектор, слово_нг, set()]
            s[0] += 1
            кл = _клетки(т, ш / 2.0, х.полная_ширина, х.полная_высота)
            s[4].update(кл)
            if краски:                                         # М-2, С12: места и слои объекта
                nx = math.ceil(х.полная_ширина / КЛЕТКА)
                маска = int(о.get('места', '0'), 16)
                for c in кл:
                    маска |= 1 << ((c // 100000) * nx + c % 100000)
                о['места'] = format(маска, 'x')
                о.setdefault('слои', {})[str(слой)] = 1
                с.setdefault('новые_слои', {})[str(слой)] = 1
        if краски and not вытертая and len(т):                # С9: названный цвет хода — в плитку его центра
            т_мм = РАЗБРОС_ММ * х.px_на_мм if х.px_на_мм else 128.0
            ц = т.mean(axis=0)
            пл = о.setdefault('цвета', {}).setdefault(f'{int(ц[1] // т_мм)}:{int(ц[0] // т_мм)}', [0.0] * 7)
            о['с краской'] = о.get('с краской', 0) + 1
            for x, д in _цвета(краски):
                пл[0] += д
                for i in range(3):
                    пл[1 + i] += д * x[i]
                    пл[4 + i] += д * x[i] * x[i]
        метка = {'о': ко, 'слой': str(слой)}
        метка['э'] = '' if этап is None else str(этап)       # Св-1
        if новый_слой:
            self.взят('новый слой')
        метка['этап'] = ('э:' + str(этап)) if этап is not None else ко      # Г-8: раз на этап
        if краски and not вытертая and len(т) and о.get('формула') != 0:     # М-1, С16: первые 100 ходов с краской
            ф = о.setdefault('формула', [0, 0, []])
            ф[0] += 1
            if not замес:
                ф[1] += 1
                ключ_цвета = ':'.join(f'{float(v):.4f}' for c, д in краски for v in (*np.asarray(c).ravel(), д))
                if ключ_цвета not in ф[2]:
                    ф[2].append(ключ_цвета)
            if ф[0] >= ФОРМУЛА_ХОДОВ:
                разных = len(ф[2])
                if ф[1] >= ФОРМУЛА_ДОЛЯ * ф[0] and разных >= ФОРМУЛА_ДОЛЯ * ф[1]:
                    self._добавить('С16', 'С16:' + ко, факт_формулы(self._имя(ко), ф[0], ф[1], разных),
                                   ИНСТРУМЕНТЫ_ФОРМУЛЫ + [f'х.однообразие({self._отбор(ко)})'])
                    метка['формула'] = 1
                о['формула'] = 0                               # раз на объект: первая сотня сосчитана
        if х.px_на_мм is not None and float(х.px_на_мм) != М_.РОДНОЙ and 'С15:холст' not in self._ключи():   # М-9
            что = М_.держит_px(кисть, н, х.px_на_мм)
            if что:
                self._масштаб(х, кисть, имя_кисти, что, ш)
                метка['масштаб'] = 1
        if новый_слой and not вытертая and краски:
            метка['новый'] = _светлота(краски)
        if мягкая and not вытертая and len(т):
            метка['плитки'] = _плитки(т, ш / 2.0)
        if краски and not вытертая and len(т):                # С13: кисть, место хода, названный тон
            from .инструмент import сырое_поле
            ц = _цвета(краски)
            метка['кисть'] = [id(кисть), str(имя_кисти or кисть.имя), сырое_поле(кисть, '_остаток') is None]
            метка['где'] = [float(т[:, 0].mean()), float(т[:, 1].mean()), max(ГРЯЗЬ_ШИРИН * ш, 64.0)]
            метка['тон'] = [sum(x[i] * д for x, д in ц) for i in range(3)]
            к = self.__dict__.setdefault('_кисти', {})
            з = к.get(id(кисть))
            if з is None or з[0]() is not кисть:
                к[id(кисть)] = [weakref.ref(кисть), []]
