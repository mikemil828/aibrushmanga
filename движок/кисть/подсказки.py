        if 'новый' in метка and 'закрыто' in д and 'серый' not in д:     # С6; мазок без следа говорит `ПустойМазок`, без замера (`замер=False`) — не судим
            закрыто = float(д['закрыто'])
            if закрыто < ПОРОГ_ЗАКРЫТО:
                слой = метка['слой']
                цвет = д.get('цвет')
                сыро = (д.get('сырое') or {}).get('по сырому', 0.0)
