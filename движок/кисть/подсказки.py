def _в_stdout(текст):
    """Канал: сказанная строка — и в stdout, если он не тот же файл, что stderr (иначе строка уже видна)."""
    import sys
    try:
        a, b = os.fstat(sys.stdout.fileno()), os.fstat(sys.stderr.fileno())
        if (a.st_dev, a.st_ino) == (b.st_dev, b.st_ino):
            return
    except (AttributeError, OSError, ValueError):       # stdout подменён (тесты, блокнот) — пишем в него
        pass
    try:
        print(текст, flush=True)
    except (OSError, ValueError):
        pass


def _цвета(краски):
    """С9: названные краски хода [(линейный RGB, доля)] -> [((L серой шкалы, a, b OKLab), доля)], доли в сумме 1."""
    from .краска import из_линейного
    from .глаз import oklab, _L
    в = sum(float(д) for _, д in краски) or 1.0
    итог = []
    for c, д in краски:
        lab = oklab(np.clip(из_линейного(np.asarray(c, np.float64)) * 255.0, 0.0, 255.0))
        итог.append(((float(_L(lab[0])), float(lab[1]), float(lab[2])), float(д) / в))
    return итог


def _разброс(о):
    """С9: σ названных цветов внутри плиток соседства, сведённая по всем плиткам: (ходов с краской, σ a, b, σ L) или None
    (ходов меньше порога, или соседей в плитках меньше четверти ходов — ходы врозь, счёт не о соседях)."""
    n = о.get('с краской', 0)
    if n < РАЗБРОС_ХОДОВ:
        return None
    ss, ст = np.zeros(3), 0.0
    for пл in о.get('цвета', {}).values():
        w = пл[0]
        if w <= 1.0 + 1e-9:
            continue
        ср = np.asarray(пл[1:4]) / w
        ss += np.maximum(np.asarray(пл[4:7]) - w * ср * ср, 0.0)
        ст += w - 1.0
    if ст < 0.25 * n:
        return None
    σ = np.sqrt(ss / ст)
    return n, float(math.hypot(σ[1], σ[2])), float(σ[0])


def _светлота(краски):
    """Тон названной краски — L серой шкалы (как `цвет['L']` ответа)."""
    from .краска import из_линейного
    from .глаз import светлота
    try:
        lin = sum(np.asarray(c, np.float64) * float(д) for c, д in краски)
        return float(светлота(np.clip(из_линейного(lin) * 255.0, 0.0, 255.0)))
    except Exception:                                        # noqa: BLE001
        return float('nan')


def _вдоль(т, шаг):
    """Точки пути через не больше чем `шаг` px."""
    if len(т) < 2:
        return т
    d = np.hypot(*np.diff(т, axis=0).T)
    s = np.concatenate([[0.0], np.cumsum(d)])
    if s[-1] <= 0:
        return т[:1]
    u = np.linspace(0.0, s[-1], max(2, int(math.ceil(s[-1] / шаг)) + 1))
    return np.column_stack([np.interp(u, s, т[:, 0]), np.interp(u, s, т[:, 1])])


def _клетки(т, r, ширина, высота=None):
    """Клетки `КЛЕТКА` px под путём шириной 2r (номер — y · 100000 + x)."""
    п = _вдоль(т, КЛЕТКА / 2.0)
    k = int(math.ceil(r / КЛЕТКА))
    o = np.arange(-k, k + 1)
    cx = np.floor(п[:, 0] / КЛЕТКА).astype(np.int64)
    cy = np.floor(п[:, 1] / КЛЕТКА).astype(np.int64)
    X = (cx[:, None, None] + o[None, None, :]).repeat(len(o), 1)
    Y = (cy[:, None, None] + o[None, :, None]).repeat(len(o), 2)
    м = (X >= 0) & (Y >= 0) & (X * КЛЕТКА < ширина) & ((Y * КЛЕТКА < высота) if высота else True)
    return set(np.unique(Y[м] * 100000 + X[м]).tolist())


def _плитки(т, r):
    """Плитки `ПЛИТКА` px, через которые прошёл след кисти шириной 2r (центр плитки — не дальше r от пути)."""
    п = _вдоль(т, ПЛИТКА / 4.0)
    k = int(math.ceil(r / ПЛИТКА)) + 1
    o = np.arange(-k, k + 1)
    cx = np.floor(п[:, 0] / ПЛИТКА).astype(np.int64)
    cy = np.floor(п[:, 1] / ПЛИТКА).astype(np.int64)
    X = (cx[:, None, None] + o[None, None, :]).repeat(len(o), 1)
    Y = (cy[:, None, None] + o[None, :, None]).repeat(len(o), 2)
    dx = (X + 0.5) * ПЛИТКА - п[:, 0, None, None]
    dy = (Y + 0.5) * ПЛИТКА - п[:, 1, None, None]
    м = (X >= 0) & (Y >= 0) & (dx * dx + dy * dy <= max(r, ПЛИТКА / 2.0) ** 2)
    return sorted(set((Y[м] * 100000 + X[м]).tolist()))


