                self._добавить('С6', 'С6:' + слой, f'первый мазок слоя «{слой}» — закрыто {_ч(закрыто, 2)}, {тон}, {под}',
                               ['х.проба', 'print(о)', 'х.перебор(мазки, нагрузка=[…])', f'х.взгляд(область, без=[{слой!r}])'])
