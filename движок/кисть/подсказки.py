    def _грязь(self, метка, д):
        """С13: подбор чужого тона кистью и ходы, что после него легли далеко (по полям ответа: `сырое`, `цвет`)."""
        ид, имя, чистая = метка['кисть']
        з = self.__dict__.get('_кисти', {}).get(ид)
        if з is None:
            return
        подборы = з[1]
        if чистая:                                       # вытерта (или новая) до этого хода
            if подборы:
                self.взят('кисть')                       # Св-1: инструменты С13 `к.вытереть()`, `к.с()`
            подборы.clear()
        cx, cy, далеко = метка['где']
        L, a, b = метка['тон']
        к = self.счёт.setdefault('к', {}).setdefault(json.dumps([имя, метка['о']], ensure_ascii=False), [0, 0, 0.0, 0.0, 0.0])
        к[1] += 1
        цвет = д.get('цвет')
        if цвет is not None:
            C, h = float(цвет['C']), math.radians(float(цвет['h']))
            dL, dab = abs(float(цвет['L']) - L), math.hypot(C * math.cos(h) - a, C * math.sin(h) - b)
        дальше = [math.hypot(p[0] - cx, p[1] - cy) for p in подборы]
        дальше = [r for r in дальше if r > далеко]
        if дальше and цвет is not None:
            к[0] += 1
            к[2], к[3], к[4] = max(к[2], dL), max(к[3], dab), max(к[4], max(дальше))
        for p in подборы:
            p[2] += 1
        подборы[:] = [p for p in подборы if p[2] < ГРЯЗЬ_ХОДОВ]
        if цвет is not None and (д.get('сырое') or {}).get('к положенному', 0.0) >= ГРЯЗЬ_К_ПОЛОЖЕННОМУ \
                and (dL >= ГРЯЗЬ_ΔL or dab >= ГРЯЗЬ_ΔAB):
            подборы.append([cx, cy, 0])

