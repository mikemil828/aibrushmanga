    def рельеф(self, х):
        """М-2: С10–С12 по слоям, в которые с прошлого счёта легли мазки; `х.сохранить`, `х.закрыть` (холст досчитан)."""
        if not self.вкл or self._pid != os.getpid() or not {'С10', 'С11', 'С12'} - self.выключены:
            return
        новые = self.счёт.get('новые_слои') or {}
        if not новые:
            return
        from . import подсказки_рельеф as Р
        было = {п['ключ'] for п in self.сказано + self.ждут}
        слои = {s for s in новые if s in х.слои and not {'С10:с:' + s, 'С11:с:' + s} <= было}
        nx = math.ceil(х.полная_ширина / КЛЕТКА)
        объекты = {}
        for ко, о in self.счёт['о'].items():
            if 'места' in о and 'С12:' + ко not in было and any(s in новые for s in о.get('слои', {})):
                маска = int(о['места'], 16)
                биты = np.nonzero(np.unpackbits(np.frombuffer(маска.to_bytes((маска.bit_length() + 7) // 8, 'little'), np.uint8),
                                                bitorder='little'))[0]
                объекты[ко] = (list(о['слои']), set(((биты // nx) * 100000 + биты % nx).tolist()))
        for вид, ключ, факт, и in Р.счёт(х, слои, объекты):
            self._добавить(вид, ключ, факт, и)
        self.счёт['новые_слои'] = {}

