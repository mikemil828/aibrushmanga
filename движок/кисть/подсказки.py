def _с_разницей(новое, р):
    """Обратное `_разница`: часть снимка из той же части следующего за ним и своей разницы. Нетронутое — те же объекты
    (снимки не правятся), `новое` не трогается. р — как записан файл памяти (ключи и номера — строками) или как посчитан;
    множество из файла приходит списком — ответ тогда множество."""
    if not р:
        return новое
    if '*' in р:
        return р['*']
    if '[' in р:
        с = list(новое)
        for i, ри in р['['].items():
            с[int(i)] = _с_разницей(с[int(i)], ри)
        return с
    if 's' in р or 'a' in р:                # как множество пишет файл: списком по порядку (`_в_json`)
        return sorted((set(новое) - set(р.get('s', ()))) | set(р.get('a', ())))
    з, уйти, г = р.get('=', {}), р.get('-', {}), р.get('~', {})
    с = {}
    for к, v in новое.items():
        if к in уйти:
            continue
        с[к] = з[к] if к in з else _с_разницей(v, г[к]) if к in г else v
    for к, v in з.items():
        if к not in с:
            с[к] = v
    return с


class _Учёт:
    """Метка в ответе мазка: первое чтение его полей — в счёт «ответ прочитан» объекта (С5). В pickle не идёт."""
    __slots__ = ('п', 'объект', 'этап')

    def __init__(self, п, объект, этап):
        self.п, self.объект, self.этап = weakref.ref(п), объект, этап

    def прочтён(self):
        п = self.п()
        if п is not None:
            о = п.счёт['о'].get(self.объект)
            if о is not None:
                о['прочтено'] += 1
            э = п.счёт.get('э', {}).get(self.этап)           # Св-1
            if э is not None:
                э['прочитано'] += 1
            п.взят('ответ')

    def __reduce__(self):
        return (type(None), ())


