"""Живая борозда (версия 3, пункт 4): глубина и наполнение борозды меняются вдоль хода, место её — нет.

Борозда — след кончика ведущего волоска. Ровной лентой она выходит, когда волосок всю дорогу давит одинаково
и несёт одинаково. Здесь у каждого ведущего волоска вдоль хода своя жизнь, и вся она — из кисти и из того, что
лежит на холсте, а не шум поверх картинки:

  запас кончика   краска на кончике кончается и возобновляется из запаса выше по волоску. Под полным кончиком
                  краска затекает за волоском — борозда мелкая и узкая; под пустым волосок скребёт — глубокая
                  и широкая, у жёсткого волоска до дна своей плёнки. Расход идёт с нажимом и касанием, поэтому
                  счёт ведётся не в px пути, а в израсходованной краске (`_запас_кончика`);
  проскок         волосок цепляется, гнётся и срывается вперёд: 1,5–4,5 px он холста не касается (борозда на этом
                  месте закрыта — короткий срыв), а приземлившись, оставляет каплю — светлую точку под светом.
                  Чаще в густой краске и под лёгкой рукой; на гребне лежащей краски — всегда (`_проскок`);
  слипание        соседние волоски слипаются и расходятся: гребень между ними проседает, две борозды читаются
                  одной широкой. Прижатая щетина расходится — под нажимом слипаний нет (`_слипание`).

`положить_мазок` зовёт `неровный_запас` (запас гребней, перенесён из укладки как был), `борозды` (один раз на мазок)
и `профиль_борозд` (поперечный профиль плёнки на каждом шаге пути). Числа — `числа.py`, блок «пункт 4».
"""
import numpy as np

from .быстро import зажать, обложить

from .числа import (_БОР_ГЛУБ, _БОР_ГРЕБЕНЬ, _БОР_ЖИВО, _БОР_ЗАПАС, _БОР_КАПЛЯ, _БОР_МЕЛКО, _БОР_ПОДЪЁМ, _БОР_ПРОСКОК, _БОР_ПРЯДЬ,
                    _БОР_СЛИП, _БОР_ТОН, _БОР_ТОН_ВЕС, _БОР_ШИРЕ, _СУХАЯ)
from .пряди import _шум


def неровный_запас(с, к, rng, Nc, шаг_к, W, мастихин, полупустая=False):
    """Неровный запас гребней: шум вытянут вдоль хода и свой у каждого гребня — сухая кисть рвётся линиями.
    Ответ: неровн (Nc, nr) — запас гребня вдоль хода; густота (Nc, nr) — гребень то гуще, то тоньше: краска
    на волоске лежит неровно."""
    nr, ns = с.nr, с.ns
    if мастихин:
        nk = max(3, int(W / 9.0) + 2)
        основа = _шум(rng, Nc, nk, 60.0 / шаг_к) * 0.38 + _шум(rng, Nc, nk, 20.0 / шаг_к) * 0.28
        t = (с.центр / W + 0.5) * (nk - 1)
        i0 = зажать(t.astype(np.intp), 0, nk - 2)
        f = t - i0
        f = f * f * (3 - 2 * f)
        неровн = 1.0 + основа[:, i0] * (1 - f)[None, :] + основа[:, i0 + 1] * f[None, :]
        return неровн, np.ones((Nc, nr))
    неровн = (1.0 + 0.30 * _шум(rng, Nc, nr, 170.0 / шаг_к) + 0.26 * _шум(rng, Nc, nr, 55.0 / шаг_к)
              + 0.14 * _шум(rng, Nc, nr, 16.0 / шаг_к)
              + 0.20 * к.клочки * _шум(rng, Nc, ns, 90.0 / шаг_к)[:, с.прядь])
    if к.неровность_запаса != 1.0:      # К8.3: мягкий длинный волос (лайнер) держит краску вдоль хода ровнее щетины
        неровн = 1.0 + (неровн - 1.0) * float(к.неровность_запаса)
    густота = зажать(1.0 + 0.16 * _шум(rng, Nc, nr, 38.0 / шаг_к) + 0.12 * _шум(rng, Nc, nr, 9.0 / шаг_к), 0.4, 1.7)
    if полупустая:
        # п. 10, инструмент 2: на полупустом ворсе краска лежит комками в несколько волосков, а не нитью вдоль каждого
        # гребня — разрыв следа выходит пятном разного размера, вытянутым по ходу, а не щелью-рельсой на весь ход
        rng_с = np.random.default_rng(rng.bit_generator.seed_seq.spawn(1)[0])

        def комки(длина, проходов):
            ш = _шум(rng_с, Nc, nr, max(длина, 2.0 * шаг_к) / шаг_к)
            for _ in range(проходов):
                q = обложить(ш, ((0, 0), (1, 1)), край=True)
                ш = 0.25 * q[:, :-2] + 0.5 * q[:, 1:-1] + 0.25 * q[:, 2:]
            return ш / max(float(ш.std()), 1e-6)

        неровн = (1.0 + _СУХАЯ[3] * комки(0.9 * W, 2 * _СУХАЯ[6]) + _СУХАЯ[4] * комки(0.3 * W, _СУХАЯ[6]) + _СУХАЯ[5] * комки(5.0, 0)
                  + 0.20 * к.клочки * _шум(rng_с, Nc, ns, 90.0 / шаг_к)[:, с.прядь])
    return неровн, густота


def _отрезки(q, длины):
    """Счёт q (N, n), растущий вдоль хода, разбит у каждого столбца на отрезки своей длины (K, n).
    Ответ: номер отрезка (N, n) и сколько пройдено от его начала (в единицах q)."""
    K, n = длины.shape
    концы = np.cumsum(длины, axis=0)
    большое = float(max(концы[-1].max(), q.max())) * 2.0 + 1.0
    сдвиг = np.arange(n) * большое
    k = np.searchsorted((концы + сдвиг[None, :]).T.ravel(), (q + сдвиг[None, :]).ravel()).reshape(q.shape) - np.arange(n) * K
    k = зажать(k, 0, K - 1)
    столбцы = np.arange(n)[None, :]
    начало = np.where(k > 0, концы[np.maximum(k - 1, 0), столбцы], 0.0)
    return k, q - начало


def _запас_кончика(с, расход_в, ds, живо, живо_ср, мелк, rng):
    """Полнота кончика каждого ведущего волоска вдоль хода, 0..1 (N, nv). Кончик пустеет, пока кладёт, и наполняется
    из запаса выше по волоску; на сколько его хватает и до какой доли он пустеет — у каждого раза своё. Тонкая
    краска под прижатой кистью стекает на кончик плавно, густая под лёгкой рукой сходит комком — разом.
    Половина запаса — общая у волосков пряди (`_БОР_ПРЯДЬ`): прядь набрана одним комком."""
    N, nv = расход_в.shape
    хватает = (_БОР_ЗАПАС[0] + (_БОР_ЗАПАС[1] - _БОР_ЗАПАС[0]) * живо) * мелк         # (N,) px
    наполняется = _БОР_ЗАПАС[5] + (_БОР_ЗАПАС[6] - _БОР_ЗАПАС[5]) * живо_ср

    def волна(расход, запас):
        n = расход.shape[1]
        q = np.cumsum(расход / хватает[:, None], axis=0) * ds / запас[None, :] ** 0.5   # в «запасах кончика»
        K = int(q.max() * 3.2) + 4
        длины = np.exp(зажать(_БОР_ЗАПАС[2] * rng.standard_normal((K, n)), -1.0, 1.0))
        до = rng.uniform(_БОР_ЗАПАС[3], _БОР_ЗАПАС[4], (K, n))
        k, от_начала = _отрезки(q + длины[0] * rng.uniform(0.0, 1.0, n), длины)      # кончики встают на холст разными
        столбцы = np.arange(n)[None, :]
        t = зажать(от_начала / длины[k, столбцы], 0.0, 1.0)
        было = np.where(k > 0, до[np.maximum(k - 1, 0), столбцы], до[K - 1, столбцы])
        z = зажать(t / наполняется, 0.0, 1.0)
        растёт = было + (1.0 - было) * z * z * (3.0 - 2.0 * z)
        падает = 1.0 - (1.0 - до[k, столбцы]) * зажать((t - наполняется) / (1.0 - наполняется), 0.0, 1.0)
        return np.where(t < наполняется, растёт, падает)

    свой = волна(расход_в, 0.5 * (с.запас[:-1] + с.запас[1:]))
    прядь_в = с.прядь[:-1]
    расход_п = np.stack([расход_в[:, прядь_в == q].mean(axis=1) if (прядь_в == q).any() else np.zeros(N) for q in range(с.ns)], axis=1)
    общий = волна(расход_п, np.ones(с.ns))[:, прядь_в]
    return _БОР_ПРЯДЬ * общий + (1.0 - _БОР_ПРЯДЬ) * свой


def _проскок(с, расход_в, ds, живо, мелк, rng, на_гребне):
    """Проскок волоска (N, nv): 1 — волосок в воздухе, борозды под ним нет; и капля (N, nv), которую он оставляет.
    Цепляется волосок тем чаще, чем гуще краска и легче рука (прижатый волосок идёт ровнее); жёсткий — чаще мягкого.
    На гребне лежащей краски (`на_гребне`, N×nv, 0..1) волосок взлетает всегда.
    Каждый проскок свой (4б): волосок отходит от холста не разом — борозда мелеет и сужается на 0,6–2,2 px и так же
    возвращается, поэтому у срыва нет стенки поперёк хода (под косым светом стенки соседних борозд складывались
    в штриховку в одну сторону). Капля — то перед срывом (краска, что волосок нагнал, зацепившись), то за ним
    (сошла с волоска, когда он сел), то её нет; величина у каждой своя. `мелк` — мелкость зерна: у тонкой краски
    срыв короче и капля меньше."""
    N, nv = расход_в.shape
    частота = np.maximum(_БОР_ПРОСКОК[0] / 100.0 * живо ** _БОР_ПРОСКОК[1], 1e-6)                     # (N,) раз на px
    q = np.cumsum(частота[:, None] * (расход_в > 0.05) * зажать(с.давит, 0.6, 1.6)[None, :], axis=0) * ds
    K = int(q.max() * 2.5) + 4
    длины = np.exp(зажать(0.7 * rng.standard_normal((K, nv)), -1.5, 1.5) - 0.245)
    длины[0] *= rng.uniform(0.2, 1.0, nv)
    k, от_начала = _отрезки(q, длины)
    px = от_начала / частота[:, None]                                                 # px пути от начала отрезка
    столбцы = np.arange(nv)[None, :]

    def своё(от, до):
        return rng.uniform(от, до, (K, nv))[k, столбцы]

    длина = своё(_БОР_ПРОСКОК[2], _БОР_ПРОСКОК[3]) * мелк
    вверх = своё(_БОР_ПОДЪЁМ[0], _БОР_ПОДЪЁМ[1]) * мелк
    вниз = своё(_БОР_ПОДЪЁМ[0], _БОР_ПОДЪЁМ[1]) * мелк
    z = зажать(px / вверх, 0.0, 1.0) * зажать((длина + вниз - px) / вниз, 0.0, 1.0)
    # волосок отходит от холста не всегда целиком: чаще борозда только мелеет
    в_воздухе = (k > 0) * z * z * (3.0 - 2.0 * z) * своё(_БОР_ПОДЪЁМ[5], 1.0)
    # капля: у каждого проскока своя — перед срывом, за ним или никакой
    жребий = своё(0.0, 1.0)
    размер = своё(0.0, 1.0) ** 1.5 * 2.5 * мелк
    пятно = своё(_БОР_КАПЛЯ[0], _БОР_КАПЛЯ[1]) * мелк                                 # длина капли, px
    скат = _БОР_КАПЛЯ[2] * мелк                               # пологие скаты: комок, а не ступенька с тенью
    перед = зажать(px / скат, 0.0, 1.0) * зажать((пятно - px) / скат, 0.0, 1.0)
    за = зажать((px - длина - 0.5 * вниз) / скат, 0.0, 1.0) * зажать((длина + 0.5 * вниз + пятно - px) / скат, 0.0, 1.0)
    перед, за = перед * перед * (3.0 - 2.0 * перед), за * за * (3.0 - 2.0 * за)
    сел = (k > 0) * размер * np.where(жребий < _БОР_ПОДЪЁМ[2], перед, np.where(жребий < _БОР_ПОДЪЁМ[3], за, 0.0))
    if на_гребне is not None:
        # гребень лежащей краски поднимает волосок; он тянется в воздухе ещё пару px за гребнем
        хвост = max(int(round(_БОР_ГРЕБЕНЬ[1] / ds)), 1)
        тянет = на_гребне.copy()
        for i in range(1, хвост + 1):
            тянет[i:] = np.maximum(тянет[i:], на_гребне[:-i] * (1.0 - i / (хвост + 1.0)))
        в_воздухе = np.maximum(в_воздухе, тянет)
    return в_воздухе, сел * _БОР_ПРОСКОК[4]


def _слипание(с, к, живо, N, ds, W, rng):
    """Слипание соседних волосков (N, nr): 1 — два волоска по бокам гребня слиплись, гребень между ними просел.
    Слипаются волоски одной пряди, в густой краске при лёгкой руке; прижатая щетина расходится. Крайние гребни
    не трогаются."""
    порог = _БОР_СЛИП[0] + _БОР_СЛИП[1] * (1.0 - живо) + 0.6 * (1.0 - min(к.клочки / 0.6, 1.0))
    слип = зажать((_шум(rng, N, с.nr, _БОР_СЛИП[2] * W / ds) - порог[:, None]) / 0.3, 0.0, 1.0)
    внутри = np.zeros(с.nr)
    внутри[1:-1] = (с.прядь[1:-1] == с.прядь[:-2]) & (с.прядь[1:-1] == с.прядь[2:])
    слип = слип * внутри[None, :]
    слип[:, 1:] *= 1.0 - (слип[:, :-1] > слип[:, 1:])          # два соседних гребня разом не проседают
    return слип * слип * (3.0 - 2.0 * слип)


def борозды(с, к, путь, p, кас, густо, rng, X, Y, перепад):
    """Жизнь борозд одного мазка. кас — касание гребней (N, nr); X, Y — места выборок профиля в прямоугольнике
    мазка (N, nm); перепад — рельеф лежащей краски в толщинах плёнки (или None).
    Ответ: None (у кисти борозд нет) или (глубже, шире, капля, слип): первые три — (N, nv) по ведущим волоскам,
    слип — (N, nr) по гребням."""
    if с.вед is None or с.nr < 3:
        return None
    ds, N = путь['ds'], len(p)
    кас_в = np.minimum(кас[:, :-1], кас[:, 1:])                # волосок стоит между двумя гребнями
    расход_в = np.sqrt(зажать(p, 0.0, None) / 0.8)[:, None] * кас_в
    # живость: тонкая краска под прижатой кистью даёт ровную борозду с плавной переменой глубины;
    # густая под лёгкой рукой — рваную: комки, проскоки, слипшиеся волоски
    твёрдо = зажать((p - 0.3) / 0.55, 0.0, 1.0)
    живо = (_БОР_ЖИВО[0] + (1.0 - _БОР_ЖИВО[0]) * густо) * (1.0 - _БОР_ЖИВО[1] * твёрдо * (1.0 - _БОР_ЖИВО[2] * густо))
    вес = расход_в.sum(axis=1)
    живо_ср = float((живо * вес).sum() / max(вес.sum(), 1e-9))
    # мелкость зерна (4б): тонкая краска живёт так же, как густая, но мельче — на кончике её меньше, запас кончается
    # раньше, срыв короче, капля меньше
    мелк = _БОР_МЕЛКО + (1.0 - _БОР_МЕЛКО) * густо
    полнота = _запас_кончика(с, расход_в, ds, живо, живо_ср, мелк, rng)
    на_гребне = None
    if перепад is not None:
        nv = с.nr - 1
        m = np.array([int(np.argmin(np.where(с.вед == v, с.d_вед, np.inf))) for v in range(nv)])   # выборка у волоска
        ix, iy = np.floor(X[:, m]).astype(np.intp), np.floor(Y[:, m]).astype(np.intp)
        годные = (ix >= 0) & (ix < перепад.shape[1]) & (iy >= 0) & (iy < перепад.shape[0])
        выше = np.where(годные, перепад[np.where(годные, iy, 0), np.where(годные, ix, 0)], 0.0)
        на_гребне = зажать((выше - _БОР_ГРЕБЕНЬ[0]) / _БОР_ГРЕБЕНЬ[0], 0.0, 1.0) * живо[:, None] ** 0.5
    в_воздухе, капля = _проскок(с, расход_в, ds, живо, мелк, rng, на_гребне)
    слип = _слипание(с, к, живо, N, ds, с.W, rng)
    # глубина: под полным кончиком мелко, под пустым глубоко; жёсткий волосок пустым скребёт сильнее мягкого
    пусто = 1.0 - полнота
    мелкая = (_БОР_ГЛУБ[0] + (_БОР_ГЛУБ[1] - _БОР_ГЛУБ[0]) * живо)[:, None]
    глубокая = (_БОР_ГЛУБ[2] + (_БОР_ГЛУБ[3] - _БОР_ГЛУБ[2]) * живо)[:, None] * зажать(с.давит, 0.75, 1.25)[None, :]
    глубже = мелкая + (глубокая - мелкая) * пусто
    шире = _БОР_ШИРЕ[0] + ((_БОР_ШИРЕ[1] + (_БОР_ШИРЕ[2] - _БОР_ШИРЕ[1]) * живо)[:, None] - _БОР_ШИРЕ[0]) * пусто
    глубже = глубже * (1.0 - в_воздухе)
    шире = шире * (1.0 - _БОР_ПОДЪЁМ[4] * в_воздухе)            # отходя от холста, волосок касается его всё уже
    # крайние волоски живут по-старому: кромку следа ведут бок и край (`пряди.py`, `_край`), а не борозда
    for v in (0, -1):
        глубже[:, v], шире[:, v], капля[:, v] = 1.0, 1.0, 0.0
    return глубже, шире, капля, слип


def профиль_борозд(с, бор, мелко):
    """Поперечный профиль плёнки на каждом шаге пути (N, nm): 1 — гребень, меньше — борозда.
    мелко (N, 1) — лёгкая кисть борозду до дна не продавливает. Без `бор` — прежний ровный профиль."""
    if бор is None:
        return 1.0 - (1.0 - с.профиль[None, :]) * мелко
    глубже, шире, капля, слип = бор
    j = с.вед
    t = зажать(с.d_вед[None, :] / (с.полб[None, :] * шире)[:, j], 0.0, 1.0)
    стенка = 1.0 - t * t * (3.0 - 2.0 * t)                     # 1 — под кончиком волоска, 0 — на гребне
    глубина = зажать((1.0 - с.дно_в)[None, :] * глубже, 0.0, 1.0 - _БОР_ГЛУБ[4])[:, j]
    основа = 1.0 - глубина * стенка
    # слипшиеся волоски: гребень между ними проседает к дну их борозд
    просел = слип[:, с.гребень] * _БОР_СЛИП[3]
    основа = основа * (1.0 - просел) + np.minimum(основа, 1.0 - глубина) * просел
    профиль = 1.0 - (1.0 - основа * с.край_проф[None, :]) * мелко
    # капля шире борозды: комок ложится и на бока соседних гребней — точка, а не чёрточка в борозде
    t = зажать(с.d_вед[None, :] / (с.полб[None, :] * _БОР_ПОДЪЁМ[6])[:, j], 0.0, 1.0)
    return профиль + (капля[:, j] * (1.0 - t * t * (3.0 - 2.0 * t))) * с.край_проф[None, :]


def тон_борозды(с, бор, профиль, масса, видно, недомес, ds):
    """Борозда цветом (версия 3, пункты 5 и 5в): тон идёт за живой глубиной борозды (N, nm, 3), множитель к цвету
    гребня. Краска на кисти недомешана (`недомес` — `разброс_тона` кисти): плотная светлая её часть сходит с полного
    кончика, жидкая тёмная остаётся там, где волосок скребёт пустым. Тёмное — двух родов: место в два-три волоска,
    где кончики пусты (пятно длиной в запас кончика, а не лента во весь ход), и дно глубокой борозды (тонкая линия,
    что рвётся там, где кончик наполнился). `бор` — жизнь борозд (`борозды`), `профиль` (N, nm) — их поперечный
    профиль; `масса` и `видно` (N, nm) — что мазок кладёт и его покрытие: средний цвет каждого сечения мазка
    на глаз не меняется (тон не темнит тонкий конец мазка и тонкие плёнки целиком)."""
    if с.вед is None or бор is None or недомес <= 0.0:
        return None
    скребёт = бор[0]
    for _ in range(_БОР_ТОН_ВЕС[0]):
        q = обложить(скребёт, ((0, 0), (1, 1)), край=True)
        скребёт = 0.25 * q[:, :-2] + 0.5 * q[:, 1:-1] + 0.25 * q[:, 2:]
    # пятно не длиннее запаса кончика: медленная часть (волосок пустеет на всём ходу, период запаса) вычтена —
    # иначе под светом вдоль длинного мазка встаёт период (`test_нет_периода_вдоль_мазка`)
    L = int(_БОР_ТОН_ВЕС[2] / ds) | 1
    q = np.cumsum(обложить(скребёт, ((L // 2 + 1, L // 2), (0, 0)), край=True), axis=0)
    скребёт = скребёт - (q[L:] - q[:-L]) / L
    тёмное = _БОР_ТОН[0] * скребёт[:, с.вед] + _БОР_ТОН[1] * зажать(1.0 - профиль - _БОР_ТОН[2], 0.0, 1.0)
    вес = масса ** _БОР_ТОН_ВЕС[1] * видно ** (1.0 - _БОР_ТОН_ВЕС[1])
    среднее = (тёмное * вес).sum(axis=1, keepdims=True) / np.maximum(вес.sum(axis=1, keepdims=True), 1e-9)
    сдвиг = -недомес * зажать(тёмное - среднее, -_БОР_ТОН[3], _БОР_ТОН[3])
    return np.exp(сдвиг[:, :, None] * np.array(_БОР_ТОН[4])[None, None, :])
