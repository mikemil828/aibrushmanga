# ------------------------------------------------------- компактная строка (А-3)
class Ход(np.ndarray):
    """Точки ядра от `жест`, `путь_с_нажимом`, `тычок` — обычный массив, который помнит, из чего он построен: опорные
    точки, конец, нажим, вход, ширина, сид или состояние генератора. Журнал холста пишет тогда строку "ctrl" (опорные
    точки), а не сотни точек "core": повтор строит по ней те же точки бит в бит. Точки поправили (на месте или новым
    массивом) — память не годится, и журнал пишет "core", как раньше."""

    def __array_finalize__(self, obj):
        self.ход = None          # срез, копия и любая арифметика — уже другие точки

    def строка(self):
        """Поля строки журнала вместо "core" или None — точки уже не те, из которых строились."""
        ход = getattr(self, 'ход', None)
        if ход is None or _отпечаток(self) != ход[1]:
            return None
        return dict(ход[0])


def _отпечаток(a):
    a = np.ascontiguousarray(a, dtype=np.float64)
    return (a.shape, hashlib.blake2b(a.tobytes(), digest_size=16).digest())


def _генератор(rng, сид):
    """rng и сид вызова -> (генератор, поля строки журнала, по которым повтор возьмёт тот же). Сид — как у повтора по
    строке с "seed": `default_rng([сид, 7])`; генератор PCG64 — его состояние до вызова ("path_rng")."""
    if сид is not None:
        if rng is not None:
            raise ValueError('путь: rng или сид — что-то одно')
        return np.random.default_rng([int(сид), 7]), {'path_seed': int(сид)}
    if rng is None:
        return np.random.default_rng(0), {'path_rng': None}
    бг = getattr(rng, 'bit_generator', None)
    if isinstance(бг, np.random.PCG64):
        с = бг.state
        return rng, {'path_rng': [с['state']['state'], с['state']['inc'], с['has_uint32'], с['uinteger']]}
    return rng, None                 # другой генератор: строки "ctrl" не будет, журнал пишет "core"


def генератор_хода(поле):
    """Повтор: "path_rng" строки -> генератор PCG64 в том же состоянии (None — `default_rng(0)`, как без rng)."""
    if поле is None:
        return np.random.default_rng(0)
    г = np.random.Generator(np.random.PCG64())
    г.bit_generator.state = {'bit_generator': 'PCG64', 'state': {'state': int(поле[0]), 'inc': int(поле[1])},
                             'has_uint32': int(поле[2]), 'uinteger': int(поле[3])}
    return г


def _с_ходом(точки, поля):
    т = np.ascontiguousarray(точки, dtype=np.float64).view(Ход)
    т.ход = None if поля is None else (поля, _отпечаток(т))
    return т


# -------------------------------------------------------------------------- путь
def _эрмит(t, P, tt):
    n = len(t)
    m = np.empty_like(P)
    if n > 2:
        m[1:-1] = (P[2:] - P[:-2]) / (t[2:] - t[:-2])[:, None]
    m[0] = (P[1] - P[0]) / (t[1] - t[0])
    m[-1] = (P[-1] - P[-2]) / (t[-1] - t[-2])
    i = зажать(np.searchsorted(t, tt, side='right') - 1, 0, n - 2)
    h = (t[i + 1] - t[i])[:, None]
    s = ((tt - t[i]) / h[:, 0])[:, None]
    s2, s3 = s * s, s * s * s
    return ((2 * s3 - 3 * s2 + 1) * P[i] + (s3 - 2 * s2 + s) * h * m[i]
            + (-2 * s3 + 3 * s2) * P[i + 1] + (s3 - s2) * h * m[i + 1])


def _окно(a, полуширина):
    """Сглаживание окном Ханна, края держатся за крайние значения."""
    k = int(полуширина)
    if k < 1 or len(a) < 3:
        return a
    w = np.hanning(2 * k + 3)[1:-1]
    w /= w.sum()
    return np.convolve(обложить(a, k, край=True), w, mode='valid')


def _осевая(ctrl, шаг=2.0):
    """Опорные точки -> плотная ломаная по сплайну и длина дуги в её точках."""
    P = np.asarray(ctrl, dtype=np.float64)[:, :2]
    if len(P) > 1:
        P = P[np.concatenate([[True], np.hypot(*np.diff(P, axis=0).T) > 1e-6])]
    if len(P) == 1:
        return P, np.zeros(1)
    хорды = np.hypot(*np.diff(P, axis=0).T)
    t = np.concatenate([[0.0], np.cumsum(np.sqrt(хорды))])
    n = max(8, int(хорды.sum() / шаг) + 2)
    Q = _эрмит(t, P, np.linspace(0.0, t[-1], n))
    s = np.concatenate([[0.0], np.cumsum(np.hypot(*np.diff(Q, axis=0).T))])
    return Q, s


def _короткий(L, W, длина, своя, доля):
    """Вход или сход короткого хода («касание и короткий ход»). Длины входа и схода нажима взяты с длинного хода и на
    коротком съедали его весь (0,32 и 0,5 длины): нажим доходил до названного в одной точке, углы плоской кисти не
    вставали (`пряди._посадка`: вход длиннее «удара»), и ход в ширину кисти выходил в три четверти ширины, веретеном.
    Короткий ход рука кладёт иначе: ставит кисть, тянет и снимает. Ход не длиннее `_КОРОТКИЙ[1]` ширин — вход и сход
    по `доля` ширины кисти (`_КОРОТКИЙ[2]` и `[3]`); до `_КОРОТКИЙ[0]` ширин — плавно к прежним; от них и дальше —
    как было, бит в бит. `своя` — длину дал вызов (`вход=`, `сход=`): она остаётся."""
    W = float(W)
    if своя or W <= 0 or L >= _КОРОТКИЙ[0] * W:
        return длина
    к = min((_КОРОТКИЙ[0] - L / W) / (_КОРОТКИЙ[0] - _КОРОТКИЙ[1]), 1.0)
    return длина + (min(длина, доля * W) - длина) * к * к


def путь_с_нажимом(ctrl, размер, rng=None, нажим=0.85, скорость=1.0, вход=None, сход=None, сид=None):
    """По опорным точкам [[x, y], ...] — точки (x, y, нажим, dt_мс) с нажимом «вход — тело — сход».

    размер — ширина кисти, px: от неё берутся длины входа и схода, если они не заданы.
    Заданные вход и сход берутся как есть (короткий сход — быстрый отрыв).
    сид (А-3) — вместо rng: те же точки, что повтор строит по строке {"ctrl", "size", "seed": сид}. С сидом или с
    генератором numpy (`default_rng`) журнал холста пишет мазок строкой "ctrl" (опорные точки), а не точками ядра."""
    rng, поля = _генератор(rng, сид)
    поля = _поля_хода(ctrl, размер, нажим, вход, None, поля) if скорость == 1.0 and сход is None else None
    return _с_ходом(_путь_с_нажимом(ctrl, размер, rng, нажим, скорость, вход, сход), поля)


def _поля_хода(ctrl, размер, нажим, вход, конец, поля):
    """Поля строки "ctrl" — те, по которым повтор зовёт `жест` / `путь_с_нажимом` (`кисть/повтор.py`)."""
    if поля is None:
        return None
    P = np.asarray(ctrl, dtype=np.float64)
    if P.ndim != 2 or P.shape[1] < 2 or not (np.hypot(*np.diff(P[:, :2], axis=0).T) > 1e-6).any():
        return None                  # на месте: повтор кладёт по одной точке тычок (`тычок`), не этот путь
    д = {'ctrl': P[:, :2].tolist(), 'size': float(размер)}
    if конец is not None:
        д['end'] = конец
    if float(нажим) != 0.85:
        д['pressure'] = float(нажим)
    if вход is not None:
        д['entry'] = float(вход)
    д.update(поля)
    return д


def _путь_с_нажимом(ctrl, размер, rng, нажим=0.85, скорость=1.0, вход=None, сход=None):
    Q, s = _осевая(ctrl)
    if len(Q) == 1:
        return np.array([[Q[0, 0], Q[0, 1], нажим, 30.0]])
    L = s[-1]
    вх = max((0.5 + 1.2 * rng.random()) * размер, 6.0) if вход is None else float(вход)
    сх = max((1.4 + 1.8 * rng.random()) * размер, 14.0) if сход is None else float(сход)
    вх = _короткий(L, размер, min(вх, 0.32 * L), вход is not None, _КОРОТКИЙ[2])
    сх = _короткий(L, размер, min(сх, 0.5 * L), сход is not None, _КОРОТКИЙ[3])
    a = зажать(s / max(вх, 1e-6), 0.0, 1.0)
    b = зажать((L - s) / max(сх, 1e-6), 0.0, 1.0)
    a = a * a * (3 - 2 * a)
    b = b ** 1.2
    тело = 1.0 + 0.07 * np.sin(s / max(L, 1.0) * (2.0 + 3.0 * rng.random()) + 6.28 * rng.random())
    p = зажать(нажим * a * b * тело, 0.0, 1.0)
    v = скорость * (0.55 + 0.45 * np.minimum(a, b))          # на входе и сходе рука медленнее
    dt = np.concatenate([[0.0], np.diff(s) / v[1:]])
    return np.column_stack([Q[:, 0], Q[:, 1], p, dt])


ЖЕСТЫ = ('подъём', 'отрыв', 'остановка', 'смахивание')


def жест(ctrl, размер, вид='подъём', rng=None, нажим=0.85, скорость=1.0, вход=None, сид=None):
    """Точки мазка с одним из четырёх концов. Конец задаётся жестом руки, а не формой следа:

    'подъём'      — кисть медленно поднимают на ходу: нажим сходит на двух-четырёх ширинах;
    'отрыв'       — кисть срывают: нажим падает на четверти ширины, рука ускоряется;
    'остановка'   — кисть останавливают, придавливают и поднимают на месте;
    'смахивание'  — конец уводят вбок дугой, ускоряясь и отпуская.
    сид (А-3) — вместо rng: те же точки, что повтор строит по строке {"ctrl", "size", "end": вид, "seed": сид}. С сидом
    или с генератором numpy журнал холста пишет мазок строкой "ctrl", а не точками ядра."""
    if вид not in ЖЕСТЫ:
        raise ValueError(f'жест: один из {ЖЕСТЫ}')
    rng, поля = _генератор(rng, сид)
    поля = _поля_хода(ctrl, размер, нажим, вход, вид, поля) if скорость == 1.0 else None
    return _с_ходом(_жест(ctrl, размер, вид, rng, нажим, скорость, вход), поля)


def _жест(ctrl, размер, вид, rng, нажим=0.85, скорость=1.0, вход=None):
    W = float(размер)
    if вид == 'смахивание':
        P = np.asarray(ctrl, dtype=np.float64)[:, :2]
        д = P[-1] - P[-2]
        д /= max(np.hypot(*д), 1e-9)
        бок = np.array([-д[1], д[0]]) * (1.0 if rng.random() < 0.5 else -1.0)
        r = (0.9 + 0.6 * rng.random()) * W
        ctrl = np.vstack([P, P[-1] + д * 0.75 * r + бок * 0.3 * r, P[-1] + д * 1.05 * r + бок * 1.05 * r])
    Q, s = _осевая(ctrl, шаг=1.0)
    L = s[-1]
    вх = max((0.5 + 1.2 * rng.random()) * W, 6.0) if вход is None else float(вход)
    a = зажать(s / max(_короткий(L, W, min(вх, 0.32 * L), вход is not None, _КОРОТКИЙ[2]), 1e-6), 0.0, 1.0)
    a = a * a * (3 - 2 * a)
    тело = 1.0 + 0.07 * np.sin(s / max(L, 1.0) * (2.0 + 3.0 * rng.random()) + 6.28 * rng.random())
    d = L - s                                               # до конца пути
    v = np.full(len(s), float(скорость))
    if вид == 'подъём':
        сх = _короткий(L, W, min((2.0 + 2.0 * rng.random()) * W, 0.5 * L), False, _КОРОТКИЙ[3])
        b = зажать(d / сх, 0.0, 1.0) ** 1.2
        v *= 0.6 + 0.4 * зажать(d / сх, 0, 1)
    elif вид == 'отрыв':
        сх = max(0.25 * W, 3.0)
        b = зажать(d / сх, 0.0, 1.0)
        v *= 1.0 + 1.5 * (1.0 - зажать(d / (1.5 * W), 0, 1))
    elif вид == 'остановка':
        тормоз = min(0.6 * W, 0.4 * L)
        b = зажать(d / 2.0, 0.0, 1.0)                      # подъём на последних двух пикселях
        придавил = 1.0 + 0.3 * (1.0 - зажать(d / тормоз, 0, 1)) ** 2
        b = b * придавил
        v *= 0.06 + 0.94 * зажать(d / тормоз, 0, 1) ** 1.5
    else:
        сх = min(1.6 * r, 0.5 * L)
        b = зажать(d / сх, 0.0, 1.0) ** 1.1
        v *= 1.0 + 2.0 * (1.0 - зажать(d / сх, 0, 1))
    p = зажать(нажим * a * b * тело, 0.0, 1.0)
    dt = np.concatenate([[0.0], np.diff(s) / v[1:]])
    return np.column_stack([Q[:, 0], Q[:, 1], p, dt])


def профиль_нажима(профиль, где='pressure_along'):
    """Проверить профиль нажима по ходу — [[доля пути, множитель], …]: доли 0–1 строго по возрастанию, множители
    не меньше 0. Ответ — массив (n, 2) или None (профиля нет). Кривой — ValueError с `где` в начале."""
    if профиль is None:
        return None
    try:
        п = np.asarray(профиль, dtype=np.float64)
    except (TypeError, ValueError):
        п = None
    if п is None or п.ndim != 2 or п.shape[1] != 2 or len(п) < 1 or not np.isfinite(п).all():
        raise ValueError(f'{где}: должен быть списком пар [доля пути, множитель]')
    if (п[:, 0] < 0).any() or (п[:, 0] > 1).any():
        raise ValueError(f'{где}: доля пути вне 0–1')
    if (np.diff(п[:, 0]) <= 0).any():
        raise ValueError(f'{где}: доли пути не по возрастанию')
    if (п[:, 1] < 0).any():
        raise ValueError(f'{где}: множитель нажима меньше 0')
    return п


def нажим_вдоль(точки, профиль):
    """Нажим по ходу (п. 11д, поле журнала "pressure_along"): нажим точек мазка (x, y, нажим, …) множится на профиль
    [(доля пути, множитель), …] по доле пройденного пути (длина ломаной точек), между узлами по прямой (np.interp).
    Счёт тот же, что у анализатора (`подбор.вдоль`). Профиля нет, у точек нет нажима или точек меньше двух — точки
    как были (тот же объект). Профиль проверяется (`профиль_нажима`)."""
    п = профиль_нажима(профиль)
    т = np.array(точки, np.float64)
    if п is None or т.ndim != 2 or т.shape[1] < 3 or len(т) < 2:
        return точки
    s = np.concatenate([[0.0], np.cumsum(np.hypot(*np.diff(т[:, :2], axis=0).T))])
    т[:, 2] *= np.interp(s / max(s[-1], 1e-9), п[:, 0], п[:, 1])
    return т


def участки_касания(точки, профиль):
    """Отрыв по ходу (п. 11ж, поле журнала "pressure_along"): где множитель профиля 0 — кисть над холстом.
    Ответ — список кусков точек (x, y, нажим, dt_мс, …): каждый от отрыва до отрыва, нажим на концах куска,
    стоящих у нуля профиля, — 0, время на месте отрыва — по ходу руки. Нулей в профиле нет (или точек меньше двух) —
    None: мазок один, как был. Точки — уже с профилем (`нажим_вдоль`); места нулей берутся из самого профиля,
    а не из точек: ноль на одном узле, между точками пути, отрывает тоже."""
    п = профиль_нажима(профиль)
    т = np.asarray(точки, np.float64)
    if п is None or т.ndim != 2 or т.shape[1] < 3 or len(т) < 2 or not (п[:, 1] == 0).any():
        return None
    # нулевые участки профиля по доле пути: [a, b] (a == b — ноль на одном узле); за крайними узлами — их множитель
    нули = []
    i = 0
    while i < len(п):
        if п[i, 1] == 0:
            j = i
            while j + 1 < len(п) and п[j + 1, 1] == 0:
                j += 1
            a = 0.0 if i == 0 else п[i, 0]
            b = 1.0 if j == len(п) - 1 else п[j, 0]
            нули.append((a, b))
            i = j + 1
        else:
            i += 1
    s = np.concatenate([[0.0], np.cumsum(np.hypot(*np.diff(т[:, :2], axis=0).T))])
    д = s / max(s[-1], 1e-9)
    время = np.cumsum(т[:, 3]) if т.shape[1] >= 4 else None
    куски = []
    начало = 0.0
    for a, b in [*нули, (1.0, 1.0)]:
        if a > начало:
            внутри = (д > начало) & (д < a)
            def точка(доля):
                return np.array([np.interp(доля, д, т[:, k]) for k in range(т.shape[1])])
            кусок = np.vstack([точка(начало), т[внутри], точка(a)])
            if начало > 0:
                кусок[0, 2] = 0.0                    # кисть входит заново от нуля
            if a < 1.0:
                кусок[-1, 2] = 0.0                   # и уходит в ноль у отрыва
            if время is not None:
                т_куска = np.interp(np.concatenate([[начало], д[внутри], [a]]), д, время)
                кусок[:, 3] = np.concatenate([[т[0, 3] if начало == 0 else 0.0], np.diff(т_куска)])
            if (кусок[:, 2] > 0).any():
                куски.append(кусок)
        начало = max(начало, b)
    return куски


def тычок(x, y, нажим=0.85, угол=None, мс=30.0):
    """Тычок — касание на месте (З-10): точки ядра одной точки, те же, что повтор кладёт по строке
    `{"ctrl": [[x, y]], "pressure": нажим, "angle": угол}`. угол — направление кисти, градусы от оси x (y вниз), широкая
    сторона плоской кисти поперёк него; None — кисть стоит как стоит (то же, что `[(x, y, нажим, мс)]`). Без нажима и
    угла тычок — просто `[(x, y)]`, как `{"ctrl": [[x, y]]}` и `{"points": [[x, y]]}`: нажим строит ядро."""
    поля = None
    if float(мс) == 30.0:            # журнал: строка {"ctrl": [[x, y]], "pressure", "angle"} — повтор кладёт этот тычок
        поля = {'ctrl': [[float(x), float(y)]]}
        if float(нажим) != 0.85:
            поля['pressure'] = float(нажим)
        if угол is not None:
            поля['angle'] = float(угол)
    if угол is None:
        return _с_ходом([[float(x), float(y), float(нажим), float(мс)]], поля)
    у = float(угол)
    return _с_ходом([[float(x), float(y), float(нажим), float(мс), 0.0, np.radians(у), у + 90.0]], поля)


def ломаная(точки, шаг=0.5):
    """К2, сырые точки руки: путь как есть. Точки (x, y, нажим[, dt_мс, наклон °, азимут рад, поворот °]) — те же, но
    каждый отрезок длиннее `шаг` px разбит на равные части не длиннее его: нажим и углы — по прямой между точками
    (азимут и поворот — кратчайшей дугой, как их читает ядро), время отрезка делится поровну. Ядро (`_путь`) ведёт
    сплайн по своим точкам; по точкам через полпикселя он идёт по самой ломаной, и угол руки остаётся углом, а не
    дугой. Точки и так не реже шага (и одна точка) — те же (тот же объект). Точка, повторённая на месте, остаётся:
    стояние кисти. Входа и схода нажима здесь нет: какие дала рука."""
    т = np.asarray(точки, dtype=np.float64)
    if т.ndim != 2 or т.shape[1] < 3 or len(т) == 0:
        raise ValueError('ломаная: нужен список точек (x, y, нажим, ...)')
    if not np.isfinite(т).all():
        raise ValueError('ломаная: есть нечисла')
    if len(т) == 1:
        return точки
    хорды = np.hypot(*np.diff(т[:, :2], axis=0).T)
    m = np.maximum(np.ceil(хорды / float(шаг) - 1e-9), 1.0)
    if (m == 1).all():
        return точки
    if m.sum() > 4_000_000:
        raise ValueError('ломаная: путь длиннее 2 млн px')
    m = m.astype(np.int64)
    т = т.copy()
    if т.shape[1] >= 6:
        т[:, 5] = np.unwrap(т[:, 5])
    if т.shape[1] >= 7:
        т[:, 6] = np.degrees(np.unwrap(np.radians(т[:, 6])))
    нач = np.concatenate([[0], np.cumsum(m)])
    i = np.repeat(np.arange(len(m)), m)                       # отрезок новой точки
    j = np.arange(нач[-1]) - нач[i] + 1                       # её номер в отрезке, 1…m
    нов = т[i] + (т[i + 1] - т[i]) * (j / m[i])[:, None]
    нов[j == m[i]] = т[1:]                                    # точки руки — сами, без округления
    if т.shape[1] >= 4:
        нов[:, 3] = т[i + 1, 3] / m[i]
    return np.vstack([т[:1], нов])


def _отпечаток_пучка(точка, к, вдоль):
    """Путь тычка: кисть, поставленная на месте, оставляет отпечаток пучка — кончики проходят его длину по ходу кисти.
    Плоская (и мягкая, и узкая): пучок встаёт всей кромкой разом и разом уходит — нажим на всей длине отпечатка тот,
    что дала рука (вход короче `пряди._посадка` «удара»: углы обоймы встают сразу); длина — толщина пучка и расход
    кончиков под нажимом (`_ТЫЧОК[0]`, `_ТЫЧОК_РАСХОД`). Круглая: пятно касания растёт от кончика к брюшку, пока кисть
    давят, — по ходу отпечатка нажим идёт так, что гребень на расстоянии r от оси (порог касания `_А_НАЖИМ`·r^1,15,
    `укладка.положить_мазок`) касается на своей хорде круга (показатели — `_ТЫЧОК_КРУГ`, по картинке); длина — ширина следа при этом нажиме
    (`укладка._расп`: распластывание кисти). Ответ — точки ядра (n, столбцов как у точки), нажим на концах 0."""
    W, нажим = float(к.ширина), float(зажать(точка[2], 0.0, 1.0))
    остр = float(зажать((_ОСТРАЯ[0] - W) / _ОСТРАЯ[1], 0.0, 1.0)) * float(getattr(к, 'остриё', 1.0))   # как `укладка._острая`: узкая кисть с острым кончиком
    if к.форма == 'круглая':
        распл = float(getattr(к, 'распластывание', 0.4))
        шире = распл + (1.0 - распл) * (нажим / 0.85) ** 0.6 * (1.0 + 0.9 * float(зажать(нажим - 0.85, 0.0, 0.15)))
        # касание-2: у узкой кисти с острым кончиком порог крайних гребней ниже (`укладка._остриё`, `_ОСТРАЯ[5]`) — нажим по
        # хорде считается от него же, иначе все гребни вставали на всей длине отпечатка и пятно выходило бруском
        А = _А_НАЖИМ * (1.0 - _ОСТРАЯ[5] * остр)
        достаёт = min(max((нажим - 0.04) / А, 0.0) ** (1.0 / 1.15), 1.0)
        длина = max(_ТЫЧОК_КРУГ[0] * достаёт * шире * W, 1.6)
    else:
        # + 1 px: нажим встаёт и уходит на крайних полпикселя пути. Касание-2: у узкой кисти с острым кончиком —
        # короче на `_ТЫЧОК_ОСТР` px: её ворс собран, кончики встают разом (с целым пикселем отпечаток узкой плоской
        # 12 px выходил квадратом 9 × 10 px, и угол тычка по пятну не читался; без него — короче 0,6 ширины, К8.2)
        длина = max((_ТЫЧОК[0] + _ТЫЧОК_РАСХОД * нажим) * W + 1.0 - _ТЫЧОК_ОСТР * остр, 1.6)
    n = max(int(np.ceil(длина / _ШАГ_ПУТИ)) + 1, 5)
    доля = np.linspace(-1.0, 1.0, n)
    if к.форма == 'круглая':
        хорда = np.sqrt(np.maximum(1.0 - доля * доля, 0.0))
        p = 0.04 * (хорда > 0) + (min(нажим, 0.04 + А) - 0.04) * хорда ** _ТЫЧОК_КРУГ[1] \
            + max(нажим - 0.04 - А, 0.0) * хорда ** _ТЫЧОК_КРУГ[2]
        p = np.minimum(p, нажим)
    else:
        p = np.full(n, нажим)
    p[0] = p[-1] = 0.0
    т = np.repeat(np.asarray(точка, dtype=np.float64)[None, :], n, axis=0)
    т[:, :2] += 0.5 * длина * доля[:, None] * вдоль[None, :]
    т[:, 2] = p
    т[:, 3] = 30.0 / n
    return т


def _путь(точки, к, rng):
    т = np.asarray(точки, dtype=np.float64)
    if т.ndim != 2 or т.shape[1] < 2 or len(т) == 0:
        raise ValueError('точки мазка: нужен список (x, y, нажим, dt_мс, ...)')
    if not np.isfinite(т).all():
        raise ValueError('точки мазка: есть нечисла')
    if т.shape[1] == 2:
        т = _путь_с_нажимом(т, к.ширина, rng)
    if т.shape[1] == 3:
        т = np.column_stack([т, np.zeros(len(т))])
    шаги = np.hypot(np.diff(т[:, 0]), np.diff(т[:, 1]))
    # стояние на месте: время повторной точки уходит следующему шагу, нажим берётся наибольший
    держать = np.concatenate([[True], шаги > 1e-6])
    if not держать.all():
        т = т.copy()
        номер = np.cumsum(держать) - 1
        время = np.bincount(номер, weights=т[:, 3])
        нажимы = np.zeros(номер[-1] + 1)
        np.maximum.at(нажимы, номер, т[:, 2])
        т = т[держать]
        т[:, 3] = время
        т[:, 2] = нажимы
    есть_поворот = т.shape[1] >= 7
    на_месте = len(т) == 1
    if на_месте:
        # касание на месте — отпечаток пучка: ряд кончиков проходит его длину по ходу кисти (п. 10, К8.2), у кисти любой
        # ширины («касание и короткий ход»: шире 16 px отпечаток сходил на нет, и круглая 22 px ставила штрих 21×7 px)
        угол = np.radians(т[0, 6]) - np.pi / 2 if есть_поворот else rng.uniform(0, 2 * np.pi)
        т = _отпечаток_пучка(т[0], к, np.array([np.cos(угол), np.sin(угол)]))
    P = т[:, :2]
    хорды = np.hypot(*np.diff(P, axis=0).T)
    t = np.concatenate([[0.0], np.cumsum(np.sqrt(хорды))])
    n = max(16, int(хорды.sum() * 4.0) + 1)
    tt = np.linspace(0.0, t[-1], n)
    Q = _эрмит(t, P, tt)
    S = np.concatenate([[0.0], np.cumsum(np.hypot(*np.diff(Q, axis=0).T))])
    L = float(S[-1])
    N = max(3, int(np.ceil(L / _ШАГ_ПУТИ - 1e-6)) + 1)       # 1e-6: длина ровно в шаг не должна зависеть от округления
    N += (-(N - 1)) % _ШК                                    # число шагов кратно шагу переноса
    s = np.linspace(0.0, L, N)
    ds = L / (N - 1)
    x = np.interp(s, S, Q[:, 0])
    y = np.interp(s, S, Q[:, 1])
    S_узлы = np.interp(t, tt, S)
    p = зажать(_окно(np.interp(s, S_узлы, т[:, 2]), int(1.0 / ds)), 0.0, 1.0)
    время = np.cumsum(np.concatenate([[0.0], np.maximum(т[1:, 3], 0.0)]))
    if время[-1] > 0:
        dtds = np.gradient(np.interp(s, S_узлы, время), ds)
        скор = _окно(1.0 / np.maximum(dtds, 0.02), int(3.0 / ds))
    else:
        скор = np.ones(N)
    скор = зажать(скор, 0.02, 50.0)
    dx = _окно(np.gradient(x, ds), int(1.5 / ds))
    dy = _окно(np.gradient(y, ds), int(1.5 / ds))
    ход = np.unwrap(np.arctan2(dy, dx))
    наклон = np.interp(s, S_узлы, т[:, 4]) if т.shape[1] >= 5 else np.zeros(N)
    азимут = np.interp(s, S_узлы, np.unwrap(т[:, 5])) if т.shape[1] >= 6 else None
    if есть_поворот:
        угол = np.interp(s, S_узлы, np.unwrap(np.radians(т[:, 6]))) - np.pi / 2
        if np.cos(угол[0] - ход[0]) < 0:
            угол = угол + np.pi
    elif к.форма == 'круглая':
        угол = ход
    else:
        # плоская кисть доворачивается за ходом с отставанием
        лямбда = max(к.отставание * к.ширина, 1e-3)
        доля = 1.0 - np.exp(-ds / лямбда)
        ход_сп = ход.tolist()
        у = ход_сп[min(len(ход_сп) - 1, int(2.0 / ds))]
        угол = []
        for ф in ход_сп:
            у += (ф - у) * доля
            угол.append(у)
        угол = np.array(угол)
    return dict(x=x, y=y, p=p, скор=скор, угол=угол, ход=ход, наклон=наклон, азимут=азимут,
                ds=ds, L=L, s=s, N=N, на_месте=на_месте)
