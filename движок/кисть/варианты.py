ФОРМАТ = 2                  # вариант.pkl — pickle словаря, сжатый zlib; 2 (М-8-2) — отпечаток по области


def _хеш(a):
    a = np.ascontiguousarray(np.asarray(a))
    return hashlib.sha256(f'{a.dtype.str}{a.shape}'.encode() + a.tobytes()).hexdigest()[:20]


def _json(v):
    return json.loads(json.dumps(v, ensure_ascii=False, default=str))


def отпечаток(х, область=None):
    """М-8: отпечаток холста — то, от чего зависят мазки куска и что `сохранить` кладёт в `.npz`: размер, грунт,
    масштаб, зерно, сид, счётчик мазков, этап и объект пометки, повторы сидов, слои по порядку и хеш каждого их поля.
    М-8-2: с `область` (x0, y0, x1, y1) поля слоёв хешируются только в ней — кусок вне области не читает и не пишет
    (рамки сверены до счёта), `взять` кладёт только её; вне области от слоя берётся одно — есть ли там сырое (ответ
    участка мягкой кисти, `Холст.участок`). Без `область` — поля целиком. Тот же холст после `сохранить` и
    `загрузить` — тот же отпечаток. Словарь (JSON)."""
    from .холст import Слой
    х.досчитать()
    повторы = sorted((х._повторы or {}).items())
    if область is None:
        слои = [[имя, {п: (None if getattr(с, п) is None else _хеш(getattr(с, п))) for п in Слой._ВСЕ}]
                for имя, с in х.слои.items()]
    else:
        у = х.участок(область)          # срезы плиток той же сетки — память и время только области
        слои = [[имя, dict({п: (None if getattr(с, п) is None else _хеш(getattr(с, п))) for п in Слой._ВСЕ},
                           сыро_вне=bool(getattr(с, '_сыро', False)))]
                for имя, с in у.слои.items()]
    return _json({'размер': [х.полная_ширина, х.полная_высота], 'грунт': list(х.грунт_srgb), 'px_на_мм': х.px_на_мм,
                  'зерно': None if х.зерно is None else list(х.зерно), 'сид': х.сид, 'счётчик': х._счётчик,
                  'этап': х._этап, 'объект': х._объект,
                  'повторы': _хеш(np.array(повторы, np.uint64).reshape(-1, 2)), 'область': область and list(область),
                  'слои': слои})


_СЛОВА = {'размер': 'размер холста', 'грунт': 'грунт', 'px_на_мм': 'px_на_мм', 'зерно': 'зерно', 'сид': 'сид листа',
          'счётчик': 'счётчик мазков', 'этап': 'этап пометки', 'объект': 'объект пометки', 'повторы': 'повторы сидов'}


def _разница(был, есть):
    """Что не так словами: у вариантов … — у холста …"""
    р = []
    for к, слово in _СЛОВА.items():
        if был.get(к) != есть.get(к):
            р.append(f'{слово}: у вариантов {был.get(к)!r}, у холста {есть.get(к)!r}' if к != 'повторы' else слово + ' иные')
    сб, се = dict((и, п) for и, п in был['слои']), dict((и, п) for и, п in есть['слои'])
    if list(сб) != list(се):
        р.append(f'слои: у вариантов {list(сб)}, у холста {list(се)}')
    for имя in сб:
        if имя in се and сб[имя] != се[имя]:
            р.append(f'слой «{имя}»: иные поля ' + ', '.join('сырое вне области' if п == 'сыро_вне' else п
                                                           for п in сб[имя] if сб[имя][п] != се[имя].get(п)))
    return р


def _писать_атомно(путь, байты):
    with open(путь + '.часть', 'wb') as f:
        f.write(байты)
    os.replace(путь + '.часть', путь)


def _png(путь, a8):
    from PIL import Image
    Image.fromarray(a8).save(путь + '.часть.png')
    os.replace(путь + '.часть.png', путь)


def _кратко(v, n=40):
    т = repr(v)
    return т if len(т) <= n else т[:n - 1] + '…'


def _на_диск(х, вв, в_папку):
    """М-8: варианты — в `<папка>/<i>/`, лист `рядом.png` и `варианты.json` — в папку."""
    from .глаз import _в_8, _лист, взгляд
    from .краска import из_линейного
    папка = os.path.abspath(os.path.expanduser(os.fspath(в_папку)))
    os.makedirs(папка, exist_ok=True)
    for имя in os.listdir(папка):           # прежние варианты этой папки с номером ≥ n — убрать: лист и номера — одного вызова
        if имя.isdigit() and int(имя) >= len(вв) and os.path.isfile(os.path.join(папка, имя, 'вариант.pkl')):
            shutil.rmtree(os.path.join(папка, имя))
    отп = отпечаток(х, вв[0].область)
    ж = getattr(х, 'журнал', None)
    журнал_до = None if ж is None else _json({'кистей': ж.номер, 'этап': ж.этап, 'объект': ж.объект})
    пустые_до = dict(getattr(х, '_пустые', {}))
    панели, подписи = [взгляд(х, вв[0].область)], ['холст сейчас']
    for в in вв:
        куда = os.path.join(папка, str(в.номер))
        os.makedirs(куда, exist_ok=True)
        строки = pickle.loads(в._данные)['журнал']
        _писать_атомно(os.path.join(куда, 'вариант.pkl'), zlib.compress(pickle.dumps(
            {'формат': ФОРМАТ, 'номер': в.номер, 'область': в.область, 'картинка': в.картинка,
             'ответ': pickle.dumps(в.ответ, 5), 'слова': в.слова, 'однообразие': в.однообразие, 'данные': в._данные,
             'отпечаток': отп, 'журнал_до': журнал_до, 'пустые_до': пустые_до}, 5), 3))
        a8 = _в_8(np.clip(из_линейного(в.картинка) * 255.0, 0.0, 255.0))
        _png(os.path.join(куда, 'картинка.png'), a8)
        ж_файл = os.path.join(куда, 'журнал.jsonl')
        if строки is not None:
            _писать_атомно(ж_файл, строки['байты'])
        elif os.path.exists(ж_файл):
            os.remove(ж_файл)
        о = в.однообразие
        _писать_атомно(os.path.join(куда, 'вариант.json'), json.dumps(_json(
            {'номер': в.номер, 'область': list(в.область), 'ответ': в.ответ, 'слова': [т for _, т in в.слова],
             'однообразие': None if о is None else round(float(о.оценка), 3),
             'строк_журнала': None if строки is None else строки['байты'].count(b'\n'),
             'взять': f"х = Холст.загрузить(<тот же .npz>, журнал=<тот же журнал>); х.взять({куда!r})"}),
            ensure_ascii=False, indent=1).encode('utf-8'))
        в.папка = куда
        панели.append(a8)
        подписи.append(f'{в.номер}' + ('' if в.ответ is None else ': ' + _кратко(в.ответ)))
    _лист(панели, подписи, os.path.join(папка, 'рядом.png'))
    _писать_атомно(os.path.join(папка, 'варианты.json'), json.dumps(_json(
        {'n': len(вв), 'область': list(вв[0].область), 'рядом': 'рядом.png', 'журнал_до': журнал_до, 'отпечаток': отп}),
        ensure_ascii=False, indent=1).encode('utf-8'))


def _с_диска(байты, что, файл, своя):
    """С-1: pickle из файла варианта. Чужая папка (своя=False) — чтецом `распаковка`: только то, что движок сам пишет
    в вариант; иное имя или вызов в файле — ValueError до того, как оно выполнено. своя=True — обычный pickle (он
    выполняет то, что названо в файле): только для папки, что считал сам."""
    if своя:
        return pickle.loads(байты)
    try:
        return распаковка.прочесть(байты)
    except распаковка.Чужое as e:
        raise ValueError(
            f'взять: {файл} — {что}: {e}; такого движок в вариант не пишет, файл не прочитан: обычное чтение pickle '
            'выполнило бы код из файла. Папку считал сам (кусок вернул объект своего класса или положил его в кисть) — '
            'х.взять(путь, своя=True); папка чужая (прислана, скачана, из архива) — не брать, посчитать варианты у себя'
        ) from None


def прочесть(путь, своя=False):
    """М-8: вариант с диска (`<папка>/<i>` от `варианты(…, в_папку=)`) — `Вариант` с картинкой, ответом, словами и
    однообразием, как в том процессе; положить — `х.взять(путь)` или `х.взять(прочесть(путь))`.
    С-1: файл читается без выполнения кода из него — папку можно брать и чужую; в файле что-то кроме данных движка
    (числа, строки, массивы, словари, кисти, краски, ответы мазков) — ValueError, какое имя. своя=True — читать обычным
    pickle: для своей папки, где кусок вернул объект своего класса; чужой папке так не верить."""
    куда = os.path.abspath(os.path.expanduser(os.fspath(путь)))
    файл = os.path.join(куда, 'вариант.pkl') if os.path.isdir(куда) else куда
    if not os.path.isfile(файл):
        raise FileNotFoundError(f'взять: варианта нет — {файл} не найден (папка — `<в_папку>/<номер>`, как у '
                                'варианты(…, в_папку=))')
    with open(файл, 'rb') as f:
        try:
            з = _с_диска(zlib.decompress(f.read()), 'в файле', файл, своя)
        except (zlib.error, pickle.UnpicklingError, EOFError):
            з = None
    if not isinstance(з, dict) or з.get('формат') != ФОРМАТ:
        raise ValueError(f'взять: {файл} — не вариант этого движка (формат {з.get("формат") if isinstance(з, dict) else "?"}, '
                         f'нужен {ФОРМАТ}); посчитать варианты заново')
    в = Вариант()
    try:
        в.номер, в.область, в.картинка, в.слова = з['номер'], tuple(з['область']), з['картинка'], з['слова']
        в.ответ, в.однообразие, в.папка = _с_диска(з['ответ'], 'в ответе куска', файл, своя), з['однообразие'], os.path.dirname(файл)
        в._данные, в._группа = з['данные'], None
        в._диск = {'отпечаток': з['отпечаток'], 'журнал_до': з['журнал_до'], 'пустые_до': з['пустые_до'],
                   'своя': bool(своя), 'файл': файл}
        if not isinstance(в._данные, bytes):
            raise TypeError('данные')
    except (KeyError, TypeError, pickle.UnpicklingError, EOFError) as e:
        raise ValueError(f'взять: {файл} — файл варианта не цел ({type(e).__name__}: {e}); посчитать варианты заново') from None
    return в


def _в_холст(х, в, д):
    """Поля слоёв области и счётчик сидов варианта — в холст (`вписать`)."""
    from .холст import Холст, Слой
    у = Холст.__new__(Холст)
    x0, y0, x1, y1 = в.область
    у.x0, у.y0, у.ширина, у.высота = x0, y0, x1 - x0, y1 - y0
    у._слои = {}
    for имя, поля in д['слои'].items():
        с = Слой.__new__(Слой)
        for п, з in поля.items():
            if з is not None or п in Слой._ПОЛЯ:
                setattr(с, п, _внутрь(з))
        у._слои[имя] = с
    у._счётчик, у._повторы, у._этап, у._объект = д['счётчик'], д['повторы'], д['этап'], д['объект']
    у._вне_журнала = False
    х.вписать(у)


def _сказать(в):
    from .холст import ПустойМазок
    for вид, текст in в.слова:
        warnings.warn(ПустойМазок(текст) if вид == 'ПустойМазок' else UserWarning(текст), stacklevel=4)


def _взять_с_диска(х, в):
    з = в._диск
    разн = _разница(з['отпечаток'], отпечаток(х, в.область))
    if разн:
        raise ValueError(f'взять: вариант {в.папка} считан с другого холста — ' + '; '.join(разн) + '. Варианты на диск '
                         'считать с сохранённого холста (`сохранить`, затем `варианты(…, в_папку=)`) и брать в холст, '
                         '`загрузить`-нутый из того же .npz, до новых мазков; иначе — посчитать варианты заново')
    try:
        д = _с_диска(в._данные, 'в данных варианта (слои, кисти куска)', з['файл'], з['своя'])
    except (pickle.UnpicklingError, EOFError) as e:
        raise ValueError(f'взять: {з["файл"]} — файл варианта не цел ({e}); посчитать варианты заново') from None
    ж = getattr(х, 'журнал', None)
    строки, до = д['журнал'], з['журнал_до']
    if ж is not None:
        if строки is None:
            raise ValueError('взять: варианты считаны с холста без журнала, а этот холст пишет журнал — мазков варианта '
                             'в нём не будет и повтор разойдётся; посчитать варианты с холстом, что пишет журнал')
        есть = _json({'кистей': ж.номер, 'этап': ж.этап, 'объект': ж.объект})
        if есть != до:
            raise ValueError(f'взять: журнал холста не на том месте, где был при варианты (кистей названо, этап, объект: '
                             f'у вариантов {до}, у журнала {есть}) — `загрузить` с тем журналом, что писал холст, и '
                             'брать до новых мазков и пометок')
    elif строки is not None:
        warnings.warn('взять: холст не пишет журнал (загружен без журнал=) — строк варианта в журнале не будет; писать '
                      'журнал дальше — Холст.загрузить(…, журнал=)', UserWarning, stacklevel=3)
    _в_холст(х, в, д)
    п = dict(getattr(х, '_пустые', {}))     # мазки без следа, что дал кусок, — к счёту этого холста
    for вид, k in д['пустые'].items():
        п[вид] = п.get(вид, 0) + k - з['пустые_до'].get(вид, 0)
    х._пустые = {вид: k for вид, k in п.items() if k}
    if ж is not None:
        ж._ф.write(строки['байты'])
        ж._ф.flush()
        ж.строк += строки['байты'].count(b'\n')      # К-3: номер строки журнала; рамок мазков варианта холст не знает
        ж.номер, ж.этап, ж.объект = строки['номер'], строки['этап'], строки['объект']
    _сказать(в)
    return None


def взять(х, в, своя=False):
    if isinstance(в, (str, os.PathLike)):
        в = прочесть(в, своя)
    if not isinstance(в, Вариант):
        raise TypeError('взять: нужен вариант из х.варианты(…) или папка варианта на диске (`<в_папку>/<i>`)')
    if в._группа is None:
        return _взять_с_диска(х, в)
    г = в._группа
    if г.холст is not х:
        if в.папка is not None:
            raise ValueError(f'взять: вариант не этого холста — с диска его берут путём: х.взять({в.папка!r})')
        raise ValueError('взять: вариант не этого холста')
    if г.взят:
        raise ValueError('взять: из этих вариантов уже взят один — прочие забыты; новые — х.варианты(…) заново')
    if х.__dict__.get('_правок', 0) != г.правок:
        raise ValueError('взять: холст менялся после варианты (мазок, сушка, откат, вписать…) — варианты считаны с '
                         'прежнего холста; посчитать их заново')
    д = pickle.loads(в._данные)
    г.взят = True
    _в_холст(х, в, д)
    х._пустые = д['пустые']
    кисти = {}
    for oid, изм, убрано, новая in д['кисти']:
        к = новая if новая is not None else г.кисти[oid]
        for п in убрано:
            к.__dict__.pop(п, None)
        к.__dict__.update(изм)
        кисти[oid] = к
    ж = getattr(х, 'журнал', None)
    if ж is not None and д['журнал'] is not None:
        с = д['журнал']
        ж._ф.write(с['байты'])
        ж._ф.flush()
        ж.номер, ж.этап, ж.объект = с['номер'], с['этап'], с['объект']
        for oid, имя, поля, ост, краска in с['кисти']:
            к = кисти.get(oid) or г.кисти[oid]
            ж.кисти.pop(oid, None)
            ж.кисти[id(к)] = [к, имя, поля, к.__dict__.get('_остаток·') if isinstance(ост, str) and ост == _СВОЁ else ост,
                             к.__dict__.get('_краска') if isinstance(краска, str) and краска == _СВОЁ else краска]
    г.кисти = {}
    _сказать(в)
    return None
