ПОТОЛОК = 16
_СВОЁ = '\0своё'           # в строке кисти журнала — то самое поле кисти, что у неё сейчас (тот же объект)
_НЕ_ПЕРЕНОСИТЬ = ('_ждёт_ядра',)


class Вариант:
    """Один вариант куска: `номер` (i в `кусок(участок, i)`), `картинка` — линейная float32 (В, Ш, 3) области,
    `ответ` — что вернула `кусок`, `область`, `слова` — предупреждения, что звучали в куске (повторятся при `взять`),
    `однообразие` — К-12, зеркало однообразия мазков куска (`кисть.однообразие.Однообразие`: оценка, слова, сводка,
    регулярность; номера — строки куска с 1); считается всегда, и у холста без журнала."""
    __slots__ = ('номер', 'картинка', 'ответ', 'область', 'слова', 'однообразие', 'папка', '_данные', '_группа', '_диск')

    def __repr__(self):
        return f'Вариант({self.номер}, область {self.область}' + (f', {self.папка}' if self.папка else '') + ')'


class _Группа:
    __slots__ = ('холст', 'правок', 'кисти', 'взят', '__weakref__')


def _наружу(a):
    if isinstance(a, Плитки):
        о, oy, ox = a.основа()
        return (о, oy, ox, a.shape)
    return a


def _внутрь(з):
    if isinstance(з, tuple):
        о, oy, ox, форма = з
        return о.окно(slice(oy, oy + форма[0]), slice(ox, ox + форма[1]))
    return з


def _кисти_процесса():
    return [o for o in gc.get_objects() if isinstance(o, Кисть)]


def _слепок(к):
    """Поля кисти и их байты. Метка мазка очереди (`ядра._Мазок`: мазок кисти, что ещё считается или посчитан на ядрах
    какого-то холста) не пиклится — она тянет за собой очередь и её холст, у чужого холста с недосчитанными мазками
    это ошибка в ветви (`test_ядра` перед `test_варианты_2г` одним процессом); кусок её не правит, а заменяет —
    сравнивается по `is`."""
    from .ядра import _Мазок
    д = dict(к.__dict__)
    return д, {п: None if isinstance(v, _Мазок) else pickle.dumps(v, 5) for п, v in д.items() if п not in _НЕ_ПЕРЕНОСИТЬ}


def _изменилось(v, v0, б0):
    return v is not v0 or (б0 is not None and pickle.dumps(v, 5) != б0)


def _ветвь(х, кусок, i, область, на_диск=False):
    """В процессе-ветви: кусок на участке, ответ — pickle всего, что нужно `взять`. на_диск (М-8) — реестр кистей
    журнала ветви пуст, как после `загрузить`: кисти куска названы заново своими строками."""
    from .холст import Слой
    у = х.участок(область)
    у.__dict__.pop('_правок', None)
    ж = getattr(х, 'журнал', None)
    зеркало = None
    if ж is None:                            # К-12: холст без журнала — ветвь пишет строки в память только для зеркала
        from .журнал import Журнал
        зеркало = Журнал.__new__(Журнал)
        зеркало.путь, зеркало.пауза, зеркало.кисти, зеркало.номер, зеркало.строк = None, 0, {}, 0, 0
        зеркало.этап, зеркало.объект = х.__dict__.get('_этап'), х.__dict__.get('_объект')
        зеркало._ф = io.BytesIO()
        у.журнал = зеркало
    if ж is not None:                        # журнал ветви — копия журнала холста в памяти: строки идут родителю
        ж2 = copy.copy(ж)
        ж2._ф = io.BytesIO()
        ж2.кисти = {} if на_диск else {k: list(з) for k, з in ж.кисти.items()}
        у.журнал = ж2
        реестр_до = {k: tuple(з) for k, з in ж2.кисти.items()}
    у._вне_журнала = False
    у._только_в = tuple(область)
    у._пустые = dict(getattr(х, '_пустые', {}))
    до = {id(к): (к, *_слепок(к)) for к in _кисти_процесса()}
    with warnings.catch_warnings(record=True) as слова:
        warnings.simplefilter('always')
        ответ = кусок(у, i)
        у.досчитать()
    if зеркало is not None:
        у.журнал = None
    о = _однообразие(у.журнал if зеркало is None else зеркало)
    кисти = []
    for oid, (к, д0, б0) in до.items():
        д1 = к.__dict__
        изм = {п: v for п, v in д1.items() if п not in _НЕ_ПЕРЕНОСИТЬ
               and (п not in д0 or _изменилось(v, д0[п], б0[п]))}
        убрано = [п for п in д0 if п not in д1]
        if изм or убрано:
            кисти.append((oid, изм, убрано, None))
    строки = None
    if ж is not None:
        ж2 = у.журнал
        строки = {'байты': ж2._ф.getvalue(), 'номер': ж2.номер, 'этап': ж2.этап, 'объект': ж2.объект, 'кисти': []}
        for k, з in ж2.кисти.items():
            if k in реестр_до and all(a is b for a, b in zip(з, реестр_до[k])):
                continue
            к = з[0]
            if k not in до:                  # кисть заведена в куске: едет целиком
                кисти.append((k, {}, [], к))
            д = к.__dict__
            строки['кисти'].append((k, з[1], з[2], _СВОЁ if з[3] is д.get('_остаток·') else з[3],
                                    _СВОЁ if з[4] is д.get('_краска') else з[4]))
    слои = {имя: {п: _наружу(getattr(с, п)) for п in Слой._ВСЕ} for имя, с in у._слои.items()}
    данные = {'слои': слои, 'счётчик': у._счётчик, 'повторы': у._повторы, 'этап': у._этап, 'объект': у._объект,
              'пустые': dict(getattr(у, '_пустые', {})), 'кисти': кисти, 'журнал': строки}
    try:
        ответ_б = pickle.dumps(ответ, 5)
    except Exception as e:                   # noqa: BLE001
        raise TypeError(f'варианты: то, что вернула кусок ({type(ответ).__name__}), не уходит из процесса (pickle): {e}; '
                        'возвращать числа, строки, массивы, словари') from None
    return pickle.dumps((у.картинка(), ответ_б, [(type(w.message).__name__, str(w.message)) for w in слова],
                         pickle.dumps(данные, 5), о), 5)


def _однообразие(ж):
    """К-12: отчёт зеркала по строкам, что кусок написал в журнал ветви; кисти, заведённые до куска, — из реестра."""
    import json
    from dataclasses import asdict
    from .журнал import _в_json
    from . import однообразие as О
    кисти = {}
    for з in ж.кисти.values():
        поля = з[2] if з[2] is not None else asdict(з[0])
        поля = _в_json(поля)
        кисти[з[1]] = (json.dumps({к: v for к, v in поля.items() if к not in О._БЕЗ}, sort_keys=True), поля.get('ширина'))
    return О.отчёт(О.мазки_журнала(ж._ф.getvalue(), кисти), 'кусок')


# У-2: разведка — мазок, чей ход с запасом (ширин кисти и полей _ПОЛЕ_Р px) весь в области, рамкой в неё же ложится:
# на всех пресетах, ширинах 4–160 px, нажимах 0,1–1 рамка шире хода не больше 1,2 ширины и 10 px + 0,15 ширины, с
# наклоном 70° — 2,4 ширины; прочие — рамкой счётом мазка до места, где он берёт холст (как `прямоугольник_мазка`).
# Ошибётся запас — мазок шире области всё равно остановит вариант при счёте (`холст._ВОбласти`)
_ЗАПАС, _ЗАПАС_НАКЛОН = 1.6, 3.0
_ПОЛЕ_Р = 12.0


def _мазок_разведки(у, з, кисть):
    from .холст import _Рамка, _ВОбластиДоРамки
    x0, y0, x1, y1 = у._только_в
    т = np.asarray(з['точки'], np.float64)
    W = float(кисть.в_пикселях(у.px_на_мм).ширина)
    наклон = т.shape[1] >= 5 and bool(np.any(т[:, 4] != 0.0))
    з_ = _ПОЛЕ_Р + ((_ЗАПАС_НАКЛОН if наклон else _ЗАПАС) + 0.15) * W
    if т.size and x0 <= т[:, 0].min() - з_ and y0 <= т[:, 1].min() - з_ and т[:, 0].max() + з_ <= x1 and т[:, 1].max() + з_ <= y1:
        return None
    у.__dict__['_мазков_рамкой'] = у.__dict__.get('_мазков_рамкой', 0) + 1
    try:
        у._положить(з, кисть, _ВОбластиДоРамки(у._только_в, у.полная_ширина, у.полная_высота))
    except _Рамка:
        pass
    return None


def _разведать(х, кусок, n, область):
    """У-2, в процессе-ветви: все n кусков на участке без счёта — каждый мазок только рамкой против области. Ответ:
    None — все рамки в области (или кусок без мазков счёта не пройти: тогда скажут варианты); текст ошибки — первый
    мазок шире области."""
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        for i in range(n):
            у = х.участок(область)           # каждый вариант — с холста, каким он был при вызове: свои счёт сидов, пометка
            у.__dict__.pop('_правок', None)
            у.журнал = None
            у._вне_журнала = False
            у._только_в = tuple(область)
            у._разведка = _мазок_разведки
            у._тихо = 1
            try:
                кусок(у, i)
            except ValueError as e:
                if 'шире области' in str(e) or str(e).startswith('варианты:'):
                    return i, str(e)
                return None
            except Exception:                # noqa: BLE001 — кусок, читающий холст, без счёта может пойти не так: скажут варианты
                return None
    return None


def _разведчик(х, кусок, n, область, труба):
    try:
        труба.send_bytes(pickle.dumps(_разведать(х, кусок, n, область), 5))
    except BaseException:                    # noqa: BLE001
        pass
    finally:
        труба.close()


def _работник(х, кусок, i, область, труба, на_диск=False):
    try:
        труба.send_bytes(b'+' + _ветвь(х, кусок, i, область, на_диск))
    except BaseException as e:               # noqa: BLE001 — родителю: что упало и где
        import traceback
        try:
            труба.send_bytes(b'-' + pickle.dumps((type(e).__name__, str(e), traceback.format_exc()), 5))
        except Exception:                    # noqa: BLE001
            pass
    finally:
        труба.close()


def варианты(х, кусок, n, область, ядра=None, в_папку=None):
    from . import ядра as Я
    n = int(n)
    if n < 1:
        raise ValueError('варианты: n — от 1')
    if not callable(кусок):
        raise TypeError('варианты: кусок — функция кусок(участок, i)')
    x0, y0, x1, y1 = (int(round(v)) for v in область)
    x0, y0 = max(x0, х.x0), max(y0, х.y0)
    x1, y1 = min(x1, х.x0 + х.ширина), min(y1, х.y0 + х.высота)
    if x1 - x0 < 1 or y1 - y0 < 1:
        raise ValueError(f'варианты: область {tuple(область)} вне холста')
    область = (x0, y0, x1, y1)
    if not Я.можно():
        raise RuntimeError('варианты: этот процесс — сам процесс счёта (демон), ветвей ему не завести')
    х.досчитать()
    if ядра is None:
        ядра = х.__dict__.get('_ядер')
        ядра = Я.число_ядер(None) if ядра is None else ядра
    k = max(1, min(int(ядра), ПОТОЛОК, n))
    г = _Группа()
    г.холст, г.правок, г.взят = х, х.__dict__.get('_правок', 0), False
    г.кисти = {id(к): к for к in _кисти_процесса()}     # держим: id кисти в ветви — тот же объект здесь
    среда = get_context('fork')
    разведка, его = среда.Pipe(duplex=False)  # У-2: рамки всех мазков куска — разведкой рядом со счётом: шире области — стоп сразу
    разведчик = среда.Process(target=_разведчик, args=(х, кусок, n, область, его), daemon=True)
    разведчик.start()
    его.close()
    ждут, идут, готово, ошибка = list(range(n)), {}, {}, None
    while (ждут and ошибка is None) or идут:
        while ждут and len(идут) < k - (разведка is not None and k >= ПОТОЛОК) and ошибка is None:   # с разведкой — не больше 16 процессов
            i = ждут.pop(0)
            наша, его = среда.Pipe(duplex=False)
            п = среда.Process(target=_работник, args=(х, кусок, i, область, его, в_папку is not None), daemon=True)
            п.start()
            его.close()
            идут[наша] = (i, п, [])
        for труба in wait(list(идут) + ([разведка] if разведка is not None else [])):
            if труба is разведка:
                try:
                    итог = pickle.loads(разведка.recv_bytes())
                except EOFError:
                    итог = None
                разведка.close()
                разведчик.join()
                разведка = None
                if итог is not None:
                    ошибка = (итог[0], ('ValueError', итог[1] + ' (рамки мазков сверены до счёта вариантов)', ''))
                    break
                continue
            i, п, куски = идут[труба]
            try:
                куски.append(труба.recv_bytes())
            except EOFError:
                pass
            else:
                continue
            труба.close()
            п.join()
            del идут[труба]
            if not куски:
                ошибка = ошибка or (i, ('RuntimeError', f'процесс варианта упал (код {п.exitcode})', ''))
            elif куски[0][:1] == b'-':
                ошибка = ошибка or (i, pickle.loads(куски[0][1:]))
            else:
                готово[i] = куски[0][1:]
            if ошибка is not None:
                break
        if ошибка is not None:               # У-2: прочие варианты не досчитывать — ошибка сразу
            for т, (_, п2, _) in list(идут.items()):
                п2.terminate()
                п2.join()
                т.close()
            идут.clear()
    if разведка is not None:
        разведчик.terminate()
        разведчик.join()
        разведка.close()
    if ошибка is not None:
        i, (имя, текст, след) = ошибка
        тип = {'ValueError': ValueError, 'TypeError': TypeError, 'KeyError': KeyError}.get(имя, RuntimeError)
        raise тип(f'варианты: вариант {i}: {имя}: {текст}' + (f'\n--- в процессе варианта:\n{след}' if след else ''))
    ответ = []
    for i in range(n):
        картинка, ответ_б, слова, данные, о = pickle.loads(готово.pop(i))
        в = Вариант()
        в.номер, в.картинка, в.ответ, в.область, в.слова = i, картинка, pickle.loads(ответ_б), область, слова
        в.однообразие, в.папка, в._диск = о, None, None
        в._данные, в._группа = данные, г
        ответ.append(в)
    одинаковые = {}
    for в in ответ:
        одинаковые.setdefault(в.картинка.tobytes(), []).append(в.номер)
    if n > 1 and len(одинаковые) < n:
        пары = [v for v in одинаковые.values() if len(v) > 1]
        warnings.warn(f'варианты: одинаковые картинки у вариантов {пары} — кусок не различает i (сиды мазков — из '
                      'сида листа, этапа, объекта пометки и точек: разные i — разные точки, цвета или объект пометки)', stacklevel=3)
    if в_папку is not None:
        _на_диск(х, ответ, в_папку)
    return ответ


