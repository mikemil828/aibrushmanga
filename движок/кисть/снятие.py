"""К8.4: снятие сырой краски по ходу — тряпка и скребок (в журнале — строка с полем "tool").

Тряпка — комок ткани: прижатая, она касается плёнки верхами нитей и складок, а ложбины между ними до краски не
достают. Нить и складка тащатся вместе с комком, поэтому каждая оставляет полосу вдоль хода: где за проход касание
было чаще, краски снято больше. Сырое впитывается в ткань, пока ткань не напиталась: к концу длинного хода она
снимает слабее. Пигмент, вошедший в грунт, ткань не берёт — на месте остаётся тонкий тон.

Скребок — жёсткая кромка поперёк хода: где она прошла, сырая краска снята до грунта. Снятое копится валом перед
кромкой; вал выдавливается за её концы — по краям следа ложится валик краски, на подъёме остаток вала остаётся
комком. Сухой и схватившийся слой ни то ни другое не трогает: снимается только сырая доля плёнки, несхваченная."""
import numpy as np

from .быстро import зажать

from .краска import в_кс, из_кс
from .зерно import Зерно
from .пряди import _шум
from .числа import _ТАУ, _СНЯТИЕ, _СКРЕБОК

ИНСТРУМЕНТЫ = ('тряпка', 'скребок')


def _шагом(точки, шаг=1.0):
    """Точки (x, y, нажим, …) -> путь через `шаг` px: (x, y, нажим), нажим по прямой между точками."""
    т = np.asarray(точки, dtype=np.float64)
    if т.ndim != 2 or т.shape[1] < 3:
        raise ValueError('снятие: точки — (x, y, нажим, …)')
    s = np.concatenate([[0.0], np.cumsum(np.hypot(*np.diff(т[:, :2], axis=0).T))])
    if s[-1] <= 0:
        return т[:1, :3].copy(), np.array([[1.0, 0.0]])
    n = max(2, int(np.ceil(s[-1] / шаг)) + 1)
    u = np.linspace(0.0, s[-1], n)
    xy = np.column_stack([np.interp(u, s, т[:, 0]), np.interp(u, s, т[:, 1]), np.interp(u, s, зажать(т[:, 2], 0.0, 1.0))])
    d = np.gradient(xy[:, :2], axis=0)
    d /= np.maximum(np.hypot(d[:, 0], d[:, 1]), 1e-9)[:, None]
    return xy, d


def _сырое(с, где, осталось):
    """Сколько плёнки слоя можно снять (h): сырая доля, не схваченная, сверх `осталось` — пигмента, вошедшего в грунт
    (тряпка его не берёт, кромка скребка по грунту оставляет его меньше)."""
    h = с.толщина[где]
    # масляная плёнка снимается целиком, пока влажность не ниже `_СНЯТИЕ[6]`; подсыхающая — по своей сырой доле
    return np.maximum(h * зажать(с.влажность[где] / _СНЯТИЕ[6], 0.0, 1.0) * (1.0 - с.схват[где]) - осталось, 0.0)


def _убрать(с, где, снять):
    """Убрать из слоя толщину `снять` (h) сырой краски: плёнка тоньше, покрытие — по оставшейся толщине."""
    h = с.толщина[где]
    h2 = np.maximum(h - снять, 0.0)
    было = 1.0 - np.exp(-h / _ТАУ)
    стало = 1.0 - np.exp(-h2 / _ТАУ)
    с.покрытие[где] = с.покрытие[где] * зажать(стало / np.maximum(было, 1e-9), 0.0, 1.0) ** 0.7
    сыро = np.maximum(h * с.влажность[где] - снять, 0.0)
    с.влажность[где] = np.where(h2 > 1e-9, зажать(сыро / np.maximum(h2, 1e-9), 0.0, 1.0), 0.0)
    с.толщина[где] = h2


def _положить(с, где, dh, кс):
    """Положить в слой толщину dh (h) сырой краски цвета кс (K/S): смесь с лежащим по толщине."""
    h = с.толщина[где]
    h2 = h + dh
    доля = dh / np.maximum(h2, 1e-9)
    было = в_кс(с.цвет[где].astype(np.float64))
    цвет = np.where((с.покрытие[где] > 1e-4)[..., None], из_кс(было * (1.0 - доля[..., None]) + кс * доля[..., None]),
                    из_кс(np.broadcast_to(кс, было.shape)))
    с.цвет[где] = np.where((dh > 0)[..., None], цвет, с.цвет[где])
    с.покрытие[где] = np.maximum(с.покрытие[где], 1.0 - np.exp(-h2 / _ТАУ))
    с.влажность[где] = np.where(h2 > 1e-9, (h * с.влажность[где] + dh) / np.maximum(h2, 1e-9), с.влажность[где])
    с.схват[где] = np.where(h2 > 1e-9, с.схват[где] * h / np.maximum(h2, 1e-9), с.схват[где])
    с.толщина[где] = h2


def _ткань(R, rng, шаг):
    """Комок ткани в своей рамке (2R+1, 2R+1): высота верхов нитей и складок 0..1."""
    к = 2 * R + 1
    з = Зерно(шаг, 1.0, int(rng.integers(1 << 30)))
    x0, y0 = (int(v) for v in rng.integers(0, 4096, 2))
    нити = з.высота(x0, y0, x0 + к, y0 + к).astype(np.float64)
    # складки смятой ткани: гладкие гребни в 1–3 мм, своя высота у каждого места комка
    складки = _шум(rng, к, к, max(R / 2.0, 3.0))
    складки = 0.5 * (складки + _шум(rng, к, к, max(R / 2.0, 3.0)).T)
    складки = (складки - складки.min()) / max(float(np.ptp(складки)), 1e-9)
    return _СНЯТИЕ[1] * нити + (1.0 - _СНЯТИЕ[1]) * складки


def _под_комком(т, R2, dx, dy, d):
    """Высота ткани под пикселями (dx, dy — px от середины комка) у комка, который тащат по `d`: складки и нити
    стоят по ходу (ткань, тянутая по холсту, складывается вдоль тяги), строка ткани — поперёк хода. Ткань `т`
    (2·R2+1 с полем в 1 px); между узлами — по прямой."""
    вдоль, поперёк = dx * d[0] + dy * d[1], -dx * d[1] + dy * d[0]
    r, c = зажать(R2 + 1 + поперёк, 0.0, 2 * R2 + 1.999), зажать(R2 + 1 + вдоль, 0.0, 2 * R2 + 1.999)
    r0, c0 = np.floor(r).astype(np.intp), np.floor(c).astype(np.intp)
    ar, ac = r - r0, c - c0
    return (1 - ar) * ((1 - ac) * т[r0, c0] + ac * т[r0, c0 + 1]) + ar * ((1 - ac) * т[r0 + 1, c0] + ac * т[r0 + 1, c0 + 1])


def тряпка(холст, точки, ширина, сид, слои):
    """Снять сырую краску тряпкой по пути `точки` (x, y, нажим, …); `ширина` — поперечник комка, px.

    Комок мягкий: прижатый, он сминается, и пятно касания растёт с нажимом (радиус — как корень кубический нажима,
    от `_СНЯТИЕ[9]` — весь комок); давление по пятну — горбом, у края пятна верхи едва касаются. Сырое масло липнет
    к ткани и при лёгком касании: где верх нити или складки тронул плёнку, краска уходит; ложбины между верхами до
    плёнки не достают — каждый верх тащит за собой полосу вдоль хода."""
    путь, dd = _шагом(точки)
    rng = np.random.default_rng([int(сид), 811])
    R = max(2, int(round(ширина / 2.0)))
    R2 = int(np.ceil(1.42 * R)) + 1                      # ткань с запасом: комок повёрнут по ходу
    ткань = np.pad(_ткань(R2, rng, max(2.0, _СНЯТИЕ[2] * холст.px_на_мм / 8.0 if холст.px_на_мм else _СНЯТИЕ[2])), 1, mode='edge')
    k = np.arange(-R, R + 1, dtype=np.float64)
    # проход комка через пиксель длится ~2R шагов: съём за шаг — доля, чтобы весь проход снимал `_СНЯТИЕ[3]` в логарифме
    # на каждую мягкость касания, на которую верх ткани вошёл в плёнку
    за_шаг = _СНЯТИЕ[3] / (2.0 * R)
    ёмкость = _СНЯТИЕ[4] * (2 * R + 1) ** 2
    впитано = 0.0
    for (x, y, p), d in zip(путь, dd):
        if p <= 0.0:
            continue
        ix, iy = int(round(x)) - холст.x0, int(round(y)) - холст.y0
        # К8б: комок тянут по ходу — складки и нити ткани ложатся вдоль тяги, и каждая ведёт свою полосу под любым углом
        # хода (ткань в рамке холста косой ход пересекал наискось: каждый пиксель собирал и верхи, и ложбины — туман);
        # комок стоит в своей доле пикселя, а не на сетке
        dy, dx = k[:, None] - (y - холст.y0 - iy), k[None, :] - (x - холст.x0 - ix)
        верх = _под_комком(ткань, R2, dx, dy, d)
        r2 = (dx * dx + dy * dy) / max(R, 1) ** 2
        ya, yb, xa, xb = iy - R, iy + R + 1, ix - R, ix + R + 1
        ca, cb, da, db = max(ya, 0), min(yb, холст.высота), max(xa, 0), min(xb, холст.ширина)
        if ca >= cb or da >= db:
            continue
        где = (slice(ca, cb), slice(da, db))
        рамка = (slice(ca - ya, cb - ya), slice(da - xa, db - xa))
        прижим = np.sqrt(зажать(1.0 - r2[рамка] / min(p / _СНЯТИЕ[9], 1.0) ** (2.0 / 3.0), 0.0, 1.0))
        # К8б: верх ткани, вдавленный в плёнку глубже, давит на неё сильнее и снимает больше; ложбина, что едва тронула
        # плёнку, — меньше (касание не насыщается на верхах: у прижатого комка касается вся середина, и ровный съём по
        # всему пятну давал молочную полосу без полос ткани)
        касание = зажать((верх[рамка] - (1.0 - (_СНЯТИЕ[7] + _СНЯТИЕ[8] * p) * прижим)) / _СНЯТИЕ[5], 0.0, None)
        сила = за_шаг * max(0.0, 1.0 - впитано / ёмкость)
        if сила <= 0:
            break
        доля = 1.0 - np.exp(-сила * касание)
        for с in слои:
            снять = _сырое(с, где, _СНЯТИЕ[0]) * доля
            if снять.any():
                впитано += float(снять.sum())
                _убрать(с, где, снять)


def _окно(холст, x, y, d, м):
    """Окно холста радиусом м px у точки (x, y) хода d: срезы, координаты вдоль и поперёк хода; None — вне холста."""
    ix, iy = int(round(x)) - холст.x0, int(round(y)) - холст.y0
    ca, cb, da, db = max(iy - м, 0), min(iy + м + 1, холст.высота), max(ix - м, 0), min(ix + м + 1, холст.ширина)
    if ca >= cb or da >= db:
        return None
    Y, X = np.mgrid[ca:cb, da:db].astype(np.float64)
    dx, dy = X + холст.x0 - x, Y + холст.y0 - y
    return (slice(ca, cb), slice(da, db)), dx * d[0] + dy * d[1], -dx * d[1] + dy * d[0]


def _горб(t, s):
    """Сечение горба масла полушириной s (px) по t (px от его середины): 1 - (t/s)², вне — 0."""
    return зажать(1.0 - (t / np.maximum(s, 1e-6)) ** 2, 0.0, 1.0)


def скребок(холст, точки, ширина, сид, слои):
    """Снять сырую краску скребком по пути `точки`: кромка шириной `ширина` px поперёк хода.

    Снятое копится валом перед кромкой там, где снято: вал — сечения по местам кромки (1 px), у каждого свой объём и
    свои краски. Вал растекается вдоль кромки от высокого к низкому и сползает к одному концу (кромку держат не ровно).
    Масло — паста с пределом текучести: у конца кромки вал течёт наружу, только когда его сечение выше предела, —
    вал, что снял мало, не выдавливается вовсе; подсохшее масло (вал суше точки студня) не течёт совсем. Выдавленное
    ложится валиком горбом той крутизны, что держит масло: полуширина — от объёма порции (больше — шире и выше),
    краски — полосами по местам вала, откуда пришли: крайнее у конца ложится дальше. На подъёме вал остаётся комом:
    каждое место — шапкой по своему объёму."""
    путь, d = _шагом(точки, 0.5)
    rng = np.random.default_rng([int(сид), 812])
    W2 = ширина / 2.0
    nb = max(2, int(np.ceil(ширина)))
    шб = ширина / nb                                         # ширина места вала вдоль кромки, px
    крен = float(зажать(_СКРЕБОК[0] * rng.standard_normal(), -0.45, 0.45))
    κ, предел, растёк, течь, гель = _СКРЕБОК[2], _СКРЕБОК[3] * шб, _СКРЕБОК[4], _СКРЕБОК[5], _СКРЕБОК[7]
    s_max = max(1.0, _СКРЕБОК[6] * ширина)
    L = len(слои)
    вал = np.zeros((L, nb))                                  # объём вала по слоям и местам кромки, h·px²
    вал_кс = np.zeros((L, nb, 24))                           # K/S · объём
    вал_вл = np.zeros(nb)                                    # влажность · объём (все слои)
    м = int(np.ceil(W2 + 2.0 * s_max + 2.0))
    for i, (x, y, p) in enumerate(путь):
        if p <= 0.02:
            continue
        о = _окно(холст, x, y, d[i], м)
        if о is None:
            continue
        где, вдоль, поперёк = о
        шаг_вдоль = зажать(1.0 - np.abs(вдоль) / 0.75, 0.0, 1.0)
        # кромка: полоса в шаг пути, по ширине — до концов с мягким краем в 1 px
        кромка = шаг_вдоль * зажать(W2 + 0.5 - np.abs(поперёк), 0.0, 1.0) * min(p / 0.3, 1.0)
        место = зажать(((поперёк + W2) / шб).astype(np.int64), 0, nb - 1)
        есть = кромка > 0
        for k, с in enumerate(слои):
            снять = _сырое(с, где, _СКРЕБОК[1]) * кромка
            if not снять.any():
                continue
            кс = в_кс(с.цвет[где][есть].astype(np.float64)) * снять[есть][:, None]
            вал[k] += np.bincount(место[есть], снять[есть], nb)
            вал_вл[:] += np.bincount(место[есть], (снять * с.влажность[где])[есть], nb)
            for q in range(24):
                вал_кс[k, :, q] += np.bincount(место[есть], кс[:, q], nb)
            _убрать(с, где, снять)
        T = вал.sum(0)
        if T.max() <= 0:
            continue
        # вал растекается вдоль кромки от высокого сечения к низкому и сползает по крену; переносится тем, что лежит в месте
        поток = растёк * (T[:-1] - T[1:]) + крен * np.where(крен > 0, T[:-1], T[1:])     # из места j в j+1 (минус — назад)
        поток = зажать(поток, -0.45 * T[1:], 0.45 * T[:-1])
        из_левого = зажать(поток, 0, None) / np.maximum(T[:-1], 1e-12)
        из_правого = зажать(-поток, 0, None) / np.maximum(T[1:], 1e-12)
        for м_ in (вал, вал_кс, вал_вл[None]):
            а = м_[:, :-1] * (из_левого[:, None] if м_.ndim == 3 else из_левого)
            б = м_[:, 1:] * (из_правого[:, None] if м_.ndim == 3 else из_правого)
            м_[:, :-1] += б - а
            м_[:, 1:] += а - б
        # у конца кромки вал держится, пока сечение не выше предела текучести; сверх него масло течёт за конец — тем
        # быстрее, чем больше превышение (паста Бингама). Подсыхающее масло густеет: предел растёт как квадрат обратной
        # доли влажности вала над точкой студня `_СКРЕБОК[7]`; вал из масла, схватившегося до студня, не течёт вовсе —
        # липким комом едет перед кромкой до подъёма. Конец кормится тем, что кромка сняла у него: где краски было
        # больше, течёт больше
        for сторона, j0, шаг_j in ((0, 0, 1), (1, nb - 1, -1)):
            Tк = вал[:, j0].sum()
            вл = float(вал_вл[j0] / max(Tк, 1e-12))
            тек = (вл - гель) / (1.0 - гель)
            if тек <= 0.0 or Tк <= предел / тек ** 2:
                continue
            пред = предел / тек ** 2
            if Tк <= пред:
                continue
            # течёт нависшее: у каждого места от конца внутрь — доля превышения, пока превышение есть
            порции = []
            for j in range(j0, j0 + шаг_j * nb, шаг_j):
                Tj = вал[:, j].sum()
                if Tj <= пред:
                    break
                доля = течь * (1.0 - пред / Tj)
                порции.append((вал[:, j] * доля, вал_кс[:, j] * доля))
                вал[:, j] *= 1.0 - доля
                вал_кс[:, j] *= 1.0 - доля
                вал_вл[j] *= 1.0 - доля
            V = sum(float(п[0].sum()) for п in порции)
            # валик — горб крутизны κ: площадь сечения A = V / шаг пути -> полуширина s = sqrt(3A / (4κ)); лежит
            # от конца кромки наружу
            s = min(np.sqrt(3.0 * (V / 0.5) / (4.0 * κ)), s_max)
            t = (поперёк if сторона == 1 else -поперёк) - W2         # px за концом кромки
            форма = _горб(t - s, s) * шаг_вдоль
            сумма = float(форма.sum())
            if V <= 0 or сумма <= 0:
                continue
            # полосы: доля объёма валика от внешнего края внутрь — по порядку порций
            порядок = np.argsort(-t, axis=None)
            накоп = np.empty(форма.size)
            накоп[порядок] = np.cumsum(форма.ravel()[порядок]) / сумма
            накоп = накоп.reshape(форма.shape)
            граница = 0.0
            for объём, кс in порции:
                доля_п = float(объём.sum()) / V
                if доля_п <= 0:
                    continue
                вес = форма * ((накоп > граница - 1e-9) & (накоп <= граница + доля_п + 1e-9))
                граница += доля_п
                св = float(вес.sum())
                if св <= 0:
                    вес, св = форма, сумма
                for k, с in enumerate(слои):
                    if объём[k] > 0:
                        _положить(с, где, вес / св * объём[k], кс[k] / объём[k])
    # на подъёме вал остаётся у кромки: каждое место вала оседает шапкой той же крутизны κ (радиус — по своему
    # объёму) перед кромкой; шапки сливаются в ком, у концов кромки он круглый, как оплывшее масло
    if вал.sum() > 0:
        живые = np.nonzero(путь[:, 2] > 0.02)[0]
        i = int(живые[-1]) if len(живые) else len(путь) - 1
        T = вал.sum(0)
        s = np.minimum((2.0 * T / (np.pi * κ)) ** (1.0 / 3.0), s_max)
        о = _окно(холст, путь[i, 0], путь[i, 1], d[i], int(np.ceil(W2 + 2.0 * s.max() + 2.0)))
        if о is not None:
            где, вдоль, поперёк = о
            for jм in np.nonzero(T > 0)[0]:
                вес = _горб(np.hypot(вдоль - s[jм], поперёк - (-W2 + (jм + 0.5) * шб)), s[jм])
                св = float(вес.sum())
                if св <= 0:
                    continue
                for k, с in enumerate(слои):
                    if вал[k, jм] > 0:
                        _положить(с, где, вес / св * вал[k, jм], вал_кс[k, jм] / вал[k, jм])


def снять(холст, точки, инструмент, ширина, сид, слой=None):
    """Снять сырую краску по ходу (К8.4). инструмент — 'тряпка' или 'скребок'; слой — имя слоя или None (все)."""
    if инструмент not in ИНСТРУМЕНТЫ:
        raise ValueError(f'снятие: инструмент — {", ".join(ИНСТРУМЕНТЫ)}, не {инструмент!r}')
    if not ширина > 0:
        raise ValueError('снятие: ширина — больше нуля')
    слои = [с for имя, с in холст.слои.items() if слой is None or имя == слой][::-1]     # сверху вниз
    if not слои:
        return
    холст._до_записи(None)
    (тряпка if инструмент == 'тряпка' else скребок)(холст, точки, float(ширина), сид, слои)
