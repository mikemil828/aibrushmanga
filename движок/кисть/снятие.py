_ЧЕРЕНОК = (0.8, 0.1, 0.03, 0.6, 0.02, 0.01)   # нажим, с которого конец садится на твёрдое (плёнка под ним рвётся); зазор между концом и твёрдым, h, у конца 1 мм при половине этого нажима (зазор — как радиус конца и как этот нажим к нажиму руки без единицы: паста из сходящейся щели выжимается тем труднее, чем щель тоньше и конец шире); плёнка над твёрдым, h (12 мкм — зерно пигмента), тоньше которой под концом не остаётся: твёрдое по твёрдому стирает её дочиста; валик за боком конца не шире этой доли поперечника конца и ещё 4 px; нажим, ниже которого конец над холстом; сухая доля слоя, h, с которой он для конца твёрдый (под ним не берётся и нижнее)

ИНСТРУМЕНТЫ = ('тряпка', 'скребок', 'черенок')


def _шагом(точки, шаг=1.0):
    """Точки (x, y, нажим, …) -> путь через `шаг` px: (x, y, нажим), нажим по прямой между точками."""
    т = np.asarray(точки, dtype=np.float64)
    if т.ndim != 2 or т.shape[1] < 3:
        raise ValueError('снятие: точки — (x, y, нажим, …)')
    s = np.concatenate([[0.0], np.cumsum(np.hypot(*np.diff(т[:, :2], axis=0).T))])
    if s[-1] <= 0:
        return т[:1, :3].copy(), np.array([[1.0, 0.0]])
    n = max(2, int(np.ceil(s[-1] / шаг)) + 1)
    u = np.linspace(0.0, s[-1], n)
    xy = np.column_stack([np.interp(u, s, т[:, 0]), np.interp(u, s, т[:, 1]), np.interp(u, s, зажать(т[:, 2], 0.0, 1.0))])
    d = np.gradient(xy[:, :2], axis=0)
    d /= np.maximum(np.hypot(d[:, 0], d[:, 1]), 1e-9)[:, None]
    return xy, d


def _сырое(с, где, осталось):
    """Сколько плёнки слоя можно снять (h): сырая доля, не схваченная, сверх `осталось` — пигмента, вошедшего в грунт
    (тряпка его не берёт, кромка скребка по грунту оставляет его меньше)."""
    h = с.толщина[где]
    # масляная плёнка снимается целиком, пока влажность не ниже `_СНЯТИЕ[6]`; подсыхающая — по своей сырой доле
    return np.maximum(h * зажать(с.влажность[где] / _СНЯТИЕ[6], 0.0, 1.0) * (1.0 - зажать(с.схват[где], 0.0, 1.0)) - осталось, 0.0)


def _убрать(с, где, снять):
    """Убрать из слоя толщину `снять` (h) сырой краски: плёнка тоньше, покрытие — по оставшейся толщине."""
    h = с.толщина[где]
    h2 = np.maximum(h - снять, 0.0)
    было = 1.0 - np.exp(-h / _ТАУ)
    стало = 1.0 - np.exp(-h2 / _ТАУ)
    с.покрытие[где] = с.покрытие[где] * зажать(стало / np.maximum(было, 1e-9), 0.0, 1.0) ** 0.7
    сыро = np.maximum(h * с.влажность[где] - снять, 0.0)
    с.влажность[где] = np.where(h2 > 1e-9, зажать(сыро / np.maximum(h2, 1e-9), 0.0, 1.0), 0.0)
    с.толщина[где] = h2


def _положить(с, где, dh, кс):
    """Положить в слой толщину dh (h) сырой краски цвета кс (K/S): смесь с лежащим по толщине."""
    h = с.толщина[где]
    h2 = h + dh
    доля = dh / np.maximum(h2, 1e-9)
    было = в_кс(с.цвет[где].astype(np.float64))
    цвет = np.where((с.покрытие[где] > 1e-4)[..., None], из_кс(было * (1.0 - доля[..., None]) + кс * доля[..., None]),
                    из_кс(np.broadcast_to(кс, было.shape)))
    с.цвет[где] = np.where((dh > 0)[..., None], цвет, с.цвет[где])
    с.покрытие[где] = np.maximum(с.покрытие[где], 1.0 - np.exp(-h2 / _ТАУ))
    с.влажность[где] = np.where(h2 > 1e-9, (h * с.влажность[где] + dh) / np.maximum(h2, 1e-9), с.влажность[где])
    с.схват[где] = зажать(np.where(h2 > 1e-9, с.схват[где] * h / np.maximum(h2, 1e-9), с.схват[где]), 0.0, 1.0)
    с.толщина[где] = h2


def _ткань(R, rng, шаг):
    """Комок ткани в своей рамке (2R+1, 2R+1): высота верхов нитей и складок 0..1."""
    к = 2 * R + 1
    з = Зерно(шаг, 1.0, int(rng.integers(1 << 30)))
    x0, y0 = (int(v) for v in rng.integers(0, 4096, 2))
    нити = з.высота(x0, y0, x0 + к, y0 + к).astype(np.float64)
    # складки смятой ткани: гладкие гребни в 1–3 мм, своя высота у каждого места комка
    складки = _шум(rng, к, к, max(R / 2.0, 3.0))
    складки = 0.5 * (складки + _шум(rng, к, к, max(R / 2.0, 3.0)).T)
    складки = (складки - складки.min()) / max(float(np.ptp(складки)), 1e-9)
    return _СНЯТИЕ[1] * нити + (1.0 - _СНЯТИЕ[1]) * складки


def _под_комком(т, R2, dx, dy, d):
    """Высота ткани под пикселями (dx, dy — px от середины комка) у комка, который тащат по `d`: складки и нити
    стоят по ходу (ткань, тянутая по холсту, складывается вдоль тяги), строка ткани — поперёк хода. Ткань `т`
    (2·R2+1 с полем в 1 px); между узлами — по прямой."""
    вдоль, поперёк = dx * d[0] + dy * d[1], -dx * d[1] + dy * d[0]
    r, c = зажать(R2 + 1 + поперёк, 0.0, 2 * R2 + 1.999), зажать(R2 + 1 + вдоль, 0.0, 2 * R2 + 1.999)
    r0, c0 = np.floor(r).astype(np.intp), np.floor(c).astype(np.intp)
    ar, ac = r - r0, c - c0
    return (1 - ar) * ((1 - ac) * т[r0, c0] + ac * т[r0, c0 + 1]) + ar * ((1 - ac) * т[r0 + 1, c0] + ac * т[r0 + 1, c0 + 1])


def тряпка(холст, точки, ширина, сид, слои):
    """Снять сырую краску тряпкой по пути `точки` (x, y, нажим, …); `ширина` — поперечник комка, px.

    Комок мягкий: прижатый, он сминается, и пятно касания растёт с нажимом (радиус — как корень кубический нажима,
    от `_СНЯТИЕ[9]` — весь комок); давление по пятну — горбом, у края пятна верхи едва касаются. Сырое масло липнет
    к ткани и при лёгком касании: где верх нити или складки тронул плёнку, краска уходит; ложбины между верхами до
    плёнки не достают — каждый верх тащит за собой полосу вдоль хода."""
    путь, dd = _шагом(точки)
    rng = np.random.default_rng([int(сид), 811])
    R = max(2, int(round(ширина / 2.0)))
    R2 = int(np.ceil(1.42 * R)) + 1                      # ткань с запасом: комок повёрнут по ходу
    ткань = np.pad(_ткань(R2, rng, max(2.0, _СНЯТИЕ[2] * холст.px_на_мм / 8.0 if холст.px_на_мм else _СНЯТИЕ[2])), 1, mode='edge')
    k = np.arange(-R, R + 1, dtype=np.float64)
    # проход комка через пиксель длится ~2R шагов: съём за шаг — доля, чтобы весь проход снимал `_СНЯТИЕ[3]` в логарифме
    # на каждую мягкость касания, на которую верх ткани вошёл в плёнку
    за_шаг = _СНЯТИЕ[3] / (2.0 * R)
    ёмкость = _СНЯТИЕ[4] * (2 * R + 1) ** 2
    впитано = 0.0
    for (x, y, p), d in zip(путь, dd):
        if p <= 0.0:
            continue
        ix, iy = int(round(x)) - холст.x0, int(round(y)) - холст.y0
        # К8б: комок тянут по ходу — складки и нити ткани ложатся вдоль тяги, и каждая ведёт свою полосу под любым углом
        # хода (ткань в рамке холста косой ход пересекал наискось: каждый пиксель собирал и верхи, и ложбины — туман);
        # комок стоит в своей доле пикселя, а не на сетке
        dy, dx = k[:, None] - (y - холст.y0 - iy), k[None, :] - (x - холст.x0 - ix)
        верх = _под_комком(ткань, R2, dx, dy, d)
        r2 = (dx * dx + dy * dy) / max(R, 1) ** 2
        ya, yb, xa, xb = iy - R, iy + R + 1, ix - R, ix + R + 1
        ca, cb, da, db = max(ya, 0), min(yb, холст.высота), max(xa, 0), min(xb, холст.ширина)
        if ca >= cb or da >= db:
            continue
        где = (slice(ca, cb), slice(da, db))
        рамка = (slice(ca - ya, cb - ya), slice(da - xa, db - xa))
        прижим = np.sqrt(зажать(1.0 - r2[рамка] / min(p / _СНЯТИЕ[9], 1.0) ** (2.0 / 3.0), 0.0, 1.0))
        # К8б: верх ткани, вдавленный в плёнку глубже, давит на неё сильнее и снимает больше; ложбина, что едва тронула
        # плёнку, — меньше (касание не насыщается на верхах: у прижатого комка касается вся середина, и ровный съём по
        # всему пятну давал молочную полосу без полос ткани)
        касание = зажать((верх[рамка] - (1.0 - (_СНЯТИЕ[7] + _СНЯТИЕ[8] * p) * прижим)) / _СНЯТИЕ[5], 0.0, None)
        сила = за_шаг * max(0.0, 1.0 - впитано / ёмкость)
        if сила <= 0:
            break
        доля = 1.0 - np.exp(-сила * касание)
        for с in слои:
            снять = _сырое(с, где, _СНЯТИЕ[0]) * доля
            if снять.any():
                впитано += float(снять.sum())
                _убрать(с, где, снять)


def _окно(холст, x, y, d, м):
    """Окно холста радиусом м px у точки (x, y) хода d: срезы, координаты вдоль и поперёк хода; None — вне холста."""
    ix, iy = int(round(x)) - холст.x0, int(round(y)) - холст.y0
    ca, cb, da, db = max(iy - м, 0), min(iy + м + 1, холст.высота), max(ix - м, 0), min(ix + м + 1, холст.ширина)
    if ca >= cb or da >= db:
        return None
    Y, X = np.mgrid[ca:cb, da:db].astype(np.float64)
    dx, dy = X + холст.x0 - x, Y + холст.y0 - y
    return (slice(ca, cb), slice(da, db)), dx * d[0] + dy * d[1], -dx * d[1] + dy * d[0]


def _горб(t, s):
    """Сечение горба масла полушириной s (px) по t (px от его середины): 1 - (t/s)², вне — 0."""
    return зажать(1.0 - (t / np.maximum(s, 1e-6)) ** 2, 0.0, 1.0)


def _вдоль_соседа(вдоль, поперёк, путь, d, i, j, сдвиг):
    """Дл-2б: координата вдоль хода от кромки шага j у пикселей окна шага i (`вдоль`, `поперёк` — от кромки шага i);
    нет шага j (конец пути) — `вдоль + сдвиг`, как на прямом."""
    if j < 0 or j >= len(путь):
        return вдоль + сдвиг
    dx = вдоль * d[i, 0] - поперёк * d[i, 1] + (путь[i, 0] - путь[j, 0])
    dy = вдоль * d[i, 1] + поперёк * d[i, 0] + (путь[i, 1] - путь[j, 1])
    return dx * d[j, 0] + dy * d[j, 1]


def _от_пути(вдоль, поперёк, путь, d, i, j):
    """Дл-2в: расстояние от пикселей окна шага i до пути середины кромки на половине шага от шага i к шагу j (отрезок
    от точки шага i до середины между i и j). Пиксель, который кромка проходит на этой половине, в миг прохода лежит
    на ней на этом расстоянии от её середины (± четверть шага) — дальше полуширины кромка до него не достаёт, как бы
    она ни повернулась. None — нет шага j (конец пути)."""
    if j < 0 or j >= len(путь):
        return None
    ex, ey = 0.5 * (путь[j, 0] - путь[i, 0]), 0.5 * (путь[j, 1] - путь[i, 1])
    qx = вдоль * d[i, 0] - поперёк * d[i, 1]
    qy = вдоль * d[i, 1] + поперёк * d[i, 0]
    t = зажать((qx * ex + qy * ey) / max(ex * ex + ey * ey, 1e-18), 0.0, 1.0)
    return np.hypot(qx - t * ex, qy - t * ey)


def _доля_поперёк(от_пути, W2):
    """Дл-2в: доля пикселя, до которой кромка полуширины W2 достаёт с пути своей середины, — `от_пути` px от центра
    пикселя до пути (`_от_пути`). Пиксель — квадрат в 1 px: ближняя к пути половина на 0,5 px ближе центра, а путь
    берётся на всей половине шага, хотя в миг прохода пикселя середина кромки — в одной её точке, — поэтому доля на
    0,5 px шире, чем `поперёк_доля` в `скребок`: на прямом и на дуге не меньше её (граница — та же доля под кромкой
    шага), на повороте режет только пиксели дальше полуширины. None — 1 (конец пути)."""
    return 1.0 if от_пути is None else зажать(W2 + 1.0 - от_пути, 0.0, 1.0)


def _перекрытие(а, б):
    """Перекрытие полосы [а, б] (б ≥ а, px от середины пикселя вдоль хода) с пикселем [−0,5; 0,5]."""
    return зажать(np.minimum(б, 0.5) - np.maximum(а, -0.5), 0.0, 1.0)


def скребок(холст, точки, ширина, сид, слои):
    """Снять сырую краску скребком по пути `точки`: кромка шириной `ширина` px поперёк хода.

    Снятое копится валом перед кромкой там, где снято: вал — сечения по местам кромки (1 px), у каждого свой объём и
    свои краски. Вал растекается вдоль кромки от высокого к низкому и сползает к одному концу (кромку держат не ровно).
    Масло — паста с пределом текучести: у конца кромки вал течёт наружу, только когда его сечение выше предела, —
    вал, что снял мало, не выдавливается вовсе; подсохшее масло (вал суше точки студня) не течёт совсем. Выдавленное
    ложится валиком горбом той крутизны, что держит масло: полуширина — от объёма порции (больше — шире и выше),
    краски — полосами по местам вала, откуда пришли: крайнее у конца ложится дальше. На подъёме вал остаётся комом:
    каждое место — шапкой по своему объёму.

    Дл-2: кромка снимает по покрытию пикселя ходом — сколько площади пикселя кромка прошла за проход (за шаг — полоса
    в шаг пути поперёк хода, по краям кромки — доля пикселя под ней), а не произведением долей шагов: пройденный
    целиком пиксель снят до грунта, где бы ни лёг ход относительно сетки px (ход не на целом px и косой оставляли
    плёнку: доли шагов не сходятся к нулю). Снято к концу прохода — доля покрытия, умноженная на прижим кромки.
    Проход — шаги подряд, пока кромка касается пикселя: вернувшись на него позже, кромка снимает заново.
    Дл-2б: полоса шага на месте пикселя — от средней линии кромок шагов i−1, i до средней линии i, i+1 (у соседа
    граница та же), а не полоса в шаг пути по середине кромки: на дуге и у вершины ломаной внешний край кромки за шаг
    проходит больше шага пути — полосы смыкаются без щелей, вся кромка снимает до грунта.
    Дл-2в: средняя линия — прямая, а кромка — отрезок: половина полосы шага снимает пиксель только в полуширине кромки
    от пути её середины на этой половине шага — на крутом повороте и ходе туда-обратно кромка не снимает впереди
    вершины, где её не было; след кончается у вершины скруглением в полуширину кромки.
    Журнал прежней физики (`холст._скребок_прежний`, ставит повтор) — прежним счётом, бит в бит."""
    путь, d = _шагом(точки, 0.5)
    по_покрытию = not getattr(холст, '_скребок_прежний', False)
    rng = np.random.default_rng([int(сид), 812])
    W2 = ширина / 2.0
    nb = max(2, int(np.ceil(ширина)))
    шб = ширина / nb                                         # ширина места вала вдоль кромки, px
    крен = float(зажать(_СКРЕБОК[0] * rng.standard_normal(), -0.45, 0.45))
    κ, предел, растёк, течь, гель = _СКРЕБОК[2], _СКРЕБОК[3] * шб, _СКРЕБОК[4], _СКРЕБОК[5], _СКРЕБОК[7]
    s_max = max(1.0, _СКРЕБОК[6] * ширина)
    L = len(слои)
    вал = np.zeros((L, nb))                                  # объём вала по слоям и местам кромки, h·px²
    вал_кс = np.zeros((L, nb, 24))                           # K/S · объём
    вал_вл = np.zeros(nb)                                    # влажность · объём (все слои)
    м = int(np.ceil(W2 + 2.0 * s_max + 2.0))
    if по_покрытию:
        # покрытие пикселей проходом — в рамке хода; шаг пути (у `_шагом` — не длиннее 0,5 px), у точки — 1 px
        h = float(np.hypot(*np.diff(путь[:, :2], axis=0).T).mean()) if len(путь) > 1 else 0.0
        h = h if h > 1e-9 else 1.0
        ра, рб = int(np.floor(путь[:, 1].min())) - холст.y0 - м, int(np.ceil(путь[:, 1].max())) - холст.y0 + м + 1
        рв, рг = int(np.floor(путь[:, 0].min())) - холст.x0 - м, int(np.ceil(путь[:, 0].max())) - холст.x0 + м + 1
        ра, рв = max(ра, 0), max(рв, 0)
        рб, рг = max(min(рб, холст.высота), ра), max(min(рг, холст.ширина), рв)
        покрыто = np.zeros((рб - ра, рг - рв))
        последний = np.full((рб - ра, рг - рв), -(1 << 30), dtype=np.int64)
    for i, (x, y, p) in enumerate(путь):
        if p <= 0.02:
            continue
        о = _окно(холст, x, y, d[i], м)
        if о is None:
            continue
        где, вдоль, поперёк = о
        шаг_вдоль = зажать(1.0 - np.abs(вдоль) / 0.75, 0.0, 1.0)
        поперёк_доля = зажать(W2 + 0.5 - np.abs(поперёк), 0.0, 1.0)
        прижим = min(p / 0.3, 1.0)
        if по_покрытию:
            # за шаг кромка проходит по пикселю полосу: доля пикселя под ней — перекрытие полосы с пикселем вдоль хода,
            # по ширине — доля под кромкой у её концов; за проход доли складываются в покрытие
            # (ровный ход — ровно 1). Снято к шагу — прижим · покрытие от лежавшего в начале прохода: доля
            # оставшегося сырого, что снимает этот шаг, — 1 − (1 − прижим·c₂)/(1 − прижим·c₁)
            лг = (slice(где[0].start - ра, где[0].stop - ра), slice(где[1].start - рв, где[1].stop - рв))
            # Дл-2б: полоса шага — между серединами кромки на шагах i−1, i и i, i+1 на месте самого пикселя: граница
            # с соседним шагом — средняя линия (a_i + a_j)/2 = 0 (a_j — вдоль от кромки шага j), у соседа та же; полосы
            # смыкаются без щелей и на дуге, и у вершины ломаной (внешний край за шаг проходит больше h). На прямом —
            # полоса в h, как было
            до = _вдоль_соседа(вдоль, поперёк, путь, d, i, i - 1, h)
            после = _вдоль_соседа(вдоль, поперёк, путь, d, i, i + 1, -h)
            г1, г2 = -0.5 * (до + вдоль), -0.5 * (вдоль + после)   # границы полосы от середины пикселя
            # Дл-2в: средняя линия — линия кромки посередине между шагами, а сама кромка — отрезок шириной W, не прямая:
            # полоса шага — две половины, от кромки шага до средней линии с каждым соседом, и половина снимает пиксель
            # только в пределах полуширины от пути середины кромки на этой половине шага (`_от_пути`). На крутом
            # повороте средняя линия уходит за вершину, но пиксель впереди вершины далеко от пути — кромка его не
            # касалась. Доля поперёк — меньшая из доли под кромкой шага и под кромкой на половине, не их произведение:
            # на прямом это та же доля под кромкой
            лев, прав = np.minimum(г1, г2), np.maximum(г1, г2)
            гк = зажать(-вдоль, лев, прав)                        # кромка шага (перевёрнутая полоса — вне её)
            до_доля = _доля_поперёк(_от_пути(вдоль, поперёк, путь, d, i, i - 1), W2)
            после_доля = _доля_поперёк(_от_пути(вдоль, поперёк, путь, d, i, i + 1), W2)
            прям = г1 <= г2
            вне = (-вдоль < лев) | (-вдоль > прав)
            обе = np.minimum(до_доля, после_доля)
            доля_лев = np.where(вне, обе, np.where(прям, до_доля, после_доля))
            доля_прав = np.where(вне, обе, np.where(прям, после_доля, до_доля))
            дc = _перекрытие(лев, гк) * np.minimum(доля_лев, поперёк_доля) + _перекрытие(гк, прав) * np.minimum(доля_прав, поперёк_доля)
            есть = дc > 0
            c1 = np.where(i - последний[лг] > 2, 0.0, покрыто[лг])        # кромка ушла и вернулась — новый проход
            c2 = np.minimum(c1 + дc, 1.0)
            кромка = np.where(есть, зажать(1.0 - (1.0 - прижим * c2) / np.maximum(1.0 - прижим * c1, 1e-12), 0.0, 1.0), 0.0)
            покрыто[лг] = np.where(есть, c2, c1)
            последний[лг] = np.where(есть, i, последний[лг])
        else:
            # прежнее (до Дл-2): кромка — полоса в шаг пути, по ширине — до концов с мягким краем в 1 px; за шаг
            # снимает долю лежащего
            кромка = шаг_вдоль * поперёк_доля * прижим
            есть = кромка > 0
        место = зажать(((поперёк + W2) / шб).astype(np.int64), 0, nb - 1)
        for k, с in enumerate(слои):
            снять = _сырое(с, где, _СКРЕБОК[1]) * кромка
            if not снять.any():
                continue
            кс = в_кс(с.цвет[где][есть].astype(np.float64)) * снять[есть][:, None]
            вал[k] += np.bincount(место[есть], снять[есть], nb)
            вал_вл[:] += np.bincount(место[есть], (снять * с.влажность[где])[есть], nb)
            for q in range(24):
                вал_кс[k, :, q] += np.bincount(место[есть], кс[:, q], nb)
            _убрать(с, где, снять)
        T = вал.sum(0)
        if T.max() <= 0:
            continue
        # вал растекается вдоль кромки от высокого сечения к низкому и сползает по крену; переносится тем, что лежит в месте
        поток = растёк * (T[:-1] - T[1:]) + крен * np.where(крен > 0, T[:-1], T[1:])     # из места j в j+1 (минус — назад)
        поток = зажать(поток, -0.45 * T[1:], 0.45 * T[:-1])
        из_левого = зажать(поток, 0, None) / np.maximum(T[:-1], 1e-12)
        из_правого = зажать(-поток, 0, None) / np.maximum(T[1:], 1e-12)
        for м_ in (вал, вал_кс, вал_вл[None]):
            а = м_[:, :-1] * (из_левого[:, None] if м_.ndim == 3 else из_левого)
            б = м_[:, 1:] * (из_правого[:, None] if м_.ndim == 3 else из_правого)
            м_[:, :-1] += б - а
            м_[:, 1:] += а - б
        # у конца кромки вал держится, пока сечение не выше предела текучести; сверх него масло течёт за конец — тем
        # быстрее, чем больше превышение (паста Бингама). Подсыхающее масло густеет: предел растёт как квадрат обратной
        # доли влажности вала над точкой студня `_СКРЕБОК[7]`; вал из масла, схватившегося до студня, не течёт вовсе —
        # липким комом едет перед кромкой до подъёма. Конец кормится тем, что кромка сняла у него: где краски было
        # больше, течёт больше
        for сторона, j0, шаг_j in ((0, 0, 1), (1, nb - 1, -1)):
            Tк = вал[:, j0].sum()
            вл = float(вал_вл[j0] / max(Tк, 1e-12))
            тек = (вл - гель) / (1.0 - гель)
            if тек <= 0.0 or Tк <= предел / тек ** 2:
                continue
            пред = предел / тек ** 2
            if Tк <= пред:
                continue
            # течёт нависшее: у каждого места от конца внутрь — доля превышения, пока превышение есть
            порции = []
            for j in range(j0, j0 + шаг_j * nb, шаг_j):
                Tj = вал[:, j].sum()
                if Tj <= пред:
                    break
                доля = течь * (1.0 - пред / Tj)
                порции.append((вал[:, j] * доля, вал_кс[:, j] * доля))
                вал[:, j] *= 1.0 - доля
                вал_кс[:, j] *= 1.0 - доля
                вал_вл[j] *= 1.0 - доля
            V = sum(float(п[0].sum()) for п in порции)
            # валик — горб крутизны κ: площадь сечения A = V / шаг пути -> полуширина s = sqrt(3A / (4κ)); лежит
            # от конца кромки наружу
            s = min(np.sqrt(3.0 * (V / 0.5) / (4.0 * κ)), s_max)
            t = (поперёк if сторона == 1 else -поперёк) - W2         # px за концом кромки
            форма = _горб(t - s, s) * шаг_вдоль
            сумма = float(форма.sum())
            if V <= 0 or сумма <= 0:
                continue
            # полосы: доля объёма валика от внешнего края внутрь — по порядку порций
            порядок = np.argsort(-t, axis=None)
            накоп = np.empty(форма.size)
            накоп[порядок] = np.cumsum(форма.ravel()[порядок]) / сумма
            накоп = накоп.reshape(форма.shape)
            граница = 0.0
            for объём, кс in порции:
                доля_п = float(объём.sum()) / V
                if доля_п <= 0:
                    continue
                вес = форма * ((накоп > граница - 1e-9) & (накоп <= граница + доля_п + 1e-9))
                граница += доля_п
                св = float(вес.sum())
                if св <= 0:
                    вес, св = форма, сумма
                for k, с in enumerate(слои):
                    if объём[k] > 0:
                        _положить(с, где, вес / св * объём[k], кс[k] / объём[k])
    # на подъёме вал остаётся у кромки: каждое место вала оседает шапкой той же крутизны κ (радиус — по своему
    # объёму) перед кромкой; шапки сливаются в ком, у концов кромки он круглый, как оплывшее масло
    if вал.sum() > 0:
        живые = np.nonzero(путь[:, 2] > 0.02)[0]
        i = int(живые[-1]) if len(живые) else len(путь) - 1
        T = вал.sum(0)
        s = np.minimum((2.0 * T / (np.pi * κ)) ** (1.0 / 3.0), s_max)
        о = _окно(холст, путь[i, 0], путь[i, 1], d[i], int(np.ceil(W2 + 2.0 * s.max() + 2.0)))
        if о is not None:
            где, вдоль, поперёк = о
            for jм in np.nonzero(T > 0)[0]:
                вес = _горб(np.hypot(вдоль - s[jм], поперёк - (-W2 + (jм + 0.5) * шб)), s[jм])
                св = float(вес.sum())
                if св <= 0:
                    continue
                for k, с in enumerate(слои):
                    if вал[k, jм] > 0:
                        _положить(с, где, вес / св * вал[k, jм], вал_кс[k, jм] / вал[k, jм])


def _положить_в_рамке(с, где, dh, кс):
    """`_положить` только в рамке пикселей, куда краска ложится (dh > 0): итог тот же, счёт — по малому куску."""
    ys, xs = np.nonzero(dh > 0)
    if not len(ys):
        return
    ya, yb, xa, xb = int(ys.min()), int(ys.max()) + 1, int(xs.min()), int(xs.max()) + 1
    _положить(с, (slice(где[0].start + ya, где[0].start + yb), slice(где[1].start + xa, где[1].start + xb)), dh[ya:yb, xa:xb], кс)


class Процарапано:
    """Ответ `х.снять(…, 'черенок')`: `прямоугольник` (x0, y0, x1, y1) хода с валиками; `длина` — px пути, где конец
    шёл в краске; `до_дна` — доля этой длины, где под серединой конца сырого не осталось (открыт нижний слой или
    грунт); `осталось` — сырая плёнка под серединой конца после прохода, мм (медиана по ходу; 0 — дно открыто);
    `на_твёрдом` — доля этой длины, где нажим посадил конец на твёрдое (при ней плёнка под концом — краска в ямках
    твёрдого: зерно, рельеф сухого слоя);
    `ширина` — поперечник борозды у поверхности краски, px (медиана по ходу); `глубже` — самая глубокая
    борозда, мм; `сдвинуто` — объём раздвинутой краски, h·px² (остался на холсте валиками), `мм3` — он же в мм³;
    `почему` — слово, если конец краски не тронул."""
    __slots__ = ('прямоугольник', 'длина', 'до_дна', 'осталось', 'на_твёрдом', 'ширина', 'глубже', 'сдвинуто', 'мм3', 'почему')

    def __init__(self, **поля):
        for имя in self.__slots__:
            setattr(self, имя, поля.get(имя))

    def __bool__(self):
        return bool(self.сдвинуто)

    def __repr__(self):
        if not self.сдвинуто:
            return f'Процарапано(ничего: {self.почему})'
        return (f'Процарапано(борозда {self.длина:.0f} px, шириной {self.ширина:.1f} px, до дна {self.до_дна:.0%} пути'
                + ('' if self.осталось <= 0.004 else f' (конец шёл по верхам твёрдого — зерно, рельеф сухого: в ямках под ним плёнка {self.осталось:.2f} мм)'
                   if self.на_твёрдом > 0.5 else f' (под концом осталась плёнка {self.осталось:.2f} мм: до твёрдого — нажим от {_ЧЕРЕНОК[0]:g})') + ', '
                f'глубже всего {self.глубже:.2f} мм, раздвинуто {self.сдвинуто:.1f} h·px² ({self.мм3:.3f} мм³) — в валиках)')


def черенок(холст, точки, ширина, слои, все=None):
    """Процарапать сырую краску концом черенка по пути `точки` (x, y, нажим, …): `ширина` — поперечник конца, px.

    Конец — полушарие радиуса R = ширина / 2: его поверхность над нижней точкой — R − √(R² − r²). Нижняя точка стоит
    над твёрдым (грунт с зерном, сухая и схватившаяся краска, краска слоёв, что не снимаются) на зазор по нажиму:
    краска — паста, из-под сходящегося с твёрдым конца она выжимается тем труднее, чем тоньше зазор и шире конец
    (зазор — как радиус конца на нажим); с нажима `_ЧЕРЕНОК[0]` плёнка рвётся — конец сел на твёрдое, на его верхи
    под всем полушарием. Всё сырое выше поверхности конца — вал перед ним, по местам поперёк хода. Круглый лоб вала
    не держит: место вала в t от оси уходит к боку на шаг · t / √(a² − t²) (a — радиус касания у поверхности краски),
    у оси — оплывает к соседям. Что дошло до бока, ложится за ним валиком горбом той крутизны, что держит масло
    (как у скребка): где краски было больше, борозда шире и валик выше. На подъёме остаток вала — комом перед концом.
    Объём краски на холсте не меняется: что ушло из борозды, лежит в валиках и коме (кроме ушедшего за край холста)."""
    путь, d = _шагом(точки, 0.5)
    пм = float(холст.px_на_мм or 8.0)
    # ход — ломаная по точкам: направление (куда смотрят бока конца) ведём средним по длине в поперечник конца —
    # у вершины ломаной валик не рвётся зубцом; сам конец идёт по точкам
    окно = 2 * max(2, int(round(ширина))) + 1
    if len(d) > 2:
        dp = np.pad(d, ((окно // 2, окно // 2), (0, 0)), mode='edge')
        d = np.column_stack([np.convolve(dp[:, q], np.ones(окно) / окно, mode='valid') for q in (0, 1)])
        d /= np.maximum(np.hypot(d[:, 0], d[:, 1]), 1e-9)[:, None]
    выс = _ТЕНЬ[0] * пм / 8.0                                # px высоты в единице h
    R = ширина / 2.0
    nb = max(2, int(np.ceil(ширина)))
    шб = ширина / nb
    tj = -R + (np.arange(nb) + 0.5) * шб                     # места вала поперёк хода, px от оси
    κ, растёк = _СКРЕБОК[2] * 8.0 / пм, _СКРЕБОК[4]          # откос масла — h на px холста 8 px/мм: на своём px — по масштабу
    s_max = _ЧЕРЕНОК[3] * ширина + 0.5 * пм                  # валик не шире этого за боком конца, px
    tt = (np.arange(int(np.ceil((R + s_max) / 0.25))) + 0.5) * 0.25
    концы = np.linspace(0.0, R + s_max, 96)
    все = слои if все is None else все
    L = len(все)
    вал, вал_кс = np.zeros((L, nb)), np.zeros((L, nb, 24))
    м = int(np.ceil(R + s_max + 2.0))
    a_бок = [min(R, 1.0), min(R, 1.0)]                       # радиус касания слева и справа, px
    длина = дно = твёрдо = сдвинуто = глубже = 0.0
    ширины, плёнки = [], []
    x0 = y0 = np.inf
    x1 = y1 = -np.inf
    последний = None

    def ком(i):
        """Остаток вала — комом перед концом: каждое место оседает шапкой крутизны κ по своему объёму."""
        T = вал.sum(0)
        if T.sum() <= 0:
            return
        s = np.minimum((2.0 * T / (np.pi * κ)) ** (1.0 / 3.0), s_max)
        о = _окно(холст, путь[i, 0], путь[i, 1], d[i], int(np.ceil(R + 2.0 * s.max() + 2.0)))
        if о is not None:
            где, вдоль, поперёк = о
            a = max(a_бок)
            for j in np.nonzero(T > 0)[0]:
                вес = _горб(np.hypot(вдоль - (np.sqrt(max(a * a - tj[j] ** 2, 0.0)) + s[j]), поперёк - tj[j]), s[j])
                св = float(вес.sum())
                if св <= 0:
                    continue
                for k, с in enumerate(все):
                    if вал[k, j] > 0:
                        _положить_в_рамке(с, где, вес / св * вал[k, j], вал_кс[k, j] / вал[k, j])
        вал[:] = 0.0
        вал_кс[:] = 0.0

    for i, (x, y, p) in enumerate(путь):
        if p <= _ЧЕРЕНОК[4]:
            if последний is not None:                        # конец поднят: вал остался, где шёл
                ком(последний)
                последний = None
            continue
        о = _окно(холст, x, y, d[i], м)
        if о is None:
            continue
        где, вдоль, поперёк = о
        r2 = вдоль * вдоль + поперёк * поперёк
        под = r2 < R * R
        if not под.any():
            continue
        дуга = np.where(под, (R - np.sqrt(np.maximum(R * R - r2, 0.0))) / выс, np.inf)
        # сверху вниз: сырое слоя конец раздвигает, пока над ним нет твёрдого — сухой доли слоя выше или чужого слоя
        h = [np.asarray(с.толщина[где], np.float64) for с in все]
        открыто = np.ones(r2.shape, bool)
        сыр = []
        for k, с in enumerate(все):
            w = _сырое(с, где, 0.0) * открыто if any(с is q for q in слои) else np.zeros(r2.shape)
            сыр.append(w)
            открыто &= (h[k] - w) <= _ЧЕРЕНОК[5]
        берётся = sum(сыр)
        S = sum(h)
        зерно = getattr(холст, '_зерно', None)
        if зерно is not None:
            S = S + холст._высота_зерна(где[0].start, где[0].stop, где[1].start, где[1].stop)
        F = S - берётся                                      # твёрдое: грунт с зерном и всё, чего конец не берёт
        if not (берётся[под] > 0).any():
            continue
        зазор = 0.0 if p >= _ЧЕРЕНОК[0] else _ЧЕРЕНОК[1] * (R / пм / 0.5) * (_ЧЕРЕНОК[0] / p - 1.0)
        z0 = float((F - дуга)[под].max()) + зазор
        # на твёрдом без краски под ним (грунт) остаётся тон пигмента, вошедшего в грунт, — как под скребком; сухая
        # краска не впитывает: с неё конец сдвигает всё
        тон = np.where(S - берётся - (0.0 if зерно is None else S - sum(h)) > 1e-4, 0.0, _СКРЕБОК[1])
        # плёнку тоньше зерна пигмента твёрдый конец над твёрдым не оставляет: стирает дочиста (кромка борозды резкая)
        над = z0 + дуга
        над = np.where(над - F < _ЧЕРЕНОК[2], F, над)
        лишнее = np.where(под, np.minimum(np.maximum(S - над, 0.0), np.maximum(берётся - тон, 0.0)), 0.0)
        есть = лишнее > 0
        if not есть.any():
            continue
        первый = последний is None
        последний = i
        длина += 0.5
        твёрдо += 0.5 * (p >= _ЧЕРЕНОК[0])
        iy, ix = np.unravel_index(np.argmin(r2), r2.shape)
        плёнки.append(float(берётся[iy, ix] - лишнее[iy, ix]))
        if плёнки[-1] <= тон[iy, ix] + 1e-6:
            дно += 0.5
        сдвинуто += float(лишнее.sum())
        глубже = max(глубже, float(лишнее.max()))
        for сторона, знак in ((0, -1.0), (1, 1.0)):
            # радиус касания — по краске, в которую лоб входит (впереди оси): позади — свой валик у бока
            на_боку = есть & (знак * поперёк > 0) & ((вдоль > 2.0) | первый)
            if на_боку.any():
                a = float(min(np.abs(поперёк[на_боку]).max() + 0.5, R))
                a_бок[сторона] = a if первый else 0.5 * (a_бок[сторона] + a)
        ширины.append(a_бок[0] + a_бок[1])
        место = зажать(((поперёк + R) / шб).astype(np.int64), 0, nb - 1)
        остаток = лишнее.copy()
        for k, с in enumerate(все):
            снять = np.minimum(остаток, сыр[k])
            if not (снять > 0).any():
                continue
            остаток = остаток - снять
            тут = снять > 0
            кс = в_кс(с.цвет[где][тут].astype(np.float64)) * снять[тут][:, None]
            вал[k] += np.bincount(место[тут], снять[тут], nb)
            for q in range(24):
                вал_кс[k, :, q] += np.bincount(место[тут], кс[:, q], nb)
            if с.пропуск is not None:                         # не кроющая плёнка тоньше — светлее (как под ножом)
                доля = np.where(h[k] > 1e-6, зажать((h[k] - снять) / np.maximum(h[k], 1e-6), 0.0, 1.0), 1.0)
                с.пропуск[где] = np.power(np.asarray(с.пропуск[где], np.float64), доля[..., None]).astype(np.float32)
            _убрать(с, где, снять)
        # вал у оси оплывает к соседним местам (от высокого сечения к низкому)
        T = вал.sum(0)
        поток = зажать(растёк * (T[:-1] - T[1:]), -0.45 * T[1:], 0.45 * T[:-1])
        из_левого = зажать(поток, 0, None) / np.maximum(T[:-1], 1e-12)
        из_правого = зажать(-поток, 0, None) / np.maximum(T[1:], 1e-12)
        for м_ in (вал, вал_кс):
            а = м_[:, :-1] * (из_левого[:, None] if м_.ndim == 3 else из_левого)
            б = м_[:, 1:] * (из_правого[:, None] if м_.ndim == 3 else из_правого)
            м_[:, :-1] += б - а
            м_[:, 1:] += а - б
        # круглый лоб гонит вал к бокам: место в t от оси за шаг уходит на шаг · |t| / √(a² − t²); за радиусом касания
        # лоб вала не держит вовсе — всё уходит за бок
        шаг_вдоль = зажать(1.0 - np.abs(вдоль) / 1.5, 0.0, 1.0)   # на внешней стороне дуги шаги расходятся: полоса шире шага
        for сторона, знак in ((0, -1.0), (1, 1.0)):
            a = a_бок[сторона]
            места = [j for j in (range(nb // 2 - 1, -1, -1) if сторона == 0 else range(nb - nb // 2, nb))]
            if nb % 2 and сторона == 1:
                места = [nb // 2] + места                     # место на оси (нечётное число мест) — к правому боку
            ушло, ушло_кс = np.zeros(L), np.zeros((L, 24))
            for j in места:                                   # от оси к боку: пришедшее из соседа идёт дальше тем же шагом
                вал[:, j] += ушло
                вал_кс[:, j] += ушло_кс
                t = abs(tj[j])
                доля = 1.0 if t >= a else min(0.5 * t / (np.sqrt(a * a - t * t) * шб + 1e-9), 1.0)
                ушло, ушло_кс = вал[:, j] * доля, вал_кс[:, j] * доля
                вал[:, j] -= ушло
                вал_кс[:, j] -= ушло_кс
            V = float(ушло.sum())
            if V <= 0:
                continue
            # валик привален к боку конца: изнутри его держит круглый бок (просвет под ним над краской — c(t)), снаружи —
            # откос, что держит масло (κ, h на px); сечение A = V / шаг пути — докуда откос дошёл, t_к, по площади
            c = np.where(tt < R, (R - np.sqrt(np.maximum(R * R - tt * tt, 0.0)) - (R - np.sqrt(max(R * R - a * a, 0.0)))) / выс, np.inf)
            c = np.where(tt >= a, c, 0.0)
            площадь = (зажать(np.minimum(c[None, :], κ * (концы[:, None] - tt[None, :])), 0.0, None)).sum(1) * (tt[1] - tt[0])
            t_к = float(np.interp(V / 0.5, площадь, концы))
            t = знак * поперёк
            tc = зажать(t, 0.0, R)
            просвет = np.where(t < R, (R - np.sqrt(R * R - tc * tc) - (R - np.sqrt(max(R * R - a * a, 0.0)))) / выс, np.inf)
            форма = зажать(np.minimum(просвет, κ * (t_к - t)), 0.0, None) * (t >= a) * шаг_вдоль
            сумма = float(форма.sum())
            if сумма <= 0:                                    # валик ушёл за край холста — с ним и краска
                continue
            for k, с in enumerate(все):
                if ушло[k] > 0:
                    _положить_в_рамке(с, где, форма / сумма * ушло[k], ушло_кс[k] / ушло[k])
        x0, y0 = min(x0, x - м), min(y0, y - м)
        x1, y1 = max(x1, x + м + 1), max(y1, y + м + 1)
    if последний is not None:
        ком(последний)
    if сдвинуто <= 0:
        живые = путь[:, 2] > _ЧЕРЕНОК[4]
        return Процарапано(прямоугольник=None, длина=0.0, до_дна=0.0, осталось=None, на_твёрдом=0.0, ширина=0.0, глубже=0.0, сдвинуто=0.0, мм3=0.0,
                           почему=('нажим 0 по всему ходу: конец над холстом' if not живые.any() else
                                   'под концом сырой краски нет или нажим слаб: конец прошёл над ней (зазор — по нажиму, '
                                   f'на твёрдое конец садится с нажима {_ЧЕРЕНОК[0]:g}); сухое и схватившееся черенок не берёт'))
    return Процарапано(прямоугольник=(int(np.floor(x0)), int(np.floor(y0)), int(np.ceil(x1)), int(np.ceil(y1))),
                       длина=длина, до_дна=дно / max(длина, 1e-9), осталось=float(np.median(плёнки)) * _ТЕНЬ[0] / 8.0, на_твёрдом=твёрдо / max(длина, 1e-9),
                       ширина=float(np.median(ширины)),
                       глубже=глубже * _ТЕНЬ[0] / 8.0, сдвинуто=сдвинуто, мм3=сдвинуто * (_ТЕНЬ[0] / 8.0) / (пм * пм), почему=None)


def снять(холст, точки, инструмент, ширина, сид, слой=None):
    """Снять сырую краску по ходу (К8.4). инструмент — 'тряпка', 'скребок' или 'черенок' (К-14а: краску не снимает,
    а раздвигает в валики; ответ — `Процарапано`); слой — имя слоя или None (все)."""
    if инструмент not in ИНСТРУМЕНТЫ:
        raise ValueError(f'снятие: инструмент — {", ".join(ИНСТРУМЕНТЫ)}, не {инструмент!r}')
    if not ширина > 0:
        raise ValueError('снятие: ширина — больше нуля')
    слои = [с for имя, с in холст.слои.items() if слой is None or имя == слой][::-1]     # сверху вниз
    if not слои:
        return
    холст._до_записи(None)
    if инструмент == 'черенок':                              # чужой слой (при `слой=`) для конца — твёрдое
        return черенок(холст, точки, float(ширина), слои, list(холст.слои.values())[::-1])
    (тряпка if инструмент == 'тряпка' else скребок)(холст, точки, float(ширина), сид, слои)
