"""v4, Сл-1: сколько следа видно на листе — не закрыто слоями выше. Только читает: холст, кисти, сиды и журнал не меняются.

Счёт — тот же, что у `Холст._цвет`: каждый слой выше кладёт свой цвет долей покрытия, а лежащее под ним доходит до глаза
долей `1 − покрытие`; сквозь несколько слоёв — произведением. Берётся по пикселям следа (где меряется и `о.цвет`; у
вытертой — под кистью, где она сняла краску), среднее — `о.видно`. Пропуск некроющей краски (лессировка) не закрывает
и в счёт не идёт, какой бы тёмной она ни была: закрывает только покрытие. Закрыл — слой, что отнял больше всех (счёт сверху вниз, как видит глаз) — `о.закрыл`.
"""
import numpy as np

ПО = 16384             # не больше стольких пикселей следа (у большого — каждый k-й)
ЗАКРЫТ = 0.25          # «закрыт»: видно меньше этой доли следа — подсказка С21
СЛОВО = 0.9            # видно меньше — слово в `print(о)` и имя закрывшего слоя


def под_верхом(х, слой, о, поля, порог):
    """Ответ мазка `о` в слой `слой`, поля его следа: ставит `о.видно` и `о.закрыл`, если слои выше что-то закрыли.
    порог — уровень покрытия, от которого пиксель — след (`ответ.ТЕЛО` от тела)."""
    имена = list(х._слои)
    выше = имена[имена.index(слой) + 1:]
    if not выше:
        return
    гy, гx = х._область(tuple(о))
    где = None
    свет = None                                     # доля света от этого места до глаза: сверху вниз
    отнял = []
    for имя in reversed(выше):
        с = х._слои[имя]
        a = np.asarray(с.покрытие[гy, гx])
        if not a.any():
            continue
        if где is None:
            маска = поля['альфа'] >= порог if о.__dict__['цвет'] is not None else поля['касание'] > 0.5
            if о.__dict__['цвет'] is None and float(поля['снято']) <= 0.0:
                return
            где = np.flatnonzero(маска)
            if not len(где):
                return
            if len(где) > ПО:
                где = где[::-(-len(где) // ПО)]
            свет = np.ones(len(где))
        п = np.clip(a.ravel()[где], 0.0, 1.0)
        отнял.append((float((свет * п).sum()), имя))
        свет = свет * (1.0 - п)
    if где is None:
        return
    видно = round(float(свет.mean()), 4)
    if видно < 1.0:
        о.__dict__['видно'] = видно
        if видно < СЛОВО:
            о.__dict__['закрыл'] = max(отнял, key=lambda p: p[0])[1]


def слово(видно, закрыл):
    """Факт С21 — и в `print(о)`, и в подсказке."""
    return f'видно на листе {видно:.2f} — закрыл слой «{закрыл}»'
