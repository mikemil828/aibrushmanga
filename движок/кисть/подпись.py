"""Подпись инструмента (п. 9): «кисть, нагрузка → числа», снятые с положенного пробного мазка.

Числа меряются с картинки, а не берутся из пресета, и той же меркой меряется образец:
  шаг_борозд(серое, угол)        шаг борозд поперёк хода, px — длина поперечных профилей на число борозд в них;
  ширина_кромки(профили)          резкость кромки — ширина перехода 10–90 % от фона к краске, px;
  просвечивание(цвет, краска, низ) доля нижнего слоя в цвете следа (0 — кроет, 1 — краски нет).
Пробный мазок: прямой, поперёк холста, длиной 8 ширин, тёмная краска по светлому грунту, нажим 0,85.
Шаг борозд — со светом (как на фото образца), кромка и просвечивание — без света: свет у кромки даёт фаску
(блик и тень), это рельеф, а не переход цвета."""
import numpy as np

from .краска import из_линейного, в_линейный
from .путь import путь_с_нажимом

_ЯРКОСТЬ = np.array([0.2126, 0.7152, 0.0722])
ГРУНТ = (200, 190, 170)
КРАСКА = (70, 60, 45)


def серое(картинка_лин):
    """Линейная картинка (В, Ш, 3) -> светлота sRGB 0..255 (как у фото)."""
    return (из_линейного(картинка_лин) * 255.0) @ _ЯРКОСТЬ


def угол_хода(серое_):
    """Главное направление борозд участка (структурный тензор), радианы, по ходу мазка."""
    gy, gx = np.gradient(np.asarray(серое_, np.float64))
    return 0.5 * np.arctan2(2.0 * (gx * gy).sum(), (gx * gx).sum() - (gy * gy).sum()) + np.pi / 2


def _выборка(a, xs, ys):
    """Билинейная выборка a в точках (xs, ys)."""
    В, Ш = a.shape
    xs = np.clip(xs, 0, Ш - 1.001)
    ys = np.clip(ys, 0, В - 1.001)
    x0, y0 = np.floor(xs).astype(int), np.floor(ys).astype(int)
    fx, fy = xs - x0, ys - y0
    return (a[y0, x0] * (1 - fx) * (1 - fy) + a[y0, x0 + 1] * fx * (1 - fy)
            + a[y0 + 1, x0] * (1 - fx) * fy + a[y0 + 1, x0 + 1] * fx * fy)


def поперечные(серое_, угол, полу=None, шаг_вдоль=2.0):
    """Профили поперёк хода (строка — один профиль, шаг 0,5 px) из середины участка."""
    a = np.asarray(серое_, np.float64)
    В, Ш = a.shape
    полу = полу if полу is not None else 0.45 * min(В, Ш)
    tx, ty = np.cos(угол), np.sin(угол)
    nx, ny = -ty, tx
    cx, cy = (Ш - 1) / 2.0, (В - 1) / 2.0
    s = np.arange(-полу, полу + 1e-9, шаг_вдоль)
    t = np.arange(-полу, полу + 1e-9, 0.5)
    xs = cx + s[:, None] * tx + t[None, :] * nx
    ys = cy + s[:, None] * ty + t[None, :] * ny
    return _выборка(a, xs, ys)


def _детали(профили):
    """Мелкая деталь профилей (шаг 0,5 px): без плавной части (квадратичная подгонка), шум пикселя сглажен (σ 0,35 px)."""
    п = np.asarray(профили, np.float64)
    t = np.linspace(-1.0, 1.0, п.shape[1])
    V = np.vstack([np.ones_like(t), t, t * t]).T
    д = п - (np.linalg.lstsq(V, п.T, rcond=None)[0].T @ V.T)
    g = np.exp(-0.5 * (np.arange(-3, 4) * 0.5 / 0.35) ** 2)
    g /= g.sum()
    return np.array([np.convolve(r, g, 'same') for r in д])[:, 3:-3]


def шаг_борозд(серое_=None, угол=None, полу=None, профили=None, порог=0.3):
    """Шаг борозд поперёк хода, px: длина профилей, делённая на число борозд в них. Борозда — местный минимум мелкой
    детали глубже `порог` её σ (у профиля своя σ: мерка не зависит от контраста). Профили поперёк хода, шаг 0,5 px:
    свои (`профили`) или из середины участка `серое_` по углу хода (None — угол по структурному тензору).
    None — борозд нет."""
    if профили is None:
        if угол is None:
            угол = угол_хода(серое_)
        профили = поперечные(серое_, угол, полу)
    n, L = 0, 0.0
    for r in _детали(профили):
        s = r.std()
        n += int(((r[1:-1] < r[:-2]) & (r[1:-1] <= r[2:]) & (r[1:-1] < -порог * s)).sum())
        L += (len(r) - 1) * 0.5
    return L / n if n else None


def ширина_кромки(профили, низ=0.1, верх=0.9):
    """Ширина перехода, px: профили (строка — от фона к краске, шаг 1 px). Уровень фона — медиана первых 3 px,
    краски — медиана последней трети; переход — от первой доли «низ» до первой доли «верх». Среднее по профилям
    (не медиана: ширины у одного мазка двугорбые — резкий бок и рваный, медиана прыгала между горбами)."""
    ш = []
    for p in np.asarray(профили, np.float64):
        ф, к = np.median(p[:3]), np.median(p[2 * len(p) // 3:])
        if abs(к - ф) < 8.0:                                   # нет перепада — нечего мерить
            continue
        q = (p - ф) / (к - ф)
        def где(уровень):
            i = int(np.argmax(q >= уровень))
            if q[i] < уровень:
                return None
            return i - 1 + (уровень - q[i - 1]) / max(q[i] - q[i - 1], 1e-9) if i > 0 else 0.0
        a, b = где(низ), где(верх)
        if a is not None and b is not None and b >= a:
            ш.append(b - a)
    return float(np.mean(ш)) if ш else None


def просвечивание(цвет_лин, краска_лин, низ_лин):
    """Доля нижнего слоя в цвете следа: проекция (цвет − краска) на (низ − краска), линейный RGB; среднее."""
    к, н = np.asarray(краска_лин, np.float64), np.asarray(низ_лин, np.float64)
    д = н - к
    t = ((np.asarray(цвет_лин, np.float64).reshape(-1, 3) - к) @ д) / float(д @ д)
    return float(np.clip(t, 0.0, 1.0).mean())


def пробный_мазок(кисть, нагрузка=None, сид=1, px_на_мм=None):
    """Положить пробный мазок подписи; ответ — (холст, ось y, x0, x1, ширина кисти px)."""
    from .холст import Холст
    к = кисть.в_пикселях(px_на_мм).копия()
    к.вытереть()
    W = float(к.ширина)
    L = 8.0 * W
    х = Холст(int(L + 4 * W), int(4 * W), грунт=ГРУНТ, px_на_мм=px_на_мм)
    y = 2.0 * W
    ctrl = np.array([[2 * W, y], [2 * W + L / 2, y], [2 * W + L, y]])
    точки = путь_с_нажимом(ctrl, W, np.random.default_rng(сид), нажим=0.85)
    х.мазок(точки, КРАСКА, к, слой='проба', сид=сид, нагрузка=нагрузка)
    return х, y, 2 * W, 2 * W + L, W


def _подпись_мазка(кисть, нагрузка, сид, px_на_мм):
    х, y, x0, x1, W = пробный_мазок(кисть, нагрузка, сид, px_на_мм)
    xa, xb = int(x0 + 0.2 * (x1 - x0)), int(x0 + 0.8 * (x1 - x0))
    со_светом = серое(х.картинка(свет=True))
    без = х.картинка(свет=False)
    сер_без = серое(без)
    yi = int(round(y))
    # профили поперёк хода — столбцы ±0,42 ширины от оси, на сетке 0,5 px
    h = 0.42 * W
    ys = np.arange(y - h, y + h + 1e-9, 0.5)
    y0 = int(np.floor(ys[0]))
    кус = со_светом[y0:int(np.ceil(ys[-1])) + 2, xa:xb]
    проф = np.array([np.interp(ys - y0, np.arange(кус.shape[0]), кус[:, j]) for j in range(кус.shape[1])])
    # кромка: столбцы через 2 px, профиль от фона (за 0,9 ширины от оси) к оси, оба бока
    д = int(0.9 * W)
    верх = сер_без[yi - д:yi + 1, xa:xb:2].T
    низ_ = сер_без[yi:yi + д + 1, xa:xb:2].T[:, ::-1]
    h2 = max(int(0.25 * W), 2)
    return (проф, np.vstack([верх, низ_]),
            просвечивание(без[yi - h2:yi + h2 + 1, xa:xb], в_линейный(КРАСКА), в_линейный(ГРУНТ)))


def подпись(кисть, нагрузка=None, сид=1, px_на_мм=None, мазков=12):
    """Подпись инструмента: {'шаг_борозд', 'кромка', 'просвечивание'} (px, px, доля); с px_на_мм — и в мм.
    Пробных мазков `мазков` (сиды от `сид`), меряется середина каждого (средние 60 % длины): шаг — по ±0,42 ширины
    от оси со светом, кромка — по обоим бокам без света, просвечивание — по ±0,25 ширины от оси без света;
    профили всех мазков — в одну мерку. Кисть не пачкается."""
    проф, кр, пр = [], [], []
    for i in range(мазков):
        а, б, в = _подпись_мазка(кисть, нагрузка, int(сид) * 1009 + i, px_на_мм)
        проф.append(а)
        кр.append(б)
        пр.append(в)
    шаг = шаг_борозд(профили=np.vstack(проф))
    кромка = ширина_кромки(np.vstack(кр))
    ответ = {'шаг_борозд': шаг, 'кромка': кромка, 'просвечивание': float(np.mean(пр))}
    if px_на_мм:
        ответ['шаг_борозд_мм'] = None if шаг is None else шаг / px_на_мм
        ответ['кромка_мм'] = None if кромка is None else кромка / px_на_мм
    return ответ
