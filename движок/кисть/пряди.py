# --------------------------------------------------------------------------- шум
def _шум(rng, n, m, масштаб):
    """Гладкий непериодический шум (n, m): случайные узлы через ~масштаб отсчётов,
    у каждого столбца своя фаза и свой шаг узлов. Среднее 0, разброс ~1."""
    масштаб = max(float(масштаб), 1.0)
    шаги = масштаб * (0.75 + 0.5 * rng.random(m))
    k = int(n / (масштаб * 0.75)) + 3
    узлы = rng.standard_normal((k, m))
    t = np.arange(n)[:, None] / шаги[None, :] + rng.random(m)[None, :]
    i = t.astype(np.intp)
    f = t - i
    f = f * f * (3.0 - 2.0 * f)
    столбцы = np.arange(m)[None, :]
    return узлы[i, столбцы] * (1.0 - f) + узлы[i + 1, столбцы] * f


# ------------------------------------------------------------------ состав кисти
class _Состав:
    """Кисть на один мазок: ведущие волоски, гребни между ними, пряди, выборка профиля."""
    __slots__ = ('nr', 'ns', 'nm', 'центр', 'полуш', 'прядь', 'ось_пряди', 'нагр', 'запас', 'порог',
                 'расст', 'отст', 'липнет', 'u', 'гребень', 'x', 'профиль', 'съём', 'полуширина',
                 'тон', 'W', 'отст_гр', 'вед', 'd_вед', 'дно_в', 'полб', 'давит', 'край_проф', 'есть')


def _пучки(к, rng, W, шаг, мм):
    """К-14б: ворс пучками (`Кисть.просветы` > 0) — веерная и растрёпанная кисть. Пучок — несколько гребней ворса
    подряд (`в_пучке` в среднем; шаг гребней — как у сплошной кисти), за ним просвет: волоса там нет. На просветы идёт
    доля `просветы` ширины кисти; пучки и просветы неровные — просвет гуляет тем сильнее, чем больше кисть живёт
    клочками (`клочки`: у веерной ворс разложен ровно, у растрёпанной торчит как попало). Пучок — прядь кисти: у него
    своя длина, нагрузка, запас, тон, жёсткость и отставание, просвет поделён между соседними прядями пополам.
    Ответ: места ведущих волосков (границы гребней без краёв кисти), пуст ли гребень (nr,), прядь гребня (nr,)."""
    g = float(зажать(к.просветы, 0.0, 0.9))
    в = max(float(к.в_пучке), 1.0)
    сигма = к.неровность_шага
    сигма_п = 0.25 + 0.6 * float(зажать(к.клочки, 0.0, 1.0))
    просвет_ср = в * шаг * g / (1.0 - g)
    ширины, пуст, прядь = [], [], []
    первый = max(просвет_ср, 1.5 * мм) * rng.random()            # кисть встаёт не с пучка у самого края
    if первый >= 1.0 * мм:
        ширины.append(первый); пуст.append(True); прядь.append(0)
    сумма, j = sum(ширины), 0
    while сумма < W:
        n = max(1, int(round(в * np.exp(0.45 * rng.standard_normal()))))
        зазоры = зажать(шаг * np.exp(сигма * rng.standard_normal(n) - 0.5 * сигма * сигма), _ЗАЗОР_МИН, 2.2 * шаг)
        пр = float(зажать(просвет_ср * np.exp(сигма_п * rng.standard_normal() - 0.5 * сигма_п * сигма_п), 1.5 * мм, max(3.0 * просвет_ср, 1.5 * мм)))
        ширины += list(зазоры) + [0.5 * пр, 0.5 * пр]
        пуст += [False] * n + [True, True]
        прядь += [j] * (n + 1) + [j + 1]
        сумма += float(зазоры.sum()) + пр
        j += 1
    края = np.cumsum(ширины)
    nr = int(np.searchsorted(края, W - 0.9 * мм)) + 1             # последний гребень кончается краем кисти
    пуст, прядь = np.array(пуст[:nr]), np.array(прядь[:nr], dtype=np.intp)
    if nr > 1 and пуст[-1] and прядь[-1] != прядь[-2]:
        прядь[-1] = прядь[-2]                                    # пряди из одного просвета нет
    return края[:nr - 1] - W / 2, пуст, прядь


def _состав(к, rng):
    W = float(к.ширина)
    мм = Ч._ММ                     # Д-8а: px ниже — px холста 8 px/мм (`мм.в_мм`)
    с = _Состав()
    с.W = W
    с.полуширина = W / 2
    мастихин = к.форма == 'мастихин'
    # --- ведущие волоски: шаг борозд
    if мастихин:
        шаг = 3.0
        ведущие = np.arange(шаг, W - шаг * 0.5, шаг) - W / 2
    else:
        шаг = float(зажать(к.шаг, 1.5 * мм, max(1.5 * мм, W / 2.5)))
        сигма = к.неровность_шага
        m = int(W / шаг * 2.0) + 8
        зазоры = зажать(шаг * np.exp(сигма * rng.standard_normal(m) - 0.5 * сигма * сигма), _ЗАЗОР_МИН, 2.2 * шаг)
        поз = np.cumsum(зазоры) - зазоры[0] * rng.random() * 0.8 + 0.6 * мм
        ведущие = поз[поз < W - 0.9 * мм] - W / 2
    пучки = None
    if not мастихин and к.просветы > 0:
        ведущие, *пучки = _пучки(к, rng, W, шаг, мм)
    границы = np.concatenate([[-W / 2], ведущие, [W / 2]])
    с.центр = 0.5 * (границы[1:] + границы[:-1])
    с.полуш = 0.5 * (границы[1:] - границы[:-1])
    nr = len(с.центр)
    с.nr = nr
    # --- пряди: соседние гребни по 3–7
    ширина_пряди = max(5.0 * мм, W * (0.30 - 0.12 * к.клочки))
    прядь = np.zeros(nr, dtype=np.intp)
    i, номер = 0, 0
    while i < nr and пучки is None:
        k = max(1, int(round(ширина_пряди / шаг * np.exp(0.35 * rng.standard_normal()))))
        прядь[i:i + k] = номер
        i += k
        номер += 1
    ns = номер
    с.есть = None
    if пучки is not None:                                         # К-14б: пучок — прядь; в просвете волоса нет
        прядь, ns, с.есть = пучки[1], int(пучки[1][-1]) + 1, 1.0 - пучки[0]
    с.ns, с.прядь = ns, прядь
    вес = с.полуш
    с.ось_пряди = np.bincount(прядь, weights=с.центр * вес, minlength=ns) / np.bincount(прядь, weights=вес, minlength=ns)
    сила = 0.0 if мастихин else к.клочки
    # нагрузка: прядь набрала больше или меньше, гребень внутри пряди — ещё чуть по-своему
    нагр = np.exp(0.30 * сила * rng.standard_normal(ns))[прядь] * np.exp(0.14 * rng.standard_normal(nr))
    рад = np.abs(с.центр) / (W / 2)
    if not мастихин:
        нагр *= 1.0 - 0.35 * рад ** 6                         # к краям кисть несёт меньше: обводки нет
    if к.форма == 'круглая':
        нагр *= 0.55 + 0.45 * np.sqrt(зажать(1.0 - рад * рад, 0.0, 1.0))
    с.нагр = нагр / np.average(нагр, weights=с.полуш)
    с.запас = np.exp(0.40 * сила * rng.standard_normal(ns))[прядь] * np.exp(0.25 * rng.standard_normal(nr))
    # длина: короткая прядь касается позже и отрывается раньше; внутри пряди — небольшой разброс
    короткость = (rng.random(ns) ** 1.2)[прядь] * (0.25 + 0.75 * сила) + 0.14 * rng.random(nr) ** 1.5
    с.порог = к.разброс_длин * короткость
    с.расст = рад
    # отставание пряди вдоль хода: кисть — не линейка, пряди стоят вразнобой
    отст_пр = (rng.standard_normal(ns) * (0.07 + 0.22 * сила) * W)[прядь]
    с.отст_гр = rng.standard_normal(nr)                       # место гребня вдоль хода внутри пряди, в долях разброса
    отст = отст_пр + (0.6 * мм + 0.02 * W) * с.отст_гр
    с.отст = отст - 0.08 * W
    с.липнет = (0.08 + 0.32 * rng.random(ns)) * сила         # насколько прядь собирается к своей оси при слабом нажиме
    if мастихин:
        с.порог = np.zeros(nr)
        с.отст = np.zeros(nr)
        с.отст_гр = np.zeros(nr)
        с.запас = np.exp(0.10 * rng.standard_normal(nr))
    # тон: недомешанная краска — у пряди и гребня свой сдвиг светлоты и чуть цвета
    # п. 12: полосы недомеса на палитре шире узкой кисти — щетина в обойме (`остриё` < 1) уже 16 px набирает краску одного
    # тона, и её две-три пряди расходятся слабее (куб ширины: у 12 px — 0,42 прежнего). Иначе каждый ход короткой серии
    # делился на тёмную и светлую половину, и серия одной краской читалась частоколом. Шире 16 px и остриё — как было
    т = к.разброс_тона * (1.0 - (1.0 - к.остриё) * (1.0 - min(к.ширина / 16.0, 1.0) ** 3))
    светлота = 0.09 * rng.standard_normal(ns)[прядь] + 0.085 * rng.standard_normal(nr)
    оттенок = 0.028 * rng.standard_normal((ns, 3))[прядь] + 0.020 * rng.standard_normal((nr, 3))
    с.тон = np.exp(т * (светлота[:, None] + оттенок))
    # 11а: среднее тона по кисти (вес — сколько гребень несёт). У кисти в 5–7 гребней оно гуляет от мазка к мазку на 7 % (σ),
    # до 17 %, красный сам по себе: мазок выходит светлее и рыжее и краски, и подложки. `тон_кисти=0` — недомес только делит
    # набранную краску между гребнями, среднее по кисти — сама краска; 1 (умолчание) — как было, бит в бит
    if к.тон_кисти != 1.0:
        с.тон = с.тон / np.average(с.тон, axis=0, weights=с.нагр * с.полуш)[None, :] ** (1.0 - к.тон_кисти)
    # --- выборка профиля поперёк кисти
    nm = max(3, int(round(W / _ПОПЕРЁК)))
    u = (np.arange(nm) + 0.5) * (W / nm) - W / 2
    гребень = зажать(np.searchsorted(ведущие, u), 0, nr - 1)
    с.nm, с.u, с.гребень = nm, u, гребень
    с.x = зажать(np.abs(u - с.центр[гребень]) / с.полуш[гребень], 0.0, 1.0)
    с.вед = None                                              # борозд нет: мастихин или кисть в один гребень
    if мастихин or len(ведущие) == 0:
        с.профиль = np.ones(nm)
        с.съём = np.ones(nm)
    else:
        # под кончиком ведущего — борозда: дно тем ниже, чем сильнее он давит
        ближний = зажать(np.searchsorted(ведущие, u), 1, len(ведущие) - 1) if len(ведущие) > 1 else np.zeros(nm, np.intp)
        if len(ведущие) > 1:
            левый = ведущие[ближний - 1]
            правый = ведущие[ближний]
            j = np.where(np.abs(u - левый) < np.abs(u - правый), ближний - 1, ближний)
        else:
            j = ближний
        d = np.abs(u - ведущие[j])
        давит = np.exp(0.6 * к.разброс_жёсткости * rng.standard_normal(len(ведущие)))
        if пучки is not None:                                     # К-14б: пучок жёстче или мягче соседнего весь — его волоски давят вместе
            давит = давит * np.exp(0.5 * к.разброс_жёсткости * rng.standard_normal(ns))[прядь[:len(ведущие)]]
        глубина = (0.80 + 0.20 * к.вязкость) / (1.0 + 0.06 * (max(int(к.ряды), 1) - 1))
        дно = зажать(1.0 - глубина * давит, 0.06, 0.9)[j]
        полборозды = _ПОЛБОРОЗДЫ + 0.35 * мм * rng.random(len(ведущие))
        t = зажать(d / полборозды[j], 0.0, 1.0)
        с.профиль = дно + (1.0 - дно) * t * t * (3.0 - 2.0 * t)
        с.съём = 1.35 - 0.7 * t                               # сырую краску кончик снимает сильнее, чем бока
        # к самому краю кисти плёнка сходит на нет: крайний гребень не должен обводить мазок
        с.край_проф = 0.45 + 0.55 * зажать((W / 2 - np.abs(u)) / (1.3 * мм), 0.0, 1.0)
        с.профиль = с.профиль * с.край_проф
        # для живой борозды (п. 4, `борозда.py`): чей волосок у места, как далеко, дно и полуширина его борозды
        с.вед, с.d_вед, с.полб, с.давит = j, d, полборозды, давит
        с.дно_в = зажать(1.0 - глубина * давит, 0.06, 0.9)
    return с


def _окно_по(sc, a, b, кромка=1.5):
    """Гладкое окно 0..1 по пути: от a до b, с краями по кромке px."""
    l = зажать((sc - a) / кромка + 0.5, 0.0, 1.0)
    r = зажать((b - sc) / кромка + 0.5, 0.0, 1.0)
    return l * l * (3.0 - 2.0 * l) * r * r * (3.0 - 2.0 * r)


def _край(с, sc, rng, W, длиннее=1.0, чаще=1.0, узкая=False):
    """Бок живой (версия 3, п. 2г). Крайние пряди кисти реже и беднее краской: след крайнего гребня рвётся,
    кромка отступает внутрь на его ширину (1–3 px) и возвращается; иногда вместе с ним отходит и соседний.
    У входа кисть полна — первую треть ширины хода край держит. Ответ (Nc, nr): 1 — гребень кладёт, 0 — нет."""
    Nc, nr = len(sc), с.nr
    держит = np.ones((Nc, nr))
    L = float(sc[-1])
    for ряд in (np.arange(nr), np.arange(nr)[::-1]):
        i = 1 if 2.0 * с.полуш[ряд[0]] < 2.0 else 0             # гребень уже двух пикселей густой краски не кладёт
        r1, r2 = ряд[i], ряд[i + 1]
        s = W * rng.uniform(0.3, 0.6)
        if узкая:
            s += rng.uniform(0.0, 1.2 * W)                    # у узкой кисти бока рвутся не в одном месте
        while s < L:
            дл = W * rng.uniform(0.12, 0.32) * длиннее
            if узкая:
                # узкая кисть в несколько красок (п. 2д): прядь, отошедшая от холста, возвращается не быстрее чем за 5–9 px
                дл = max(дл, rng.uniform(4.0, 7.0) * min((20.0 - W) / 4.0, 1.0))
            держит[:, r1] = np.minimum(держит[:, r1], 1.0 - _окно_по(sc, s, s + дл, 3.0))
            if rng.random() < 0.4:
                держит[:, r2] = np.minimum(держит[:, r2], 1.0 - _окно_по(sc, s + дл * rng.uniform(0.15, 0.4), s + дл * rng.uniform(0.6, 0.85), 3.0))
            s += дл + W * rng.uniform(0.3, 0.8) / чаще
    return держит


def раскрывает_рукой(p, рука):
    """К8б: кисть раскрывает рука — нажим ведёт рука ("pressure_along") и где-то на ходу был ниже `_РАСКРЫТА`
    (кисть касалась не всей шириной). Иначе посадка — как без поля."""
    return bool(рука) and bool(((np.maximum.accumulate(p) < _РАСКРЫТА) & (p > 0.02)).any())


def _лёг_на_месте(z, s, вперёд, тащит, короче):
    """К8б: касание z (N, n) места или гребня кисти, который кладут на холст раскрытием нажимом. Кончик пряди отстаёт
    от кисти (`вперёд`, (N, n), px вдоль хода: впереди — больше нуля), потому что его тащат по холсту; волосок, который
    ещё не касался, никто не тащил — он ложится туда, где стоит кисть, и только потом отстаёт. Волосок короче соседних
    (`короче`, (n,), px) согнутая тащимая кисть доносит до холста на столько позже, насколько её уже тащат (`тащит`,
    (N,)); у первого касания кисть стоит прямо — там все встают вместе. Ответ — то же касание, вставшее на столько
    раньше или позже по пути, чтобы кончик лёг там, где до него дошло раскрытие, и ещё позже на свою длину. Подъём —
    как был."""
    рост = np.maximum.accumulate(z, axis=0)
    есть = рост > 0.5
    стало = z.copy()
    for m in np.nonzero(есть.any(axis=0))[0]:
        i = int(np.argmax(есть[:, m]))
        d = 0.0
        for _ in range(3):                         # кончик лёг в s_i: место встало там, где s + вперёд(s) = s_i
            j = int(зажать(np.searchsorted(s, s[i] - d), 0, len(s) - 1))
            d = float(вперёд[j, m])
        d -= короче[m] * float(тащит[i])
        r = np.interp(s + d, s, рост[:, m])
        стало[:, m] = np.where(рост[:, m] > 1e-9, r * z[:, m] / np.maximum(рост[:, m], 1e-9), r)
    return стало


def _посадка(с, путь, p, rng, W, rng_к=None, густо=0.0, p_руки=None, держит=None, рука=False, вперёд=None):
    """Посадка и подъём плоской кисти плашмя (версия 3, п. 2д): какая часть ширины касается холста, пока нажим
    набирают и пока его снимают. Кисть встаёт серединой обоймы — от половины до четырёх пятых ширины, одна
    сторона раньше другой (как — от сида); углы встают, когда нажим набран, а щетину протащило на `_ПОСАДКА[2..3]`
    ширины: в ширину она расходится с ходом. Пряди встают не по линейке: у каждой своя задержка. Вход короче
    пятой части ширины — удар: кисть ложится разом, торец плоский. При подъёме углы уходят первыми, тем же
    порядком; сорванная кисть (`быстро`) отходит плашмя. Пока рука держит набранный нажим, кисть лежит всей шириной.
    Конец (п. 4, `rng_к`): кисть уходит с холста с креном — срез густой краски идёт под углом к ходу и чуть дугой
    (`_срез`); на медленном подъёме гребень держится за холст по-своему, и концы гребней стоят вразнобой.
    Ответ: (N, nr) — касается ли гребень, (N, nm) — касается ли место на кисти; (None, None) — кисть легла разом
    и ушла разом."""
    s = путь['s']
    ds = путь['ds']
    i0 = int(np.argmax(p > 0.02))
    рост = np.gradient(p, ds)
    # п. 10 (`p_руки`): у узкой кисти в одну краску нажим у посадки держит капля (`укладка._дрожь`), а вход меряется
    # по руке — иначе капля читалась набранным нажимом, каждый вход выходил «ударом», и корень следа срезан прямо
    pв = p if p_руки is None else p_руки
    рост_в = рост if p_руки is None else np.gradient(pв, ds)
    стоит = np.nonzero((рост_в[i0:] * W < 0.15 * pв[i0:]) & (pв[i0:] > 0.02))[0]
    i1 = i0 + int(стоит[0]) if len(стоит) else len(p) - 1          # нажим набран
    if путь['L'] < Ч._КОРОТКИЙ[0] * W and not путь['на_месте']:
        # Н-2: короткий ход (`путь._короткий`) — рука ставит кисть, а `'остановка'` дальше давит её до конца хода: рост
        # нажима не стихал, набранным читался нажим у самого конца, вход — в полхода, и угол кисти не вставал (след 0,54–0,8
        # ширины у 5 из 30). Нажим набран, где рост упал вчетверо против самого быстрого на входе
        быстрее = np.maximum.accumulate(рост_в[i0:])
        колено = np.nonzero((рост_в[i0:] < 0.25 * быстрее) & (pв[i0:] > 0.02) & (np.arange(len(p) - i0) > 0))[0]
        if len(колено):
            i1 = min(i1, i0 + int(колено[0]))
    # длина входа: путь, на котором рука набрала 85 % нажима (дальше нажим тела только дышит)
    вход = float(s[int(np.argmax(pв >= 0.85 * pв[i1]))]) - (0.0 if p_руки is None else float(s[i0]))
    мягкий, резкий = max(0.26 * W, 3.8), max(0.15 * W, 2.8)
    удар = float(зажать((мягкий - вход) / (мягкий - резкий), 0.0, 1.0))
    удар = удар * удар * (3.0 - 2.0 * удар)
    w0 = rng.uniform(_ПОСАДКА[0], _ПОСАДКА[1])
    крен = rng.uniform(-1.0, 1.0) * _ПОСАДКА[4]
    c0 = зажать(np.array([w0 + крен, w0 - крен]), 0.2, 1.0)        # доля полуширины, что встала сразу: слева и справа
    ход = W * rng.uniform(_ПОСАДКА[2], _ПОСАДКА[3])
    задержка = _ПОСАДКА[5] * rng.random(с.ns)[с.прядь] + _ПОСАДКА[6] * rng.random(с.nr)
    раскрывает = раскрывает_рукой(p, рука)
    if раскрывает:
        # К8б: кисть раскрывают нажимом — до места доходит раскрытие от середины к краю, одно на всю обойму; ни прядь,
        # ни гребень не ждут сверх него своей очереди по нажиму (задержка по нажиму пускала крайнюю прядь раньше
        # внутренней, и та вставала позже бруском во всю свою ширину). Волоски короче или длиннее соседних, и край
        # пряди входит зубцами, — это по пути (`_лёг_на_месте`, `_РАСКРЫТА_ВРАЗБЕГ`)
        задержка = np.zeros(с.nr)
    g = np.ones(len(p))
    пятка = np.ones(len(p))
    if удар < 1.0:
        # (п. 10: севшая каплей кисть набрана против нажима капли, а не руки — пятно обратного хода не игла)
        t = np.where(np.arange(len(p)) <= i1, p / max(float(p[i1] if p_руки is None else min(p[i1], p[i0:i1 + 1].min())), 1e-6), 1.0)
        набор = зажать((t - 0.1) / 0.85, 0.0, 1.0)
        мягко = np.minimum(набор, зажать((s - s[i0]) / ход, 0.0, 1.0))
        g = удар + (1.0 - удар) * мягко
        # самое первое касание — пятно у середины: до своей доли ширины оно расходится, пока набирается первая
        # половина нажима (перёд следа круглый, а не срезанный)
        z = зажать((t - 0.1) / _ПОСАДКА[9], 0.0, 1.0)
        пятка = удар + (1.0 - удар) * (_ПОСАДКА[8] + (1.0 - _ПОСАДКА[8]) * z * (2.0 - z))
        if p_руки is not None:
            # п. 10: узкая кисть — с острым концом: севшая каплей, она касается сначала остриём, и пятно расходится до
            # своей доли ширины, пока кисть протащило на треть-половину ширины (по нажиму капли оно вставало разом: у
            # кисти, севшей одной стороной во всю полуширину, корень следа 12 px выходил прямым срезом, бруском)
            z = зажать((s - s[i0]) / (W * (0.3 + 0.2 * abs(крен) / _ПОСАДКА[4])), 0.0, 1.0)
            пятка = удар + (1.0 - удар) * (0.35 + 0.65 * z * (2.0 - z))     # остриё в капле — пятно в треть своей доли ширины, не игла
    if рука:
        # К8.1: нажим ведёт рука ("pressure_along") — ширина касания растёт с самим нажимом, а не с долей набранного:
        # слабо поставленная кисть касается серединой обоймы и раскрывается, пока на неё давят, в долю ширины по
        # доле нажима от `_РАСКРЫТА`, до всей ширины; раскрытая на ходу не сжимается (снимает её подъём ниже). Удар слабой рукой — тоже узкий
        t_р = np.maximum.accumulate(p) / _РАСКРЫТА
        g = np.minimum(g, зажать(t_р, 0.0, 1.0))
        пятка = np.minimum(пятка, зажать(t_р, _ПОСАДКА[8], 1.0))
    доля = p / np.maximum(np.maximum.accumulate(p), 1e-6)
    # сорванная кисть (нажим ушёл быстрее, чем за треть ширины хода) отходит плашмя: углы уйти первыми не успевают
    спад = np.maximum(-рост, 0.0) * W / np.maximum(np.maximum.accumulate(p), 1e-6)
    срыв = зажать((спад - _ПОСАДКА[10]) / (_ПОСАДКА[11] - _ПОСАДКА[10]), 0.0, 1.0)
    наиб = 0.0
    for i in range(len(p)):
        наиб = max(наиб, срыв[i]) if доля[i] < 0.97 else срыв[i]
        срыв[i] = наиб
    g = np.minimum(g, np.maximum(зажать((доля - 0.12) / 0.78, 0.0, 1.0), срыв))
    срез_г = срез_м = None
    вразнобой = np.zeros(с.nr)
    if rng_к is not None:
        срез_г, срез_м = _срез(с, s, p, rng_к, W, густо, крен)
        # гребень, полный краски, липнет к холсту дольше соседа; бедный уходит раньше — не лесенкой от угла к середине
        вразнобой = _СРЕЗ[4] * (rng_к.random(с.ns)[с.прядь] - 0.5 + 0.8 * (rng_к.random(с.nr) - 0.5))
    if g.min() >= 1.0 and пятка.min() >= 1.0:
        return срез_г, срез_м
    уходит = (np.arange(len(p)) > int(np.argmax(p))) & (доля < 0.97)        # рука снимает нажим

    def касается(место, сторона, зад, сдвиг):
        g_м = зажать((g[:, None] - зад[None, :]) / (1.0 - зад[None, :]), 0.0, 1.0)
        # углы встают последними: край касания идёт к краю кисти сначала медленно, под конец быстро
        # (К8б: кисть, которую раскрывает рука, раскрывается в долю ширины по доле нажима — край касания идёт к краю
        # кисти ровно, без рывка под конец: рывок клал крайнюю прядь разом)
        g_м = g_м if раскрывает else g_м ** _ПОСАДКА[7]
        до = с.полуширина * (c0[сторона][None, :] * пятка[:, None] + (1.0 - c0[сторона][None, :]) * g_м) + 1.0 * g_м
        до_раскрыта = до
        до = до + с.полуширина * сдвиг[None, :] * (уходит * (1.0 - срыв) * (1.0 - g))[:, None]
        if раскрывает:
            # К8б: кисть, недожатая до всей ширины, на подъёме уходит вразнобой, но шире, чем её раскрыли, не ложится
            # (иначе недожатый край вставал бруском, когда руку уже снимали)
            до = np.minimum(до, np.maximum.accumulate(до_раскрыта, axis=0))
        z = зажать((до - место[None, :]) / 0.8 + 0.5, 0.0, 1.0)
        return z * z * (3.0 - 2.0 * z)

    по_гребням = касается(np.maximum(np.abs(с.центр) - с.полуш, 0.0), (с.центр > 0).astype(np.intp), задержка, вразнобой)
    if держит is not None:
        # п. 18в (`укладка._держит`): рука сходит с кисти на ходу — углы на укладке не уходят первыми, кисть лежит всей
        # шириной до конца нажима; перенос краски (по гребням) — как был
        # К8б: кисть, которую раскрывают нажимом, лежит шириной, до какой её раскрыли, а не всей: недожатые края не
        # ложатся разом, когда рука её отпускает (вставали бруском на подъёме позже соседней пряди)
        g = g + ((np.maximum.accumulate(g) if раскрывает else 1.0) - g) * держит * уходит
    по_местам = касается(np.abs(с.u), (с.u > 0).astype(np.intp), задержка[с.гребень], вразнобой[с.гребень])
    if раскрывает and вперёд is not None:
        # К8б: волоски обоймы не одной длины: у гребня своя, у волоска в нём — ещё своя (свой поток, от сида)
        rng_в = np.random.default_rng(rng.bit_generator.seed_seq.spawn(1)[0])
        короче_г = _РАСКРЫТА_ВРАЗБЕГ[0] * W * rng_в.random(с.nr)
        короче_м = короче_г[с.гребень] + _РАСКРЫТА_ВРАЗБЕГ[1] * W * rng_в.random(с.nm) ** 2
        вд, тащит = вперёд
        по_гребням = _лёг_на_месте(по_гребням, s, вд, тащит, короче_г)
        по_местам = _лёг_на_месте(по_местам, s, вд[:, с.гребень], тащит, короче_м)
    if срез_г is not None:
        по_гребням, по_местам = по_гребням * срез_г, по_местам * срез_м
    return по_гребням, по_местам


def _срез(с, s, p, rng, W, густо, крен):
    """Срез конца удара (версия 3, п. 4). Кисть уходит с холста не ровно: одна сторона отрывается раньше другой
    (чаще та, что позже встала, — рука держит тот же крен), середина обоймы отстаёт или опережает. Конец следа
    густой кисти — линия под углом к ходу и чуть дугой, у каждого удара своя, а не поперечный срез буквой D.
    Тонкая краска обойму не держит — её конец прежний. Ответ: (N, nr) и (N, nm) — лежит ли ещё гребень и место;
    (None, None) — срез не нужен."""
    if густо <= 0.0:
        return None, None
    есть = np.nonzero(p > 0.02)[0]
    if not len(есть):                                          # Р-1: рука нигде не нажала выше 0,02 — кисть не вставала, срезать нечего (было: IndexError, мазок падал без слов)
        return None, None
    s_к = float(s[есть[-1]])                                   # где кисть ушла с холста
    ход = s_к - float(s[есть[0]])
    сторона = -np.sign(крен) if rng.random() < 0.7 else np.sign(крен)     # раньше уходит сторона, что встала позже
    скос = min(W * rng.uniform(_СРЕЗ[0], _СРЕЗ[1]), _СРЕЗ[3] * ход) * густо * (сторона if сторона != 0 else 1.0)
    дуга = min(W * rng.uniform(-_СРЕЗ[2], _СРЕЗ[2]), _СРЕЗ[3] * ход) * густо

    после = np.arange(len(p)) >= int(np.argmax(p))
    половина = np.nonzero(после & (p <= 0.5 * float(p.max())))[0]
    сход = _СРЕЗ[5] * (s_к - float(s[половина[0]])) if len(половина) else 0.0
    t_ = np.array([-1.0, 0.0, 1.0])
    наиб = (np.abs(скос) * 0.5 * (1.0 + np.sign(скос) * t_) + дуга * (1.0 - t_ * t_))
    наиб = float(наиб.max() - наиб.min())

    def лежит(u):
        t = u / с.полуширина                                  # -1..1 поперёк кисти
        раньше = np.abs(скос) * 0.5 * (1.0 + np.sign(скос) * t) + дуга * (1.0 - t * t)
        раньше = раньше - раньше.min()                        # дальше всех кисть лежит до конца хода
        # 4б: скос считается от места, где рука сняла половину нажима, а не от последней точки пути: иначе он
        # прятался в сходе нажима, и конец читался прежним торцом. Сторона, что лежит до конца, не тронута
        раньше = раньше + сход * раньше / max(float(наиб), 1e-6)
        z = зажать(s_к - раньше[None, :] - s[:, None] + 1.5, 0.0, 1.0)     # где кисть лежит до конца, срез ничего не трогает
        return z * z * (3.0 - 2.0 * z)

    return лежит(с.центр), лежит(с.u)
