"""Мн-2: форма следа одного мазка — числами в ширинах его кисти: вход, сход, торцы, пряди, изгиб.

Перенос `архив/анализатор/рука.py` (шаг 2в-5) на мазок картины: там маска мазка готова (скан на белом), здесь её край
ищется по снимку (`след`). Все длины — в ширинах кисти W (медиана ширины среза по середине мазка), поэтому мазок 3 мм
картины 655 мм и мазок 1 мм той же картины, названной 250 мм, — одни числа. Миллиметров здесь нет.

1. `след` — сколько краски мазка в каждом px снимка, 0–1: доля на отрезке «краска соседа — краска мазка», обе краски
   берутся рядом с этим px. Край мазка — уровень 0,5 — стоит точнее px. Решается только полоса у края; что внутри и
   что снаружи, знает разбор.
2. `замер` — ось по серединам срезов тела, за ним — по касательной; хвост, загнутый вбок, — по дуге до кончика (`_дуга`):
   по касательной его мерили бы поперёк него самого. След выпрямляется вдоль оси; по выпрямленному: ширина по ходу, где
   она набирает и теряет 0,8 тела (вход и сход), тупость кончика, кромка торца и её рваность, пряди, изгиб.

Куда шла рука, по картинке не узнать: вход — конец, где больше сплошной краски, сход — где он прядями, у́же или острее."""
import math

import numpy as np
from scipy import ndimage
from scipy.spatial import cKDTree

ШАГ = 1.0 / 24.0       # W: шаг выпрямления
СЕРЕДИНА = 0.6         # W — медиана ширины по средним 60 % длины (концы в тело не входят)
ТЕЛО = 0.8             # вход и сход — где ширина меньше 0,8 тела
ШИРЕ = 1.25            # срез у конца шире медианы больше — не тело, а загнутый хвост вдоль среза
ВГЛУБЬ = 0.5           # W: дуга хвоста начинается внутри тела — касательная там чистая
ЗАГИБ_ПХ = 0.25        # px: точнее кромка на снимке с шумом не видна
ЗАГИБ, ЗАГИБ_ЯВНЫЙ = 0.03, 0.07  # W: кромка хвоста пошла наружу на столько — загнут, если торец не прямой; на столько — загнут. Чистые: срез
#                        наискось до 0,04, клин 1,6 W, загнутый на 40°, — 0,04–0,12 (от 8 px)
СГЛАДИТЬ = 0.1         # W: окно ширины по ходу — зубец пряди не обрывает тело
ДЛИННЫЙ = 5.0          # W: длиннее — ось многочленом 3-й степени, короче — 2-й
ЗОНА_ТОРЦА = 0.6       # W: кромка торца ищется от кончика внутрь на длину конца + столько
РОВНЯТЬ = 0.2          # W: рваность — отклонение кромки торца от неё же, сглаженной этим окном
ЩЕЛЬ = 0.05            # W: щель поперёк хода шире делит пряди
ТУПОСТЬ = 0.25         # W: тупость — средняя ширина на таком куске от кончика, считая от среза (срез наискось — тоже срез)
СКОС = 1.5             # тангенс: срез наискось не круче (56°); круче — это уже сход клином
ОТРОСТОК = 1.25        # px: отросток тоньше — зуб растра, хода не загибает
ЗОНА_ВХОДА = 1.5       # W: вход — конец, где на таком куске больше краски (пряди и сход длиной до 1,5 W)
ФРОНТ = 0.15           # W: кончик — середина следа, самого далёкого от тела, с таким допуском
ЛУЧШЕ = 0.75          # дуга принимается, если середина следа ушла от неё во столько раз меньше, чем от касательной
ШПОРА = 0.25           # W: отросток тоньше половины этого (1 px у 8 px) тупости не меняет
ПРЯДИ = 0.3            # W: пряди считаются от кончика внутрь на max(столько, длина конца), не дальше 1,5 W
ОТСЧЁТОВ = 24          # px на W: мазок вдвое крупнее и больше меряется клетками k×k px
КРАЙ_НАРУЖУ, КРАЙ_ВНУТРЬ = 0.35, 0.2   # W: полоса у границы разбора, в которой край решает снимок
КОНТРАСТ = 5.0         # единицы разбора: краски по сторонам ближе — края на снимке нет, он как у разбора


def _краска_рядом(lab, где, σ):
    """Краска пикселей `где`, какой она видна из каждого места: среднее с весом гаусса `σ`; далеко от всех — ближайшая."""
    в = ndimage.gaussian_filter(где.astype(np.float64), σ, mode='constant')
    к = np.stack([ndimage.gaussian_filter(lab[..., j] * где, σ, mode='constant') for j in range(3)], -1)
    хорошо = в > 1e-4
    к = к / np.maximum(в, 1e-12)[..., None]
    if not хорошо.all() and где.any():
        iy, ix = ndimage.distance_transform_edt(~где, return_distances=False, return_indices=True)
        к = np.where(хорошо[..., None], к, lab[iy, ix])
    return к


def след(lab, маска, ширина):
    """Доля краски мазка в каждом px, 0–1. `lab` — снимок в единицах разбора, `маска` — область разбора, `ширина` px."""
    да = ndimage.distance_transform_edt(маска)
    нет = ndimage.distance_transform_edt(~маска)
    внутри = да > КРАЙ_ВНУТРЬ * ширина
    снаружи = нет > КРАЙ_НАРУЖУ * ширина
    if внутри.sum() < 4 or not снаружи.any():
        return маска.astype(np.float64)
    свой = _краска_рядом(lab, внутри, max(0.5 * ширина, 1.0))
    чужой = _краска_рядом(lab, снаружи, max(0.2 * ширина, 0.7))
    d = свой - чужой
    dd = (d * d).sum(-1)
    доля = np.clip(((lab - чужой) * d).sum(-1) / np.maximum(dd, 1e-9), 0.0, 1.0)
    доля = np.where(dd >= КОНТРАСТ ** 2, доля, маска)
    доля[внутри] = 1.0
    доля[снаружи] = 0.0
    return доля


def _кусок(а):
    """Самый большой связный кусок следа (пряди, отошедшие до 0,5 доли, — с ним); остальное — соседи."""
    метки, n = ndimage.label(а > 0.5, np.ones((3, 3)))
    if n <= 1:
        return а
    к = 1 + int(np.argmax(ndimage.sum(а, метки, range(1, n + 1))))
    iy, ix = ndimage.distance_transform_edt(метки == 0, return_distances=False, return_indices=True)
    return np.where(метки[iy, ix] == к, а, 0.0)


def _между(a, доля):
    """Процентиль упорядоченного ряда, как у `np.percentile`."""
    м = доля * (len(a) - 1)
    i = min(int(м), len(a) - 2)
    return a[i] + (м - i) * (a[i + 1] - a[i])


def _ось(yx, W0, гл, поп):
    ц = yx.mean(0)
    s, t = (yx - ц) @ гл, (yx - ц) @ поп
    L = s.max() - s.min()
    степ = 3 if L > ДЛИННЫЙ * W0 else 2
    n = int(np.clip(L / (0.25 * W0), 6, 80))
    к = np.clip(((s - s.min()) / max(L, 1e-9) * n).astype(int), 0, n - 1)
    сеч = []
    for i in range(n):
        tt = t[к == i]
        if len(tt) >= 2:
            tt = np.sort(tt)
            lo, hi = _между(tt, 0.02), _между(tt, 0.98)
            сеч.append((s.min() + (i + 0.5) * L / n, 0.5 * (lo + hi), hi - lo, math.sqrt(len(tt))))
    сеч = np.array(сеч).reshape(-1, 4)
    # середины срезов конца, срезанного наискось, уходят к его углу: ось тела — по телу, за ним — по касательной или `_дуга`.
    # Срез много шире тела у самого конца — это хвост, загнутый вдоль среза: в тело он не входит
    тело = np.zeros(len(сеч), bool)
    if len(сеч):
        м = np.median(сеч[:, 2])
        тело = сеч[:, 2] >= ТЕЛО * м
        узк = np.flatnonzero(тело & (сеч[:, 2] <= ШИРЕ * м))
        if len(узк):
            тело[:узк[0]] = False
            тело[узк[-1] + 1:] = False
    if тело.sum() > степ + 1:
        сеч = сеч[тело]
    if len(сеч) <= степ + 1:
        return ц, np.zeros(1), s.min(), s.max(), s.min(), s.max()
    return ц, np.polyfit(сеч[:, 0], сеч[:, 1], степ, w=сеч[:, 3]), s.min(), s.max(), сеч[0, 0], сеч[-1, 0]


def _дуга(yx, б, h, W0):
    """Продолжение оси за телом: `б` — точка оси внутри конца тела, `h` — ход в ней (наружу). Ход с постоянным загибом —
    дуга от `б` по касательной `h` через кончик (самое далёкое от `б` за телом); точки с шагом `ШАГ` и за кончик на 0,75 W."""
    d = yx - б
    d = d[d @ h > 0]
    if not len(d):
        return None
    р = np.linalg.norm(d, axis=1)
    e = d[р >= р.max() - max(ФРОНТ * W0, 0.75)].mean(0)
    n = np.array([-h[1], h[0]])
    x, y = float(e @ h), float(e @ n)
    α = math.atan2(y, x)                                         # хорда к касательной; вся дуга загнута на 2α
    if abs(α) < 1e-3:
        return None
    R = math.hypot(x, y) / (2 * math.sin(α))
    φ = np.arange(0.0, 1.0, ШАГ * W0 / (2 * α * R)) * 2 * α
    т = math.cos(2 * α) * h + math.sin(2 * α) * n
    return np.r_[б + np.outer(R * np.sin(φ), h) + np.outer(R * (1 - np.cos(φ)), n),
                 б + e + np.outer(np.arange(0, int(0.75 / ШАГ)) * ШАГ * W0, т)]


def _выпрямить(а, yx, ось, W0, загнут=(False, False)):
    ц, коэф, s0, s1, с0, с1, гл, поп = ось
    шаг = ШАГ * W0
    ss = np.arange(s0 - 0.75 * W0, s1 + 0.75 * W0, шаг / 4)
    сс = np.clip(ss, с0, с1)                                     # за телом ось — по касательной
    пр = np.polyval(np.polyder(коэф), сс) if len(коэф) > 1 else 0.0 * сс
    тчк = ц + np.outer(ss, гл) + np.outer(np.polyval(коэф, сс) + пр * (ss - сс), поп)
    части, от, до = [], 0, len(тчк)
    for конец in (0, 1):                                         # загнутый хвост: вместо касательной — дуга до кончика
        if not загнут[конец]:
            continue
        с_ = max(с1 - ВГЛУБЬ * W0, 0.5 * (с0 + с1)) if конец else min(с0 + ВГЛУБЬ * W0, 0.5 * (с0 + с1))
        i = int(np.clip(np.searchsorted(ss, с_), 1, len(ss) - 2))
        h = тчк[i + 1] - тчк[i - 1]
        h = (h if конец else -h) / max(float(np.linalg.norm(h)), 1e-9)
        д = _дуга(yx, тчк[i], h, W0)
        if д is not None:
            части.append((конец, д))
            от, до = (от, i) if конец else (i + 1, до)
    тчк = np.concatenate([д[::-1] for к, д in части if not к] + [тчк[от:до]] + [д for к, д in части if к])
    дуга = np.r_[0.0, np.cumsum(np.linalg.norm(np.diff(тчк, axis=0), axis=1))]
    u = np.arange(0.0, дуга[-1], шаг)
    оси = np.stack([np.interp(u, дуга, тчк[:, 0]), np.interp(u, дуга, тчк[:, 1])], 1)
    кас = np.gradient(оси, axis=0)
    кас /= np.maximum(np.linalg.norm(кас, axis=1, keepdims=True), 1e-9)
    нор = np.stack([-кас[:, 1], кас[:, 0]], 1)
    v = np.arange(-1.6 * W0, 1.6 * W0 + шаг / 2, шаг)
    Y = оси[None, :, 0] + v[:, None] * нор[None, :, 0]
    X = оси[None, :, 1] + v[:, None] * нор[None, :, 1]
    сер = ndimage.map_coordinates(а, [Y, X], order=1, cval=0.0)
    вып = сер > 0.5
    if части:                                                    # срезы загнутой оси пересекаются: px — у ближайшей точки оси
        vv, uu = np.nonzero(вып & (np.abs(v) > 0.5 * W0)[:, None])
        вып[vv, uu] = cKDTree(оси).query(np.stack([Y[vv, uu], X[vv, uu]], 1))[0] >= np.abs(v[vv]) - 0.1 * W0
    return вып, сер, оси, нор, шаг, np.stack([Y, X], -1)


def _круг(d):
    n = max(1, int(round(d)) // 2)
    y, x = np.mgrid[-n:n + 1, -n:n + 1]
    return y * y + x * x <= max(0.25 * d * d, 1.0)


def _загнут(сер, верх, низ, кончик, внутрь, край, W, строки):
    """Насколько загнут хвост у `кончик`а, W: на сколько кромка одной стороны, отойдя от тела внутрь или нет, идёт наружу
    там, где противоположная — внутрь. У среза наискось длинная кромка прямая, у клина обе идут внутрь: у них 0."""
    ст = np.arange(край + внутрь * int(W), кончик - внутрь, -внутрь)  # от тела (на W вглубь) до кончика
    ст = ст[(ст >= 0) & (ст < len(верх))]
    ст = ст[низ[ст] >= верх[ст]]
    if len(ст) < 2:
        return 0.0
    # кромки точнее шага: уровень 0,5 между соседними строками
    в, н = np.clip(верх[ст], 1, None), np.clip(низ[ст], None, сер.shape[0] - 2)
    в = в - np.clip((сер[в, ст] - 0.5) / np.maximum(сер[в, ст] - сер[в - 1, ст], 1e-6), 0.0, 1.0)
    н = н + np.clip((сер[н, ст] - 0.5) / np.maximum(сер[н, ст] - сер[н + 1, ст], 1e-6), 0.0, 1.0)
    у = np.abs(ст - край) <= 0.5 * W
    в0, н0 = (np.median(в[у]), np.median(н[у])) if у.any() else строки
    о = 0.0
    for своя, чужая in ((н - н0, в - в0), (в0 - в, н0 - н)):
        наружу = своя - np.minimum(np.minimum.accumulate(своя), 0.0)
        о = max(о, float(np.minimum(наружу, чужая).max()) / W)
    return о


def _мимо_середины(верх, низ, конец, W, ряд):
    """Насколько середина следа на последней W хода в среднем отходит от середины тела, W."""
    ст = конец[0] + конец[1] * np.arange(max(1, int(round(W))))
    ст = ст[(ст >= 0) & (ст < len(верх))]
    ст = ст[низ[ст] >= верх[ст]]
    return float(np.abs(0.5 * (верх[ст] + низ[ст]) - 0.5 * (ряд[0] + ряд[1])).mean() / W) if len(ст) else 0.0


def _прядей(столбцы, щель):
    """Прядей в каждом столбце: полос краски, между которыми щель не у́же `щель`."""
    т = столбцы.T
    д = np.diff(np.pad(т.astype(np.int8), ((0, 0), (1, 1))), axis=1)
    (кн, нач), (_, кон) = np.nonzero(д == 1), np.nonzero(д == -1)
    делит = (кн[1:] == кн[:-1]) & (нач[1:] - кон[:-1] >= щель)
    return т.any(1) + np.bincount(кн[1:][делит], minlength=len(т))


def _торец(вып, кончик, внутрь, длина, W, строки):
    """Кромка торца — где в каждой строке тела от кончика внутрь впервые краска; числа в W."""
    глуб = int(round((длина + ЗОНА_ТОРЦА) * W))
    ст = кончик + внутрь * np.arange(глуб)
    ст = ст[(ст >= 0) & (ст < вып.shape[1])]
    к = вып[строки[0]:строки[1] + 1][:, ст]
    e = np.where(к.any(1), к.argmax(1), len(ст)) / W
    if len(e) < 3:
        return {'рваность': 0.0, 'скос': 0.0, 'тупость': 0.0}
    v = (np.arange(len(e)) - 0.5 * (len(e) - 1)) / W
    н = float(np.clip((v @ (e - e.mean())) / (v @ v), -СКОС, СКОС))
    ост = e - н * v
    гладк = ndimage.uniform_filter1d(ост, max(3, int(round(РОВНЯТЬ * W)) | 1), mode='nearest')
    ход = ndimage.median_filter(ост, int(round(ШПОРА * W)) | 1, mode='nearest')   # шпора — не кончик
    до = np.clip((ТУПОСТЬ - (ход - ход.min())) / ТУПОСТЬ, 0.0, 1.0)   # средняя ширина кончика до глубины ТУПОСТЬ от среза
    return {'рваность': float(np.sqrt(np.mean((ост - гладк) ** 2))), 'скос': float(np.degrees(np.arctan(abs(н)))),
            'тупость': float(до.sum() / W)}


def _на_краске(yx, вып, оси, нор, шаг, u, внутрь, W):
    """Кончик: середина краски в последних 0,1 W хода — в ближайший px следа."""
    ст = u + внутрь * np.arange(max(1, int(round(0.1 * W))))
    ст = ст[(ст >= 0) & (ст < вып.shape[1])]
    vv, i = np.nonzero(вып[:, ст])
    v = (vv - (вып.shape[0] - 1) / 2) * шаг
    т = (оси[ст[i]] + v[:, None] * нор[ст[i]]).mean(0)
    return tuple((yx[np.argmin(((yx - т) ** 2).sum(1))] - 1.0).tolist())


def замер(а, ширина):
    """Форма следа: `а` — доля краски 0–1 (или маска), `ширина` — примерная ширина, px. Ответ — словарь: 'W' px,
    'длина к ширине', 'вход', 'сход' — {'длина', 'тупость', 'рваность', 'скос', 'пряди', 'сплошность',
    'полнота' — средняя ширина последней W хода,
    'краски' — краска на последних `ЗОНА_ВХОДА`, W²}, 'разброс ширины',
    'сплошность', 'изгиб', 'поворот'. Меньше 12 px краски — None."""
    а = np.asarray(а, np.float64)
    а = _кусок(np.pad(а, 1))
    if (а > 0.5).sum() < 12:
        return None
    W0 = max(float(ширина), 2.0)
    yx = np.argwhere(а > 0.5).astype(np.float64)
    с, в = np.linalg.eigh(np.cov(yx.T))
    ось = _ось(yx, W0, в[:, 1], в[:, 0]) + (в[:, 1], в[:, 0])
    загнут, yx_, мимо, проход = None, yx, None, 1
    while True:
        вып, сер, оси, нор, шаг, место = _выпрямить(а, yx, ось, W0, загнут or (False, False))
        u_ = np.flatnonzero(вып.any(0))
        if len(u_) < 6:
            return None
        u0, u1 = int(u_[0]), int(u_[-1])
        есть = вып.any(0)
        верх, низ = вып.argmax(0), np.where(есть, вып.shape[0] - 1 - вып[::-1].argmax(0), -1)
        шир = np.where(есть, низ - верх + 1, 0).astype(np.float64)
        сплошь = np.where(есть, вып.sum(0) / np.maximum(шир, 1.0), 0.0)
        n = u1 - u0 + 1
        поле = int(0.5 * (1 - СЕРЕДИНА) * n)
        W = max(float(np.median(шир[u0 + поле:u1 + 1 - поле])), 4.0)
        глад = ndimage.uniform_filter1d(шир, max(1, int(round(СГЛАДИТЬ * W))), mode='constant')
        тело = np.flatnonzero(глад[u0:u1 + 1] >= ТЕЛО * W) + u0
        т0, т1 = (int(тело[0]), int(тело[-1])) if len(тело) else (u0 + поле, u1 - поле)
        т = np.arange(т0, т1 + 1)
        т = т[есть[т]]
        ряды = []
        for край in (т0, т1):                                    # тело у этого конца: кисть могла увести след от оси
            у = т[np.abs(т - край) <= max(W, 3)]
            ряды.append((int(np.median(верх[у])), int(np.median(низ[у]))))
        концы_u = ((u0, 1), (u1, -1))
        сейчас = [_мимо_середины(верх, низ, у, W, ряд) for у, ряд in zip(концы_u, ряды)]
        if загнут is not None:                                   # дуга верна, если идёт серединой следа, — не к углу прямого конца
            верно = tuple(з and с_ < ЛУЧШЕ * м for з, с_, м in zip(загнут, сейчас, мимо))
            if верно == загнут or проход > 2:
                break
            загнут, проход = верно, проход + 1
            if not any(загнут):
                вып, сер, оси, нор, шаг, верх, низ, есть, шир, сплошь, n, W, т0, т1, т, ряды, u0, u1 = прямой_ход
                break
            continue
        мимо = сейчас
        прямой_ход = вып, сер, оси, нор, шаг, верх, низ, есть, шир, сплошь, n, W, т0, т1, т, ряды, u0, u1
        торцы = [_торец(вып, *ш, W, ряд) for ш, ряд in zip(((u0, 1, (т0 - u0) / W), (u1, -1, (u1 - т1) / W)), ряды)]
        тол = ndimage.binary_opening(вып, _круг(ОТРОСТОК / шаг))  # отросток в px ход не загибает
        есть_ = np.flatnonzero(тол.any(0))
        if len(есть_) < 6:
            break
        в_, н_ = тол.argmax(0), np.where(тол.any(0), тол.shape[0] - 1 - тол[::-1].argmax(0), -1)
        наружу = [_загнут(сер, в_, н_, есть_[0], 1, т0, W, ряды[0]), _загнут(сер, в_, н_, есть_[-1], -1, т1, W, ряды[1])]
        yx = место[тол]
        загнут = tuple(н > ЗАГИБ_ЯВНЫЙ or (н > max(ЗАГИБ, ЗАГИБ_ПХ / (W * шаг)) and т_['тупость'] < ПРЯМОЙ) for н, т_ in zip(наружу, торцы))
        if not any(загнут):
            break
    концы = []
    for кончик, внутрь, длина, ряд in ((u0, 1, (т0 - u0) / W, ряды[0]), (u1, -1, (u1 - т1) / W, ряды[1])):
        к = торцы[внутрь < 0] if not загнут or not any(загнут) else _торец(вып, кончик, внутрь, длина, W, ряд)
        зона = кончик + внутрь * np.arange(max(1, int(round(min(1.5, max(ПРЯДИ, длина)) * W))))
        зона = зона[(зона >= 0) & (зона < len(шир)) & (есть[np.clip(зона, 0, len(шир) - 1)])]
        к['пряди'] = int(np.percentile(_прядей(вып[:, зона], max(1, int(round(ЩЕЛЬ * W)))), 90))
        к['сплошность'] = float(сплошь[зона].mean())
        к['длина'] = float(длина)
        ст = кончик + внутрь * np.arange(max(1, int(round(W))))
        к['полнота'] = float(np.minimum(шир[ст[(ст >= 0) & (ст < len(шир))]], W).sum() / W / len(ст))
        ст = кончик + внутрь * np.arange(max(1, int(round(ЗОНА_ВХОДА * W))))
        к['краски'] = float(np.minimum(вып[:, ст[(ст >= 0) & (ст < len(шир))]].sum(0), W).sum() / W ** 2)
        концы.append(к)
    # вход — где больше сплошной краски на последних 1,5 W: кисть, уходя, сходит длинно, остро, прядями
    a, b = концы
    прямо = a['краски'] * a['сплошность'] >= b['краски'] * b['сплошность']
    тч = оси[u0:u1 + 1]
    х = тч[-1] - тч[0]
    дл = max(float(np.linalg.norm(х)), 1e-9)
    концы_px = (u0, u1) if прямо else (u1, u0)
    return {'W': W * шаг, 'длина к ширине': n / W, 'вход': a if прямо else b, 'сход': b if прямо else a,
            'разброс ширины': float(np.std(шир[т]) / W), 'сплошность': float(сплошь[т].mean()),
            'изгиб': float(np.abs((тч - тч[0]) @ np.array([-х[1], х[0]]) / дл).max() / дл),
            'поворот': float(np.degrees(np.arccos(np.clip(нор[u0] @ нор[u1], -1.0, 1.0)))),
            'концы': [_на_краске(yx_, вып, оси, нор, шаг, u, 1 if u == u0 else -1, W) for u in концы_px]}


# ---------------------------------------------------------------- слова

ВИДНО = 5.0            # px: у́же — концы не различаются (сужение на 1 W — меньше двух пределов снимка)
ВИДНО_ТОРЕЦ = 12.0     # px: у́же — рваный торец от суженного, прямой от круглого не отличить (зуб 1/4 W — 3 px, предел снимка)
СУЖЕН, ПРЯМОЙ = 0.4, 0.7      # тупость: клин 0,1–0,3, полукруг 0,5–0,65, срез 0,7–1
ПОЛОВИНА = 0.5         # полнота (средняя ширина последней W хода): клин 1,5 W — 0,33, срез 45° — 0,5, полукруг — 0,9
СПЛОШНОЙ = 0.9         # узкий (полнота меньше половины) и щелей меньше десятой — сплошной хвост, а не рваный торец
РВАНЫЙ = 0.08          # W: рваность ровных концов (срез, полукруг, клин) с растром и шумом — до 0,07
КОРОТОК = 1.5          # длина к ширине: короче — концов не назвать


def сужен(к):
    """Конец сужен: остёр кончик или последняя ширина хода наполовину пуста (длинный хвост с тупым кончиком); срез наискось — нет."""
    return к['тупость'] < СУЖЕН or (к['полнота'] < ПОЛОВИНА and к['тупость'] < ПРЯМОЙ)


def торец(к, W):
    """Имя конца: 'рваный', 'сужен' (клином или со скошенными углами), 'круглый', 'прямой'; у мазка у́же `ВИДНО_ТОРЕЦ` px — только 'сужен' или 'тупой'; у́же
    `ВИДНО` — None."""
    if W < ВИДНО:
        return None
    if W < ВИДНО_ТОРЕЦ:
        return 'сужен' if сужен(к) else 'тупой'
    if к['рваность'] > РВАНЫЙ and к['пряди'] >= 2 and not (к['полнота'] < ПОЛОВИНА and к['сплошность'] > СПЛОШНОЙ):
        return 'рваный'
    return 'сужен' if сужен(к) else 'круглый' if к['тупость'] < ПРЯМОЙ else 'прямой'


def слова(з):
    """Форма одного мазка строкой."""
    ч = lambda v, n=1: f'{v:.{n}f}'.replace('.', ',')
    if з['длина к ширине'] < КОРОТОК or з['W'] < ВИДНО:
        return (f'удар {ч(з["длина к ширине"])} ширины' if з['W'] >= ВИДНО else f'шириной {ч(з["W"])} px') + ' — концы не различаются'
    т = [торец(з[и], з['W']) for и in ('вход', 'сход')]
    к = [f'{и} {т[i]} (тупость {ч(з[и]["тупость"], 2)}), {ч(з[и]["длина"])} ширины' + (f', прядей {з[и]["пряди"]}' if з['W'] >= ВИДНО_ТОРЕЦ and з[и]['пряди'] > 1 else '')
         + (f', срез наискось {ч(з[и]["скос"], 0)}°' if т[i] == 'прямой' and з[и]['скос'] >= 20 else '')
         for i, и in enumerate(('вход', 'сход'))]
    return f'длина {ч(з["длина к ширине"])} ширины; {к[0]}; {к[1]}; изгиб {ч(з["изгиб"], 2)} длины'
