def _подпись(ном, адрес, ч, px_на_мм):
    """Строки подписи под кропом."""
    from .манера import _ч
    р, к, т, н = ч['мазки разбором'], ч['края'], ч['тон в пятне'], ч['направления']
    тр = lambda v: '–'.join(_ч(v[и]) for и in ('p10', 'p50', 'p90'))
    x0, y0, x1, y1 = адрес
    проц = lambda v: f'{_ч(100 * v, 0)} %'
    с = [f'{ном}. x {x0}–{x1}, y {y0}–{y1} · {_ч((x1 - x0) / px_на_мм, 0)}×{_ч((y1 - y0) / px_на_мм, 0)} мм',
         f'мазков {р["мазков"]}, на дм² {_ч(р["на дм²"], 0)}; протяжек {проц(р["доли"]["протяжек"])}' if р['мазков'] else 'мазков не видно',
         f'без мазков {_ч(100 * р["без мазков"], 0)} %; края {_ч(100 * к["доля"], 0)} %'
         + (f', жёстких {_ч(100 * к["жёстких"], 0)} %' if к['жёстких'] is not None else '')]
    if р['слово'] is None:
        с.append(f'ширина {тр(р["ширина"])}, длина {тр(р["длина"])} мм')
    else:
        с.append('размер не числом: ' + (f'целых мазков меньше {Р.МАЛО_МАЗКОВ}' if р['слово'].startswith('целых') else
                                        'мазков мало' if р['слово'].startswith('размер держится') else 'на снимке мельче другой'))
    ф = р['форма']
    if ф is not None:
        с.append(f'вход {_ч(ф["вход"]["длина"]["p50"])}, сход {_ч(ф["сход"]["длина"]["p50"])} шир., сужен '
                 f'{_ч(100 * ф["вход"]["сужен"], 0)} и {_ч(100 * ф["сход"]["сужен"], 0)} %')
    else:
        с.append('форма не числом: ' + (f'концов видно меньше {Р.МАЛО_МАЗКОВ}' if р['слово формы'].startswith('мазков') else
                                       'на снимке мельче другая'))
    с.append(f'тон в пятне {_ч(т["p10"])}–{_ч(т["p50"])}–{_ч(т["p90"])} L')
    if н is not None and н['главные']:
        с[-1] += f'; ход {н["главные"][0][0]}° — {_ч(100 * н["главные"][0][1], 0)} %'
    return с


def _строкой(ном, д):
    """Место — строкой отчёта: полные слова мерки."""
    from .манера import _ч, _слова_разбора

    def одно(адрес, ч):
        т, к, н = ч['тон в пятне'], ч['края'], ч['направления']
        напр = f'; направление {н["главные"][0][0]}°±15 — {_ч(100 * н["главные"][0][1], 0)} %' if н and н['главные'] else ''
        return (f'{tuple(адрес)} px: {_слова_разбора(ч["мазки разбором"], ч["края пятен"])}; тон в пятне {_ч(т["p50"])} L; '
                f'края {_ч(100 * к["доля"], 0)} % места{напр}')
    с = f'{ном}. {одно(д["адрес"], д["мерка"])}'
    if 'холст' in д:
        с += f'\n   холст {одно(д["холст"]["адрес"], д["холст"]["мерка"])}'
    return с


def _переносом(строки, шрифт, ширина):
    """Строки, не шире `ширина` px: длинная — переносом по словам."""
    итог = []
    for с in строки:
        т = ''
        for сл in с.split(' '):
            п = f'{т} {сл}' if т else сл
            if т and шрифт.getlength(п) > ширина:
                итог.append(т)
                п = сл
            т = п
        итог.append(т)
    return итог


def _лист(ячейки, шапка, в_ряд, панель, путь):
    """Ячейки [(кроп, подпись)] по `в_ряд` в ряд под шапкой; кроп — в `панель` (ш, в) px, подпись — под ним."""
    from PIL import Image, ImageDraw
    шрифт, поле, стр = глаз._шрифт(ШРИФТ), 8, ШРИФТ + 2
    ш, в = панель
    подписи = [_переносом(п, шрифт, ш) for _, п in ячейки]
    низ = стр * max(СТРОК, *(len(п) for п in подписи)) + 4
    W = в_ряд * (ш + поле) + поле
    верх = _переносом([шапка], шрифт, W - 2 * поле)
    y0 = стр * len(верх) + 6
    ряды = math.ceil(len(ячейки) / в_ряд)
    лист = Image.new('RGB', (W, y0 + ряды * (в + низ)), (255, 255, 255))
    д = ImageDraw.Draw(лист)
    for i, с in enumerate(верх):
        д.text((поле, 2 + i * стр), с, fill=(0, 0, 0), font=шрифт)
    for i, ((кроп, _), п) in enumerate(zip(ячейки, подписи)):
        x, y = поле + i % в_ряд * (ш + поле), y0 + i // в_ряд * (в + низ)
        им = Image.fromarray(кроп)
        k = min(ш / им.width, в / им.height)
        # целое увеличение — повтором px, без придуманных полутонов между ними
        им = им.resize((max(1, round(им.width * k)), max(1, round(им.height * k))),
                       Image.NEAREST if abs(k - round(k)) < 1e-9 else Image.LANCZOS)
        лист.paste(им, (x, y))
        for j, с in enumerate(п):
            д.text((x, y + в + 1 + j * стр), с, fill=(0, 0, 0), font=шрифт)
    if путь is not None:
        лист.save(os.path.expanduser(str(путь)))
    return np.asarray(лист)


# ---------------------------------------------------------------- альбом

def альбом(м, холст=None, путь=None, мест=None, ядра=None):
    """Альбом мерки `м` (`Мерка`): до `мест` самых непохожих мест ×2 с числами и адресом, одним PNG (`путь`); `холст` — `Мерка`
    холста: его те же места рядом (та же доля меренной рамки, кадр — та же доля длинной стороны картины)."""
    from .манера import _ч
    мест = int(мест or (ПАР if холст is not None else МЕСТ))
    if мест < 1:
        raise ValueError(f'альбом: мест={мест} — нужно хотя бы одно')
    снимок = м.массивы['снимок']
    В, Ш = снимок.shape[:2]
    клетки = _сетка(В, Ш, КАДР, МЕСТ)
    взято = [клетки[j] for j in _непохожие(*_признаки(м, клетки), клетки, max(мест, МЕСТ), _цельно(м, клетки))][:мест]
    if холст is not None:                                         # те же места, что без холста, — их средняя полоса
        взято = [(x0, (y0 + y1 - п) // 2, x1, (y0 + y1 - п) // 2 + п) for x0, y0, x1, y1 in взято
                 for п in [max(int(round((y1 - y0) * ПОЛОСА_ПАРЫ)), 1)]]
    задачи = [_кусок(м, кл) for кл in взято]
    свои = []
    if холст is not None:
        вх, шх = холст.массивы['снимок'].shape[:2]
        k = холст.откуда['сторона'] / м.откуда['сторона']         # кадр — та же доля длинной стороны картины
        for x0, y0, x1, y1 in взято:
            ш, в = (int(round(min(max(a * k, 16), n))) for a, n in ((x1 - x0, шх), (y1 - y0, вх)))
            x = int(round(min(max((x0 + x1) / 2 / Ш * шх - ш / 2, 0), шх - ш)))
            y = int(round(min(max((y0 + y1) / 2 / В * вх - в / 2, 0), вх - в)))
            свои.append((x, y, x + ш, y + в))
        задачи += [_кусок(холст, кл) for кл in свои]
    числа = _разом(задачи, ядра)

    def где(мерка_, кл):
        ox, oy = мерка_.откуда['угол']
        return (кл[0] + ox, кл[1] + oy, кл[2] + ox, кл[3] + oy)

    а = Альбом()
    а.места, ячейки = [], []
    for i, кл in enumerate(взято):
        д = {'адрес': где(м, кл), 'мерка': числа[i]}
        ячейки.append((снимок[кл[1]:кл[3], кл[0]:кл[2]], _подпись(i + 1, д['адрес'], д['мерка'], м.px_на_мм)))
        if холст is not None:
            кл = свои[i]
            д['холст'] = {'адрес': где(холст, кл), 'мерка': числа[len(взято) + i]}
            ячейки.append((холст.массивы['снимок'][кл[1]:кл[3], кл[0]:кл[2]],
                           _подпись(f'{i + 1} холст', д['холст']['адрес'], д['холст']['мерка'], холст.px_на_мм)))
        а.места.append(д)
    w, h = взято[0][2] - взято[0][0], взято[0][3] - взято[0][1]
    шапка = (f'{м.что} {_ч(м.размер[0], 0)}×{_ч(м.размер[1], 0)} мм, {Ш}×{В} px ({_ч(м.px_на_мм, 2)} px/мм): мест {len(взято)}, по одному на вид '
             f'(края, мазки, тон в пятне, краска), ×{УВЕЛИЧЕНИЕ}; числа — мерка самого места, адрес — px картинки')
    р = м['мазки разбором']
    тр = lambda v: '–'.join(_ч(v[и]) for и in ('p10', 'p50', 'p90'))
    шапка += ('. Вся картинка: размер мазка не числом' if р['слово'] is not None else
              f'. Вся картинка: мазок шириной {тр(р["ширина"])}, длиной {тр(р["длина"])} мм (p10–p50–p90)')
    if холст is not None:
        шапка += (f'. Правее — то же место холста: та же доля рамки, кадр — та же доля длинной стороны (×{_ч(w * УВЕЛИЧЕНИЕ / (свои[0][2] - свои[0][0]), 2)}), '
                  f'адрес — px холста')
    а.лист = _лист(ячейки, шапка, 4, (w * УВЕЛИЧЕНИЕ, h * УВЕЛИЧЕНИЕ), путь)
    а.слова = '\n'.join([шапка] + [_строкой(i + 1, д) for i, д in enumerate(а.места)])
    return а
