"""Мн-3: альбом образца — самые непохожие места картинки вблизи, ×2, под каждым — числа мерки этого места и его адрес.

Место — клетка снимка `КАДР` px (меньше — если клеток иначе не хватает на `МЕСТ`). Чем клетки отличаются, берётся из готовой
мерки (`_признаки`): края, мазки, тон в пятне, краска. Места — по одному на вид (`_непохожие`), из клеток, что не на границе
двух масс (`_цельно`).

Числа под кропом — мерка тех же px, та же, что у `мерка(картинка, px, область=адрес)` (`_место`), а не кусок общей: большой
снимок мерка разбирает мелкими уровнями по плиткам, и вне плиток мелких мазков в ней нет. Места считаются разом процессами.
С холстом рядом — то же место холста: та же доля рамки, кадр — та же доля длинной стороны картины. Случайных чисел нет;
холст и мерки только читаются. Рецептов и оценок «похоже» нет: картинка, числа, адрес."""
import math
import multiprocessing
import os

import numpy as np

from . import глаз
from . import разбор as Р

КАДР = 145                # px снимка: сторона кропа; ×2 — 290 px панели, по четыре в ряд — лист 1200 px
ПОЛОСА_ПАРЫ = 0.55        # доля высоты кадра: с холстом рядом — средняя полоса места, две пары в ряд, три ряда
КАДР_МИН = 48             # px: мельче кадр не режется — пусть мест будет меньше
УВЕЛИЧЕНИЕ = 2
МЕСТ = 8                  # мест образца; с холстом рядом — `ПАР`
ПАР = 6
ЦЕЛЫХ = 0.7               # доля клеток, из которых берутся места (`_цельно`)
ПРОЦЕССОВ = 8
ШРИФТ, СТРОК = 12, 6      # px и строк подписи под кропом


class Альбом:
    """Ответ `мерка(…).альбом()` и `х.манера(…).альбом()`: `лист` — PNG-массив (В, Ш, 3); `места` — словари 'адрес' (x0, y0, x1, y1)
    в px картинки, 'мерка' — числа места (`_место`: 'мазки разбором', 'края пятен', 'тон в пятне', 'края', 'направления'), с
    холстом — 'холст': {'адрес' в px холста, 'мерка'}; `слова` — то же строкой (print)."""
    __slots__ = ('лист', 'места', 'слова')

    def __repr__(self):
        return self.слова


# ---------------------------------------------------------------- места

def _сетка(В, Ш, кадр, мест):
    """Клетки снимка: [(x0, y0, x1, y1)] — кадром `кадр` px через полкадра, от края до края; впритык их меньше
    `мест` вдвое — кадр мельче (не мельче `КАДР_МИН`): места через полкадра впритык не ложатся."""
    к = 1.0
    while True:
        ш, в = min(int(кадр * к), Ш), min(int(кадр * к), В)
        if (Ш // ш) * (В // в) >= 2 * мест or кадр * к * 0.95 < КАДР_МИН:
            break
        к *= 0.95
    x, y = ([int(round(v)) for v in np.linspace(0, N - n, 2 * (N // n) - 1)] for N, n in ((Ш, ш), (В, в)))
    return [(a, b, a + ш, b + в) for b in y for a in x]


def _признаки(м, клетки):
    """Клетка — строка: (группы по столбцам, числа). Края: доля места и доля жёстких; мазки: сколько крупных, длина к ширине,
    направление (удвоенный угол с весом порядка), порядок; тон в пятне p50 и p90; краска — средняя L, a, b (места одной
    краски и одной фактуры — одно место, ровное небо и ровная стена — разные)."""
    from .манера import РАБОЧИЙ
    a = м.массивы
    s = РАБОЧИЙ / м.px_на_мм                                      # px снимка -> px счёта
    р = a['разбор']
    о = р['области']
    весь = {у['k'] for у in р['уровни'] if not у['плитки']}        # уровни, разобранные на всём снимке: клетки сравнимы
    взять = р['мазки'] & np.isin(о['уровень'], sorted(весь))
    ox, oy = о['x'][взять], о['y'][взять]
    кш = np.log(np.maximum(о['длина'][взять] / np.maximum(о['ширина'][взять], 1e-6), 1.0))
    ряды = []
    снимок = a['снимок']
    жёст, мягк, тон, θ, с, шаг = (a[и] for и in ('жёсткие', 'мягкие', 'тон в пятне', 'направление', 'порядок', 'шаг'))
    кк = тон.shape[0] / жёст.shape[0]

    def срез(b, x0, y0, x1, y1, м_):
        i0, j0 = min(int(y0 / м_), b.shape[0] - 1), min(int(x0 / м_), b.shape[1] - 1)
        return b[i0:max(int(math.ceil(y1 / м_)), i0 + 1), j0:max(int(math.ceil(x1 / м_)), j0 + 1)]

    for x0, y0, x1, y1 in клетки:
        р4 = (x0 * s, y0 * s, x1 * s, y1 * s)
        ж, мг = срез(жёст, *р4, кк), срез(мягк, *р4, кк)
        т = срез(тон, *р4, 1.0)[::4, ::4]                          # карта размыта на пятно 4 мм: хватает отсчёта на мм
        г, п = np.radians(срез(θ, *р4, шаг)), срез(с, *р4, шаг)
        тут = (ox >= x0) & (ox < x1) & (oy >= y0) & (oy < y1)
        ряды.append((ж.mean() + мг.mean(), ж.sum() / max(ж.sum() + мг.sum(), 1),
                     тут.sum(), np.median(кш[тут]) if тут.any() else 0.0,
                     (п * np.cos(2 * г)).mean(), (п * np.sin(2 * г)).mean(), п.mean(),
                     np.median(т), np.percentile(т, 90),
                     *глаз.oklab(снимок[y0:y1, x0:x1].mean((0, 1))[None, None])[0, 0]))
    return np.array(ряды, np.float64), np.array([0, 0, 1, 1, 1, 1, 1, 2, 2, 3, 3, 3])


def _цельно(м, клетки):
    """Какие клетки показывают одно место, а не границу двух: краска четвертей клетки разошлась не больше, чем у половины
    клеток картины."""
    сн = м.массивы['снимок']
    р = []
    for x0, y0, x1, y1 in клетки:
        xс, yс = (x0 + x1) // 2, (y0 + y1) // 2
        q = np.array([[сн[a:b, c:d].mean((0, 1)) for c, d in ((x0, xс), (xс, x1))] for a, b in ((y0, yс), (yс, y1))])
        р.append(np.sqrt(((глаз.oklab(q) - глаз.oklab(q).mean((0, 1))) ** 2).sum(-1)).max())
    return np.array(р) <= np.quantile(р, ЦЕЛЫХ)


def _непохожие(числа, группы, клетки, мест, цельно):
    """Номера клеток — по одной на вид места: столбцы рангами 0–1, группы признаков — с равным весом. Начало — самые непохожие
    (первая дальше всех от середины, следующая — дальше всех от взятых, не кроя их); дальше клетки делятся между ними, и
    место — середина своего вида (клетка, что ближе всех к остальным его клеткам), пока не сойдётся: самая крайняя
    клетка картины — обычно граница двух предметов, а не вид места. Места друг друга не кроют."""
    р = []
    for v in числа.T:                                             # ранг 0–1, у равных — средний
        _, и, n = np.unique(np.round(v, 6), return_inverse=True, return_counts=True)
        р.append(((np.cumsum(n) - 0.5 * (n - 1)) / len(v))[и])
    р = np.stack(р, 1)
    р /= np.sqrt(np.bincount(группы)[группы])
    x0, y0, x1, y1 = np.array(клетки).T
    врозь = lambda j: (x0 >= x1[j]) | (x1 <= x0[j]) | (y0 >= y1[j]) | (y1 <= y0[j])
    D = np.sqrt(((р[:, None] - р[None]) ** 2).sum(-1))
    можно = np.ones(len(р), bool)
    до, взято = np.sqrt(((р - np.median(р, 0)) ** 2).sum(1)), []
    while len(взято) < мест and можно.any():
        целые = можно & цельно                                    # цельных без нахлёста не осталось — любая
        j = int(np.where(целые if целые.any() else можно, до, -1.0).argmax())
        до = D[j] if not взято else np.minimum(до, D[j])
        взято.append(j)
        можно &= врозь(j)
    for _ in range(50):
        вид = D[:, взято].argmin(1)
        было = list(взято)
        for n in range(len(взято)):
            можно = np.logical_and.reduce([врозь(j) for k, j in enumerate(взято) if k != n]) if len(взято) > 1 else np.ones(len(р), bool)
            свои = вид == n
            можно &= цельно
            взято[n] = int(np.where(свои & можно, D[:, свои].sum(1), np.inf).argmin()) if (свои & можно).any() else взято[n]
        if взято == было:
            break
    сколько = np.bincount(D[:, взято].argmin(1), minlength=len(взято))
    return [взято[n] for n in np.argsort(-сколько, kind='stable')]


# ---------------------------------------------------------------- числа места

def _место(снимок, px_на_мм, предел, сторона, окно):
    """Числа куска снимка — те же, что `мерка` этого куска: мазки разбором и их форма, края пятен, тон в пятне, края, направления
    (кусок мельче окна — None)."""
    from . import манера as М
    rgb = М._к_рабочему(снимок.astype(np.float64), px_на_мм)
    L = глаз._L(глаз.oklab(rgb)[..., 0])
    мазки, края_пятен, _ = М._разбором(снимок, px_на_мм, предел, сторона)
    return {'мазки разбором': мазки, 'края пятен': края_пятен,
            'тон в пятне': М._тон_в_пятне(L)[1], 'края': М._края_места(L, px_на_мм)[0],
            'направления': М._направления(L, окно * М.РАБОЧИЙ)[0] if min(rgb.shape[:2]) >= окно * М.РАБОЧИЙ else None}


def _задача(а):
    return _место(*а)


def _разом(задачи, ядра=None):
    """`_место` каждой задачи: процессами (не больше `ПРОЦЕССОВ`, ядер и задач), в процессе-работнике — подряд."""
    n = min(ядра or ПРОЦЕССОВ, ПРОЦЕССОВ, len(os.sched_getaffinity(0)) if hasattr(os, 'sched_getaffinity') else os.cpu_count() or 1,
            len(задачи))
    if n < 2 or multiprocessing.current_process().daemon or 'fork' not in multiprocessing.get_all_start_methods():
        return [_задача(а) for а in задачи]
    with multiprocessing.get_context('fork').Pool(n) as пул:
        return пул.map(_задача, задачи, chunksize=1)


def _кусок(м, клетка):
    x0, y0, x1, y1 = клетка
    return (м.массивы['снимок'][y0:y1, x0:x1], м.px_на_мм, м.откуда['предел'], м.откуда['сторона'], м.откуда['окно'])


