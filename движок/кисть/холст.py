def _общий(форма, чем=0.0):
    """Массив float32 в общей памяти (анонимный mmap, полон нулями или `чем`): процессы счёта мазков (`ядра.py`) пишут
    в него же. Занимает память, как обычный: страницы берутся, когда в них пишут."""
    n = 4 * int(np.prod(форма))
    if n == 0:
        return np.zeros(форма, np.float32)
    a = np.frombuffer(mmap.mmap(-1, n), dtype=np.float32).reshape(форма)
    if чем:
        a[...] = чем
    return a


def _в_общей(a):
    if isinstance(a, Плитки):
        return a.общая
    while isinstance(a, np.ndarray):         # вид вида …: в конце цепочки — владелец памяти
        a = a.base
    if isinstance(a, memoryview):
        a = a.obj
    return isinstance(a, mmap.mmap)


def _в_общую(a):
    """Копия массива в общей памяти (сам он — если уже там)."""
    if isinstance(a, Плитки):
        return a if a.общая else a.своя(общая=True)
    if a is None or _в_общей(a) or a.nbytes == 0 or a.dtype != np.float32:
        return a
    н = _общий(a.shape)
    н[...] = a
    return н


def _поле_слоя(имя, по_надобности=False, doc=None):
    """Массив слоя — свойством: пока мазки холста считаются на ядрах (`ядра.py`), чтение массива сперва досчитывает их
    (у слоя холста с очередью — `_ждать`); у прочих слоёв — просто массив."""
    слот = '_' + имя

    def взять(self):
        try:
            ждать = self._ждать
        except AttributeError:
            ждать = None
        if ждать is not None:
            ждать()
        return getattr(self, слот, None) if по_надобности else getattr(self, слот)

    def дать(self, a):
        setattr(self, слот, a)

    return property(взять, дать, doc=doc)


def записать_рамку(х, r):
    """К-3: рамка мазка — в `х._рамки` по метке строки журнала (`х._метка`), если повтор их собирает; обрезана по
    холсту, пустая — None (мазок холста не тронул)."""
    рамки = х.__dict__.get('_рамки')
    if рамки is None:
        return
    if r is not None:
        r = (max(int(r[0]), 0), max(int(r[1]), 0), min(int(r[2]), х.полная_ширина), min(int(r[3]), х.полная_высота))
        if r[2] <= r[0] or r[3] <= r[1]:
            r = None
    рамки.setdefault(х.__dict__.get('_метка'), []).append(None if r is None else list(r))


class _Рамка(Exception):
    """Мазок дошёл до своей рамки и остановлен: её просили без самого мазка (`Холст.прямоугольник_мазка`, `ядра.py`)."""


class _ТолькоРамка(dict):
    """Словарь «почему пусто» мазка, который считается только до рамки: как мазок её назвал — стоп, до чтения и записи холста."""

    def __setitem__(self, ключ, v):
        if ключ == 'рамка':
            raise _Рамка(v)
        super().__setitem__(ключ, v)


class _ВОбласти(dict):
    """2г: «почему пусто» мазка варианта (`варианты`): рамка мазка (что он прочтёт и запишет) — только в области куска."""

    def __init__(self, область, ш, в):
        super().__init__()
        self.область, self.ш, self.в = область, ш, в

    def __setitem__(self, ключ, v):
        if ключ == 'рамка':
            x0, y0, x1, y1 = self.область
            r = (max(v[0], 0), max(v[1], 0), min(v[2], self.ш), min(v[3], self.в))
            if r[2] > r[0] and r[3] > r[1] and not (x0 <= r[0] and y0 <= r[1] and r[2] <= x1 and r[3] <= y1):
                raise ValueError(f'варианты: мазок куска читает и пишет {r} (след с полями: смешение, вал, сырое под ним) — '
                                 f'это шире области {self.область}; область — шире на поле мазка (`х.прямоугольник_мазка` '
                                 'с доводами мазка), или мазки — внутрь')
        super().__setitem__(ключ, v)


class _ВОбластиДоРамки(_ВОбласти):
    """У-2: разведка `варианты` — рамка мазка сверяется с областью куска (вышла — ValueError), и мазок стоит: дальше
    рамки не считается, холст не читается и не пишется."""

    def __setitem__(self, ключ, v):
        super().__setitem__(ключ, v)
        if ключ == 'рамка':
            raise _Рамка(v)


