    def прижать(self, точки, кисть=None, ширина=None, слой=None, глубина=None, этап=None, объект=None, намерение=None):
        """М-3: ход мастихина плашмя по высохшей краске — срезать то, что выше плоскости ножа: вершины сухого вала,
        гребни пастоза, резкий бугор. точки — (x, y, нажим[, …]), как у мазка (`жест`, `путь_с_нажимом`, сырые точки);
        кисть — мастихин (берётся его ширина) или ширина — длина кромки, px. Нажим до 0,3 — нож едет по вершинам и
        ничего не берёт; 0,6 — полпути к телу; от 0,9 лезвие садится на тело краски под собой (медиана высот краски под
        подошвой 4 мм × кромка; голый грунт рядом не в счёт) и ниже не идёт: гребни пастоза срезаются до его середины,
        и на косом ходе у кромки вала тоже; вал на ровном тонком слое срезается до слоя.
        глубина — мм (None — без предела): осторожный ход, ниже самой высокой точки под ножом больше чем на столько
        лезвие за ход не садится.
        Срезанное (сухое и сырое) уходит на нож и с холста; цвет слоя на месте, грунт и зерно не режутся. слой — имя
        (режется только он, и не под целой краской другого слоя) или None (все, сверху вниз). Кисть ворса сухое по-прежнему не мнёт. Это правка места:
        срезанная площадка гладкая, много таких — лист как пластик (подсказка «срезано ножом»). В журнале — строка с
        "tool": "нож". Ответ — `Прижато`: `срезано` px, `на_нож` (объём), `доля`, `глубже` мм, `почему` — если пусто."""
        from .правка import прижать
        if self.__dict__.get('_только_в') is not None:
            raise ValueError('варианты: прижать в куске нельзя (рамку хода с областью не сверить) — прижимать до варианты или после взять')
        if (кисть is None) == (ширина is None):
            raise ValueError('прижать: нужен нож — кисть=Кисть мастихин или ширина= (длина кромки, px), одно из двух')
        if кисть is not None:
            if кисть.форма != 'мастихин':
                raise ValueError(f'прижать: это ход ножа — кисть формы «мастихин», не «{кисть.форма}» (ворс сухое не режет)')
            if (кисть.ширина_мм is not None or кисть.шаг_мм is not None) and self.px_на_мм is None:
                raise ValueError('кисть в мм: у холста не задан px_на_мм')
            ширина = кисть.в_пикселях(self.px_на_мм).ширина
        self.__dict__['_правок'] = self.__dict__.get('_правок', 0) + 1   # 2г: правка холста — варианты, считанные до неё, не годны
        ж = self._пишет()
        if ж is not None:
            from .журнал import _в_json
            д = {'tool': 'нож', 'size': _в_json(ширина), 'core': _в_json(np.asarray(точки, np.float64)), 'seed': 0}
            if глубина is not None:
                д['depth'] = _в_json(глубина)
            if слой is not None:
                д['layer'] = str(слой)
            ж.строка(ж._намерение(д, этап, объект, намерение))
        elif getattr(self, '_вне_журнала', False):
            self._вне_журнала = 'мазки'
        о = прижать(self, точки, float(ширина), слой, глубина)
        п = self._п()
        if п is not None and о.срезано:
            п.срезано(self, о._клетки)
        return о

    # ------------------------------------------------------------ сохранение
    def сохранить(self, путь, сверх=None):
        """Состояние холста в .npz: слои целиком (и след текучей кисти, К4), счётчик мазков, грунт, зерно.
        сверх (К3) — (словарь, массивы) того, кто пишет файл: словарь (JSON) — в мету, массивы — рядом под именами
        `x_<имя>`; так `кисть.повтор` кладёт в файл кисти и место в журнале. Тот же холст — тот же файл байт в байт.
        Ответ — `Сохранено`: путь, счётчик мазков, `подсказки` — новые с прошлой выдачи (М-2+М-4-2)."""
        self._граница()
        мета = {'ширина': self.ширина, 'высота': self.высота, 'грунт': self.грунт_srgb,
                'слои': list(self.слои), 'счётчик': self._счётчик}
        if self._повторы is not None and (self.сид or self._этап is not None or self._объект is not None):
            мета.update(сид=self.сид, этап=self._этап, объект=self._объект)
        if self.зерно is not None:
            мета.update(зерно=self.зерно, px_на_мм=self.px_на_мм)
        elif self.px_на_мм is not None:
            мета.update(px_на_мм=self.px_на_мм)
        if self.__dict__.get('_замесы'):     # М-1: палитра — с холстом (повтор с точки, `загрузить`)
            from .журнал import цвет_строки
            мета['палитра'] = [[и, цвет_строки(Краска(tuple(з), з.вид))] for и, з in self._замесы.items()]
        if self._пишет() is not None:
            self.журнал.сохранён(путь, self._счётчик)       # А-1: строка {"saved": …} — `загрузить(…, журнал=)` продолжит с неё
        п = self._п()
        if п is not None:
            п.сохранён(self, путь)                          # 5б: счёт подсказок на это сохранение; граница
        if сверх is not None:
            мета['сверх'] = сверх[0]
        if self.__dict__.get('_ленты'):       # Н-3: ленты скотча — с холстом: маска, что под ней, затёк
            мета['ленты'], ленты_м = [], {}
            имена = list(self.слои)
            for j, л in enumerate(self._ленты):
                мета['ленты'].append({'имя': л.имя, 'слой': л.слой, 'высота_мм': л.высота_мм,
                                      'под': {и: sorted(поля) for и, поля in л.под.items() if и in имена}})   # слой убран — его нет
                ленты_м[f'L{j}m'] = л.маска
                ленты_м[f'L{j}z'] = л.затёк
                for и, поля in л.под.items():
                    for поле, a in (sorted(поля.items()) if и in имена else ()):
                        ленты_м[f'L{j}_{имена.index(и)}_{поле}'] = a
        массивы = {'мета': np.array(json.dumps(мета, ensure_ascii=False))}
        if self._повторы:                    # А-9: мазки, уже легшие с теми же точками в объекте
            к = np.array(sorted(self._повторы), dtype=np.uint64)
            массивы['повторы'] = np.column_stack([к, np.array([self._повторы[int(v)] for v in к], dtype=np.uint64)])
        for i, с in enumerate(self.слои.values()):
            массивы[f'c{i}'] = с.цвет
            массивы[f'a{i}'] = с.покрытие
            массивы[f'h{i}'] = с.толщина
            массивы[f'w{i}'] = с.влажность
            массивы[f's{i}'] = с.схват
            if с.пропуск is not None:
                массивы[f't{i}'] = с.пропуск
            if с.текучая is not None:
                массивы[f'l{i}'] = с.текучая
        if мета.get('ленты'):
            массивы.update(ленты_м)
        if сверх is not None:
            массивы.update((f'x_{имя}', a) for имя, a in сверх[1].items())
        ответ = Сохранено(путь, self._счётчик, [] if п is None else п.новые())
        # как np.savez_compressed, но время записи в архив не идёт: один холст — один файл. Пишется рядом и встаёт на
        # место целиком (1г): обрыв не оставляет битого файла, а файл, на который смотрит жёсткая ссылка (точка повтора
        # под тем же `--save`), не переписывается на месте — ссылка рвётся, точка остаётся как была
        цель = os.fspath(путь) if isinstance(путь, (str, os.PathLike)) else None
        куда = путь if цель is None else f'{цель}.часть{os.getpid()}'
        try:
            with zipfile.ZipFile(куда, 'w', zipfile.ZIP_DEFLATED, allowZip64=True) as z:
                # М-9: поля сжимаются в потоках, по порядку и тем же zlib, что у zipfile, — файл тот же байт в байт
                сжатые = _по_порядку(_сжать_npy, ((a,) for a in массивы.values()), self._потоков())
                for (имя, a), готово in zip(массивы.items(), сжатые):
                    запись = zipfile.ZipInfo(имя + '.npy', date_time=(1980, 1, 1, 0, 0, 0))
                    запись.compress_type = zipfile.ZIP_DEFLATED
                    with z.open(запись, 'w', force_zip64=True) as f:
                        if not _вписать_сжатое(f, готово):
                            np.lib.format.write_array(f, np.asanyarray(a), allow_pickle=False)
            if цель is not None:
                os.replace(куда, цель)
        except BaseException:
            if цель is not None and os.path.exists(куда):
                os.remove(куда)
            raise
        self._записать_путь_журнала(путь)
        return ответ

    def _записать_путь_журнала(self, путь):
        """М-10 (а): путь журнала, которым описан холст, — в файл рядом `<путь>.путь_журнала` (полный и относительно `.npz`):
        `загрузить` без `журнал=` возьмёт его для чтения. Не в сам `.npz`: тот же холст — тот же файл байт в байт, с каким
        бы журналом и где он ни писался (повтор, два процесса). Журнала нет — прежний файл рядом убирается."""
        if not isinstance(путь, (str, os.PathLike)):
            return
        рядом = os.fspath(путь) + '.путь_журнала'
        ж = self.журнал_путь
        if ж is None:
            if os.path.exists(рядом):
                os.remove(рядом)
            return
        з = {'путь': os.path.abspath(ж), 'рядом': os.path.relpath(os.path.abspath(ж), os.path.dirname(os.path.abspath(путь))),
             'счётчик': self._счётчик}
        with open(рядом + '.часть', 'w', encoding='utf-8') as f:
            json.dump(з, f, ensure_ascii=False)
        os.replace(рядом + '.часть', рядом)

    @classmethod
    def загрузить(cls, путь, сверх=False, журнал=None, ядра=None, подсказки=None):
        """Холст из файла `сохранить`. сверх=True (К3) — ответ (холст, словарь, массивы): что положил в файл пишущий
        (`сохранить(…, сверх=)`); словарь None — в файле этого нет. журнал (А-1) — путь журнала, с которым холст писался:
        журнал обрезается до строки {"saved": …} этого файла и пишется дальше (правка этапа 5 с `этап4.npz` — строки
        этапов 5… уходят). Без `журнал=` (М-10 (а)) — журнал из `<путь>.путь_журнала` только для чтения (`журнал_путь`). В журнале такой строки нет — ValueError. ядра, подсказки — как у `Холст(…)`; с журналом подсказки
        берут свой счёт на этом сохранении (`<журнал>.подсказки.json`)."""
        with np.load(путь) as д:
            мета = json.loads(str(д['мета']))
            поля = {}
            if 'px_на_мм' in мета:
                поля['px_на_мм'] = мета['px_на_мм']
            if 'зерно' in мета:
                поля['зерно'] = мета['зерно']
            х = cls(мета['ширина'], мета['высота'], мета['грунт'], ядра=ядра, подсказки=False if журнал is not None else подсказки, **поля)
            общая = lambda a, пусто=0.0: Плитки.из(a, пусто, общая=х._ядер != 1)   # 2в: плитками; 2б: на ядрах — в общей памяти
            х._счётчик = мета.get('счётчик', 0)
            х.сид, х._этап, х._объект = int(мета.get('сид', 0)), мета.get('этап'), мета.get('объект')
            if 'повторы' in д:
                х._повторы = {int(к): int(n) for к, n in д['повторы']}
            if мета.get('палитра'):
                from .палитра import замес
                from .повтор import _цвет
                х._замесы = {и: замес(и, _цвет(поля_цвета)) for и, поля_цвета in мета['палитра']}
            for i, имя in enumerate(мета['слои']):
                с = Слой.__new__(Слой)
                с.цвет = общая(д[f'c{i}'])
                с.покрытие = общая(д[f'a{i}'])
                с.толщина = общая(д[f'h{i}'])
                с.влажность = общая(д[f'w{i}'])
                с.схват = общая(д[f's{i}']) if f's{i}' in д else общая(np.zeros(с.влажность.shape, np.float32))
                с.пропуск = общая(д[f't{i}'], 1.0) if f't{i}' in д else None
                с.текучая = общая(д[f'l{i}']) if f'l{i}' in д else None
                х._слои[имя] = с
            if мета.get('ленты'):                # Н-3: ленты скотча
                from .скотч import Лента
                х._ленты = []
                for j, о in enumerate(мета['ленты']):
                    л = Лента(о['имя'], д[f'L{j}m'], о['слой'], о['высота_мм'])
                    л.затёк = np.array(д[f'L{j}z'])
                    л.под = {и: {п: np.array(д[f'L{j}_{мета["слои"].index(и)}_{п}']) for п in поля} for и, поля in о['под'].items()}
                    х._ленты.append(л)
            х._загружен_из = os.path.basename(os.fspath(путь)) if isinstance(путь, (str, os.PathLike)) else None
            if журнал is not None:
                from .журнал import Журнал
                х.журнал = Журнал(журнал, х, продолжить=(путь, х._счётчик))
                х._этап, х._объект = х.журнал.этап, х.журнал.объект
                х._подсказки = Подсказки(х, _подсказки_включены(подсказки), журнал, новый=False)
                if х._подсказки.вкл:
                    х._подсказки.загружен(х, путь, х._счётчик)    # 5б: С3 — пуск с этого сохранения
            elif isinstance(путь, (str, os.PathLike)) and os.path.isfile(os.fspath(путь) + '.путь_журнала'):
                with open(os.fspath(путь) + '.путь_журнала', encoding='utf-8') as f:     # М-10 (а): только для чтения
                    запись = json.load(f)
                ж = _найти_журнал(запись, путь)
                х._журнал_чтения = (ж, х._счётчик, запись.get('путь'),
                                    None if ж is None else _до_сохранения(ж, путь, х._счётчик))
            if сверх:
                return х, мета.get('сверх'), {имя[2:]: д[имя] for имя in д.files if имя.startswith('x_')}
        return х

    @property
    def журнал_путь(self):
        """М-10 (а): путь журнала, которым описан холст — тот, что он пишет (`журнал=`), или взятый для чтения из `.npz`
        (`загрузить` без `журнал=`, пока на холст не легло новых мазков); None — журнала нет. По нему читают
        `однообразие`, `регулярность`, `виды`, `манера`; его же — `python3 -m кисть.повтор <путь>`."""
        ж = getattr(self, 'журнал', None)
        if ж is not None:
            return ж.путь
        ч = self.__dict__.get('_журнал_чтения')
        if ч is None or ч[0] is None or ч[1] != self._счётчик:
            return None
        return ч[0]

    # ----------------------------------------------------------------- сборка
    def рельеф(self, y0=0, y1=None, x0=0, x1=None, полный=False, зерно=True):
        """Суммарная толщина краски по слоям: толщина копится от слоя к слою.

        Верхний слой заливает неровности нижнего: под его краской рельеф нижних слоёв берётся
        ослабленным (на ЗАЛИВКА = 70 % при полном покрытии) — иначе борозды нижнего мазка
        проступают сквозь верхний и он кажется прозрачным. полный=True — простая сумма."""
        y1 = self.высота if y1 is None else y1
        x1 = self.ширина if x1 is None else x1
        h = np.zeros((y1 - y0, x1 - x0), np.float32)
        for i, с in enumerate(self.слои.values()):
            if i and not полный:
                h *= 1.0 - ЗАЛИВКА * с.покрытие[y0:y1, x0:x1]
            h += с.толщина[y0:y1, x0:x1]
        if зерно and getattr(self, '_зерно', None) is not None:
            # п. 5б: зерно грунта под краской — тонкая плёнка идёт по нитям, толстая заливает ямки
            всего = sum(с.толщина[y0:y1, x0:x1] for с in self.слои.values()) if self.слои else 0.0
            h += self._зерно.залито(self._высота_зерна(y0, y1, x0, x1), всего)
        return h

    def _высота_зерна(self, y0, y1, x0, x1):
        """М-9: высота зерна грунта под строками y0:y1, столбцами x0:x1 массива холста — из запаса полосами по
        `_ПОЛОСА_ЗЕРНА` строк во всю ширину: зерно не меняется, а вывод большого холста считал его заново на каждую
        полосу и каждый взгляд. Значения те же бит в бит (`Зерно.высота` поточечна). Запас — этого процесса: в копию и
        в pickle не идёт."""
        з = self.__dict__.get('_запас_зерна')
        if з is None or з[0] is not self._зерно or з[1] != (self.x0, self.y0, self.ширина, self.высота):
            з = self._запас_зерна = (self._зерно, (self.x0, self.y0, self.ширина, self.высота), {})
        полосы, П = з[2], _ПОЛОСА_ЗЕРНА
        части = []
        for п in range(y0 // П, -(-y1 // П)):
            a = полосы.get(п)
            if a is None:
                a = полосы[п] = self._зерно.высота(self.x0, self.y0 + п * П, self.x0 + self.ширина,
                                                   self.y0 + min(self.высота, (п + 1) * П))
            части.append(a[max(y0 - п * П, 0):min(y1 - п * П, П), x0:x1])
        return части[0].copy() if len(части) == 1 else np.concatenate(части)

    def _без_канавы(self, y0, y1, x0, x1):
        """К9. Поправка к наклону рельефа (по x, по y) для света, или None, если слои не лежат друг на друге.

        `рельеф` берёт толщу нижних слоёв под краской верхнего ослабленной — так заливаются их борозды. Но у кромки
        верхнего слоя от этого встаёт ступень, которой на холсте нет: тонкая плёнка будто роет в толстом слое канаву
        во всю свою ширину, и стенка канавы под светом — белый контур вокруг бледного хода. Наклон рельефа — это
        наклон толщины слоёв (ослабленный под краской выше) и та самая ступень: толщина слоя на перепад его
        закрытости. Ступень здесь и считается, чтобы свет её вычел; под самой краской и на открытом месте она —
        ровно ноль, там свет прежний бит в бит. Поле счёта — тот же 1 px, что у света. Ступень от кромки некроющего слоя
        (у слоя есть `пропуск`) не вычитается."""
        слои = list(self.слои.values())
        открыто, вуаль, kx, ky = None, None, None, None    # доля рельефа, не залитая кроющими слоями выше и некроющими
        for i in range(len(слои) - 1, 0, -1):
            a = слои[i].покрытие[y0:y1, x0:x1]
            if слои[i].пропуск is not None:      # некроющий слой (лессировка, вуаль): его ступень остаётся как была —
                if a.any():                      # с ней мерены пороги п. 10, инструмент 3 (`test_лессировка`); долг
                    вуаль = 1.0 - ЗАЛИВКА * a if вуаль is None else вуаль * (1.0 - ЗАЛИВКА * a)
            elif открыто is not None or a.any():
                открыто = 1.0 - ЗАЛИВКА * a if открыто is None else открыто * (1.0 - ЗАЛИВКА * a)
            t = слои[i - 1].толщина[y0:y1, x0:x1]
            if открыто is None or not t.any():
                continue
            if kx is None:
                kx, ky = np.zeros(t.shape, np.float32), np.zeros(t.shape, np.float32)
            # те же разности, что в `свет.множители`: середина — полуразность соседей, край массива — односторонняя
            в = t if вуаль is None else t * вуаль
            kx[:, 1:-1] += (в[:, 2:] + в[:, :-2]) * (открыто[:, 2:] - открыто[:, :-2]) * 0.25
            kx[:, 0] += (в[:, 1] + в[:, 0]) * (открыто[:, 1] - открыто[:, 0]) * 0.5
            kx[:, -1] += (в[:, -1] + в[:, -2]) * (открыто[:, -1] - открыто[:, -2]) * 0.5
            ky[1:-1] += (в[2:] + в[:-2]) * (открыто[2:] - открыто[:-2]) * 0.25
            ky[0] += (в[1] + в[0]) * (открыто[1] - открыто[0]) * 0.5
            ky[-1] += (в[-1] + в[-2]) * (открыто[-1] - открыто[-2]) * 0.5
        return None if kx is None else (kx, ky)

    def картинка(self, свет=True, сила=None, область=None, тень=0.0, поверхность=None):
        """Готовая картинка, линейный свет, float32 (В, Ш, 3). область = (x0, y0, x1, y1) холста: считается только она
        (со светом — с полем 2 · `свет.поле_перелива()` + 1 px), и она равна тому же месту полной картинки. У участка свет
        у его края считается без соседей: брать область не ближе этого поля к краю участка (если тот не край холста).
        тень — сила падающей тени по рельефу (п. 20): 0 — нет, картинка как была; True — рабочая сила
        (`свет.ТЕНЬ_РАБОЧАЯ`); с тенью поле области — `свет.ПОЛЕ_ТЕНИ` px больше.
        Г-2: со светом светлая краска возвращает свет, ушедший с наклонов (`свет.ПЕРЕОТРАЖЕНИЕ`), а свет выше белого
        переливается к соседям (`свет.перелить`) — белила под светом не серят. поверхность — ключ вывода
        ('матовое', 'полуматовое', 'лак'; None — умолчание: слабый узкий блик без дымки): блик и насыщение под плёнкой масла; без света ключ
        ничего не меняет; журнал, слои и холст не трогает."""
        _свет.поверхность_вывода(поверхность)
        if область is None and not self.__dict__.get('_в_глазу'):
            п = self._п()
            if п is not None:
                п.вывод(self)                   # 5б: С4 — холст выведен целиком
        return self._картинка(свет, сила, область, тень, поверхность)

    def _картинка(self, свет, сила, область, тень, поверхность, полосами=True):
        """`картинка` без подсказки вывода; полосами=False — область одним куском (полоса `png`)."""
        гy, гx = self._область(область)
        x0, y0, x1, y1 = гx.start, гy.start, гx.stop, гy.stop
        if not (свет and (self.слои or getattr(self, '_зерно', None) is not None)):
            return self._цвет(y0, y1, x0, x1)
        тень = _сила_тени(тень)
        полосы = self._полосы_картинки(y0, y1, x1 - x0) if полосами else None
        if полосы is not None:          # М-9: большая область — полосами в потоках: память полосы, а не холста
            self._граница()
            к = np.empty((y1 - y0, x1 - x0, 3), np.float32)

            def полоса(a, b):
                return self._картинка_света(x0, a, x1, b, сила, тень, поверхность)
            with в_мм(self.px_на_мм):
                for (a, b), п in zip(полосы, _по_порядку(полоса, полосы, self._потоков())):
                    к[a - y0:b - y0] = п
            return к
        return self._картинка_света(x0, y0, x1, y1, сила, тень, поверхность)

    def _картинка_света(self, x0, y0, x1, y1, сила, тень, поверхность):
        """Картинка со светом строк y0:y1, столбцов x0:x1 массива холста одним куском (`картинка`)."""
        with в_мм(self.px_на_мм):          # Д-8: высота рельефа и перелив в px этого холста
            пп = _свет.поле_перелива()
            поле = (_свет.ПОЛЕ_ТЕНИ if тень else 1) + 2 * пп
            ya, yb = max(0, y0 - поле), min(self.высота, y1 + поле)
            xa, xb = max(0, x0 - поле), min(self.ширина, x1 + поле)
            h = self.рельеф(ya, yb, xa, xb)
            м, б = _свет.множители(h, _свет.СИЛА_ПО_УМОЛЧАНИЮ if сила is None else сила, тень,
                                    self._без_канавы(ya, yb, xa, xb), поверхность)
            D = _свет.недостача(м)
            # перелив берёт соседей не дальше `пп` px: считается на области с этим полем, затем вырезается
            ca, cb = max(ya, y0 - пп), min(yb, y1 + пп)
            da, db = max(xa, x0 - пп), min(xb, x1 + пп)
            в = (slice(ca - ya, cb - ya), slice(da - xa, db - xa))
            к = _свет.перелить(_свет.вывести(self._цвет(ca, cb, da, db), м[в], б[в], D[в], поверхность))
        return np.ascontiguousarray(к[y0 - ca:y0 - ca + (y1 - y0), x0 - da:x0 - da + (x1 - x0)])

    def _цвет(self, y0, y1, x0, x1):
        """Цвет красок без света, линейный, float32 (В, Ш, 3), строки y0:y1, столбцы x0:x1 массива холста."""
        к = np.empty((y1 - y0, x1 - x0, 3), np.float32)
        к[:] = self.грунт
        for с in self.слои.values():
            a = с.покрытие[y0:y1, x0:x1, None]
            if с.пропуск is not None:        # п. 10, инструмент 3: не кроющая краска слоя темнит то, что под ним, на просвет
                к *= с.пропуск[y0:y1, x0:x1]
            к += (с.цвет[y0:y1, x0:x1] - к) * a
        return к

