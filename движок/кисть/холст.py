def _писать_png(путь, высота, ширина, каналов, полосы, текст=None):
    """Свой писатель PNG 16 бит (Pillow не пишет 16-битный RGB/RGBA).
    полосы — генератор массивов uint16 (строк, ширина, каналов). текст — {ключ: значение} ASCII: куски tEXt (М-10: мм на
    уровень серого у карт толщины и высот); пиксели от них не меняются."""
    тип = {1: 0, 2: 4, 3: 2, 4: 6}[каналов]

    def кусок(имя, данные):
        return (struct.pack('>I', len(данные)) + имя + данные
                + struct.pack('>I', zlib.crc32(имя + данные) & 0xffffffff))

    bpp = 2 * каналов
    with open(путь, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n')
        f.write(кусок(b'IHDR', struct.pack('>IIBBBBB', ширина, высота, 16, тип, 0, 0, 0)))
        f.write(кусок(b'gAMA', struct.pack('>I', 45455)))
        f.write(кусок(b'sRGB', b'\x00'))
        for к, v in (текст or {}).items():
            f.write(кусок(b'tEXt', str(к).encode('latin-1') + b'\x00' + str(v).encode('latin-1')))
        сжатие = zlib.compressobj(4)
        for п in полосы:
            п = np.ascontiguousarray(п, dtype=np.uint16).reshape(п.shape[0], ширина * каналов)
            б = п.astype('>u2').view(np.uint8).reshape(п.shape[0], ширина * bpp)
            строки = np.empty((б.shape[0], б.shape[1] + 1), np.uint8)
            строки[:, 0] = 1                                   # фильтр Sub
            строки[:, 1:bpp + 1] = б[:, :bpp]
            строки[:, bpp + 1:] = б[:, bpp:] - б[:, :-bpp]
            д = сжатие.compress(строки.tobytes())
            if д:
                f.write(кусок(b'IDAT', д))
        д = сжатие.flush()
        if д:
            f.write(кусок(b'IDAT', д))
        f.write(кусок(b'IEND', b''))


def _по_порядку(f, куски, n):
    """М-9: f(*кусок) для каждого куска — в n потоках (numpy отпускает GIL), ответы — по порядку кусков; вперёд считается
    не больше n + 1 кусков (память — как у n + 1 полос). n = 1 — по одному в этом потоке, как прежде. Пока вызывающий
    сжимает готовую полосу, потоки считают следующие: файл тот же байт в байт — сжатие идёт по порядку, одним потоком."""
    if n <= 1:
        for к in куски:
            yield f(*к)
        return
    from collections import deque
    from concurrent.futures import ThreadPoolExecutor
    with ThreadPoolExecutor(n) as пул:
        очередь = deque()
        for к in куски:
            очередь.append(пул.submit(f, *к))
            if len(очередь) > n:
                yield очередь.popleft().result()
        while очередь:
            yield очередь.popleft().result()


class _Сжатое:
    """М-9: поле .npy, уже сжатое (`_сжать_npy`): куски deflate, crc32 и длина несжатого."""
    __slots__ = ('куски', 'crc', 'длина', '_z')

    def __init__(self):
        self.куски, self.crc, self.длина = [], 0, 0

    def write(self, данные):
        м = memoryview(данные)
        self.crc = zlib.crc32(м, self.crc)
        self.длина += м.nbytes
        self.куски.append(self._z.compress(м))
        return м.nbytes


def _сжать_npy(a):
    """М-9: массив -> `_Сжатое`: .npy (`np.lib.format.write_array`) тем же deflate, что пишет zipfile в ZIP_DEFLATED
    (уровень по умолчанию, сырой поток) — в своём потоке, пока прочие поля пишутся. zlib отпускает GIL."""
    с = _Сжатое()
    с._z = zlib.compressobj(zlib.Z_DEFAULT_COMPRESSION, zlib.DEFLATED, -15)
    np.lib.format.write_array(с, np.asanyarray(a), allow_pickle=False)
    с.куски.append(с._z.flush())
    del с._z
    return с



class _Отдать:
    """Вместо сжимателя записи zipfile: при закрытии отдаёт готовые сжатые байты."""
    def __init__(self, куски):
        self._куски = куски

    def compress(self, данные):          # не зовётся: в запись пишется уже сжатое
        raise RuntimeError('М-9: запись поля уже сжата')

    def flush(self):
        к, self._куски = self._куски, []
        return b''.join(к)


def _вписать_сжатое(f, готово):
    """М-9: в открытую запись zipfile — уже сжатое поле. Внутренности записи у zipfile CPython не на виду: если они не те,
    что ждём (другая версия Python), — False, и поле пишется прежним путём (то же, только дольше)."""
    if not (isinstance(готово, _Сжатое) and type(getattr(f, '_compressor', None)) is _ТИП_СЖАТИЯ
            and getattr(f, '_crc', None) == 0 and getattr(f, '_file_size', None) == 0 and getattr(f, '_compress_size', None) == 0):
        return False
    f._compressor, f._crc, f._file_size = _Отдать(готово.куски), готово.crc, готово.длина
    return True


_ТИП_СЖАТИЯ = type(zlib.compressobj(zlib.Z_DEFAULT_COMPRESSION, zlib.DEFLATED, -15))


