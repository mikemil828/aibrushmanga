        с.старшие = [(r, len(r().записи)) for r in живые]         # длина записей старших на миг взятия (п. 14 (б))
        с.журнал = None if getattr(self, 'журнал', None) is None else self.журнал.место()   # А-5: откат обрежет и журнал
