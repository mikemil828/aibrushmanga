        ломаная_дана = bool(ломаная)
        дано = точки
        self.__dict__['_правок'] = self.__dict__.get('_правок', 0) + 1   # 2г: правка холста — варианты, считанные до неё, не годны
        точки, краски, раскладка = self._разобрать_мазок(точки, цвет, кисть, раскладка, нагрузка, ломаная, волокна)
        разбавитель = проверить_разбавитель(разбавитель, кисть.нагрузка if нагрузка is None else нагрузка)
        сид_листа = self.сид_мазка(точки, этап, объект, взять=True)   # и мазок со своим сидом в счёт повторов идёт
