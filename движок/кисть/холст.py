    @staticmethod
    def _пропуск(слой):
        """Массив пропуска слоя (п. 10, инструмент 3) — заводится с первой не кроющей краской в слое (в общей памяти,
        если там слой)."""
        if слой.пропуск is None:
            слой.пропуск = Плитки(слой.цвет.shape, 1.0, общая=_в_общей(слой.цвет))
        return слой.пропуск

    @staticmethod
    def _текучая(слой):
        """Массив следа текучей кисти слоя (К4) — заводится с первым текучим ходом в слое."""
        if слой.текучая is None:
            слой.текучая = Плитки(слой.толщина.shape, общая=_в_общей(слой.толщина))
        return слой.текучая

    def _до_записи(self, область):
        """Перед записью в прямоугольник холста: прежние пиксели — каждому живому снимку (слои, что были при нём)."""
        self.__dict__['_правок'] = self.__dict__.get('_правок', 0) + 1   # 2г: правка холста — варианты, считанные до неё, не годны
        if not getattr(self, '_снимки', None):
            return
        if область is None:
            область = (self.x0, self.y0, self.x0 + self.ширина, self.y0 + self.высота)
        живые = []
        for r in self._снимки:
            с = r()
            if с is None or с.холст is not self:
                continue
            живые.append(r)
            где = self._область(область)
            if где[0].stop > где[0].start and где[1].stop > где[1].start:
                с.записи.append(self._копия(область, [и for и in с.имена if и in self._слои and и not in с.убранные]))
        self._снимки = живые

    def править(self, ядра=None, путь=None, **правка):
        """К-3, А-7: правка задним числом — строки журнала этого холста (`журнал=`) по фильтру правятся, на холсте
        пересобирается только затронутое: после вызова холст и кисти — бит в бит как полный повтор правленого журнала.
        Фильтр и правка — доводы `кисть.задним.править_строки`: строки_с ("4-200"), слой, этап, объект, замес,
        область (x0, y0, x1, y1); удалить, цвет, новый_замес, dL, dC, dh, теплее, сдвиг (dx, dy), нагрузка, нажим,
        нажим_в, ширина. Прежний журнал — `<журнал>.до_правки`; снимки до правки гаснут. путь — PNG «до | после» по
        рамке затронутого 1:1. Ответ — `кисть.задним.Правка` (строк правлено, пересчитано, доля, площадь, время, как)."""
        from .задним import править_холст
        return править_холст(self, ядра=ядра, путь_png=путь, **правка)

    def откатить(self, снимок):
        """Вернуть холст к снимку бит в бит: все тронутые пиксели всех слоёв, новые слои убраны, счётчик и кисти снимка
        прежние. Снимок остаётся годен (можно класть и откатывать снова); снимки, взятые после него, гаснут."""
        с = снимок
        if not isinstance(с, Снимок) or с.холст is not self:
            raise ValueError('откатить: снимок не этого холста')
        if not any(r() is с for r in self._снимки):      # взят после снимка, к которому уже откатили
            raise ValueError('откатить: снимок погас')
        self._граница(пишу=True)
        self.__dict__['_правок'] = self.__dict__.get('_правок', 0) + 1   # 2г: правка холста — варианты, считанные до неё, не годны
        for имя in [и for и in self._слои if и not in с.имена or и in с.убранные]:
            del self._слои[имя]            # новые слои; и новый слой того же имени, что убран после снимка
        self._слои.update(с.убранные)       # убранные после снимка — на место, с их краской
        self._слои = {и: self._слои[и] for и in с.имена}       # порядок снимка
        с.убранные = {}
        не_было = set()
        for где, массивы in reversed(с.сразу + с.записи):
            for имя, поля in массивы.items():
                for поле, a in zip(Слой._ВСЕ, поля):
                    if a is not None:
                        getattr(self.слои[имя], поле)[где] = a
                    elif getattr(self.слои[имя], поле) is not None:      # пропуск, текучая: при снимке такого массива в слое не было
                        не_было.add((имя, поле))
        for имя, поле in не_было:          # и нет снова (2б): слой с пустым `пропуск` свет считал бы не кроющим, `сохранить` писал бы лишний массив
            setattr(self.слои[имя], поле, None)
        с.записи = []
        for r, длина in с.старшие:                                # холст — как на миг взятия с: записи старших,
            старший = r()                                           # взятые позже, не нужны (п. 14 (б))
            if старший is not None:
                del старший.записи[длина:]
        self._счётчик = с.счётчик
        if getattr(с, 'замесы', None) is not None and (с.замесы or self.__dict__.get('_замесы')):
            self._замесы = dict(с.замесы)
        self._повторы, self._этап, self._объект = (None if с.сиды[0] is None else dict(с.сиды[0])), с.сиды[1], с.сиды[2]
        if getattr(с, 'ленты', None):
            self._ленты = [л for л, _ in с.ленты]
            for л, затёк in с.ленты:
                л.затёк = затёк.copy()
        else:
            self.__dict__.pop('_ленты', None)
        if с.журнал is not None and getattr(self, 'журнал', None) is not None:
            self.журнал.откатить(с.журнал)
            р = self.__dict__.get('_рамки')
            if р is not None:                                   # К-3: рамки мазков, чьи строки откат снял
                for н in [н for н in р if isinstance(н, int) and н > self.журнал.строк]:
                    del р[н]
        п = self._п()
        if п is not None and getattr(с, 'подсказки', None) is not None:
            п.счёт = copy.deepcopy(с.подсказки)
        for к, остаток, краска in с.кисти:
            к._остаток, к._краска = copy.deepcopy(остаток), copy.deepcopy(краска)
        self._снимки = [r for r in self._снимки if r() is not None and r().номер <= с.номер]

    def __getstate__(self):
        self._граница()
        д = dict(self.__dict__)
        д['_снимки'] = []            # снимки — этого холста в этом процессе: в копию и в pickle не идут
        д['_ядра'] = None            # очередь мазков и её процессы — тоже: копия заведёт свои
        д['_подсказки'] = None       # 5б: подсказки — этого холста в этом процессе
        д.pop('_запас_зерна', None)  # М-9: запас высоты зерна — этого процесса, считается заново
        if д.get('журнал') is not None:   # файл журнала — этого процесса: копия в другом процессе пишет мимо него
            д['журнал'], д['_вне_журнала'] = None, True
        return д

    def __deepcopy__(self, memo):
        self._граница()
        н = Холст.__new__(Холст)
        memo[id(self)] = н
        for к, v in self.__dict__.items():
            setattr(н, к, [] if к == '_снимки' else None if к in ('журнал', '_ядра', '_подсказки', '_запас_зерна') else copy.deepcopy(v, memo))
        if н.__dict__.get('_ядер', 1) != 1:          # копия считает на ядрах, как и холст: её слои — в общей памяти
            for с in н._слои.values():
                for поле in Слой._ВСЕ:
                    setattr(с, поле, _в_общую(getattr(с, поле)))
        return н

    def проба(self, точки, цвет=None, кисть=None, область=None, свет=True, **как):
        """Пробный мазок с откатом: положить, снять картинку области (по умолчанию — изменённого прямоугольника),
        вернуть холст как был. Кисть не пачкается (мазок идёт её копией). Ответ: (прямоугольник, картинка) —
        картинка линейная float32 (`картинка`), None — если мазок холста не тронул."""
        if кисть is None:
            raise ValueError('проба: не задана кисть')
        self._граница(пишу=True)
        сид = как.pop('сид', None)
        сид = self.сид_мазка(точки, как.get('этап'), как.get('объект')) if сид is None else сид
        п = self.прямоугольник_мазка(точки, кисть, сид, цвет=цвет, точно=True, **как)
        if п is None:
            return None, None
        self.__dict__['_тишина'] = self.__dict__.get('_тишина', 0) + 1     # 5б: проба молчит
        с = self.снимок()                  # 11б: копирует только то, что мазок тронет
        ж = getattr(self, 'журнал', None)
        if ж is not None:
            ж.пауза += 1                     # проба в журнал не идёт
        try:
            изм = self.мазок(точки, цвет, кисть.копия(), сид=сид, **как)
            if изм is None:
                return None, None
            return изм, self.картинка(свет=свет, область=область or изм)
        finally:
            if ж is not None:
                ж.пауза -= 1
            self.откатить(с)
            self.__dict__['_тишина'] -= 1

    def _область(self, область):
        """Прямоугольник холста (x0, y0, x1, y1) -> срезы массивов (у участка — со сдвигом на его угол)."""
        if область is None:
            return slice(0, self.высота), slice(0, self.ширина)
        x0, y0, x1, y1 = (int(round(v)) for v in область)
        x0, x1, y0, y1 = x0 - self.x0, x1 - self.x0, y0 - self.y0, y1 - self.y0
        x0, y0 = min(max(x0, 0), self.ширина), min(max(y0, 0), self.высота)
        return slice(y0, max(min(y1, self.высота), y0)), slice(x0, max(min(x1, self.ширина), x0))

