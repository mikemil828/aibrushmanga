    def скотч(self, маска, слой=None, имя=None, высота_мм=None, этап=None, объект=None, намерение=None):
        """Н-3: малярная лента там, где `маска` (bool H×W холста) истинна. Краска мазков поверх ленты ложится на ленту,
        а не на холст и не на слой под ней; кромка — ступенька высоты ленты (0,1 мм — `высота_мм`), кисть идёт через неё
        по рельефу, как через гребень сухой краски: с ленты сходит не обрывом, у кромки по холсту до дна достаёт по
        нажиму и густоте. слой — None: лента на всех слоях; имя — лента только для мазков в этот слой (другие её не
        видят). имя — имя ленты (`снять_скотч(имя)`); None — «лента N». Пока лента лежит, `картинка` под ней — цвет
        грунта и краска на ленте; мазки считаются в этом процессе (без ядер). В журнале — строка {"tape": …}. Ответ — лента."""
        from . import скотч as С
        if (self.x0, self.y0, self.ширина, self.высота) != (0, 0, self.полная_ширина, self.полная_высота):
            raise ValueError('скотч: только на холсте целиком (не на участке и не в варианте)')
        маска = np.asarray(маска)
        if маска.shape != (self.высота, self.ширина):
            raise ValueError(f'скотч: маска {маска.shape} — нужна (высота, ширина) холста ({self.высота}, {self.ширина})')
        маска = маска.astype(bool)
        if not маска.any():
            raise ValueError('скотч: маска пуста — ленте негде лечь')
        if слой is not None and not isinstance(слой, str):
            raise ValueError('скотч: слой — имя слоя или None (все слои)')
        ленты = self.__dict__.setdefault('_ленты', [])
        if имя is None:
            n = len(ленты) + 1
            while any(л.имя == f'лента {n}' for л in ленты):
                n += 1
            имя = f'лента {n}'
        if any(л.имя == str(имя) for л in ленты):
            raise ValueError(f'скотч: лента «{имя}» уже лежит (ленты: {", ".join(л.имя for л in ленты)})')
        высота_мм = С.ВЫСОТА_ММ if высота_мм is None else float(высота_мм)
        if not 0.0 < высота_мм <= 1.0:
            raise ValueError('скотч: высота_мм — от 0 до 1 мм (малярная лента — 0,1)')
        self._граница(пишу=True)
        ж = self._пишет()
        if ж is not None:
            д = {'tape': str(имя), 'shape': [self.высота, self.ширина], 'mask': С.маска_в_строку(маска)}
            if слой is not None:
                д['layer'] = слой
            if высота_мм != С.ВЫСОТА_ММ:
                д['height'] = высота_мм
            ж.строка(ж._намерение(д, этап, объект, намерение))
        л = С.Лента(имя, маска, слой, высота_мм)
        y0, y1, x0, x1 = л.рамка
        self._до_записи((x0, y0, x1, y1))
        С.положить(self, л)
        ленты.append(л)
        return л

    def снять_скотч(self, имя=None, этап=None, объект=None, намерение=None):
        """Н-3: снять ленту `имя` (None — все, сверху вниз): краска на ней уходит с ней; под ней — что было до неё, бит в
        бит; за кромкой — краска как легла. У кромки — физика: текучая краска (разбавитель, `ровно`), лёгшая у кромки,
        затекла под ленту на доли мм (глубже с нажимом), густая — нет; сырой пастоз, лёгший через кромку, рвётся (часть
        тела у кромки уходит с лентой), сухой (`подсушить`) режется ровно. Лента под другой лентой — ValueError: сперва
        верхнюю. В журнале — строка {"untape": …}. Ответ — {имя: {'затёк': px, 'разрыв': px}}."""
        from . import скотч as С
        if (self.x0, self.y0, self.ширина, self.высота) != (0, 0, self.полная_ширина, self.полная_высота):
            raise ValueError('снять_скотч: только на холсте целиком (не на участке и не в варианте)')
        ленты = self.__dict__.get('_ленты') or []
        if not ленты:
            raise ValueError('снять_скотч: лент на холсте нет')
        if имя is None:
            снять = list(reversed(ленты))
        else:
            найдено = [л for л in ленты if л.имя == str(имя)]
            if not найдено:
                raise ValueError(f'снять_скотч: ленты «{имя}» нет (ленты: {", ".join(л.имя for л in ленты)})')
            л = найдено[0]
            выше = [в for в in ленты[ленты.index(л) + 1:] if (в.маска & л.маска).any() and (в.слой is None or л.слой is None or в.слой == л.слой)]
            if выше:
                raise ValueError(f'снять_скотч: на ленте «{л.имя}» лежит «{выше[0].имя}» — сперва её')
            снять = [л]
        self._граница(пишу=True)
        ж = self._пишет()
        if ж is not None:
            ж.строка(ж._намерение({'untape': None if имя is None else str(имя)}, этап, объект, намерение))
        итог = {}
        for л in снять:
            y0, y1, x0, x1 = л.рамка
            self._до_записи((x0, y0, x1, y1))
            итог[л.имя] = С.снять(self, л)
            ленты.remove(л)
        if not ленты:
            del self.__dict__['_ленты']
        return итог

