def _L(цвет, кто):
    """(L, sRGB) цвета (sRGB 0–255, `Краска`, `цвет(L, C, h)`) или числа L (серый)."""
    from .глаз import светлота
    if isinstance(цвет, (int, float, np.floating)) and not isinstance(цвет, bool):
        if not 0.0 <= float(цвет) <= 255.0:
            raise ValueError(f'предел_светлоты: {кто} L {float(цвет):g} — светлота 0–255')
        ц = np.asarray(_серая(цвет), np.float64)
    else:
        try:
            ц = np.asarray(tuple(цвет), np.float64)
        except (TypeError, ValueError):
            ц = np.zeros(0)
        if ц.shape != (3,) or not np.all(np.isfinite(ц)) or ц.min() < 0.0 or ц.max() > 255.0:
            raise ValueError(f'предел_светлоты: {кто}={цвет!r} — нужен sRGB (r, g, b) 0–255 или светлота L числом')
    return float(светлота(ц)), tuple(float(v) for v in ц)


def _знак(Lк, Lп):
    """+1 — краска светлее подложки (предел сверху), −1 — темнее (предел снизу)."""
    return 1.0 if Lк >= Lп else -1.0


def предел_светлоты(кисть, цвет, подложка, нагрузка=None, нажим=0.6, проходов=1, сырая=False, L=None, свет=False,
                    px_на_мм=None, предел=False):
    """З-2 (В-6): что даст поле плотных рядов краской `цвет` этой кистью по подложке — до кладки, живым стендом.

    кисть — любая, как есть (копией): ширина в мм (`ширина_мм`) или px при `px_на_мм` (без него 8). цвет — sRGB
    (r, g, b), `Краска` (с видом) или светлота L числом; подложка — sRGB или L. нагрузка — нагрузка ходов (число
    больше 0 и до 1 или имя; без неё — нагрузка кисти); нажим — рука (`жест`, 0,05–1); проходов — 1–8: по сухой каждый
    по высохшему прежнему, по сырой — подряд; сырая — подложка сырая, ход в её слой. свет — L со светом рельефа
    (`х.средний(…, свет=True)`), иначе без.

    Три вызова. Прогноз (без `L` и `предел`) — 16 полей стенда в этой точке. `предел=True` — прогноз и предел: перебор
    нагрузок `НАГРУЗКИ` и проходов 1–3 тремя сидами, найденная точка заново — 16 сидами ответа. `L=` — заказ: нагрузка
    (из `НАГРУЗКИ`) и число проходов, что его дают дешевле всего (меньше проходов, затем меньше нагрузка), ответ — счёт
    этой точки 16 сидами; недостижимое — `ValueError` с ближайшим достижимым.

    Ответ — словарь: 'L' (среднее 16 полей стенда), 'σ_поля' (разброс одного поля по сиду), 'ошибка_прогноза'
    (σ_поля / 4 — на столько не известно само среднее), 'σ' (обе вместе: на сколько одно поле уходит от 'L'), 'сидов',
    'нагрузка', 'проходов', 'краска_L', 'подложка_L', 'по_проходам' (L после 1…`проходов` проходов), 'причина' (на
    сколько уводит от краски: по сухой — 'тон прядей' и 'подложка', по сырой — 'смешение с сырой подложкой'; со
    `свет=True` — ещё 'свет рельефа'), 'тон' (L слоя хода без подложки), 'покрытие', 'толщина' (слоя хода; по сырой —
    None), 'слова'; с `предел=True` — ещё 'предел' (светлее у светлой краски, темнее у тёмной не вышло), 'предел_нагрузка',
    'предел_проходов', 'предел_ошибка'. Одни доводы — один ответ.

    Стенд не считает (`ValueError`): нагрузку 0 и выше 1, нажим вне 0,05–1, проходов вне 1–8, холст поля больше
    `ХОЛСТ_МП` Мп (широкая кисть при большом `px_на_мм`)."""
    from .инструмент import НАГРУЗКИ as ИМЕНА
    from .кисть import Кисть
    from .краска import Краска
    if not isinstance(кисть, Кисть):
        raise ValueError(f'предел_светлоты: нужна кисть (`Кисть.из_файла(…, ширина=…)`), а не {кисть!r}')
    px = float(px_на_мм or ПХ_НА_ММ)
    if not px > 0.0:
        raise ValueError(f'предел_светлоты: px_на_мм {px:g} — больше 0')
    W = float(кисть.ширина_мм) * px if кисть.ширина_мм is not None else float(кисть.ширина)
    Ш, В = _размеры(W, px)[:2]
    if Ш * В > ХОЛСТ_МП * 1e6:
        raise ValueError(f'предел_светлоты: стенд не считает поле кистью {W / px:g} мм при {px:g} px/мм — холст поля '
                         f'{Ш * В / 1e6:.1f} Мп, потолок {ХОЛСТ_МП:g}; меньше `px_на_мм` — то же поле в мм')
    нажим = float(нажим)
    if not 0.05 <= нажим <= 1.0:
        raise ValueError(f'предел_светлоты: нажим {нажим:g} — от 0,05 до 1; ближайшее — {min(max(нажим, 0.05), 1.0):g}')
    (Lк, ц_к), (Lп, ц_п) = _L(цвет, 'цвет'), _L(подложка, 'подложка')
    краска = цвет if isinstance(цвет, Краска) else Краска(ц_к)
    сырая = bool(сырая)
    проходов = int(проходов)
    if not 1 <= проходов <= ПРОХОДОВ_НАИБ:
        raise ValueError(f'предел_светлоты: проходов {проходов} — стенд считает 1–{ПРОХОДОВ_НАИБ}')
    if L is not None and нагрузка is not None:
        raise ValueError('предел_светлоты: с заказом L= нагрузку не давай — она и подбирается')

    def число(н):
        v = float(ИМЕНА[н]) if isinstance(н, str) and н in ИМЕНА else н
        if isinstance(v, (str, bool)) or not 0.0 < float(v) <= 1.0:
            raise ValueError(f'предел_светлоты: нагрузка {н!r} — число больше 0 и до 1 или имя ({", ".join(ИМЕНА)}); '
                             'вытертой кистью (0) поле не кладётся')
        return float(v)

    н0 = None if L is not None else число(кисть.нагрузка if нагрузка is None else нагрузка)
    ключ = 'Lс' if свет else 'L'
    зн = _знак(Lк, Lп)
    т = _Точка(кисть.с(), W, px, краска, ц_п, сырая, нажим)
    вар = [(н, п) for н in НАГРУЗКИ for п in range(1, ПРОХОДОВ + 1)]

    def точно(н, п):
        """Точка сидами ответа: замер [сид][проход] не короче п проходов."""
        return т.замеры([(н, СИДЫ)], п)[(н, СИДЫ)]

    def среднее(н, п):
        return float(точно(н, п)[ключ][:, п - 1].mean())

    def перебор():
        """Нагрузки и проходы сидами перебора (разом — поля своей точки сидами ответа): ({точка: L}, лучшая)."""
        свои = [(н0, СИДЫ, проходов)] if н0 is not None else []
        зам = т.замеры_разом([(н, СИДЫ_ПОИСКА, ПРОХОДОВ) for н in НАГРУЗКИ] + свои)
        знач = {(н, п): float(зам[(н, СИДЫ_ПОИСКА, ПРОХОДОВ)][ключ][:, п - 1].mean()) for н, п in вар}
        return знач, max(вар, key=lambda в: (зн * знач[в], -в[1], -в[0]))

    def ответ_для(н, п):
        з = точно(н, п)
        k = п - 1
        v = з[ключ][:, k]
        Lб, Lс = float(з['L'][:, k].mean()), float(з['Lс'][:, k].mean())
        σп = float(v.std(ddof=1))
        ош = σп / math.sqrt(len(v))
        if сырая:
            Lт = пок = тол = None
            причина = {'смешение с сырой подложкой': round(Lб - Lк, 2)}
        else:
            Lт, пок, тол = (float(np.nanmean(з[q][:, k])) for q in ('тон', 'покрытие', 'толщина'))
            причина = {'тон прядей': round(Lт - Lк, 2), 'подложка': round(Lб - Lт, 2)}
        if свет:
            причина['свет рельефа'] = round(Lс - Lб, 2)
        return {'L': round(float(v.mean()), 2), 'σ': round(math.hypot(σп, ош), 2), 'σ_поля': round(σп, 2),
                'ошибка_прогноза': round(ош, 2), 'сидов': len(v), 'нагрузка': н, 'проходов': п,
                'краска_L': round(Lк, 2), 'подложка_L': round(Lп, 2), 'тон': None if Lт is None else round(Lт, 2),
                'покрытие': None if пок is None else round(пок, 4), 'толщина': None if тол is None else round(тол, 4),
                'по_проходам': [round(float(u), 2) for u in з[ключ][:, :п].mean(axis=0)], 'причина': причина}

    рт = float(кисть.разброс_тона)

    def слова(д):
        главная = max(д['причина'], key=lambda к: abs(д['причина'][к]))
        return (f'выйдет L {д["L"]:.1f} ±{д["σ"]:.1f} (нагрузка {д["нагрузка"]:g}, проходов {д["проходов"]}): одно поле '
                f'гуляет на {д["σ_поля"]:.1f}, само среднее {д["сидов"]} полей стенда известно до '
                f'{д["ошибка_прогноза"]:.1f}; ' +
                (f'предел {д["предел"]:.1f} ±{д["предел_ошибка"]:.1f} нагрузкой {д["предел_нагрузка"]:g}, проходов '
                 f'{д["предел_проходов"]}; ' if 'предел' in д else '') +
                f'краска L {Lк:.1f}; больше всего уводит {главная} ({д["причина"][главная]:+.1f} L)' +
                (f' — разброс_тона {рт:g}: недомешанная краска, пряди светлее белого не бывают'
                 if главная == 'тон прядей' and зн > 0 else '') +
                ('' if 'предел' in д else '; где потолок — `предел=True`'))

    def с_пределом(д, лучший):
        """Предел — найденная точка заново сидами ответа; своя точка вызова, если вышла дальше неё."""
        пр = среднее(*лучший)
        if зн * (д['L'] - пр) > 0.0:
            лучший, пр = (д['нагрузка'], д['проходов']), д['L']
        ош = float(точно(*лучший)[ключ][:, лучший[1] - 1].std(ddof=1)) / math.sqrt(len(СИДЫ))
        д.update({'предел': round(пр, 2), 'предел_нагрузка': лучший[0], 'предел_проходов': лучший[1],
                  'предел_ошибка': round(ош, 2)})
        return д

    if L is None:
        if предел:
            _, лучший = перебор()
            д = с_пределом(ответ_для(н0, проходов), лучший)
        else:
            д = ответ_для(н0, проходов)
        д['слова'] = слова(д)
        return д
    цель = float(L)
    знач, лучший = перебор()
    # дешевле: меньше проходов, затем меньше нагрузка; точка перебора считается заново сидами ответа и должна заказ взять
    годные = sorted((в for в in вар if зн * (знач[в] - цель) >= 0.0), key=lambda в: (в[1], в[0]))
    выбор = None
    for в in годные[:2]:
        if зн * (среднее(*в) - цель) >= 0.0:
            выбор = в
            break
    if выбор is None:
        пр_L = среднее(*лучший)
        if зн * (пр_L - цель) >= 0.0:
            выбор = лучший
    if выбор is None:
        пр_ош = float(точно(*лучший)[ключ][:, лучший[1] - 1].std(ddof=1)) / math.sqrt(len(СИДЫ))
        совет = ''
        if зн > 0 and рт > 0.0 and пр_L < Lк - 0.5:
            # та же точка краской без недомеса — сидами перебора: сколько съедает тон прядей
            ровная = _Точка(кисть.с(разброс_тона=0.0), W, px, краска, ц_п, сырая, нажим)
            L0 = float(ровная.замеры([(лучший[0], СИДЫ_ПОИСКА)], лучший[1])[(лучший[0], СИДЫ_ПОИСКА)][ключ][:, лучший[1] - 1].mean())
            if L0 - пр_L > 0.5:
                if цель < L0:
                    совет = (f'; ближе к краске — краской ровнее: около `кисть.с(разброс_тона='
                             f'{рт * (L0 - цель) / (L0 - пр_L):.2f})` (с разброс_тона {рт:g} тон прядей съедает '
                             f'{L0 - пр_L:.1f} L, с 0 выйдет около {L0:.1f})')
                else:
                    совет = (f'; тон прядей съедает {L0 - пр_L:.1f} L, но и краской без недомеса (`разброс_тона=0`) '
                             f'выйдет около {L0:.1f}')
        где = (f'кисть «{кисть.имя}» {W / px:g} мм, нажим {нажим:g}, краска L {Lк:.1f}, подложка L {Lп:.1f} '
               f'{"сырая" if сырая else "сухая"}{", со светом" if свет else ""}')
        raise ValueError(f'предел_светлоты: L {цель:g} недостижимо — {где}: {"наибольшее" if зн > 0 else "наименьшее"} '
                         f'{пр_L:.1f} ±{пр_ош:.1f} нагрузкой {лучший[0]:g}, проходов {лучший[1]}{совет}')
    д = ответ_для(*выбор)
    if предел:
        с_пределом(д, лучший)
    д['слова'] = слова(д)
    return д
