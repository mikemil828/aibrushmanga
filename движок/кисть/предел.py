"""З-2 (В-6): предел светлоты — сколько выйдет L у поля рядов краски по подложке и где его потолок, до кладки.
Счёт — живой стенд: поле кладётся на своём холсте этой самой кистью, краской и по такой же подложке, 16 раз.

Откуда предел (замер смены Движка 228). Белила (255, 255, 251) мягкой 6 мм нагрузкой 0,5 по высохшему сливочному
дают L 249–250, а не 254,6, и тремя проходами не светлее. Покрытие при этом 0,997–1,0: подложка почти не видна.
Светлоту съедает тон прядей: краска на кисти недомешана (`Кисть.разброс_тона`), тон пряди — множитель к цвету
краски, в среднем около 1, а светлее белого пряди быть не может. Тёмные пряди темнят, светлые обрезаны
белым, и среднее выходит ниже краски. С `разброс_тона=0` те же ряды дают 254,5, с 0,2 — 252,9. Новый проход тоже
кладёт пряди своего тона, поэтому проходы потолок не поднимают. Тёмная краска упирается в обратное: сквозь просветы
видна светлая подложка.

Стенд (З-2б, смена Движка 230; в мм — тот же при любом `px_на_мм`). Грунт (200, 190, 170); подложка — слой плоской
12,5 мм нагрузкой 0,6 цветом подложки, её ходы — свои у каждого сида: рельеф подложки водит ход (мастихин 4 мм
белилами по серой — σ поля 2,7 L по одной подложке и 9 L по разным). По сухой она высушена, поле идёт в слой над
ней и сохнет после каждого прохода; по сырой поле идёт в её же слой. Поле — ряды (`_геометрия`: не меньше 7, у узкой
кисти больше) прямых ходов жестом 'подъём' через четверть ширины кисти, ход — 40 мм или 6,67 ширины; замер — средняя
светлота окна посередине поля, как у `х.средний`, без света и со светом рельефа.

Сиды. Прогноз — среднее 16 полей сидов `СИДЫ` (свои у стенда: подложка и ходы у каждого свои). Предел и заказ `L=` —
перебор нагрузок `НАГРУЗКИ` и проходов 1–3 тремя сидами `СИДЫ_ПОИСКА`, найденная точка считается заново сидами
`СИДЫ`, и в ответ идёт этот второй счёт: лучшая из шумных сама завышена. Проходы — из одного прогона поля.

Подложка держится в памяти процесса (`_ПОДЛОЖКИ`, не больше `ПАМЯТЬ_МБ`): одна на сид, на все нагрузки и вызовы.
Сухая тёмная подложка (линейный цвет не выше `ПЕРЕКРАСКА`) не кладётся заново, а перекрашивается из серой L 180:
геометрия слоя от цвета не зависит, цвет слоя — линейный цвет краски на тон прядей (сверено кладкой: до тысячных L).
Светлую перекрасить нельзя — светлые пряди обрезаны белым до смешения рядов (перекраска врёт до 2,4 L), она кладётся
своим цветом.

Счёт идёт в процессах (`ПРОЦЕССОВ`, не больше ядер и `KIST_CORES`); из процесса-потомка пула — в нём самом. Только
счёт: холст, кисть и журнал модели не трогаются.
"""
import math
import os
import pickle
import warnings
from collections import OrderedDict
from dataclasses import asdict

import numpy as np

from . import калибровка as кал

# ----------------------------------------------------------------- стенд
ПХ_НА_ММ = 8.0                 # px/мм стенда, если не дан свой; длины ниже — в px при 8 px/мм
ГРУНТ = (200, 190, 170)
ПОД_ШИРИНА = 100               # px: плоская подложки (12,5 мм)
ПОД_КРАСКА = 180.0             # L серой подложки-основы для перекраски
ПЕРЕКРАСКА = 0.4               # линейный цвет подложки не выше — перекраской основы (sRGB до 168), выше — кладкой
ШАГ = 0.25                     # шаг рядов поля, доля ширины кисти
РЯДОВ = 7                      # рядов поля у кисти 6 мм и шире
ДЛИНА = 320                    # px: ход не короче (40 мм); у кисти шире 6 мм — 6,67 ширины (жест 'подъём' сходит на 2–4 ширинах)
ПОЛЕ_X = (0.25, 0.75)          # окно замера вдоль хода — доли длины хода
ПРОХОДОВ = 3                   # проходов в переборе предела и заказа
ПРОХОДОВ_НАИБ = 8              # проходов в вызове не больше
НАГРУЗКИ = (0.1, 0.15, 0.2, 0.28, 0.4, 0.6, 0.9)      # нагрузки перебора предела и заказа
СИДЫ = tuple(range(41001, 41017))                     # 16 полей прогноза и ответа
СИДЫ_ПОИСКА = tuple(range(42001, 42004))              # перебор предела и заказа
ПРОЦЕССОВ = 10
ХОЛСТ_МП = 6.0                 # холст поля не больше, Мп
ПАМЯТЬ_МБ = 400                # подложки в памяти процесса не больше


def _серая(L):
    return (float(L),) * 3


def _геометрия(W, px=ПХ_НА_ММ):
    """(рядов, полуокно поперёк px, длина хода px) поля кистью W px при px/мм."""
    м = float(px) / ПХ_НА_ММ
    h = max(0.5 * W, min(16.0 * м, 3.0 * W))
    рядов = max(РЯДОВ, int(math.ceil(2.0 * (h + ШАГ * W) / (ШАГ * W))) + 1)
    return рядов, h, max(float(ДЛИНА) * м, 6.67 * W)


def _размеры(W, px=ПХ_НА_ММ):
    """(Ш, В, окно, рядов, y0, длина) холста поля кистью W px."""
    м = float(px) / ПХ_НА_ММ
    рядов, h, длина = _геометрия(W, px)
    y0 = 30.0 * м + W / 2
    yc = y0 + (рядов - 1) * ШАГ * W / 2
    Ш, В = int(длина + 80 * м), int(2 * y0 + (рядов - 1) * ШАГ * W)
    окно = (int(40 * м + ПОЛЕ_X[0] * длина), int(round(yc - h)), int(40 * м + ПОЛЕ_X[1] * длина), int(round(yc + h)))
    return Ш, В, окно, рядов, y0, длина


def _холст(W, под, сырая, сид, px=ПХ_НА_ММ):
    """Холст поля кистью W px по подложке `под` (L или sRGB), её ходы — свои у сида. Ответ: (холст, окно, рядов, y0, длина)."""
    from .холст import Холст
    from .кисть import Кисть
    from .путь import жест
    м = float(px) / ПХ_НА_ММ
    Ш, В, окно, рядов, y0, длина = _размеры(W, px)
    х = Холст(Ш, В, грунт=ГРУНТ, px_на_мм=float(px), ядра=1, подсказки=False, замер=False)
    шп = ПОД_ШИРИНА * м
    пл = Кисть.из_файла(os.path.join(кал._ПРЕСЕТЫ, 'плоская.json'), ширина=шп)
    цв = tuple(float(v) for v in под) if isinstance(под, (tuple, list, np.ndarray)) else _серая(под)
    шаг = 50 * м
    for i in range(int(math.ceil((В + шаг) / шаг))):
        y = i * шаг
        х.мазок(жест([[-40 * м, y], [Ш + 40 * м, y]], шп, 'остановка', сид=сид * 100 + i, нажим=0.7), цв, пл.с(),
               слой='под', нагрузка=0.6)
    if not сырая:
        х.подсушить(1.0)
    return х, окно, рядов, y0, длина


def _ряды(х, к, W, рядов, y0, длина, краска, нагрузка, нажим, сид, проход, слой, px=ПХ_НА_ММ):
    """Один проход поля: `рядов` ходов кистью к краской (L, sRGB или `Краска`)."""
    from .путь import жест
    from .краска import Краска
    м = float(px) / ПХ_НА_ММ
    if isinstance(краска, Краска):
        цв = краска
    else:
        цв = tuple(float(v) for v in краска) if isinstance(краска, (tuple, list, np.ndarray)) else _серая(краска)
    for j in range(рядов):
        с = сид * 1000 + 100 * проход + j
        y = y0 + j * ШАГ * W
        with warnings.catch_warnings():
            warnings.simplefilter('ignore')
            х.мазок(жест([[40 * м, y], [40 * м + длина, y]], W, 'подъём', сид=с, нажим=float(нажим)), цв, к.с(),
                   слой=слой, нагрузка=float(нагрузка), сид=с)


def поле(пресет, ширина_мм, нагрузка, нажим, краска, подложка, сид, проходов=1, сырая=False):
    """Одно живое поле стенда кистью пресета при 8 px/мм, подложка кладкой своим цветом: (L, L со светом) окна после
    `проходов` проходов (по сухой каждый сохнет, по сырой — подряд в слой подложки). Для сверки со стороны."""
    from .кисть import Кисть
    W = float(ширина_мм) * ПХ_НА_ММ
    к = Кисть.из_файла(os.path.join(кал._ПРЕСЕТЫ, пресет + '.json'), ширина=W)
    х, окно, рядов, y0, длина = _холст(W, подложка, сырая, сид)
    for п in range(int(проходов)):
        _ряды(х, к, W, рядов, y0, длина, краска, нагрузка, нажим, сид, п, 'под' if сырая else 'верх')
        if not сырая:
            х.подсушить(1.0, слой='верх')
    return х.средний(окно)['L'], х.средний(окно, свет=True)['L']


# ----------------------------------------------------------------- подложки в памяти
_ПОДЛОЖКИ = OrderedDict()      # (Ш, В, px, сырая, цвет или None — основа, сид) -> холст с подложкой, pickle
_ЗАМЕРЫ = OrderedDict()        # (ключ точки, нагрузка, сиды, проходов) -> замер
_ЗАМЕРОВ = 256


def _перекраска(цв):
    """Можно ли сухую подложку sRGB `цв` перекрасить из основы: ни одна прядь не дойдёт до белого."""
    from .краска import в_линейный
    return float(np.max(в_линейный(np.asarray(цв, np.float64)))) <= ПЕРЕКРАСКА


def _ключ_подложки(W, px, цв, сырая, сид):
    Ш, В = _размеры(W, px)[:2]
    основа = (not сырая) and _перекраска(цв)
    return (Ш, В, float(px), bool(сырая), None if основа else tuple(float(v) for v in цв), int(сид))


def _подложка_кусок(з):
    W, px, цв, сырая, сид = з
    ключ = _ключ_подложки(W, px, цв, сырая, сид)
    х = _холст(W, ПОД_КРАСКА if ключ[4] is None else ключ[4], сырая, сид, px)[0]
    return ключ, pickle.dumps(х, protocol=pickle.HIGHEST_PROTOCOL)


def _запомнить(ключ, б):
    _ПОДЛОЖКИ[ключ] = б
    _ПОДЛОЖКИ.move_to_end(ключ)


def _тесно(нужные):
    """Выкинуть давние подложки сверх `ПАМЯТЬ_МБ` (нужные этому счёту остаются)."""
    всего = sum(len(б) for б in _ПОДЛОЖКИ.values())
    for ключ in list(_ПОДЛОЖКИ):
        if всего <= ПАМЯТЬ_МБ * 1e6:
            break
        if ключ not in нужные:
            всего -= len(_ПОДЛОЖКИ.pop(ключ))


def _взять_подложку(W, px, цв, сырая, сид):
    """Свой холст с подложкой цвета `цв` (sRGB) сида — из памяти; основа перекрашена."""
    from .краска import в_линейный
    ключ = _ключ_подложки(W, px, цв, сырая, сид)
    х = pickle.loads(_ПОДЛОЖКИ[ключ])
    if ключ[4] is None:
        сп = х.слои['под']
        k = np.asarray(в_линейный(np.asarray(цв, np.float64)), np.float64) / float(в_линейный(ПОД_КРАСКА))
        сп.цвет[...] = (np.asarray(сп.цвет, np.float64) * k).astype(np.float32)
    return х


def _поле_кусок(з):
    """Поле сида: {'L', 'Lс' — [проход], 'тон', 'покрытие', 'толщина' — [проход] (по сырой — nan)}."""
    from .глаз import светлота
    from .краска import из_линейного
    кисть, W, px, краска, под, сырая, нагрузка, нажим, проходов, сид = з
    х = _взять_подложку(W, px, под, сырая, сид)
    окно, рядов, y0, длина = _размеры(W, px)[2:]
    x0, a, x1, b = окно
    о = {п: np.full(проходов, np.nan) for п in ('L', 'Lс', 'тон', 'покрытие', 'толщина')}
    for п in range(проходов):
        _ряды(х, кисть, W, рядов, y0, длина, краска, нагрузка, нажим, сид, п, 'под' if сырая else 'верх', px)
        if not сырая:
            х.подсушить(1.0, слой='верх')
            св = х.слои['верх']
            пок = np.asarray(св.покрытие[a:b, x0:x1], np.float64)
            Lс = светлота(np.clip(из_линейного(np.asarray(св.цвет[a:b, x0:x1], np.float64)) * 255.0, 0.0, 255.0))
            о['покрытие'][п] = float(пок.mean())
            о['толщина'][п] = float(np.asarray(св.толщина[a:b, x0:x1], np.float64).mean())
            о['тон'][п] = float((Lс * пок).sum() / пок.sum()) if пок.sum() > 0 else np.nan
        о['L'][п] = х.средний(окно)['L']
        о['Lс'][п] = х.средний(окно, свет=True)['L']
    return о


def _процессов(n):
    from . import ядра
    if n < 2 or not ядра.можно():
        return 1
    return max(1, min(ПРОЦЕССОВ, ядра.число_ядер(None), n))


def _разом(ф, зз):
    """ф по списку заданий — в процессах (fork: подложки потомкам видны из памяти), порядок ответов — как у заданий."""
    зз = list(зз)
    n = _процессов(len(зз))
    if n > 1:
        import multiprocessing as mp
        try:
            конт = mp.get_context('fork')
        except ValueError:
            конт = None
        if конт is not None:
            with конт.Pool(n) as пул:
                return пул.map(ф, зз, chunksize=1)
    return [ф(з) for з in зз]


class _Точка:
    """Кисть, краска, подложка, нажим, сырая — всё, кроме нагрузки и проходов: счёт полей с памятью."""

    def __init__(self, кисть, W, px, краска, под, сырая, нажим):
        self.кисть, self.W, self.px, self.краска, self.под, self.сырая, self.нажим = кисть, W, px, краска, под, сырая, нажим
        self.ключ = pickle.dumps((sorted(asdict(кисть).items()), W, px, tuple(краска), getattr(краска, 'вид', None),
                                  под, сырая, нажим))

    def замеры(self, пары, проходов):
        """{(нагрузка, сиды): замер} для пар (нагрузка, сиды), не короче `проходов` проходов."""
        р = self.замеры_разом([(н, сс, проходов) for н, сс in dict.fromkeys(пары)])
        return {(н, сс): з for (н, сс, _), з in р.items()}

    def _готовый(self, н, сс, проходов):
        for п in range(проходов, ПРОХОДОВ_НАИБ + 1):          # счёт с большим числом проходов годится: проходы — подряд
            з = _ЗАМЕРЫ.get((self.ключ, н, сс, п))
            if з is not None:
                return з
        return None

    def замеры_разом(self, тройки):
        """{(нагрузка, сиды, проходов): {'L', 'Lс', 'тон', 'покрытие', 'толщина' — [сид][проход]}}; чего нет в памяти —
        считается одним заходом в процессы."""
        тройки = list(dict.fromkeys(тройки))
        нет = [т for т in тройки if self._готовый(*т) is None]
        if нет:
            сиды = sorted({с for _, сс, _ in нет for с in сс})
            ключи = {с: _ключ_подложки(self.W, self.px, self.под, self.сырая, с) for с in сиды}
            класть = [(self.W, self.px, self.под, self.сырая, с) for с in сиды if ключи[с] not in _ПОДЛОЖКИ]
            for ключ, б in _разом(_подложка_кусок, класть):
                _запомнить(ключ, б)
            for с in сиды:
                _ПОДЛОЖКИ.move_to_end(ключи[с])
            _тесно(set(ключи.values()))
            зз = [(self.кисть, self.W, self.px, self.краска, self.под, self.сырая, н, self.нажим, п, с)
                  for н, сс, п in нет for с in сс]
            рр = iter(_разом(_поле_кусок, зз))
            for н, сс, п in нет:
                кк = [next(рр) for _ in сс]
                _ЗАМЕРЫ[(self.ключ, н, сс, п)] = {q: np.array([к[q] for к in кк]) for q in кк[0]}
            while len(_ЗАМЕРЫ) > _ЗАМЕРОВ:
                _ЗАМЕРЫ.popitem(last=False)
        return {т: self._готовый(*т) for т in тройки}


