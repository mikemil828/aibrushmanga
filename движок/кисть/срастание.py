def _перемычки(rng, N, m, ds, щель, мост):
    """(N, m), 0–1: вдоль хода щель живёт `щель` px (от и до), потом её на `мост` px затягивает краска — и снова.
    У каждого столбца свой счёт; края перемычки плавные (пара px)."""
    r = np.zeros((N, m))
    s = np.arange(N) * ds
    for j in range(m):
        x = -rng.uniform(0.0, щель[1])
        while x < s[-1]:
            x += rng.uniform(*щель)
            д = rng.uniform(*мост)
            r[:, j] = np.maximum(r[:, j], зажать(np.minimum(s - x, x + д - s) / 2.0 + 0.5, 0.0, 1.0))
            x += д
    return r


class Просвет:
    """Просвет между прядями открывается и закрывается — краской, а не местом пряди: пряди и борозды стоят где стояли.
    Тонкая сырая краска двух соседних прядей то смыкается через щель плёнкой (щель затекла: краска взята у крайних
    гребней этих прядей, цвет — их же), то стянута каждая к своей пряди, и края у щели кладут тоньше (щель открыта) —
    щель живёт от половины до полутора ширин кисти, потом её затягивает перемычка. То же у бока кисти: отошедшую внутрь крайнюю прядь краска возвращает на линию кисти,
    не дальше. Густая краска держит пряди обоймой: у неё этого нет."""

    оба = False   # К8б: плёнка щели — не толще, чем кладёт беднейшая из двух прядей (у кисти, которую раскрывает рука)

    def __init__(self, rng, с, липн, уход, густо, N, ds, W):
        щель, мост, раскрытие, порог, self.доля, self.внахлёст = Ч._СРАСТ_ПРОСВЕТ
        self.есть = с.ns >= 2 and густо < 1.0 and (self.доля > 0.0 or раскрытие > 0.0)
        if not self.есть:
            return
        ns = с.ns
        self.лев = np.array([(с.центр - с.полуш)[с.прядь == j].min() for j in range(ns)])
        self.прав = np.array([(с.центр + с.полуш)[с.прядь == j].max() for j in range(ns)])
        self.кр_л = np.array([np.nonzero(с.прядь == j)[0].min() for j in range(ns)])      # крайние гребни пряди
        self.кр_п = np.array([np.nonzero(с.прядь == j)[0].max() for j in range(ns)])
        ось = с.ось_пряди
        # на сколько бок кисти отошёл внутрь от её линии, px (слева, справа)
        self.отошёл = np.stack([зажать((ось[0] + (self.лев[0] - ось[0]) * липн[:, 0] + уход[:, 0]) - self.лев[0], 0.0, None),
                                зажать(self.прав[-1] - (ось[-1] + (self.прав[-1] - ось[-1]) * липн[:, -1] + уход[:, -1]), 0.0, None)], axis=1)
        # ширина плёнки, px: щель между прядями (как они встали) и нахлёст на оба края; у бока — от края до линии кисти
        зазор = зажать((ось[None, 1:] + (self.лев[1:] - ось[1:])[None, :] * липн[:, 1:] + уход[:, 1:])
                        - (ось[None, :-1] + (self.прав[:-1] - ось[:-1])[None, :] * липн[:, :-1] + уход[:, :-1]), 0.0, None)
        self.ширина = np.concatenate([зазор + 2.0 * self.внахлёст, self.отошёл + self.внахлёст], axis=1)
        тонко = 1.0 - густо
        # ns − 1 щелей и два бока кисти. Затягивает ту щель, что есть: сомкнутым прядям и вставшему на линию боку нечего
        есть_щель = np.concatenate([зажать(зазор / 0.4, 0.0, 1.0), зажать(self.отошёл / 0.3, 0.0, 1.0)], axis=1)
        self.затекла = _перемычки(rng, N, ns + 1, ds, (щель[0] * W, щель[1] * W), (max(мост[0] * W, 3.0), max(мост[1] * W, 5.0))) * есть_щель * тонко
        # между перемычками края прядей то и дело стянуты каждый к своей пряди — щель шире
        self.открыта = зажать((-_шум(rng, N, ns + 1, max(0.4 * W, 6.0) / ds) - порог) / 0.6, 0.0, 1.0) * (1.0 - self.затекла) * тонко
        раскрытие = max(раскрытие, 1e-6)
        # края у открытой щели кладут тоньше: на `раскрытие` px от границы пряди
        пр_м = с.прядь[с.гребень]
        у_п = зажать(1.0 - (self.прав[пр_м] - с.u) / раскрытие, 0.0, 1.0)
        у_л = зажать(1.0 - (с.u - self.лев[пр_м]) / раскрытие, 0.0, 1.0)
        щ_п = np.where(пр_м < ns - 1, пр_м, ns)                    # номер щели справа от отсчёта (у последней пряди — правый бок)
        щ_л = np.where(пр_м > 0, пр_м - 1, ns - 1)                 # слева (у первой — левый бок)
        self.тоньше = зажать(1.0 - self.открыта[:, щ_п] * у_п[None, :] - self.открыта[:, щ_л] * у_л[None, :], 0.0, 1.0)

    def открыть(self, D, с, шир, тау_ds, задет=None):
        """Отсчёты следа D (N, nm): у открытой щели тоньше; у затёкшей крайние гребни отдают краску плёнке.
        К6, "ridges": задет (N, nm) — насколько выборку профиля задел верх лежащего гребня (`зерно.Рвёт.заполнен`). Верх
        снимает краску с ворса куском, а кусок шире щели между прядями: где верх задели края обеих соседних прядей, щель
        под ним закрыта краской этих краёв, той же толщины — кусок на гребне щелью кисти поперёк не разрезан."""
        if not self.есть:
            return D
        кусок = None
        if задет is not None:
            слева, справа = np.searchsorted(с.гребень, self.кр_п[:-1], side='right') - 1, np.searchsorted(с.гребень, self.кр_л[1:])
            кусок = np.concatenate([np.minimum(задет[:, слева], задет[:, справа]), np.zeros((len(задет), 2))], axis=1)
            self.затекла = np.maximum(self.затекла, кусок)
        D = D * self.тоньше
        г = с.гребень
        n = np.maximum(np.bincount(г, minlength=с.nr), 1)
        сумма = (np.add.reduceat(D, np.searchsorted(г, np.arange(с.nr)), axis=1) if np.all(np.diff(г) >= 0) and len(np.unique(г)) == с.nr
                 else np.stack([D[:, г == q].sum(axis=1) for q in range(с.nr)], axis=1))   # (N, nr)
        a = np.concatenate([self.кр_п[:-1], [self.кр_л[0], self.кр_п[-1]]])               # гребни по сторонам щели; у бока — один
        b = np.concatenate([self.кр_л[1:], [self.кр_л[0], self.кр_п[-1]]])
        # плёнка на px ширины щели: тонкая, едва кроет (`доля` толщин полного укрытия) — и не толще, чем кладут соседи
        # (на отсчёт — среднее двух крайних гребней): сухие пряди щель не затянут, борозда на дне щели остаётся
        соседи = np.minimum(сумма[:, a] / n[a], сумма[:, b] / n[b]) if self.оба else 0.5 * (сумма[:, a] / n[a] + сумма[:, b] / n[b])
        # (К8б, `оба`: щель затягивают края обеих прядей; прядь, которую нажим ещё не донёс до холста, края не даёт, и
        # плёнка от соседки к ней не идёт — иначе у недожатого края вставала бледная плашка)
        self.на_px = self.затекла * np.minimum(self.доля * тау_ds, соседи / шир)
        if кусок is not None:
            self.на_px = np.maximum(self.на_px, кусок * 0.5 * (сумма[:, a] / n[a] + сумма[:, b] / n[b]) / шир)
        self.a, self.b = a, b
        # что ушло плёнкой, крайние гребни не доложили (поровну с двух сторон щели; у бока — один гребень)
        взято = 0.5 * self.на_px * self.ширина
        доля = np.zeros_like(сумма)
        np.add.at(доля, (slice(None), a), взято / np.maximum(сумма[:, a], 1e-12))
        np.add.at(доля, (slice(None), b), взято / np.maximum(сумма[:, b], 1e-12))
        return D * (1.0 - зажать(доля, 0.0, 0.6))[:, г]

    def в_растр(self, xs, ys, веса, с, D, на_холст, отст, конч, цвета, i0, ax, ay, расп, bx0, by0, расп0=None, вдоль=None, вкось=None):
        """Дописать отсчёты плёнки в затёкших щелях; сколько легло плёнкой, столько крайние гребни не доложили.
        Щель — между следами двух прядей, поперёк их хода. Кончики прядей отстают от кисти каждый на своё (`вдоль(отст,
        конч)`, px вдоль ворса), и у кисти, чья ось не поперёк ворса (повёрнута рукой, К1; дуга), разница отставаний ложится
        на ось кисти долей `вкось` (N,) — косинус угла между осью и ворсом. Это не ширина щели: плёнка шла бы по оси
        кисти на всю разницу отставаний — ровной плашкой поперёк прядей в хвосте схода, где пряди отстают врозь. Из
        расстояния по оси она вычитается; плёнка идёт от края пряди по оси кисти до следа соседней."""
        if not self.есть:
            return xs, ys, веса
        ns = с.ns
        # границы прядей на холсте: правый край пряди j и левый край пряди j+1; у боков — край кисти
        u = np.concatenate([self.прав[:-1], self.лев[1:], [self.лев[0], self.прав[-1]]])
        пр = np.concatenate([np.arange(ns - 1), np.arange(1, ns), [0, ns - 1]])
        гр = np.concatenate([self.кр_п[:-1], self.кр_л[1:], [self.кр_л[0], self.кр_п[-1]]])
        X, Y = на_холст(u, пр, отст[гр], конч[гр])
        m = ns - 1
        врозь = None if вдоль is None or m < 1 else (lambda вд: (вд[:, m:2 * m] - вд[:, :m]) * вкось[:, None])(вдоль(отст[гр], конч[гр]))   # (N, m): доля разницы отставаний краёв щели на оси кисти
        Xa, Ya, Xb, Yb = X[:, :m], Y[:, :m], X[:, m:2 * m], Y[:, m:2 * m]
        # п. 18в: число отсчётов плёнки в щели считается по ходу, каким он был бы без хвоста плашмя (`расп0`): иначе хвост
        # менял бы его для всего хода, и плёнка перемычек в теле ложилась бы на 1e-4 иначе
        X0, Y0 = (X, Y) if расп0 is None else на_холст(u, пр, отст[гр], конч[гр], было=True)
        шаг = 0.5
        доп = ([], [], [], [])
        for q in range(ns + 1):
            if q < m:
                x0, y0 = Xa[:, q], Ya[:, q]
                зазор = зажать((Xb[:, q] - x0) * ax + (Yb[:, q] - y0) * ay - (0.0 if врозь is None else врозь[:, q]), 0.0, None)
                от, до = -self.внахлёст * np.ones(len(зазор)), зазор + self.внахлёст
            else:
                # бок кисти: от отошедшего края до линии кисти, внутрь — на тот же нахлёст
                знак = -1.0 if q == m else 1.0
                x0, y0 = X[:, 2 * m + (q - m)], Y[:, 2 * m + (q - m)]
                вне = self.отошёл[:, q - m] * расп
                от, до = (-вне, self.внахлёст * np.ones(len(вне))) if знак < 0 else (-self.внахлёст * np.ones(len(вне)), вне)
            ii = np.nonzero(self.на_px[:, q] > 0.0)[0]
            if len(ii) == 0:
                continue
            шире = (до - от) if расп0 is None else ((зажать((X0[:, m + q] - X0[:, q]) * ax + (Y0[:, m + q] - Y0[:, q]) * ay - (0.0 if врозь is None else врозь[:, q]), 0.0, None) + 2.0 * self.внахлёст) if q < m else self.отошёл[:, q - m] * расп0 + self.внахлёст)
            k = int(np.ceil(float(шире[ii].max()) / шаг)) + 1
            t = (np.arange(k) + 0.5) / k
            поз = от[ii, None] + (до - от)[ii, None] * t[None, :]                            # px поперёк от края пряди
            d = np.broadcast_to((self.на_px[ii, q] * (до - от)[ii] / k)[:, None], поз.shape)
            ц = 0.5 * (цвета[i0[ii], self.a[q]] + цвета[i0[ii], self.b[q]])
            доп[0].append((x0[ii, None] + поз * ax[ii, None] - bx0).ravel())
            доп[1].append((y0[ii, None] + поз * ay[ii, None] - by0).ravel())
            доп[2].append(d.ravel())
            доп[3].append(np.repeat(ц, k, axis=0))
        if not доп[0]:
            return xs, ys, веса
        d, ц = np.concatenate(доп[2]), np.concatenate(доп[3])
        свои = [d, d * ц[:, 0], d * ц[:, 1], d * ц[:, 2]]
        веса = [np.concatenate([w, свои[i] if i < 4 else np.zeros(len(d))]) for i, w in enumerate(веса)]
        return np.concatenate([xs, np.concatenate(доп[0])]), np.concatenate([ys, np.concatenate(доп[1])]), веса


class Струи:
    """Струи лежащей краски в теле мазка по сырому (6а-1). Гребень кладёт свою краску; волосок, что идёт кончиком
    в лежащей сырой краске, своей под собой не оставляет: в его борозде остаётся цвет лежащей — струёй вдоль ворса.
    Какой волосок идёт в лежащей, а какой по подушке своей краски — от его жёсткости (на весь мазок) и медленно гуляет
    вдоль хода; в воздухе (проскок) волосок ничего не скребёт. Подобранное кончиком (`Ноша`) сходит в ту же струю,
    а не красит гребень. Только у тонкой краски: пастозная кроет телом."""

    def __init__(self, rng, с, бор, N, ds, W, густо):
        порог, переход, жёстк, медл, длина, шире = Ч._СРАСТ_СТРУЯ[:6]
        self.есть = с.вед is not None and бор is not None and густо < 1.0 and с.nr >= 3
        if not self.есть:
            return
        nv = с.nr - 1
        z = (зажать(с.давит, 0.75, 1.25) - 1.0) / 0.25
        сила = зажать((жёстк * z[None, :] + медл * _шум(rng, N, nv, длина * W / ds) - порог) / переход + 0.5, 0.0, 1.0)
        сила = сила * сила * (3.0 - 2.0 * сила) * зажать(бор[0] / 0.3, 0.0, 1.0)      # в воздухе глубина борозды 0
        сила[:, 0] = сила[:, -1] = 0.0                            # кромку следа ведут бок и край, не струя
        t = зажать(с.d_вед[None, :] / (с.полб[None, :] * бор[1] * шире)[:, с.вед], 0.0, 1.0)
        self.L = сила[:, с.вед] * (1.0 - t * t * (3.0 - 2.0 * t)) * (1.0 - густо)        # (N, nm): 1 — струя, 0 — гребень
        n = np.maximum(np.bincount(с.гребень, minlength=с.nr), 1)
        self.доля = np.stack([np.bincount(с.гребень, weights=r, minlength=с.nr) for r in self.L]) / n[None, :]   # (N, nr)
        self.равно = max(густо, Ч._СРАСТ_СТРУЯ[8])                                        # такая доля прежнего закона (ноша красит гребень) остаётся

    @staticmethod
    def кромка(густо):
        """Во сколько раз мельче «кромка на сырой краске»: у тонкой краски она шла во всю кисть, и гребни своей не давали."""
        return густо + (1.0 - густо) * Ч._СРАСТ_СТРУЯ[6] if Ч._СРАСТ_СТРУЯ_ВКЛ else 1.0

    @staticmethod
    def для(rng, с, бор, N, ds, W, густо, вал, ic):
        """Струи мазка или None: выключено, по сухому, мастихин, пастозная краска."""
        if not Ч._СРАСТ_СТРУЯ_ВКЛ or вал is None or вал.ноша is None:
            return None
        струи = Струи(np.random.default_rng(rng.bit_generator.seed_seq.spawn(1)[0]), с, бор, N, ds, W, густо)
        if not струи.есть:
            return None
        струи.шаги(ic, с.nr)
        return струи

    def вмещает(self, c, берёт, ноша, кладёт):
        """Сколько лежащей краски гребень снимает с холста за шаг. В струе лежащая остаётся на месте, меж струй кончик
        снимает её, как снимал: сколько берёт, решает место на кончике (`Вал.перелив`), а не струи. Струи решают, куда
        снятое идёт: ношей — не больше, чем сойдёт в струи гребня за срок ноши (`кладёт` — что гребень кладёт за шаг;
        `self.место`), остальное мешается в каплю (грязная кисть), на холсте не остаётся и за кромку не идёт."""
        self.место = np.maximum(ноша.шагов * self.доля_к[c] * кладёт - ноша.объём, 0.0)
        return берёт * (1.0 - self.доля_к[c])

    def в_плёнку(self, d, ц, i0, i1, f0, f1, г, ii, jj, край):
        """Отсчёты плёнки: в струе под волоском своей краски нет — там лежащая (на месте) или подобранная (ношей)."""
        нет_своей, ношей = self.на_пути(i0, i1, f0, f1, г)
        d_н = d * ношей[ii, jj]
        self.обмен = d_н                                          # сколько ноши легло в струю, столько лежащей волосок там снял
        d = d * (1.0 - нет_своей[ii, jj])
        # цвет ноши между двумя шагами переноса — с весом того, сколько её на каждом шаге сошло: у шага без ноши цвета нет
        # (её К-С — нули, а это белое), и без веса он подмешивал белое в начало и конец каждой струи ноши (Дв103, Д1)
        ц_н, в0, в1 = из_кс(self.кс), (self.ношей[i0] * f0)[:, г][ii, jj][:, None], (self.ношей[i1] * f1)[:, г][ii, jj][:, None]
        ц_н = (ц_н[i0[ii], г[jj]] * в0 + ц_н[i1[ii], г[jj]] * в1) / np.maximum(в0 + в1, 1e-300)
        d = d if край is None else d * край.кладёт(i0, i1, f0, f1, г, ii, jj)
        край_в = [] if край is None else [d * край.доля(i0, i1, f0, f1, г, ii, jj)]
        return d + d_н, (ц * d[:, None] + ц_н * d_н[:, None]) / np.maximum(d + d_н, 1e-12)[:, None], край, край_в

    def снято(self, снято, i0, i1, f0, f1, г, ii, jj, край):
        """Съём по отсчётам: в струе лежащая не снята, меж струй — снята та же всего; у бока — по ноше волоска
        (`Край.с_тела`); в струе ноша ложится взамен лежащей (`обмен`)."""
        снято = снято / np.maximum(1.0 - (self.доля_к[i0] * f0 + self.доля_к[i1] * f1)[:, г][ii, jj], 0.05) * (1.0 - self.L[ii, jj])
        return (снято if край is None else край.с_тела(снято, ii, jj)) + self.обмен

    @staticmethod
    def ровнять(h, трогает, размыть):
        """Лежащая сырая краска под кистью после съёма: волосок в струе идёт в ней и её разглаживает — струя остаётся
        цветом, а не гребнем толщины (кисть сняла меж струй, в струе не сняла). Объём тот же."""
        return h + (размыть(h, 2) - h) * трогает

    @staticmethod
    def под_кистью(трогает):
        """Щель между прядями уже 2 px лежит под кистью: волоски идут по обе её стороны и сырую краску в ней двигают
        так же, как под собой. Без этого по сырому в щели стояла нетронутая стенка лежащей краски в 1 px (по бокам
        снято на четверть плёнки) и под углом к растру дробилась в пунктир вдоль гребня (6а-2, Движок 24).
        Наружу, за кромку следа, не идёт: сначала наибольшее по 3×3, потом наименьшее."""
        def окно(a, f, край):
            p = обложить(a, 1, край)
            r = p[1:-1, 1:-1]
            for dy in range(3):
                for dx in range(3):
                    r = f(r, p[dy:dy + a.shape[0], dx:dx + a.shape[1]])
            return r
        return np.maximum(трогает, окно(окно(трогает, np.maximum, 0.0), np.minimum, 0.0))

    def шаги(self, ic, nr):
        self.доля_к = self.доля[ic]
        self.в_сыром = np.zeros((len(ic), nr))                    # струя открыта: волосок в лежащей сырой краске или несёт её
        self.ношей = np.zeros((len(ic), nr))                      # такая доля струи заполнена подобранной краской
        self.кс = np.zeros((len(ic), nr, 2 * ПОЛОС))

    def на_пути(self, i0, i1, f0, f1, г):
        """(N, nm): доля своей краски, что волосок не оставил; доля плёнки, что легла в струю подобранной."""
        a = (self.в_сыром[i0] * f0 + self.в_сыром[i1] * f1)[:, г]
        g = (self.ношей[i0] * f0 + self.ношей[i1] * f1)[:, г]
        return self.L * a, self.L * g


class Край:
    """Края мазка по сырому (6а-2): вход, бок и отрыв без дощечки. Кончик, севший в сырую краску, первые доли ширины
    кисти несёт её на себе: что он кладёт, меняется местами с лежащей (плёнка на этом месте — лежащая краска, своя
    осталась на кончике), свой тон набирается по ходу — у каждого гребня на своей длине. Крайние волоски несут мало
    краски и прижаты слабее: они идут в лежащей краске и двигают её, а своей поверх не кладут. Гребень, который рука
    поднимает, идёт в лежащей с того нажима, что у него остался сверх порога касания, — у каждого гребня со своего.
    Объём слоя тот же: сколько плёнки заменено лежащей, столько лежащей с этого места снято (`укладка.py`, «края по
    сырому»). Только со струями; по грунту и по сухому края прежние; пастозная на отрыве и у бока кроет телом."""

    def __init__(self, rng, с, N, Nc, ds, W, густо, шаг_к, кас_к, сыр_плёнок, доля_нажима, запас_г, ic):
        """`кас_к` (Nc, nr) — касание гребней по шагам переноса (шаг `шаг_к` px); `сыр_плёнок` — лежащая сырая краска
        под гребнем в толщинах плёнки мазка; `доля_нажима` (N,) и `запас_г` (N, nr) — нажим руки и запас нажима гребня
        сверх порога касания по шагам пути; `ic` — шаги пути, на которых считается перенос."""
        вх, бок, кон, ход = Ч._СРАСТ_КРАЙ[:4]
        по_холсту = шаг_к * np.cumsum(кас_к, axis=0)             # сколько гребень прошёл, касаясь холста, px
        сыро = зажать(сыр_плёнок / 0.06, 0.0, 1.0)              # 1 — под гребнем сырая краска
        # запас нажима гребня на последнем подъёме руки против того, что был в теле: 1 — до подъёма, 0 — гребень отошёл
        подъём = np.arange(N) > N - 1 - int(np.argmax((доля_нажима >= 0.97)[::-1]))
        запас = np.where(подъём[:, None], запас_г / np.maximum(запас_г.max(axis=0), 1e-6), 1.0)[ic]
        nr = с.nr
        тонко = 1.0 - густо
        # вход: гребень набирает свой тон за 0,35–0,85 ширины кисти от своего первого касания; короткий удар —
        # не дольше трети своего хода по холсту: иначе он весь остаётся в лежащей и своего тона не доносит
        L = np.minimum(W * rng.uniform(*вх, nr), ход * по_холсту[-1])
        g = зажать(1.0 - по_холсту / np.maximum(L, 1e-6)[None, :], 0.0, 1.0)
        # отрыв: руку поднимают, нажим гребня падает к порогу касания — кончик уже не давит свою краску в холст,
        # а идёт в лежащей; с какой доли своего запаса нажима (`запас`: 1 — до подъёма, 0 — гребень отошёл) —
        # у каждого гребня своё: концы вразнобой, а не чертой
        g2 = зажать(1.0 - запас / rng.uniform(*кон, nr)[None, :], 0.0, 1.0)
        g2 = g2 * g2 * (3.0 - 2.0 * g2) * (по_холсту > 0.0) * float(зажать(2.0 * тонко, 0.0, 1.0))
        self.гребень = 1.0 - (1.0 - g * тонко) * (1.0 - g2)                              # (Nc, nr); сырость — в `доля`
        # отрыв, рельеф (Движок 24): в теле гребень продавливает подушку своей краски, снимает лежащую и кладёт свою;
        # на подъёме руки он продавливать перестаёт (`втир` падает) — и кладёт своей настолько же меньше: слабо прижатый
        # кончик на сырой краске своей не оставляет. Без этого последние 10 px гребень лежащую уже не снимал, а свою
        # клал полной плёнкой поверх: наплыв +0,4 плёнки с обрывом после канавки тела — крючок и тёмное пятно света.
        # Гребень, что и в теле лежал сверху (втирания не было), кладёт как клал
        self.подъём = (запас < 1.0) * float(зажать(2.0 * тонко, 0.0, 1.0))
        # вход, рельеф (Движок 24): кончик, севший в сырую краску, уже несёт её на себе и больше не берёт — снимать
        # лежащую он начинает по мере того, как набирает свой тон (та же длина у гребня). Без этого канавка тела
        # начиналась уступом на линии первого касания: тёмная черта света поперёк входа
        self.берёт = 1.0 - g * тонко * сыро
        # бок: крайние волоски несут до пятой части краски (тот же закон, что у капли: `укладка.py`, «полная») и
        # кладут свою, только пока прижаты; порог ноши, ниже которого волосок идёт в лежащей, гуляет вдоль хода
        м = float(зажать(W / 40.0, 0.6, 1.0))
        self.порог = 0.2 + м * (бок[0] - 0.2 + (бок[1] - бок[0]) * зажать(0.5 + 0.6 * _шум(rng, N, 2, max(0.5 * W, 8.0) / ds), 0.0, 1.0))   # (N, 2)
        # п. 13 (хвост 11ж): у кисти уже 16 px бок мельче вместе с шириной (как кромка по сырому, `укладка._узко`): иначе кисть
        # 6 px — вся «бок», в три гребня клала нить в 2 px, а в два гребня (без струй и краёв) — брусок, по сиду
        self.несёт = Ч.ноша_у_края((с.полуширина - np.abs(с.u)) / min(W / Ч._ОСТРАЯ[0], 1.0))    # (nm,)
        self.ст = (с.u > 0).astype(np.intp)
        self.сыро = сыро
        self.тонко = тонко

    @staticmethod
    def для(есть_краска, rng, *а):
        """Края мазка или None: по голому грунту (без струй и по сухому сюда не доходит)."""
        if not есть_краска:
            return None
        return Край(np.random.default_rng(rng.bit_generator.seed_seq.spawn(1)[0]), *а)

    @staticmethod
    def на_месте(просят, V, h, подвижно, ц_нов, C):
        """По пикселям: столько своей плёнки заменено лежащей краской этого места (не больше, чем её там сырой);
        столько же лежащей снято — объём слоя тот же. Ответ — цвет плёнки и толщина лежащего."""
        меняет = np.minimum(np.minimum(просят, V), np.maximum(h, 0.0) * подвижно * 0.9)
        m = меняет > 1e-7
        if m.any():
            g = (меняет[m] / np.maximum(V[m], 1e-9))[:, None]
            ц_нов[m] = из_кс(в_кс(ц_нов[m]) * (1.0 - g) + в_кс(C[m]) * g)
            h = h - меняет
        return ц_нов, h

    def с_тела(self, снято, ii, jj):
        """Бок, рельеф (Движок 25). Съём лежащей краски по отсчётам: крайний волосок несёт до пятой части ноши и прижат
        слабо — лежащую он не скребёт, а снимает её столько, сколько несёт (тот же закон `ноша_у_края`); что кисть
        подняла, она подняла телом: съём каждого шага пути тот же, поперёк кисти он делится по ноше волосков.
        Было: крайние 3 px клали 0,3–0,5 плёнки своей, а снимали 2–2,8 лежащей, как полные, — ров под кромкой глубже
        тела, и вал, что из него же вышел, стоял за кромкой стенкой в 1 px."""
        w = self.несёт[jj] ** self.тонко
        n = int(ii.max()) + 1
        return снято * w * (np.bincount(ii, weights=снято, minlength=n) / np.maximum(np.bincount(ii, weights=снято * w, minlength=n), 1e-12))[ii]

    def к_плёнке(self, касание, втир, острая=1.0):
        """После переноса краски: касание по отсчётам; `втир` (Nc, nr) — как гребень продавливал подушку своей краски;
        `острая` — доля острого кончика у кисти (п. 12: 1 — ворс собран в остриё, подушки под ним нет, бок идёт в лежащей всегда)."""
        пол = Ч._СРАСТ_КРАЙ[6]
        self.касание, self.достаёт = касание, острая + (1.0 - острая) * (пол + (1.0 - пол) * зажать(втир / Ч._СРАСТ_КРАЙ[5], 0.0, 1.0))
        c0 = np.maximum(np.argmax(self.подъём > 0.0, axis=0) - 1, 0)
        self.тает = зажать(втир[c0, np.arange(втир.shape[1])][None, :] - втир, 0.0, 1.0) * self.подъём
        return self

    def кладёт(self, i0, i1, f0, f1, г, ii, jj):
        """По отсчётам: какую долю своей плёнки гребень на подъёме руки по сырому ещё кладёт."""
        return 1.0 - ((self.тает[i0] * f0 + self.тает[i1] * f1) * (self.сыро[i0] * f0 + self.сыро[i1] * f1))[:, г][ii, jj]

    def доля(self, i0, i1, f0, f1, г, ii, jj):
        """По отсчётам: какая доля своей плёнки заменена лежащей краской на месте."""
        гр = (self.гребень[i0] * f0 + self.гребень[i1] * f1)[:, г][ii, jj]
        сыро = (self.сыро[i0] * f0 + self.сыро[i1] * f1)[:, г][ii, jj]
        бок = зажать((self.порог[ii, self.ст[jj]] - self.несёт[jj] * self.касание) / Ч._СРАСТ_КРАЙ[4] + 0.5, 0.0, 1.0) * self.тонко
        бок = бок * (self.достаёт[i0] * f0 + self.достаёт[i1] * f1)[:, г][ii, jj]   # п. 12: у щетины плашмя крайний волосок идёт в лежащей, насколько кисть до неё достаёт; лежит на подушке своей краски — бок ложится сверху своим цветом (подрезка)
        return (1.0 - (1.0 - гр) * (1.0 - бок)) * сыро


class Ноша:
    """Протяжка: подобранная сырая краска ложится на кончик снаружи и сходит первой — раньше своей, что под ней.
    Ход стирает ношу с кончика за `Ч._СРАСТ_ТЯНЕТ[2]` ширин кисти (сколько бы её ни было: толстую полосу след несёт
    гуще, а не дальше), и гребень кладёт её вместо своей краски — не больше доли `[3]` того, что кладёт: тонкое место следа одной ношей
    не красится; кончилась — идёт своя. Так мазок тянет сырую полосу
    на ширину-полторы кисти, а не красит ею весь остаток хода."""

    def __init__(self, nr, шагов):
        self.объём = np.zeros(nr)
        self.кс = np.zeros((nr, 2 * ПОЛОС))
        self.за_шаг = np.zeros(nr)
        self.шагов = шагов                                       # шагов переноса, за которые ноша сходит
        self.вверх = np.zeros(nr)                                # 6а-1: подобранное, ушедшее вверх по ворсу, в запас кисти
        self.вверх_кс = np.zeros((nr, 2 * ПОЛОС))

    def взять(self, чужая, кс_холста, место=None, в_каплю=1.0):
        """Подобранное за шаг: доля `Ч._СРАСТ_ТЯНЕТ[0]` — в ношу; ответ — что уходит в каплю, как раньше.
        6а-1 (струи): ношей — не больше `место` (что сойдёт в струи). Не вместившееся у тощей кисти мешается в каплю
        (доля `в_каплю`: на кончике место есть), у полной — уходит вверх по ворсу и мешается с запасом (`из_запаса`)."""
        в_ношу = Ч._СРАСТ_ТЯНЕТ[0] * чужая if место is None else np.minimum(Ч._СРАСТ_ТЯНЕТ[0] * чужая, место)
        новый = self.объём + в_ношу
        self.кс = (self.кс * self.объём[:, None] + кс_холста * в_ношу[:, None]) / np.maximum(новый, 1e-12)[:, None]
        self.объём = новый
        self.за_шаг = np.where(в_ношу > 0.0, новый / self.шагов, self.за_шаг)
        if место is None:
            return чужая - в_ношу
        вверх = (1.0 - в_каплю) * (Ч._СРАСТ_ТЯНЕТ[0] * чужая - в_ношу)
        новый = self.вверх + вверх
        self.вверх_кс = (self.вверх_кс * self.вверх[:, None] + кс_холста * вверх[:, None]) / np.maximum(новый, 1e-12)[:, None]
        self.вверх = новый
        return чужая - в_ношу - вверх

    def из_запаса(self, своя, кс_своя, запас):
        """6а-1: своя краска идёт из запаса кисти вместе с тем, что ушло в него с холста (в их доле). Ответ — её цвет."""
        g = self.вверх / np.maximum(self.вверх + запас, 1e-12)
        self.вверх = self.вверх - np.minimum(g * своя, self.вверх)
        return кс_своя * (1.0 - g[:, None]) + self.вверх_кс * g[:, None]

    def в_струи(self, c, уходит, струи, сыро):
        """6а-1, тонкая краска: подобранное сходит в струи под волосками (сколько их у гребня), свою краску гребень
        в струе не оставляет. `сыро` — волосок идёт в лежащей сырой краске (0–1). Ответ — что гребень кладёт своей."""
        место = струи.доля_к[c] * уходит
        из_ноши = np.minimum(np.minimum(self.объём, self.за_шаг), место)
        self.объём = self.объём - из_ноши
        g = из_ноши / np.maximum(место, 1e-12)
        струи.ношей[c] = g
        струи.в_сыром[c] = np.maximum(сыро, g)
        струи.кс[c] = self.кс
        # что не сошло в струи за свой срок (струя закрылась, гребень кладёт мало), остаётся на кончике под своей
        # краской: мешается в каплю (`в_каплю`), за кромку не уходит
        self.стёрто = np.minimum(self.объём, np.maximum(self.за_шаг - из_ноши, 0.0))
        self.объём = self.объём - self.стёрто
        return уходит * (1.0 - струи.доля_к[c] * струи.в_сыром[c])

    def в_каплю(self, капля, кс_капли):
        """6а-1: несошедшая ноша вмешана в каплю кончика (объём и цвет те же). Ответ — капля и её краска."""
        новая = капля + self.стёрто
        кс = (кс_капли * капля[:, None] + self.кс * self.стёрто[:, None]) / np.maximum(новая, 1e-12)[:, None]
        self.стёрто = np.zeros_like(self.стёрто)
        return новая, np.where((self.объём + новая > 1e-9)[:, None] & (новая > 1e-9)[:, None], кс, кс_капли)

    def сойти(self, уходит, кс_капли, доля=1.0):
        """Гребень кладёт `уходит`: сколько может — ношей. Ответ: цвет того, что легло, и сколько из него взято у капли."""
        из_ноши = np.minimum(np.minimum(self.объём, self.за_шаг), Ч._СРАСТ_ТЯНЕТ[3] * доля * уходит)
        self.объём = self.объём - из_ноши
        g = (из_ноши / np.maximum(уходит, 1e-12))[:, None]
        return кс_капли * (1.0 - g) + self.кс * g, уходит - из_ноши


class Вал:
    """Сырая краска, которую кисть подняла и не унесла: кончик держит каплю не больше `Ч._СРАСТ_ВАЛ[0]` полной, лишнее
    обтекает кисть и ложится валом сразу за кромкой следа — с той стороны, к которой гребень ближе. Объём — тот,
    что снят с холста; цвет — лежавшей краски."""

    def __init__(self, Nc, с, тощая, шагов_на_ширину):
        self.ноша = Ноша(с.nr, Ч._СРАСТ_ТЯНЕТ[2] * шагов_на_ширину) if Ч._СРАСТ_ТЯНЕТ[0] > 0 else None
        self.держит = Ч._СРАСТ_ВАЛ[0] * max(1.0, тощая)         # тощая кисть (своей краски мало) чужой держит больше: место есть
        self.в_каплю = float(зажать(тощая - 1.0, 0.0, 1.0))    # 6а-1: у тощей кисти не вместившееся в струи — в каплю
        self.лево = с.центр < 0
        self.ширина = 2.0 * с.полуш
        self.объём = np.zeros((Nc, 2))
        self.кс = np.zeros((Nc, 2, 2 * ПОЛОС))

    def перелив(self, c, новая, полная, чужая, кс_холста, место=None):
        """Шаг переноса c: подобранное, что не поместилось на кончике, записано в вал. Ответ — капля и подобранное без него.
        `место` (6а-1, струи) — сколько подобранного кончик несёт ношей; остальное — в каплю."""
        несёт = 0.0 if self.ноша is None else self.ноша.объём + self.ноша.вверх   # ноша (и ушедшее вверх по ворсу) — на той же кисти: место занимает
        лишнее = зажать(новая + несёт - self.держит * полная, 0.0, чужая)
        новая, чужая = новая - лишнее, чужая - лишнее
        if self.ноша is not None:
            в_каплю = self.ноша.взять(чужая, кс_холста, место, self.в_каплю)
            новая, чужая = новая - чужая + в_каплю, в_каплю
        if лишнее.any():
            v = лишнее * self.ширина
            for ст, m in ((0, self.лево), (1, ~self.лево)):
                self.объём[c, ст] = v[m].sum()
                self.кс[c, ст] = (кс_холста[m] * v[m, None]).sum(axis=0) / max(self.объём[c, ст], 1e-12)
        return новая, чужая

    def сойти(self, c, уходит, кс_капли, струи, сыро):
        """Гребень кладёт `уходит`: ноша сходит первой — на гребень (как было) или, у тонкой краски по сырому, в струи."""
        if струи is None:
            return self.ноша.сойти(уходит, кс_капли)
        своей = self.ноша.в_струи(c, уходит, струи, сыро)
        return self.ноша.сойти(своей, кс_капли, струи.равно)

    def в_растр(self, xs, ys, веса, с, W, на_холст, отст, i0, bx0, by0):
        """Дописать отсчёты вала к отсчётам мазка: места, объём и цвет; касания и съёма у вала нет."""
        if not self.объём.any():
            return xs, ys, веса
        ширина = Ч._СРАСТ_ВАЛ[1] + Ч._СРАСТ_ВАЛ[2] * W
        # вал лежит откосом на обе стороны от кромки (Движок 25): наружу сходит на нет на своей ширине, внутрь — на
        # тех 7 px, где волоски несут меньше полной ноши и прижаты слабо (`ноша_у_края`): они его не сминают.
        # Было: вал начинался полной высотой сразу за кромкой — стенка в 1 px, тёмная черта света вдоль бока
        внутрь = min(7.0, 0.5 * с.полуширина)
        n = max(int(np.ceil((ширина + внутрь) / 0.5)), 2)
        за = -внутрь + (np.arange(n) + 0.5) * ((ширина + внутрь) / n)   # px за краем кисти (минус — под краем)
        вес = np.where(за > 0.0, 1.0 - за / ширина, 1.0 + за / внутрь)   # вал выше у кромки и сходит на нет
        вес = вес / вес.sum()
        кромка = с.полуширина - Ч._ЯДРО                         # кромка следа: самый край кисти краски не кладёт
        u = np.concatenate([-кромка - за, кромка + за])
        ст = np.repeat([0, 1], n)
        край = np.where(ст == 0, 0, с.nr - 1)
        X, Y = на_холст(u, с.прядь[край], отст[край], np.zeros(2 * n))
        d = self.объём[i0][:, ст] * (np.tile(вес, 2) / _ШК)[None, :]     # объём шага переноса — на его шаги пути поровну
        ii, jj = np.nonzero(d > 0.0)
        d = d[ii, jj]
        ц = из_кс(self.кс)[i0[ii], ст[jj]]
        свои = [d, d * ц[:, 0], d * ц[:, 1], d * ц[:, 2]]
        веса = [np.concatenate([w, свои[q] if q < 4 else np.zeros(len(d))]) for q, w in enumerate(веса)]
        return np.concatenate([xs, X[ii, jj] - bx0]), np.concatenate([ys, Y[ii, jj] - by0]), веса
