def _кисть(имя, размер, кэш, тон_кисти=None, масштаб=1.0):
    ключ = (имя, round(размер, 2)) if тон_кисти is None else (имя, round(размер, 2), float(тон_кисти))
    if ключ not in кэш:
        if имя is None:
            имя = 'плоская' if размер >= 20 else 'плоская_узкая'
        путь = имя if имя.endswith('.json') else os.path.join(_ПРЕСЕТЫ, имя + '.json')
        замены = {} if тон_кисти is None else {'тон_кисти': float(тон_кисти)}       # 11а: поле журнала "brush_tone"
        к = Кисть.из_файла(путь, ширина=размер, **замены)
        if масштаб != 1.0 and к.шаг_мм is None:      # Д-8: шаг ворса пресета — px журнала, как "size"
            к.шаг = float(к.шаг) * масштаб
        кэш[ключ] = к
    return кэш[ключ]


