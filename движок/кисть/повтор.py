def _профиль_угла(профиль, где, предел=None):
    """Профиль угла по ходу — [[доля пути, градусы], …]: доли 0–1 строго по возрастанию, градусы — конечные,
    с пределом (мин, макс) — в нём. Ответ — массив (n, 2) или None. Кривой — ValueError с `где` в начале."""
    if профиль is None:
        return None
    try:
        п = np.asarray(профиль, dtype=np.float64)
    except (TypeError, ValueError):
        п = None
    if п is None or п.ndim != 2 or п.shape[1] != 2 or len(п) < 1 or not np.isfinite(п).all():
        raise ValueError(f'{где}: должен быть списком пар [доля пути, градусы]')
    if (п[:, 0] < 0).any() or (п[:, 0] > 1).any():
        raise ValueError(f'{где}: доля пути вне 0–1')
    if (np.diff(п[:, 0]) <= 0).any():
        raise ValueError(f'{где}: доли пути не по возрастанию')
    if предел is not None and ((п[:, 1] < предел[0]).any() or (п[:, 1] > предел[1]).any()):
        raise ValueError(f'{где}: градусы вне {предел[0]:g}–{предел[1]:g}')
    return п


def _ход_точек(xy):
    """Направление хода у каждой точки ломаной, радианы без скачков: среднее соседних отрезков; у стоящих на месте
    точек — направление ближайшего отрезка с длиной."""
    d = np.diff(xy, axis=0)
    есть = np.hypot(d[:, 0], d[:, 1]) > 1e-6
    if not есть.any():
        return np.zeros(len(xy))
    уг = np.arctan2(d[:, 1], d[:, 0])
    номер = np.arange(len(d))
    к_ближ = np.where(есть, номер, -1)
    np.maximum.accumulate(к_ближ, out=к_ближ)                  # пустой отрезок берёт направление прошлого
    первый = int(np.argmax(есть))
    к_ближ[к_ближ < 0] = первый
    уг = np.unwrap(уг[к_ближ])
    return np.concatenate([[уг[0]], 0.5 * (уг[:-1] + уг[1:]), [уг[-1]]])


def углы_вдоль(точки, поворот=None, наклон=None, азимут=None):
    """К1, поля журнала "rotation_along", "tilt_along", "azimuth_along": профили [[доля пути, градусы], …] -> столбцы
    ядра (наклон °, азимут рад, поворот ° от оси x) у точек мазка (x, y, нажим, dt). Доля пути — по длине ломаной
    точек, как у `нажим_вдоль`; между узлами по прямой. Поворот и азимут — от направления хода в этой точке: кисть
    держится к ходу и на дуге. Нет ни одного профиля — точки как были (тот же объект)."""
    пов = _профиль_угла(поворот, 'rotation_along')
    накл = _профиль_угла(наклон, 'tilt_along', (0.0, 85.0))
    аз = _профиль_угла(азимут, 'azimuth_along')
    т = np.asarray(точки, np.float64)
    if (пов is None and накл is None and аз is None) or т.ndim != 2 or т.shape[1] < 4 or len(т) < 2:
        return точки
    т = т[:, :4]
    s = np.concatenate([[0.0], np.cumsum(np.hypot(*np.diff(т[:, :2], axis=0).T))])
    д = s / max(s[-1], 1e-9)
    ход = _ход_точек(т[:, :2])

    def по(п):
        return np.zeros(len(т)) if п is None else np.interp(д, п[:, 0], п[:, 1])
    # ядро (`путь._путь`): угол кисти = поворот − 90°, поперёк кисти — её широкая ось; поворот 0 журнала — угол = ход
    return np.column_stack([т, по(накл), ход + np.radians(по(аз)), np.degrees(ход) + по(пов) + 90.0])


