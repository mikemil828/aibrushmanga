"""Рука патчем: готовый журнал мазков -> тот же журнал, где ходы проведены рукой (Рм-1 — кисть по опорным точкам; Рм-2 —
сырые точки, инструменты, лента).

    python3 -m рука.патч вход.jsonl выход.jsonl [--сила 0.15] [--человек N] [--зерно N] [--сила-объекта лицо=0.1 …]
                        [--без-сырых] [--лента]

Запуск — из папки `движок/` (как `python3 -m кисть.повтор`). Движок не трогается: на выходе обычный журнал, его кладёт
обычный повтор, руку повтор не считает — точки хода лежат в строке готовыми ("core").

Сила: 0 — журнал как есть, байт в байт; к 0,3 геометрия хода целиком от руки; выше — рука размашистее (потолка нет).
Число — на весь журнал; `--сила-объекта имя=число` (можно несколько раз) — своя сила объекту (поле "object" строки
или последней пометки). «Человек» (постоянное у руки: правша или левша, опора, уклон, размах, хват) и «зерно»
(поток случая этого раза) без ключа берутся случайно, один раз, печатаются и пишутся в строку холста:
    "arm": {"person": N, "seed": N, "strength": 0.15, "by_object": {…}, "who": "патч"}
Те же вход, сила, человек и зерно — тот же выход байт в байт.

Строка хода по опорным точкам, которую провела рука: вместо "ctrl", "end", "entry", "pressure", "path_seed", "path_rng", "angle" — "core"
(готовые точки: x, y, нажим, dt мс, наклон °, азимут рад[, поворот °]) и "arm_from" — исходное намерение: убранные поля
как были и порядок ключей строки. Ход, который рука сделала в два касания, — две строки, вторая с "arm_part": 1.
По "arm_from" журнал патчится заново (патч сперва возвращает строки к исходным) и при силе 0 возвращается к исходному.

Что берётся из строки как намерение: опорные точки (цели), изгиб — по соседним точкам, нажим, ширина кисти (допуск
цели — от неё), вид конца (остановка — приказ «медленно», отрыв и смахивание — «быстро»), объект и этап (интерес к
месту). Вход, тело и конец нажима — всегда те, что выбрала модель: рука нажим только качает.
К ходу движка прибавляется увод руки от её намерения (дуг через цели), а не разница двух ходов: гладкая кривая по
редким опорным точкам остаётся гладкой; у хода в три и больше опорных точек цели руки берутся с кривой движка. Время
шага — как у движка, рука его качает до 1,3 раза в степени силы (у цели медлит, но не встаёт). Точки хода пишутся
реже (`РЕДКО_PX`): без выброшенной точки прямая между соседями уходит от хода не дальше 0,2 px.

Рм-2 — сырые ходы и инструменты. Строка с готовым путём ("core", "points") — намерение целиком: рука берёт из пути
немногие цели (упрощённая ломаная), ведёт к ним свой ход, и к записанным точкам прибавляется только то, чем ход руки
разошёлся с её же намерением: снос, дуга рычага, срез угла, недолёт; темп (dt) и нажим качаются вокруг записанных.
Точек столько же, столбцы наклона, азимута и поворота — как записала модель; мелкая форма пути остаётся её. Исходные
точки — в "arm_from". Ручка `сырые` (`--без-сырых`) — такие строки как есть. Ход по опорным точкам с профилем по ходу
("pressure_along", "rotation_along", "tilt_along", "azimuth_along") сперва считается точками ядра, как их кладёт
повтор, и идёт тем же путём; с отрывом по ходу (множитель 0) — как есть. Увод от записанного пути ограничен: не дальше
4 мм на единицу силы (0,15 — до 0,6 мм), и у хода по опорным точкам тоже.
Инструменты — своя мера силы руки (`МЕРА`): кисть 1; мастихин 0,6; черенок 0,8; тряпка 1; скребок и нож 0,5 (твёрдая
кромка идёт ровнее ворса). Лента скотча (`--лента`, по умолчанию выключено) — малая ошибка места и угла: 2 мм и 2° на
единицу силы (0,15 — 0,3 мм и 0,3°), маска сдвинута и довёрнута вокруг своей середины, исходная — в "arm_from".
Как есть всегда: тычок в одну точку, набор линий ("lines"), ход короче 0,5 мм.
Глаза и дорисовки в патче нет: холста рука не видит. Состояние (разогрев, усталость, уверенность, внимание, скука,
кураж, сеансы) идёт по журналу от мазка к мазку; пометка этапа — пауза. Большой журнал читается строкой за строкой."""
