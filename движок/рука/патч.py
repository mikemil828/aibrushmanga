class _Сиды:
    """Сид мазка строки, как его возьмёт повтор (`кисть.повтор._сид_строки`, `Холст.сид_мазка`): "seed"; без него у
    журнала с "seeds": "tree" — из сида листа, этапа, объекта и точек (и счёта строк с теми же точками выше); у
    прежнего — от номера строки. `на_выходе` — тот же счёт по строкам НОВОГО журнала: ход руки несёт свой "seed" и в
    счёт повтора не идёт, поэтому строке «как есть» ниже повтор дал бы другой сид — такой строке сид пишется."""

    def __init__(self):
        self.лист, self.дерево, self.повторы, self.вых = 0, False, {}, {}

    def холст(self, d):
        self.лист, self.дерево = int(d.get('seed', 0)), d.get('seeds') == 'tree'

    def _ключ(self, d, тек):
        э, о = d.get('stage', тек['stage']), d.get('object', тек['object'])
        try:
            т = np.ascontiguousarray(d.get('core', d.get('points', d.get('ctrl'))), dtype=np.float64)
        except (TypeError, ValueError):
            return None
        h = hashlib.blake2b(json.dumps([self.лист, None if э is None else str(э), None if о is None else str(о),
                                        list(т.shape)]).encode('utf-8'), digest_size=8)
        h.update(т.tobytes())
        return int.from_bytes(h.digest(), 'little') >> 1

    @staticmethod
    def _сид(ключ, n):
        return int.from_bytes(hashlib.blake2b(ключ.to_bytes(8, 'little') + n.to_bytes(4, 'little'),
                                              digest_size=4).digest(), 'little') & 0x7FFFFFFF

    def сид(self, d, номер, тек):
        if 'seed' in d:
            return int(d['seed'])
        if not self.дерево:
            return номер
        ключ = self._ключ(d, тек)
        if ключ is None:
            return номер
        n = self.повторы.get(ключ, 0)
        self.повторы[ключ] = n + 1
        return self._сид(ключ, n)

    def на_выходе(self, d, тек):
        ключ = self._ключ(d, тек)
        if ключ is None:
            return None
        n = self.вых.get(ключ, 0)
        self.вых[ключ] = n + 1
        return self._сид(ключ, n)


def путь_движка(d, сид_мазка):
    """Точки, которыми сам движок кладёт эту строку (как в `кисть.повтор`): x, y, нажим, dt — px журнала."""
    from кисть import жест, путь_с_нажимом
    from кисть.путь import генератор_хода
    ctrl = np.asarray(d['ctrl'], float)
    if 'path_rng' in d:
        rng = генератор_хода(d['path_rng'])
    else:
        rng = np.random.default_rng([int(d.get('path_seed', сид_мазка)), 7])
    нажим = float(d.get('pressure', 0.85))
    вход = None if d.get('entry') is None else float(d['entry'])
    размер = float(d.get('size', 12.0))
    if 'end' in d:
        return np.asarray(жест(ctrl, размер, d['end'], rng, нажим=нажим, вход=вход), float)
    return np.asarray(путь_с_нажимом(ctrl, размер, rng, нажим=нажим, вход=вход), float)


def ядро_движка(d, сид_мазка):
    """Точки ядра строки с профилями по ходу, как их кладёт повтор: путь движка, углы кисти в руке ("rotation_along",
    "tilt_along", "azimuth_along"), нажим по ходу ("pressure_along"). Отрыв по ходу (множитель 0) — None."""
    from кисть.повтор import нажим_вдоль, углы_вдоль, участки_касания
    т = путь_движка(d, сид_мазка)
    if any(d.get(k) is not None for k in ('rotation_along', 'tilt_along', 'azimuth_along')):
        т = углы_вдоль(т, d.get('rotation_along'), d.get('tilt_along'), d.get('azimuth_along'))
    if d.get('pressure_along') is not None:
        т = нажим_вдоль(т, d['pressure_along'])
        if участки_касания(т, d['pressure_along']) is not None:
            return None
    return np.asarray(т, float)


def _доля(xy):
    s_ = np.concatenate([[0.0], np.cumsum(np.hypot(*np.diff(xy, axis=0).T))])
    return s_ / max(s_[-1], 1e-9)


def _в_предел(dx, dy, предел, снос=None, где=None):
    """Увод (dx, dy) плавно ограничен: не дальше `предел` (None — без предела). `снос` — память глаза (`живая.Снос`):
    среднее увода хода правится по ходам, уже лежащим под путём `где`. Ответ: dx, dy, длины увода."""
    if снос is not None and len(dx):
        m = np.array([dx.mean(), dy.mean()])
        m2 = снос(где, m)
        dx, dy = dx + (m2[0] - m[0]), dy + (m2[1] - m[1])
    r_ = np.hypot(dx, dy)
    if предел is None:
        return dx, dy, r_
    предел = max(float(предел), 1e-9)
    k_ = np.where(r_ > 1e-9, предел * np.tanh(r_ / предел) / np.maximum(r_, 1e-9), 1.0)
    return dx * k_, dy * k_, r_ * k_


def _качание(Hp, u, g):
    """Во сколько раз рука качает нажим в доле пути u (0–1): вокруг своего среднего, у концов хода — 1."""
    тело = Hp > 0.5 * Hp.max()
    к = np.clip(Hp / max(float(np.median(Hp[тело])), 1e-6), 0.6, 1.4)
    у_концов = np.clip(np.minimum(u, 1 - u) / 0.12, 0, 1)               # вход и конец — как записаны
    return (1 + (к - 1) * у_концов) ** g


