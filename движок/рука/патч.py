def _изгибы(P):
    """Опорные точки — гладкая кривая через них: изгиб отрезка = поворот касательной между его концами, °."""
    n = len(P)
    кас = np.zeros((n, 2))
    кас[0], кас[-1] = P[1] - P[0], P[-1] - P[-2]
    for i in range(1, n - 1):
        кас[i] = P[i + 1] - P[i - 1]
    уг = np.arctan2(кас[:, 1], кас[:, 0])
    return [math.degrees((уг[j + 1] - уг[j] + math.pi) % (2 * math.pi) - math.pi) for j in range(n - 1)]


def намерение_из_строки(d, px_мм):
    P = np.asarray(d['ctrl'], float)[:, :2] / px_мм
    держать = np.concatenate([[True], np.hypot(*np.diff(P, axis=0).T) > 0.05])     # повтор точки на месте — не цель
    P = P[держать]
    if len(P) < 2:
        return None, None
    W = float(d.get('size', 16.0)) / px_мм
    ход = dict(точки=[tuple(p) for p in P], изгиб=_изгибы(P), допуск=float(np.clip(0.3 * W, 0.6, 4.0)),
               нажим=float(d.get('pressure', 0.8)) / 0.8, роль=(d.get('object'), d.get('brush', d.get('tool'))))
    return ход, ПРИКАЗ.get(d.get('end'))


def _упростить(P, допуск):
    """Сырой путь — в немногие цели: номера точек, без которых ломаная уходит от пути дальше допуска (мм)."""
    держать = np.zeros(len(P), bool)
    держать[[0, -1]] = True
    стек = [(0, len(P) - 1)]
    while стек:
        a, b = стек.pop()
        if b - a < 2:
            continue
        d = P[b] - P[a]
        L = np.hypot(*d)
        Q = P[a + 1:b] - P[a]
        откл = np.abs(Q[:, 0] * d[1] - Q[:, 1] * d[0]) / L if L > 1e-9 else np.hypot(*Q.T)
        i = int(np.argmax(откл))
        if откл[i] > допуск:
            m = a + 1 + i
            держать[m] = True
            стек += [(a, m), (m, b)]
    return np.nonzero(держать)[0]


def намерение_из_сырых(A, d, px_мм, ширина_px):
    """Готовый путь (точки ядра A: x, y, нажим, …, px журнала) — намерение: цели — упрощённая ломаная (от 0,5 мм и
    грубее, пока целей больше десяти), изгиб — по соседним целям. Ответ: ход и номера точек-целей; None — рука не берёт."""
    P = A[:, :2] / px_мм
    допуск = 0.5
    idx = _упростить(P, допуск)
    while len(idx) > 10:
        допуск *= 1.6
        idx = _упростить(P, допуск)
    держать = np.concatenate([[True], np.hypot(*np.diff(P[idx], axis=0).T) > 0.05])
    if not держать[-1] and len(idx) > 2:                  # ход вернулся в начало: конец остаётся целью, сосед уходит
        держать[-1], держать[-2] = True, False
    idx = idx[держать]
    if len(idx) < 2 or idx[-1] != len(P) - 1 or (np.hypot(*np.diff(P[idx], axis=0).T) <= 0.05).any():
        return None, None
    Ц = P[idx]
    p = A[:, 2]
    нажим = float(np.median(p[p > 0.5 * p.max()])) / 0.8 if p.max() > 0 else 1.0
    W = ширина_px / px_мм
    ход = dict(точки=[tuple(q) for q in Ц], изгиб=_изгибы(Ц), допуск=float(np.clip(0.3 * W, 0.6, 4.0)),
               нажим=float(np.clip(нажим, 0.3, 1.25)), роль=(d.get('object'), d.get('brush', d.get('tool'))))
    return ход, idx


def _дуга(A, B, изгиб, f):
    """Точки на дуге от A к B с поворотом касательной на `изгиб`° в долях f (как `движение._на_дуге`, разом)."""
    Δ = math.radians(изгиб)
    if abs(Δ) < 1e-4:
        return A + np.outer(f, B - A)
    хорда = B - A
    R = np.hypot(*хорда) / (2 * math.sin(Δ / 2))
    θ0 = math.atan2(хорда[1], хорда[0]) - Δ / 2
    C = A + R * np.array([math.cos(θ0 + math.pi / 2), math.sin(θ0 + math.pi / 2)])
    v = A - C
    c, s_ = np.cos(Δ * f), np.sin(Δ * f)
    return C + np.column_stack([c * v[0] - s_ * v[1], s_ * v[0] + c * v[1]])


def увести(A, idx, ход, куски, сила, px_мм, увод=None, темп=1.0, снос=None):
    """Готовый путь A (px) через руку. К каждой записанной точке прибавляется то, чем ход руки (куски касания, мм)
    разошёлся с её же намерением — дугами через цели, — в той же доле пути: снос, дуга рычага, срез угла, недолёт.
    Увод растёт с силой до 0,3 и не дальше `УВОД_ММ`·сила. Нажим качается вокруг записанного (у концов — как записан),
    время шага — по ходу руки вокруг записанного (в 0,5–2 раза) и весь ход — в `темп` раз в степени силы. Точек столько
    же; столбцы от пятого — как были."""
    g = float(np.clip(сила / 0.3, 0.0, 1.0))
    H = np.vstack(куски)
    P = A[:, :2] / px_мм
    Ц, изг = np.asarray(ход['точки'], float), ход['изгиб']
    n, m = len(P), len(idx) - 1
    s_ = np.concatenate([[0.0], np.cumsum(np.hypot(*np.diff(P, axis=0).T))])
    j = np.clip(np.searchsorted(idx, np.arange(n), side='right') - 1, 0, m - 1)
    f = (s_ - s_[idx[j]]) / np.maximum(s_[idx[j + 1]] - s_[idx[j]], 1e-9)
    хорды = np.hypot(*np.diff(Ц, axis=0).T)
    полу = np.radians(np.asarray(изг, float)) / 2
    Lc = хорды * np.where(np.abs(полу) > 1e-4, полу / np.sin(np.where(np.abs(полу) > 1e-4, полу, 1.0)), 1.0)
    cum = np.concatenate([[0.0], np.cumsum(Lc)])
    u = (cum[j] + f * Lc[j]) / max(cum[-1], 1e-9)
    опора = np.empty((n, 2))
    for k in range(m):
        тут = j == k
        if тут.any():
            опора[тут] = _дуга(Ц[k], Ц[k + 1], изг[k], f[тут])
    uH = _доля(H[:, :2])
    dx, dy, r_ = _в_предел(g * (np.interp(u, uH, H[:, 0]) - опора[:, 0]), g * (np.interp(u, uH, H[:, 1]) - опора[:, 1]),
                           УВОД_ММ * сила if УВОД_ММ else None, снос, P)
    out = A.copy()
    out[:, 0] += dx * px_мм
    out[:, 1] += dy * px_мм
    out[:, 2] = np.clip(A[:, 2] * np.interp(u, uH, _качание(H[:, 2], uH, g)), 0, 1)
    if A.shape[1] > 3 and np.isfinite(A[:, 3]).all():
        tH = np.cumsum(H[:, 3])
        τ = np.interp(u, uH, tH / max(tH[-1], 1e-9))
        du, dτ = np.diff(u), np.diff(τ)
        ρ = np.where(du > 1e-9, dτ / np.maximum(du, 1e-9), 1.0)
        out[1:, 3] = A[1:, 3] * (np.clip(ρ, 0.5, 2.0) * темп) ** g
    if увод is not None:
        увод.append(float(np.median(r_)))
    return out


def увести_ленту(d, сила, r, px_мм):
    """Лента скотча с малой ошибкой места и угла: маска сдвинута (σ `ЛЕНТА_ММ`·сила) и довёрнута вокруг своей середины
    (σ `ЛЕНТА_ГРАД`·сила). Ответ: строка маски, сдвиг мм, угол °; пустая маска — None."""
    from scipy import ndimage
    from кисть.скотч import маска_в_строку, маска_из_строки
    м = маска_из_строки(d['mask'], d['shape'])
    ys, xs = np.nonzero(м)
    if not len(ys):
        return None
    сдвиг = r.standard_normal(2) * ЛЕНТА_ММ * сила                       # мм: по x, по y
    угол = float(r.standard_normal()) * ЛЕНТА_ГРАД * сила
    ц = np.array([ys.mean(), xs.mean()])
    c, s_ = math.cos(math.radians(угол)), math.sin(math.radians(угол))
    M = np.array([[c, s_], [-s_, c]])                                   # откуда берётся пиксель выхода: поворот назад
    куда = ц + np.array([сдвиг[1], сдвиг[0]]) * px_мм
    нов = ndimage.affine_transform(м.astype(np.float32), M, offset=ц - M @ куда, order=1, mode='nearest') > 0.5
    return маска_в_строку(нов), (float(сдвиг[0]), float(сдвиг[1])), угол


def _точки(d):
    """Готовые точки строки ("core" или "points") массивом; None — не числа или не таблица."""
    try:
        A = np.array(d['core'] if 'core' in d else d['points'], dtype=np.float64)
    except (TypeError, ValueError):
        return None
    return A if A.ndim == 2 and len(A) >= 1 else None


def вид_хода(d):
    """Как рука берёт строку мазка: ('цели', None) — ход по опорным точкам; ('ядро', None) — опорные точки с профилем
    по ходу; ('сырые', None) — готовые точки; (None, почему) — как есть."""
    if 'lines' in d:
        return None, 'набор линий'
    if 'ctrl' in d:
        try:
            c = np.asarray(d['ctrl'], float)
        except (TypeError, ValueError):
            return None, 'тычок'
        if not (c.ndim == 2 and c.shape[1] >= 2 and len(c) >= 2 and bool((np.hypot(*np.diff(c[:, :2], axis=0).T) > 1e-6).any())):
            return None, 'тычок'
        return ('ядро' if any(d.get(k) is not None for k in ПО_ХОДУ) else 'цели'), None
    return 'сырые', None


def _рукой(d):
    """Строка Рм-1: ход кисти по опорным точкам без профиля по ходу (рука строит весь путь и привязывает к ходу движка)."""
    return 'tool' not in d and any(k in d for k in _МАЗОК) and вид_хода(d)[0] == 'цели'


def инструмент(d, формы):
    """Чем сделан ход — имя для `МЕРА`: "tool" строки, мастихин (форма кисти или имя пресета) или кисть."""
    if 'tool' in d:
        return str(d['tool'])
    if формы.get(d.get('brush')) == 'мастихин' or 'мастихин' in str(d.get('preset', '')):
        return 'мастихин'
    return 'кисть'


class Интерес:
    """Интерес к месту (0 — фон, рука свободна; 1 — важное, рука собрана). Из "object" и "stage" строки (своих или
    последней пометки): чем уже кисти объекта среди кистей картины и чем позже этап, тем место важнее; имя объекта
    («фон», «глаза») — малая поправка. Где объекта и этапа нет — прежняя догадка: ширина кисти хода и счёт пометок.
    Собирается первым проходом журнала (`учесть` каждой строке, затем `готово`). Ширина хода — "size" строки, без
    него — ширина кисти из её строки "def"."""

    def __init__(self, записи=None):
        self.Ws, self._по, self._этапы, self.пометок, self.ширины = [], {}, [], 0, {}
        if записи is not None:                           # разом: [(строка словарём, текущие этап и объект), …]
            for d, тек in записи:
                self.учесть(d, тек)
            self.готово()

    def ширина(self, d):
        w = d.get('size')
        if w is None:
            w = self.ширины.get(d.get('brush'))
        return None if w is None else float(w)

    def учесть(self, d, тек):
        if 'mark' in d:
            self.пометок += 1
        if 'def' in d and isinstance(d.get('brush'), str):
            try:
                self.ширины[d['brush']] = float((d['def'] or {}).get('ширина'))
            except (TypeError, ValueError):
                pass
            return
        if 'lines' in d or not any(k in d and isinstance(d[k], list) and len(d[k]) >= 2 for k in _МАЗОК):
            return
        w = self.ширина(d)
        о, э = d.get('object', тек['object']), d.get('stage', тек['stage'])
        if w is not None:
            self.Ws.append(w)
            if о is not None:
                self._по.setdefault(str(о), []).append(w)
        if э is not None and э not in self._этапы:
            self._этапы.append(э)

    def готово(self):
        self.Ws = sorted(self.Ws) or [16.0]
        этапы = self._этапы
        if all(isinstance(э, (int, float)) for э in этапы):
            этапы.sort()
        self.этапы = {str(э): i / max(len(этапы) - 1, 1) for i, э in enumerate(этапы)}
        self.объекты = {о: self._место(float(np.median(w))) for о, w in self._по.items()}
        self.пометок = max(1, self.пометок)
        self._по = None

    def _место(self, w):
        return float(np.searchsorted(self.Ws, w) / len(self.Ws))            # 0 — самая узкая кисть картины

    def __call__(self, d, тек, пометка):
        w = self.ширина(d)
        место = self._место(self.Ws[len(self.Ws) // 2] if w is None else w)
        о, э = d.get('object', тек['object']), d.get('stage', тек['stage'])
        if о is None and э is None:
            return float(np.clip(0.75 * (1 - место) + 0.35 * пометка / self.пометок, 0, 1))
        слово = 0.0
        if о is not None:
            имя = str(о).lower()
            место = 0.6 * self.объекты.get(str(о), место) + 0.4 * место
            слово = -0.12 * any(с in имя for с in _ФОН) + 0.12 * any(с in имя for с in _ВАЖНОЕ)
        этап = self.этапы.get(str(э), пометка / self.пометок) if э is not None else пометка / self.пометок
        return float(np.clip(0.75 * (1 - место) + 0.35 * этап + слово, 0, 1))


