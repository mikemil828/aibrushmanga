def _строка(d):
    return json.dumps(d, ensure_ascii=False)


def _разобрать(l):
    s = l.strip()
    return json.loads(s) if s and not s.startswith('#') else {}


def _снять(l):
    """Строка журнала после патча -> исходная: (строка или None — строки не было, была ли в ней рука)."""
    if '"arm' not in l or l.lstrip().startswith('#'):
        return l, False
    d = json.loads(l)
    if ЧАСТЬ in d or ЗАЛАТАНО in d:
        return None, True
    if НАМЕРЕНИЕ in d:
        н = d[НАМЕРЕНИЕ]
        поля = {**{k: v for k, v in d.items() if k != НАМЕРЕНИЕ}, **н['fields']}
        return _строка({k: поля[k] for k in н['keys']}), True
    if ЗАГОЛОВОК in d and ('canvas' in d or 'note' in d):
        return (_строка({k: v for k, v in d.items() if k != ЗАГОЛОВОК}) if 'canvas' in d else None), True
    return l, False


def снять_руку(строки):
    """Журнал после патча -> исходный: строки с "arm_from" возвращаются к намерению (поля и порядок ключей — как были),
    строки "arm_part" и ходы дорисовки "arm_fill" (Рм-4) уходят, из строки холста уходит "arm". Журнал без руки
    возвращается как есть (те же строки)."""
    out, было = [], False
    for l in строки:
        x, б = _снять(l)
        было = было or б
        if x is not None:
            out.append(x)
    return out, было


def _силы(сила, сила_объектов):
    общая = СИЛА if сила is None else float(сила)
    по = {str(k): float(v) for k, v in (сила_объектов or {}).items()}
    if общая < 0 or any(v < 0 for v in по.values()) or not all(map(math.isfinite, [общая, *по.values()])):
        raise ValueError('сила руки — число от 0: 0 — журнал как есть, 0,15 — по умолчанию, к 0,3 геометрия хода целиком от руки')
    return общая, по


def _счёт(общая, по):
    return dict(рукой=0, как_есть=0, кусков=0, сеансов=0, почему={}, сила=общая, сила_объектов=по, снята=False,
                пути={}, инструменты={}, лент=0, увод_мм=None)


def провести_строку(d, сид_мазка, рука, тек, интерес, пометка, формы, px_мм, общая, по, сырые, счёт, увод, глаз=None):
    """Одна строка мазка или снятия (словарь) через руку — общий ход патча и живого письма (`рука.вживую`). Ответ:
    (новые строки словарями — первая с "arm_from", дальше касания с "arm_part"; None) или (None, почему как есть).
    `тек` — этап и объект от последней пометки, `интерес` — `Интерес`, `пометка` — сколько пометок выше, `формы` —
    {имя кисти: форма}; `счёт` и `увод` (мм) пополняются. `глаз` (Рм-4, только вживую) — функция: ход -> что рука
    делает иначе, увидев холст под ходом (`тормоз`, `точнее`, `легче` для `ЖиваяРука.ход`; допуск правит в самом ходе)."""
    вых = []
    путь, почему = вид_хода(d)
    чем = инструмент(d, формы)
    поле = A = None
    if путь == 'сырые':
        поле = 'core' if 'core' in d else 'points'
        A = _точки(d)
        if not сырые:
            путь, почему = None, 'сырые выключены'
        elif A is None or A.shape[1] < 3 or not np.isfinite(A[:, :3]).all():
            путь, почему = None, 'сырые точки без нажима'
        elif len(A) < 2 or float(np.sum(np.hypot(*np.diff(A[:, :2], axis=0).T))) < КОРОТКИЙ_ММ * px_мм:
            путь, почему = None, 'тычок' if len(A) < 2 else 'короткий ход'
    if путь is None:
        return None, почему
    объект = d.get('object', тек['object'])
    с = (по.get(str(объект), общая) if объект is not None else общая) * МЕРА.get(чем, 0.5)
    if с == 0:
        return None, 'сила 0'
    if путь == 'ядро':                               # профиль по ходу: точки ядра, как их кладёт повтор, дальше — как сырые
        try:
            A = ядро_движка(d, сид_мазка)
        except ValueError:
            A = None
        if A is None or len(A) < 2:
            return None, 'отрыв по ходу'
    рука.сила = с
    idx = приказ = E = None
    if путь == 'цели':
        ход, приказ = намерение_из_строки(d, px_мм)
        if ход is not None:
            E = путь_движка(d, сид_мазка)
        if ход is not None and len(ход['точки']) >= 3:
            # кривая по редким опорным точкам: цели руки — с гладкой кривой движка, а не сами опорные точки
            # (дуги через них ломаются в точках, и ход выходил с изломом); нажим — как назвала модель
            по_кривой, _ = намерение_из_сырых(E, d, px_мм, float(d.get('size', 16.0)))
            if по_кривой is not None:
                ход = {**по_кривой, 'нажим': ход['нажим']}
    else:
        ход, idx = намерение_из_сырых(A, d, px_мм, интерес.ширина(d) or 16.0)
    куски = []
    if ход is not None:
        if рука.пора_отойти():
            рука.с.новый_сеанс()
            рука.рука.где = None
        ход['интерес'] = интерес(d, тек, пометка)
        куски, зап = рука.ход(ход, приказ=приказ, **(глаз(ход) if глаз is not None else {}))
        рука.увидел(зап)
    if not куски or not all(np.isfinite(к).all() for к in куски):
        return None, 'рука не провела'
    предел = УВОД_ММ * с * px_мм if УВОД_ММ else None
    снос_px = (lambda где, m: рука.снос(где / px_мм, m / px_мм) * px_мм) if рука.снос is not None else None
    if путь == 'цели':
        плоская = формы.get(d.get('brush')) == 'плоская'
        база = {k: v for k, v in d.items() if k not in УБРАТЬ}
        if 'seed' not in база:
            база['seed'] = сид_мазка                    # ворс — с тем же сидом, что был у хода без руки
        время = float(E[:, 3].sum()) / max(sum(float(к[:, 3].sum()) for к in куски), 1e-9) if E.shape[1] > 3 else 1.0
        if len(куски) > 1:                               # рука оторвалась по ходу: куски её, время — как у движка
            куски, E = [np.column_stack([к[:, :3], к[:, 3] * время, к[:, 4:]]) for к in куски], None
        for k, кус in enumerate(куски):
            # на малой силе плоскую доворачивает сам движок; инструменту углы кисти не нужны
            т = в_точки(кус[:, :4] if 'tool' in d else кус if (плоская and с >= 0.3) else кус[:, :6], px_мм)
            if E is not None and len(т) >= 3:
                у = []
                т = привязать(np.asarray(т, float), E, с, предел, у, темп_руки(рука, зап), снос_px, ход, px_мм).tolist()
                увод.append(у[0] / px_мм)
            н = dict(база)
            н['core'] = [[round(v, 3) for v in p] for p in _реже(т).tolist()]
            if k:
                н['seed'] = int(база['seed']) + k
                н[ЧАСТЬ] = k
            else:
                н[НАМЕРЕНИЕ] = {'keys': list(d), 'fields': {f: d[f] for f in УБРАТЬ if f in d}}
            вых.append(н)
            счёт['кусков'] += 1
    else:
        B = увести(A, idx, ход, куски, с, px_мм, увод, темп_руки(рука, зап), рука.снос)
        if not np.isfinite(B).all():
            return None, 'рука не провела'
        if путь == 'ядро':
            убрать = УБРАТЬ + В_ЯДРО
            н = {k: v for k, v in d.items() if k not in убрать}
            н['core'] = [[round(v, 3) for v in p] for p in B.tolist()]
            if d.get('pressure_along') is not None and 'hand' not in d and 'tool' not in d:
                н['hand'] = True                         # с профилем нажима ход клался «нажим ведёт рука» — так и остаётся
            поля = {f: d[f] for f in убрать if f in d}
        else:
            исх = d[поле]
            н = dict(d)
            н[поле] = [[round(v, 3) for v in p[:4]] + list(q[4:]) for p, q in zip(B.tolist(), исх)]
            поля = {поле: исх}
        if 'seed' not in н:
            н['seed'] = сид_мазка
        н[НАМЕРЕНИЕ] = {'keys': list(d), 'fields': поля}
        вых.append(н)
        счёт['кусков'] += 1
    счёт['рукой'] += 1
    счёт['пути'][путь] = счёт['пути'].get(путь, 0) + 1
    счёт['инструменты'][чем] = счёт['инструменты'].get(чем, 0) + 1
    return вых, None


def _провести(источник, рука, общая, по, заголовок, сырые, лента, счёт):
    """Журнал через руку, строкой за строкой. `источник()` — новый проход по строкам исходного журнала (руки в них
    уже нет); проходов два: что за журнал (кисти, объекты, этапы), затем сам патч. Генератор строк нового журнала."""
    интерес, тек, есть_холст = Интерес(), dict(stage=None, object=None), False
    for l in источник():
        d = _разобрать(l)
        if 'mark' in d:
            тек = {п: d.get(п, тек[п]) for п in тек}
        есть_холст = есть_холст or 'canvas' in d
        интерес.учесть(d, тек)
    интерес.готово()

    сиды = _Сиды()
    px_мм, формы, пометка, сдвиг, вписан = 8.0, {}, 0, 0, False
    тек = dict(stage=None, object=None)
    увод = []
    if not есть_холст:                                 # журнал без строки холста: заголовок руки — заметкой первой строкой
        yield _строка({'note': 'рука', ЗАГОЛОВОК: заголовок})
        сдвиг, вписан = 1, True

    def как_есть(l, d, номер, свой, почему):
        счёт['как_есть'] += 1
        счёт['почему'][почему] = счёт['почему'].get(почему, 0) + 1
        if 'seed' not in d:
            # дерево сидов: повтор считает строки с теми же точками без своего "seed" — ходы руки из счёта ушли;
            # прежний журнал: сид шёл от номера строки, а он сдвинут. Сид пишется, строка возвращается по "arm_from"
            if (сиды.на_выходе(d, тек) != свой) if сиды.дерево else bool(сдвиг):
                return _строка({**d, 'seed': свой, НАМЕРЕНИЕ: {'keys': list(d), 'fields': {}}})
        return l

    for номер, l in enumerate(источник(), 1):
        d = _разобрать(l)
        if not d:
            yield l
            continue
        if 'mark' in d:
            тек = {п: d.get(п, тек[п]) for п in тек}
        if 'canvas' in d and not вписан:
            сиды.холст(d)
            px_мм = float(d.get('px_per_mm') or px_мм)
            yield _строка({**d, ЗАГОЛОВОК: заголовок})
            вписан = True
            continue
        if 'def' in d and isinstance(d.get('brush'), str):
            формы[d['brush']] = (d['def'] or {}).get('форма')
        if 'mark' in d:
            пометка += 1
            рука.с.пауза(0.5)
            рука.рука.где = None
        if 'tape' in d and 'mask' in d and 'shape' in d:
            if лента and общая > 0:
                нов = увести_ленту(d, общая, рука.с.r, px_мм)
                if нов is not None:
                    счёт['лент'] += 1
                    yield _строка({**d, 'mask': нов[0], НАМЕРЕНИЕ: {'keys': list(d), 'fields': {'mask': d['mask']}}})
                    continue
            yield l
            continue
        if not any(k in d for k in _МАЗОК):
            yield l
            continue
        сид_мазка = сиды.сид(d, номер, тек)
        нов, почему = провести_строку(d, сид_мазка, рука, тек, интерес, пометка, формы, px_мм, общая, по, сырые, счёт, увод)
        if нов is None:
            yield как_есть(l, d, номер, сид_мазка, почему)
            continue
        for н in нов:
            yield _строка(н)
        сдвиг += len(нов) - 1
    счёт['сеансов'] = рука.с.сеанс
    if увод:
        счёт['увод_мм'] = tuple(float(v) for v in np.percentile(увод, [50, 95]))


def _заголовок(человек, зерно, общая, по, кто, сырые, лента):
    return dict(person=человек, seed=зерно, strength=общая, **({'by_object': по} if по else {}),
                **({} if сырые else {'raw': False}), **({'tape': True} if лента else {}), who=кто)


def переписать(строки, сила=СИЛА, человек=None, зерно=None, сила_объектов=None, кто='патч', сырые=True, лента=False):
    """Строки журнала -> (строки нового журнала, счёт, рука). Строки — без перевода строки на конце. `сила` — число на
    весь журнал, `сила_объектов` — {объект: сила}. `человек`, `зерно` — None: случайные, один раз; выбранные — в
    `счёт['человек']`, `счёт['зерно']` и в строке холста. Сила 0 везде — те же строки (журнал без руки — как есть).
    `сырые=False` — строки с готовыми точками ("core", "points") как есть; `лента=True` — лента с ошибкой места и угла."""
    общая, по = _силы(сила, сила_объектов)
    строки, был_патч = снять_руку([l.rstrip('\n') for l in строки])
    счёт = _счёт(общая, по)
    счёт['снята'] = был_патч
    if общая == 0 and not any(по.values()):
        return строки, счёт, None
    человек = secrets.randbelow(1_000_000) if человек is None else int(человек)
    зерно = secrets.randbelow(1_000_000) if зерно is None else int(зерно)
    счёт.update(человек=человек, зерно=зерно)
    рука = ЖиваяРука(Человек(человек), зерно=зерно, сила=общая)
    out = list(_провести(lambda: iter(строки), рука, общая, по, _заголовок(человек, зерно, общая, по, кто, сырые, лента),
                         сырые, лента, счёт))
    return out, счёт, рука


def _строки_файла(путь):
    """Строки файла без перевода строки, как `текст.split('\\n')`: после последнего перевода строки — пустая."""
    конец = False
    with open(путь, encoding='utf-8', newline='') as f:
        for l in f:
            конец = l.endswith('\n')
            yield l[:-1] if конец else l
    if конец:
        yield ''


def _записать(путь, строки):
    with open(путь, 'w', encoding='utf-8', newline='') as f:
        for i, l in enumerate(строки):
            f.write(('\n' + l) if i else l)


def переписать_файл(вход, выход, сила=СИЛА, человек=None, зерно=None, сила_объектов=None, кто='патч', сырые=True, лента=False):
    """То же, что `переписать`, из файла в файл строкой за строкой: большой журнал в память не грузится.
    Ответ: (счёт, рука). Сила 0 и журнал без руки — файл копируется байт в байт."""
    общая, по = _силы(сила, сила_объектов)
    счёт = _счёт(общая, по)

    def источник():
        for l in _строки_файла(вход):
            x, б = _снять(l)
            счёт['снята'] = счёт['снята'] or б
            if x is not None:
                yield x

    if общая == 0 and not any(по.values()):
        for _ in источник():
            pass
        if счёт['снята']:
            _записать(выход, источник())
        else:
            shutil.copyfile(вход, выход)
        return счёт, None
    человек = secrets.randbelow(1_000_000) if человек is None else int(человек)
    зерно = secrets.randbelow(1_000_000) if зерно is None else int(зерно)
    счёт.update(человек=человек, зерно=зерно)
    рука = ЖиваяРука(Человек(человек), зерно=зерно, сила=общая)
    _записать(выход, _провести(источник, рука, общая, по, _заголовок(человек, зерно, общая, по, кто, сырые, лента),
                               сырые, лента, счёт))
    return счёт, рука


def main(argv=None):
    ap = argparse.ArgumentParser(prog='python3 -m рука.патч', description='Рука патчем: журнал мазков -> журнал, где ходы проведены рукой (кисть и инструменты, опорные и сырые точки). Движок не трогается; выход кладёт обычный повтор.')
    ap.add_argument('вход', help='журнал .jsonl')
    ap.add_argument('выход', help='новый журнал .jsonl (не тот же файл)')
    ap.add_argument('--сила', type=float, default=СИЛА, help='0 — журнал как есть; 0.15 — по умолчанию; к 0.3 геометрия хода целиком от руки; выше — размашистее')
    ap.add_argument('--сила-объекта', action='append', default=[], metavar='ИМЯ=ЧИСЛО', help='своя сила объекту ("object" строки или пометки); можно несколько раз')
    ap.add_argument('--человек', type=int, default=None, help='число руки (постоянное: правша/левша, опора, уклон, размах, хват); без ключа — случайное')
    ap.add_argument('--зерно', type=int, default=None, help='поток случая этого раза; без ключа — случайное')
    ap.add_argument('--без-сырых', action='store_true', help='строки с готовыми точками ("core", "points") — как есть')
    ap.add_argument('--лента', action='store_true', help='лента скотча — с малой ошибкой места и угла (без ключа — как есть)')
    a = ap.parse_args(argv)
    if os.path.abspath(a.вход) == os.path.abspath(a.выход):
        ap.error('вход и выход — один файл: журнал без руки нужен, чтобы пропатчить заново')
    по = {}
    for пара in a.сила_объекта:
        имя, знак, число = пара.rpartition('=')
        try:
            по[имя] = float(число.replace(',', '.'))
        except ValueError:
            знак = ''
        if not знак or not имя:
            ap.error(f'--сила-объекта {пара!r}: нужно ИМЯ=ЧИСЛО, например лицо=0.1')
    t0 = time.time()
    try:
        счёт, рука = переписать_файл(a.вход, a.выход, a.сила, a.человек, a.зерно, по, сырые=not a.без_сырых, лента=a.лента)
    except ValueError as e:
        ap.error(str(e))
    if рука is None:
        print(f'{a.выход}: сила 0 — ' + ('рука снята, строки возвращены к исходным' if счёт['снята']
                                         else 'журнал как есть, байт в байт; заголовок руки не пишется'))
        return 0
    ж = рука.журнал
    print(f'{a.выход}: человек {счёт["человек"]}, зерно {счёт["зерно"]}, сила {счёт["сила"]:g}'
          + (', по объектам ' + ', '.join(f'{k}={v:g}' for k, v in счёт['сила_объектов'].items()) if счёт['сила_объектов'] else ''))
    print(f'  рука: {рука.ч0.строка()}')
    всего = счёт['рукой'] + счёт['как_есть']
    имена = {'цели': 'по опорным точкам', 'сырые': 'по сырым точкам', 'ядро': 'с профилем по ходу'}
    print(f'  мазков рукой {счёт["рукой"]} из {всего} ({100 * счёт["рукой"] / max(всего, 1):.1f} %; строк {счёт["кусков"]}): '
          + ', '.join(f'{имена[k]} {v}' for k, v in счёт['пути'].items()) + '; '
          + ', '.join(f'{k} {v}' for k, v in счёт['инструменты'].items()))
    print(f'  как есть {счёт["как_есть"]}' + (' (' + ', '.join(f'{k} {v}' for k, v in счёт['почему'].items()) + ')' if счёт['почему'] else '')
          + (f', лент с ошибкой места {счёт["лент"]}' if a.лента else '')
          + f', сеансов {счёт["сеансов"]}, {time.time() - t0:.1f} с')
    if счёт['увод_мм']:
        print(f'  увод от записанного пути: медиана {счёт["увод_мм"][0]:.2f} мм, 95 % ходов — до {счёт["увод_мм"][1]:.2f} мм')
    if ж:
        b = [з['b'] for з in ж]
        print(f'  темп {np.mean(b):.2f} ({min(b):.2f}–{max(b):.2f}), усталость к концу {ж[-1]["усталость"]:.2f}')
    print(f'  повтор: python3 -m кисть.повтор {a.выход} --out лист.png; тот же журнал снова — те же ключи --человек, --зерно')
    return 0


if __name__ == '__main__':
    sys.exit(main())
