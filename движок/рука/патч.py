def _опора(ход, px_мм, u):
    """Намерение руки — дуги через цели хода (мм) — точками в px в долях пути u (0–1)."""
    Ц, изг = np.asarray(ход['точки'], float), ход['изгиб']
    f = np.linspace(0.0, 1.0, 33)
    О = np.vstack([_дуга(Ц[k], Ц[k + 1], изг[k], f[(1 if k else 0):]) for k in range(len(Ц) - 1)]) * px_мм
    uО = _доля(О)
    return np.column_stack([np.interp(u, uО, О[:, 0]), np.interp(u, uО, О[:, 1])])


def привязать(H, E, сила, предел=None, увод=None, темп=1.0, снос=None, ход=None, px_мм=8.0):
    """Ход руки H (px, столбцы ядра) привязан к ходу движка E: к силе 0 это ход движка, к силе 0,3 увод руки в полную
    меру, но не дальше `предел` px от хода движка (None — без предела). С `ход` (намерение руки, мм) к ходу движка
    прибавляется то, чем рука разошлась со своим же намерением — дугами через цели (как у сырых точек, `увести`):
    гладкая кривая движка между редкими опорными точками остаётся гладкой, а не ломается в целях; без `ход` —
    прежний счёт: разница хода руки и хода движка. Нажим — всегда профиль движка (вход, тело и
    конец выбрала модель), рука его только качает вокруг своего среднего. Наклон ручки растёт с силой. Время хода —
    как у движка (краска ложится по времени касания, а его выбрала модель), помноженное на `темп` в степени силы; по
    ходу время расходится, как шла рука (разгон, середина, торможение). `увод` — список: в него ложится медиана увода, px.
    `снос` — память глаза в px: f(путь, средний увод) -> средний увод (ходы одного места уходят вместе)."""
    g = float(np.clip(сила / 0.3, 0.0, 1.0))
    uH, uE = _доля(H[:, :2]), _доля(E[:, :2])
    Ex, Ey, Ep = (np.interp(uH, uE, E[:, k]) for k in (0, 1, 2))
    out = H.copy()
    Ох, Оу = (Ex, Ey) if ход is None else _опора(ход, px_мм, uH).T
    dx, dy, r_ = _в_предел(g * (H[:, 0] - Ох), g * (H[:, 1] - Оу), предел, снос, np.column_stack([Ex, Ey]))
    out[:, 0] = Ex + dx
    out[:, 1] = Ey + dy
    out[:, 2] = np.clip(Ep * _качание(H[:, 2], uH, g), 0, 1)
    if out.shape[1] > 3:
        if ход is None:
            out[:, 3] = H[:, 3] * (float(E[:, 3].sum()) / max(float(H[:, 3].sum()), 1e-9)) * темп ** g
        else:
            # время шага — как у движка в этой доле пути; рука его качает до `ШАГ_ВРЕМЕНИ` раз в степени силы:
            # у цели она медлит, но не встаёт — стоячая кисть оставляла шов поперёк хода
            dt = np.diff(np.interp(uH, uE, np.cumsum(E[:, 3])), prepend=0.0)
            ds = np.hypot(*np.diff(H[:, :2], axis=0).T)
            ρ = (H[1:, 3] / np.maximum(ds, 1e-9)) / max(float(H[1:, 3].sum()) / max(float(ds.sum()), 1e-9), 1e-9)
            dt[1:] *= np.clip(ρ, 1.0 / ШАГ_ВРЕМЕНИ, ШАГ_ВРЕМЕНИ) ** g
            out[:, 3] = dt * (float(E[:, 3].sum()) / max(float(dt.sum()), 1e-9)) * темп ** g
    if out.shape[1] > 4:
        out[:, 4] *= g
    if увод is not None:
        увод.append(float(np.median(r_)))
    return out


def _реже(т, допуск=РЕДКО_PX):
    """Точки хода руки (px; x, y, нажим, dt мс, наклон °, азимут рад, поворот °) — реже: остаются те, без которых
    прямая между соседями уходит от хода дальше `допуск`. Мера одна на все столбцы, в px места: нажим 0,01 — 0,2 px,
    время хода 1 мс — 0,3 px, наклон и поворот 1° — 0,3 px, азимут 0,04 рад — 0,2 px. Время выброшенных точек уходит
    следующей оставленной: время хода то же. Рука ставит точки через 0,4 px — журнал натюрморта рос впятеро; ядро
    между точками идёт по прямой, и на картинке разницы нет (стенд Движка 267: 0,3 из 255 в среднем)."""
    A = np.asarray(т, float)
    n = len(A)
    if допуск is None or n < 4:
        return A
    t = np.cumsum(A[:, 3])
    вес = [1.0, 1.0, 20.0, 0.3, 0.3, 5.0, 0.3]
    F = np.column_stack([A[:, 0], A[:, 1], A[:, 2] * вес[2], t * вес[3]] + [A[:, k] * вес[min(k, 6)] for k in range(4, A.shape[1])])
    s_ = np.concatenate([[0.0], np.cumsum(np.hypot(*np.diff(A[:, :2], axis=0).T))])
    держать = np.zeros(n, bool)
    держать[[0, -1]] = True
    стек = [(0, n - 1)]
    while стек:
        a, b = стек.pop()
        if b - a < 2:
            continue
        w = ((s_[a + 1:b] - s_[a]) / max(s_[b] - s_[a], 1e-9))[:, None]
        откл = np.abs(F[a + 1:b] - (F[a] + w * (F[b] - F[a]))).max(axis=1)
        i = int(np.argmax(откл))
        if откл[i] > допуск:
            m = a + 1 + i
            держать[m] = True
            стек += [(a, m), (m, b)]
    idx = np.nonzero(держать)[0]
    B = A[idx].copy()
    B[:, 3] = np.diff(np.concatenate([[0.0], t[idx]]))
    return B


