"""Рука с живым состоянием (Den 26.11 23:18 +04: «в + зависимость от еще чего-то … второе, с возможностью приказать,
но не до 100% … яблоко.. 5 раз подряд»). Блок 10 «Рука-модуль», Рм-1: модуль отдельный, движок его не зовёт.

Сида мазка нет. Есть человек (постоянное) и состояние, которое идёт от мазка к мазку и от картины к картине:

  время     — разогрев (первые мазки скованы), усталость (копится с путём и нажимом, отходит на паузе),
              внимание (медленно гуляет само, как у человека);
  холст     — что легло на самом деле: промах мимо цели, сухой рваный след, кончившаяся краска;
  задача    — допуск цели и длина хода (точное место — медленно), роль мазка, знаком ли жест (повтор смелее);
  удача     — уверенность растёт от попаданий и падает от промахов; после промаха рука осторожнее;
  краска    — сытая кисть идёт смелее и тяжелее, голодная прижимается; когда идти к палитре, решает рука;
  поза      — далеко от удобного места рука менее точна.

Темп рука выбирает сама; приказ («быстрее», «медленнее») исполняет частью — насколько, зависит от состояния."""
import copy
import math

import numpy as np

