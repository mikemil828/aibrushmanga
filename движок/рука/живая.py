class Состояние:
    def __init__(self, человек, зерно):
        self.r = np.random.default_rng([человек.сид, зерно, 259])
        self.разогрев = 0.15
        self.усталость = 0.0
        self.внимание = 0.0            # −1…1, гуляет само — сумма трёх волн: в десяток, сотню и тысячу мазков
        self.волны = [0.0, 0.0, 0.0]
        self.скука = 0.0               # растёт на одинаковых мазках подряд, сбивается сменой жеста и промахом
        self.кураж = 0.0               # растёт на серии удач: рука рискует, пока не промахнётся
        self.день = 0.0                # настроение сеанса: своё у каждого присеста
        self.сеанс = 1
        self.с_начала_сеанса = 0
        self.уверенность = 0.55
        self.знаком = 0                # сколько раз подряд тот же жест
        self.прошлый = None
        self.уклон = 0.0               # медленный увод привычек руки
        self.размах = 0.0
        self.после_промаха = 0.0
        self.после_добора = 0.0
        self.мазков = 0

    def шаг_времени(self, путь_мм, нажим):
        r = self.r
        self.разогрев += (1 - self.разогрев) * 0.05
        self.усталость = min(1.0, self.усталость + путь_мм * (0.4 + нажим) * 0.00004)
        for i, (держит, толчок) in enumerate([(0.88, 0.22), (0.988, 0.085), (0.9988, 0.030)]):
            self.волны[i] = держит * self.волны[i] + толчок * r.standard_normal()
        self.внимание = float(np.clip(sum(self.волны) + self.день - self.скука, -1.5, 1.5))
        self.с_начала_сеанса += 1
        self.уклон = 0.96 * self.уклон + math.radians(0.8) * r.standard_normal()
        self.размах = 0.96 * self.размах + 0.012 * r.standard_normal()
        self.после_промаха *= 0.6
        self.после_добора *= 0.4
        self.мазков += 1

    def пауза(self, сила=1.0):
        """Отошёл от холста: усталость отходит, разогрев частью теряется, внимание встряхивается."""
        self.усталость *= 1 - 0.55 * сила
        self.разогрев *= 1 - 0.35 * сила
        self.волны[0] = 0.6 * self.r.standard_normal()
        self.скука *= 1 - 0.8 * сила
        self.знаком = 0

    def новый_сеанс(self):
        """Рука отошла надолго и вернулась: свежая, остывшая, с другим настроением."""
        self.усталость *= 0.1
        self.разогрев = 0.2
        self.день = 0.22 * float(self.r.standard_normal())
        self.волны[0] = self.волны[1] = 0.0
        self.скука = self.кураж = 0.0
        self.знаком = 0
        self.сеанс += 1
        self.с_начала_сеанса = 0

    def снимок(self):
        return dict(разогрев=self.разогрев, усталость=self.усталость, внимание=self.внимание,
                    уверенность=self.уверенность, скука=self.скука, кураж=self.кураж, сеанс=self.сеанс)


class Снос:
    """Память глаза о том, куда на холсте уже ушли ходы (Рм-2). Человек кладёт мазок не по линейке холста, а к тому,
    что уже лежит: если прежние ходы этого места легли на полмиллиметра левее задуманного, следующий целится туда же.
    Поэтому общий снос хода (среднее его увода) берётся частью `доля` из сноса ходов, уже лежащих под ним, и только
    остальное — своё; форма хода (дуга, срез угла, недолёт) остаётся своей. Без этого соседние ходы уходят врозь, и
    в щели между ними проступает нижний слой. Сетка — ячейки `ячейка` мм; первый ход места задаёт его снос сам."""

    def __init__(self, ячейка=5.0, доля=0.7, память=0.3):
        self.ячейка, self.доля, self.память, self.поле = float(ячейка), float(доля), float(память), {}

    def __call__(self, точки, свой):
        """точки — путь хода, мм (n, 2); свой — средний увод хода, мм (dx, dy). Ответ — средний увод с поправкой глаза."""
        ячейки = set(map(tuple, np.floor(np.asarray(точки, float)[:, :2] / self.ячейка).astype(int).tolist()))
        были = [self.поле[я] for я in ячейки if я in self.поле]
        свой = np.asarray(свой, float)
        if были:
            свой = self.доля * np.mean(были, axis=0) + (1 - self.доля) * свой
        for я in ячейки:
            было = self.поле.get(я)
            self.поле[я] = свой if было is None else (1 - self.память) * было + self.память * свой
        return свой


class ЖиваяРука:
    def __init__(self, человек, зерно=0, сила=1.0):
        self.ч0 = человек
        self.сила = float(сила)      # насколько рука видна: 0 — путь почти как задуман, 1 — в полную силу
        self.с = Состояние(человек, зерно)
        self.рука = Рука(человек, человек.темп, сид=зерно)
        self.рука.r = self.с.r                       # один поток случая на всю жизнь руки: сид не возвращается
        self.журнал = []
        self.снос = Снос()                           # куда на холсте уже ушли ходы — глаз целит к лежащему

    # ------------------------------------------------------------------ выбор темпа
    def темп(self, ход, краска, приказ=None):
        с, ч = self.с, self.ч0
        P = np.asarray(ход['точки'], float)
        D = float(np.sum(np.hypot(*np.diff(P, axis=0).T))) if len(P) > 1 else 1.0
        допуск = float(ход.get('допуск', 3.0))
        трудность = math.log2(D / допуск + 1.0)                    # чем длиннее ход и уже цель, тем медленнее
        жест = ход.get('роль')                                      # тот же предмет той же кистью — тот же жест
        с.знаком = с.знаком + 1 if жест == с.прошлый else 0
        if жест == с.прошлый:
            с.скука = min(1.0, с.скука + 0.006)                    # одно и то же подряд — рука идёт на автомате
        else:
            с.скука *= 0.55
        с.прошлый = жест
        интерес = float(ход.get('интерес', 0.5))                   # важное место — рука собрана, фон — свободна
        b = (ч.темп + 0.22 * (с.разогрев - 0.6) + 0.35 * (с.уверенность - 0.6) - 0.25 * с.усталость
             + 0.10 * с.внимание - 0.13 * (трудность - 2.3) + 0.035 * min(с.знаком, 6)
             - 0.30 * с.после_промаха + 0.10 * с.после_добора
             + 0.12 * с.скука + 0.15 * с.кураж - 0.22 * (интерес - 0.5))
        if краска is not None and краска < 0.25:
            b -= 0.10                                              # голодной кистью не размахнёшься
        свой = float(np.clip(b, 0.03, 0.97))
        if приказ is None:
            return свой, свой, None
        слушается = float(np.clip(0.72 - 0.25 * с.усталость + 0.08 * с.внимание + 0.10 * (с.уверенность - 0.6), 0.35, 0.88))
        return float(np.clip(свой + слушается * (приказ - свой), 0.03, 0.97)), свой, слушается

    # ------------------------------------------------------------------ один ход
    def ход(self, ход, краска=None, приказ=None, тормоз=0.0, точнее=1.0, легче=1.0):
        """Ответ: куски касания (мм) и запись о ходе. `краска` — сколько осталось на кисти (0–1) или None."""
        с, ч0 = self.с, self.ч0
        b, свой, слушается = self.темп(ход, краска, приказ)
        b = float(np.clip(b - тормоз, 0.03, 0.97))
        ч = copy.copy(ч0)
        поза = 0.0
        if self.рука.дом is not None:
            поза = float(np.clip(np.hypot(*(np.asarray(ход['точки'][0], float) - self.рука.дом)) / max(self.рука.R, 1.0), 0, 1.5))
        интерес = float(ход.get('интерес', 0.5))
        шум = ((1.35 - 0.5 * с.разогрев) * (1 + 0.8 * с.усталость) * (1 - 0.15 * с.внимание) * (1 + 0.35 * поза)
               * (1 + 0.6 * с.скука) * (1 + 0.5 * с.кураж) * (1.3 - 0.6 * интерес))
        k = self.сила
        ч.kD, ч.kθ = ч0.kD * шум * точнее * k, ч0.kθ * шум * точнее * k
        ч.уклон = (ч0.уклон + с.уклон) * k
        ч.размах = 1.0 + (ч0.размах + с.размах - 1.0) * k
        ч.тело = ч0.тело * k
        ч.тяжесть, ч.лёгкость = ч0.тяжесть * (0.4 + 0.6 * k), ч0.лёгкость * (0.4 + 0.6 * k)
        ч.хват = ч0.хват * k
        ч.следит = 1.0 - (1.0 - ч0.следит) * k
        тяж = 1 + 0.12 * с.усталость + 0.10 * с.после_добора
        if краска is not None:
            тяж *= 1 + 0.18 * max(0.0, 0.35 - краска) / 0.35       # голодную кисть прижимают
        ч.нажим = min(0.97, ч0.нажим * тяж * легче * float(ход.get('нажим', 1.0)))
        self.рука.ч, self.рука.b = ч, b
        self.рука.вид = math.sqrt(max(k, 0.0))                     # на малой силе темп почти не меняет форму хода
        куски, путь = self.рука.жест([ход])
        цель = np.asarray(ход['точки'][-1], float)
        if куски:
            конец = куски[-1][-1, :2]
            начало = куски[0][0, :2]
            L = float(sum(np.sum(np.hypot(*np.diff(к[:, :2], axis=0).T)) for к in куски))
            p = float(np.mean(np.concatenate([к[:, 2] for к in куски])))
        else:
            конец = начало = цель
            L, p = 0.0, 0.0
        промах = self.рука.промах                                   # мимо цели пришла сама рука (подъём на ходу — не промах)
        с.усталость = min(1.0, с.усталость + 0.00012 * интерес)        # собранность утомляет и без пути
        зап = dict(b=b, свой=свой, слушается=слушается, промах=промах, допуск=float(ход.get('допуск', 3.0)), интерес=интерес,
                   роль=ход.get('роль'), путь=L, нажим=p, **с.снимок())
        self.журнал.append(зап)
        с.шаг_времени(L, p)
        return куски, зап

    def прикинуть(self, ход, краска=None):
        """Свой темп на этот ход, не начиная его (рука решает, сливать ли ходы или дробить)."""
        зн, пр = self.с.знаком, self.с.прошлый
        свой = self.темп(ход, краска)[1]
        self.с.знаком, self.с.прошлый = зн, пр
        return свой

    def фраза(self):
        """Сколько мазков подряд до взгляда на целое: увлечённая и уверенная рука тянет дольше."""
        return int(np.clip(round(4.5 + 1.5 * (self.с.уверенность - 0.6) * 4 - 1.0 * self.с.внимание + self.с.r.standard_normal()), 3, 7))

    def отошёл(self):
        """Взгляд на целое между фразами: короткая передышка, внимание собирается."""
        self.с.усталость *= 0.97
        self.с.внимание = 0.7 * self.с.внимание + 0.25
        self.с.знаком = max(0, self.с.знаком - 2)

    # ------------------------------------------------------------------ что рука узнала с холста
    def увидел(self, зап, закрыто=None, осталось=None, добрал=False):
        """После хода глаз видит след: попал ли, легла ли краска. От этого — уверенность и следующий ход."""
        с = self.с
        # удача — против своего обычного: рука судит ход по тому, как у неё выходит сейчас, а не по линейке
        об = getattr(с, 'обычный_промах', None)
        об = зап['промах'] if об is None else об
        плохо = зап['промах'] > max(2.0 * об, 0.05) or зап['промах'] > зап['допуск']
        удача = 1.0 - min(зап['промах'] / max(2.5 * об, 0.05), 1.0)
        с.обычный_промах = 0.97 * об + 0.03 * зап['промах']
        if закрыто is not None and закрыто < 0.45:
            удача *= 0.6                                           # след вышел рваным
        с.уверенность += 0.22 * (удача - с.уверенность)
        зап['плохо'] = плохо
        if плохо:
            с.после_промаха = 1.0
            с.кураж = 0.0                                          # промах отрезвляет и будит
            с.скука *= 0.3
        elif с.уверенность > 0.55:
            с.кураж = min(1.0, с.кураж + 0.008)
        if добрал:
            с.после_добора = 1.0
        зап.update(удача=удача, закрыто=закрыто, осталось=осталось, добрал=добрал)

    def пора_отойти(self):
        """Рука сама решает кончить сеанс: устала (порог свой у дня) и поработала хотя бы сотню мазков."""
        с = self.с
        return с.с_начала_сеанса > 300 and с.усталость > 0.5 + 0.5 * с.день + 0.1 * с.внимание

    def порог_добора(self):
        """Когда идти к палитре — своё у руки и по состоянию: внимательная добирает раньше, увлечённая тянет досуха."""
        return float(np.clip(0.26 + 0.10 * self.с.внимание - 0.10 * self.с.знаком / 6 + 0.08 * self.с.усталость, 0.08, 0.5))
