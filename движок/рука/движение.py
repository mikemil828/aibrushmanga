"""Движение руки (блок 10 «Рука-модуль», Рм-1; вырос из проб Движка 258–263, Den 26.11 22:59 +04: «надо умнее и
интереснее»). Модуль отдельный: движок (`кисть/`) его не зовёт, физики мазка здесь нет — только путь кончика.

Рука получает не путь, а НАМЕРЕНИЕ: цели (куда прийти), изгиб хода, где касаться. Движение строит сама:

1. Броски. Ход — цепочка баллистических бросков к целям; у каждого логнормальный колокол скорости
   (кинематическая теория быстрых движений человека). Следующий бросок начинается, не дождавшись конца
   прежнего: чем беглее рука, тем больше нахлёст — углы сами скругляются и срезаются, форма меняется от темпа.
2. Тело. Бросок делает рычаг вокруг опоры: «прямая» выходит дугой, конец тянет туда, куда рычагу удобно;
   опора стоит, пока рука достаёт, потом переставляется — серия идёт пачками.
3. Глаз. Медленный ход — не один бросок, а цепочка подходов по ~0,3 с; каждый целится заново от того места,
   где рука оказалась. Неровность линии — от этих поправок, а не от добавленной дрожи. Ошибка броска растёт
   со скоростью: быстрый ход чист, но мимо; медленный точен, но волнист.
4. Кисть в руке. Нажим — не конверт: посадка и подъём привязаны к броску (беглая рука садится и снимается на
   ходу, прилежная встаёт, давит, ведёт, останавливается), ход «к себе» тяжелее хода «от себя», на скорости
   легче. Плоскую кисть держит кисть руки: она доворачивается за ходом лишь частью — лента то широкая, то узкая.

На выходе — куски касания: точки ядра (x, y, нажим, dt_мс, наклон°, азимут рад, поворот°), мм."""
import math
from statistics import NormalDist

import numpy as np
from scipy.special import erf as _erf

ДТ = 0.002          # с
_Z = NormalDist().inv_cdf
_Q = 2.05           # бросок «длится» между квантилями 2 % и 98 %


def _угол(v):
    return math.atan2(v[1], v[0])


def _ед(a):
    return np.array([math.cos(a), math.sin(a)])


def _пов(v, a):
    c, s = math.cos(a), math.sin(a)
    return np.array([c * v[0] - s * v[1], s * v[0] + c * v[1]])


class Человек:
    """Постоянное у руки: с какой стороны опора, как скошен колокол, куда тяжелее, как держит кисть."""

    def __init__(self, сид, левша=None):
        r = np.random.default_rng([сид, 258])
        self.сид = сид
        self.левша = (r.random() < 0.15) if левша is None else левша
        ψ = math.radians(50 + 25 * r.random())                 # опора справа-снизу от кончика (y вниз)
        self.ψ = math.pi - ψ if self.левша else ψ
        self.σ = 0.22 + 0.20 * r.random()                      # скошенность колокола скорости
        self.kD = 0.03 + 0.04 * r.random()                     # разброс длины броска (на единицу беглости)
        self.kθ = math.radians(1.5 + 2.5 * r.random())         # разброс направления
        self.уклон = math.radians(12 * r.random() - 6)          # все ходы чуть довёрнуты — своё у руки
        self.размах = 0.85 + 0.27 * r.random()                 # недолёт или перелёт — своё у руки
        self.тело = 0.5 + 0.5 * r.random()                     # насколько ход — дуга рычага
        self.рычаг = 0.8 + 0.5 * r.random()
        self.подход = 0.22 + 0.12 * r.random()                 # с — один подход медленного хода
        self.к_себе = self.ψ + math.radians(30 * r.random() - 15)
        self.тяжесть = 0.10 + 0.40 * r.random()                # на сколько ход к себе тяжелее
        self.лёгкость = 0.10 + 0.25 * r.random()               # на сколько легче на скорости
        self.нажим = 0.72 + 0.16 * r.random()
        self.хват = math.radians(40 * r.random() - 20)         # плоская в руке стоит к ходу не точно — на столько
        self.следит = 0.3 + 0.5 * r.random()                   # доля доворота кисти за ходом
        self.темп = 0.45 + 0.45 * r.random()                   # своя беглость, когда темп не задан

    def строка(self):
        return (f'сид {self.сид}, {"левша" if self.левша else "правша"}, опора {math.degrees(self.ψ):.0f}°, '
                f'колокол σ {self.σ:.2f}, уклон {math.degrees(self.уклон):+.1f}°, размах {self.размах:.2f}, '
                f'к себе тяжелее на {self.тяжесть:.2f}, кисть следит {self.следит:.2f}')


class Рука:
    def __init__(self, человек, беглость, сид=0):
        self.ч = человек
        self.b = float(человек.темп if беглость is None else беглость)
        self.r = np.random.default_rng([человек.сид, сид, 7])
        self.дом = None
        self.R = None
        self.где = None          # где рука осталась после прошлого жеста (мм)
        self.вид = 1.0           # насколько темп меняет форму: срезание углов, посадка и подъём на ходу (0 — нет)

    # ------------------------------------------------------------------ время броска
    def _длительность(self, D):
        b = self.b
        return (0.15 + 0.80 * (1 - b) ** 1.6) * (max(D, 2.0) / 30.0) ** 0.35

    # ------------------------------------------------------------------ тело
    def _опора(self, точки):
        """Опора стоит, пока ход в досягаемости; иначе рука переставляется под новый ход."""
        P = np.asarray(точки, float)
        размах = float(np.max(np.hypot(*(P - P[0]).T))) if len(P) > 1 else 0.0
        R = float(np.clip(3.5 * размах, 60.0, 400.0)) * self.ч.рычаг
        if self.дом is not None and abs(R - self.R) < 0.3 * self.R:
            if np.max(np.hypot(*(P - self.дом).T)) < 0.7 * self.R:
                return False
        self.дом = P[0] + self.r.standard_normal(2) * 1.5
        self.R = R
        self.C = self.дом + R * _ед(self.ч.ψ + math.radians(8) * self.r.standard_normal())
        return True

    def _удобный_конец(self, A, B):
        """Куда придёт кончик, если ход той же длины сделать одним рычагом вокруг опоры; угол дуги."""
        u = self.C - A
        R = max(np.hypot(*u), 1e-6)
        ψ = _угол(u)
        d = B - A
        D = np.hypot(*d)
        a = _угол(d) - ψ
        Δ = -(D / R) * math.sin(a)
        rr = _пов(A - self.C, Δ) * (1 - D * math.cos(a) / R)
        return self.C + rr, Δ

    # ------------------------------------------------------------------ план бросков
    def жест(self, ходы):
        """ходы: [{'точки': [(x, y), …], 'изгиб': [° на отрезок], 'акцент': [0–1 на цель]}, …] — мм.
        Между ходами рука идёт по воздуху сама. Ответ: куски касания, список массивов (x, y, нажим, dt_мс,
        наклон°, азимут рад, поворот°), и воздух — весь путь кончика (t, x, y, нажим) для схемы."""
        ч, b, r = self.ч, self.b, self.r
        броски = []           # (on, T, μ, σ, D, θmid, Δ)
        касания = []          # (t_down, t_up, акценты [(t, сила)])
        паузы_опоры = []
        первая = np.asarray(ходы[0]['точки'][0], float)
        # рука приходит к первой точке со стороны опоры
        self._опора(ходы[0]['точки'])
        старт = первая + 14.0 * _ед(ч.ψ + 0.4 * r.standard_normal()) if self.где is None else np.array(self.где, float)
        план = старт.copy()         # где рука думает, что она
        факт = старт.copy()         # где она на самом деле (сумма бросков)
        t_on = 0.0
        нахл = 0.42 * b * self.вид

        def бросок(цель, изгиб, on, вес_глаза, в_воздухе=False):
            nonlocal план, факт
            верю = вес_глаза * факт + (1 - вес_глаза) * план
            цель_удоб, Δтело = self._удобный_конец(верю, цель)
            if not в_воздухе:
                цель_э = цель + (0.05 + 0.30 * b) * ч.тело * (цель_удоб - цель)
            else:
                цель_э = цель
            d = цель_э - верю
            D = np.hypot(*d)
            if D < 1e-6:
                план = цель.copy()
                return None
            T = self._длительность(D)
            шум = 0.35 + b
            D2 = D * (ч.размах ** b) * (1 + ч.kD * шум * r.standard_normal())
            θ = _угол(d) + ч.уклон * b + ч.kθ * (0.9 + 0.5 * b) * r.standard_normal()
            Δ = math.radians(изгиб) + 0.6 * Δтело * ч.тело * (0.5 + 0.5 * b)
            полу = Δ / 2
            Dд = D2 * (полу / math.sin(полу) if abs(полу) > 1e-4 else 1.0)
            emu = T / (math.exp(_Q * ч.σ) - math.exp(-_Q * ч.σ))
            μ = math.log(emu)
            t0 = on - math.exp(μ - _Q * ч.σ)
            броски.append((t0, μ, ч.σ, Dд, θ, Δ, on, T))
            факт = факт + D2 * _ед(θ)
            план = цель.copy()
            return len(броски) - 1

        def t_кв(k, q):
            t0, μ, σ = броски[k][:3]
            return t0 + math.exp(μ + σ * _Z(q))

        for i, ход in enumerate(ходы):
            P = [np.asarray(p, float) for p in ход['точки']]
            изгибы = list(ход.get('изгиб') or [0.0] * (len(P) - 1))
            акценты = list(ход.get('акцент') or [0.0] * len(P))
            # беглая рука целит за угол (мнимая цель): нахлёст бросков срежет угол, и след придёт почти в него
            V = [p.copy() for p in P]
            for j in range(1, len(P) - 1):
                a, c = P[j] - P[j - 1], P[j + 1] - P[j]
                la, lc = np.hypot(*a), np.hypot(*c)
                V[j] = P[j] + 0.75 * нахл * 0.22 * 0.5 * (la + lc) * (_пов(a / la, math.radians(изгибы[j - 1]) / 2)
                                                                     - _пов(c / lc, -math.radians(изгибы[j]) / 2))
            # --- по воздуху к началу хода
            if i > 0 and self._опора(ход['точки']):
                t_on += 0.10 + 0.25 * (1 - b) + 0.05 * r.random()
            k = бросок(P[0], 0.0, t_on, 0.9 - 0.3 * b, в_воздухе=True)
            if k is not None:
                T, Dв = броски[k][7], броски[k][3]              # издалека рука сперва приходит, потом садится
                t_on += T * (1 - нахл * float(np.clip(12.0 / Dв, 0.1, 1.0)))
                if np.hypot(*(P[0] - факт)) > 0.6:             # глаз доводит кончик до места: короткий второй бросок
                    k2 = бросок(P[0], 0.0, t_on - 0.25 * T, 1.0 - 0.25 * b, в_воздухе=True)
                    if k2 is not None:
                        t_on = max(t_on, t_on - 0.25 * T + броски[k2][7] * (1 - 0.6 * нахл))
                t_on += (1 - b) ** 2 * 0.12 * (0.5 + r.random())
            первый = последний = None
            акц = []
            # --- сам ход
            for j in range(1, len(P)):
                D = np.hypot(*(P[j] - P[j - 1]))
                T = self._длительность(D)
                n = max(1, int(round(T / (ч.подход * (1 + 1.2 * b)))))
                изг = изгибы[j - 1]
                for m in range(n):
                    цель = V[j] if m == n - 1 else _на_дуге(P[j - 1], P[j], изг, (m + 1) / n)
                    k = бросок(цель, изг / n, t_on, 0.9 - 0.4 * b)
                    if k is None:
                        continue
                    if первый is None:
                        первый = k
                    последний = k
                    Tk = броски[k][7]
                    угол_цели = m == n - 1 and j < len(P) - 1
                    if угол_цели:                              # цель-угол: беглая рука его срезает, прилежная встаёт
                        t_on += Tk * (1 - нахл * (1 - 0.7 * акценты[j])) + (1 - b) ** 2 * 0.10 * (0.5 + r.random())
                    else:
                        t_on += Tk * (1 - (0.42 if m < n - 1 else нахл))
                if акценты[j] > 0 and последний is not None:
                    акц.append((t_кв(последний, 0.9), акценты[j]))
            if первый is None:
                continue
            if акценты[0] > 0:
                акц.append((t_кв(первый, 0.05), акценты[0]))
            стоит = (1 - b) ** 2 * 0.10
            t_down = t_кв(первый, 0.004 + 0.07 * b ** 1.5 * self.вид) - стоит * (0.6 + 0.8 * r.random())
            t_up = t_кв(последний, 0.996 - 0.09 * b ** 1.5 * self.вид) + стоит * (0.6 + 0.8 * r.random())
            касания.append((t_down, t_up, акц, броски[первый][7], броски[последний][7],
                            _угол(P[1] - P[0]) - math.radians(изгибы[0]) / 2))
            t_on = max(t_on, t_up - 0.5 * b * 0.1) + (1 - b) * 0.08

        self.промах = float(np.hypot(*(факт - P[-1])))      # насколько рука пришла мимо последней цели
        # ------------------------------------------------------------------ движение: сумма бросков
        t_кон = max(бр[0] + math.exp(бр[1] + 3.2 * бр[2]) for бр in броски) + 0.15
        t = np.arange(min(-0.2, касания[0][0] - 0.1), t_кон, ДТ)
        v = np.zeros((len(t), 2))
        for t0, μ, σ, D, θ, Δ, on, T in броски:
            τ = np.maximum(t - t0, 1e-9)
            z = (np.log(τ) - μ) / σ
            Λ = np.exp(-0.5 * z * z) / (σ * math.sqrt(2 * math.pi) * τ)
            Λ[t <= t0] = 0.0
            F = 0.5 * (1 + _erf(z / math.sqrt(2)))
            F[t <= t0] = 0.0
            φ = θ + Δ * (F - 0.5)
            v[:, 0] += D * Λ * np.cos(φ)
            v[:, 1] += D * Λ * np.sin(φ)
        xy = старт + np.cumsum(v, 0) * ДТ
        self.где = xy[-1].copy()
        скор = np.hypot(*v.T)

        # ------------------------------------------------------------------ кисть в руке: нажим, наклон, поворот
        vref = 120.0
        касается = np.zeros(len(t))
        акцент = np.ones(len(t))
        for t_down, t_up, акц, Tп, Tк, _ in касания:
            τв = min(0.03 + 0.05 * (1 - b) * r.random(), 0.18 * Tп)     # короткий бросок — и посадка короче
            τс = min(0.04 + 0.05 * r.random(), 0.25 * Tк)
            a = np.clip((t - t_down) / τв, 0, 1)
            c = np.clip((t_up - t) / τс, 0, 1)
            касается = np.maximum(касается, (a * a * (3 - 2 * a)) * (c * c * (3 - 2 * c)))
            if b < 0.5:                                        # прилежная рука, встав, придавливает
                акцент += 0.25 * (1 - 2 * b) * np.exp(-0.5 * ((t - t_down - τв) / 0.05) ** 2)
            for ta, сила in акц:
                акцент += 0.5 * сила * np.exp(-0.5 * ((t - ta) / 0.06) ** 2)
        ход_угол = np.arctan2(v[:, 1], v[:, 0])
        идёт = скор / (скор + 15.0)
        нажим = ч.нажим * (1 + ч.тяжесть * np.cos(ход_угол - ч.к_себе) * идёт)
        нажим *= 1 - ч.лёгкость * np.clip(скор / (2.5 * vref), 0, 1) * 0.8
        нажим *= акцент
        ядро = np.exp(-0.5 * (np.arange(-30, 31) * ДТ / 0.012) ** 2)
        нажим = np.convolve(нажим, ядро / ядро.sum(), 'same')
        нажим = np.clip(нажим * касается, 0, 1)
        # направление хода, сглаженное и без скачков там, где рука почти стоит
        ux = np.convolve(v[:, 0], ядро / ядро.sum(), 'same')
        uy = np.convolve(v[:, 1], ядро / ядро.sum(), 'same')
        # кисть в касании: к началу хода рука ставит её по ходу (со своей ошибкой); пряди тянутся за ходом с
        # отставанием; плоскую кисть руки доворачивает за ходом лишь частью — на повороте лента сужается или ширится
        напр = np.arctan2(uy, ux)
        кисть_угол = напр.copy()
        for t_down, t_up, _, _, _, θ0 in касания:
            idx = np.nonzero((t >= t_down - 0.06) & (t <= t_up + 0.06))[0]
            if not len(idx):
                continue
            тек = θ0
            for i in idx:
                if math.hypot(ux[i], uy[i]) > 4.0 and t[i] >= t_down:
                    цель = math.atan2(uy[i], ux[i])
                    тек += ((цель - тек + math.pi) % (2 * math.pi) - math.pi) * min(1.0, ДТ / 0.03)
                напр[i] = тек
            стоит_так = θ0 + ч.хват + math.radians(5) * r.standard_normal()
            кисть_угол[idx] = стоит_так + ч.следит * (напр[idx] - θ0)
        наклон = 12 + 28 * np.clip(скор / (2 * vref), 0, 1)
        dt = np.full(len(t), ДТ * 1000)
        все = np.column_stack([xy, нажим, dt, наклон, напр, np.degrees(кисть_угол) + 90.0])

        куски = []
        на = нажим > 0.02
        i = 0
        while i < len(t):
            if not на[i]:
                i += 1
                continue
            j = i
            while j < len(t) and на[j]:
                j += 1
            a, c = max(i - 1, 0), min(j + 1, len(t))
            if c - a >= 4:
                куски.append(все[a:c].copy())
            i = j
        return куски, np.column_stack([t, xy, нажим])


def _на_дуге(A, B, изгиб, доля):
    """Точка на дуге от A к B с поворотом касательной на `изгиб`° (0 — прямая)."""
    Δ = math.radians(изгиб)
    if abs(Δ) < 1e-4:
        return A + (B - A) * доля
    хорда = B - A
    L = np.hypot(*хорда)
    R = L / (2 * math.sin(Δ / 2))
    θ0 = _угол(хорда) - Δ / 2                   # касательная в начале
    C = A + R * _ед(θ0 + math.pi / 2)
    return C + _пов(A - C, Δ * доля)


def намерение(ходы, шаг=1.0):
    """Намерение как есть — ломаные по целям и дугам (мм), для клетки «без руки»."""
    out = []
    for ход in ходы:
        P = [np.asarray(p, float) for p in ход['точки']]
        изг = list(ход.get('изгиб') or [0.0] * (len(P) - 1))
        Q = [P[0]]
        for j in range(1, len(P)):
            n = max(2, int(np.hypot(*(P[j] - P[j - 1])) * (1 + abs(изг[j - 1]) / 90) / шаг))
            Q += [_на_дуге(P[j - 1], P[j], изг[j - 1], (m + 1) / n) for m in range(n)]
        out.append(np.array(Q))
    return out


def в_точки(кусок, px_мм):
    """Кусок касания (мм) -> точки ядра в px; точки ближе 0,4 px сливаются (время копится, нажим — больший)."""
    P = np.array(кусок, float)
    P[:, :2] *= px_мм
    out = [P[0].tolist()]
    for q in P[1:]:
        if math.hypot(q[0] - out[-1][0], q[1] - out[-1][1]) < 0.4:
            out[-1][3] += q[3]
            out[-1][2] = max(out[-1][2], q[2])
            continue
        out.append(q.tolist())
    return out
