"""Глаз руки вживую (Рм-4): что рука видит на холсте до хода и дорисовка островов грунта.

Глаз смотрит не весь холст и не каждый ход. Холст он помнит плитками `ПЛИТКА_ММ`: кусок холста (плитку с соседними)
берёт, когда ход впервые заходит в неё (на ядрах ждёт только мазки этой плитки — `Холст._под_рукой`, очередь остальных считается
дальше), и потом дописывает в неё свои ходы сам, по памяти; память сбрасывается, когда холст и так досчитан — модель
посмотрела на него или правит мимо кисти, — и следующий ход берёт плитки заново. Письмо идёт фразами по 3–7 ходов
(`ЖиваяРука.фраза`); между фразами рука отходит глазом; ход дальше `ПОЛЕ_ММ` от места фразы — новая фраза.

До хода: под началом, серединой и концом — грунт, своя краска или чужая. По сырой краске кисть вязнет — рука идёт
медленнее и легче; впереди за концом чужая краска — рука тормозит у границы и целит точнее; перед точным местом
(короткий ход в важном месте) — примерка в воздухе.

Дорисовка: когда фраза кончена и рука отошла глазом, она ищет острова голого грунта внутри того, что уже закрывала
своими ходами (след задуманных путей шириной `СЛЕД` кисти, без кромки `КРОМКА_ММ`), — не зону и не то, что модель
оставила между ходами. Остров от `ОСТРОВ_ММ2` — один ход по его длинной оси (круглый остров — по ходу соседнего
мазка; остров короче ширины кисти — одно короткое касание кистью поперёк него), кистью хода, что там лежит, краской, которая на самом деле лежит вокруг
острова (цвет берётся с холста, не из строки соседнего хода). Волосяные щели уже `2 · ЩЕЛЬ_ММ` — не острова. Ходы
дорисовки идут через ту же руку и в журнал — с пометкой "arm_fill". Когда рука смотрит: по ходу письма — место
фразы, после которой легло `ОТСТАВАНИЕ` ходов, и только крупные острова (от `КРУПНЫЙ_ММ2`); до любого чтения холста
моделью и до правки мимо кисти — всё, что осталось, и мелкое. Взгляд на ядрах ждёт мазки своего места — поэтому
свежие ходы рука по ходу письма не смотрит: очередь мазков не стоит.

Всё считается в клетках `КЛЕТОК_НА_ММ` на мм — от плотности холста не зависит."""
import math

import numpy as np

КЛЕТОК_НА_ММ = 4.0
ПОЛЕ_ММ = 30.0            # ход дальше этого от места фразы — рука перешла, новая фраза
ПЛИТКА_ММ = 16.0          # плитка памяти глаза
ОКРУГА = 3                # взгляд берёт плитку и столько соседних в каждую сторону (7 × 7 плиток — 112 мм)
ОТСТАВАНИЕ = 48           # ходов: по ходу письма рука смотрит дыры фразы, когда после неё легло столько ходов (свежие
                          # ещё считаются на ядрах — взгляд ждал бы их, а очередь стояла бы)
СЛЕД = 0.8                # доля ширины кисти: что ход «хотел закрыть»
КРОМКА_ММ = 0.8           # кромка задуманного — не дыра (край пятна рваный сам по себе)
ЩЕЛЬ_ММ = 0.25            # щель уже двух таких — волос между прядями, не остров
ОСТРОВ_ММ2 = 2.0          # остров грунта от этой площади дорисовывается
КРУПНЫЙ_ММ2 = 8.0         # по ходу письма (фраза назад) — только такие; мельче ждут, пока модель посмотрит на холст
В_КРАСКЕ = 0.75           # доля кольца вокруг острова под краской: меньше — это край пятна, а не остров
ГОЛО = 0.5                # просвет грунта от этого — голо (как порог `х.просвет`)
ЗА_КОНЦОМ_ММ = 3.5        # куда глаз смотрит за концом хода
СВОЯ = 0.22               # сумма разниц линейного цвета: ближе — своя краска
ОСТРОВОВ_ЗА_ВЗГЛЯД = 12
КРУГОВ = 2                # сколько раз рука возвращается к месту, где дорисовала


def путь_намерения(d, сид):
    """Путь, которым ход задуман (px холста, (n, 2)), по строке журнала до руки; None — не ход кисти по пути."""
    from .патч import вид_хода, путь_движка, _точки
    вид, _ = вид_хода(d)
    try:
        if вид in ('цели', 'ядро'):
            return np.asarray(путь_движка(d, сид), float)[:, :2]
        if вид == 'сырые':
            A = _точки(d)
            return None if A is None or len(A) < 2 else np.asarray(A[:, :2], float)
    except (ValueError, TypeError, KeyError):
        return None
    return None


def _свой_цвет(d):
    """Цвет краски хода, линейный, — если в строке одна краска цветом; иначе None (набор, живая краска)."""
    ц = d.get('color')
    if isinstance(ц, (list, tuple)) and len(ц) == 3 and all(isinstance(v, (int, float)) for v in ц):
        from кисть.краска import в_линейный
        return np.asarray(в_линейный(ц), np.float32)
    return None


def _клетками(a, форма):
    """Поле в px -> клетки (среднее по клетке)."""
    from PIL import Image
    if a.ndim == 3:
        return np.dstack([_клетками(a[..., i], форма) for i in range(a.shape[2])])
    return np.array(Image.fromarray(np.ascontiguousarray(a, np.float32), 'F').resize((форма[1], форма[0]), Image.BOX))


class ГлазРуки:
    def __init__(self, х):
        self.px = float(х.px_на_мм or 8.0)
        self.г = min(КЛЕТОК_НА_ММ, self.px)                      # клеток на мм
        self.k = self.px / self.г                                 # px в клетке
        self.В, self.Ш = int(math.ceil(х.полная_высота / self.k)), int(math.ceil(х.полная_ширина / self.k))
        self.холст = (int(х.полная_ширина), int(х.полная_высота))
        self.задумано = np.zeros((self.В, self.Ш), bool)
        self.ходы = []            # задуманные ходы: путь (клетки), ширина (клетки), кисть, поля вызова, этап, объект
        self.рамки = []           # их рамки в клетках (x0, y0, x1, y1)
        self.T = int(round(ПЛИТКА_ММ * self.г))
        self.плитки = {}          # (ty, tx) -> [просвет, цвет, сыро] клетками: что глаз помнит о холсте
        self.идёт = False         # фраза начата
        self.пора = False         # пора смотреть дыры по ходу письма
        self.ходов = 0
        self.фраза = None         # рамка ходов текущей фразы, клетки
        self.до_взгляда = 0
        self.очередь = []         # [рамка фразы (клетки), круг]: ждут взгляда на дыры
        self.взглядов = self.дорисовано = 0

    # ------------------------------------------------------------------ взгляд
    def _рамка(self, P, поле):
        x0, y0 = np.floor(P.min(0) - поле).astype(int)
        x1, y1 = np.ceil(P.max(0) + поле).astype(int) + 1
        return max(x0, 0), max(y0, 0), min(x1, self.Ш), min(y1, self.В)

    def _взять(self, х, r):
        """Кусок холста по рамке в клетках -> (просвет, цвет, сыро) клетками."""
        k = self.k
        px = (int(r[0] * k), int(r[1] * k), min(int(math.ceil(r[2] * k)), self.холст[0]), min(int(math.ceil(r[3] * k)), self.холст[1]))
        п, ц, с = х._под_рукой(px)
        форма = (r[3] - r[1], r[2] - r[0])
        self.взглядов += 1
        if п.shape == форма:
            return np.array(п), np.array(ц), np.array(с)
        return _клетками(п, форма), _клетками(ц, форма), _клетками(с, форма)

    def _плитка(self, х, ty, tx):
        п = self.плитки.get((ty, tx))
        if п is None:
            # взгляд: плитка и соседние на `ОКРУГА` плиток одним куском — пока рука пишет здесь, глаз холста не ждёт
            T = self.T
            y0, y1 = max(ty - ОКРУГА, 0), min(ty + ОКРУГА, (self.В - 1) // T)
            x0, x1 = max(tx - ОКРУГА, 0), min(tx + ОКРУГА, (self.Ш - 1) // T)
            r = (x0 * T, y0 * T, min((x1 + 1) * T, self.Ш), min((y1 + 1) * T, self.В))
            кусок = self._взять(х, r)
            for j in range(y0, y1 + 1):
                for i in range(x0, x1 + 1):
                    if (j, i) not in self.плитки:
                        где = (slice(j * T - r[1], min((j + 1) * T, self.В) - r[1]), slice(i * T - r[0], min((i + 1) * T, self.Ш) - r[0]))
                        self.плитки[j, i] = [np.array(a[где]) for a in кусок]
            п = self.плитки[ty, tx]
        return п

    def забыть(self):
        """Холст досчитан или правлен мимо кисти: память глаза — заново с холста."""
        self.плитки.clear()

    def _что(self, х, p, своя):
        """В точке p (клетки холста): (есть ли краска, чужая ли она, сырая ли)."""
        x, y = int(p[0]), int(p[1])
        if not (0 <= x < self.Ш and 0 <= y < self.В):
            return False, False, False
        T = self.T
        п, ц, с = self._плитка(х, y // T, x // T)
        x, y = x % T, y % T
        if п[y, x] >= ГОЛО:
            return False, False, False
        чужая = своя is not None and float(np.abs(ц[y, x] - своя).sum()) >= СВОЯ
        return True, чужая, bool(с[y, x] > 0.05)

    def перед_ходом(self, х, d, путь_px, рука):
        """Что глаз видит под задуманным ходом -> функция для `патч.провести_строку` (ход -> поправки руке) или None."""
        P = путь_px / self.k
        if self.идёт and self.фраза is not None:
            f, поле = self.фраза, ПОЛЕ_ММ * self.г
            if not (f[0] - поле <= P[0, 0] <= f[2] + поле and f[1] - поле <= P[0, 1] <= f[3] + поле):
                self.конец_фразы(рука)                             # рука перешла на другое место — новая фраза
        if not self.идёт:
            self.идёт, self.до_взгляда = True, рука.фраза()
        своя = _свой_цвет(d)
        d_ = P[-1] - P[max(len(P) - 4, 0)]
        n = float(np.hypot(*d_))
        за = P[-1] + (d_ / n if n > 1e-6 else 0.0) * ЗА_КОНЦОМ_ММ * self.г
        под = [self._что(х, p, своя) for p in (P[0], P[len(P) // 2], P[-1])]
        сырое = sum(1 for есть, _, сыро in под if есть and сыро) / 3.0
        впереди = self._что(х, за, своя)
        у_края = впереди[1] and not под[2][1]
        длина = float(np.sum(np.hypot(*np.diff(P, axis=0).T))) / self.г

        def поправки(ход):
            кв = {'тормоз': 0.10 * сырое, 'легче': 1.0 - 0.10 * сырое}
            if у_края:
                ход['допуск'] = 0.6 * ход.get('допуск', 3.0)
                кв['тормоз'] += 0.12
            if ход.get('интерес', 0.5) >= 0.75 and длина < 15.0:
                кв['точнее'] = 0.65                                # примерка перед точным местом
            return кв
        return поправки

    def после_хода(self, d, путь_px, кисть, рука):
        """Ход принят: он — задуманное рукой и последнее, что лежит в памяти глаза; фраза идёт к концу."""
        from PIL import Image, ImageDraw
        P = путь_px / self.k
        w = float(d.get('size', 16.0)) / self.k
        r = self._рамка(P, 0.5 * w + 1)
        кроет = (кисть is not None and d.get('load') != 'сухая' and d.get('reserve') is None
                 and float(d.get('opacity', 1.0)) >= 0.5 and not d.get('medium'))
        if r[2] > r[0] and r[3] > r[1]:
            м = Image.new('L', (r[2] - r[0], r[3] - r[1]), 0)
            ImageDraw.Draw(м).line([(float(x - r[0]), float(y - r[1])) for x, y in P], fill=255,
                                   width=max(1, int(round(СЛЕД * w))), joint='curve')
            м = np.asarray(м) > 0
            if кроет:
                self.задумано[r[1]:r[3], r[0]:r[2]] |= м
                self.ходы.append(dict(P=P, w=w, кисть=кисть, слой=d.get('layer', 'основа'), нагрузка=d.get('load'),
                                      этап=d.get('stage'), объект=d.get('object')))
                self.рамки.append(r)
                self.фраза = r if self.фраза is None else (min(self.фраза[0], r[0]), min(self.фраза[1], r[1]),
                                                         max(self.фраза[2], r[2]), max(self.фраза[3], r[3]))
            своя, T = _свой_цвет(d), self.T                       # свой ход — в память глаза (в плитки, что уже взяты)
            for ty in range(r[1] // T, (r[3] - 1) // T + 1):
                for tx in range(r[0] // T, (r[2] - 1) // T + 1):
                    пл = self.плитки.get((ty, tx))
                    if пл is None:
                        continue
                    a = (max(r[0], tx * T), max(r[1], ty * T), min(r[2], (tx + 1) * T), min(r[3], (ty + 1) * T))
                    часть = м[a[1] - r[1]:a[3] - r[1], a[0] - r[0]:a[2] - r[0]]
                    куда = (slice(a[1] - ty * T, a[3] - ty * T), slice(a[0] - tx * T, a[2] - tx * T))
                    пл[0][куда][часть] = 0.0
                    пл[2][куда][часть] = 1.0
                    if своя is not None:
                        пл[1][куда][часть] = своя
        self.ходов += 1
        self.до_взгляда -= 1
        if self.до_взгляда <= 0:
            self.конец_фразы(рука)
        if not self.пора and any(з[1] == 0 and self.ходов - з[2] >= ОТСТАВАНИЕ for з in self.очередь[:4]):
            self.пора = True

    def конец_фразы(self, рука):
        """Фраза кончилась: рука отходит глазом; место фразы — в очередь на взгляд по дырам."""
        if not self.идёт:
            return
        рука.отошёл()
        if self.фраза is not None:
            self.очередь.append([self.фраза, 0, self.ходов])
        self.фраза, self.идёт = None, False

    # ------------------------------------------------------------------ дорисовка
    def острова(self, х, рамка, площадь_мм2=ОСТРОВ_ММ2):
        """Острова грунта (от `площадь_мм2`) внутри задуманного в рамке (клетки): список ходов дорисовки, крупные первыми."""
        from scipy import ndimage
        г = self.г
        поле = int(math.ceil((КРОМКА_ММ + 2.0) * г))
        r = (max(рамка[0] - поле, 0), max(рамка[1] - поле, 0), min(рамка[2] + поле, self.Ш), min(рамка[3] + поле, self.В))
        if r[2] - r[0] < 3 or r[3] - r[1] < 3:
            return []
        зад = self.задумано[r[1]:r[3], r[0]:r[2]]
        if not зад.any():
            return []
        внутри = ndimage.binary_erosion(зад, iterations=max(1, int(round(КРОМКА_ММ * г))))
        if not внутри.any():
            return []
        просвет, цвет, _ = self._взять(х, r)
        дыра = (просвет >= ГОЛО) & внутри
        if not дыра.any():
            return []
        щель = int(round(ЩЕЛЬ_ММ * г))
        if щель:
            дыра = ndimage.binary_opening(дыра, iterations=щель)
        метки, n = ndimage.label(дыра, structure=np.ones((3, 3), bool))
        if not n:
            return []
        площади = np.bincount(метки.ravel(), minlength=n + 1)
        закрыто = просвет < 0.2
        вых = []
        for j in np.argsort(-площади[1:], kind='stable') + 1:
            if площади[j] < площадь_мм2 * г * г or len(вых) >= ОСТРОВОВ_ЗА_ВЗГЛЯД:
                break
            ход = self._ход_по_острову(метки == j, r, цвет, закрыто)
            if ход is not None:
                вых.append(ход)
        return вых

    def _ход_по_острову(self, остров, r, цвет, закрыто):
        from scipy import ndimage
        г = self.г
        yx = np.argwhere(остров)
        p = yx[:, ::-1].astype(float) + 0.5 + np.array([r[0], r[1]])                 # клетки холста, (x, y)
        ц = p.mean(0)
        # краска — та, что лежит вокруг острова
        вокруг = ndimage.binary_dilation(остров, iterations=max(2, int(round(1.5 * г)))) & ~остров
        кольцо = вокруг & закрыто
        if int(кольцо.sum()) < 4 or кольцо.sum() < В_КРАСКЕ * вокруг.sum():
            return None                                            # вокруг грунт: край пятна, не остров в краске
        краска = _главный_цвет(цвет[кольцо])
        # кто здесь работал: последний из задуманных ходов, чей след накрывает остров; нет такого — ближайший
        свой, напр, лучше = None, None, None
        R = np.asarray(self.рамки, float)
        поле = 2.0 * г
        около = np.nonzero((R[:, 0] - поле <= ц[0]) & (ц[0] <= R[:, 2] + поле) & (R[:, 1] - поле <= ц[1]) & (ц[1] <= R[:, 3] + поле))[0]
        for i in около[::-1]:
            h = self.ходы[i]
            d2 = np.hypot(*(h['P'] - ц).T)
            k = int(np.argmin(d2))
            мера = float(d2[k]) - 0.5 * h['w']
            if лучше is None or мера < лучше:
                a, b = h['P'][max(k - 2, 0)], h['P'][min(k + 2, len(h['P']) - 1)]
                свой, напр, лучше = h, b - a, мера
            if мера <= 0.0:
                break
        if свой is None:
            return None
        n = float(np.hypot(*напр))
        напр = напр / n if n > 1e-6 else np.array([1.0, 0.0])
        if len(p) >= 3:
            _, v = np.linalg.eigh(np.cov((p - ц).T))
            ось = v[:, 1]
        else:
            ось = напр
        вдоль = (p - ц) @ ось
        поперёк = (p - ц) @ np.array([-ось[1], ось[0]])
        L, W = float(np.ptp(вдоль)) + 1.0, float(np.ptp(поперёк)) + 1.0
        if W > 0.7 * L:                                            # остров без длинной оси — по ходу соседнего мазка
            ось = напр
            вдоль = (p - ц) @ ось
            поперёк = (p - ц) @ np.array([-ось[1], ось[0]])
            L, W = float(np.ptp(вдоль)) + 1.0, float(np.ptp(поперёк)) + 1.0
        elif float(ось @ напр) < 0:
            ось = -ось
            вдоль = -вдоль
        запас = 0.3 * г
        if L <= 0.9 * свой['w']:
            # остров короче ширины кисти: кисть ставится вдоль него и идёт поперёк, коротко — один мазок-касание
            # (ход вдоль острова тянул бы след на всю длину ворса за его концы)
            поп = np.array([-ось[1], ось[0]])
            if float(поп @ напр) < 0:
                поп = -поп
            середина = ц + ось * 0.5 * (вдоль.min() + вдоль.max()) + np.array([-ось[1], ось[0]]) * 0.5 * (поперёк.min() + поперёк.max())
            пол = max(0.5 * W + запас, 0.75 * г)
            a, b = середина - поп * пол, середина + поп * пол
            доля = 1.0
        else:
            a, b = ц + ось * (вдоль.min() - запас), ц + ось * (вдоль.max() + запас)
            доля = W / свой['w']
        # кисть — та, что здесь работала: на ней краска этого места (чужая кисть принесла бы свою грязь)
        h = свой
        return dict(a=a * self.k, b=b * self.k, краска=краска, кисть=h['кисть'], ширина=h['w'] * self.k, доля=доля,
                    слой=свой['слой'], нагрузка=h['нагрузка'], этап=свой['этап'], объект=свой['объект'])

    def взгляды(self, все):
        """Места фраз, что пора смотреть. все=True — модель смотрит на холст: вся очередь (и она пустеет). Иначе — по
        ходу письма (`пора`): фразы, которых рука ещё не смотрела; они остаются в очереди — мелкое ждёт модели."""
        if все:
            while self.очередь:
                yield self.очередь.pop(0)[:2]
        else:
            for з in self.очередь:
                if з[1] == 0 and self.ходов - з[2] >= ОТСТАВАНИЕ // 2:
                    yield з
        self.пора = False


def _главный_цвет(c):
    """Цвета клеток вокруг острова (линейные, (n, 3)) -> sRGB 0–255 краски, которой вокруг больше: остров на стыке
    двух красок берёт одну из них, а не их середину."""
    from кисть.краска import из_линейного
    c = np.asarray(c, np.float64)
    for _ in range(3):                                             # пока вокруг разные краски — берём ту, которой больше
        m = c.mean(0)
        if len(c) < 8:
            break
        _, v = np.linalg.eigh(np.cov((c - m).T))
        t = (c - m) @ v[:, 2]
        if float(t.std()) <= 0.025:
            break
        граница = 0.5 * (float(t.min()) + float(t.max()))
        for _ in range(4):                                         # две кучи по главной оси цвета
            ниже = t <= граница
            if ниже.all() or not ниже.any():
                break
            граница = 0.5 * (float(t[ниже].mean()) + float(t[~ниже].mean()))
        ниже = t <= граница
        if ниже.all() or not ниже.any():
            break
        c = c[ниже] if ниже.sum() >= (~ниже).sum() else c[~ниже]
    m = c.mean(0)
    return tuple(int(round(v)) for v in np.clip(из_линейного(m) * 255.0, 0, 255))
