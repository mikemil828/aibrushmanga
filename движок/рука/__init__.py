def __getattr__(имя):                 # патч — по первому обращению: `python3 -m рука.патч` не грузит его дважды
    if имя in ('переписать', 'переписать_файл', 'снять_руку', 'СИЛА', 'МЕРА', 'патч'):
        import importlib
        м = importlib.import_module('.патч', __name__)
        return м if имя == 'патч' else getattr(м, имя)
    raise AttributeError(имя)
