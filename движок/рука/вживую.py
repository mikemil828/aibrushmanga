def найти_ручку(папка=None):
    """Путь `рука.json`: в папке запуска (или `папка`), затем в папке `движок/`; None — файла нет."""
    for где in (os.getcwd() if папка is None else папка, _ПОСТАВКА):
        путь = os.path.join(где, ИМЯ_JSON)
        if os.path.isfile(путь):
            return путь
    return None


def _число(имя, v, путь, целое=False):
    if v is None:
        return None
    if isinstance(v, bool) or not isinstance(v, (int, float)) or not math.isfinite(v) or v < 0 or (целое and v != int(v)):
        raise ValueError(f'{путь}: "{имя}" — {"целое " if целое else ""}число от 0 или null, а не {v!r}')
    return int(v) if целое else float(v)


def прочитать_ручку(путь):
    """`рука.json` -> словарь полей `ПОЛЯ` (пропущенные — по умолчанию). Кривой файл — ValueError с путём и полем."""
    try:
        with open(путь, encoding='utf-8') as f:
            д = json.load(f)
    except (OSError, ValueError) as e:
        raise ValueError(f'{путь}: не читается как JSON ({e})') from None
    if not isinstance(д, dict):
        raise ValueError(f'{путь}: нужен объект {{"положение": …}}')
    д = {к: в for к, в in д.items() if not к.startswith(ПОЯСНЕНИЕ)}   # «// …» — пояснение человеку (`рука.пример.json`)
    лишние = [к for к in д if к not in ПОЛЯ]
    if лишние:
        raise ValueError(f'{путь}: неизвестные поля ' + ', '.join(map(repr, лишние)) + ' — есть: ' + ', '.join(ПОЛЯ)
                         + '; пояснение — поле с именем на «//»')
    п = д.get('положение', УСМОТРЕНИЕ)
    if п not in ПОЛОЖЕНИЯ:
        raise ValueError(f'{путь}: "положение" — одно из ' + ', '.join(f'"{x}"' for x in ПОЛОЖЕНИЯ) + f', а не {п!r}')
    for к in ('дорисовка', 'сырые', 'лента'):
        if к in д and not isinstance(д[к], bool):
            raise ValueError(f'{путь}: "{к}" — true или false, а не {д[к]!r}')
    return dict(положение=п, сила=_число('сила', д.get('сила'), путь), потолок=_число('потолок', д.get('потолок'), путь),
                человек=_число('человек', д.get('человек'), путь, True), зерно=_число('зерно', д.get('зерно'), путь, True),
                дорисовка=д.get('дорисовка', True), сырые=д.get('сырые', True), лента=д.get('лента', False))


def _ч(v):
    return f'{v:g}'.replace('.', ',')


class ИнтересВживую(Интерес):
    """`Интерес` по уже написанному: кисти, объекты и этапы копятся мазок за мазком (у патча — весь журнал разом)."""

    def __init__(self):
        super().__init__()
        self.этапы, self.объекты, self.пометок = {}, {}, 1

    def учесть(self, d, тек):
        n = len(self.Ws)
        super().учесть(d, тек)
        if len(self.Ws) > n:
            bisect.insort(self.Ws, self.Ws.pop())
        этапы = list(self._этапы)
        if all(isinstance(э, (int, float)) for э in этапы):
            этапы.sort()
        self.этапы = {str(э): i / max(len(этапы) - 1, 1) for i, э in enumerate(этапы)}
        о = d.get('object', тек['object'])
        if о is not None and str(о) in self._по:
            self.объекты[str(о)] = self._место(float(np.median(self._по[str(о)])))

    def __call__(self, d, тек, пометка):
        if not self.Ws:
            self.Ws = [16.0]
        return super().__call__(d, тек, пометка)


class РукаХолста:
    """Рука одного холста: ручка человека, включена ли, сила, кто включил; сама рука (`ЖиваяРука`) — с первого
    включения, человек и зерно — один раз на холст."""

    def __init__(self, ручка=None, путь=None, журнал=None):
        self.путь = путь
        self.ручка = ручка or dict(положение=УСМОТРЕНИЕ, сила=None, потолок=None, человек=None, зерно=None,
                                   дорисовка=True, сырые=True, лента=False)
        self.положение = self.ручка['положение']
        self.потолок = self.ручка['потолок']
        self.сила = self._в_потолок(СИЛА if self.ручка['сила'] is None else self.ручка['сила'])
        self.человек, self.зерно = self.ручка['человек'], self.ручка['зерно']
        if журнал is not None:                             # холст продолжает журнал: тот же человек и зерно, что в нём
            self.человек, self.зерно = _из_журнала(журнал, self.человек, self.зерно)
        self.вкл = self.положение == ВКЛ
        self.кто = 'json' if self.вкл else None
        self.рука = None
        self.интерес = ИнтересВживую()
        self.тек_пометок = 0
        self.формы = {}
        self.счёт = _счёт(self.сила, {})
        self.увод = []
        self.дорисовка = bool(self.ручка['дорисовка'])        # Рм-4
        self.глаз = None                                      # глаз руки (`глаз.ГлазРуки`) — с первого хода рукой
        self.мой = None                                       # id холста, который глаз видит (участки и копии — мимо)
        self.в_ходе = 0                                       # идёт `Холст.мазок`: дорисовка — до хода или после, не посреди
        self._есть = self._дорисовываю = False
        self._pid = os.getpid()
        if self.вкл:
            self._завести()

    @classmethod
    def с_ручки(cls, журнал=None):
        """Рука холста по `рука.json`; None — файла нет (рука выключена, заголовок журнала не меняется)."""
        путь = найти_ручку()
        if путь is None:
            return None
        return cls(прочитать_ручку(путь), путь, журнал)

    def _в_потолок(self, сила):
        return сила if self.потолок is None else min(сила, self.потолок)

    def _завести(self):
        if self.человек is None:
            self.человек = secrets.randbelow(1_000_000)
        if self.зерно is None:
            self.зерно = secrets.randbelow(1_000_000)
        if self.рука is None:
            self.рука = ЖиваяРука(Человек(self.человек), зерно=self.зерно, сила=self.сила)

    def заголовок(self):
        """Поле "arm" строки холста (или заметки при переключении)."""
        if self.вкл:
            self._завести()
        з = {}
        if self.человек is not None:
            з.update(person=self.человек, seed=self.зерно)
        з.update(strength=self.сила, on=self.вкл, knob=self.положение)
        if self.кто:
            з['who'] = self.кто
        if self.потолок is not None:
            з['cap'] = self.потолок
        if not self.ручка['сырые']:
            з['raw'] = False
        if not self.дорисовка:
            з['fill'] = False
        return з

    def _где(self, х=None):
        if х is not None and getattr(х, 'журнал', None) is None and self.путь is None:
            # у холста без журнала ручка не читается (`Холст.__init__`): «ручки нет» врало бы, когда файл лежит
            путь = найти_ручку()
            return 'ручка не читается: у холста нет журнала' + (f' ({путь} лежит, но не действует)' if путь else '')
        return f'ручка — {self.путь}, «{self.положение}»' if self.путь else f'ручки нет ({ИМЯ_JSON} не найден): «{УСМОТРЕНИЕ}»'

    def ответ(self):
        if not self.вкл:
            return f'рука выключена; {self._где()}'
        дор = 'дорисовка выключена' if not self.дорисовка else ('дорисовка включена' + (
            f' (дорисовано ходов: {self.глаз.дорисовано})' if self.глаз is not None and self.глаз.дорисовано else ''))
        return (f'рука включена: сила {_ч(self.сила)}, кто — {self.кто}; человек {self.человек}, зерно {self.зерно}; '
                f'{дор}; {self._где()}')

    def включить(self, х, вкл=True, сила=None, кто='модель', дорисовка=None):
        """`Холст.рука`: ответ строкой; отказ — тоже строкой (и в stderr), холст и рука как были."""
        def отказ(почему):
            т = f'рука: {почему}; {self._где(х)}'
            print(т, file=sys.stderr, flush=True)
            return т
        if кто not in КТО:
            return отказ(f'кто — «модель» или «приказ» (по слову человека), а не {кто!r}; ничего не меняю')
        if сила is not None:
            if isinstance(сила, bool) or not isinstance(сила, (int, float)) or not math.isfinite(сила) or сила < 0:
                return отказ(f'сила — число от 0 (0,15 — по умолчанию, к 0,3 ход целиком от руки), а не {сила!r}; ничего не меняю')
        if дорисовка is not None and not isinstance(дорисовка, bool):
            return отказ(f'дорисовка — True или False, а не {дорисовка!r}; ничего не меняю')
        вкл = bool(вкл)
        if вкл and self.положение == ВЫКЛ:
            return отказ('не включена — человек выключил руку ручкой, переключить может только он')
        if not вкл and self.положение == ВКЛ:
            return отказ('не выключена — человек включил руку ручкой, переключить может только он')
        ж = х._пишет()
        if ж is None:
            return отказ('не ' + ('включена' if вкл else 'выключена') + ' — ход руки пишется в журнал, а у холста его нет: '
                         'Холст(…, журнал=…)')
        слово = ''
        if сила is not None:
            нов = self._в_потолок(float(сила))
            if нов < float(сила):
                слово = f'; сила {_ч(float(сила))} выше потолка {_ч(self.потолок)} из ручки — взята {_ч(нов)}'
            self.сила = нов
        if self.вкл and (not вкл or дорисовка is False):
            self.досмотреть(х)                                 # Рм-4: начатое рука дорисовывает, пока включена
        self.вкл = вкл
        if дорисовка is not None:
            self.дорисовка = дорисовка
        self.кто = кто if self.положение != ВКЛ else 'json'    # кто переключил: и выключил — тоже он
        ж.строка({'note': 'рука', ЗАГОЛОВОК: self.заголовок()})
        return self.ответ() + слово

    def запас(self, х, кисть):
        """`х.перебор` без своей области: на сколько px шире рамки намерения (`прямоугольник_мазка`) ляжет ход этой
        кисти рукой — увод `УВОД_ММ`·сила и `ЗАПАС_ШИРИН` ширины кисти; 0 — рука не ведёт."""
        if not self.вкл or кисть is None:
            return 0
        px = float(х.px_на_мм or 8.0)
        W = float(кисть.в_пикселях(х.px_на_мм).ширина if (х.px_на_мм and кисть.ширина_мм is not None) else кисть.ширина)
        return int(math.ceil(УВОД_ММ * self.сила * px + ЗАПАС_ШИРИН * W))

    def состояние(self):
        """`Холст.снимок`: то, что о руке говорит журнал, — включена ли, сила, кто, дорисовка."""
        return dict(вкл=self.вкл, сила=self.сила, кто=self.кто, дорисовка=self.дорисовка)

    def вернуть(self, было):
        """`Холст.откатить`: рука — какой была при снимке (`было` — `состояние()`; None — руки при снимке не было:
        выключена, сила из ручки или 0,15). Журнал откат обрезал до снимка — его последняя строка руки снова правда.
        Поток случая, человек, зерно, интерес — как стали: тот же кусок рука второй раз ведёт иначе."""
        if было is None:
            было = dict(вкл=self.положение == ВКЛ, сила=self._в_потолок(СИЛА if self.ручка['сила'] is None else self.ручка['сила']),
                        кто='json' if self.положение == ВКЛ else None, дорисовка=bool(self.ручка['дорисовка']))
        self.вкл, self.сила, self.кто, self.дорисовка = было['вкл'], было['сила'], было['кто'], было['дорисовка']
        if self.вкл:
            self._завести()

    # ------------------------------------------------------------------ глаз и дорисовка (Рм-4)
    @property
    def ждёт(self):
        """Есть ли что досмотреть до чтения холста (`Холст.слои`, `Холст._граница`); посреди хода — нет."""
        return self._есть and not self.в_ходе and not self._дорисовываю and self._pid == os.getpid()

    def перед(self, х):
        """`Холст.мазок`, до хода: дорисовка фраз, что уже можно смотреть (кроме последней)."""
        if self.ждёт and self.глаз.пора:
            self._дорисовать(х, False)
        self.в_ходе += 1

    def после(self, х):
        self.в_ходе -= 1

    def досмотреть(self, х):
        """До чтения холста моделью и до правки мимо кисти: фраза кончена, всё, что ждёт взгляда, досмотрено."""
        if self.ждёт:
            self._дорисовать(х, True)
        elif self.глаз is not None and not self.в_ходе and not self._дорисовываю:
            self.глаз.забыть()

    def _дорисовать(self, х, все):
        г = self.глаз
        if г is None or id(х) != self.мой or х._пишет() is None:
            return
        self._дорисовываю = True
        try:
            можно = self.вкл and self.дорисовка
            if not все:                                        # по ходу письма: крупное — сразу, место остаётся в очереди
                for з in list(г.взгляды(False)):
                    з[1] = 1
                    for h in (г.острова(х, з[0], КРУПНЫЙ_ММ2) if можно else ()):
                        self._ход_дорисовки(х, h)
                return
            г.конец_фразы(self.рука)
            круг = 0
            while г.очередь:                                   # модель смотрит на холст: всё, что ждало, и мелкое
                снова = []
                for рамка, _ in г.взгляды(True):
                    ходы = г.острова(х, рамка) if можно else ()
                    for h in ходы:
                        self._ход_дорисовки(х, h)
                    if ходы and круг + 1 < КРУГОВ:
                        снова.append([рамка, 1, г.ходов])
                г.очередь, круг = снова, круг + 1
        finally:
            self._дорисовываю = False
            if все:
                г.забыть()                                     # холст досчитан: память глаза — заново с него
            self._есть = bool(г.очередь or г.идёт)

    def _ход_дорисовки(self, х, h):
        """Один ход по острову грунта: через `Холст.мазок` — его ведёт та же рука, в журнал он идёт с "arm_fill"."""
        from кисть import жест
        кисть = h['кисть']
        кв, нажим = {}, 0.7
        if кисть.форма != 'плоская':                            # круглая: ширина следа — нажимом, по острову
            нажим = float(np.clip(1.3 * h['доля'], 0.45, 0.8))
        сид = int(self.рука.с.r.integers(1, 2 ** 31 - 1))
        д = х.__dict__
        д['_тишина'] = д.get('_тишина', 0) + 1                   # подсказки модели ходы руки не считают
        try:
            х.мазок(жест(np.array([h['a'], h['b']], float), float(h['ширина']), 'отрыв', сид=сид, нажим=нажим), h['краска'],
                    кисть, слой=h['слой'], сид=сид, нагрузка=h['нагрузка'], этап=h['этап'], объект=h['объект'], **кв)
        finally:
            д['_тишина'] -= 1
        self.глаз.дорисовано += 1

    def пометка(self):
        """`Холст.пометка`: новый этап или объект — пауза руки, как у патча."""
        self.тек_пометок += 1
        self.интерес.пометок = max(1, self.тек_пометок)
        if self.рука is not None and self.вкл:
            self.рука.с.пауза(0.5)
            self.рука.рука.где = None

    def мазок(self, х, строка, кисть):
        """Строка мазка, снятия или среза ножом (словарь, как идёт в журнал) -> строки руки (словари: первая — этот
        ход, дальше — касания "arm_part") или None — ход как есть (рука выключена, тычок, набор линий …)."""
        тек = {'stage': х._этап, 'object': х._объект}
        if кисть is not None and isinstance(строка.get('brush'), str):
            px = х.px_на_мм
            self.формы[строка['brush']] = кисть.форма
            self.интерес.ширины[строка['brush']] = float(кисть.в_пикселях(px).ширина if (px and кисть.ширина_мм is not None)
                                                          else кисть.ширина)
        self.интерес.учесть(строка, тек)
        if not self.вкл:
            return None
        self._завести()
        сид = int(строка.get('seed', 0))
        # Рм-4: глаз — у хода кисти на холсте, который пишет модель (не участок, не копия, не процесс-потомок)
        путь = поправки = None
        if кисть is not None and 'tool' not in строка and self._pid == os.getpid() and (
                х.x0, х.y0, х.ширина, х.высота) == (0, 0, х.полная_ширина, х.полная_высота):
            if self.глаз is None:
                self.глаз, self.мой = ГлазРуки(х), id(х)
            if id(х) == self.мой:
                путь = путь_намерения(строка, сид)
        if путь is not None and not self._дорисовываю:
            строка_г = {**{'stage': тек['stage'], 'object': тек['object']}, **строка,
                        'size': self.интерес.ширины.get(строка.get('brush'), строка.get('size', 16.0))}
            поправки = self.глаз.перед_ходом(х, строка_г, путь, self.рука)
        нов, почему = провести_строку(строка, сид, self.рука, тек, self.интерес, self.тек_пометок,
                                      self.формы, float(х.px_на_мм or 8.0), self.сила, {}, self.ручка['сырые'],
                                      self.счёт, self.увод, поправки)
        if нов is None:
            self.счёт['как_есть'] += 1
            self.счёт['почему'][почему] = self.счёт['почему'].get(почему, 0) + 1
        if self._дорисовываю:                                  # ход дорисовки: пометка в журнал, в задуманное не идёт
            for н in нов or (строка,):
                н[ЗАЛАТАНО] = 1
        elif путь is not None:
            self.глаз.после_хода(строка_г, путь, кисть, self.рука)
            self._есть = True
        return нов


def _из_журнала(путь, человек, зерно):
    """Человек и зерно последней строки с "arm" журнала (холст продолжают) — если ручка их не вписала."""
    try:
        with open(путь, encoding='utf-8') as f:
            for l in f:
                if '"arm"' not in l:
                    continue
                а = json.loads(l).get(ЗАГОЛОВОК) or {}
                if 'person' in а:
                    человек = а['person'] if человек is None else человек
                    зерно = а.get('seed') if зерно is None else зерно
    except (OSError, ValueError):
        pass
    return человек, зерно
