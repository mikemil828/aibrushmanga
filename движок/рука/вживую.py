"""Рука вживую (Рм-3): рука ведёт ходы, пока модель пишет, — тем же ходом строки, что и патч (`патч.провести_строку`).

Движок зовёт её крючком (`кисть/холст.py`): мазок, снятие и срез ножом собирают свою строку журнала, как всегда; при
включённой руке строка уходит руке, и холст кладёт ход по её готовым точкам ("core"), а в журнал идёт её строка —
с исходным намерением в "arm_from" (касание, которое рука сделала вторым, — строкой с "arm_part"). Повтор такой
журнал кладёт сам, руку не считает: модуль ему не нужен. Рука ведёт ход только у холста с журналом.

Включает модель (`х.рука(сила=0.15, кто='модель')`, по слову человека — `кто='приказ'`; `х.рука(False)` — выключить)
или человек ручкой — файлом `рука.json` (папка запуска, затем папка `движок/`):

    {"положение": "на усмотрение модели", "сила": 0.15, "потолок": null, "человек": null, "зерно": null,
     "дорисовка": true, "сырые": true, "лента": false}

Поле, чьё имя начинается с «//», — пояснение человеку, ручка его пропускает (образец с пояснениями —
`движок/рука.пример.json`: под этим именем не читается, переименованный в `рука.json` — работает).

положение — «выключена» (модель включить не может), «на усмотрение модели» (умолчание и когда файла нет),
«включена» (рука ведёт с первого мазка, модель выключить не может); на «вкл/выкл» попытка модели переключить — отказ
строкой ответа, не исключение. сила — с какой силой рука включается (0,15, если не вписана); модель силу меняет свободно,
`потолок` — жёсткий предел, только если его вписал человек. человек, зерно — числа руки; не вписаны — случайные, один раз
на холст. дорисовка — глаз руки дорисовывает острова грунта внутри того, что она закрывала своими ходами (Рм-4,
`глаз_руки.py`); при включённой руке — включена, `false` — выключена (модель: `х.рука(дорисовка=False)`). сырые — вести ли
ходы готовыми точками; лента — вживую лента скотча рукой не ведётся (только патчем, `--лента`).

В журнале: у строки холста — "arm" (человек, зерно, сила, положение ручки, включена ли, кто), когда `рука.json` есть;
каждое включение и выключение по ходу — строкой {"note": "рука", "arm": {…}} ("who" — кто переключил; "fill": false —
дорисовка выключена). Ход дорисовки — строка мазка с "arm_fill": 1 (этап и объект — хода, у которого остров). Патч по
такому журналу сперва снимает руку (`снять_руку`: ходы дорисовки уходят) и проводит заново."""
